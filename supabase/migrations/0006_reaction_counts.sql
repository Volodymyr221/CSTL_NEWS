-- ── ЩО НЕ ТАК ───────────────────────────────────────────────────────────────
-- `fetchAllReactions()` читає ВСЮ таблицю `reactions` — усі реакції всіх людей
-- на всі пости — і рахує підсумки на телефоні. Сьогодні там 7 рядків, тож це
-- нічого не коштує.
-- 🛑 Межа не в трафіку, а в тиші: PostgREST віддає ЩОНАЙБІЛЬШЕ 1000 РЯДКІВ.
-- На 1001-й реакції вибірка обрізається БЕЗ ПОМИЛКИ, і під постами почнуть
-- стояти числа МЕНШІ за справжні. Не «повільно колись», а «неправильні числа,
-- щойно спільнота оживе».
--
-- 🔑 ЧОМУ ПОДАННЯ, А НЕ КОЛОНКА-ЛІЧИЛЬНИК У `posts`. Колонку треба тримати в
-- згоді тригерами на INSERT/DELETE, і кожна розбіжність — це число, яке бреше
-- назавжди. Подання рахує з тих самих рядків, тобто розійтись не може за
-- побудовою. Ціна — count() на кожен запит; на цих обсягах вона нульова, а
-- коли перестане бути нульовою, подання можна зробити матеріалізованим, не
-- чіпаючи клієнта.
--
-- ⚠️ ТОЧНО ТАК САМО ВЖЕ ЗРОБЛЕНО для «Стрічки»: `page_reaction_counts` існує на
-- проді з попередніх потоків. Ця міграція лише доводить той самий розкрій до
-- реакцій Дошки й обговорень.
--
-- 🔴 ПОДАННЯ СВІДОМО ОБХОДИТЬ RLS (воно `security definer` за замовчуванням у
-- Postgres < 15 і тут лишається звичайним): у ньому НЕМАЄ `user_id`, тільки
-- пост, емодзі й число. Тобто гість бачить кількість і не бачить, ХТО поставив
-- — рівно те, що показує інтерфейс.

create or replace view public.reaction_counts as
  select post_id, emoji, count(*)::int as cnt
  from public.reactions
  group by post_id, emoji;

comment on view public.reaction_counts is
  'Кількість реакцій за постом і емодзі (міграція 0006). Без user_id навмисно:
   інтерфейс показує число, а не список людей. Клієнт бере звідси лічильники,
   а «моя реакція» читається окремим запитом по своїх рядках.';

grant select on public.reaction_counts to anon, authenticated;

