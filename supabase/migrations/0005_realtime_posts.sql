-- 🔴 `posts` У ЦЬОМУ ПЕРЕЛІКУ НЕМАЄ. Тобто підписка існує, код навколо неї
-- написаний і навіть акуратний (не перемальовує список під пальцем), але
-- ПОДІЇ ДО НЕЇ НЕ ПРИХОДЯТЬ ЖОДНОГО РАЗУ.
--
-- 🛑 ЧОМУ ЦЕ НЕ ПОМІТИЛИ. Симптом у точності збігається з поведінкою ДО
-- підписки: нове оголошення зʼявляється в інших після перезаходу на вкладку.
-- А перезахід у застосунку відбувається постійно. Тобто фіча, якої немає,
-- виглядає як фіча, яка просто спрацювала трохи пізніше.
-- ⚠️ Запуску ще не було, тож двох людей одночасно на Дошці майже не буває —
-- перевірити це руками було практично нічим.
--
-- 🔑 REPLICA IDENTITY тут НЕ потрібна. Видалення оголошення в застосунку
-- мʼяке (`deleted_at`), тобто приходить як UPDATE із повним рядком. Ставити
-- `full` заради DELETE, якого не буває, означало б платити розміром WAL
-- (журналу реплікації) за подію, що не настає.

do $$ begin
  begin
    alter publication supabase_realtime add table public.posts;
  exception when duplicate_object then null;
  end;
end $$;

