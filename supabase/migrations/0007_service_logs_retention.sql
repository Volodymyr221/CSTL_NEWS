-- ═══════════════════════════════════════════════════════════════════════════
-- КРОК 1. РАЗОВЕ ПРИБИРАННЯ
-- ═══════════════════════════════════════════════════════════════════════════
-- 🛑 Саме `truncate`, а не `delete`: видалення 250 тисяч рядків саме по собі
-- спалило б диск, якого й так бракує (кожен видалений рядок це запис у журнал
-- попереднього запису WAL плюс потім прибирання). `truncate` просто відкидає
-- файл таблиці — миттєво, майже без вводу-виводу, і одразу віддає місце.
-- Місця після цього звільниться ~186 МБ.
--
-- ⚠️ Що втрачається: історія запусків розкладу і відповіді на HTTP-виклики за
-- останні години. Нічого з цього не читає ні застосунок, ні адмінка — звірено
-- грепом по `src/` і `admin.html`.

truncate table cron.job_run_details;
truncate table net._http_response;

-- ═══════════════════════════════════════════════════════════════════════════
-- КРОК 2. СТОРОЖ, ЩОБ НЕ НАРОСЛО ЗНОВУ
-- ═══════════════════════════════════════════════════════════════════════════
-- Без цього кроку через кілька місяців повернеться рівно та сама задуха.
--
-- 🔑 Строки різні й обидва виведені, а не вигадані:
--   журнал запусків  → 2 доби. Стільки треба, щоб побачити «задача падала
--                      вночі» наступного ранку. Глибше історію ніхто не читав
--                      жодного разу.
--   журнал відповідей → 6 годин. Це власний строк придатності `pg_net`: старші
--                      відповіді вже нікому не віддати, бо їх ніхто не чекає.

create or replace function public.prune_service_logs()
returns text
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  n_cron integer;
  n_http integer;
begin
  delete from cron.job_run_details where end_time < now() - interval '2 days';
  get diagnostics n_cron = row_count;

  delete from net._http_response where created < now() - interval '6 hours';
  get diagnostics n_http = row_count;

  return 'журнал запусків: ' || n_cron || ', журнал відповідей: ' || n_http;
end;
$function$;

revoke all on function public.prune_service_logs() from public, anon, authenticated;

-- Щодня о 03:55 UTC. Окремо від сусідів, щоб не зустрітись із згортанням
-- переглядів (02:10), лікуванням коментарів (03:15) і прибиранням аналітики
-- (03:40, міграція 0003).
select cron.schedule('prune-service-logs', '55 3 * * *',
                     'select public.prune_service_logs()');

