-- ── ЩО НЕ ТАК ──────────────────────────────────────────────────────────────
-- У `profiles` три колонки, які людина про себе оголошувати НЕ МОЖЕ:
--   trusted         — позначка «перевірений житель»
--   official        — офіційний акаунт (громада, служба)
--   approved_count  — скільки її оголошень пройшло модерацію
--
-- UPDATE на них уже був закритий колонковим GRANT-ом: `anon` і `authenticated`
-- мають UPDATE рівно на 10 змістовних колонок анкети, і цих трьох там немає.
-- А от INSERT лишався відкритим. Тобто захист виглядав поставленим, а
-- обходився створенням рядка замість його зміни: профіль у застосунку
-- створюється `upsert`-ом, і нічого не заважало покласти в нього `trusted`.
--
-- 🔑 Це не недогляд у політиці RLS, а АСИМЕТРІЯ між двома шляхами запису.
-- Клас вади варто запамʼятати: закриваєш колонку — закривай ОБИДВА шляхи,
-- бо INSERT і UPDATE у Postgres мають незалежні набори колонкових прав.
--
-- ── 🔴 ПЕРША РЕДАКЦІЯ ЦЬОГО ФАЙЛУ БУЛА КОСМЕТИКОЮ ──────────────────────────
-- Вона робила так:
--     revoke insert (trusted, official, approved_count) on public.profiles ...
-- Накат проходив без помилки, а `information_schema.column_privileges` ПІСЛЯ
-- нього далі показував ці колонки доступними на INSERT. Заміряно 24.09: шість
-- рядків (три колонки × дві ролі) як до, так і після.
--
-- Причина: у `anon`/`authenticated` стоїть INSERT на ТАБЛИЦЮ ЦІЛКОМ (типовий
-- грант Supabase на `public`), а колонковий `revoke` НЕ ВМІЄ віднімати від
-- табличного гранта — він знімає лише колонкові права. Табличний грант
-- перекриває все.
--
-- ➡️ Правило класу: `revoke` на колонку має сенс лише тоді, коли права видані
-- теж поколонково. Інакше спершу знімаєш табличний грант — і аж тоді видаєш
-- колонковий. Саме так у цій базі вже зроблено для UPDATE, і друга редакція
-- просто повторює той самий, уже перевірений часом прийом.

-- ── ЩО РОБИМО ──────────────────────────────────────────────────────────────
-- Список із 10 колонок звірено з двох боків:
--   1) з чинним колонковим грантом на UPDATE — рівно ті самі 10;
--   2) з клієнтом: `PROFILE_FIELDS` у `src/core/auth.js` (8 полів анкети)
--      плюс `uid` і `email`, які додає `saveProfile()`.
-- `created_at` не видаємо навмисно: у нього є значення за замовчуванням, і
-- клієнт його не шле.
revoke insert on public.profiles from anon, authenticated;

grant insert (uid, email, name, surname, birth_date, phone,
              settlement, street, bio, avatar_url)
  on public.profiles to anon, authenticated;

-- REFERENCES дозволяє послатись на колонку зовнішнім ключем — теж зайве.
revoke references (trusted, official, approved_count)
  on public.profiles from anon, authenticated;

