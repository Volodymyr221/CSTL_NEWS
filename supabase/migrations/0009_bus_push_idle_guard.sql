-- ── ЗАПОБІЖНИК ──────────────────────────────────────────────────────────────
-- Адреса і публічний ключ беруться з тіла попередньої редакції функції, а не
-- вписуються руками: так у файл не потрапляє навіть те, що можна сплутати з
-- секретом (репозиторій ПУБЛІЧНИЙ).
do $$
declare
  старе text;
  адреса text;
  публічний text;
begin
  select prosrc into старе from pg_proc p join pg_namespace n on n.oid=p.pronamespace
   where n.nspname='public' and p.proname='nudge_bus_push';
  if старе is null then
    raise exception 'Немає функції public.nudge_bus_push — спершу накоти 0008';
  end if;

  адреса    := (regexp_match(старе, 'url\s*:=\s*''([^'']+)'''))[1];
  публічний := (regexp_match(старе, 'Bearer ''\s*\|\|\s*''([A-Za-z0-9_.-]+)'''))[1];
  if публічний is null then
    публічний := (regexp_match(старе, 'Bearer ([A-Za-z0-9_.-]+)'))[1];
  end if;
  if адреса is null or публічний is null then
    raise exception 'Не впізнав крій nudge_bus_push — зупиняюсь, щоб не зламати розсилку';
  end if;

  execute format($тіло$
    create or replace function public.nudge_bus_push() returns void
    language plpgsql
    as $ф$
    declare
      секрет text;
    begin
      -- 🛑 УМОВА НАВМИСНО НАЙШИРША: не «є підписка на сьогодні», а «є хоч один
      -- рядок». Вужча умова лишила б застарілі рядки неприбраними назавжди —
      -- саме їх чистить сама Edge Function рядком delete .lt(track_date) — і
      -- перший живий житель дістав би сміття замість роботи.
      --
      -- Звірено з тілом send-bus-push: на ПОРОЖНІЙ таблиці вона й так вертає
      -- {sent:0, checked:0}, а її прибирання на порожній таблиці нічого не
      -- робить. Тому пропуск тут не втрачає НІЧОГО.
      if not exists (select 1 from public.push_subscriptions) then
        return;
      end if;

      select value into секрет from public.app_secrets where name = 'bus_push_secret';
      if секрет is null or секрет = '' then
        return;
      end if;

      perform net.http_post(
        url     := %L,
        headers := jsonb_build_object(
          'Content-Type',       'application/json',
          'Authorization',      'Bearer ' || %L,
          'x-cstl-push-secret', секрет),
        body    := '{}'::jsonb);
    end;
    $ф$;
  $тіло$, адреса, публічний);
end $$;

comment on function public.nudge_bus_push() is
  'Щохвилинний поштовх send-bus-push. Секрет бере з app_secrets на льоту (0008). Мовчить, поки підписок на рейси немає жодної (0009) — саме це палило бюджет дискового вводу-виводу.';

revoke all on function public.nudge_bus_push() from public, anon, authenticated;

