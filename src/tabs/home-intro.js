// ЗНАЙОМСТВО НА ГРОМАДІ — єдиний екран, який пояснює, що це за застосунок.
//
// 🔴 ЗАРАДИ ЧОГО (27.09.2026). Оцінка готовності 26.09 назвала два окремі
// пункти, і виявилось, що це ОДИН пункт у одному місці:
//   • «немає онбордингу» — людина після сплешу падає прямо на Громаду і ніде
//     не дізнається, навіщо застосунок. Призначення було написане лише в
//     правових текстах і в підзаголовку вкладки Питання;
//   • «перший житель побачить майже порожній екран» — Громада ХОВАЄ порожні
//     секції повністю (збір, стрічка, події), тож на нульових даних лишається
//     привітання, погода і два рядки «поки порожньо».
//
// 🔑 ЧОМУ НЕ ОКРЕМИЙ ЕКРАН ПІСЛЯ СПЛЕШУ, хоч так було записано в оцінці.
// Сплеш уже коштує 3.5 секунди до першого корисного пікселя; другий екран
// поспіль відкладав би застосунок ще далі, і його неможливо пропустити, лише
// закрити. Цей блок натомість: (1) нічого не відкладає, (2) пропускається
// прокруткою, (3) САМ ЗНИКАЄ, коли в громаді зʼявився зміст, — тобто не
// перетворюється на плашку, яку сотий раз гортає той, хто вже все зрозумів.
//
// ⚠️ НОВИНИ НЕ РАХУЮТЬСЯ ЗА ЗМІСТ ГРОМАДИ, і це головне рішення тут.
// Новини привозить парсер, вони є завжди — і в день запуску теж. Якби вони
// вважались змістом, блок не показався б НІКОЛИ, тобто був би мертвим кодом
// із першого дня. Рахуємо лише те, що робять САМІ ЖИТЕЛІ: збір, дайджест
// Стрічки, події, оголошення.
//
// 🛑 Три дії, а не одна, і порядок у них не випадковий. Перша — автобуси, бо це
// єдиний розділ, який на нульових користувачах працює на повну: розклад
// статичний, лежить у репозиторії, і відповідь там справжня вже сьогодні.
// Обіцяти першому жителю «напиши щось, і хтось відповість» першим пунктом
// означало б обіцяти те, чого в день запуску ще немає.
// Секції, наявність яких означає «громада жива». Порожня або відсутня секція
// стоїть з атрибутом `hidden` — саме так це роблять home-fund, home-feed і
// блок подій (рішення Вови: порожньо → секції немає зовсім).
const ЖИВІ_СЕКЦІЇ = ['hm-fund', 'hm-feed', 'hm-events'];

function громадаПорожня() {
  const хочащось = ЖИВІ_СЕКЦІЇ.some(id => {
    const s = document.getElementById(id);
    return s && !s.hasAttribute('hidden');
  });
  if (хочащось) return false;
  // Оголошення не ховають секцію — вони пишуть у неї текст або картки. Тож
  // питаємо не секцію, а сам вміст: є хоч одна картка — громада не порожня.
  // ⚠️ Скелет теж лежить у цьому контейнері, тому шукаємо САМЕ картку
  // оголошення (`.bd-ad`), а не будь-який дочірній вузол: під час завантаження
  // тут стоять три скелетні рядки, і «щось є» означало б «уже не порожньо».
  const дошка = document.getElementById('cm-board-content');
  if (дошка && дошка.querySelector('.bd-ad')) return false;
  return true;
}

// 🛑 ГІСТЬ І ЖИТЕЛЬ БАЧАТЬ ОДНЕ Й ТЕ САМЕ — свідомо. Заклик «увійдіть» тут був
// би ТРЕТІМ проханням входу поспіль: банер згоди, банер встановлення PWA і
// запрошення після трьох переходів між вкладками вже стоять. Вхід попросить
// сама дія — `requireAuth` у Дошці й Питаннях, — і попросить тоді, коли він
// справді потрібен, а не до того, як людина зрозуміла навіщо.
function розмітка() {
  return `
    <div class="hm-intro">
      <h2 class="hm-intro-title">Місцеве — в одному місці</h2>
      <p class="hm-intro-text">CSTL LIFE збирає те, що стосується Олицької
        громади: новини, розклад автобусів, графік світла, оголошення сусідів і
        питання, на які відповідають самі жителі.
        Громада тільки починається — і видно це саме тут.</p>
      <div class="hm-intro-acts">
        <button class="hm-intro-act" type="button" data-switch-tab="buses">Коли автобус</button>
        <button class="hm-intro-act" type="button" data-switch-tab="board">Подати оголошення</button>
        <button class="hm-intro-act" type="button" data-switch-tab="discussions">Запитати громаду</button>
      </div>
    </div>`;
}

let _намальовано = false;

// Перемальовуємо лише при ЗМІНІ стану — інакше спостерігач нижче ловив би
// власний запис і крутився б по колу.
function оновити() {
  const sec = document.getElementById('hm-intro');
  if (!sec) return;
  const треба = громадаПорожня();
  const видно = !sec.hasAttribute('hidden');
  if (треба === видно) return;   // стан уже потрібний — не торкаємось DOM
  if (треба && !_намальовано) { sec.innerHTML = розмітка(); _намальовано = true; }
  if (треба) sec.removeAttribute('hidden');
  else sec.setAttribute('hidden', '');
}

export function renderHomeIntro() {
  // 🔑 СПОСТЕРІГАЧ, А НЕ ТАЙМЕР. Блоки Громади вантажаться ПАРАЛЕЛЬНО, кожен
  // своїм запитом, і точки «усі готові» в коді немає. Таймер на 600 мс був би
  // вгаданою умовою: на швидкій мережі блок блимнув би й зник, на повільній
  // показався б уже після появи змісту. Спостерігач реагує на факт.
  оновити();
  const root = document.getElementById('cm-content');
  if (!root) return;
  let заплановано = false;
  new MutationObserver(() => {
    // Один перерахунок на кадр: блоки пишуть у DOM пачками, і рахувати на
    // кожен вузол означало б десятки однакових обходів.
    if (заплановано) return;
    заплановано = true;
    requestAnimationFrame(() => { заплановано = false; оновити(); });
  }).observe(root, { childList: true, subtree: true, attributes: true, attributeFilter: ['hidden'] });
}
