// src/tabs/home-contacts.js — ТЕЛЕФОНИ НА ГОЛОВНІЙ: екстрені + контакти громади.
//
// Замовлення Вови (04.08): «заголовок "Телефони громади", а зверху показані
// екстрені служби, які не мають відношення саме до громади. Через це користувач
// не зовсім розуміє структуру». І далі — зробити систему, що масштабується від
// 10 до 100+ контактів, з категоріями, розкриттям і швидкими діями.
//
// ─────────────────────────────────────────────────────────────────────────────
// 🔴 ЩО В ЗАМОВЛЕННІ РОЗІЙШЛОСЬ ІЗ ДАНИМИ — І ЯК ЦЕ ВИРІШЕНО
//
// ТЗ описувало інтерфейс під 50-100 контактів: список категорій, кожна
// згорнута, розкриваєш потрібну. Перевірка даних (`data/community.json`):
// **контактів рівно 9**, з них 5 екстрених. Тобто після розділення в «Громаді»
// лишається **чотири** записи — сільрада, ЦНАП, амбулаторія, Волиньобленерго.
//
// Згорнутий акордеон на чотирьох контактах шкодить: людина бачить
// «🏛 Органи влади (2)» і мусить тапнути, щоб побачити ДВА рядки. Це зайвий
// крок там, де все й так вміщується на екран.
//
// Тому система масштабована, а поведінка адаптивна:
//   • категорії існують ЗАВЖДИ (і в даних, і в розмітці) — додати 50 контактів
//     можна не чіпаючи ні код, ні дизайн;
//   • групи РОЗКРИТІ, поки контактів мало (≤ AUTO_OPEN_MAX);
//   • щойно їх стає більше — групи згортаються самі, і інтерфейс лишається
//     чистим рівно так, як просив Вова.
// Тобто «100+ контактів» обслуговується, але сьогоднішні чотири не платять за
// це зайвим тапом.
//
// 📋 ФОРМАТ ЗАПИСУ (для того, хто наповнюватиме):
//   { "id", "name", "phone",
//     "category": "gov|admin|medical|utility|edu|post|safety|emergency",
//     "address": "…"  (необовʼязково — дає кнопку «На карті»),
//     "hours":   "…"  (необовʼязково — рядок «08:00–17:00»),
//     "group":   "emergency" | "local" }
// ⚠️ Нових ОБОВʼЯЗКОВИХ полів не заведено: старі записи лишаються чинними,
// міграція даних не потрібна. Невідома категорія не ламає блок — запис
// потрапляє в «Інші контакти».

// ─────────────────────────────────────────────────────────────────────────────
// 🔴 ПЕРЕРОБЛЕНО 31.08 — ЗАМОВЛЕННЯ ВОВИ. Три претензії, усі влучні:
//
//   1. «телефони громади мають бути ЗВЕРХУ, а екстрені знизу — 101/102/103 і
//      так всі знають; а от телефони громади не кожен знає». Порядок
//      перевернуто: спершу те, чого людина НЕ знає напамʼять.
//   2. «мені не подобається, що вони в списках, в таких категоріях».
//      📐 Заміряно на живих даних (`data/community.json`): контактів **9**, у
//      громаді після відділення екстрених лишається **4** — сільрада, ЦНАП,
//      амбулаторія, Волиньобленерго. Вони були розкладені на **3 категорії**,
//      тобто три заголовки на чотири номери: СТРУКТУРА БІЛЬША ЗА ВМІСТ.
//      Тепер список ПЛАСКИЙ, поки контактів мало, а групи вмикаються самі
//      (`GROUP_FROM`), коли їх справді стає багато.
//   3. «іконки у вигляді смайлів, а ми домовились що емодзі не буде».
//      Правда: цей файл лишався ОСТАННІМ острівцем емодзі (🏛 🏥 ⚡ 📦 👮 📇
//      🚨 🏘 ⧉ 📍) при тому, що `core/icons.js` існує з 12.07 і решта
//      застосунку давно векторна. Замінено на Tabler-іконки з того самого
//      набору — однакова товщина лінії (1.75) і колір від `currentColor`.
// ─────────────────────────────────────────────────────────────────────────────

import { escapeHtml, showToast } from '../core/utils.js';
import { ICONS } from '../core/icons.js';

// Скільки контактів громади показувати розкритими. 6 — стільки вміщується на
// екран без прокрутки разом із заголовками груп; більше вже вимагає згортання.
const AUTO_OPEN_MAX = 6;

// Екстрені номери, які мусять бути на видноті завжди і в цьому порядку.
// ⚠️ Порядок не алфавітний і не «як у даних» — це послідовність, яку люди
// знають напам'ять з дитинства (101 → 102 → 103), і ламати її не можна.
const EMERGENCY_ORDER = ['101', '102', '103', '104', '112'];

// Категорії громади. Ключ = поле `category` у даних, значення = як це назвати
// людині. Порядок тут визначає порядок груп на екрані.
// ⚠️ `gov` і `admin` навмисно зведені в одну групу: сільрада і ЦНАП — це для
// людини «куди йти по документи», а не дві різні гілки влади.
// ⚠️ Значок бере кожен КОНТАКТ, а не лише заголовок групи: у пласкому списку
// заголовків груп немає взагалі, і без цього рядки лишились би без знаків.
const CATEGORIES = [
  { keys: ['gov', 'admin'], icon: ICONS.bank,        title: 'Органи влади' },
  { keys: ['medical'],      icon: ICONS.stethoscope, title: 'Медицина' },
  // Лампочка, а не блискавка: єдина комунальна служба в даних —
  // Волиньобленерго, тобто СВІТЛО. Значок уже є в наборі, новий не заводимо.
  { keys: ['utility'],      icon: ICONS.bulb,        title: 'Комунальні служби' },
  { keys: ['post'],         icon: ICONS.mail,        title: 'Пошта' },
  { keys: ['edu'],          icon: ICONS.bulb,        title: 'Освіта' },
  { keys: ['safety'],       icon: ICONS.shield,      title: 'Безпека' },
];
const OTHER = { icon: ICONS.phone, title: 'Інші контакти' };

// Значок для одного контакту — за його категорією. Невідома категорія віддає
// загальну трубку, а не порожнечу: дірка в сітці помітніша за приблизний знак.
function iconOf(c) {
  const cat = CATEGORIES.find(x => x.keys.includes(c.category));
  return (cat || OTHER).icon;
}

// 🔴 З якої кількості вмикати групи. Поки контактів мало, заголовок групи —
// це рядок, що коштує висоти і не несе інформації («Медицина (1)» над одним
// рядком). Коли їх стане більше — групи вмикаються самі, код і дані вже готові.
// ⚠️ Це та сама думка, що жила в `AUTO_OPEN_MAX`, але доведена до кінця: там
// групи лишались НАЗАВЖДИ і лише розкривались; тут при малій кількості їх
// немає зовсім.
const GROUP_FROM = 9;

// Для набору `tel:` лишаємо лише цифри і плюс.
const telOf = p => String(p || '').replace(/[^\d+]/g, '');

// ⚠️ `plural()` прибрано 31.08 разом із лічильником «4 контакти»: лічильник жив
// у заголовку «Служби громади», а сам заголовок зник як дубль назви секції.
// Чотири рядки людина перелічує оком швидше, ніж читає про них число.

// ── Екстрені ─────────────────────────────────────────────────────────────────
// Однакові компактні плитки. Тап = дзвінок одразу, без проміжного екрана:
// у цьому блоці кожна зайва дія коштує секунд.
function emergencyHtml(list) {
  const rank = c => {
    const i = EMERGENCY_ORDER.indexOf(String(c.phone || '').trim());
    return i === -1 ? 99 : i;
  };
  const sorted = [...list].sort((a, b) => rank(a) - rank(b));
  return `
    <div class="hm-sos">
      ${sorted.map(c => `
        <a class="hm-sos-b" href="tel:${escapeHtml(telOf(c.phone))}">
          <span class="hm-sos-n">${escapeHtml(c.phone)}</span>
          <span class="hm-sos-t">${escapeHtml(c.name)}</span>
        </a>`).join('')}
    </div>`;
}

// ── Контакти громади ─────────────────────────────────────────────────────────

// 🔴 01.09 — ДРУГИЙ НОМЕР (поле `phone2`) + ПЕРЕБУДОВА КАРТКИ (сесія «c»).
//
// 🗣️ ТРИ ПРЕТЕНЗІЇ ВОВИ, дослівно:
//   1. «номер має бути під номером… номер А, далі вулиця Замкова, 17»;
//   2. пін і копіювати «розташовані хаотично… якщо коротка назва, вона зразу за
//      ним стоїть, якщо довга — то далі… щоб копіювати було під копіювати, а
//      пін під піном»;
//   3. «іконки… відцентрувати вертикально, по центру самого тексту».
//
// 📐 ЗАМІРЯНО ЖИВИМ БРАУЗЕРОМ (не на око — учора прилад брехав шість разів):
//   • порядок рядків ЦНАПу був `name → phone → АДРЕСА → phone2`;
//   • кнопка «копіювати» мала ТРИ різні позиції: x=267 (картки з адресою),
//     294.7 (Соцзахист, довга назва), 249.2 (Волиньобленерго, коротка);
//   • значок стояв рівно по центру ТЕКСТУ (0.0px), але на −16.0px від центру
//     КАРТКИ ЦНАПу.
//
// 🔬 КОРІНЬ (2) — РЕГРЕС МОГО Ж ВЧОРАШНЬОГО PR #1134. Обгортка `.hm-ct-row`,
// додана заради другого номера, не мала `flex-grow`, тобто стискалась ПО ВМІСТУ,
// і кнопки їхали за текстом. Три картки з адресою виглядали рівно ВИПАДКОВО:
// їхня адреса переносить рядок, вміст упирається в максимум, і край збігається
// з краєм картки. Тобто вада ховалась за збігом — рівно той клас, який ловиться
// лише виміром, а не поглядом.
//
// 🔑 (3) — НЕ ОКРЕМА ВАДА, А НАСЛІДОК (1). Значок центрувався всередині
// `.hm-ct-row`, а рядок другого номера лежав ПОЗА нею, тож картка була вища за
// те, по чому рахувався центр. Щойно номер став частиною тієї самої текстової
// колонки, центр збігся сам — окремого правила не знадобилось.
//
// ─────────────────────────────────────────────────────────────────────────────
// 🛑 ГОЛОВНЕ РІШЕННЯ: STRETCHED LINK (розтягнуте посилання).
//
// Другий номер мусить стояти ПІД першим, тобто всередині тієї самої текстової
// колонки. Але обидва — посилання `tel:`, а **посилання в посиланні браузер
// «лікує» сам**: розмітка недійсна, і другий номер може просто не набратись.
// Тому велике посилання більше НЕ обгортає картку.
//
// ✅ Щоб не втратити перевірену пальцем поведінку «тап будь-де по картці =
// дзвінок на ПЕРШИЙ номер» (Вова підтвердив її 01.09; HOT_RULES №9 — перевірене
// не ламаємо), перший номер лишається посиланням, але розтягує невидиму ціль на
// всю картку через `::after { inset: 0 }`.
// 🔑 Чому саме цей прийом, а не обробник кліку на картці: він не додає JS, не
// чіпає делегування «копіювати» (воно й далі ловить `closest('[data-copy]')`) і
// **не рухає розкладку** — а отже з-під пальця між `pointerdown` і `click`
// нічого не зникає (HOT_RULES №10, кейс 26.07, який коштував базової дії).
//
// ⚠️ Другий номер і кнопки лежать НАД накладкою (`z-index: 1`) — інакше вони
// стали б недосяжні, і тап по «копіювати» набирав би номер.
//
// 📐 ЧОМУ ПІН СТОЇТЬ ПЕРЕД «КОПІЮВАТИ», А НЕ НАВПАКИ (претензія Вови №2).
// Вимога — «копіювати під копіювати, пін під піном». Перший підхід резервував
// порожній слот піна (`min-width: 88px`), і він працював — але заміряно ціну:
// колонка тексту на картках БЕЗ адреси звужувалась 189.7 → 164px, назва
// «Соцзахист (за записом)» переносилась у два рядки, картка росла 56 → 71.9px.
// ✅ Порядок «пін, потім копіювати» + притискання праворуч дає ті самі рівні
// стовпці БЕЗ резерву: «копіювати» завжди біля правого краю, пін — на 44px
// лівіше, а там, де піна немає, ця ширина дістається тексту.
// 🔑 Тобто вимога Вови виконується двома способами, і дешевший — цей.
// ─────────────────────────────────────────────────────────────────────────────
function contactHtml(c) {
  const tel = telOf(c.phone);
  const tel2 = c.phone2 ? telOf(c.phone2) : '';
  const meta = [c.hours, c.address].filter(Boolean).map(escapeHtml).join(' · ');
  return `
    <div class="hm-ct">
      <span class="hm-ct-ic" aria-hidden="true">${iconOf(c)}</span>
      <span class="hm-ct-txt">
        <span class="hm-ct-name">${escapeHtml(c.name)}</span>
        <a class="hm-ct-main hm-ct-phone" href="tel:${escapeHtml(tel)}">${escapeHtml(c.phone)}</a>
        ${tel2 ? `<a class="hm-ct-alt hm-ct-phone" href="tel:${escapeHtml(tel2)}">${escapeHtml(c.phone2)}</a>` : ''}
        ${meta ? `<span class="hm-ct-meta">${meta}</span>` : ''}
      </span>
      <span class="hm-ct-acts">
        ${c.address
          ? `<a class="hm-ct-act" href="https://maps.google.com/?q=${encodeURIComponent(c.address)}" target="_blank" rel="noopener noreferrer" aria-label="Відкрити на карті">${ICONS.pin}</a>`
          : ''}
        <button class="hm-ct-act" type="button" data-copy="${escapeHtml(c.phone)}" aria-label="Копіювати номер">${ICONS.copy}</button>
      </span>
    </div>`;
}

function groupHtml(g, open) {
  return `
    <details class="hm-cgrp"${open ? ' open' : ''}>
      <summary class="hm-cgrp-sum">
        <span class="hm-cgrp-ic" aria-hidden="true">${g.icon}</span>
        <span class="hm-cgrp-t">${escapeHtml(g.title)}</span>
        <span class="hm-cgrp-n">${g.items.length}</span>
      </summary>
      <div class="hm-cgrp-body">${g.items.map(contactHtml).join('')}</div>
    </details>`;
}

// Розкласти контакти по категоріях у порядку CATEGORIES. Порожні категорії не
// створюються — мертвий рядок «Пошта (0)» гірший за його відсутність.
function groupContacts(list) {
  const groups = [];
  const used = new Set();
  for (const cat of CATEGORIES) {
    const items = list.filter(c => cat.keys.includes(c.category));
    items.forEach(c => used.add(c));
    if (items.length) groups.push({ ...cat, items });
  }
  const rest = list.filter(c => !used.has(c));
  if (rest.length) groups.push({ ...OTHER, items: rest });
  return groups;
}

export async function renderContactsBlock() {
  const el = document.getElementById('cm-contacts-content');
  if (!el) return;

  try {
    const res = await fetch('./data/community.json');
    const data = await res.json();
    const list = data.contacts || [];
    if (!list.length) {
      el.innerHTML = '<div class="hm-empty">Контактів немає</div>';
      return;
    }

    // 🔴 РОЗДІЛЕННЯ — головна суть цієї переробки.
    // «Пожежна 101» не є телефоном ГРОМАДИ: це загальнодержавна служба. Поки
    // вони лежали під заголовком «Телефони громади», заголовок казав неправду.
    const isEmergency = c => c.group === 'emergency' || c.group === 'hero' || c.priority === 'critical';
    // ⚠️ Волиньобленерго стоїть у даних із `group: emergency`, але його
    // `category` — `utility`. Це не екстрена служба, а комунальна: у блок
    // швидкого набору вона не потрапляє, бо туди йдуть лише короткі номери
    // зі списку EMERGENCY_ORDER.
    const sos = list.filter(c => isEmergency(c) && EMERGENCY_ORDER.includes(String(c.phone || '').trim()));
    const local = list.filter(c => !sos.includes(c));

    // 🔴 ПОРЯДОК ПЕРЕВЕРНУТО 31.08 — і це не косметика, а зміна призначення блока.
    // Слово Вови: «екстрені служби і так всі прекрасно знають… 101, 102, 103 —
    // так зрозуміло. А от телефони громади — це такі телефони, які вже не кожен
    // може знати повністю».
    // 🔑 Тобто вгорі має стояти те, чого людина НЕ памʼятає, а не те, що
    // виглядає найтривожніше. Екстрені лишаються на сторінці й нікуди не
    // зникають — вони просто нижче, за один рух пальця.
    //
    // ⚠️ Групи проти плаского списку. `local.length` сьогодні = 4, і три
    // заголовки категорій над чотирма рядками були рівно тим, на що скаржився
    // Вова. Пласко до `GROUP_FROM`, далі — групами; жодна з двох гілок не є
    // «тимчасовою», обидві робочі.
    const flat   = local.length < GROUP_FROM;
    const groups = flat ? [] : groupContacts(local);

    el.innerHTML =
      // ⚠️ Свого заголовка тут НЕМАЄ навмисно: секція на сторінці вже
      // називається «Телефони громади» (`tabs/community.js`). Подвійний
      // заголовок — окрема відома вада проєкту, її вже прибирали з віджета
      // Дошки 04.08 («Оголошення» + «АКТУАЛЬНІ ОГОЛОШЕННЯ ГРОМАДИ»).
      (local.length ? `
        <div class="hm-csec">
          ${flat
            ? `<div class="hm-ctlist">${local.map(contactHtml).join('')}</div>`
            : groups.map(g => groupHtml(g, local.length <= AUTO_OPEN_MAX)).join('')}
        </div>` : '') +
      (sos.length ? `
        <div class="hm-csec hm-csec--sos">
          <div class="hm-csec-h">Екстрені служби</div>
          ${emergencyHtml(sos)}
        </div>` : '');

    // Копіювання номера. Один слухач на блок; вішається раз.
    if (!el.dataset.wired) {
      el.dataset.wired = '1';
      el.addEventListener('click', async e => {
        const btn = e.target.closest('[data-copy]');
        if (!btn) return;
        e.preventDefault();
        const num = btn.dataset.copy;
        try {
          // `navigator.clipboard` існує лише в захищеному контексті (https або
          // localhost). На проді це https, але запас потрібен: без нього тап у
          // незахищеному контексті мовчки нічого не робив би.
          if (navigator.clipboard && window.isSecureContext) {
            await navigator.clipboard.writeText(num);
          } else {
            const ta = document.createElement('textarea');
            ta.value = num; ta.style.position = 'fixed'; ta.style.opacity = '0';
            document.body.appendChild(ta); ta.select();
            document.execCommand('copy'); ta.remove();
          }
          showToast(`Скопійовано: ${num}`);
        } catch {
          showToast('Не вдалося скопіювати', 0, 'error');
        }
      });
    }
  } catch {
    el.innerHTML = '<div class="hm-empty">Контакти недоступні</div>';
  }
}
