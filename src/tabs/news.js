// показує — ніхто нічого не перевимірює вдруге.
//
// ⚠️ `contentSource` немає у статей, спаршених ДО 12.08 — для них лишається
// старий доказ (`fullText !== true` і тіло коротке). Це не «про всяк випадок»:
