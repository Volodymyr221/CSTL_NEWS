// віджет стрибати на кожному переході — саме те, чого Вова просив уникнути («плавно,
// без ривків»).
//
// 🔑 ЧОМУ НЕ «ОДНА ФОРМА З ФІКСОВАНОЮ ВИСОТОЮ». Допис із фото і допис із самим текстом
// різняться не на відсотки, а в рази (заміряно на чинній картці: 302px проти 123px).
// Одна форма означала б, що допис без знімка отримує півкартки порожнечі — рівно вада,
// яку вже лікували в PR #943 («картка без фото не тримає порожнечі»).
//
// ✅ ЗАМІСТЬ ЦЬОГО — форма підбирається під вміст, а висота лишається спільною:
//   `--photo` — текст коротким підписом (2 рядки), знімок забирає весь залишок висоти;
//   `--text`  — знімка немає, тож текст дістає БІЛЬШИЙ КЕГЛЬ і всі рядки картки.
// Так обидві виглядають повними, і жодна не тримає порожнечі.
function postHtml(p, page = null) {
  page = page || p.pages || {};
  const name = page.name || 'Громада';
  const img = p.image_url || (Array.isArray(p.image_urls) ? p.image_urls[0] : null);
  // 📐 170 / 700 — під ЧОТИРИ рядки підпису під знімком і ЧОТИРНАДЦЯТЬ рядків
  // суцільного тексту (стеля картки, виведена в `home.css`).
  // 🔴 28.08 — БУЛО 520, І ЦЕ РІЗАЛО РАНІШЕ ЗА КАРТКУ. Обидві стелі різали той самий
  // текст, тобто одна з них завжди зайва — а яка саме, залежало від довжини слів.
  // 🔑 Стеля має бути ОДНА, і саме та, що міряє РЯДКИ: `-webkit-line-clamp` рахує
  // намальовані рядкові коробки (порожній рядок абзацу теж), а символи їх лише
  // вгадують. Тут лишається запас, щоб clamp завжди встигав спрацювати першим.
  // 🔴 02.09 — 170 → 400 ДЛЯ КАРТКИ ЗІ ЗНІМКОМ. Підпис більше не має фіксованих
  // чотирьох рядків: коли кадр широкий, він займає менше висоти, і вивільнене місце
  // віддається тексту (`--hm-fd-lines` рахує `fitPhotoCards`). Зі старим лімітом
  // 170 символів показувати в тих рядках було б НІЧОГО — текст закінчувався раніше.
  // 🛑 Це навмисно ЗАПАС, а не друга стеля: різати має лише `line-clamp` (урок 28.08
  // — дві стелі на тому самому тексті означають, що одна завжди зайва).
  const txt = preview(p.text, img ? 400 : 700, !!img);
  const ava = page.avatar_url
    ? `<img src="${escapeHtml(page.avatar_url)}" alt="">`
    : `<span class="hm-fd-p-tx">${escapeHtml(initial(name))}</span>`;

  return `
    <article class="hm-card hm-card--tap hm-fd-post hm-fd-post--${img ? 'photo' : 'text'}"
      data-fd-page="${escapeHtml(String(p.page_id ?? ''))}" data-fd-post="${escapeHtml(String(p.id ?? ''))}">
      <span class="hm-fd-p-head">
        <span class="hm-fd-p-av">${ava}</span>
        <span class="hm-fd-p-who">
          <span class="hm-fd-p-name">${escapeHtml(name)}</span>
          <span class="hm-fd-p-when">${escapeHtml(formatTime(p.created_at))}</span>
        </span>
      </span>
      ${txt ? `<span class="hm-fd-p-txt">${escapeHtml(txt)}</span>` : ''}
      ${img ? `<span class="hm-fd-p-img"><img src="${escapeHtml(img)}" alt="" loading="lazy"></span>` : ''}
    </article>`;
}

