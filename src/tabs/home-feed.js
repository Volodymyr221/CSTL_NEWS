// вкладений запис, щоб функція лишалась придатною і поза віджетом.
// 🔴 25.08 — ДВІ ФОРМИ КАРТКИ ОДНАКОВОЇ ВИСОТИ.
// Скарга Вови: «пост обрізається, треба вертикально збільшити». Але просто підняти
