function initial(name) {
  const n = (name || '').trim();
  return n ? n[0].toUpperCase() : '•';
}

// Текст допису для картки, обрізаний ПО МЕЖІ СЛОВА.
// 🔑 Стеля залежить від того, є в допису фото чи ні (25.08): без фото текст лишається
// сам на картці й дістає і більше місця, і більший кегль, тож 150 символів залишили б
// половину картки порожньою. З фото він навпаки мусить бути коротким — це підпис до
// знімка, а не сам допис.
// 🔴 28.08 — АБЗАЦИ БІЛЬШЕ НЕ ЗНИКАЮТЬ. Скарга Вови по знімку: у віджеті допис іде
// суцільною плитою, а в самій Стрічці він розбитий на абзаци.
// 📐 Корінь був в одному символі: `\s` у регулярному виразі означає БУДЬ-ЯКИЙ пробільний
// символ, разом із переносом рядка. Тобто `replace(/\s+/g, ' ')` зводив порожній рядок між
// абзацами до звичайного пробілу — структура тексту зникала ще до показу.
// 🔑 Рішення Вови (варіант «А»): у віджеті абзац = ОДИН перенос рядка, без порожнього.
// Причина не смакова, а вимірна: у картці з фото видно лише 4 рядки, і порожній рядок
// зʼїдав би чверть прев'ю. Одне правило на обидва типи карток — саме це й називається
// стандартизацією; повний абзац із порожнім рядком лишається в Стрічці, де показують
// увесь допис, а не його початок.
function preview(text, limit) {
  const t = (text || '')
    .replace(/[^\S\n]+/g, ' ')      // пробіли й табуляції — в один пробіл, ПЕРЕНОСИ не чіпаємо
    .replace(/\n{2,}/g, '\n')       // порожні рядки між абзацами — в один перенос (варіант «А»)
    .replace(/ *\n */g, '\n')       // прибрати пробіли, що прилипли до переносу
    .trim();
  if (t.length <= limit) return t;
  const cut = t.slice(0, limit);
  // ⚠️ Межу слова шукаємо по БУДЬ-ЯКОМУ пробільному символу, а не лише по пробілу:
  // після правки вище текст містить переноси, і `lastIndexOf(' ')` міг би вказати
  // далеко назад, обрізавши цілий абзац.
  const sp = cut.search(/\s\S*$/);
  // Межу слова шукаємо лише в останній третині: інакше на тексті без пробілів
  // (одне довге слово) обрізка з'їла б дві третини рядка.
  return (sp > limit * 0.6 ? cut.slice(0, sp) : cut) + '…';
}

// 🔴 25.08 — ДОВГІ НАЗВИ СКОРОЧУЮТЬСЯ ЗМІСТОВНО, А НЕ БАГАТОКРАПКОЮ.
// 🗣️ Слово Вови по скріну: «КЦ «ЦЕНТР КУЛЬТУРИ,...» — обрізка посеред слова не каже
// нічого. Рішення: «назви залишити, але довгі скорочувати розумніше».
//
// 🔑 ПРАВИЛО: назва спільноти майже завжди має ЯДРО в лапках, а все зайве — після коми.
//   «КЦ «Центр культури, спорту та дозвілля»» → «КЦ «Центр культури»»
// Тобто ріжемо по МЕЖІ ЗМІСТУ (лапки, кома), а не по числу символів. Багатокрапка
// лишається крайнім заходом — коли розрізати нема по чому.
//
// ⚠️ Скорочується ЛИШЕ те, що показано на екрані: повна назва їде в `title` і
// `aria-label`, тож читач екрана і довгий дотик дають людині справжню назву.
const NAME_FIT = 22;   // стільки символів тримають два рядки підпису на 390pt

function shortPageName(name) {
  const n = (name || '').trim();
  if (n.length <= NAME_FIT) return n;

  // 1. Ядро в лапках — найнадійніша межа змісту.
  const q = n.match(/^(.*?)[«"]([^»"]+)[»"]?(.*)$/);
  if (q) {
    const до = q[1].trim();
    for (const ядро of [q[2].split(',')[0].trim(), q[2].trim().split(/\s+/)[0]]) {
      const кандидат = (до ? до + ' ' : '') + '«' + ядро + '»';
      if (кандидат.length <= NAME_FIT + 4) return кандидат;
    }
  }

  // 2. Кома теж є межею змісту: «Центр культури, спорту та дозвілля» → «Центр культури».
  const доКоми = n.split(',')[0].trim();
  if (доКоми.length <= NAME_FIT + 4 && доКоми.length < n.length) return доКоми;

  // 3. Розрізати нема по чому — обрізаємо по межі слова.
  const cut = n.slice(0, NAME_FIT);
  const sp = cut.lastIndexOf(' ');
  return (sp > NAME_FIT * 0.5 ? cut.slice(0, sp) : cut) + '…';
}

function circleHtml(page, fresh) {
  const name = page.name || 'Канал';
  const короткa = shortPageName(name);
  const inner = page.avatar_url
    ? `<img src="${escapeHtml(page.avatar_url)}" alt="" loading="lazy">`
    : `<span class="hm-fd-c-tx">${escapeHtml(initial(name))}</span>`;
  // `title` і `aria-label` несуть ПОВНУ назву — скорочення живе лише на екрані.
  return `
    <span class="hm-fd-c${fresh ? ' hm-fd-c--new' : ''}" data-fd-page="${escapeHtml(String(page.id ?? ''))}" title="${escapeHtml(name)}">
      <span class="hm-fd-c-ring"><span class="hm-fd-c-av">${inner}</span></span>
      <span class="hm-fd-c-name" aria-label="${escapeHtml(name)}">${escapeHtml(короткa)}</span>
    </span>`;
}

