const ЧЕКАТИ_ГЕО_МС = 1200;

async function поточнеСело() {
  // Обране місце знаємо миттєво, без мережі й без дозволів — тому воно перше.
  const обране = pickedPlace();
  if (обране) return обране;
  if (_гдеЯ !== null) return _гдеЯ || null;
  if (!_гдеЯПошук) _гдеЯПошук = обчислитиСело();
  const швидко = await Promise.race([
    _гдеЯПошук,
    new Promise(r => setTimeout(() => r(undefined), ЧЕКАТИ_ГЕО_МС)),
  ]);
  return швидко || null;
}

async function обчислитиСело() {
  try {
    const c = await getCoords();
    // 🔴 ЗАПАСНІ КООРДИНАТИ — НЕ МІСЦЕ ЛЮДИНИ. `getCoords()` за відмови в
    // дозволі (або за таймаутом 4с) віддає координати ОЛИКИ — правильно для
    // погоди, але тут означало б «ти в Олиці» для кожного, хто дозволу не дав.
    // Розрізняє їх поле `city`: у справжньої позиції воно порожнє.
    _гдеЯ = (c && c.city == null) ? ((await nearestSettlement(c)) || '') : '';
  } catch { _гдеЯ = ''; }
  return _гдеЯ || null;
}

// Зупинка посадки: місце з погоди → де я фізично → анкета → Олика.
async function мояЗупинка() {
  return (await поточнеСело()) || (await mySettlement()) || HOME_STOP;
}

