let _place = null;
let _placeFor = null;
async function mySettlement() {
  const uid = currentUserId();
  if (!uid) return null;
  if (_placeFor === uid) return _place;
  try {
    const pr = await getProfile();
    _place = (pr && pr.settlement) || null;
    _placeFor = uid;
  } catch { return null; }
  return _place;
}

