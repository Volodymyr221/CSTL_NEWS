  // пропонує їй.
  // ⚠️ Питання живе в полі `text`, а НЕ `title`: форма створення має рівно одне
  // поле, і саме `p.text` малює картка у вкладці «Питання». Слова «Потрібна
  // відповідь» теж узяті звідти — щоб той самий стан не називався на головній
  // інакше, ніж у своєму розділі.
  const q = unansweredQuestion(posts);
