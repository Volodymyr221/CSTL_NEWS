  // `fitLine` ріже ЛИШЕ останній щабель, тож слово-запасне з'їдало б саму себе:
  // при довгій назві воно вміщалось, драбина зупинялась на ньому — і людина знову
  // бачила голе «ПОВІДОМЛЕННЯ» замість «ПРОДАМ БУДИНОК…». Спіймано контрольним
  // прогоном стенда, а не міркуванням.
  // ➡️ Правило ролі: останній щабель — це те, що МОЖНА обрізати.
