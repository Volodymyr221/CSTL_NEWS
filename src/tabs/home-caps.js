// 🛑 Крапок циклу тут більше немає — показувати нічого, бо рядок один.
function capHtml(c) {
  return `
    <button class="hm-cap2" type="button" data-cap="${escapeHtml(c.key)}"${
      c.aria ? ` aria-label="${escapeHtml(c.aria)}"` : ''}>
      <span class="hm-cap2-ic" aria-hidden="true">${c.icon}</span>
      <span class="hm-cap2-tx">
        <span class="hm-cap2-k">${escapeHtml(c.label)}</span>
        <span class="hm-cap2-v">${escapeHtml(c.value)}</span>
      </span>
    </button>`;
}

// ── СКІЛЬКИ МІСЦЯ Є НАСПРАВДІ ────────────────────────────────────────────────
//
// 🔴 Замовлення Вови 17.08: «в капсулу має влазити хоча б певна інформація, а не
// обрізатися на половині». Щоб це виконати, треба знати ширину рядка ДО того, як
// складено текст. Тому в смугу на мить ставиться невидима капсула-зразок, з неї
// знімається геометрія обох рядків — і вона прибирається.
//
// 🔑 Чому зразок, а не готова капсула: інакше довелось би спершу намалювати текст,
// потім переміряти і перемалювати — тобто два записи в DOM на кожен рендер, і той
// самий «блим», який лікували 15.08 (`core/list-patch.js`).
// ⚠️ Кеш по ШИРИНІ СМУГИ: поворот екрана або інший телефон дають інше число, а
// в межах однієї ширини міряти щоразу нема сенсу.
let _metricsFor = 0;
let _metrics = null;
function capMetrics(box) {
  const ширина = box.clientWidth;
  if (_metricsFor === ширина && _metrics) return _metrics;
  const зразок = document.createElement('div');
  // 🔴 ЗРАЗОК ЛЕЖИТЬ У ПОТОЦІ, А НЕ `position:absolute`, і текст у ньому НАВМИСНО
  // задовгий. Перша редакція зробила навпаки — і це показовий випадок брехливої
  // мірки: `.hm-cap2-v` це flex-елемент із `min-width: 0`, тобто його ширина
  // дорівнює ВМІСТУ, поки вміст коротший за вільне місце. Зі зразком «X» вимір
  // давав ≈8px, `fitLine` чесно вміщав у 8px рівно одну літеру, і КОЖНА капсула
  // на екрані ставала «О…». Тобто зламався не рядок, а лінійка.
  // ✅ Задовгий текст переростає доступне місце, і ширина зупиняється рівно на
  // тому, що є (`overflow: hidden` + `nowrap` уже стоять у CSS).
  // ⚠️ `height:0` + `overflow:hidden` — щоб зразок нічого не зсунув; він живе
  // менше за кадр (додали → зміряли → прибрали в тому самому виклику).
  зразок.style.cssText = 'visibility:hidden;height:0;overflow:hidden;pointer-events:none';
  const довгий = 'Ш'.repeat(200);
  зразок.innerHTML = capHtml({ key: 'probe', icon: '', label: довгий, value: довгий });
  box.appendChild(зразок);
  const m = {
    label: lineMetrics(зразок.querySelector('.hm-cap2-k')),
    value: lineMetrics(зразок.querySelector('.hm-cap2-v')),
  };
  зразок.remove();
  // Нуль ширини (смуга ще прихована) — не кешуємо: наступний рендер зміряє знову.
  if (!m.label && !m.value) return null;
  _metricsFor = ширина; _metrics = m;
  return m;
}

// Обрати обидва рядки капсули під живу геометрію.
// 🛑 Мітка проходить ТУ САМУ драбину, що й значення: до 17.08 у ній стояло одне
// слово і думати про ширину не було потреби, тепер вона несе контекст і цілком
// може не вміститись. Кожна роль сама вирішує, чим жертвувати першим — саме тому
// це драбина готових рядків, а не частини зі спільним роздільником.
function fitCap(c, m) {
  return { ...c,
    label: fitLine(c.labelVariants, m && m.label),
    value: fitLine(c.valueVariants, m && m.value),
  };
}

// Перемальовування зі своїх приводів. Підписки ставимо ОДИН раз на модуль —
// інакше вони накопичувались би на кожен рендер (той самий урок, що з
// `_threadsEvtWired` у `board.js`).
let _wired = false;
function wireCapsRefresh() {
  if (_wired) return;
  _wired = true;
  // Повернувся на Громаду → капсули перечитано (антифлуд 5с — усередині примітива).
  onReturn('community', () => renderHomeCaps());
  // Вхід/вихід міняє все: МОЄ зʼявляється, село в НОВЕ теж.
  onAuthChange(() => { _place = null; _placeFor = null; renderHomeCaps(); });
  // Увімкнув/зняв відстеження рейсу — ЗАРАЗ мусить це відбити одразу.
  window.addEventListener('cstl-bus-track-changed', () => renderHomeCaps());
  // Відповіді на питання приїхали (їх вантажить Дошка при старті, паралельно з
  // Громадою) — тільки тепер можна чесно сказати «без відповіді».
  window.addEventListener('cstl-discussions-data', () => renderHomeCaps());
  // Зліпок непрочитаного оновився (вхід, push, realtime, прочитання розмови) —
  // капсула повідомлень мусить зʼявитись/зникнути тим самим кроком, що й бейджі.
  window.addEventListener('cstl-unread-changed', () => renderHomeCaps());
  // 🔴 22.08 — під моїм дописом у Стрічці щойно відповіли (подію кидає ЖИВА
  // підписка самої Стрічки, вже відфільтрована по «це моє» — див.
  // `notifyCapsIfMine` у tabs/feed.js). Своєї підписки тут немає навмисно:
  // другий канал на ту саму подію — це шлях до B-27.
  window.addEventListener('cstl-feed-mine-changed', () => renderHomeCaps());
  // 🔴 24.08 — мітки «бачив» приїхали з бази (інший пристрій того самого
  // акаунта). Без цього рядка синхронізація була б МОВЧАЗНОЮ: капсули вже
  // намальовані зі старим значенням, і правда доїхала б лише при наступному
  // перемиканні вкладки — тобто виглядало б як «не працює».
  window.addEventListener('cstl-seen-synced', () => renderHomeCaps());
}

// Покоління рендера: три ролі ходять у мережу, і повільна відповідь старого
// виклику не має перетирати свіжий (перемикання вкладок туди-сюди).
let _gen = 0;
// Підпис намальованого — щоб не перемальовувати те, що не змінилось (див. нижче).
let _paint = '';

export async function renderHomeCaps() {
  const el = document.getElementById('hm-caps');
  if (!el) return;
  wireCapsRefresh();
  const gen = ++_gen;

  // allSettled, а не all: падіння однієї ролі не має забирати з екрана решту.
  const результати = await Promise.allSettled([myCapsule(), nowCapsule(), newCapsule(), msgCapsule(), answersCapsule(), feedCapsule()]);
  if (gen !== _gen) return;
  const caps = результати
    .map(r => (r.status === 'fulfilled' ? r.value : null))
    .filter(Boolean)
    // ⚖️ Порядок вирішує БАЛ, а не те, у якому порядку ролі приїхали з мережі.
    // 🛑 `rank` мусить бути в кожної ролі: без нього (`undefined`) порівняння дає
    // NaN і сортування мовчки лишає порядок таким, яким його віддав allSettled —
    // тобто шкала «ніби працює», а насправді ні. Тому запасне 0, а не «якось».
    .sort((a, b) => (b.rank || 0) - (a.rank || 0))
    .slice(0, MAX_CAPS);

  // Немає жодної ролі з даними — смуги немає зовсім (не порожня коробка).
  if (!caps.length) { el.hidden = true; el.innerHTML = ''; _paint = ''; return; }

  el.hidden = false;
  // Складаємо рядки під ЖИВУ ширину — після зняття `hidden`, інакше зразок міряв
  // би приховану смугу і віддав нуль.
  const m = capMetrics(el);
  const готові = caps.map(c => fitCap(c, m));
  // ⚠️ Не перемальовуємо те, що не змінилось. Капсули тепер перечитуються на
  // КОЖНЕ повернення на Громаду, а безумовна заміна `innerHTML` — це той самий
  // клас вади, який ловили у Стрічці й на Дошці 15.08 («контент ніби блимає»).
  // Порівнюємо РЯДОК РОЗМІТКИ, а не список полів: однаковий рядок = однакова
  // картинка за визначенням, і забути поле неможливо (урок `core/list-patch.js`).
  // 🛑 І не звіряємось із `el.innerHTML` — браузер його нормалізує, рядки не
  // збіглися б ніколи, і запобіжник мовчки не працював би.
  const розмітка = готові.map(capHtml).join('');
  if (розмітка !== _paint) { _paint = розмітка; el.innerHTML = розмітка; }
  el.classList.add('hm-appear');

  // Тап по капсулі → її обʼєкт. Слухач один на контейнер.
  el.onclick = e => {
    const btn = e.target.closest('[data-cap]');
    if (!btn) return;
    const c = caps.find(x => x.key === btn.dataset.cap);
    if (c && c.tap) c.tap();
  };
}
