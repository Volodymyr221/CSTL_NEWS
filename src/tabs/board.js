//
// 📐 Заміряно на 17 живих оголошеннях: картка 96px, до першої картки 214px,
// без прокрутки видно 6 карток.
// 🔴 03.08 — ДВА РЯДКИ ОПИСУ НА КАРТЦІ (замовлення Вови: «добавити рядок чи два
// опису, щоб зразу було ясно»). Заголовки на кшталт «Продаю машину» самі по собі не
// кажуть нічого — людина однаково мусила відкрити картку, щоб зрозуміти, що продають.
//
// ⚠️ ОПИС, ЩО ДУБЛЮЄ ЗАГОЛОВОК СЛОВО В СЛОВО, НЕ МАЛЮЄМО. Порівнюємо ЗМІСТ, а не рядки:
// знімаємо регістр, розділові знаки й повторні пробіли.
//
// 🔴 03.08 — ПОРІГ ПОСЛАБЛЕНО. Спершу тут відсікалось іще й «заголовок + менше 20
// символів», і на живих даних це прибирало опис у 7 оголошень із 18. Але саме ці 20
// символів часто і є вся конкретика: «Куплю мотоцикл» + «у робочому стані» — це вже
// відповідь на питання «який?». Заразом порожній слот робив картку на 30px нижчою за
// сусідні, і список ставав рваним.
// Тепер відсікається лише ТОЧНИЙ дубль — таких 1 із 18.
// 🔴 03.08 — ЗАГОЛОВОК СТАВ ГОЛОВНИМ АКЦЕНТОМ КАРТКИ (замовлення Вови: «щоб користувач
// міг миттєво зчитувати назву навіть при швидкому скролінгу»). КАПС робить CSS
// (`text-transform: uppercase`) — дані не чіпаємо: оригінальне написання потрібне
// пошуку і сторінці оголошення. Заміряно в базі: 7 із 10 назв люди вже пишуть капсом,
// 3 — ні, тобто список був різнобійний саме через людей, а не через код.
//
// 🔑 ЧОМУ ТУТ ЗʼЯВИЛАСЬ ОКРЕМА ФУНКЦІЯ, А НЕ САМЕ ЛИШЕ CSS.
// Заміряно в живій базі: з 19 опублікованих оголошень **9 не мають назви взагалі**, і
// картка підставляла в заголовок УВЕСЬ текст (`p.title || p.text`), найдовший — 1296
// символів. Поки заголовок був 14.5px і тихий, це просто обрізалось двома рядками.
// Зробити такий рядок капсом 16px/800 означало б поставити на пів списку стіну крику,
// обрізану посеред слова. Тому безназвене оголошення дістає ЗАГОЛОВОК З ТЕКСТУ —
// перше речення, — а решта тексту йде в рядок опису під ним.
// 🔑 06.08 — `clampChars` / `cardTitleText` ПЕРЕЇХАЛИ у `core/board-shared.js`.
// Причина: тих самих заголовків потребує картка профілю (`core/profile-card.js`),
// а `core` не має імпортувати з `tabs` — це зворотний напрямок залежності.
// Розбір «чому заголовок узагалі рахується, а не береться як `title || text`»
// лежить тепер там, при самій функції.

function cardDescText(p) {
  const title = (p.title || '').trim();
  const text  = (p.text || '').trim();
  if (!text) return '';
  // Назви немає → заголовок узяли з ТЕКСТУ, тож в опис іде РЕШТА тексту. Без цього
  // опис починався б тими самими словами, що й заголовок над ним.
  if (!title) {
    const head = cardTitleText(p).replace(/…$/u, '');
    const rest = text.startsWith(head) ? text.slice(head.length) : text;
    return rest.replace(/^[\s.!?,;:—–-]+/u, '').trim();
  }
  const norm = v => v.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
  const nt = norm(title), nx = norm(text);
  if (nx === nt) return '';                       // текст = заголовок, слово в слово
  return text;
}

function renderCardDesc(p) {
  const d = cardDescText(p);
  return d ? `<p class="bd-ad-desc">${escapeHtml(d)}</p>` : '';
}

function renderBoardCard(p) {
  const photo = (Array.isArray(p.photos) && p.photos[0]) || p.photo;
  // 🔄 07.08 — ЗАМІСТЬ ФОТО ІКОНКА КАТЕГОРІЇ, А НЕ ПЕРША БУКВА ЗАГОЛОВКА
  // (замовлення Вови по знімках: «так як це в віджеті оголошень»).
  // Буква нічого не повідомляла: «Р» у «РЕМОНТ ПРАЛЬНИХ МАШИН» і «К» у «КУПЛЮ
  // МОТОЦИКЛ» — це просто перший символ тексту, який людина вже читає поруч.
  // Іконка категорії натомість каже те, чого в заголовку може й не бути: візок =
  // куплю, цінник = продам, подарунок = віддам.
  // 🔑 Не нова сутність: `catIcon` з `core/board-categories.js` уже малюють ДВА інші
  // місця — віджет Громади (`community-blocks.js`) і картка профілю
  // (`core/profile-card.js`). Дошка лишалась єдиною з буквою, тобто це зведення до
  // спільного вигляду, а не третій варіант.
  // ⚠️ Плейсхолдер тримає ту саму висоту рядка, що й фото — заради цього монограму
  // й заводили, і ця причина лишається чинною (у новинах порожнє місце давало
  // рвані картки 100/71/100).
  const ph = `<div class="bd-ad-img bd-ad-img--mono">${catIcon(p.category)}</div>`;
  // ⚠️ ЗАПАСНИЙ ШЛЯХ ПЕРЕБУДОВАНО. Було: `onerror` вставляв монограму рядком HTML
  // просто в атрибут. Для однієї літери це працювало, для SVG — ні: іконка сама
  // повна лапок, і вони розірвали б атрибут. Тому плейсхолдер лежить ПІД фото
  // завжди, фото перекриває його зверху (обидва `position: absolute` в тій самій
  // рамці), а якщо кадр не завантажився — фото прибирає себе і видно іконку.
  // Заразом зник inline-обробник у розмітці: з такими в проєкті вже боролись
  // (баги B-15 і B-21 — inline `onclick` перевели на делегування).
  const media = photo
    ? `${ph}<img class="bd-ad-img" src="${escapeHtml(photo)}" alt="" loading="lazy" onerror="this.remove()">`
    : ph;
  return `
    <article class="cm-board-note bd-card bd-card--board bd-ad" data-post-id="${p.id}">
      ${media}
      <div class="bd-ad-body">
        <div class="bd-ad-meta">
          <span class="bd-ad-type cat-c-${escapeHtml(catColor(p.category))}">${escapeHtml(catShort(p.category))}</span>
          <span class="bd-ad-time">${renderPostTime(p)}</span>
          ${boardActionsHtml(p)}
        </div>
        <h3 class="bd-ad-title">${escapeHtml(cardTitleText(p))}</h3>
        ${renderCardDesc(p)}
        <div class="bd-ad-foot">
          <span class="bd-ad-loc">${PIN_ICON_SVG}${escapeHtml(locLabel(p.location))}</span>
          ${renderPrice(p)}
        </div>
      </div>
    </article>
  `;
}

// BOARD: вміст зум-модалки оголошення — будується З ДАНИХ поста (не клон картки).
// Фото flush зверху (без відʼємного margin → не обрізається скролом), нижче —
// прокручуване тіло з категорією, заголовком, повним описом, контактом і діями.
// Дії (зберегти/шер/контакт) — ті самі хелпери, що й на картці → делеговані
// обробники працюють без змін.
// 🔴 02.08 — МОДАЛКА ПЕРЕРОБЛЕНА ЗА МАКЕТОМ (два скріни від ChatGPT, схвалені Вовою).
//
// Структура секціями. Кожна секція — окрема функція, яка повертає ПОРОЖНІЙ РЯДОК,
// коли даних немає. Це і є вся потрібна «модульність»: новий блок додається одним
// рядком, а відсутні дані нічого не ламають. Каркас «незалежних секцій» із ТЗ на
// 18 оголошеннях був би оверинжинірингом.
//
// ⚠️ ЧОГО В МАКЕТІ НЕ РЕАЛІЗОВАНО І ЧОМУ — щоб наступна сесія не шукала «загублене»:
//   • «👁 324 перегляди» — колонки переглядів у базі НЕМА, подій аналітики про
//     оголошення 0. Показувати нічого; вигадати число = збрехати людині.
//   • «★ 4.9 (27 відгуків)» — таблиці відгуків не існує взагалі. При 18 оголошеннях
//     від 1 автора намальований рейтинг був би імітацією життя.
//   • «Площа 120 м² · Ділянка 25 сот. · Кімнати 4» — полів характеристик немає;
//     потрібна схема під категорії + нові поля у формі подачі. Місце під блок
//     лишено: `renderAdSpecs()` віддає '' і чекає на дані.
//   • Синя галочка верифікації — поле `trusted` у профілі Є, але воно не приходить
//     разом із постом; тягнути профіль окремим запитом на кожне відкриття не стали.
// 🔴 02.08 — спільне дротування нової модалки: кнопки закриття, скарга, лічильник фото.
// ⚠️ ОДНА функція на дві модалки (зум із Дошки і standalone з чату) — обидві малюються
// тим самим `renderAdModal`, тож і поводитись мусять однаково. Дублювати цей блок
// означало б завести дві копії, які колись розійдуться (у проєкті таке вже було).
function wireAdModalChrome(modal, close) {
  // Кнопка «←». Раніше закрити можна було лише свайпом або тапом у затемнення — на
  // повноекранному аркуші затемнення майже не видно, тож явна кнопка стала обовʼязковою.
  modal.querySelectorAll('[data-ad-close]').forEach(b => b.addEventListener('click', () => close()));

  // ── Доступність: це діалог, і з нього має бути вихід із клавіатури ──────────
  // 🔴 Знахідка власного аудиту 02.08, яка лишалась відкритою: екран накривав застосунок
  // цілком, але не називав себе діалогом (читач екрана оголошував його як звичайний
  // блок і не замикав фокус), а Escape не робив нічого — на зовнішній клавіатурі та в
  // десктопному браузері виходу не було взагалі.
  modal.setAttribute('role', 'dialog');
  modal.setAttribute('aria-modal', 'true');
  modal.setAttribute('aria-label', modal.querySelector('.cm-ad-title')?.textContent || 'Оголошення');
  // ⚠️ Слухач висить НА САМІЙ МОДАЛЦІ, а не на `document`. Це не стиль, а запобіжник:
  // модалку зносять із DOM щонайменше чотирма шляхами (кнопка, свайп, затемнення,
  // перехід у профіль автора), і слухач на `document` пережив би частину з них. Тут він
  // помирає разом із вузлом — рівно той клас витоку, який аудит 02.08 уже знайшов на
  // `window.resize` (24 слухачі замість 4 після десяти відкриттів).
  modal.tabIndex = -1;
  modal.addEventListener('keydown', e => { if (e.key === 'Escape') { e.preventDefault(); close(); } });
  // `preventScroll` — інакше фокус сам прокрутив би вміст на початок.
  try { modal.focus({ preventScroll: true }); } catch (_) { }
  // «Скаржитися» поки лише підтверджує прийом: черги скарг у базі немає, а мовчазна
  // кнопка гірша за її відсутність.
  modal.querySelector('[data-ad-report]')?.addEventListener('click', () => {
    const pid = modal.dataset.postId;
    if (pid) openAdReportSheet(pid);
  });
  // «Показати номер» — телефон віддає сервер окремим запитом (крок 10 потоку 2).
  // ⚠️ Кнопка замінюється на справжнє посилання `tel:` ОДИН раз: другий тап уже
  // має дзвонити, а не питати базу знову — інакше кожен дотик з'їдав би одиницю
  // з погодинної стелі 30 номерів і людина сама себе заблокувала б.
  modal.querySelector('[data-show-phone]')?.addEventListener('click', e => {
    const btn = e.currentTarget;
    if (btn.dataset.busy) return;                 // подвійний тап поки лунає запит
    requireAuth('побачити номер', async () => {
      btn.dataset.busy = '1';
      const prev = btn.innerHTML;
      btn.innerHTML = `${PHONE_ICON_SVG}<span>Хвилинку…</span>`;
      const r = await fetchPostContact(Number(modal.dataset.postId));
      delete btn.dataset.busy;
      if (!r.ok) { btn.innerHTML = prev; showToast(r.error, 3000); return; }
      if (!r.contact) { btn.innerHTML = prev; showToast('Автор не залишив номера', 2500); return; }
      const a = document.createElement('a');
      a.className = 'cm-ad-call';
      a.href = `tel:${r.contact.replace(/[^\d+]/g, '')}`;
      a.innerHTML = `${PHONE_ICON_SVG}<span>${escapeHtml(r.contact)}</span>`;
      btn.replaceWith(a);
    });
  });
  // Фото автора підтягується прогресивно (літера → фото), як у чатах і обговореннях.
  hydrateAvatars(modal);
  // «Учасник CSTL LIFE з …» + галочка довіри — окремим тихим запитом уже ПІСЛЯ показу.
  // ⚠️ Свідомо не блокуємо відкриття модалки заради цього рядка: без нього картка
  // повноцінна, а чекати на мережу, щоб показати оголошення, — гірше за його брак.
  // ⚠️ Рядок уже НЕ порожній — у розмітці стоїть «Учасник CSTL LIFE». Запит його лише
  // УТОЧНЮЄ до дати. Тому картка не стрибає і виглядає однаково в кожному оголошенні,
  // хоч профіль приїхав, хоч ні (скарга Вови: «не в кожного пише інформація»).
  const sinceEl = modal.querySelector('[data-ad-since]');
  const authorUid = modal.querySelector('.cm-ad-author')?.dataset.avUid;
  if (sinceEl && authorUid) {
    fetchPublicProfile(authorUid).then(pr => {
      if (!pr || !sinceEl.isConnected) return;
      const dt = new Date(pr.created_at);
      if (!isNaN(dt.getTime()) && dt.getFullYear() > 2000) {
        // ⚠️ 06.08 — ХВІСТ «· ще N оголошень» БІЛЬШЕ НЕ СКЛЕЮЄТЬСЯ З ЦИМ РЯДКОМ.
        // Кількість оголошень живе окремим елементом (`.cm-ad-author-more`), тож
        // мережева відповідь фізично не може її стерти. До цього хвіст доводилось
        // вирізати з тексту і приклеювати назад — крихко: рядок ділився за
        // видимим роздільником « · », тобто за оформленням, а не за даними.
        sinceEl.textContent = `Учасник CSTL LIFE з ${MONTHS_GEN[dt.getMonth()]} ${dt.getFullYear()}`;
      }
      // 🔵 09.08 — ГАЛОЧКУ ТУТ НЕ МАЛЮЄМО, І ЦЕ НАВМИСНО.
      // Перша редакція ставила її саме тут, з відповіді `fetchPublicProfile`.
      // Замовлення Вови показало, що це неправильний рівень: *«вона має
      // відображатися ВСЮДИ де пише ім'я… користувачі можуть просто прочитати,
      // але не тапнути і не відкрити картку»*. Один екран — один шматок коду, і
      // так довелось би обійти всі поверхні застосунку по черзі.
      // Тепер знак їде разом з іменем: вузол уже несе `data-name-uid`
      // (`nameUid(p.owner_uid)` нижче в розмітці), а `hydrateNames` ставить
      // галочку сама. Тримати тут другий шлях означало б дві галочки поспіль.
    }).catch(() => {});   // fail-soft: профіль не приїхав — картка лишається як є
  }

  // ── Компактна шапка зʼявляється, коли велика поїхала за верх ────────────────
  // ⚠️ Перша версія показувала її за СТАНОМ АРКУША (піднятий → показати). На знімку
  // одразу стало видно дурницю: у піднятому стані велика шапка ще на екрані, і назва
  // писалась ДВІЧІ поспіль. Правильний привід — не положення аркуша, а те, що заголовок
  // реально зник із очей. Той самий прийом, що в App Store і Apple Music.
  const scrollEl = modal.querySelector('.cm-ad-scroll');
  // ⚠️ Стежимо саме за НАЗВОЮ, а не за всією шапкою: шапка містить ще й ціну, і поки
  // вона доїде за край, людина вже давно не бачить, ЩО читає. Назва — це і є відповідь
  // на «що це», тому компактна шапка заступає саме її.
  const headEl = modal.querySelector('.cm-ad-title') || modal.querySelector('.cm-ad-head');
  if (scrollEl && headEl) {
    // 🔴 ПІД ЧАС ПРОКРУТКИ ЧИТАЄМО ЛИШЕ `scrollTop` — просте число, розкладку не чіпає.
    // Було: два `getBoundingClientRect()` на КОЖНУ подію прокрутки. Читання геометрії
    // під час прокрутки змушує браузер перерахувати розкладку негайно, тобто найдорожча
    // операція виконувалась саме тоді, коли треба малювати кадри.
    //
    // ⚠️ ЖОДНОГО `window.addEventListener` (витік, заміряний в аудиті: 24 слухачі
    // замість 4 після десяти відкриттів). Поворот екрана міняє поріг — тому міряємо
    // ЛІНИВО: на першій прокрутці після зміни ширини вікна, а не за подією вікна.
    let threshold = 0, atW = 0;
    const syncMini = () => {
      if (atW !== window.innerWidth) {
        atW = window.innerWidth;
        // ⚠️ Міряємо ВІДСТАНЬ ДО НИЗУ НАЗВИ від верху видимої області, плюс уже пройдену
        // прокрутку. Перша версія складала `offsetTop` — і промахнулась, бо найближчий
        // позиційований предок назви це АРКУШ, а не скролер: поріг вийшов 180 замість
        // 506, і компактна шапка проявлялась, коли велика ще повністю на екрані
        // (видно на знімку — назва писалась двічі). Один вимір на зміну ширини вікна.
        threshold = Math.max(0, Math.round(
          headEl.getBoundingClientRect().bottom - scrollEl.getBoundingClientRect().top + scrollEl.scrollTop));
      }
      modal.classList.toggle('cm-ad-screen--mini', scrollEl.scrollTop >= threshold);
    };
    scrollEl.addEventListener('scroll', syncMini, { passive: true });
    // Після вставки в документ: до неї `offsetTop` порожній (урок 28.07 про `wireClamps`).
    requestAnimationFrame(syncMini);
  }

  // ── Галерея фото: тап → повний екран, крапки й лічильник «1 / N» при гортанні ──
  // ⚠️ Переїхало сюди 02.08 з ДВОХ call-site'ів: блок був скопійований слово в слово
  // в `openAdModalStandalone` і в `expand()`. Рівно таке дублювання й дало баг свайпу
  // (дві копії розійшлись), тож усе спільне дротування модалки живе в одному місці.
  const gallery = modal.querySelector('.cm-board-modal-gallery');
  if (gallery) {
    const photoUrls = [...gallery.querySelectorAll('[data-photo-full]')].map(im => im.dataset.photoFull);
    gallery.querySelectorAll('img[data-photo-idx]').forEach(im => {
      im.addEventListener('click', e => {
        e.stopPropagation();
        openPhotoLightbox(photoUrls, Number(im.dataset.photoIdx) || 0);
      });
    });
    const dots = modal.querySelectorAll('.cm-board-modal-dot');
    const counter = modal.querySelector('.cm-ad-hero-count');
    if (dots.length || counter) {
      gallery.addEventListener('scroll', () => {
        const i = gallery.clientWidth ? Math.round(gallery.scrollLeft / gallery.clientWidth) : 0;
        dots.forEach((d, di) => d.classList.toggle('active', di === i));
        if (counter) counter.textContent = `${i + 1} / ${gallery.children.length}`;
      }, { passive: true });
    }
  }
}

