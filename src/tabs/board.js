// Українська відміна слова «оголошення» для лічильника (Д-11).
function pluralAds(n) {
  const d = n % 10, dd = n % 100;
  if (d === 1 && dd !== 11) return 'оголошення';
  if (d >= 2 && d <= 4 && (dd < 12 || dd > 14)) return 'оголошення';
  return 'оголошень';
}

