// Авто-ховання шапки Дошки при скролі. Слухач на .app-main (справжній скролер),
// rAF-throttle (як hero-blur у community.js). Ховаємо назву+категорії лише коли
// прогорнули «через деякий час» (THRESHOLD) і напрямок — вниз; вгору → показуємо.
// ── ПОКАЗ ШАПКИ ПРИ РУСІ ПАЛЬЦЕМ УГОРУ ────────────────────────────────────────
//
// Вова 06.08: «щоб ховався він так як зараз + якщо скрол посеред сторінки то так
// як раніше, а зʼявлявся теж як раніше». Тобто потрібні ОБИДВІ поведінки:
//   • на початку сторінки — шапка просто частина потоку (це робить CSS, `sticky`);
//   • з середини списку — ховається за жестом униз і виїжджає за жестом угору.
//
// 🔑 JS ТУТ НЕ РУХАЄ ШАПКУ. Він лише вмикає клас, який міняє ТОЧКУ ПРИЛИПАННЯ
// (`top: 0` замість від'ємного). Сам рух і плавність — на браузері. Саме тому це
// не повертає дьоргання: покадрового JS-руху, який тричі провалився, тут немає.
// Скидач кеша висоти. На рівні модуля, бо кликати треба ЗЗОВНІ обробника —
// після кожної перебудови шапки (`syncBoardBodyOffset`) і після повороту екрана.
let _invalidateHeaderH = null;
let _headerShowWired = false;
function setupHeaderShowOnScrollUp() {
  if (_headerShowWired) return;
  const main = document.querySelector('.app-main');
  if (!main) return;
  _headerShowWired = true;

  // Пороги ті самі, що були до всіх переробок: ховати ПІЗНІШЕ (випадковий рух
  // пальцем не має забирати пошук), повертати ШВИДКО (рух угору майже завжди
  // означає «хочу назад»). Патерн Twitter/Instagram.
  const HIDE_AFTER = 110;
  const SHOW_AFTER = 70;
  let lastY = main.scrollTop;
  let accDown = 0, accUp = 0;
  let ticking = false;

  // Висота потрібна для ОДНОГО рішення: чи шапка вже схована. Кешуємо — читати
  // `offsetHeight` у обробнику прокрутки означає примусовий перерахунок розкладки.
  let cachedH = 0;
  const headerH = (el) => (cachedH ||= el.offsetHeight + 6);
  _invalidateHeaderH = () => { cachedH = 0; };

  let elCache = null;
  const controlsEl = () => {
    if (!elCache || !elCache.isConnected) elCache = getBoardRoot()?.querySelector('.bd-controls') || null;
    return elCache;
  };
  const setShown = (el, on) => el.classList.toggle('bd-controls--shown', on);

  const apply = () => {
    ticking = false;
    if (main.dataset.tab !== 'board') return;
    const el = controlsEl();
    if (!el) return;
    const y = main.scrollTop;
    const dy = y - lastY;
    lastY = y;

    // Самий верх — чистий стан. Знімати клас тут безпечно й непомітно: на нулі
    // обидва стани дають ту саму позицію (шапка стоїть на своєму місці в потоці).
    if (y <= 0) { accDown = accUp = 0; setShown(el, false); return; }

    if (dy > 0) {
      accDown += dy; accUp = 0;
      if (accDown >= HIDE_AFTER) setShown(el, false);
    } else if (dy < 0) {
      accUp -= dy; accDown = 0;
      // ⚠️ Показ вмикаємо ЛИШЕ коли шапка справді схована. Інакше на початку
      // сторінки (де вона частково видима й їде в потоці) жест угору смикнув би
      // її з природної позиції на 56 — тобто повернув би той самий стрибок,
      // тільки з іншого боку.
      if (accUp >= SHOW_AFTER && y > headerH(el)) setShown(el, true);
    }
  };

  main.addEventListener('scroll', () => {
    if (!ticking) { ticking = true; requestAnimationFrame(apply); }
  }, { passive: true });

  window.addEventListener('resize', () => requestAnimationFrame(() => {
    _invalidateHeaderH?.();
    syncBoardBodyOffset();
    fitBoardAuthors();
  }), { passive: true });
}

// 🗑 06.08 — `setupHeaderCollapse()` (старий покадровий рух) ВИДАЛЕНО ЦІЛКОМ.
//
// Історія цього місця в трьох рядках, щоб наступна сесія не почала знову:
//   • до 06.08 — шапка `fixed`, JS ховав її стрибком за порогами 110/70;
//   • вранці 06.08 — JS рухав її покадрово «за пальцем» (дві спроби, обидві
//     дьоргались: на iOS прокрутку веде композитор, події `scroll` доходять із
//     затримкою — JS-рух за пальцем не буває плавним у принципі);
//   • тепер — шапка просто лежить у потоці (`position: sticky` з від'ємним
//     `top`, див. `style/board.css`). Її рух ЦІЛКОМ обслуговує браузер.
//
// Останнім залишком був клас `--shown`: він виїжджав transform-ом при русі
// пальцем угору. Вова: «коли я доскролюю до верху, верхній блок дьоргається тим,
// що з'їжджає донизу, потім рівняється до верху — він має виїжджати разом за
// останньою карткою, по такій логіці як і ховається». Причина рівно та: показ
// накладався на власний рух шапки в потоці, і на підході до верху виходило два
// рухи один поверх одного.
// ➡️ Прибрано. Шапка тепер СИМЕТРИЧНА: ховається з прокруткою і виїжджає з
// прокруткою. JS у цьому не бере участі ніяк.
//
// ⚠️ ЦІНА, названа Вові чесно: щоб дістатись пошуку з середини списку, треба
// прокрутити до верху — «викликати» шапку жестом більше не можна. Це прямий
// наслідок симетрії, якої він і просив.
//
// ℹ️ Разом із функцією пішли `HIDE_AFTER`/`SHOW_AFTER` (пороги 110/70),
// накопичувачі напрямку, кеш висоти (`headerH`) і кеш вузла — вони
// обслуговували виключно її. `--bd-h` для CSS лишився: на ньому тримається
// `top` самого `sticky`, і його виставляє `syncBoardBodyOffset()`.

export function initBoard() {
  // Двигун Обговорень: доступ до постів (ін'єкція — board.js лишається власником
  // стану allPosts), слухач форми коментаря, realtime-підписки.
  initDiscussionsEngine({ getPosts: () => allPosts });
  attachDiscussionsDelegation();
  attachDiscussionsRealtime();
  attachBoardDelegation();
  setupHeaderShowOnScrollUp();
  renderBoard();
  // Відкрити модалку оголошення з чату («Переглянути оголошення →» в розмові)
  window.addEventListener('cstl-open-ad', (e) => {
    const p = e.detail && e.detail.post;
    if (p) openAdModalStandalone(p);
  });
  // Зміна статусу власних постів («Мої оголошення»: завершити/повернути/видалити)
  // і публікація нового — зміна має бути видима одразу, без перезапуску застосунку.
  // ⚠️ Саме `refreshBoardKeepingPlace`, а не `renderBoard`: друге збирає вкладку заново
  // і кидає на початок списку (та сама скарга, що була у «Стрічці» 27.07).
  window.addEventListener('cstl-posts-changed', () => refreshBoardKeepingPlace());

  // 🔴 07.08 — ПОВЕРНУВСЯ НА ДОШКУ → СПИСОК ПЕРЕЧИТАНО.
  // Імена і фото оновлює сам примітив (гідрація по маркерах), тут — тільки те,
  // чого він не знає: самі оголошення (нове чуже, завершене, знята ціна).
  // ⚠️ Свідомо `refreshBoardKeepingPlace`, а не `renderBoard`: людина повертається
  // у ТУ САМУ точку списку, і перебудова вкладки кинула б її на початок.
  onReturn('board', () => refreshBoardKeepingPlace());

  // ── ЖИВА СИНХРОНІЗАЦІЯ ОГОЛОШЕНЬ (Вова 26.07) ──────────────────────────────────
  // Досі підписки на `posts` не було: нове оголошення сусіда зʼявлялось лише після
  // перезаходу на вкладку. `cstl-posts-changed` вище — подія ОДНОГО пристрою (мої власні
  // дії), вона нікуди не летить.
  //
  // ⚠️ Чому не перемальовуємо одразу на кожну подію: `renderBoard()` перезавантажує і
  // перемальовує весь список. Якщо людина саме гортає оголошення — список стрибне під
  // пальцем (та сама сім'я, що HOT_RULES №10). Тому:
  //   • Дошка не активна → лише позначка «дані змінились», перемалюємо при вході;
  //   • активна і людина ВГОРІ списку (нічого не читає всередині) → одразу;
  //   • активна, але прогорнута → чекаємо, поки повернеться вгору або вийде з вкладки.
  if (isSupabaseReady()) {
    subscribePosts(() => {
      const main = document.querySelector('.app-main');
      const onBoard = main?.dataset.tab === 'board';
      if (onBoard && (main?.scrollTop || 0) < 120) renderBoard();
      else _boardStale = true;
    });
    // Повернення вгору — момент, коли перемалювати безпечно.
    document.querySelector('.app-main')?.addEventListener('scroll', () => {
      const main = document.querySelector('.app-main');
      if (!_boardStale || main?.dataset.tab !== 'board') return;
      if ((main.scrollTop || 0) < 120) { _boardStale = false; renderBoard(); }
    }, { passive: true });
  }
  // Обговорення — справжня сторінка: рендеримо її контент при ВХОДІ на вкладку
  // і відновлюємо Дошку при ВИХОДІ (board.js поки рендерить обидві; розділ — Потік 2).
  window.addEventListener('cstl-tab-changed', () => {
    const tab = document.querySelector('.app-main')?.dataset.tab;
    if (tab === 'discussions' && !discOpen) openDiscussions();
    else if (tab !== 'discussions' && discOpen) closeDiscussions();
    // Д-12: фільтр локації скидається на «Уся громада» при кожному вході на Дошку.
    if (tab === 'board' && activeLocation !== COMMUNITY_ALL) {
      activeLocation = COMMUNITY_ALL;
      renderAll();
    }
    // Поки нас не було, хтось подав/змінив оголошення (жива підписка це помітила) —
    // вхід на вкладку і є безпечний момент показати свіже.
    if (tab === 'board' && _boardStale) { _boardStale = false; renderBoard(); }
    // Відступ під шапку: при ВХОДІ на Дошку вкладка щойно стала видимою, тому
    // тепер .bd-controls має реальну висоту (на старті вона була схована → offsetHeight=0
    // → вимір не спрацьовував). Міряємо тут. rAF — дочекатись layout після показу.
    if (tab === 'board') requestAnimationFrame(() => { syncBoardBodyOffset(); fitBoardAuthors(); });
    // Правила Дошки — один раз на акаунт, при вході на вкладку.
    if (tab === 'board') maybeShowBoardRules();
  });
  // Холодний старт із Дошкою вже активною (перезапуск застосунку на цій вкладці):
  // події `cstl-tab-changed` не буде, бо вкладка не мінялась.
  if (document.querySelector('.app-main')?.dataset.tab === 'board') maybeShowBoardRules();
  // Авто-ховання шапки при скролі Дошки (гортаєш вниз — ховаються назва+категорії;
  // вгору — з'являються). Лічильник/локація + пошук лишаються закріпленими.
  // Вхід/вихід → перезавантажити дошку: закладки, підсвітку «моє», таб «Збережені».
  onAuthChange(() => {
    if (!isLoggedIn()) {
      setSavedIds(new Set());
      if (activeType === 'saved') activeType = 'board';   // персональний таб зник
    }
    renderBoard();
    // Відкрита модалка чату обговорення: перезібрати низ (форма/кнопка входу) —
    // логіка у board-discussions.js (перевіряє чи модалка відкрита).
    handleDiscussionsAuthChange();
  });
}
