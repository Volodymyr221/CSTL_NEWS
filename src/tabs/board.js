// 🔴 05.08 — КАТЕГОРІЇ ЖИВУТЬ У МЕНЮ КНОПКИ В ШАПЦІ (було: ряд чіпів `bd-types`).
//
// Правила відбору лишились ті самі, що були у чіпів 01.08 — змінився лише
// спосіб показу, і це важливо, бо саме правила тут неочевидні:
//   • показуємо ЛИШЕ непорожні категорії. У нас 19 оголошень, і
//     «шукаю»/«віддам»/«знайдено» бувають нулями; мертвий пункт зі «0» робить
//     список сміттям — та сама пастка, через яку 31.07 прибрали чіпи з табла
//     новин (фільтр над трьома картками показував 3 з 212);
//   • лічильники рахуються по постах, які проходять УСІ інші фільтри (пошук,
//     локація) — інакше пункт обіцяв би «Продам 8», а показував 2.
//
// 🔴 ФУНКЦІЯ НА РІВНІ МОДУЛЯ, А НЕ ВСЕРЕДИНІ `renderControls` — і це не стиль.
// Меню перемальовує ще й `updateAdCount()` (пошук міняє склад пунктів, не лише
// числа), а він живе поза `renderControls` і вкладеної функції просто не побачив
// би. Перша версія лежала всередині — і зламалася б рівно на першому ж пошуку.
//
// ⚠️ Меню бере готові класи `.bd-cat-menu` / `.bd-cat-mi`, які лишились у CSS
// від кнопки-лійки до 01.08 (спільна база з меню локації). Це не «оживлення
// мертвого коду» навмання: вони й досі стилізують чинне меню локації, тобто
// весь час були живі — просто одного з двох користувачів у них не було.
function catMenuHtml() {
  const base = getFilteredPosts({ ignoreCategory: true });
  const n = {};
  base.forEach(p => { n[p.category] = (n[p.category] || 0) + 1; });
  // Пункт = іконка + назва + число. Іконка та сама, що на кнопці й на картці
  // оголошення — одна таксономія на весь застосунок (`core/board-categories.js`).
  const mi = (id, label, on, num, ico) => `
    <button class="bd-cat-mi${on ? ' active' : ''}" type="button" role="menuitem" data-bd-cat="${escapeHtml(id)}">
      <span class="bd-cat-mi-ico">${ico}</span>
      <span class="bd-cat-mi-label">${escapeHtml(label)}</span>
      <span class="bd-cat-mi-n">${num}</span>
    </button>`;
  const live = CATS.filter(c => n[c.id] > 0)
    .sort((a, b) => n[b.id] - n[a.id])
    .map(c => mi(c.id, c.short || c.label, activeCategory === c.id, n[c.id], c.icon))
    .join('');
  // Якщо активна категорія стала порожньою (звузили пошук) — її пункт усе одно
  // показуємо, інакше людина не побачить, ЯКИЙ фільтр тримає екран порожнім,
  // і не матиме куди тапнути, щоб його зняти.
  const orphan = (activeCategory !== 'all' && !n[activeCategory])
    ? mi(activeCategory, catShort(activeCategory), true, 0, catIcon(activeCategory)) : '';
  return `<div class="bd-cat-menu" id="bd-cat-menu" role="menu" hidden>
    ${mi('all', 'Усі', activeCategory === 'all', base.length, ALL_ICON)}${orphan}${live}
  </div>`;
}

// Оновити лічильник оголошень у шапці без повного ре-рендеру (Д-11).
// Викликається після фільтрів (пошук/локація), коли header не перебудовується.
function updateAdCount() {
  // Історія: до 01.08 — рядок «N оголошень» у шапці; 01.08 — число в чіпі «Усі»;
  // 05.08 — лічильники живуть у МЕНЮ фільтра, біля кожної категорії (на кружечку
  // кнопки числа немає — див. `heroHtml`).
  //
  // 🔴 ЧОМУ ПЕРЕМАЛЬОВУЄМО МЕНЮ ЦІЛКОМ, а не правимо самі числа: від пошуку
  // змінюється не лише кількість, а й СКЛАД пунктів — категорія, що стала
  // порожньою, зникає зі списку, а активна-порожня навпаки лишається сиротою.
  // Правка самих чисел лишила б у меню пункти, які нічого не знайдуть.
  //
  // ⚠️ Перемальовка безпечна лише тому, що вибір категорії слухає КОНТЕЙНЕР меню
  // (делегування у `wireMenuButton`), а не кожен пункт окремо: слухачі на пунктах
  // злетіли б із першим же `innerHTML`.
  const menu = document.getElementById('bd-cat-menu');
  if (!menu || activeType !== 'board') return;
  const wasOpen = !menu.hasAttribute('hidden');
  const fresh = document.createElement('div');
  fresh.innerHTML = catMenuHtml();
  menu.innerHTML = fresh.firstElementChild.innerHTML;
  if (wasOpen) menu.removeAttribute('hidden');   // перемальовка не має закривати відкрите меню
}

// 🔴 07.08 — ПОРОЖНІЙ СТАН НАЗИВАЄ ВСІ ПРИЧИНИ, А НЕ ОДНУ (баги B-1 і B-2).
//
// **B-1.** Було одне речення на всі випадки: «У цій категорії поки порожньо».
// Відтворення з аудиту: категорія «Куплю» + локація «Олика». У самій категорії
// «Куплю» оголошення Є — воно в Котові. Тобто екран називав ОДНУ причину з двох,
// і людина робила хибний висновок «у Куплю нічого немає», хоча досить було змінити
// село. Локація при цьому легко лишається ввімкненою з минулого разу: сама вона не
// скидається і в тексті порожнього стану її не було видно взагалі.
//
// **B-2.** Щоб повернутись до повного списку з трьома активними фільтрами, треба
// було ТРИ окремі дії в трьох різних місцях: меню категорій → «Усі», очистити поле
// пошуку, меню локацій → «Олицька громада». Кнопка стоїть саме тут, у порожньому
// стані, а не в шапці: у шапці вона висіла б завжди без потреби, а порожній екран —
// рівно той момент, коли людина найменш схильна шукати три органи керування і
// найімовірніше просто піде.
//
// ⚠️ Кнопку показуємо ЛИШЕ коли є що скидати: на щиро порожній Дошці (жодного
// оголошення, жодного фільтра) вона обіцяла б дію, яка нічого не змінить.
function emptyStateHtml() {
  if (activeType === 'saved') {
    return 'У «Збережених» поки нічого. Натисніть закладку на пості щоб зберегти.';
  }
  // Складаємо причини в тому порядку, в якому їх бачить людина у шапці.
  const причини = [];
  if (activeCategory !== 'all') причини.push(`у «${escapeHtml(catLabel(activeCategory))}»`);
  if (activeLocation !== COMMUNITY_ALL) причини.push(`для «${escapeHtml(locLabel(activeLocation))}»`);
  if (searchQuery.trim()) причини.push(`за запитом «${escapeHtml(searchQuery.trim())}»`);

  if (!причини.length) return 'Тут поки порожньо';

  const текст = `Нічого не знайшлось ${причини.join(' ')}`;
  return `${текст}
    <button class="bd-empty-reset" type="button" data-bd-reset>Скинути фільтри</button>`;
}

function renderBody() {
  const filtered = getFilteredPosts();

  if (!filtered.length) {
    return `<div class="bd-empty">${emptyStateHtml()}</div>`;
  }

  // Порядок: спершу bumped_at (підняте власником угору), далі ts/published_at.
  //
  // 🆕 11.08 — ПИТАННЯ СОРТУЮТЬСЯ ЗА ЖИВІСТЮ, А НЕ ЗА ДАТОЮ СТВОРЕННЯ.
  // У Q&A нагорі має стояти те, де щойно відповіли: питання місячної давнини, на
  // яке сьогодні прийшла відповідь, знову цікаве, а свіже без відповідей — ні.
  // Беремо ПІЗНІШУ з двох дат (питання / остання відповідь), тому нове питання без
  // відповідей однаково стоїть угорі за своєю датою і не тоне.
  // 🔑 Чому клієнтом, а не `bumped_at`: політика бази `posts UPDATE` дозволена лише
  // `is_admin()` (заміряно `pg_policies` 11.08), тож підняти запис нікому — поле
  // лишалося б порожнім. Коментарі й так усі в памʼяті, мережі це не коштує нічого.
  const rankTs = (x) => {
    const base =
      (x.bumped_at && new Date(x.bumped_at).getTime()) ||
      x.ts || (x.published_at && new Date(x.published_at).getTime()) || 0;
    return x.type === 'chat' ? Math.max(base, lastAnswerTs(x.id)) : base;
  };
  const sorted = [...filtered].sort((a, b) => rankTs(b) - rankTs(a));

  if (activeType === 'board') {
    // 🔴 01.08 — ОДИН СТОВПЧИК замість двох колонок-масонрі (рішення Вови).
    // ⚠️ Заразом зникла давня пастка розкладки: картки розкладались за парністю
    // (`i % 2`), тож поява або зникнення ОДНІЄЇ картки законно перекладала всі
    // наступні між колонками. Саме через це тут свідомо не робили точкового
    // патчу однієї картки, а перемальовували список під якорем прокрутки.
    // У списку такої залежності немає взагалі.
    // ⚠️ Ім'я функції лишаю нейтральним (`adList`), бо «corkboard» тепер брехало б.
    const adList = (list) => `<div class="bd-ads">${list.map(p => renderBoardCard(p)).join('')}</div>`;
    const corkboard = adList;
    // Фільтр по конкретному НП (Д-12+) → ДВІ групи: спершу оголошення цього НП,
    // нижче — загальногромадські («Олицька громада»). Дефолт «Уся громада» — один список.
    if (activeLocation !== COMMUNITY_ALL) {
      const npGroup = sorted.filter(p => p.location === activeLocation);
      // Друга група: якщо в НП Є власні оголошення — лише загальногромадські
      // (вузько, як і було). Якщо НЕМАЄ — ВСЯ громада (усі НП разом), той самий
      // набір що й у дефолтному перегляді «Олицька громада» без фільтра —
      // не лише позначені як «вся громада» (Вова 11.07, знайдений баг: раніше
      // тут губились пости інших конкретних НП, напр. Жорнище).
      const wideGroup = npGroup.length
        ? sorted.filter(p => isCommunityWide(p.location))
        : [...getFilteredPosts({ ignoreLocation: true })].sort((a, b) => rankTs(b) - rankTs(a));
      const section = (title, list) => list.length
        ? `<h3 class="bd-group-title">${escapeHtml(title)}</h3>${corkboard(list)}`
        : '';
      // Немає оголошень у КОНКРЕТНОМУ НП (напр. «Олика») — не мовчки перескакувати
      // одразу на загальногромадські, а показати явне повідомлення (Вова 11.07).
      const npEmptyMsg = !npGroup.length
        ? `<div class="bd-group-empty">В розділі «${escapeHtml(activeLocation)}» оголошень не знайдено<span class="bd-group-empty-hint">Перегляньте всі оголошення громади</span></div>`
        : '';
      return `
        <div class="board-backdrop" id="board-backdrop"></div>
        ${section(activeLocation, npGroup)}
        ${npEmptyMsg}
        ${section(COMMUNITY_ALL_LABEL, wideGroup)}
      `;
    }
    return `
      <div class="board-backdrop" id="board-backdrop"></div>
      ${corkboard(sorted)}
    `;
  }

  // chat / saved — вертикальна стрічка карток.
  // #board-backdrop рендеримо і тут, щоб у «Збережених» працювала зум-модалка
  // оголошення (initBoardNoteExpand виходить рано, якщо backdrop відсутній).
  return `
    <div class="board-backdrop" id="board-backdrop"></div>
    <div class="bd-stream">${sorted.map(renderCard).join('')}</div>`;
}

// Перечитати дані Дошки з бази (без жодного рендера). Винесено з `renderBoard`, щоб
// «мʼяке» оновлення могло взяти свіжі дані й перемалювати ЛИШЕ список, не чіпаючи шапку
// й не будуючи вкладку заново.
// Повертає true, якщо дані прийшли з бази.
async function loadBoardData() {
  if (!isSupabaseReady()) return false;
  const uid = currentUserId();
  const [posts, anns, comments, saved, reactions] = await Promise.all([
    fetchPublishedPosts(),
    fetchPublishedAnnouncements(),
    fetchAllComments(),
    uid ? fetchSavedPostIds(uid) : Promise.resolve(new Set()),
    fetchAllReactions(uid || getAnonId()),
  ]);
  if (posts === null) return false;
  allPosts         = posts;
  allAnnouncements = anns || [];
  setDiscussionsData(comments, reactions);   // стан обговорень живе у board-discussions.js
  setSavedIds(saved);                        // закладки — у board-shared.js
  return true;
}

