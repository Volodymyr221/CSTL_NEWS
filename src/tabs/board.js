// ⚠️ НІЧОГО СВОГО ТУТ НЕ ВИНАЙДЕНО — усе на наявних механізмах проєкту:
//   • `avatarCircle({uid})` сам ставить `data-av-uid` + `data-av-circle`;
//   • `hydrateAvatars(root)` прогресивно міняє літеру на фото (без блокування рендера);
