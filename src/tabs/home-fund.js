// Відмінювання днів. Копію не заводимо дарма: у `utils.js` такої функції немає,
// а в `home-contacts.js` вона локальна й під інші слова.
function plural(n, one, few, many) {
  const t = n % 100, o = n % 10;
  if (t >= 11 && t <= 14) return many;
  if (o === 1) return one;
  if (o >= 2 && o <= 4) return few;
  return many;
}

// Формат суми: «500 000 ₴» — нерозривні пробіли, щоб число не переносилось.
function money(n) {
  if (!Number.isFinite(n)) return null;
  // `toLocaleString('uk-UA')` ставить між тисячами НЕРОЗРИВНИЙ пробіл.
  // ⚠️ Не беремо `formatPrice`: вона має семантику ЦІНИ і віддає «Безкоштовно»
  // на нулі — для цілі збору це неправильні слова.
  return `${Math.round(n).toLocaleString('uk-UA')} ₴`;
}

// Скільки днів завершений збір ще видно. 🔴 Не нуль і не назавжди.
// Нуль означав би, що збір зникає МОВЧКИ: людина, яка вчора донатила, ніколи не
// дізнається, чим усе скінчилось, — а це найгірше, що можна зробити з довірою.
// Назавжди означало б, що головна перетворюється на архів.
const CLOSED_DAYS = 7;

const dayDiff = (a, b) => Math.round((Date.parse(a) - Date.parse(b)) / 864e5);

async function loadFundraisers() {
  try {
    // 🔴 ДЖЕРЕЛО — БАЗА, а не файл у git (переїзд 17.08, розбір у шапці й у
    // `core/supabase.js`). Правила нижче НЕ змінились ані на йоту: та сама
    // перевірка обовʼязкових полів, той самий строк показу завершених, той
    // самий порядок. Змінився рівно рядок, що дістає дані, — саме заради цього
    // форма запису трималась пласкою від 05.08.
    const items = await fetchFundraisers();
    if (!Array.isArray(items)) return [];      // збій або немає клієнта → блока немає
    const todayISO = new Date().toISOString().slice(0, 10);

    const ok = items.filter(it =>
      it && it.active !== false &&
      it.title && it.org && it.url &&        // 🔴 без відповідального і посилання — не показуємо
      /^https:\/\//i.test(String(it.url))   // 🔴 тільки https: посилання про гроші не йде по http
    ).map(it => {
      // `left` — днів до кінця; відʼємне означає, що збір уже завершився.
      const left = it.until ? dayDiff(it.until, todayISO) : null;
      return { ...it, left, closed: left != null && left < 0 };
    // Завершений збір лишається ще CLOSED_DAYS днів — уже без кнопки.
    }).filter(it => !it.closed || -it.left <= CLOSED_DAYS);

    // 🔑 ПОРЯДОК ПОКАЗУ — це рішення, а не випадковість. До 05.08 збори бралися
    // так, як лежать у файлі: хто перший рядок, той і на екрані.
    //   1. живі перед завершеними;
    //   2. 🆕 17.08 — ручне підняття адміном (`sort_order`, більше = вище);
    //   3. серед решти — той, у кого менше днів лишилось (терміновість);
    //   4. збір без дати — після тих, у кого дата є: він не горить.
    //
    // 🔑 `sort_order` стоїть ВИЩЕ за терміновість навмисно. Терміновість — добре
    // правило за замовчуванням, але воно не знає контексту: коли громада збирає
    // на щось справді важливе, рішення «це зараз головне» приймає людина, а не
    // арифметика днів. За замовчуванням поле = 0, тобто правило 05.08 діє далі.
    return ok.sort((a, b) => {
      if (a.closed !== b.closed) return a.closed ? 1 : -1;
      const sa = Number(a.sort_order) || 0, sb = Number(b.sort_order) || 0;
      if (sa !== sb) return sb - sa;
      const la = a.left == null ? Infinity : a.left;
      const lb = b.left == null ? Infinity : b.left;
      return la - lb;
    });
  } catch {
    return [];
  }
}

// Ряд статистики в нижній частині скляної панелі. 🔴 МАЛЮЄМО ЛИШЕ ТЕ, ЩО В
// ДАНИХ СПРАВДІ Є: немає поля — немає комірки; немає жодної — немає й ряду
// (порожня рамка гірша за її брак).
//
// Порядок навмисний і є пріоритетом: **перевірено нами · скільки лишилось ·
// звідки збір**. Довіра йде першою — у зборі коштів найважливіше не цифри, а чи
// можна вірити тому, хто просить.
//
// 🛑 «124 донати» і «оновлено 5 хв тому» з макета тут НЕ буде (рішення Вови
// 16.08, розбір у шапці файлу). Обидва довелось би вписувати руками, тобто вони
// старіли б мовчки. Усе, що лишилось у ряду, або ставить людина СВІДОМО
// («перевірено»), або рахується від сьогодні й тому не старіє взагалі (строк).
//
// ⚠️ РЯД ПЕРЕНОСИТЬСЯ (`flex-wrap`), А НЕ ДІЛИТЬСЯ НА РІВНІ КОМІРКИ.
// Попередня версія («факти») ділила ширину порівну — і на вужчій картці у
// стрічці (249px) три комірки НАЛАЗИЛИ одна на одну, через що стеля була два.
// Ряд, що переноситься, зламатись так не може за побудовою, тому стеля тут не
// потрібна: на вузькому екрані елементи просто стануть у два рядки.
function statsHtml(it) {
  const st = [];

  // 🔴 `verified` ставить Вова руками, коли справді перевірив збір. Позначка,
  // яку клеять усім підряд, знецінює слово, заради якого існує.
  if (it.verified) st.push({ ic: ICONS.shieldCheck, t: 'перевірено', on: true });

  // Строк. 🔑 Єдине число на картці, і воно НЕ старіє мовчки: рахується від
  // сьогодні, тож правдиве без жодного оновлення файлу з даними.
  if (!it.closed && it.left != null) {
    st.push({ ic: ICONS.calendar,
      t: it.left === 0 ? 'останній день' : `ще ${it.left} ${plural(it.left, 'день', 'дні', 'днів')}` });
  }

  if (it.place) st.push({ ic: ICONS.pin, t: it.place });

  if (!st.length) return '';
  return `
            <div class="hm-fund-stats">
              ${st.map(s => `
              <span class="hm-fund-stat${s.on ? ' is-on' : ''}">
                <span class="hm-fund-sic" aria-hidden="true">${s.ic}</span>${escapeHtml(s.t)}
              </span>`).join('')}
            </div>`;
}

// Скляна панель — те, що лишилось від макета 16.08 після рішення Вови прибрати
// суму. Верхній ряд «Збирає / Ціль», під ним ряд статистики.
//
// 🔑 Хто збирає стоїть ЛІВОРУЧ і першим навмисно: у зборі коштів найважливіше
// не число, а чи можна довіряти тому, хто просить. Ціль праворуч — єдина сума,
// яка не старіє, бо її ставлять один раз і більше не чіпають.
function panelHtml(it) {
  const goalTxt = money(it.goal);
  return `
          <div class="hm-fund-panel">
            <div class="hm-fund-sums">
              <div class="hm-fund-cell">
                <span class="hm-fund-k">Збирає</span>
                <span class="hm-fund-v">${escapeHtml(it.org)}</span>
              </div>
              ${goalTxt ? `
              <div class="hm-fund-cell hm-fund-cell--goal">
                <span class="hm-fund-k">Ціль</span>
                <span class="hm-fund-v hm-fund-v--big">${goalTxt}</span>
              </div>` : ''}
            </div>
            ${statsHtml(it)}
          </div>`;
}

function fundCardHtml(it) {
  const kind = KIND[it.kind] || KIND.community;

  // 🔑 ФОТО — ПІДКЛАДКА ВСІЄЇ КАРТКИ, а не смужка згори (варіант «2» з макета
  // Вови 05.08). Текст лежить ПОВЕРХ знімка, на градієнті затемнення.
  //
  // ⚠️ Через це картка мусить лишатись читабельною БЕЗ фото: якщо `photo`
  // порожній або знімок не завантажився, під текстом усе одно темна поверхня
  // (див. `.hm-fund` у home.css — базовий фон стоїть на самій картці, а не на
  // зображенні). Тому `onerror="this.remove()"` тут безпечний: зникає лише шар
  // фото, а не тло під літерами. У варіанті «1» такої вимоги не було — там
  // текст лежав на власній білій поверхні.
  return `
    <article class="hm-card hm-fund${it.closed ? ' hm-fund--closed' : ''}">
      ${it.photo ? `
      <img class="hm-fund-ph" src="${escapeHtml(it.photo)}" alt="" loading="lazy"
           onerror="this.remove()">` : ''}
      <span class="hm-fund-scrim" aria-hidden="true"></span>
      <div class="hm-fund-body">
        <div class="hm-fund-kind">
          <span class="hm-fund-ic" aria-hidden="true">${kind.ic}</span>
          <span>${escapeHtml(kind.label)}</span>
        </div>
        <div class="hm-fund-main">
          <h3 class="hm-fund-ttl">${escapeHtml(it.title)}</h3>
          ${it.note ? `<p class="hm-fund-note">${escapeHtml(it.note)}</p>` : ''}

          ${panelHtml(it)}
          ${it.closed ? `
          <p class="hm-fund-done">Збір завершено</p>
          <p class="hm-fund-hint">Дякуємо всім, хто долучився</p>` : `
          <a class="hm-fund-go" href="${escapeHtml(it.url)}" target="_blank" rel="noopener noreferrer"
             aria-label="Відкрити банку Monobank — ${escapeHtml(it.title)}">
            <span class="hm-fund-go-ic" aria-hidden="true">${ICONS.link}</span>
            <span class="hm-fund-go-tx">Посилання на банку Monobank</span>
            <span class="hm-fund-go-ch" aria-hidden="true">${ICONS.chevronRight}</span>
          </a>
          <p class="hm-fund-hint">
            <span class="hm-fund-hic" aria-hidden="true">${ICONS.lock}</span>
            Перехід на офіційну банку
          </p>`}
        </div>
      </div>
    </article>`;
}

export async function renderHomeFund() {
  const sec = document.getElementById('hm-fund');
  const body = document.getElementById('hm-fund-body');
  if (!sec || !body) return;

  const items = await loadFundraisers();
  if (!items.length) {
    // Немає зборів → секції немає ЗОВСІМ. Не «порожній стан», не заглушка:
    // блок про допомогу, який показує «зборів немає», займає місце й нічого не дає.
    sec.hidden = true;
    body.innerHTML = '';
    return;
  }

  sec.hidden = false;

  // Один збір — звичайна картка. Кілька — горизонтальна стрічка з прилипанням,
  // рівно та сама механіка, що у новин (`.hm-ntrack`): людина гортає пальцем,
  // а не вибирає з довгого списку, кому допомогти.
  // ⚠️ Стеля 6: більше зборів на головній перетворюють допомогу на каталог.
  const list = items.slice(0, 6);
  body.innerHTML = list.length === 1
    ? fundCardHtml(list[0])
    : `<div class="hm-ftrack">${list.map(fundCardHtml).join('')}</div>` +
      `<div class="hm-fdots" role="tablist" aria-label="Збори">${
        list.map((_, i) => `<i${i ? '' : ' class="on"'}></i>`).join('')}</div>`;
  body.classList.add('hm-appear');

  // Підпис секції каже, скільки зборів, лише коли їх більше одного.
  const kicker = sec.querySelector('.hm-kicker');
  if (kicker) kicker.textContent = list.length > 1 ? 'Актуальні збори' : 'Актуальний збір';

  if (list.length > 1) wireFundDots(body);
}

// Крапки під стрічкою — «скільки зборів і котрий зараз». На макеті вони є, і це
// не прикраса: у стрічці з прилипанням видно лише край наступної картки, тож
// без крапок незрозуміло, чи там ще один збір, чи їх пʼять.
//
// 🔑 Рахуємо позицію за `scrollLeft`, а не через `IntersectionObserver`: трек
// прилипає (`scroll-snap`), тобто позиція завжди кратна ширині картки, і просте
// ділення дає точну відповідь без спостерігача, який довелось би відчіплювати
// при кожній перемальовці головної (`initCommunity()` перебудовує `#cm-content`
// цілком — саме на цьому вже злітали слухачі в інших блоках).
function wireFundDots(body) {
  const track = body.querySelector('.hm-ftrack');
  const dots = [...body.querySelectorAll('.hm-fdots i')];
  if (!track || dots.length < 2) return;

  let raf = 0;
  const sync = () => {
    raf = 0;
    const card = track.querySelector('.hm-fund');
    if (!card) return;
    // Крок = ширина картки + проміжок. Беремо з ЖИВИХ розмірів, а не з числа в
    // CSS: картка задана у відсотках, і на різних телефонах це різні пікселі.
    const step = card.getBoundingClientRect().width + parseFloat(getComputedStyle(track).gap || 0);
    const i = Math.min(dots.length - 1, Math.max(0, Math.round(track.scrollLeft / (step || 1))));
    dots.forEach((d, n) => d.classList.toggle('on', n === i));
  };
  // Через `requestAnimationFrame`: подія прокрутки сипле десятками разів за
  // секунду, а перемальовувати крапки частіше за кадр немає сенсу.
  track.addEventListener('scroll', () => { if (!raf) raf = requestAnimationFrame(sync); }, { passive: true });
}
