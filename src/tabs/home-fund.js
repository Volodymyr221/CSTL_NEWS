// ⚠️ Форма запису пласка, щоб переїзд у Supabase не зачепив цей файл: зміниться
// лише джерело в `loadFundraisers()`, розмітка й правила лишаться ті самі.
//
//   { "id", "title", "org", "url",
//     "goal":  число ₴ | null,          // ціль; немає — рядок цілі не малюється
