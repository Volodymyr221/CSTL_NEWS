// src/core/layers.js
// Міст між повноекранними шарами додатка і історією браузера.
//
// НАВІЩО (баг зі скріна IMG_3557, 24.07):
//   Жест «назад» від лівого краю на iPhone — СИСТЕМНИЙ. Скасувати його з коду
//   неможливо: `preventDefault()` на нього не діє, бо його обробляє сама iOS, а не
//   веб-сторінка. Раніше наш `attachScreenSwipeBack` ловив рух у тій самій зоні
//   (перші 24px), тож один рух пальця робив ДВІ речі одночасно: ми закривали екран
//   спільноти, а браузер тим часом відкочувався на попередній запис історії — і
//   з-під сторінки виїжджала Дошка, яку користувач не вибирав.
//
// ⚠️ ВАЖЛИВЕ УТОЧНЕННЯ (24.07, друга ітерація — скрін IMG_3559):
//   Перша спроба лишала НАШ свайп на місці й додавала історію — стало гірше: запис в
//   історії ВМИКАЄ системний жест, і тоді iOS малює свою анімацію переходу (тягне всю
//   сторінку, показує знімок попереднього стану) ОДНОЧАСНО з нашим перетягуванням
//   екрана. Два рухи замість одного. Системну анімацію вимкнути неможливо, тому
//   власний свайп прибрано зовсім: жест повністю обслуговує система, ми лише
//   прибираємо екран, коли вона повідомляє про «назад» (popstate).
//
// ЯК ЛІКУЄМО:
//   Не боремося з жестом, а даємо йому правильну роботу. Кожен повноекранний шар,
//   відкриваючись, кладе в історію свій запис. Системний жест «з'їдає» саме цей
//   запис → спрацьовує `popstate` → ми закриваємо ЛИШЕ верхній шар. Додаток
//   лишається на місці, вкладка не міняється. Один рух — одна дія, як у Telegram.
//
// ВАЖЛИВО: закриття з інтерфейсу (кнопка «назад», свайп, тап по фону) теж має йти
// через `closeLayer` — тоді запис в історії знімається разом з екраном і стан не
// розходиться. Якщо закрити екран напряму, в історії лишиться «порожній» запис і
// наступний жест «назад» з'їсть його вхолосту.

import { createDragTracker, finishSwipe } from './sheet-motion.js';

const stack = [];      // відкриті шари, останній = верхній
let seq = 0;

// ── ЗАПОБІЖНИК КОРЕНЯ: не випускати людину в порожню вкладку ─────────────────
//
// 🔴 15.08, скарга Вови (третій знімок — порожня сторінка Safari): «як виходжу
// свайпом з чату в повідомлення і з повідомлень у дошку, то знову таке».
//
// 📐 ЗАМІРЯНО (`tests/tools/notif-backstack-probe.mjs`): перші два «назад»
// ведуть правильно (чат → Повідомлення → застосунок на Дошці), а ТРЕТІЙ дає
// `url: about:blank`. Причина проста й не наша: сповіщення відкриває застосунок
// у СВІЖІЙ вкладці, тобто позаду коренем немає нічого. Будь-який зайвий рух
// пальця вивалює людину на порожню сторінку браузера.
//
// ЛІКУВАННЯ: у сеансі, який почався зі сповіщення, корінь застосунку ПОГЛИНАЄ
// «назад» — ми кладемо запасний запис і повертаємо його щоразу, коли історія
// добігла до низу з порожнім стеком шарів.
//
// 🛑 ЧОМУ ЛИШЕ ДЛЯ СПОВІЩЕНЬ, А НЕ ЗАВЖДИ. Якщо людина прийшла за звичайним
// посиланням (з пошуку, з месенджера), позаду в неї СПРАВЖНЯ попередня
// сторінка, і поглинати «назад» означало б замкнути її в застосунку силоміць.
// А при вході зі сповіщення позаду порожньо за визначенням — там поглинати
// нічого, крім виходу в нікуди.
let rootGuarded = false;

export function guardAppRoot() {
  if (rootGuarded) return;
  rootGuarded = true;
  // ⚠️ Кличеться ДО відкриття будь-якого шару — запис має лягти одразу над
  // сторінкою, інакше він опинився б посеред стеку і поглинав не той крок.
  history.pushState({ cstlRoot: 1 }, '');
}

export function isRootGuarded() { return rootGuarded; }

// Відкрити шар. close — що робити при закритті (прибрати з DOM тощо).
// reuseEntry: true — переоткриття того самого екрана, коли попередній прибрали з DOM
// вручну (напр. після збереження сторінки). Тоді новий запис в історію НЕ додаємо —
// займаємо вільний запис попереднього шару, інакше вони б накопичувались.
// animateOut — необовʼязково: як показати зникнення при закритті з КНОПКИ
// (системний жест анімує сам, тому там це не потрібно).
export function openLayer(close, opts = {}) {
  const layer = { id: ++seq, close, closed: false, animateOut: opts.animateOut || null };
  const top = stack[stack.length - 1];
  if (opts.reuseEntry && top) {
    top.closed = true;
    stack[stack.length - 1] = layer;
    if (opts.el) attachSwipeBack(opts.el, layer);
    return layer;
  }
  stack.push(layer);
  history.pushState({ cstlLayer: layer.id }, '');
  // `el` — необовʼязковий: шар без нього поводиться рівно як раніше (закриття
  // системним жестом від краю). Передали елемент — додається ще й свайп
  // «звідки завгодно», див. пояснення нижче.
  if (opts.el) attachSwipeBack(opts.el, layer);
  return layer;
}

// ── СВАЙП НАЗАД «ЗВІДКИ ЗАВГОДНО» (19.08) ────────────────────────────────────
//
// 🔴 СКАРГА ВОВИ: «коли я закриваю сторінки свайпом з лівої частини екрану, мені
// треба палець ставити аж на самий край і звідти тягнути, важко дотягнутись».
// Він має рацію, і причина не в нашому коді: досі цей жест ОБСЛУГОВУВАЛА iOS, а
// ширину її зони (≈20pt від краю) задає Apple — з вебу вона не міняється.
//
// 🛑 ЧОМУ РАНІШЕ ВЛАСНОГО СВАЙПУ ТУТ НЕ БУЛО (і чому тепер можна).
// 24.07 його прибрали після двох невдач (скріни IMG_3557 / IMG_3559): наш жест
// жив у ТІЙ САМІЙ зоні, що системний, тож один рух пальця робив дві дії — ми
// закривали екран, а iOS паралельно відкочувала історію й малювала СВОЮ
// анімацію переходу. Помилка була не в самій ідеї власного жесту, а в тому, що
// він накладався на системний.
// ➡️ Тому тут зона починається ПІСЛЯ системної (`EDGE`): 0-28px лишаються iOS,
//    від 28px і далі — наші. Один рух — одна дія, як і домовлялись.
//
// 🔑 ПЛАВНІСТЬ. Вова окремо просив, щоб «плавність була така як зараз є». Тому це
// не спрацювання по відпусканню, а ІНТЕРАКТИВНЕ перетягування: екран іде за
// пальцем, а рішення (закрити чи повернути) і доїзд рахує `finishSwipe` з
// `core/sheet-motion.js` — той самий модуль і та сама крива, що в усіх аркушів
// застосунку. Другої фізики не заводимо (HOT_RULES №8).
const EDGE      = 28;    // px від лівого краю — власність системного жесту iOS
// 🔴 19.08, друга редакція — ЗОНА ОБМЕЖЕНА ЛІВОЮ ПОЛОВИНОЮ (Вова: «щоб з лівої
// частини до половини був екран з закриттям свайпом, даже з 40%»).
// Перша редакція ловила жест на ВСІЙ ширині. Це працювало, але має ціну: на
// правому краю живе те, чим людина користується великим пальцем — кнопки,
// каруселі, галерея фото в оголошенні. Обмеження робить поведінку передбачуваною:
// ліва половина закриває, права ніколи нічого не закриває.
// ⚠️ Якщо на живому телефоні почне здаватись «іноді працює, іноді ні» — причина
// буде саме тут, у межі. Тоді повертаємо 1 (уся ширина) одним числом.
const ZONE      = 0.5;   // частка ширини екрана зліва, де жест наш
const DECIDE    = 10;    // px — доки не пройшли стільки, напрям руху ще не ясний
const DOMINANCE = 1.5;   // горизонталь має бути настільки більшою за вертикаль

// Чи стоїть палець усередині чогось, що САМЕ прокручується вбік і ще має куди.
// Приклад із життя: смуга категорій у Хабі новин і каруселі. Якщо там ще є що
// гортати вправо — жест належить їй, а не закриттю екрана.
function всерединіБічногоСкролера(node, root) {
  for (let el = node; el && el !== root; el = el.parentElement) {
    if (!(el instanceof Element)) continue;
    const ox = getComputedStyle(el).overflowX;
    if ((ox === 'auto' || ox === 'scroll') && el.scrollWidth > el.clientWidth + 1 && el.scrollLeft > 0) {
      return true;
    }
  }
  return false;
}

function attachSwipeBack(el, layer) {
  let startX = null, startY = null, locked = false, dx = 0;
  const tracker = createDragTracker();

  el.addEventListener('touchstart', (e) => {
    startX = null; locked = false; dx = 0;
    if (e.touches.length !== 1) return;                       // мультитач — не наш
    if (layer.closed || stack[stack.length - 1] !== layer) return;  // зверху інший шар
    const t = e.touches[0];
    if (t.clientX <= EDGE) return;                            // системна зона — віддаємо iOS
    // Праворуч від межі жест не наш: там кнопки, каруселі й галереї, і випадкове
    // закриття екрана коштувало б дорожче за зручність «тягнути звідусіль».
    if (t.clientX > (el.clientWidth || window.innerWidth) * ZONE) return;
    // 🛑 Місця, де горизонтальний рух УЖЕ щось означає (перемикання категорій у
    // Хабі новин, відповідь на повідомлення в чаті, переміщення фото в кропері).
    // Перелічені явно атрибутом, а не вгадані: вгадування тут коштувало б
    // зламаного жесту, про який ніхто б не здогадався.
    if (e.target.closest && e.target.closest('[data-swipe-own]')) return;
    if (всерединіБічногоСкролера(e.target, el)) return;
    startX = t.clientX; startY = t.clientY;
    tracker.start(t.clientX);
  }, { passive: true });

  // ⚠️ НЕ `passive`: щойно ми впізнали свій жест, треба скасувати прокрутку
  // сторінки, інакше екран поїде за пальцем І прокрутиться водночас.
  el.addEventListener('touchmove', (e) => {
    if (startX == null || e.touches.length !== 1) return;
    const t = e.touches[0];
    const рух  = t.clientX - startX;
    const вбік = t.clientY - startY;

    if (!locked) {
      if (Math.abs(рух) < DECIDE && Math.abs(вбік) < DECIDE) return;  // ще не ясно
      // Наш жест — тільки рух УПРАВО і тільки якщо горизонталь переважає.
      // Діагональний рух лишається прокруткою: так само, як в `attachSwipe`.
      if (рух <= 0 || Math.abs(рух) <= Math.abs(вбік) * DOMINANCE) { startX = null; return; }
      locked = true;
      el.style.transition = 'none';
    }

    e.preventDefault();
    dx = Math.max(0, рух);
    tracker.move(t.clientX);
    el.style.transform = `translateX(${dx}px)`;
  }, { passive: false });

  const кінець = () => {
    if (startX == null) { return; }
    startX = null;
    if (!locked) return;
    locked = false;
    finishSwipe({
      panel: el,
      dy: dx,                                   // тут це відстань УПРАВО
      velocity: tracker.velocity,
      remaining: Math.max((el.offsetWidth || window.innerWidth) - dx, 1),
      dismissTransform: 'translateX(100%)',
      restTransform: '',
      // Закриваємо ПІСЛЯ доїзду: `closeLayer` знімає запис історії й прибирає
      // екран з DOM, тож викликаний одразу він обірвав би анімацію на льоту.
      onDismiss: (ms) => setTimeout(() => closeLayer(layer), ms),
    });
    dx = 0;
  };
  el.addEventListener('touchend', кінець, { passive: true });
  el.addEventListener('touchcancel', кінець, { passive: true });
}

// Закриття з інтерфейсу (кнопка «назад», тап по фону). Йдемо через історію →
// popstate виконає саме закриття. `animate` — програти власну анімацію ПЕРЕД тим:
// системний жест анімує сам, а натискання кнопки — ні, тож інакше екран зникав би різко.
export function closeLayer(layer, opts = {}) {
  if (!layer || layer.closed) return;
  const go = () => {
    if (stack[stack.length - 1] === layer) history.back();
    else finish(layer);            // не верхній (рідкісний випадок) — напряму
  };
  if (opts.animate && typeof layer.animateOut === 'function') {
    layer.animating = true;
    try { layer.animateOut(); } catch (_) {}
    setTimeout(go, opts.animate);
    return;
  }
  go();
}

function finish(layer) {
  const i = stack.indexOf(layer);
  if (i >= 0) stack.splice(i, 1);
  if (layer.closed) return;
  layer.closed = true;
  try { layer.close(); } catch (e) { console.warn('[layers] close:', e && e.message); }
}

// Системний жест «назад» або кнопка «назад» браузера.
// Є відкритий шар → закриваємо його. Немає → нічого не робимо, і жест працює як
// звичайна навігація (нормальна поведінка для PWA).
window.addEventListener('popstate', () => {
  const top = stack[stack.length - 1];
  if (top) { finish(top); return; }
  // Шарів більше немає, а історія добігла до низу. У сеансі зі сповіщення це
  // означає «наступний крок — порожня вкладка», тож повертаємо запасний запис
  // і лишаємо людину в застосунку.
  if (rootGuarded) history.pushState({ cstlRoot: 1 }, '');
});

// Чи є зараз відкритий шар (для налагодження і майбутніх перевірок).
export function hasOpenLayer() { return stack.length > 0; }
