// src/core/refresh-on-return.js
// 🔴 ОДНЕ МІСЦЕ ПРАВДИ ПРО «ЛЮДИНА ПОВЕРНУЛАСЬ — ПОКАЖИ СВІЖЕ» (07.08).
//
// ЗАМОВЛЕННЯ ВОВИ (дослівно): «зайшов з другого акаунту і змінив імʼя та
// встановив фото на профіль, але мені не оновило це відразу в додатку,
// приходиться закрити додаток повністю і зайти… ми можемо це і все інше де
// відображається публічна інформація оновлювати відразу… хоча б коли вони
// перейшли на іншу вкладку і назад. Це питання треба закрити раз і назавжди».
//
// ЩО ЦЕ ДАЄ. Контракт навмисно вузький і той самий для всіх зон:
//   «повернувся на вкладку (або в застосунок) → те, що на екрані, перечитано».
// Не «оновлюємо все і завжди» — це був би шквал запитів і сіпання екрана.
//
// 🔑 ДВА ПРИВОДИ, А НЕ ОДИН:
//   1. `cstl-tab-changed` — перемикання вкладок усередині застосунку (`app.js`);
//   2. `visibilitychange` → `visible` — повернення в застосунок ззовні. На
//      iPhone у режимі PWA це ГОЛОВНИЙ шлях: людина згорнула застосунок, пішла
//      в інший, повернулась — жодного перемикання вкладок при цьому не було.
//      Без другого приводу «раз і назавжди» не вийшло б.
//
// 🛑 ЧОГО ТУТ НЕМАЄ І НЕ МАЄ ЗʼЯВИТИСЬ:
//   • власного перемальовування — зона сама вирішує, ЩО оновити своїм наявним
//     механізмом (`refreshBoardKeepingPlace`, `patchPostCard`, `hydrateNames`…);
//   • другого таймера-опитувача — «раз на N секунд питати базу» ми свідомо не
//     заводимо: це трафік і батарея заради даних, на які ніхто не дивиться.
//
// ⚠️ АНТИФЛУД ОБОВʼЯЗКОВИЙ. Перемикання вкладок — найдешевший жест у
// застосунку, і людина робить його підряд. Без порогу кожен тик таб-бару
// перетворювався б на похід у базу.

import { invalidateProfiles, hydrateNames, hydrateAvatars } from './supabase.js';

// Мінімум між двома оновленнями. 🔑 Число підбиралось НЕ «щоб було»:
// перша версія стояла 20с — і сцена Вови («перейшов на вкладку і назад») просто
// не спрацьовувала, бо між двома тапами минає кілька секунд. Тобто поріг з'їдав
// саме те замовлення, заради якого все й робиться.
// 5с лежать у розриві між двома величинами: швидке смикання таб-бару — це частки
// секунди (його поріг ловить), а свідоме «пішов і повернувся» — одиниці секунд і
// довше (його пропускає). Піднімеш назад — зламаєш замовлення, і `live-profile`
// це покаже.
const MIN_GAP = 5000;

const _subs = [];        // { tab, fn, last }
let _wired = false;
let _lastHydrate = 0;    // коли востаннє перечитували імена/фото (спільний поріг)

// Скільки минуло з останнього спрацювання — окремо для кожного підписника,
// бо зони повертаються в різний час і чужий тик не має «з'їдати» твій поріг.
function fire(reason) {
  const now = Date.now();
  // Свіжість профілів знімаємо ОДИН раз на подію, а не на кожного підписника:
  // інакше три зони поспіль підняли б покоління кешу тричі й змусили б
  // перемальовувати вже перемальоване.
  let invalidated = false;
  const дозріло = (s) => (!s.tab || s.tab === currentTab()) && (now - s.last >= MIN_GAP);
  const готові = _subs.filter(дозріло);
  if (готові.length || now - _lastHydrate >= MIN_GAP) {
    invalidateProfiles();
    invalidated = true;
  }
  for (const s of готові) {
    s.last = now;
    try { s.fn(reason); } catch (e) { console.warn('[refresh-on-return]', e && e.message); }
  }
  // 🔑 ІМЕНА І ФОТО — ОДНИМ МІСЦЕМ НА ВЕСЬ ЗАСТОСУНОК, а не по зонах.
  // Кожна поверхня, що показує чужу людину, уже несе маркер `data-name-uid` або
  // `data-av-uid` (Дошка, Стрічка, Обговорення, чати, коментарі — див. карту в
  // `_ai-tools/BYYOU_PLAN.md`). Тому після зняття свіжості достатньо пройтись
  // гідрацією по документу: вона сама збере всі uid у ОДИН батч-запит і підмінить
  // те, що змінилось. Заводити на це по виклику в кожній зоні означало б чотири
  // копії одного правила — рівно та хвороба, від якої проєкт уже страждав.
  if (invalidated) {
    _lastHydrate = now;
    hydrateNames(document.body);
    hydrateAvatars(document.body);
  }
}

// Активна вкладка — по атрибуту, який ставить `switchTab` (`app.js`).
// Через DOM, а не через імпорт зі `app.js`: той імпортує пів застосунку, і
// коло імпортів тут коштувало б дорожче за один `querySelector`.
function currentTab() {
  return document.querySelector('.app-main')?.dataset.tab || '';
}

/**
 * Підписатись на «людина повернулась».
 * @param tab  імʼя вкладки (`board`, `shotam`…) або '' — «будь-де в застосунку»
 * @param fn   що перечитати. Кличеться з причиною: 'tab' | 'visible'
 *
 * ⚠️ Кличеться ОДИН раз на модуль (не з рендера) — інакше підписники
 * накопичувались би на кожну перемальовку. Той самий урок, що з
 * `_threadsEvtWired` у `board.js`.
 */
export function onReturn(tab, fn) {
  _subs.push({ tab: tab || '', fn, last: Date.now() });
  initRefreshOnReturn();
}

// Увімкнути механізм. Кличеться з `app.js` БЕЗ умов — імена і фото оновлюються
// навіть якщо жодна зона не підписалась своєю роботою (це базовий контракт).
export function initRefreshOnReturn() {
  if (_wired) return;
  _wired = true;
  _lastHydrate = Date.now();   // щойно стартували — усе щойно намальоване свіже
  window.addEventListener('cstl-tab-changed', () => fire('tab'));
  document.addEventListener('visibilitychange', () => {
    if (document.visibilityState === 'visible') fire('visible');
  });
}

// Для стендів і налагодження: примусово, повз поріг.
export function forceReturnRefresh() {
  _subs.forEach(s => { s.last = 0; });
  fire('force');
}
