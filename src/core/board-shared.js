// 🔑 БЕРЕМО НАЙПІЗНІШЕ З ДВОХ (`Math.max`). Пристрій міг поставити мітку
// офлайн — тоді вона свіжіша за базу; база могла дістати мітку з іншого
// телефона — тоді свіжіша вона. Максимум обидва випадки покриває одним
// правилом, і воно те саме, що `greatest` у базі: **мітка рухається тільки
// вперед**. Інакше старий відкритий таб «непрочитував» би все назад.
//
// 🛑 Гість лишається ПОВНІСТЮ на пристрої: синхронізувати нема з чим, акаунта
// немає. Це не виняток із правила, а те саме правило.
let seenCache = {};        // { base: мітка в мс } — злите значення бази й пристрою
let seenLoadedFor = null;  // для якого uid кеш наповнений (null = гість/ще ні)

// 🔴 01.09 — ПЕРЕНОС МІТКИ З ГОСТЯ НА АКАУНТ. Без нього прочитане ЗНИКАЛО.
//
// 🗣️ Скарга Вови: «якщо я його прочитав, воно мені не має вибивати другий раз,
// коли я заходжу в додаток».
//
// 🔬 ЩО ВІДБУВАЛОСЬ. Ключ мітки — `base + ':' + (currentUserId() || 'anon')`, а
// `initAuth()` кличеться БЕЗ await (це задокументоване рішення: інакше запуск
// застосунку залежав би від мережі). Тобто в перші секунди після відкриття
// `currentUserId()` ще `null`. `openNewsHub()` кличе `markNewsSeen()` одразу —
// і мітка лягає під `:anon`. Коли авторизація доїжджає, читання йде вже під
// `:<uid>`, де порожньо, і «прочитане» зникає назавжди.
// 📐 Доведено приладом `tests/tools/news-seen-anon2.mjs`: у сховищі мирно
// співіснували ДВА простори ключів — `cstl_news_seen_ts:anon` і
// `cstl_news_seen_ts:<uid>`, і жоден не знав про інший.
//
// 🔑 Беремо НАЙПІЗНІШЕ з двох, а не просто копіюємо: мітка рухається лише
// вперед — те саме правило, що вже діє для пари «пристрій / база».
// 🛑 Гостьовий ключ стираємо ЛИШЕ коли його забрав СПРАВЖНІЙ акаунт — та сама
// асиметрія, що в `adoptLegacySeen` нижче: поки людина не увійшла, вона має
// право на свої мітки.
function adoptAnonSeen(base) {
  const uid = currentUserId();
  if (!uid) return null;                       // ще гість — переносити нема куди
  const anon = localStorage.getItem(base + ':anon');
  if (anon == null) return null;
  try {
    const мій = Number(localStorage.getItem(base + ':' + uid) || 0);
    const гість = Number(anon || 0);
    if (Number.isFinite(гість) && гість > мій) {
      localStorage.setItem(base + ':' + uid, String(гість));
    }
    localStorage.removeItem(base + ':anon');
    return String(Math.max(мій, Number.isFinite(гість) ? гість : 0));
  } catch (_) { return null; }
}

export function readSeen(base) {
  const local = (() => {
    // Спершу забираємо мітку, залишену до того, як застосунок дізнався, хто я.
    adoptAnonSeen(base);
    let raw = localStorage.getItem(seenKey(base));
    if (raw == null) raw = adoptLegacySeen(base);
    const v = Number(raw || 0);
    return Number.isFinite(v) ? v : 0;
  })();
  return Math.max(local, seenCache[base] || 0);
}

export function writeSeen(base) {
  const now = Date.now();
  seenCache[base] = Math.max(seenCache[base] || 0, now);
  // Пристрій — одразу: екран мусить відреагувати без мережі.
  try { localStorage.setItem(seenKey(base), String(now)); } catch (_) {}
  // База — слідом, тихо. ⚠️ НЕ чекаємо і НЕ показуємо помилку: мітка «я це
  // бачив» не та річ, заради якої можна зупинити людину або блимнути тостом.
  // Не доїхало — наступний `markSeen` перекриє, бо час іде тільки вперед.
  const uid = currentUserId();
  if (uid) markSeenRemote(SCOPE_OF[base]).catch(() => {});
}

// ── СПИСОК «ЦЕ Я ВЖЕ ЧИТАВ» (окремі записи, а не одна мітка) ────────────────
// 🔴 31.08 — заведено під скаргу Вови на «N нових» у новинах: «читаю статті…
// закриваю додаток, заходжу і знову пише сім нових».
//
// 🔑 ЧОМУ ОДНОГО ЧИСЛА БУЛО ЗАМАЛО. Мітка розділу каже лише «коли я востаннє
// заходив». Виразити «прочитав ОДНУ з семи» вона не вміє В ПРИНЦИПІ: після
// прочитання однієї статті або гасне все, або не гасне нічого. Тому поруч живе
// список конкретних записів, а мітка лишається ПІДЛОГОЮ під ним.
//
// 🛑 ЧОМУ ТУТ, А НЕ В `tabs/news.js`. Ім'я ключа акаунта (`base:uid`) — те саме
// правило, що вже обслуговує чотири мітки. Друга копія цього правила розійшлася
// б із першою, і симптом виглядав би як «у декого прочитане зникло»; у проєкті
// це вже коштувало бага зі списками антиспаму.
//
// ⚠️ ЧЕСНА МЕЖА: список живе НА ПРИСТРОЇ. Мітка розділу синхронізується через
// базу, а окремі записи — ні: для них потрібна власна таблиця, а `user_seen_threads`
// зайняти не можна — там лежать `post_id` Питань, і номери мовчки збіглися б.
// Наслідок для людини: «відкрив усі новини» переїжджає на інший пристрій, а
// «прочитав одну статтю з семи» — ні. Шкода від розсинхрону — зайва одиниця в
// бейджі, а не чужі дані на екрані.
export function readSeenIds(base) {
  try {
    const raw = JSON.parse(localStorage.getItem(seenKey(base)) || '[]');
    return Array.isArray(raw) ? raw.filter(Number.isFinite) : [];
  } catch (_) { return []; }
}

// ⚠️ СТЕЛЯ ОБОВ'ЯЗКОВА. Без неї список росте вічно і колись переповнить сховище —
// а `localStorage` при переповненні кидає виняток на ЗАПИСІ, тобто зламалося б
// не читання новин, а перше-ліпше збереження поруч. Ріжемо з ХВОСТА: свіжі
// номери важливіші, бо старі статті однаково нижчі за підлогу-мітку.
export const SEEN_IDS_MAX = 300;

export function writeSeenIds(base, ids) {
  const next = [...new Set(ids.filter(Number.isFinite))].slice(-SEEN_IDS_MAX);
  try { localStorage.setItem(seenKey(base), JSON.stringify(next)); } catch (_) {}
  return next;
}

// Назви розділів у базі (`user_seen_marks.scope`). Тримаємо мапу тут, поруч із
// самими ключами, а не в чотирьох викликачах — інакше друга копія розійшлась би
// з першою (у проєкті таке вже коштувало бага зі списками антиспаму).
const SCOPE_OF = {};

/** Зареєструвати мітку: локальний ключ ↔ назва розділу в базі. */
export function registerScope(base, scope) { SCOPE_OF[base] = scope; return base; }

/**
 * Наповнити кеш із бази. Кличеться при вході й зміні акаунта.
 *
 * ⚠️ ПЕРЕНОСИМО ТЕ, ЩО ВЖЕ ЛЕЖИТЬ НА ПРИСТРОЇ. Людина користувалась застосунком
 * до цього оновлення, і її мітки живуть лише тут. Якби ми просто прочитали базу
 * (порожню) і поклали в кеш, усе прочитане стало б «новим» — рівно та вада, яку
 * вранці вже ловив `home-caps`. Тому кожну локальну мітку відправляємо в базу
 * через `seed_seen`, а вона сама вирішує через `greatest`, чи вона свіжіша.
 */
export async function loadSeenMarks() {
  const uid = currentUserId();
  if (!uid) { seenCache = {}; seenLoadedFor = null; return; }
  if (seenLoadedFor === uid) return;      // уже наповнено для цієї людини

  const remote = await fetchSeenMarks(uid);
  const next = {};
  for (const [base, scope] of Object.entries(SCOPE_OF)) {
    const fromDb = remote[scope] || 0;
    let local = Number(localStorage.getItem(seenKey(base)) || 0);
    if (!Number.isFinite(local)) local = 0;
    next[base] = Math.max(fromDb, local);
    if (local > fromDb) seedSeenRemote(scope, local).catch(() => {});
  }
  seenCache = next;
  seenLoadedFor = uid;
}

// 🔑 Підписка живе ТУТ, а не в `app.js`: мітки знає цей файл, і додавати за ними
// нагляд ззовні означало б, що про новий розділ треба памʼятати у двох місцях.
// ⚠️ Після завантаження шлемо `cstl-seen-synced` — бейджі «N нових» уже
// намальовані зі СТАРИМ значенням, і без сигналу мітка з іншого пристрою
// доїхала б лише до наступного перемальовування. Саме це людина й помітила б як
// «синхронізація не працює».
onAuthChange(() => {
  seenLoadedFor = null;
  loadSeenMarks().then(() => {
    try { window.dispatchEvent(new CustomEvent('cstl-seen-synced')); } catch (_) {}
  });
});

// Той самий перенос для міток, що живуть поза цим файлом (Новини, теми Питань).
// 🛑 Копію логіки НЕ робити — правило одноразовості легко зіпсувати наполовину,
// і симптом виглядав би як «у декого мітки зникли».
export function adoptLegacyScopedKey(base) {
  const key = base + ':' + (currentUserId() || 'anon');
  if (localStorage.getItem(key) != null) return;
  const old = localStorage.getItem(base);
  if (old == null) return;
  try {
    localStorage.setItem(key, old);
    if (currentUserId()) localStorage.removeItem(base);
  } catch (_) { /* нічого не робимо */ }
}

