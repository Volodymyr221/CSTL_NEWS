import { hasShape, shapeHtml } from './skeletons.js';   // форми під кожен екран (19.09)

// 🔴 19.09 — ПЕРША ФІЧА, ЯКА ЇХАЛА ЧЕРЕЗ СИСТЕМУ ОНОВЛЕНЬ. ПРАПОРЕЦЬ ЗНЯТО 20.09.
// 🗣️ Вова: «стрічка зараз завантажується як список, а може так як елементи на
// стрічці… І так з кожною вкладкою — взяти макет сторінки і створити сторінку
// завантаження».
//
// 📐 Шлях прапорця `skeleton_shapes`, записаний, щоб не відновили його наосліп:
// `off` 19.09 → `all` 19.09 19:59 (Вова тапнув «усім») → «Прибрано з коду» 20.09.
// 🔑 ЧОМУ ВІН ТУТ БІЛЬШЕ НЕ ПОТРІБЕН: прапорець існує рівно для часу, поки на
// екрані два шляхи і треба вміти вернутись на старий БЕЗ деплою. Фіча в усіх
// другу добу, старий загальний кістяк лишається тільки запасним (коли форми під
// екран немає) — тримати заради цього мережеву перевірку означає платити за
// відкат, якого вже не буде.
// 🛑 І це не косметика: `featureOn()` на невідомий ключ віддає `false` МОВЧКИ.
// Рядок у базі вже архівований, перемикача в адмінці немає — тож варто було б
// тому рядку колись перестати приїжджати, і форми зникли б без жодного сліду,
// а подивитись було б ніде. Прибрана перевірка такого стану не має в принципі.

// 🔑 Скелет повторює ФОРМУ того, що приїде, а не абстрактні прямокутники:
// інакше в момент появи даних розкладка сіпнеться — саме те, від чого скелет і
// має рятувати.
// 🔴 І ДО 19.09 ЦЕЙ КОМЕНТАР БУВ НАПІВПРАВДОЮ. Намір правильний, виконання — ні:
// форма була ОДНА на всі екрани («фото 64px ліворуч + три смужки»), хоч на
// Стрічку приїжджає карусель спільнот і картка з фото 4:5 на всю ширину. Саме
// це зняв Вова знімками. Форми під кожен екран живуть у `skeletons.js`.
// ⚠️ Класи `.hm-sk*` глобальні (style/home.css) і вже мають анімацію
// мерехтіння — другої такої не заводимо.
//
// `kind` — який екран малюємо ('feed' | 'board' | 'questions' | 'buses' |
// 'community'). Не переданий або невідомий → старий загальний кістяк.
export function loadingHtml(rows = 3, kind = '') {
  if (kind && hasShape(kind)) {
    return `<div class="scr-loading" role="status">
      <p class="scr-loading-tx">Завантажую…</p>
      ${shapeHtml(kind, rows)}
    </div>`;
  }
  return загальнийКістяк(rows);
}

function загальнийКістяк(rows = 3) {
  const row = `
    <div class="hm-card hm-sk-row" aria-hidden="true">
      <div class="hm-sk hm-sk-ph"></div>
      <div class="hm-sk-lines">
        <div class="hm-sk hm-sk-l1"></div>
        <div class="hm-sk hm-sk-l2"></div>
        <div class="hm-sk hm-sk-l3"></div>
      </div>
    </div>`;
  // 🔴 НАПИС, А НЕ САМЕ МЕРЕХТІННЯ. Скелет зрозумілий тому, хто бачив його в
  // інших застосунках; жителю, який уперше відкрив телефон-застосунок, сірі
  // смужки не кажуть нічого. Слово «Завантажую…» коштує один рядок і знімає
  // питання «воно зламалось чи думає».
  return `<div class="scr-loading" role="status">
      <p class="scr-loading-tx">Завантажую…</p>
      ${row.repeat(rows)}
    </div>`;
}

// Стан «не змогли». Кнопка тут не прикраса: єдина причина цього екрана —
// тимчасова недосяжність бази, тобто повтор справді має шанс спрацювати.
export function offlineHtml(title = 'Не вдалось завантажити') {
  return `
    <div class="scr-offline" role="alert">
      <p class="scr-offline-ttl">${title}</p>
      <p class="scr-offline-tx">Не вдалось звʼязатися з сервером. Перевір інтернет і спробуй ще раз.</p>
      <button class="scr-offline-btn" type="button">Спробувати ще</button>
    </div>`;
}

// ── 🔴 20.09 — КІСТЯК НЕ ДОВШИЙ ЗА ЕКРАН ──────────────────────────────────────
//
// 🗣️ Вова: «в момент завантаження новий фон завантаження скролиться, він має бути
// може статичним? Чи як це в інших соцмережах?».
//
// 📐 ЗАМІРЯНО (`tests/tools/skeleton-scroll-probe.mjs`, вікно 390×844): при
// увімкненому прапорці кістяк Стрічки тримав **1407px** — це 707px сірої
// порожнечі під згином; Автобуси 802px і 214px запасу. Дошка (534) і Питання
// (583) влазили. Зі старим загальним кістяком не гортався ЖОДЕН екран — тобто
// довжину привели саме нові форми.
//
// 🔑 ЩО РОБЛЯТЬ ФЕЙСБУК І ІНСТАГРАМ. Прокрутку вони не блокують — кістяк живе у
// звичайному скролері. Але й довгої сірої колони не малюють: одна-дві заглушки,
// рівно щоб тримати форму НАД ЗГИНОМ. Нижче згину кістяк не тримає нічого, він
// лише дає куди гортати.
// 🛑 ЧОМУ НЕ ЗАБОРОНИТИ ПРОКРУТКУ. Заблокований екран читається як «застосунок
// завис» — рівно те, від чого кістяк і рятує; на iPhone зникла б гумова віддача,
// і неживість екрана відчувається одразу. Тому ріжемо ДОВЖИНУ, а не рух.
//
// ⚠️ ЧОМУ ВИМІР, А НЕ ЧИСТИЙ CSS. Верх кістяка різний на різних вкладках
// (заміряно: Стрічка 56px, Автобуси 180px — над ним стоїть хром, намальований
// одразу), а CSS не знає, де саме опинився елемент. Стеля «висота вікна мінус
// щось однакове» різала б Автобуси на 124px зайвого.
function застосуватиСтелю(кістяк) {
  if (!кістяк.offsetParent) return false;       // вкладка схована — міряти нічого
  const r = кістяк.getBoundingClientRect();
  if (r.height < 40) return false;
  // Низ видимої зони — ВЕРХ смуги вкладок, а не низ вікна: під смугою кістяка
  // однаково не видно. Беремо живий елемент, а не `--tabbar-h`: до змінної ще
  // додається безпечна зона телефона, і складати їх у JS означало б завести
  // другий рахунок тієї самої висоти.
  const смуга = document.querySelector('.tab-bar');
  const низ = смуга ? смуга.getBoundingClientRect().top : window.innerHeight;
  const доступно = Math.round(низ - r.top);
  // Менше двох третин екрана — щось у вимірі не те (перехідна розкладка,
  // згорнуте вікно). Обрізати наосліп гірше, ніж лишити як є.
  if (доступно < 200) return false;
  кістяк.style.maxHeight = `${доступно}px`;
  кістяк.style.overflow = 'hidden';

  // 🔑 ДРУГИЙ ПРОХІД — І ВІН НЕ ПЕРЕСТРАХОВКА. 📐 Після першого лишалось 31px
  // прокрутки на Стрічці і 19px на Автобусах: під кістяком у скролері стоять
  // власні поля контейнера, яких вимір «від верху кістяка до смуги вкладок» не
  // бачить. Замість того, щоб вгадувати ці поля числом, питаємо скролер, чи
  // лишилось куди гортати, і знімаємо рівно стільки.
  const скролер = кістяк.closest('.app-main');
  if (скролер) {
    const зайве = скролер.scrollHeight - скролер.clientHeight;
    if (зайве > 0) кістяк.style.maxHeight = `${Math.max(200, доступно - зайве)}px`;
  }
  return true;
}

function обрізатиПоВікно(el) {
  const кістяк = el && el.querySelector('.scr-loading');
  if (!кістяк) return;
  if (застосуватиСтелю(кістяк)) return;
  // 🔴 І ОСЬ ТУТ ПЕРША РЕДАКЦІЯ ЦІЄЇ ПРАВКИ НІЧОГО НЕ РОБИЛА, а виглядала
  // зробленою. 📐 Заміряно приладом: стеля лягла лише на Питання (731px), а на
  // Стрічці, Дошці й Автобусах не лягла ЗОВСІМ. Причина: кістяк малюється на
  // старті застосунку, коли вкладку ще не відкрито, — `offsetParent` порожній,
  // мірка дає нулі, і функція чесно виходила. Тобто вада лишалась рівно там, де
  // на неї скаржився Вова (Стрічка, 707px порожнечі).
  // ✅ Тому міряємо ВДРУГЕ — коли кістяк справді показали. Спостерігач видимості
  // тут той самий примітив, що й у каруселі: жодного таймера, жодного опитування.
  if (!('IntersectionObserver' in window)) return;
  const io = new IntersectionObserver((записи) => {
    if (!записи.some(z => z.isIntersecting)) return;
    io.disconnect();
    застосуватиСтелю(кістяк);
  });
  io.observe(кістяк);
}

export function paintLoading(el, rows = 3, force = false, kind = '') {
  if (!el) return;
  // ⚠️ Не затираємо те, що вже намальоване даними: скелет доречний лише на
  // ПОРОЖНЬОМУ екрані. Інакше повернення на вкладку (`onReturn`) щоразу
  // змітало б готовий список і показувало мерехтіння на рівному місці.
  // 🔑 `force` — для випадку, коли на екрані стоїть НЕПРАВДА: Дошка при першому
  // відкритті вже має намальоване «Тут поки порожньо», і саме його треба
  // замінити скелетом, поки правда їде з мережі.
  if (!force && (el.querySelector('.scr-loading') || el.children.length)) return;
  el.innerHTML = loadingHtml(rows, kind);
  обрізатиПоВікно(el);

  // 🔴 20.09 — ТУТ СТОЯВ ДРУГИЙ МАЛЮНОК «КОЛИ ПРИЇДУТЬ ПРАПОРЦІ», І ВІН ПІШОВ
  // РАЗОМ ІЗ ПРАПОРЦЕМ. Потрібен він був через справжню суперечність: кістяк
  // малюється ДО мережі (у цьому весь його сенс), а `my_features()` приходить З
  // мережі, тож на першому запуску форма вибиралась, коли прапорця ще не знали.
  // 🔑 Знявши перевірку, ми зняли й саму суперечність: форма відома одразу, з
  // коду. Слухач `cstl-features-ready` лишався б вічно хибним і перемальовував
  // би кістяк тим самим кістяком.
}

// ⚠️ Параметри читаються з обʼєкта, а НЕ розбираються в сигнатурі: сторож
// `scripts/check-imports.js` бачить деструктуризований `onRetry` як «виклик
// неоголошеного імені» і падає. Дрібниця, але вона тримає збірку зеленою.
export function paintOffline(el, opts = {}) {
  if (!el) return;
  const retry = opts.onRetry;
  const kind = opts.kind || '';
  el.innerHTML = offlineHtml(opts.title);
  const btn = el.querySelector('.scr-offline-btn');
  if (btn && typeof retry === 'function') {
    btn.addEventListener('click', () => {
      // Повтор починається з того самого скелета: без нього тап по кнопці
      // виглядав би так, ніби нічого не сталось, і людина тапала б ще раз.
      el.innerHTML = loadingHtml(2, kind);
      retry();
    });
  }
}

// Чи стоїть на екрані наш стан (скелет або збій) — щоб виклик нагорі знав,
// що екран НЕ порожній і його вміст ще не є відповіддю про громаду.
export function hasScreenState(el) {
  return !!el && !!el.querySelector('.scr-loading, .scr-offline');
}
