// 🔴 ЗАРАДИ ЧОГО (18.09.2026, прогін «перший житель із поганим інтернетом»).
//
// Заміряно на живому застосунку з недосяжною базою — рівно те, що буває в селі:
//   • Стрічка   — 0 знаків на екрані. Порожнє полотно, жодного слова;
//   • Питання   — 0 знаків;
//   • Дошка     — «Тут поки порожньо», тобто ОГОЛОШЕНЬ У ГРОМАДІ НЕМАЄ. Неправда.
// А на повільному звʼязку (база думає 12 с) усі три лишались порожніми ЩОНАЙМЕНШЕ
// шість секунд — без скелета, без «вантажу», без нічого.
//
// 🔑 ПРИЧИНА ОДНА НА ВСІ ТРИ, і вона не в тому, що стану збою не написали.
// На Дошці він якраз написаний (`bd-offline`, 05.08) і навіть спрацьовує — інколи.
// Причина в тому, що **відмова мережі приходить ВИНЯТКОМ, а не значенням**:
// `fetchPublishedPosts()` повертає `null` лише коли Supabase віддав `{ error }`.
// Обрив звʼязку — це `reject` промісу, тобто `Promise.all` кидає, `loadData()`
// кидає, і виклик нагорі його ковтає (`.catch(() => {})` у `openDiscussions`)
// або не ловить узагалі. Малювання просто НЕ ВІДБУВАЄТЬСЯ — звідси порожньо.
//
// 🛑 ЧОМУ ЦЬОГО НЕ СПІЙМАЛИ 155 СТЕНДІВ. Жоден із них не питав «а що на екрані,
// коли база не відповіла»: усі стенди підміняють Supabase ЗАГЛУШКОЮ, яка завжди
// відповідає. Тобто сцена простіша за життя — та сама вада приладу, що вже
// описана в пульсі. Сторож на цей випадок заводиться разом із цим модулем.
//
// 📐 ПРАВИЛО, ЯКЕ ЦЕЙ МОДУЛЬ ТРИМАЄ (воно вже було в проєкті, але лише в одному
// місці — у листі коментарів `feed.js`): **порожньо і «не змогли» плутати НЕ
// МОЖНА**. «Порожньо» — це відповідь про громаду. «Не змогли» — про звʼязок.
// Людина має бачити різні екрани, бо дії в них різні: чекати чи повторити.
//
// ⚠️ ЧОМУ ОДИН МОДУЛЬ, А НЕ ТРИ КОПІЇ. Дошка вже має власний `bd-offline` із
// власним текстом. Копіювати його в Стрічку й Питання означало б завести три
// формулювання одного стану — і наступна правка змінила б одне з трьох. Тут одне
// місце правди; Дошка лишається зі своїм оформленням (воно прицільно зроблене
// під її корок), але текст і поведінка кнопки тепер беруться звідси.
// ═════════════════════════════════════════════════════════════════════════════

import { featureOn } from './features.js';        // прапорці оновлень (19.09)
import { hasShape, shapeHtml } from './skeletons.js';   // форми під кожен екран (19.09)

// 🔴 19.09 — ПЕРША ФІЧА, ЯКА ЇДЕ ЧЕРЕЗ СИСТЕМУ ОНОВЛЕНЬ.
// 🗣️ Вова: «стрічка зараз завантажується як список, а може так як елементи на
// стрічці… І так з кожною вкладкою — взяти макет сторінки і створити сторінку
// завантаження».
// 🛑 Прапорець `skeleton_shapes` керує ПОКАЗОМ: поки він `off`, малюється старий
// загальний кістяк, і громада не бачить нічого нового. Увімкнути «лише колу» →
// Вова тапає й каже «годиться» → «усім». Відкат — тим самим тапом, без деплою.
const ФОРМИ_УВІМКНЕНО = () => featureOn('skeleton_shapes');

// 🔑 Скелет повторює ФОРМУ того, що приїде, а не абстрактні прямокутники:
// інакше в момент появи даних розкладка сіпнеться — саме те, від чого скелет і
// має рятувати.
// 🔴 І ДО 19.09 ЦЕЙ КОМЕНТАР БУВ НАПІВПРАВДОЮ. Намір правильний, виконання — ні:
// форма була ОДНА на всі екрани («фото 64px ліворуч + три смужки»), хоч на
// Стрічку приїжджає карусель спільнот і картка з фото 4:5 на всю ширину. Саме
// це зняв Вова знімками. Форми під кожен екран живуть у `skeletons.js`.
// ⚠️ Класи `.hm-sk*` глобальні (style/home.css) і вже мають анімацію
// мерехтіння — другої такої не заводимо.
//
// `kind` — який екран малюємо ('feed' | 'board' | 'questions' | 'buses' |
// 'community'). Не переданий або невідомий → старий загальний кістяк.
export function loadingHtml(rows = 3, kind = '') {
  if (kind && ФОРМИ_УВІМКНЕНО() && hasShape(kind)) {
    return `<div class="scr-loading" role="status">
      <p class="scr-loading-tx">Завантажую…</p>
      ${shapeHtml(kind, rows)}
    </div>`;
  }
  return загальнийКістяк(rows);
}

function загальнийКістяк(rows = 3) {
  const row = `
    <div class="hm-card hm-sk-row" aria-hidden="true">
      <div class="hm-sk hm-sk-ph"></div>
      <div class="hm-sk-lines">
        <div class="hm-sk hm-sk-l1"></div>
        <div class="hm-sk hm-sk-l2"></div>
        <div class="hm-sk hm-sk-l3"></div>
      </div>
    </div>`;
  // 🔴 НАПИС, А НЕ САМЕ МЕРЕХТІННЯ. Скелет зрозумілий тому, хто бачив його в
  // інших застосунках; жителю, який уперше відкрив телефон-застосунок, сірі
  // смужки не кажуть нічого. Слово «Завантажую…» коштує один рядок і знімає
  // питання «воно зламалось чи думає».
  return `<div class="scr-loading" role="status">
      <p class="scr-loading-tx">Завантажую…</p>
      ${row.repeat(rows)}
    </div>`;
}

// Стан «не змогли». Кнопка тут не прикраса: єдина причина цього екрана —
// тимчасова недосяжність бази, тобто повтор справді має шанс спрацювати.
export function offlineHtml(title = 'Не вдалось завантажити') {
  return `
    <div class="scr-offline" role="alert">
      <p class="scr-offline-ttl">${title}</p>
      <p class="scr-offline-tx">Не вдалось звʼязатися з сервером. Перевір інтернет і спробуй ще раз.</p>
      <button class="scr-offline-btn" type="button">Спробувати ще</button>
    </div>`;
}

export function paintLoading(el, rows = 3, force = false, kind = '') {
  if (!el) return;
  // ⚠️ Не затираємо те, що вже намальоване даними: скелет доречний лише на
  // ПОРОЖНЬОМУ екрані. Інакше повернення на вкладку (`onReturn`) щоразу
  // змітало б готовий список і показувало мерехтіння на рівному місці.
  // 🔑 `force` — для випадку, коли на екрані стоїть НЕПРАВДА: Дошка при першому
  // відкритті вже має намальоване «Тут поки порожньо», і саме його треба
  // замінити скелетом, поки правда їде з мережі.
  if (!force && (el.querySelector('.scr-loading') || el.children.length)) return;
  el.innerHTML = loadingHtml(rows, kind);

  // 🔴 19.09 — ПЕРЕМАЛЮВАТИ, КОЛИ ПРИЇДУТЬ ПРАПОРЦІ. Спіймано стендом
  // `skeleton-shapes`, і це не дрібниця, а суть: кістяк малюється ДО мережі (у
  // цьому весь його сенс), а `my_features()` приходить З мережі. На першому
  // запуску на пристрої кеш порожній, тож у мить малювання ми ще не знаємо про
  // прапорець — і фіча не вмикалась саме на тих екранах, заради яких робилась.
  // 🔑 Заміна форми ВСЕРЕДИНІ кістяка не блимає в очі: він і так мерехтить, а
  // правильна розкладка потрібна до появи даних, не після.
  // ⚠️ `once` обовʼязковий: `paintLoading` кличеться на кожному відкритті
  // вкладки, і слухач без нього накопичувався б до кінця сеансу.
  if (kind && !ФОРМИ_УВІМКНЕНО()) {
    window.addEventListener('cstl-features-ready', () => {
      // Лише якщо на екрані ДОСІ кістяк: дані могли приїхати раніше за прапорці,
      // і тоді перемальовувати означало б стерти готовий список.
      if (el.querySelector('.scr-loading')) el.innerHTML = loadingHtml(rows, kind);
    }, { once: true });
  }
}

// ⚠️ Параметри читаються з обʼєкта, а НЕ розбираються в сигнатурі: сторож
// `scripts/check-imports.js` бачить деструктуризований `onRetry` як «виклик
// неоголошеного імені» і падає. Дрібниця, але вона тримає збірку зеленою.
export function paintOffline(el, opts = {}) {
  if (!el) return;
  const retry = opts.onRetry;
  const kind = opts.kind || '';
  el.innerHTML = offlineHtml(opts.title);
  const btn = el.querySelector('.scr-offline-btn');
  if (btn && typeof retry === 'function') {
    btn.addEventListener('click', () => {
      // Повтор починається з того самого скелета: без нього тап по кнопці
      // виглядав би так, ніби нічого не сталось, і людина тапала б ще раз.
      el.innerHTML = loadingHtml(2, kind);
      retry();
    });
  }
}

// Чи стоїть на екрані наш стан (скелет або збій) — щоб виклик нагорі знав,
// що екран НЕ порожній і його вміст ще не є відповіддю про громаду.
export function hasScreenState(el) {
  return !!el && !!el.querySelector('.scr-loading, .scr-offline');
}
