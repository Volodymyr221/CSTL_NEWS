// «Заставка вже зійшла?» — одне місце правди для дій, які людина мусить ПОБАЧИТИ.
//
// 🔴 НАВІЩО (скарга Вови 15.08, два знімки). Тап по сповіщенню відкривав розмову
// правильно, але під нею стояла ЗАСТАВКА, а не застосунок: `#splash` живе
// 3.5с + 0.4с згасання (кінець `init()` в `app.js`), а deep-link спрацьовує за
// ~0.5с. Тому перший свайп «назад» показував не Дошку, а «сторінку завантаження».
// Заміряно `tests/tools/notif-backstack-probe.mjs`: на 700мс — `заставка: ВИДНО`.
//
// Друга половина тієї самої вади — у «Стрічці»: підсвітка коментаря зі сповіщення
// тримається 2.4с і встигала ЗГАСНУТИ під заставкою. Вова сказав прямо: «треба
// вважати те, що три секунди сторінка завантаження ще йде… щоб він почав
// виділятися трішки пізніше, вже після завантаження».
//
// 🔑 ОДНЕ ПРАВИЛО НА ОБИДВА ВИПАДКИ: показова частина deep-link'а чекає заставку.
// Не «прибрати заставку раніше» — вона тримає видимість недобудованого екрана;
// саме дію відсуваємо на мить, коли її видно.
//
// ⚠️ Модуль НІЧОГО не імпортує — його чекають `feed.js` і `board-chat.js`, а
// ставить прапорець `app.js`. Через спільний файл, а не через `app.js`, бо той
// імпортує обидві зони: зустрічний імпорт замкнув би коло.

let зійшла = false;
let охочі = [];

// Стеля очікування. Заставку прибирає `init()`, і якщо туди не дійшли (заслінка
// розробки, помилка вище по коду) — deep-link не має зависнути назавжди. Краще
// показати дію під заставкою, ніж не показати взагалі.
const СТЕЛЯ_МС = 6000;

export function markSplashGone() {
  if (зійшла) return;
  зійшла = true;
  const черга = охочі; охочі = [];
  черга.forEach(fn => { try { fn(); } catch (_) {} });
}

// Обіцянка, яка виконується, щойно заставки на екрані немає.
// Заставки не було взагалі (гарячий шлях: застосунок уже відкритий) → одразу.
export function whenSplashGone() {
  if (зійшла) return Promise.resolve();
  if (!document.getElementById('splash')) { зійшла = true; return Promise.resolve(); }
  return new Promise(resolve => {
    охочі.push(resolve);
    setTimeout(resolve, СТЕЛЯ_МС);   // запобіжник, не основний шлях
  });
}
