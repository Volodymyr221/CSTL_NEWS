// запит «будинок Жорнище» — зараз НЕ знаходиться.
//
// 🔴 ЧОМУ НЕ ЗНАХОДИТЬСЯ (заміряно в коді до цього модуля). Пошук був одним рядком:
//     hay.includes(q)   // board.js:1415
// тобто точний ПІДРЯДОК по злитому тексту. Провал давали ДВІ незалежні причини:
//   1. суміжність — слова мусили стояти поряд і в тому ж порядку;
//   2. відмінки   — «жорнищЕ» не є підрядком «жорнищАХ».
// Друга причина означала, що навіть ОДНЕ слово в іншому відмінку не знаходилось.
//
// 📐 ЧОМУ ЦЕ КЛІЄНТ, А НЕ БАЗА (перевірено на живій базі 30.08, не з памʼяті):
//   • `select cfgname from pg_ts_config` → 29 конфігурацій, **ukrainian НЕМАЄ**;
//   • to_tsvector('simple','Продам будинок в Жорнищах')
//       @@ plainto_tsquery('simple','будинок Жорнище')  → FALSE
//       @@ plainto_tsquery('simple','Жорнищах будинок') → TRUE
//     тобто Postgres FTS українською дає ПОРЯДОК СЛІВ, але НЕ дає відмінки;
//   • similarity('хата','будинок') = 0.00, ('пральну машину','побутової техніки') = 0.03
//     тобто синоніми не бере ЖОДЕН лексичний метод — ні FTS, ні триграми.
// ➡️ Висновок: морфологію робимо тут, на клієнті (миттєво, офлайн, 0 грн), а
//    «хата ↔ будинок» — окремим словником синонімів, не морфологією.
//
// 🛑 ЧОМУ НЕ ВЗЯЛИ ГОТОВУ БІБЛІОТЕКУ (перевірено 30.08):
//   • `ukrstemmer` — ліцензія **GPLv2**, версія 0.1.0. GPL — copyleft: включення в
//     `bundle.js` тягне вимогу ліцензувати похідний твір під GPL. Проєкт і бренд
//     належать Вові — звʼязувати їх таким зобовʼязанням заради обрізання закінчень
//     це погана угода;
//   • `ukrstemmer-node` — у npm **не існує (404)**;
//   • у проді проєкту НЕМАЄ жодної runtime-залежності (лише вендорений supabase-js,
//     і той принесли до себе після того, як CDN клав застосунок).

// ── МІНІМАЛЬНА ОСНОВА ────────────────────────────────────────────────────────
// 🔑 ГОЛОВНИЙ ЗАПОБІЖНИК ВІД СКЛЕЮВАННЯ РІЗНИХ СЛІВ, і він тут не «про всяк випадок».
//
// Ціна помилки АСИМЕТРИЧНА — той самий принцип, яким 30.08 закрили B-14:
//     не дообрізали → слово не знайшлось  = як було, НЕ ГІРШЕ
//     склеїли       → знайшлось ЧУЖЕ      = ГІРШЕ, ніж було
// Тому правила навмисно консервативні: краще пропустити збіг, ніж підмішати чуже.
//
// 📐 Чому саме 4, а не 3 — виведено з пар, а не вибрано на око:
//     мило / милий  → обидва дали б основу «мил» (3) і СКЛЕЇЛИСЬ БИ;
//     при межі 4 обидва лишаються цілими — «мило» і «милий» різні. ✅
// ⚠️ Ціна цього рішення названа чесно: короткі пари (вода/води → «вод», 3) НЕ
// зводяться. Це «не гірше, ніж зараз», тоді як склеювання було б гірше.
const MIN_STEM = 4;

// Закінчення — від найдовших до найкоротших. Порядок ОБОВʼЯЗКОВИЙ: інакше коротке
// правило зʼїсть хвіст довшого («будинкАМИ» стало б «будинкам», а не «будинк»).
const ENDINGS = [
  // прикметники й дієприкметники
  'ього', 'ими', 'ому', 'ого', 'ему', 'ій', 'их', 'ий', 'ої', 'ою', 'ею', 'ім',
  // іменники множини й непрямі відмінки
  'ами', 'ями', 'ові', 'еві', 'ах', 'ях', 'ів', 'ям', 'ом', 'ем', 'ей', 'им', 'ї',
  // однина
  'а', 'я', 'у', 'ю', 'и', 'і', 'е', 'о',
];

/**
 * Зводить українське слово до основи.
 *
 * ⚠️ Це НЕ повна морфологія, а свідомо консервативна евристика: вона радше
 * недообріже, ніж склеїть. Стереже `tests/search-stem.mjs`, і в ньому ДВІ
 * половини — «мусять зійтись» і «не сміють склеїтись». Без другої половини
 * сторож світився б зеленим над зіпсованим пошуком.
 */
export function stem(word) {
  let w = String(word || '').toLowerCase().trim();
  if (w.length <= MIN_STEM) return w;

  // Мʼякий знак наприкінці не несе змісту для пошуку, але робить «нерухомість»
  // і «нерухомості» різними словами. Знімаємо ДО обрізання закінчень.
  if (w.endsWith('ь')) {
    const bare = w.slice(0, -1);
    if (bare.length >= MIN_STEM) w = bare;
  }

  for (const end of ENDINGS) {
    if (w.length - end.length < MIN_STEM) continue;
    if (w.endsWith(end)) { w = w.slice(0, -end.length); break; }
  }

  // 🔴 БІГЛИЙ ГОЛОСНИЙ — без цього правила НЕ ПРАЦЮЄ найчастіше слово нашої Дошки.
  // 📐 Заміряно на живих оголошеннях: «будинок» ×9, «будинку» ×6, «будинки» ×3.
  //    «будинку» → «будинк», «будинки» → «будинк», а «будинок» закінчення не має
  //    взагалі (стоїть на «к») і лишився б «будинок» — тобто найпопулярніша пара
  //    Дошки НЕ зійшлася б, і весь модуль не вирішив би те, заради чого писався.
  // Те саме: хлопець/хлопця, вітер/вітру.
  //
  // 🛑 ЛІТЕРИ «в» І «л» ЗВІДСИ НАВМИСНО ПРИБРАНІ — і це не дрібниця.
  // Перша редакція мала `[ое]([кцнлрв])$` і зʼїдала голосну З КОРЕНЯ:
  // «готовий» → «готов» → **«готв»**. Стенд цього НЕ впіймав, бо всі чотири
  // форми («готовий/готових/готові/готова») зіпсувались ОДНАКОВО і чесно
  // зійшлися в одну основу — перевірка «форми збігаються» була зелена над
  // спотвореним коренем. Тому нижче стоїть окремий блок Г: очікувані основи
  // виписані ЯВНО. ➡️ Урок: збіг форм між собою не доводить, що основа осмислена.
  if (w.length > MIN_STEM && /[ое]([кцнр])$/.test(w)) {
    const bare = w.replace(/[ое]([кцнр])$/, '$1');
    if (bare.length >= MIN_STEM) w = bare;
  }

  // Чергування і/о в суфіксі «-ість» → «-ост»: нерухомІСТЬ / нерухомОСТі,
  // вартість/вартості, наявність/наявності — усі чотири є в живих оголошеннях.
  // ⚠️ Правило вузьке саме через «і»: слова на «-ист» («турист») його не чіпає.
  if (w.length > MIN_STEM && w.endsWith('іст')) w = w.slice(0, -3) + 'ост';

  return w;
}
