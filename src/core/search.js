//     тобто синоніми не бере ЖОДЕН лексичний метод — ні FTS, ні триграми.
// ➡️ Висновок: морфологію робимо тут, на клієнті (миттєво, офлайн, 0 грн), а
//    «хата ↔ будинок» — окремим словником синонімів, не морфологією.
//
// 🛑 ЧОМУ НЕ ВЗЯЛИ ГОТОВУ БІБЛІОТЕКУ (перевірено 30.08):
//   • `ukrstemmer` — ліцензія **GPLv2**, версія 0.1.0. GPL — copyleft: включення в
