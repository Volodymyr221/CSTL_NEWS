//     належать Вові — звʼязувати їх таким зобовʼязанням заради обрізання закінчень
//     це погана угода;
//   • `ukrstemmer-node` — у npm **не існує (404)**;
//   • у проді проєкту НЕМАЄ жодної runtime-залежності (лише вендорений supabase-js,
//     і той принесли до себе після того, як CDN клав застосунок).

// ── МІНІМАЛЬНА ОСНОВА ────────────────────────────────────────────────────────
// 🔑 ГОЛОВНИЙ ЗАПОБІЖНИК ВІД СКЛЕЮВАННЯ РІЗНИХ СЛІВ, і він тут не «про всяк випадок».
//
// Ціна помилки АСИМЕТРИЧНА — той самий принцип, яким 30.08 закрили B-14:
//     не дообрізали → слово не знайшлось  = як було, НЕ ГІРШЕ
//     склеїли       → знайшлось ЧУЖЕ      = ГІРШЕ, ніж було
// Тому правила навмисно консервативні: краще пропустити збіг, ніж підмішати чуже.
//
// 📐 Чому саме 4, а не 3 — виведено з пар, а не вибрано на око:
//     мило / милий  → обидва дали б основу «мил» (3) і СКЛЕЇЛИСЬ БИ;
//     при межі 4 обидва лишаються цілими — «мило» і «милий» різні. ✅
// ⚠️ Ціна цього рішення названа чесно: короткі пари (вода/води → «вод», 3) НЕ
// зводяться. Це «не гірше, ніж зараз», тоді як склеювання було б гірше.
const MIN_STEM = 4;

// Закінчення — від найдовших до найкоротших. Порядок ОБОВʼЯЗКОВИЙ: інакше коротке
// правило зʼїсть хвіст довшого («будинкАМИ» стало б «будинкам», а не «будинк»).
const ENDINGS = [
  // прикметники й дієприкметники
  'ього', 'ими', 'ому', 'ого', 'ему', 'ій', 'их', 'ий', 'ої', 'ою', 'ею', 'ім',
  // іменники множини й непрямі відмінки
  'ами', 'ями', 'ові', 'еві', 'ах', 'ях', 'ів', 'ям', 'ом', 'ем', 'ей', 'им', 'ї',
  // однина
  'а', 'я', 'у', 'ю', 'и', 'і', 'е', 'о',
];

/**
 * Зводить українське слово до основи.
 *
 * ⚠️ Це НЕ повна морфологія, а свідомо консервативна евристика: вона радше
 * недообріже, ніж склеїть. Стереже `tests/search-stem.mjs`, і в ньому ДВІ
 * половини — «мусять зійтись» і «не сміють склеїтись». Без другої половини
 * сторож світився б зеленим над зіпсованим пошуком.
 */
// 🔴 ОКРЕМИЙ, НИЖЧИЙ ПОРІГ ДЛЯ ОДНОБУКВЕНИХ ЗАКІНЧЕНЬ — заведено після падіння стенда.
// Перша редакція мала один поріг 4 на всі правила, і через нього НЕ стемились
// чотирилітерні слова взагалі: «хату» лишалось «хату», «хата» — «хата».
// 📐 Наслідок був не там, де здається: ламались не відмінки, а СИНОНІМИ, бо майже
// всі вони короткі — хата, дім, авто, земля. Запит «хочу купити хату» не знаходив
// «Продам приватний будинок», хоч словник синонімів стояв і був правильний.
// ⚠️ Чому 3 безпечне саме для ОДНІЄЇ літери: пари, що склеюються (мило/милий,
// коса/косий), відрізняються ДВОБУКВЕНИМ закінченням «-ий», а на нього поріг
// лишається 4 — тобто «милий» і «косий» не обрізаються й далі. Доведено блоком Б.
const MIN_STEM_SHORT = 3;

export function stem(word) {
  let w = String(word || '').toLowerCase().trim();
  if (w.length < MIN_STEM) return w;

  // Мʼякий знак наприкінці не несе змісту для пошуку, але робить «нерухомість»
  // і «нерухомості» різними словами. Знімаємо ДО обрізання закінчень.
  if (w.endsWith('ь')) {
    const bare = w.slice(0, -1);
    if (bare.length >= MIN_STEM) w = bare;
  }

  for (const end of ENDINGS) {
    const мінОснова = end.length === 1 ? MIN_STEM_SHORT : MIN_STEM;
    if (w.length - end.length < мінОснова) continue;
    if (w.endsWith(end)) { w = w.slice(0, -end.length); break; }
  }

  // 🔴 БІГЛИЙ ГОЛОСНИЙ — без цього правила НЕ ПРАЦЮЄ найчастіше слово нашої Дошки.
  // 📐 Заміряно на живих оголошеннях: «будинок» ×9, «будинку» ×6, «будинки» ×3.
  //    «будинку» → «будинк», «будинки» → «будинк», а «будинок» закінчення не має
  //    взагалі (стоїть на «к») і лишився б «будинок» — тобто найпопулярніша пара
  //    Дошки НЕ зійшлася б, і весь модуль не вирішив би те, заради чого писався.
  // Те саме: хлопець/хлопця, вітер/вітру.
  //
  // 🛑 ЛІТЕРИ «в» І «л» ЗВІДСИ НАВМИСНО ПРИБРАНІ — і це не дрібниця.
  // Перша редакція мала `[ое]([кцнлрв])$` і зʼїдала голосну З КОРЕНЯ:
  // «готовий» → «готов» → **«готв»**. Стенд цього НЕ впіймав, бо всі чотири
  // форми («готовий/готових/готові/готова») зіпсувались ОДНАКОВО і чесно
  // зійшлися в одну основу — перевірка «форми збігаються» була зелена над
  // спотвореним коренем. Тому нижче стоїть окремий блок Г: очікувані основи
  // виписані ЯВНО. ➡️ Урок: збіг форм між собою не доводить, що основа осмислена.
  if (w.length > MIN_STEM && /[ое]([кцнр])$/.test(w)) {
    const bare = w.replace(/[ое]([кцнр])$/, '$1');
    if (bare.length >= MIN_STEM) w = bare;
  }

  // Чергування і/о в суфіксі «-ість» → «-ост»: нерухомІСТЬ / нерухомОСТі,
  // вартість/вартості, наявність/наявності — усі чотири є в живих оголошеннях.
  // ⚠️ Правило вузьке саме через «і»: слова на «-ист» («турист») його не чіпає.
  if (w.length > MIN_STEM && w.endsWith('іст')) w = w.slice(0, -3) + 'ост';

  return w;
}

// ── НОРМАЛІЗАЦІЯ ─────────────────────────────────────────────────────────────
// ⚠️ Апостроф знімаємо ДО розбору — інакше «обʼєкт» розпадається на «об» і «єкт».
// Це вже коштувало проєкту бага B-29 в антиспамі: там склейка навпаки СТВОРЮВАЛА
// матюки зі звичайних слів. Накреслень апострофа в живих текстах кілька, тому
// перелічені всі чотири, а не лише той, що на клавіатурі.
const APOSTROPHES = /['’‘ʼ`]/g;

// 🔴 ЗМІШАНА РОЗКЛАДКА — знайдено аудитом 30.08, а не припущено.
// Заміряно: запит «хромякiв» (з ЛАТИНСЬКОЮ «i») НЕ знаходив село «Хром'яків»,
// хоч на екрані два рядки виглядають однаково. На телефоні це набирається легко —
// достатньо не перемкнути розкладку на одній літері.
//
// 🛑 ЧОМУ ЗАМІНА ЛИШЕ В ЗМІШАНИХ СЛОВАХ, А НЕ ПІДРЯД.
// Мапа гомогліфів агресивна (p→р, h→н, o→о…), і суцільна заміна перетворила б
// «iphone» на кирилицю — тобто зламала б пошук брендів. А критерій словника прямо
// вимагає: бренди й моделі мусять шукатись ТОЧНО. Тому правило вузьке: чіпаємо
// слово, лише якщо кирилиця в ньому ВЖЕ є. «хромякiв» — так, «iphone» — ні.
// 🔑 Сама мапа береться з `core/utils.js`, а не копіюється: це той самий фізичний
// факт про схожі літери, і другий список розійшовся б (як уже було з антиспамом).
function fixLayout(word) {
  if (!hasCyrillic(word)) return word;
  return word.replace(/[a-z]/g, ch => FILTER_HOMOGLYPHS[ch] || ch);
}

export function normalize(text) {
  return String(text || '')
    .toLowerCase()
    .replace(APOSTROPHES, '')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim()
    .split(' ')
    .map(fixLayout)
    .join(' ');
}

// ── СТОП-СЛОВА І НАМІР ───────────────────────────────────────────────────────
// 🔴 НАМІР ЧИТАЄТЬСЯ З КАТЕГОРІЙ ДОШКИ, А НЕ З ВЛАСНОГО СПИСКУ (крок 4 аудиту 30.08).
//
// Перша редакція цього файлу мала свій `INTENT = { sell: […], buy: […] }` — тобто
// ДРУГИЙ список тих самих понять, які вже описані в `core/board-categories.js`
// (`куплю · продам · послуга · шукаю · віддам · знайдено · загубилось`).
// Це рівно та хвороба, від якої проєкт постраждав двічі: два списки антиспаму
// розійшлись, і дві реалізації каруселі жили паралельно.
//
// 🔑 Тепер намір називається ТАК САМО, як категорія Дошки (`'продам'`, а не `'sell'`) —
// одна мова на весь застосунок. Ключі `INTENT_FORMS` мусять бути id категорій, і це
// не побажання: `tests/search-synonyms.mjs` звіряє їх із `BOARD_CATEGORIES` і падає
// при розходженні. Перейменують категорію — сторож скаже одразу.
//
// ⚠️ ЧОМУ ФОРМИ ВСЕ Ж ПЕРЕЛІЧЕНІ, А НЕ ВИВЕДЕНІ `stem()`. Заміряно:
//     продам → продам · продаю → прода · продати → продат · продається → продаєтьс
// Стемер зводить іменники й прикметники, а дієслівна морфологія української значно
// складніша — виводити її правилами означало б ризикувати склеюванням заради
// семи слів. Список тут чесніший за евристику.
//
// 🛑 Рішення Вови 30.08 (варіант «Б»): намір поки НІ НА ЩО не впливає у видачі —
// лише читається. Дзеркалення («куплю» підіймає оголошення «продам») відкладено
// свідомо: воно змінює видачу, а перевірити його по-справжньому можна лише на
// живих запитах після запуску.
const INTENT_FORMS = {
  'продам':  ['продаю', 'продати', 'продається', 'продаж'],
  'куплю':   ['купую', 'купити', 'купівля'],
  'шукаю':   ['шукати', 'розшукую', 'потрібен', 'потрібна', 'потрібно'],
  'віддам':  ['віддаю', 'віддати', 'задарма', 'безкоштовно'],
  'послуга': ['послуги', 'надаю'],
};

// Усі слова наміру одним набором — щоб `tokenize` не тягнув їх у зміст запиту.
const INTENT_WORDS = new Set(
  Object.entries(INTENT_FORMS).flatMap(([id, forms]) => [id, ...forms])
);

// Слова, які справді нічого не додають до змісту запиту.
const STOP_WORDS = new Set([
  'хочу', 'треба', 'дуже', 'будь', 'ласка', 'терміново', 'недорого',
  // Питальні й службові — саме ними починається природний запит людини
  // («хто може покосити траву?»). Без них пошук вимагав би знайти слово «хто»
  // в оголошенні, і жоден природний запит не проходив би взагалі.
  'хто', 'що', 'де', 'коли', 'чому', 'чи', 'може', 'мені', 'нам', 'вам',
  'який', 'яка', 'яке', 'які', 'щось', 'когось', 'десь', 'можна', 'можливо',
  'для', 'про', 'над', 'під', 'при', 'без', 'від', 'або', 'та', 'і', 'й',
  'в', 'у', 'на', 'з', 'із', 'зі', 'до', 'по', 'за', 'як', 'це',
]);

/** Намір запиту — id КАТЕГОРІЇ Дошки (`'куплю'`, `'продам'`…) або `null`. */
export function detectIntent(text) {
  const words = normalize(text).split(' ');
  for (const [id, forms] of Object.entries(INTENT_FORMS)) {
    if (words.some(w => w === id || forms.includes(w))) return id;
  }
  return null;
}

// ── РОЗШИРЕННЯ ЗА СЛОВНИКОМ ──────────────────────────────────────────────────
// Слова живуть у `core/search-vocab.js` — там же критерій, за яким вони туди
// потрапляють, і перелік того, що свідомо НЕ внесено. Тут лише механіка.
//
// 🔑 ТРИ ТИПИ ЗВʼЯЗКУ, і кожен заведено через доведений випадок, а не для стрункості:
//   1. EQUIVALENT — рівні, двобічно (хата = будинок);
//   2. HIERARCHY  — рід ↔ види, але ВИД З ВИДОМ ніколи. Пласка група давала
//      реальну ваду: запит «холодильник» знаходив «Ремонт пральних машин»;
//   3. ONE_WAY    — омоніми, лише в один бік. «машина» → «автомобіль» так,
//      назад ні: `stem('машину')` і `stem('пральних машин')` дають те саме
//      «машин», тож зворотний звʼязок тягнув би пральні машини в запит «авто».
const SYN_INDEX = (() => {
  const map = new Map();
  const link = (from, to) => {
    if (!map.has(from)) map.set(from, new Set([from]));
    map.get(from).add(to);
  };

  for (const group of EQUIVALENT) {
    const stems = group.map(stem);
    for (const a of stems) for (const b of stems) link(a, b);
  }

  for (const [head, kinds] of Object.entries(HIERARCHY)) {
    // Рід може бути словосполученням («побутова техніка») — беремо всі його слова.
    const headStems = normalize(head).split(' ').map(stem);
    for (const kind of kinds) {
      const k = stem(kind);
      for (const h of headStems) { link(k, h); link(h, k); }
    }
    // 🛑 Виду з видом НЕ звʼязуємо — саме тут була вада пласкої групи.
  }

  for (const [from, targets] of Object.entries(ONE_WAY)) {
    for (const t of targets) link(stem(from), stem(t));   // і НІКОЛИ навпаки
  }

  return map;
})();

// ── ТОКЕНИ ЗАПИТУ ────────────────────────────────────────────────────────────
export function tokenize(text, { keepStop = false } = {}) {
  const words = normalize(text).split(' ').filter(Boolean);
  return words
    .filter(w => w.length > 1)
    .filter(w => keepStop || (!STOP_WORDS.has(w) && !INTENT_WORDS.has(w)))
    .map(stem);
}

// Розширення запиту синонімами. Людина цього не бачить — воно лише додає шляхи,
// якими той самий зміст може бути записаний в оголошенні.
export function expand(stems) {
  return stems.map(s => [...(SYN_INDEX.get(s) || new Set([s]))]);
}

// ── ДРУКАРСЬКІ ПОМИЛКИ ───────────────────────────────────────────────────────
// Відстань Левенштейна ≤1 і лише для слів від 5 літер: на коротких одна літера —
// це вже інше слово («ліс»/«лис»), і fuzzy почав би підмішувати чуже.
function near(a, b) {
  if (a === b) return true;
  if (Math.min(a.length, b.length) < 5) return false;
  if (Math.abs(a.length - b.length) > 1) return false;
  let i = 0, j = 0, diff = 0;
  while (i < a.length && j < b.length) {
    if (a[i] === b[j]) { i++; j++; continue; }
    if (++diff > 1) return false;
    if (a.length > b.length) i++;
    else if (a.length < b.length) j++;
    else { i++; j++; }
  }
  return diff + (a.length - i) + (b.length - j) <= 1;
}

// ── РАНЖУВАННЯ ───────────────────────────────────────────────────────────────
// 📐 Ієрархія важливіша за конкретні числа (порада ChatGPT, прийнята).
// Локація для нас — не фільтр, а частина НАМІРУ: у громаді 17 сіл, і назва села
// в запиті це майже завжди головне, що людина хоче звузити.
const W = { title: 50, location: 40, tags: 25, text: 15, syn: 0.6, fuzzy: 0.4, prefix: 0.5 };

// ── ПОШУК ПІД ЧАС НАБОРУ (`opts.prefix`, 06.09) ──────────────────────────────
// 📐 ЗАМІРЯНО перед рішенням, а не припущено: двигун не знає префіксів зовсім.
//     «велосипед» → знайшлось · «велосипеда» → знайшлось (морфологія)
//     «вело» → НІЧОГО · «вел» → НІЧОГО · «окса» → НІЧОГО (при живій «Оксана»)
// Для Дошки це нормально: там людина формулює запит і тисне «знайти».
// 🔴 Але в «Повідомленнях» до 06.09 стояв `hay.includes(q)` — точний ПІДРЯДОК,
// який префікси якраз ловив. Тобто переведення на цей двигун БЕЗ префікса було б
// не покращенням, а регресом: набрав «вело» — і розмова про велосипед зникла.
//
// 🔑 ПРЕФІКС ЛИШЕ ДЛЯ ОСТАННЬОГО СЛОВА ЗАПИТУ, і це не спрощення. Останнє слово —
// єдине, яке людина в цю мить ДОНАБИРАЄ; попередні вона вже дописала, і послаблення
// на них лише підмішувало б чуже. Той самий принцип, що в звичайних пошукових полях.
// ⚠️ Стеля знизу — 3 літери: на двох («ве») у видачу лізе пів застосунку, а користі
// нуль, бо людина все одно продовжує набирати.
// 🛑 ВМИКАЄТЬСЯ ЯВНО, за замовчуванням ВИМКНЕНО — щоб майбутній споживач діставав
// строгу поведінку, поки свідомо не попросить іншу.
// ⚠️ ДЕ ВВІМКНЕНО НАСПРАВДІ (щоб цей рядок не розійшовся з кодом): пошуковий рядок
// Дошки/Питань (`board.js`) і пошук розмов (`board-chat.js`) — усі три поверхні, де
// видача перемальовується НА КОЖНЕ НАТИСКАННЯ КЛАВІШІ.
// 🔑 Дошка потрапила сюди не «заразом»: у неї і в Питань ОДНЕ поле вводу, яке лише
// міняє вкладку. Префікс на одній вкладці й не на іншій — це різна поведінка того
// самого поля, і людина читала б її як поломку. Уніфіковано свідомо.
const MIN_PREFIX = 3;

/**
 * Шукає по масиву записів. Повертає відсортовані `{ item, score, matched }`.
 * `matched` — слова, ЯКІ збіглись: з них будується підпис «✦ знайдено за…».
 *
 * 🛑 Логіка «І», а не «АБО»: кожне значуще слово запиту мусить десь знайтись.
 * Інакше «будинок жорнище» видало б усі будинки громади, і потрібне втопилось би.
 */
export function search(items, query, opts = {}) {
  const префіксОк = opts.prefix === true;
  const stems = tokenize(query);
  if (!stems.length) return items.map(item => ({ item, score: 0, matched: [] }));

  const groups = expand(stems);
  const fields = opts.fields || (it => ({
    title: it.title, location: it.location, text: it.text,
    tags: Array.isArray(it.tags) ? it.tags.join(' ') : '',
  }));

  const out = [];
  for (const item of items) {
    const src = fields(item);
    const bag = {};
    for (const [f, val] of Object.entries(src)) bag[f] = tokenize(val, { keepStop: true });

    let score = 0;
    const matched = [];
    const усіЗнайшлись = groups.every((group, gi) => {
      let best = 0, hit = '';
      for (const [f, weight] of Object.entries(W)) {
        if (!bag[f]) continue;
        for (const variant of group) {
          const точно = bag[f].includes(variant);
          const майже = !точно && bag[f].some(w => near(w, variant));
          // Префікс — лише для ОСТАННЬОГО слова запиту і лише коли його попросили
          // (див. блок «ПОШУК ПІД ЧАС НАБОРУ» вище).
          const початок = (!точно && !майже && префіксОк && gi === groups.length - 1
                           && variant.length >= MIN_PREFIX)
            ? bag[f].find(w => w.length > variant.length && w.startsWith(variant))
            : '';
          if (!точно && !майже && !початок) continue;
          // Синонім важить менше за власне слово автора: якщо збіг прямий —
          // це сильніший сигнал, ніж те, що ми самі домислили.
          const свій = variant === stems[gi];
          let v = weight * (свій ? 1 : W.syn) * (точно ? 1 : майже ? W.fuzzy : W.prefix);
          // 🔑 У підпис «знайдено за…» іде СЛОВО, ЯКЕ ЗНАЙШЛОСЬ, а не огризок, який
          // людина встигла набрати: «знайдено за: вело» не пояснює нічого.
          if (v > best) { best = v; hit = початок || variant; }
        }
      }
      if (best > 0) { score += best; matched.push(hit); }
      return best > 0;
    });
    if (!усіЗнайшлись) continue;

    // Свіжість — слабкий доважок, який лише розводить однакові за змістом.
    const ts = item.bumped_at ? Date.parse(item.bumped_at) : (item.ts || 0);
    if (ts) score += Math.max(0, 5 - (Date.now() - ts) / 86400000 / 30);

    out.push({ item, score, matched: [...new Set(matched)] });
  }
  return out.sort((a, b) => b.score - a.score);
}
