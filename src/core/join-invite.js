// Запрошення увійти для гостя, який уже трохи покористувався застосунком.
//
// 🗣️ ЗАМОВЛЕННЯ ВОВИ (29.08): «заходить новий користувач… він сто відсотків має
// через деякий час побачити вспливаючу іконку: авторизуйтеся, чи станьте
// учасником громади».
//
// 🔴 ЗРОБЛЕНО НЕ ЗА ТАЙМЕРОМ, І ЦЕ ЄДИНЕ, В ЧОМУ Я З ВОВОЮ НЕ ЗГОДЕН.
// «Через N секунд» спрацьовує однаково і для того, хто читає новину, і для того,
// хто ще не зрозумів, куди потрапив. Перший читає запрошення як перешкоду
// («мене відірвали»), другий — як рекламу («ще нічого не бачив, а вже щось
// просять»). Обидва закривають його не читаючи, і другого разу вже не буде.
//
// ✅ ТОМУ ЛІЧИМО ДІЇ, А НЕ СЕКУНДИ. Три переходи між розділами означають, що
// людина роздивилась застосунок і він їй цікавий — і саме тоді пропозиція
// звучить як продовження, а не як перепин. Час при цьому теж минає: три переходи
// швидше ніж за півхвилини не робить ніхто.
//
// 🛑 І ПОКАЗУЄМО РІВНО ОДИН РАЗ. Друге таке вікно — це вже набридання, а не
// пропозиція; людина, якій треба, увійде сама через 👤 у шапці.
//
// ⚙️ Три числа, які Вова може міняти без розбору коду:
//    ACTIONS_BEFORE — скільки переходів чекаємо (3);
//    SNOOZE_DAYS    — через скільки днів можна запропонувати ще раз (30);
//    SETTLE_MS      — пауза після останнього переходу, щоб вікно не вискочило
//                     під палець (900 мс).

import { isLoggedIn, onAuthChange } from './auth.js';

const SEEN_KEY       = 'cstl-join-invite-v1';
const ACTIONS_BEFORE = 3;
const SNOOZE_DAYS    = 30;
const SETTLE_MS      = 900;

let actions = 0;
let done    = false;   // за один запуск — не більше одного разу

function shownRecently() {
  try {
    const t = Number(localStorage.getItem(SEEN_KEY) || 0);
    return t && (Date.now() - t) < SNOOZE_DAYS * 24 * 60 * 60 * 1000;
  } catch { return false; }
}
function remember() { try { localStorage.setItem(SEEN_KEY, String(Date.now())); } catch {} }

// 🛑 НЕ ПЕРЕБИВАЄМО ТЕ, ЩО ВЖЕ НА ЕКРАНІ. Три випадки, і кожен коштував би
// довіри більше, ніж дає саме запрошення:
//   • відкрита модалка або кабінет — людина щось робить прямо зараз;
//   • банер «встанови на екран» — два спливаючих поспіль читаються як реклама
//     (на iOS він виходить сам через 2.5 с після запуску);
//   • банер згоди з Правилами — його показують ПЕРШИМ, і він юридичний;
//   • 🔴 покрокова інструкція «Як встановити» (`.pwa-guide`) — людина читає крок
//     1/4 з чужого меню в руках, і вікно поверх неї збиває саме те, заради чого
//     інструкцію відкрили.
// Не показали зараз — не втратили: наступний перехід між розділами спробує знову.
//
// 🛑 `.pwa-guide` ДОДАНО ПРИ ЗЛИТТІ ДВОХ СЕСІЙ 29.08, і це не дрібниця порядку.
// Обидві сесії того дня робили поверхні для НОВОГО гостя незалежно: «b» —
// онбординг із браузера, «c» — це запрошення. Кожна окремо правильна; разом вони
// вперше зустрілись у `main`. Тобто список тут мусить рости РАЗОМ із застосунком:
// зʼявилась нова поверхня для гостя — її імʼя додається сюди, інакше запрошення
// мовчки навчиться перебивати саме те, чого не мало чіпати.
function screenBusy() {
  return !!document.querySelector('.app-modal, .acc-cab, .pwa-cta, .pwa-guide, .consent-bar');
}

function maybeInvite() {
  if (done || isLoggedIn() || shownRecently()) return;
  if (actions < ACTIONS_BEFORE) return;
  if (screenBusy()) return;
  done = true;
  remember();
  // Йдемо тим самим шляхом, що й контекстний гейт (`requireAuth`): подію вже
  // слухає `account-ui.js` і відкриває нею екран входу. Другого способу
  // відкривати вхід у застосунку не заводимо — інакше їх довелось би правити
  // парами, а розійшлись би вони при першій же зміні.
  document.dispatchEvent(new CustomEvent('cstl-need-login', {
    detail: { actionLabel: 'зберігати оголошення, писати й реагувати' },
  }));
}

export function initJoinInvite() {
  if (isLoggedIn() || shownRecently()) return;
  // Людина увійшла сама, поки ми лічили — більше нічого не пропонуємо.
  onAuthChange(() => { if (isLoggedIn()) done = true; });

  let timer = 0;
  window.addEventListener('cstl-tab-changed', () => {
    actions++;
    // Пауза після переходу: вкладка щойно перемалювалась, і вікно поверх неї в
    // ту саму мить виглядало б як збій. Кожен новий перехід відкладає перевірку
    // ще раз — тобто ловимо момент, коли людина ЗУПИНИЛАСЬ, а не гортає далі.
    if (timer) clearTimeout(timer);
    timer = setTimeout(maybeInvite, SETTLE_MS);
  });
}
