// 🔑 ДВІ РІЗНІ ПОДІЇ, І ПЛУТАТИ ЇХ НЕ МОЖНА — бо поверхні влаштовані по-різному:
//
//   `content_open` — людина ВІДКРИЛА матеріал окремим екраном. Це намір: у
//     Новинах картка в списку показує лише заголовок, і тап по ній означає
//     «хочу прочитати».
//   `content_seen` — картка ПОБУЛА на екрані. У Стрічці й на Дошці текст видно
//     прямо в списку, відкривати нема чого: там «прочитав» це «побачив».
//
// ⚠️ Якби ми міряли обидві поверхні тапами, Стрічка показувала б нуль при живих
// читачах — і ми зробили б хибний висновок «дописи нікому не цікаві».
//
// 🛑 ПОКАЗУЄМО ЧИСЛО, НІКОЛИ ІМЕНА. «Прочитали 40 людей» — так; «прочитав
// Сергій» — ніколи. Олика це містечко, де всі одне одного знають, і натяк на
// стеження відлякує сильніше, ніж допомагає користь (те саме правило, що тримає
// капсули: `HOT_RULES.md` №12, «тест на пригадування»).
// ═════════════════════════════════════════════════════════════════════════════

import { logEvent, getAnonId, analyticsUid } from './supabase.js';

// Скільки картка має пробути на екрані, щоб це рахувалось читанням.
// 🔑 Поріг існує саме проти прокрутки навиліт: без нього швидкий мах пальцем
// зарахував би двадцять «прочитань» за секунду, і число, яке ми покажемо
// авторові, було б утричі більшим за правду. Завищене число гірше за відсутнє —
// на ньому людина будує рішення (той самий урок, що в `HOT_RULES.md` №12 про
// капсулу, яка применшувала: брехня в будь-який бік однаково брехня).
const ПОРІГ_МС = 1000;

// Яку частку картки видно, щоб почати відлік. Половина, а не весь елемент:
// картка Стрічки з фото 4:5 вища за екран, і вимога «видно цілком» не
// справдилась би НІКОЛИ — лічильник мовчав би над людиною, яка саме читає.
const ЧАСТКА = 0.5;

// 🔑 ОДНА ПОДІЯ НА МАТЕРІАЛ ЗА СЕАНС. Людина гортає стрічку вгору-вниз десятки
// разів; без цього ми писали б рядок на кожен прохід і отримали б і роздуту
// базу, і брехливе число («допис прочитали 300 разів» від трьох людей).
// 📐 Живе в памʼяті сторінки, не в localStorage: наступний захід — новий сеанс,
// і це правильно, бо «повернувся і перечитав» це справді нова подія.
//
// 🔴 ЧЕСНО ПРО ЦЕЙ SET — ЙОГО РОЛЬ ВУЖЧА, НІЖ ЗДАЄТЬСЯ, І ЦЕ ЗАМІРЯНО.
// Одну подію на вузол гарантує `io.unobserve` нижче, а не Set: мутація 21.09
// (Set знято, `unobserve` лишено) залишила стенд ЗЕЛЕНИМ. Червоніє лише
// мутація, що знімає ОБИДВА (3 події → 6).
// ➡️ Set страхує єдиний випадок, якого `unobserve` не покриває: коли список
// ПЕРЕСТВОРЮЄ вузли (`patchList` у режимі 'full'), спостерігач вішається на нові
// елементи, і без Set та сама картка порахувалась би вдруге.
// 📐 Перевірено окремим зондом: перехід на іншу вкладку і назад вузлів НЕ
// перестворює (мітка на картці переживає повернення) — саме тому мутація «зняти
// лише Set» і не ловиться сценою.
const побачене = new Set();

function хтоЯ() {
  // Той самий порядок, що в решті викликів `logEvent` по застосунку: акаунт,
  // інакше анонімний id пристрою. Нічого нового про людину тут не збирається.
  return analyticsUid() || getAnonId();
}

// Явне відкриття матеріалу окремим екраном (Новини).
// 🛑 Дедуп той самий: перечитав ту саму статтю вдруге за сеанс — подія одна.
export function trackContentOpen(kind, id) {
  if (!kind || id == null) return;
  const ключ = `open:${kind}:${id}`;
  if (побачене.has(ключ)) return;
  побачене.add(ключ);
  logEvent(хтоЯ(), 'content_open', { meta: { kind, id } });
}

// Спостерігач показу карток у списку (Стрічка, Дошка).
//
// ⚠️ ЧОМУ `IntersectionObserver`, А НЕ СЛУХАЧ `scroll`. Слухач будив би нас на
// КОЖЕН кадр прокрутки і ми б самі рахували координати кожної картки — на
// телефоні це видно пальцем. Той самий вибір і з тієї самої причини вже
// зроблено в `community-blocks.js` і `news-hub.js`.
//
// 🔑 Спостерігач ОДИН на список, а не на картку: дротуємо після кожної
// перемальовки, а вже побачені картки відсіює `побачене`.
export function observeContentCards(root, kind, selector, attr) {
  if (!root || !('IntersectionObserver' in window)) return null;
  const картки = root.querySelectorAll(selector);
  if (!картки.length) return null;

  // Таймери відліку живуть на самому вузлі: картка може зникнути з екрана
  // (перемальовка, перехід на вкладку) раніше, ніж мине поріг, — тоді відлік
  // треба скасувати, інакше ми зарахуємо читання того, чого вже немає.
  const таймери = new WeakMap();

  const io = new IntersectionObserver((entries) => {
    for (const en of entries) {
      const вузол = en.target;
      const id = вузол.getAttribute(attr);
      if (!id) continue;
      const ключ = `seen:${kind}:${id}`;

      if (!en.isIntersecting) {
        clearTimeout(таймери.get(вузол));
        таймери.delete(вузол);
        continue;
      }
      if (побачене.has(ключ)) { io.unobserve(вузол); continue; }
      if (таймери.has(вузол)) continue;

      таймери.set(вузол, setTimeout(() => {
        таймери.delete(вузол);
        if (побачене.has(ключ)) return;
        побачене.add(ключ);
        logEvent(хтоЯ(), 'content_seen', { meta: { kind, id: Number(id) || id } });
        io.unobserve(вузол);      // більше стежити нема за чим
      }, ПОРІГ_МС));
    }
  }, { threshold: ЧАСТКА });

  картки.forEach(el => io.observe(el));
  return io;
}

// 🔎 Діагностичне вікно для стендів і для живої перевірки з телефона.
// Прав тут немає жодних: це той самий Set, що вже лежить у памʼяті сторінки.
export function _seenKeys() { return [...побачене]; }
