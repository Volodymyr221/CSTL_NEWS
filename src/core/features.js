// src/core/features.js — ПРАПОРЦІ ОНОВЛЕНЬ.
//
// 🗣️ Замовлення Вови 19.09: «як робити покращення застосунку… щоб не бачили
// користувачі. І тільки після того, як погодиться, що ця версія робоча…
// випускати його в прод. Але… щоб я міг протестити і побачити його В РАМКАХ
// ДОДАТКУ, як воно працює».
//
// Стани фічі (база, `app_features.stage`):
//   `off`    — код у проді, але мертвий. Навіть зламаний нікому не шкодить.
//   `circle` — бачить лише коло раннього доступу.
//   `all`    — бачать усі.
//
// 🛑 ГОЛОВНА МЕЖА: ЦЕ ПОКАЗ, А НЕ ПРАВО.
// Прапорець НІКОЛИ не є перевіркою доступу: будь-хто з devtools виставить собі
// що завгодно в цьому модулі за секунду. Право живе в RLS і `has_perm()` на
// сервері. Тут вирішується одне: малювати новий шлях чи старий.
//
// 🛑 І ДРУГА МЕЖА, ЯКОЇ ЛЕГКО НЕ ПОМІТИТИ: невідома фіча — ВИМКНЕНА.
// Якщо `my_features()` не відповів (мережа, гість, стара база), `featureOn()`
// віддає `false`, тобто застосунок малює те, що бачить громада. Протилежний
// вибір («не знаю → показати») означав би, що збій мережі показує людям
// недороблене — рівно те, від чого ця система й будувалась.

import { getSupabase } from './supabase.js';

let _features = null;        // { key: { stage, on } } або null, поки не спитали
let _inCircle = false;       // чи я в колі раннього доступу (каже сервер)
let _asResident = false;     // «дивитись як житель» — перемикач для команди

// 🔑 Ключ БЕЗ прив'язки до людини навмисно: це не дані акаунта, а режим
// ПЕРЕГЛЯДУ на цьому пристрої. Прив'язка до `uid` дала б дивне: зайшов іншим
// профілем — і режим перегляду поїхав за тобою.
const AS_RESIDENT_KEY = 'cstl_as_resident';

try { _asResident = localStorage.getItem(AS_RESIDENT_KEY) === '1'; } catch (_) { /* приватний режим */ }

// Читаємо один раз при старті. ⚠️ Без `await` у місці виклику: перший кадр не
// має чекати мережі (урок `authReady` — застосунок не повинен залежати від
// того, чи відповів сервер, щоб намалюватись).
export async function loadFeatures() {
  const supa = getSupabase();
  if (!supa) return;
  try {
    const { data, error } = await supa.rpc('my_features');
    // 🔑 Форма відповіді: `{ in_circle, features }`. Якщо приїхало щось інше
    // (стара база, збій), лишаємось при `null` — тобто малюємо те, що бачить
    // громада. Мовчазне «вгадування» тут показало б людям недороблене.
    if (!error && data && typeof data === 'object' && data.features
        && typeof data.features === 'object') {
      _features = data.features;
      _inCircle = data.in_circle === true;
      // Про зміну повідомляємо подією: вкладки, намальовані ДО відповіді,
      // мають нагоду перемалюватись, а не лишитись зі старим виглядом до
      // перезапуску застосунку.
      window.dispatchEvent(new CustomEvent('cstl-features-ready'));
    }
  } catch (e) { console.warn('[features]', e); }
}

// Чи малювати нову поведінку ЦІЙ людині.
export function featureOn(key) {
  const f = _features?.[key];
  if (!f) return false;                       // не знаю → як у громади
  if (_asResident) return f.stage === 'all';  // режим «як житель» ігнорує коло
  return !!f.on;
}

// Чи людина взагалі в колі раннього доступу — за цим показуємо перемикач.
//
// 🔴 ЦЕ ВИПРАВЛЕННЯ МОЄЇ Ж ВАДИ, І ВОНО ВАРТЕ ЧИТАННЯ ПЕРЕД ЗМІНОЮ.
// Перша редакція виводила відповідь із самих фіч: «є хоч одна `circle`, і вона
// для мене `on` — значить я в колі». Виглядало ощадно (без зайвого запиту) і
// було НЕПРАВДОЮ в найважливішу мить: 📐 `app_features` перед деплоєм — **0
// рядків**. Тобто Вова, для кого цю систему й будували, відкрив би застосунок
// і не знайшов пункту «Дивитись як житель» узагалі — бо фіч, з яких той пункт
// виводився, ще не існує.
// 🔑 Членство в колі — факт про ЛЮДИНУ. Його каже сервер окремим полем, і воно
// не залежить від того, що саме зараз тестується.
export function inTestCircle() { return _inCircle; }

export function asResident() { return _asResident; }

// 🔎 ДІАГНОСТИЧНЕ ВІКНО — і це НЕ люк для тесту.
// Прапорці не є секретом: їхні назви і стани однаково лежать у бандлі й
// приїжджають з `my_features()` кожному, хто ввійшов. Тут немає ЖОДНОГО права,
// яке можна було б відчинити — саме тому виставляти це назовні безпечно, на
// відміну від обхідного ключа заслінки, який був би справжньою дірою.
// 🔑 Навіщо: стенд мусить питати про стан фічі ТОЙ САМИЙ код, яким живе
// застосунок. Інакше перевірка порахувала б стан власною копією правила — і
// зеленіла б рівно тоді, коли копія розійшлась би з оригіналом.
try { window.__cstlFeatureOn = featureOn; } catch (_) {}

// Перемикач «дивитись як житель» (рішення Вови: «Одразу»).
// 🔑 Перезавантаження сторінки навмисне: половина екранів малюється один раз
// при старті, і «частково нова, частково стара» картинка збила б з пантелику
// саме тоді, коли людина перевіряє, як воно виглядає насправді.
export function setAsResident(on) {
  _asResident = !!on;
  try { localStorage.setItem(AS_RESIDENT_KEY, _asResident ? '1' : '0'); } catch (_) {}
  location.reload();
}
