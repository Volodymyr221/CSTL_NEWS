// ➡️ Модуль лишається під ОДИН сценарій: якщо Вова погодиться зробити бордову
// шапку прибитою назавжди, зона `#hm-rubber` стане окремим прокрутником із
// РІДНИМ відскоком, і цей файл або знадобиться для країв, або піде зовсім.
//
// ── нижче — початковий опис, чинний для самої механіки ──────────────────────
// 🔴 ГУМОВИЙ ВІДСКОК, ЯКИЙ НЕ ЧІПАЄ ШАПКУ — одне місце правди.
//
// ЗАМОВЛЕННЯ ВОВИ (10.08, дослівно): «треба щоб при скролі "натягування" вверх
// верхній бордовий блок з привітанням та погодою не відривався, тільки від
// початку скляних віджетів… гумовий ефект має починатись від скляних
// міні-віджетів до телефонів громади».
//
// ═══ ЧОМУ ЦЕ НЕ РОБИТЬСЯ НАЛАШТУВАННЯМ ═══════════════════════════════════════
// Рідна «гумка» iOS зсуває ВЕСЬ вміст прокрутника. Виключити з неї одну дитину
// не можна: немає ні CSS-властивості, ні прапорця. Тобто «hero не рухається, а
// решта пружинить» рідним відскоком недосяжне В ПРИНЦИПІ — його треба вимкнути
// (`overscroll-behavior-y: none`) і зробити свій, який рухає лише потрібну зону.
//
// ═══ ЧОМУ ЦЕ НЕ ПОВТОРИТЬ ПРОВАЛ ДОШКИ ══════════════════════════════════════
// На Дошці тричі провалились спроби рухати шапку скриптом за подією `scroll`:
// на iOS прокрутку веде КОМПОЗИТОР в окремому потоці, події приходять із
// затримкою, і скрипт за пальцем не встигає ніколи (`style/board.css`, блок
// «ТРЕТІЙ ПІДХІД»). Тут ситуація протилежна: ми рухаємось ЛИШЕ коли рідна
// прокрутка вже стоїть на нулі й нічого не робить. Конкуренції немає — це той
// самий прийом, на якому зроблені всі «потягни, щоб оновити».
//
// ═══ ТРИ РЕЧІ, ЯКІ ТУТ НАВМИСНО ═════════════════════════════════════════════
// 1. Рухаємо `transform: translate3d(0, y, 0)` — тільки композиторна властивість
//    (§11 скіла). Ніяких `height`, `margin`, `padding`: вони викликали б
//    перерахунок розкладки на кожен кадр.
// 2. Опір рахується формулою Apple з §9 скіла — чим далі тягнеш, тим менше йде.
//    Це не «поділити на три»: без насичення зона їхала б за пальцем один-в-один
//    і на довгому русі поїхала б на пів екрана.
// 3. Повернення — через `transition`, і воно ПЕРЕРИВАНЕ: новий дотик знімає
//    перехід і бере зону з поточного місця (§3 скіла — «grab a moving element
//    mid-flight»). Без цього палець «чекав би», поки доїде анімація.
// 4. Межі ДВІ — верхня і нижня. Рідний відскок вимкнено на всю вкладку, тож
//    якби ми вели лише верх, низ лишився б мертвим (Вова це й помітив одразу:
//    «а знизу віджетів громади чому гумка не працює?»).
//
// 🛑 ЩО НЕ КЛАСТИ В ЗОНУ: нічого з `position: fixed`. `transform` робить із
// контейнера containing block, і `fixed` усередині перестане кріпитись до
// екрана — пастка вже записана в `style/home.css`. Сторож це перевіряє.

const МАКС = 120;        // стеля зсуву, px. Далі опір робить рух майже нульовим.
const ОПІР = 0.55;       // константа з формули Apple (§9)
const ПОРІГ = 3;         // px — нижче цього рух вважаємо тремтінням пальця

// Опір: чим далі за межу, тим менше зона йде за пальцем.
// Формула зі скіла: (overshoot * dim * c) / (dim + c * |overshoot|).
function опір(перебіг, розмір) {
  return (перебіг * розмір * ОПІР) / (розмір + ОПІР * Math.abs(перебіг));
}

// Поточний зсув зони по Y — читаємо з ОБЧИСЛЕНОЇ матриці, а не з нашої змінної.
// 🔑 Різниця принципова: під час повернення пружиною наша змінна вже дорівнює
// нулю (це ЦІЛЬ), а на екрані зона ще їде. Щоб перехопити її «на льоту» (§3
// скіла), потрібне саме живе значення.
// ⚠️ Розбираємо рядок самі, без `DOMMatrixReadOnly`: сторож імпортів проєкту
// не знає цього браузерного глобала, а заводити для нього виняток дорожче, ніж
// один регулярний вираз. Формат: `matrix(a, b, c, d, tx, ty)`.
function живийЗсувЗ(el) {
  const t = getComputedStyle(el).transform;
  if (!t || t === 'none') return 0;
  const ч = t.slice(t.indexOf('(') + 1, t.lastIndexOf(')')).split(',').map(parseFloat);
  if (ч.length === 6) return ч[5] || 0;        // matrix(a,b,c,d,tx,ty)
  if (ч.length === 16) return ч[13] || 0;      // matrix3d — ty на 14-й позиції
  return 0;
}

/**
 * Вішає гумовий відскок на зону всередині прокрутника.
 * @param {HTMLElement} scroller — хто реально прокручується (`.app-main`)
 * @param {HTMLElement} zone     — що саме пружинить (усе ПІСЛЯ шапки)
 * @returns {() => void} — зняти
 */
export function attachRubberZone(scroller, zone) {
  if (!scroller || !zone) return () => {};

  let startY = 0;
  let тягнемо = false;   // палець уже перетнув поріг і ми ведемо зону
  let край = 0;          // 0 — не на межі; +1 — верхня; −1 — нижня
  const живийЗсув = () => живийЗсувЗ(zone);

  // На якій межі стоїть прокрутник ЗАРАЗ.
  // ⚠️ Запас 1px: на дробових масштабах (iOS зумить сторінку при повороті й при
  // системному збільшенні шрифту) `scrollTop + clientHeight` не дорівнює
  // `scrollHeight` рівно, а відрізняється на десяті. Без запасу нижній край
  // просто не спрацьовував би на частині пристроїв.
  const наМежі = () => {
    if (scroller.scrollTop <= 0) return 1;
    if (scroller.scrollTop + scroller.clientHeight >= scroller.scrollHeight - 1) return -1;
    return 0;
  };

  const поставити = (y) => {
    zone.style.transform = y ? `translate3d(0, ${y.toFixed(1)}px, 0)` : '';
  };

  const відпустити = () => {
    // Повернення пружиною. `transition` вішаємо лише на час повернення і
    // знімаємо після — інакше він гальмував би рух за пальцем.
    zone.style.transition = 'transform 0.34s cubic-bezier(0.22, 1, 0.36, 1)';
    поставити(0);
    тягнемо = false;
    край = 0;
  };

  const onStart = (e) => {
    // 🔑 Перериваність (§3): дотик під час повернення забирає зону з ПОТОЧНОГО
    // місця, а не чекає кінця анімації. Знімаємо перехід і фіксуємо живий зсув.
    const живий = живийЗсув();
    zone.style.transition = '';
    if (живий) поставити(живий);

    startY = e.touches ? e.touches[0].clientY : e.clientY;
    край = наМежі();
    тягнемо = !!живий;
  };

  const onMove = (e) => {
    const y = e.touches ? e.touches[0].clientY : e.clientY;
    const dy = y - startY;

    // 🔴 ДВІ МЕЖІ, А НЕ ОДНА (додано 10.08 за питанням Вови: «а знизу віджетів
    // громади чому гумка не працює?»). Перша редакція вела лише верхній край —
    // тобто половину обіцянки. Рідний відскок вимкнено на всю вкладку, отже
    // низ лишався мертвим, і це виглядало як недоробка, а не як задум.
    // Напрямок мусить збігатися з межею: на верхній тягнемо ВНИЗ, на нижній —
    // ВГОРУ. Інакше рух проти межі підміняв би звичайну прокрутку.
    const край_ = наМежі();
    const свій = (край_ === 1 && dy > 0) || (край_ === -1 && dy < 0);

    if (!свій) {
      // Палець пішов у бік звичайної прокрутки — віддаємо керування їй.
      if (тягнемо) відпустити();
      return;
    }
    if (!тягнемо && Math.abs(dy) < ПОРІГ) return;   // поріг проти тремтіння (§10)

    тягнемо = true;
    край = край_;
    поставити(опір(dy, МАКС * 2.4));
  };

  scroller.addEventListener('touchstart', onStart, { passive: true });
  scroller.addEventListener('touchmove', onMove, { passive: true });
  scroller.addEventListener('touchend', відпустити, { passive: true });
  scroller.addEventListener('touchcancel', відпустити, { passive: true });

  return () => {
    scroller.removeEventListener('touchstart', onStart);
    scroller.removeEventListener('touchmove', onMove);
    scroller.removeEventListener('touchend', відпустити);
    scroller.removeEventListener('touchcancel', відпустити);
    zone.style.transition = '';
    поставити(0);
  };
}
