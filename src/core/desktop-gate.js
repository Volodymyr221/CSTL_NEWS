// НАВІЩО (Вова 29.08): «веб-версія адаптована тільки для телефону, для компʼютера
// ні, тому якщо користувач відкриває компʼютерну версію — потрібно написати, що
// зараз доступна тільки телефонна версія, і QR-код, щоб перекидало на сайт із
// телефону».
//
// 🔴 ЧОМУ ЗАМІСТЬ ЗАСТОСУНКУ, А НЕ ПОВЕРХ НЬОГО. Якщо застосунок під низом усе
// одно вантажиться, повідомлення перетворюється на банер: людина його закриє
// (або просто прокрутить) і користуватиметься зламаним макетом. Тому `init()`
// сюди впирається і далі НЕ ЙДЕ — жодна вкладка не будується.
//
// 🔴 ЧОМУ НЕ ЗА ШИРИНОЮ ЕКРАНА. Ширина бреше двічі: на iPhone із «Запросити
// версію для компʼютера» вона лишається телефонною, а планшет дає «десктопні»
// 1024 при цілком робочому дотиковому макеті. Питаємо ВКАЗІВНИК: `pointer: fine`
// і `hover: hover` — це миша або трекпад, тобто рівно те, чого в нас немає в
// макеті. Дотикові пристрої проходять усі.
// ⚠️ І ширина теж потрібна, але як ДРУГА умова: у вузькому вікні браузера на
// компʼютері телефонний макет виглядає правильно, і замикати його немає за що.
//
// 🛑 ОБХІДНОЇ КНОПКИ НЕМАЄ — пряме рішення Вови: «компʼютерної версії, поки вона
// не налаштована, вони не мають бачити взагалі, тільки після того як налаштуємо».
// Наслідок, сказаний вголос і прийнятий: власник на своєму Mac теж сюди впреться.
//
// 🔑 ПОРЯДОК: цей екран стоїть ПІСЛЯ заслінки розробки (`dev-lock`), теж за
// рішенням Вови. Заслінка — про доступ, цей екран — про пристрій; спершу «чи
// можна тобі сюди взагалі», потім «чи вийде тобі тут користуватись».

import { qrSvg } from './qr.js';

// Нижче цієї ширини навіть із мишею макет виглядає як задумано — вікно браузера
// просто вужче за телефонну колонку.
const MIN_DESKTOP_WIDTH = 900;

let _gate = null;         // сам екран, поки він на сторінці
let _blockedBoot = false; // застосунок ТАК І НЕ ЗАПУСТИВСЯ через цей екран

/** Миша/трекпад і широке вікно? */
export function isDesktopBrowser() {
  try {
    const mouse = window.matchMedia
      && window.matchMedia('(pointer: fine) and (hover: hover)').matches;
    return !!mouse && window.innerWidth >= MIN_DESKTOP_WIDTH;
  } catch (_) {
    // Не змогли спитати — пускаємо. Замикати людину через збій перевірки гірше,
    // ніж показати їй незручний макет.
    return false;
  }
}

// ── Розмітка екрана ──────────────────────────────────────────────────────────
function buildGate() {
  const el = document.createElement('div');
  el.className = 'dg';
  el.setAttribute('role', 'dialog');
  el.setAttribute('aria-modal', 'true');
  el.setAttribute('aria-label', 'Застосунок доступний у телефоні');

  // 🔑 QR веде НА ЦЮ САМУ АДРЕСУ, а не на головну. Людина, яка прийшла з
  // месенджера по конкретну статтю (`#/post/news/123`), після сканування
  // потрапляє на неї ж — інакше ми б відправили її шукати матеріал заново.
  let qr = '';
  try {
    qr = qrSvg(location.href, { label: 'QR-код з адресою цієї сторінки' });
  } catch (_) {
    // Адреса не влізла в код — краще без картинки, ніж із тією, що не сканується.
    // Текстова адреса нижче лишається робочим шляхом.
    qr = '';
  }

  el.innerHTML = `
    <div class="dg-in">
      <div class="dg-logo">CSTL <span>LIFE</span></div>
      <h1 class="dg-title">Застосунок поки що<br>живе в телефоні</h1>
      <p class="dg-text">Версію для компʼютера ще не зробили.
        Наведіть камеру телефона на код — відкриється саме ця сторінка.</p>
      ${qr ? `<div class="dg-qr">${qr}</div>` : ''}
      <p class="dg-addr">${location.host}</p>
    </div>`;
  return el;
}

function showGate() {
  if (_gate) return;
  // Заставка лишилась би висіти під екраном назавжди: її прибирає кінець
  // `init()`, а ми туди не доходимо. Той самий прийом, що в заслінки розробки.
  const splash = document.getElementById('splash');
  if (splash) splash.remove();

  _gate = buildGate();
  document.body.appendChild(_gate);
  // Прокрутка сторінки під екраном нікому не потрібна — і на трекпаді вона
  // видно «відсовує» наш екран, хоч він і `fixed`.
  document.body.classList.add('dg-open');
}

function hideGate() {
  if (!_gate) return;
  _gate.remove();
  _gate = null;
  document.body.classList.remove('dg-open');
}

// ── Зміна розміру вікна ──────────────────────────────────────────────────────
// Людина розтягує вікно з половини екрана на весь — і макет ламається мовчки.
// Тому стан перевіряється не лише при завантаженні.
function watchViewport() {
  let planned = false;
  const react = () => {
    planned = false;
    const desktop = isDesktopBrowser();
    if (desktop && !_gate) { showGate(); return; }
    if (!desktop && _gate) {
      // 🔑 Якщо застосунок ТАК І НЕ ЗАПУСТИВСЯ (ми впинились у цей екран на
      // старті), просто прибрати екран не можна — під ним порожньо, а половини
      // `init()` не існує. Чесний вихід — перезавантажити сторінку: тоді
      // застосунок збереться нормально, з тією ж адресою.
      if (_blockedBoot) { location.reload(); return; }
      hideGate();
    }
  };
  window.addEventListener('resize', () => {
    if (planned) return;
    planned = true;
    requestAnimationFrame(react);
  });
}

/**
 * Головний вхід. `true` — застосунок може будуватись далі, `false` — ні.
 * Кличеться з `src/app.js` одразу після заслінки розробки.
 */
export function passDesktopGate() {
  watchViewport();
  if (!isDesktopBrowser()) return true;
  _blockedBoot = true;
  showGate();
  return false;
}
