// НАЗВА СЕЛА ↔ НАЗВА ЗУПИНКИ В РОЗКЛАДІ ПЕРЕВІЗНИКА.
//
// 🔴 22.08. Перевізник пише назви сіл по-своєму, і звірка рядок-у-рядок цього не
// пробачає. Заміряно на живому розкладі: з 17 сіл СІМ не збігались із жодною
// зупинкою, і два з них автобус обслуговує щодня:
//   «Хром'яків» ↔ «Хромяків» (без апострофа) — 168 рейсів, шоста зупинка за
//   завантаженістю в усьому розкладі;
//   «Метельне» ↔ «Мительно» (інше слово) — 42 рейси.
// Наслідок: житель такого села НЕ ОТРИМУВАВ капсули автобуса взагалі — хоч як
// точно ми визначили його місце. Тобто вся робота над локацією впиралась у те,
// що останній крок не міг зіставити два рядки.
//
// 🔑 Правильні назви — наші (перевірено за Вікіпедією: «Хром'яків», «Метельне»).
// Тому зводимо до НАШОГО написання, а не навпаки: воно вже стоїть у профілі,
// у фільтрі Дошки і в бейджах локації, і другого написання в застосунку бути
// не повинно.
//
// 🛑 «Одеради АЗ» СВІДОМО НЕ зводимо до «Одеради»: у розкладі це дві різні
// зупинки (84 і 70 рейсів), тобто два різні місця посадки в одному селі.
// Злити їх означало б сказати людині, що автобус зупиниться там, де він не
// зупиняється.
const ЗУПИНКА_ДО_СЕЛА = {
  // Виправлення в сирих даних, які були тут із самого початку.
  'Гараджа': 'Гаразджа',
  // ⚠️ Перевіряється ДО зрізання « пов.»: «Хорлупи» — окрема справжня зупинка,
  // і якби ми спершу зрізали суфікс, цей рядок став би нею.
  'Хорлупи пов.': 'Хром\'яків',
  // Інше слово, а не інше написання — правилом не виводиться, лише списком.
  'Мительно': 'Метельне',
};

// Ключ для звірки: без апострофа і без регістру. Апостроф — це ПРАВИЛО, а не
// список: «Хром'яків» / «Хром’яків» / «Хромяків» — одне слово в трьох
// друкарських варіантах, і кожен новий варіант має лікуватись сам.
const ключ = н => String(н || '').toLowerCase().replace(/['\u02bc\u2019`]/g, '');
const СЕЛО_ЗА_КЛЮЧЕМ = Object.fromEntries(SETTLEMENTS.map(н => [ключ(н), н]));

// Зводить будь-яке написання до нашої канонічної назви. Якщо назва нам
// невідома (Луцьк, Рівне, Ківерці — не наші села) — віддаємо як є, лише
// прибравши службовий суфікс: вигадувати за перевізника ми не беремось.
export function canonicalPlace(сире) {
  const н = String(сире || '').trim();
  if (!н) return '';
  if (ЗУПИНКА_ДО_СЕЛА[н]) return ЗУПИНКА_ДО_СЕЛА[н];
  const безПов = н.replace(/\s+пов\.$/, '').trim();
  if (ЗУПИНКА_ДО_СЕЛА[безПов]) return ЗУПИНКА_ДО_СЕЛА[безПов];
  return СЕЛО_ЗА_КЛЮЧЕМ[ключ(безПов)] || безПов;
}
