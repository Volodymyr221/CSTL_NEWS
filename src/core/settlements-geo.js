//
// І він має рацію двічі. По-перше, «додому» спиралось на село з АНКЕТИ, а вона
// заповнена в одного профілю з дванадцяти — логіка на даних, яких майже ні в
// кого немає. По-друге, застосунок уже показує місце людини великими літерами в
// шапці погоди, і людина сама його там міняє. Мати друге, приховане уявлення
// про те, «де вона насправді», — означає сперечатись із власним екраном.
//
// ➡️ Тому місце одне: те, що написане в погоді. Порядок той самий, що вже діє
// для самої погоди (обране людиною має пріоритет над геолокацією) — інакше
// застосунок показував би погоду одного міста і автобуси іншого.
export const WX_PLACE_KEY = 'wx_place_v1';

// 🔴 21.08 — ДЕ Я ЗАРАЗ ЗА ВИЗНАЧЕННЯМ ЗАСТОСУНКУ (окремо від обраного руками).
//
// Слово Вови: «в погоді ясно пише — я заходжу, мене пише Луцьк; буду в Дерні,
// писатиме Дерно. Зроби, щоб автобус вибивало з місця його локації».
//
// І він мав рацію: застосунок уже з'ясовує назву населеного пункту за
// координатами (зворотне геокодування для погоди) і МАЛЮЄ її великими літерами.
// Але зберігав її лише тоді, коли людина обрала місто РУКАМИ. Визначена сама
// собою назва жила рівно до перемальовки — тобто відповідь була, і сусідній
// екран її не бачив.
//
// 🛑 ЧОМУ ОКРЕМИЙ КЛЮЧ, А НЕ ТОЙ САМИЙ. `wx_place_v1` означає «людина ОБРАЛА це
// місце», і погода через нього перестає питати геолокацію. Якби ми писали туди
// визначену назву, людина назавжди прикипіла б до першого села, у якому
// відкрила застосунок, — поїхала б і бачила чужу погоду. Тому «обрав» і «тут
// зараз» — дві різні відповіді й два різні ключі.
const HERE_KEY = 'wx_here_v1';

export function detectedPlace() {
  try {
    const v = localStorage.getItem(HERE_KEY);
    return v && isKnownPlace(v) ? v : null;
  } catch { return null; }
}

export function rememberDetectedPlace(name) {
  try {
    if (name && isKnownPlace(name)) localStorage.setItem(HERE_KEY, name);
  } catch { /* приватний режим — просто не запамʼятаємо */ }
}

export function pickedPlace() {
  try {
    const v = localStorage.getItem(WX_PLACE_KEY);
    // Звіряємось зі списком: перелік НП міг змінитись, і старий запис вказував
    // би в нікуди — та сама перевірка, що робить погода.
    return v && isKnownPlace(v) ? v : null;
  } catch { return null; }
}
