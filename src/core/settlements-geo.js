//              немає — просто йдемо далі, нічого не ламається.
//   3. КЕШ   — те, що вже з'ясували на цьому телефоні (localStorage).
//   4. NOMINATIM — прямий геокод «назва, Волинська область, Україна».
//              Результат одразу лягає в кеш, тож звертання разове на село.
//
// ⚠️ ЧОМУ ЗАЛЕЖНІСТЬ ВІД МЕРЕЖІ ТУТ НЕ Є НОВОЮ ПРОБЛЕМОЮ: погоду й так неможливо
// показати офлайн — вона приходить з Open-Meteo. Тобто геокод не додає нового
// класу залежності, він живе в тому ж запиті, що й сама погода.
//
// ─────────────────────────────────────────────────────────────────────────────
// 🔬 ЧЕСНО ПРО ТЕ, ЧОГО ЦЕЙ СЕЛЕКТОР НЕ ДАСТЬ (сказано Вові до роботи)
// Прогнозні моделі мають сітку близько 7-11 км, а вся Олицька громада — це
// приблизно 15-20 км упоперек. Тобто більшість сіл потраплять в одну-дві
// клітинки моделі й покажуть ОДНАКОВІ числа. Луцьк (~30 км) відрізняється
// помітніше. Це не робить підпис нечесним: «Олика» лишається правдою і тоді,
// коли в Дерні стільки ж градусів. Але очікувати різних температур по селах
// не варто.

import { SETTLEMENTS } from './settlements.js';
import { OLYKA_COORDS } from './utils.js';

// Міста поруч — не входять у громаду, тому окремою групою у списку.
// Луцьк доданий на пряме прохання Вови («І плюс Луцьк»).
export const NEARBY_CITIES = ['Луцьк'];

// Перевірене продом. Свідомо ОДИН запис: решту чесніше з'ясувати геокодером,
// ніж вписати по пам'яті.
const SEED = { 'Олика': { ...OLYKA_COORDS } };

const CACHE_KEY = 'wx_geo_v1';
const GEO_FILE  = './data/settlements-geo.json';

// Файл читаємо один раз за сесію. `null` = ще не пробували, `{}` = пробували і не вийшло.
let _filePromise = null;

function readCache() {
  try { return JSON.parse(localStorage.getItem(CACHE_KEY) || '{}'); }
  catch { return {}; }
}

function writeCache(name, c) {
  try {
    const all = readCache();
    all[name] = c;
    localStorage.setItem(CACHE_KEY, JSON.stringify(all));
  } catch { /* приватний режим або переповнене сховище — не критично */ }
}

function loadFile() {
  if (_filePromise) return _filePromise;
  _filePromise = fetch(GEO_FILE)
    .then(r => (r.ok ? r.json() : {}))
    .then(d => (d && typeof d === 'object' ? (d.coords || d) : {}))
    .catch(() => ({}));   // файлу немає — це штатний стан, не помилка
  return _filePromise;
}

// Пряме геокодування: назва → координати. `limit=1` бо нас цікавить один пункт.
// ⚠️ Уточнення «Волинська область, Україна» обовʼязкове: сіл із назвами на
// кшталт «Ставок» чи «Котів» в Україні кілька, і без області геокодер міг би
// віддати чуже село за сотні кілометрів — тобто чужу погоду під нашим підписом.
async function geocode(name) {
  const q = encodeURIComponent(`${name}, Волинська область, Україна`);
  const res = await fetch(
    `https://nominatim.openstreetmap.org/search?q=${q}&format=json&limit=1`,
    { headers: { 'Accept-Language': 'uk' } }
  );
  const arr = await res.json();
  const hit = Array.isArray(arr) ? arr[0] : null;
  if (!hit) return null;
  const lat = parseFloat(hit.lat), lon = parseFloat(hit.lon);
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return null;
  return { lat, lon };
}

// Координати населеного пункту або `null`, якщо з'ясувати не вдалося.
// 🔴 Саме `null`, а не «підставимо Олику»: мовчазна підміна показала б людині
// погоду іншого місця під назвою її села. Краще чесно сказати, що не вийшло.
export async function coordsOf(name) {
  if (SEED[name]) return SEED[name];

  const cached = readCache()[name];
  if (cached && Number.isFinite(cached.lat)) return cached;

  const file = await loadFile();
  if (file[name] && Number.isFinite(file[name].lat)) {
    writeCache(name, file[name]);
    return file[name];
  }

  try {
    const c = await Promise.race([
      geocode(name),
      // Той самий запобіжник, що для назви міста в погоді: чужий сервіс не має
      // права підвісити інтерфейс назавжди.
      new Promise(r => setTimeout(() => r(null), 6000)),
    ]);
    if (c) { writeCache(name, c); return c; }
  } catch { /* нижче — null */ }
  return null;
}

// Групи для нижньої шторки. Порядок і склад — те, що просив Вова:
// спершу громада, окремо «міста поруч» з Луцьком.
export function locationGroups() {
  return [
    { title: 'Олицька громада', items: SETTLEMENTS },
    { title: 'Міста поруч',     items: NEARBY_CITIES },
  ];
}

// Чи є назва «нашою» (є у списках) — щоб не намагатись геокодувати сміття
// зі старого localStorage після перейменувань.
export function isKnownPlace(name) {
  return SETTLEMENTS.includes(name) || NEARBY_CITIES.includes(name);
}

// ── ДЕ Я? НАЙБЛИЖЧЕ СЕЛО ГРОМАДИ ЗА КООРДИНАТАМИ (20.08) ─────────────────────
//
// 🔑 Замовлення Вови: «село користувача ми ж беремо — витягуємо локацію, дані про
// місце розташування для погоди ми це беремо». І він мав рацію: координати вже
// питаються для погоди (`getCoords`, з 04.08), координати сіл уже лежать у цьому
// файлі. Усе потрібне в проєкті було — бракувало одного обчислення.
//
// 🛑 ЧОМУ ЦЕ НЕ ЗАМІНЮЄ АНКЕТУ. Анкета каже, ДЕ ЛЮДИНА ЖИВЕ; координати — ДЕ ВОНА
// ЗАРАЗ. Це різні відповіді, і для автобуса важлива друга: житель Дерна, який
// сьогодні в Луцьку, рейсів із Дерна не потребує.
//
// ⚠️ РАДІУС 6 КМ — не «щоб напевно», а з розмірів громади: села розкидані на
// 5-12 км одне від одного, тож ближче 6 км до села можна бути лише в ньому або
// на його околиці. Далі — людина просто не в громаді, і вгадувати не треба.
const БЛИЗЬКО_КМ = 6;

// Відстань між точками (гаверсинус). Для 17 точок у радіусі 20 км вистачило б і
// плоскої геометрії, але різниця в коді — один рядок, а похибка плоскої моделі
// росте непомітно.
function км(a, b) {
  const R = 6371, рад = д => (д * Math.PI) / 180;
  const dLat = рад(b.lat - a.lat), dLon = рад(b.lon - a.lon);
  const h = Math.sin(dLat / 2) ** 2
          + Math.cos(рад(a.lat)) * Math.cos(рад(b.lat)) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

// 🛑 БЕЗ ЖОДНОГО МЕРЕЖЕВОГО ЗАПИТУ, і це вимога, а не оптимізація.
// Перша версія кликала `coordsOf()`, який за потреби йде в геокодер. На чистому
// телефоні це означало б до 17 звернень до чужого безкоштовного сервісу — на
// КОЖНЕ відкриття вкладки, заради одного рядка капсули. Такий код працює у
// розробника і лягає в проді.
// ➡️ Тому порівнюємо ЛИШЕ з тими селами, координати яких УЖЕ відомі: seed, файл
// `data/settlements-geo.json` (якщо згенерований) і кеш телефона.
// ⚠️ Наслідок, який треба знати: поки файл не згенеровано (`node
// scripts/geocode-settlements.mjs`), з коробки відома лише Олика — тобто «я в
// Олиці» визначається одразу, а решта сіл після генерації або після того, як
// людина сама гляне погоду свого села.
async function відоміКоординати(назва) {
  if (SEED[назва]) return SEED[назва];
  const c = readCache()[назва];
  if (c && Number.isFinite(c.lat)) return c;
  const file = await loadFile();
  return file[назва] && Number.isFinite(file[назва].lat) ? file[назва] : null;
}

// 🔴 22.08 — ПʼЯТЬ СІЛ, ДО ЯКИХ АВТОБУС НЕ ЇЗДИТЬ ВЗАГАЛІ.
// Заміряно на живому розкладі: у зупинках немає Горянівки, Залісочого,
// Мощаниці, Путилівки і Ставка. Це не поломка даних — туди справді не їздять.
//
// Але поводився застосунок так, ніби це поломка: людина в Ставку не отримувала
// капсули НІЯКОЇ. Визначили село точно, і саме тому нічого не показали — бо
// шукали рейс із зупинки, якої не існує. Мовчання гірше за приблизну відповідь:
// людина не дізнається ні що автобуса немає, ні звідки він є.
//
// 🔑 Питання, на яке треба відповідати, — не «який автобус з мого села», а
// «звідки я реально можу поїхати». Для цього і потрібні координати: вони
// відповідають не тільки «де я», а й «яка найближча зупинка, куди автобус
// заходить».
//
// 🛑 Межа та сама, що й у `nearestSettlement`: без мережі і лише серед відомих
// координат. Не знаємо, де село, — краще нічого не вигадати (викличний код
// відкотиться на Олику), ніж назвати навмання.
// ⚠️ Межі відстані тут НЕМАЄ свідомо: список кандидатів уже обмежений
// зупинками нашого ж розкладу, і найдальша з них — Луцьк. Додати сюди ще одне
// число означало б завести другу межу, яка мовчки розійдеться з першою.
export async function nearestServedStop(назва, зупинки) {
  const свої = (зупинки || []).filter(Boolean);
  if (!назва || !свої.length) return null;
  let точка = null;
  try { точка = await відоміКоординати(назва); } catch { точка = null; }
  if (!точка || typeof точка.lat !== 'number') return null;
  let best = null;
  for (const кандидат of свої) {
    if (кандидат === назва) return назва;   // моє село і є зупинкою
    let c = null;
    try { c = await відоміКоординати(кандидат); } catch { c = null; }
    if (!c || typeof c.lat !== 'number') continue;
    const d = км(точка, c);
    if (!best || d < best.d) best = { кандидат, d };
  }
  return best ? best.кандидат : null;
}

export async function nearestSettlement(coords) {
  if (!coords || typeof coords.lat !== 'number') return null;
  let best = null;
  for (const назва of SETTLEMENTS) {
    let c = null;
    try { c = await відоміКоординати(назва); } catch { c = null; }
    if (!c || typeof c.lat !== 'number') continue;
    const d = км(coords, c);
    if (!best || d < best.d) best = { назва, d };
  }
  return best && best.d <= БЛИЗЬКО_КМ ? best.назва : null;
}

