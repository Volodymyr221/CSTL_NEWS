// 🔑 Копію робити НЕ МОЖНА — у проєкті вже розходились дві копії списків антиспаму,
// і це коштувало бага, який виглядав як «текст правильний, а не надсилається». Тому
// не «такий самий код у другому файлі», а спільний примітив, яким користуються обидва.
//
// ⚠️ ЧОМУ `sessionStorage`, А НЕ `localStorage` — рішення 27.07, лишається чинним.
// Чернетка тут — СТРАХОВКА від випадкового тапу, а не архів написаного: вона живе,
// поки відкритий застосунок, і зникає разом із ним. Слова Вови про попередню версію:
// «закрив додаток — а мені знову пише великий пост». Мовчазне «вічне» збереження без
// видимого списку чернеток гірше за обидва варіанти: текст спливає через дні, а
// знайти чи прибрати його ніде. Знадобиться справжній список чернеток — це окрема
// фіча, і тоді сховище має стати постійним І видимим людині.
//
// ⚠️ Доступ до `sessionStorage` може КИНУТИ ВИНЯТОК (приватний режим, старі движки,
// вимкнені куки). Чернетка — не та річ, заради якої можна впалити екран, тому все
// загорнуте в try/catch і при збої поводиться як «чернетки немає».

const DEFAULT_TTL = 12 * 3600 * 1000;   // запобіжник, якщо вкладка висить добу

function ssGet(key, fallback) {
  try { const v = sessionStorage.getItem(key); return v ? JSON.parse(v) : fallback; }
  catch { return fallback; }
}
function ssSet(key, value) {
  try { sessionStorage.setItem(key, JSON.stringify(value)); } catch {}
}
function ssDel(key) {
  try { sessionStorage.removeItem(key); } catch {}
}

/**
 * Створити сховище чернеток для однієї форми.
 *
 * @param prefix      префікс ключа, напр. 'cstl_fd_draft_' або 'cstl_bd_draft'
 * @param meaningful  (d) => boolean — ЩО вважати непорожньою чернеткою.
 *                    Задає КОЖНА форма сама: у композера «Стрічки» це текст/дата/час/місце,
 *                    у подачі оголошення — заголовок/опис/категорія/ціна/контакт.
 *                    Порожня чернетка не зберігається взагалі: інакше при поверненні
 *                    показувався б тост ні про що, а стирання останнього символу
 *                    лишало б «привид» попереднього тексту.
 * @param ttl         скільки чернетка лишається дійсною (за замовчуванням 12 год)
 */
export function createDraftStore(prefix, meaningful, ttl = DEFAULT_TTL) {
  const keyOf = (id = '') => `${prefix}${id}`;
  return {
    read(id = '') {
      const d = ssGet(keyOf(id), null);
      if (!d || typeof d !== 'object') return null;
      if (!d.ts || Date.now() - d.ts > ttl) { ssDel(keyOf(id)); return null; }
      return meaningful(d) ? d : null;
    },
    write(id = '', d = {}) {
      // Стер усе — чернетки більше немає. Саме тут, а не в читанні: інакше в сховищі
      // накопичувались би порожні записи, які «оживали» б після правки критерію.
      if (!meaningful(d)) { ssDel(keyOf(id)); return; }
      ssSet(keyOf(id), { ...d, ts: Date.now() });
    },
    clear(id = '') { ssDel(keyOf(id)); },
  };
}

/**
 * Разове прибирання чернеток, які СТАРА версія писала у `localStorage`.
 * Читати ми їх більше не читаємо, але лишати сміття в сховищі людини негарно.
 * Кличеться один раз при завантаженні модуля-споживача.
 */
export function purgeLegacyDrafts(prefix) {
  try {
    const keys = [];
    for (let i = 0; i < localStorage.length; i++) {
      const k = localStorage.key(i);
      if (k && k.startsWith(prefix)) keys.push(k);
    }
    keys.forEach(k => localStorage.removeItem(k));
  } catch {}
}
