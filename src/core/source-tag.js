// 🔴 ЗАРАДИ ЧОГО. План кампанії (`launch/ZVEDENYI_PLAN_KAMPANII_2026-09-25.md`)
// розводить людей шістьма офлайн- і онлайн-точками одночасно: наліпка в
// автобусі, аркуш у костелі, табличка в крамниці, Viber-групи, групи Facebook,
// Instagram. Аудит 30.09 показав, що в коді не було НІЧОГО: ні читання
// параметра, ні події. Тобто на другому тижні кампанії ми бачили б загальне
// число встановлень і не могли б відповісти на єдине питання, яке тоді важить —
// **яка з точок їх дала**. Решту грошей і часу далі довелось би ділити навмання.
//
// 🔑 ДВА РІШЕННЯ, ЯКІ ТУТ НЕ ОЧЕВИДНІ, І БЕЗ ЯКИХ ЧИСЛО БРЕХАЛО Б.
//
//   1. **Запамʼятовуємо, а не читаємо щоразу.** Застосунок ставиться як PWA, а
//      `manifest.json` має `"start_url": "./"` — БЕЗ запиту. Отже встановлений
//      з головного екрана застосунок стартує з чистої адреси, і подія
//      `pwa_install` не донесла б джерела взагалі ніколи. А саме вона тут
//      головна: Вові потрібно знати, яка точка дала ВСТАНОВЛЕННЯ, а не відкриття.
//      ➡️ Тому перший дотик лягає в `localStorage` і живе там.
//
//   2. **Перший дотик виграє, і його НЕ перезаписуємо.** Питання звучить «що
//      привело цю людину в застосунок», і відповідь належить тій точці, яка
//      привела. Людина, що вже користується застосунком, за місяць тицьне
//      посилання з Viber-групи — і без цього правила Viber забрав би собі
//      заслугу наліпки в автобусі. 🛑 Це та сама вада, що «завищене число гірше
//      за відсутнє» (`HOT_RULES.md` №12): на такому числі Вова вирішує, куди
//      клеїти наступну сотню наліпок.
//
// 🧹 **Прибираємо параметр з адреси одразу.** Дві причини, і друга важливіша за
// першу: адреса не тягне за собою сміття у «Поділитись», і людина, яка
// перешле посилання зі свого екрана другові, не припише друга до наліпки, яку
// сканувала сама. Без цього одна наліпка розмножувалась би переказом.
//
// 🛑 ВИМИКАЧ СТАТИСТИКИ ГЛУШИТЬ І ЦЕ. Хто відкликав згоду в кабінеті — не
// лишає сліду жодного виду, тож при вимкненій аналітиці ми НЕ зберігаємо
// нічого. Параметр з адреси все одно прибираємо: то гігієна адреси, не збір.
// ═════════════════════════════════════════════════════════════════════════════

import { analyticsEnabled } from './supabase.js';

const КЛЮЧ = 'cstl-source-v1';

// Назви параметра, які читаємо. `from` — наш (короткий, щоб влазив у QR і в
// надруковану адресу), `utm_source` — бо посилання в рекламі Facebook і в
// розсилках приходить із ним, і людина, яка ставить допис, може взяти звичну
// для себе форму. Порядок = пріоритет.
const ПАРАМЕТРИ = ['from', 'utm_source'];

// 📐 Межі значення. Воно приходить із адреси, тобто з-поза застосунку, а далі
// йде в базу і в звіт — отже бути відкритим текстовим полем не має права.
// Дозволяємо тільки те, з чого складаються наші ж мітки (`bus-sticker`,
// `kostel`, `viber`, `fb-grupa`), і ріжемо до 32 знаків.
const ДОЗВОЛЕНО = /^[a-z0-9_-]{1,32}$/;

// Нормалізація: регістр і пробіли по краях — найчастіша розбіжність між тим, що
// надруковано на наліпці, і тим, що набрала рука. `Bus-Sticker` і `bus-sticker`
// мусять бути однією точкою, інакше звіт роздвоїться на дві половинки.
// ⚠️ Порожнє значення відсікаємо ДО `String()`: `String(null)` дає рядок
// `'null'`, а він пройшов би перевірку як цілком законна мітка — і в звіті
// зʼявилась би точка «null», якої ніде не існує.
function нормалізувати(сире) {
  if (сире === null || сире === undefined) return null;
  const v = String(сире).trim().toLowerCase();
  return ДОЗВОЛЕНО.test(v) ? v : null;
}

// Перший дотик із памʼяті пристрою.
export function sourceTag() {
  try {
    const v = localStorage.getItem(КЛЮЧ);
    return v && ДОЗВОЛЕНО.test(v) ? v : null;
  } catch (_) { return null; }
}

// Прибрати параметри з адреси, не зачепивши шлях і хеш.
// 🔑 `replaceState`, а не `pushState`: кнопка «назад» не має вести на ту саму
// сторінку з параметром — для людини це виглядало б як застрягання.
// ⚠️ Хеш зберігаємо обовʼязково: на ньому тримаються всі deep-link'и
// застосунку (`#/thread/<id>`, вкладки), і згубити його тут означало б
// ламати перехід зі сповіщення — рівно в заході, який ми ж і міряємо.
function прибратиЗАдреси() {
  try {
    if (!window.history || !history.replaceState) return;
    const u = new URL(window.location.href);
    let чіпали = false;
    for (const п of ПАРАМЕТРИ) {
      if (u.searchParams.has(п)) { u.searchParams.delete(п); чіпали = true; }
    }
    if (!чіпали) return;
    const запит = u.searchParams.toString();
    history.replaceState(null, '', u.pathname + (запит ? '?' + запит : '') + u.hash);
  } catch (_) { /* адреса — не та річ, за яку варто падати */ }
}

// Зняти джерело з адреси при заході. Кличеться ОДИН раз і РАНО — до
// `session_start`, інакше перша ж подія заходу пішла б без мітки, а саме вона
// і є «людина прийшла з наліпки».
//
// Повертає мітку (або `null`) — і для подій, і щоб стенд мав що перевіряти.
export function captureSource() {
  let мітка = null;
  try {
    const q = new URLSearchParams(window.location.search || '');
    for (const п of ПАРАМЕТРИ) {
      const v = нормалізувати(q.get(п));
      if (v) { мітка = v; break; }
    }
  } catch (_) {}

  прибратиЗАдреси();

  // 🛑 Нічого не зберігаємо, якщо статистика вимкнена (див. шапку файлу).
  if (!мітка || !analyticsEnabled()) return sourceTag();

  try {
    // Перший дотик виграє: уже є мітка — нову НЕ пишемо (див. шапку, рішення 2).
    if (!sourceTag()) localStorage.setItem(КЛЮЧ, мітка);
  } catch (_) {}

  return sourceTag();
}

// 🔎 Для стендів: прибрати запамʼятоване, щоб сцена починалась із чистого
// пристрою. У застосунку не кличеться ніде.
export function _forgetSource() {
  try { localStorage.removeItem(КЛЮЧ); } catch (_) {}
}
