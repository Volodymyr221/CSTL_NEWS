// 🗣️ ЗАМОВЛЕННЯ ВОВИ 19.09 (зі знімків): «зроби сторінку завантаження кожної
// сторінки в такому вигляді як сторінка, до прикладу стрічка зараз завантажується
// як список, а може так як елементи на стрічці… І так з кожною вкладкою треба
// зробити, взяти макет сторінки і створити сторінку завантаження».
//
// 🔴 ВІН МАЄ РАЦІЮ, І КОД САМ СЕБЕ ВИДАВАВ. У `screen-state.js` стояв коментар
// «Скелет повторює ФОРМУ того, що приїде (фото + три смужки), а не абстрактні
// прямокутники: інакше в момент появи даних розкладка сіпнеться». Намір
// правильний, виконання — ні: форма була ОДНА на всі екрани, «фото 64px ліворуч
// + три смужки». На Стрічку ж приїжджає карусель спільнот і картка з фото 4:5
// на всю ширину; на Автобуси — банер рейсу і рядки з часом. Тобто кістяк
// обіцяв не те, що приходило, і сіпав розкладку рівно тоді, коли мав її тримати.
// ➡️ Той самий клас вади, що вже двічі ловили в цьому проєкті: коментар описує
// намір, а не те, що код робить насправді.
//
// 📐 РОЗМІРИ ЗНЯТІ З ЖИВОГО DOM, не з голови: `tests/tools/skeleton-shapes.mjs`
// обходить вкладки із заглушкою і друкує дерево з розмірами. Заміряно 19.09:
// картка Дошки 366×125 · рядок Питання 358×165 · картка рейсу 390×110 · банер
// автобусів 362×168 · кільце Стрічки 62×62 у колонці 96px · картки Стрічки
// йдуть через 8px (`.fd-list` gap).
//
// 🛑 МЕЖА, ЯКУ ЛЕГКО ПЕРЕСТУПИТИ: кістяк малює лише ТЕ МІСЦЕ, КУДИ ПРИЙДУТЬ ДАНІ.
// Шапка Громади, смужка днів і пошук Автобусів малюються миттєво з коду, без
// мережі — домалювати їх іще й кістяком означало б показати людині ДВІ шапки.
// Виняток — кружечки спільнот на Стрічці: вони приходять із бази разом із
// дописами, тож вони частина очікування.
// ═════════════════════════════════════════════════════════════════════════════

const сірий = (клас) => `<div class="hm-sk ${клас}"></div>`;

// ── СТРІЧКА ───────────────────────────────────────────────────────────────
// Карусель спільнот + великі картки дописів. Чотири кільця — стільки влазить
// на 390px (колонка 96 + проміжок 18), далі край екрана.
function стрічка(карток = 2) {
  const кільце = `
    <div class="sk-circle" aria-hidden="true">
      ${сірий('sk-circle-ring')}
      ${сірий('sk-circle-cap')}
    </div>`;
  const картка = `
    <article class="sk-feed-card" aria-hidden="true">
      <div class="sk-feed-head">
        ${сірий('sk-feed-ava')}
        <div class="sk-feed-head-tx">
          ${сірий('sk-feed-name')}
          ${сірий('sk-feed-meta')}
        </div>
      </div>
      ${сірий('sk-feed-photo')}
      <div class="sk-feed-body">
        ${сірий('sk-feed-l1')}
        ${сірий('sk-feed-l2')}
        ${сірий('sk-feed-l3')}
      </div>
    </article>`;
  return `
    <div class="sk-circles" aria-hidden="true">${кільце.repeat(4)}</div>
    <div class="sk-feed">${картка.repeat(карток)}</div>`;
}

// ── ДОШКА ─────────────────────────────────────────────────────────────────
// Заголовок + пошук + оголошення: фото ліворуч, праворуч — пігулка категорії,
// назва, опис, ціна.
//
// 🔴 ЗАГОЛОВОК І ПОШУК ТУТ ТЕЖ ОБОВʼЯЗКОВІ — та сама причина, що в Автобусах, і
// я знайшов її лише коли подивився на знімок. `paintLoading` затирає корінь
// цілком, а `renderAll()` малює хром РАЗОМ зі списком. Тобто під час очікування
// хрому немає, і без нього список стрибав би вниз на висоту шапки в мить появи
// даних. 📐 Заміряно: `bd-hero` 44px + рядок пошуку 40px.
function дошка(карток = 3) {
  const картка = `
    <article class="sk-board-card" aria-hidden="true">
      ${сірий('sk-board-ph')}
      <div class="sk-board-body">
        ${сірий('sk-board-cat')}
        ${сірий('sk-board-title')}
        ${сірий('sk-board-desc')}
        ${сірий('sk-board-price')}
      </div>
    </article>`;
  return `
    <div class="sk-head" aria-hidden="true">
      ${сірий('sk-head-ttl')}
      ${сірий('sk-head-search')}
    </div>
    <div class="sk-board">${картка.repeat(карток)}</div>`;
}

// ── ПИТАННЯ ───────────────────────────────────────────────────────────────
// Рядок питання вищий за картку Дошки (165 проти 125) — бо під питанням стоїть
// рядок про відповіді. Без нього кістяк був би нижчим за правду, і список
// підстрибував би вгору при появі даних.
// 📐 Шапка тут вища за Дошкину: `qa-hero` 98px (заголовок + пояснення) + пошук
// 40px + рядок лічильника 18px — разом 156 проти 84.
function питання(рядків = 3) {
  const рядок = `
    <article class="sk-qa-row" aria-hidden="true">
      ${сірий('sk-qa-ava')}
      <div class="sk-qa-body">
        ${сірий('sk-qa-who')}
        ${сірий('sk-qa-q1')}
        ${сірий('sk-qa-q2')}
        ${сірий('sk-qa-foot')}
      </div>
    </article>`;
  return `
    <div class="sk-head sk-head--tall" aria-hidden="true">
      ${сірий('sk-head-ttl')}
      ${сірий('sk-head-note')}
      ${сірий('sk-head-search')}
      ${сірий('sk-head-count')}
    </div>
    <div class="sk-qa">${рядок.repeat(рядків)}</div>`;
}

// ── АВТОБУСИ ──────────────────────────────────────────────────────────────
// Смужка тижня + пошук + банер найближчого рейсу + рядки розкладу. Час ліворуч
// окремим блоком: саме він і є те, заради чого вкладку відкривають.
//
// 🔴 СМУЖКА І ПОШУК ТУТ НЕ ЗАЙВІ, І ЦЕ ВИПРАВЛЕННЯ МОГО Ж НЕДОГЛЯДУ.
// Перша редакція їх не малювала — я вважав, що вони стоять на екрані з коду, як
// шапка Громади. 📐 Перевірено знімком і виміром: `initBuses()` вставляє їх у
// ТОМУ Ж `innerHTML`, що й список, тобто ПІСЛЯ `fetch`. Під час завантаження їх
// немає взагалі, і без них розклад стрибав би вниз на 127px (смужка 67 + пошук
// 60) рівно в мить появи даних — те, від чого кістяк і рятує.
function автобуси(рейсів = 4) {
  const картка = `
    <div class="sk-bus-card" aria-hidden="true">
      ${сірий('sk-bus-time')}
      <div class="sk-bus-body">
        ${сірий('sk-bus-route')}
        ${сірий('sk-bus-note')}
      </div>
    </div>`;
  const день = `<div class="sk-bus-day" aria-hidden="true"></div>`;
  return `
    <div class="sk-bus-week" aria-hidden="true">${день.repeat(7)}</div>
    <div class="sk-bus-search" aria-hidden="true">
      ${сірий('sk-bus-field')}
      ${сірий('sk-bus-swap')}
      ${сірий('sk-bus-field')}
    </div>
    ${сірий('sk-bus-hero')}
    <div class="sk-bus-list">${картка.repeat(рейсів)}</div>`;
}

// ── ГРОМАДА ───────────────────────────────────────────────────────────────
// Віджети: заголовок і плитка вмісту. Шапку з погодою НЕ малюємо — вона вже
// стоїть на екрані до будь-якої мережі.
function громада(віджетів = 2) {
  const віджет = `
    <section class="sk-hm-widget" aria-hidden="true">
      ${сірий('sk-hm-ttl')}
      ${сірий('sk-hm-body')}
    </section>`;
  return `<div class="sk-hm">${віджет.repeat(віджетів)}</div>`;
}

const ФОРМИ = {
  feed:      стрічка,
  board:     дошка,
  questions: питання,
  buses:     автобуси,
  community: громада,
};

// Чи є в нас форма під цей екран. Питає `screen-state.js`, щоб не вгадувати.
export function hasShape(вид) {
  return Object.prototype.hasOwnProperty.call(ФОРМИ, вид);
}

// Кістяк під конкретний екран. Невідомий вид — порожній рядок, а не «щось
// схоже»: краще старий загальний кістяк, ніж форма чужого екрана.
export function shapeHtml(вид, скільки) {
  const f = ФОРМИ[вид];
  if (!f) return '';
  return скільки == null ? f() : f(скільки);
}
