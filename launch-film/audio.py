#!/usr/bin/env python3
# launch-film/audio.py — ЗВУКОВА ДОРІЖКА РОЛИКА, ЗІБРАНА З НУЛЯ.
#
# 🔴 ЧОМУ СИНТЕЗ, А НЕ ГОТОВИЙ ТРЕК. В оточенні немає ЖОДНОЇ бібліотеки музики:
# Freesound, YouTube Audio Library і моделі генерації вимагають або ключів, або
# мережі, яку тут закрито. Лишалось два шляхи — тиша або власний синтез.
# Тиша під тридцятисекундний ролик запуску гірша за скромну музику.
#
# 🔑 ЩО САМЕ ТУТ ГРАЄ. Мінімальна кінематографічна електроніка — саме те, що
# просив Вова: «Begin with near-silence… build the music toward 00:24. At 00:27
# introduce a short silence before logo reveal.» Це зроблено буквально:
#   0.0–3.0   майже тиша, лише низьке гудіння
#   3.0       перший подих — вступ кадру Олики
#   9.0       заходить пульс (80 ударів/хв)
#   12.0      рідкі ноти зверху
#   21.0→24.0 наростання: октава вгору, фільтр відкривається
#   26.6–27.0 ПОВНА ТИША перед знаком
#   27.0      низький удар і фінальний акорд
#
# 🛑 ЖОДНОГО ЗОВНІШНЬОГО СЕМПЛУ. Усе — сума синусів і відфільтрований шум, тож
# питання прав не виникає взагалі: доріжка наша від першого семпла.
#
# Запуск:  vendor/openmontage/.venv/bin/python launch-film/audio.py

import math
import struct
import wave
from pathlib import Path

import numpy as np

SR = 48_000          # частота дискретизації
DUR = 30.0           # секунд
N = int(SR * DUR)
t = np.arange(N, dtype=np.float64) / SR

ТУТ = Path(__file__).resolve().parent
OUT = ТУТ / "out"
OUT.mkdir(exist_ok=True)


# ── допоміжне ──────────────────────────────────────────────────────────────
def ramp(a, b, ease=True):
    """Обвідна 0→1 на відрізку [a,b]. З помʼякшенням — щоб не клацало."""
    x = np.clip((t - a) / max(b - a, 1e-9), 0.0, 1.0)
    return x * x * (3 - 2 * x) if ease else x


def seg(a, b):
    """Маска відрізка."""
    return ((t >= a) & (t < b)).astype(np.float64)


def sine(freq, phase=0.0):
    return np.sin(2 * math.pi * freq * t + phase)


def onepole_lp(x, cutoff):
    """Однополюсний ФНЧ. cutoff — масив або число (Гц).

    🔑 Фільтр із ЗМІННОЮ частотою зрізу потрібен саме для наростання: у
    мінімальній електроніці «стає гучніше» майже завжди означає «відкривається
    фільтр», а не «крутнули гучність». На слух це різні речі.
    """
    c = np.full(N, cutoff, dtype=np.float64) if np.isscalar(cutoff) else cutoff
    a = np.exp(-2 * math.pi * np.clip(c, 20, SR / 2 - 100) / SR)
    y = np.empty(N)
    prev = 0.0
    # Цикл на 1.44 млн кроків у чистому Python — кілька секунд. Прийнятно:
    # доріжка збирається один раз, а векторний варіант зі змінним коефіцієнтом
    # довелось би писати самому й ловити в ньому помилки.
    xa = x
    for i in range(N):
        prev = (1 - a[i]) * xa[i] + a[i] * prev
        y[i] = prev
    return y


def pluck(freq, at, dur=0.9, amp=0.2, detune=0.0):
    """Коротка нота з миттєвою атакою і довгим спадом."""
    m = seg(at, at + dur)
    local = np.where(m > 0, t - at, 0.0)
    env = np.exp(-local * (4.5 / dur)) * m
    # Друга гармоніка тихіша — так синус перестає бути «писком» і стає нотою.
    w = np.sin(2 * math.pi * freq * local) + 0.28 * np.sin(2 * math.pi * freq * 2 * local)
    if detune:
        w += 0.5 * np.sin(2 * math.pi * (freq * (1 + detune)) * local)
    return w * env * amp


def noise_burst(at, dur, amp, lp_from, lp_to, rev=False):
    """Шумовий сплеск: клац, свист, повітря."""
    rng = np.random.default_rng(int(at * 1000) & 0xFFFF)
    m = seg(at, at + dur)
    local = np.where(m > 0, (t - at) / dur, 0.0)
    env = (local if rev else (1 - local)) ** 2.2 * m
    nz = rng.standard_normal(N) * m
    # Дешева заміна фільтра зі змінним зрізом: два проходи ковзним середнім,
    # ширина яких зростає/спадає разом із обвідною.
    k_from, k_to = max(1, int(SR / lp_from)), max(1, int(SR / lp_to))
    k = int((k_from + k_to) / 2)
    if k > 1:
        kern = np.ones(k) / k
        nz = np.convolve(nz, kern, mode="same")
    return nz * env * amp


# ═══════════════════════════════════════════════════════════════════════════
# ШАРИ
# ═══════════════════════════════════════════════════════════════════════════
mix = np.zeros(N)

# ── 1. Низьке гудіння. Є від першого семпла до останнього. ─────────────────
# A1 = 55 Гц. Дуже тихе биття (55 і 55.14 Гц) дає повільну пульсацію — саме
# вона перетворює рівний тон на «атмосферу», не додаючи жодного інструмента.
drone = (sine(55.0) + 0.7 * sine(55.14) + 0.45 * sine(110.0) + 0.2 * sine(164.81))
drone_env = (
    0.10 * ramp(0.0, 2.2)
    + 0.10 * ramp(3.0, 4.4)
    + 0.09 * ramp(9.0, 12.0)
    + 0.10 * ramp(21.0, 24.0)
)
mix += drone * drone_env

# ── 2. Подушка (pad). Ля-мінор: A-C-E, з доданою квінтою. ──────────────────
pad = (
    0.55 * sine(220.00)            # A3
    + 0.40 * sine(261.63)          # C4
    + 0.34 * sine(329.63)          # E4
    + 0.18 * sine(440.00)          # A4
    + 0.10 * sine(659.25)          # E5 — зʼявиться лише коли відкриється фільтр
)
# Дуже повільне «дихання» — 0.07 Гц, тобто один цикл на 14 секунд.
pad *= 1 + 0.10 * np.sin(2 * math.pi * 0.07 * t)
pad_env = (
    0.055 * ramp(3.0, 5.2)
    + 0.045 * ramp(9.0, 12.5)
    + 0.075 * ramp(21.0, 24.0)
)
# Фільтр: закритий на початку (420 Гц), розкривається до 24-ї секунди (4200 Гц).
cut = 420 + 3800 * ramp(12.0, 24.0)
mix += onepole_lp(pad * pad_env, cut)

# ── 3. Пульс. 80 ударів/хв → 0.75 с. Заходить на 9-й секунді. ─────────────
# Це не барабан, а короткий низький синус із падінням висоти — той самий
# прийом, що в мінімальній електроніці замінює бочку й не відволікає.
BEAT = 60.0 / 80.0
beat_i = 0
tm = 9.0
while tm < 26.5:
    # Наростання гучності до 24-ї секунди, далі — обрив.
    a = 0.16 + 0.16 * min(1.0, max(0.0, (tm - 18.0) / 6.0))
    if tm > 24.0:
        a *= max(0.0, 1 - (tm - 24.0) / 2.4)
    d = 0.38
    m = seg(tm, tm + d)
    local = np.where(m > 0, t - tm, 0.0)
    env = np.exp(-local * 11.0) * m
    # Висота падає 88 → 46 Гц за перші 60 мс: саме це дає «удар», а не «гудок».
    f = 46 + 42 * np.exp(-local * 34.0)
    mix += np.sin(2 * math.pi * f * local) * env * a
    # Кожен четвертий удар — тихе повітря зверху, щоб ритм не був голим.
    if beat_i % 4 == 2 and tm > 12.0:
        mix += noise_burst(tm, 0.20, 0.016, 9000, 3000)
    beat_i += 1
    tm += BEAT

# ── 4. Рідкі ноти. Пентатоніка від ля-мінора — не буває фальшивою. ────────
НОТИ = {"A4": 440.00, "C5": 523.25, "D5": 587.33, "E5": 659.25, "G5": 783.99, "A5": 880.00}
МЕЛОДІЯ = [
    (12.30, "E5", 0.075), (13.05, "C5", 0.060), (13.95, "A4", 0.055),
    (15.30, "G5", 0.070), (16.05, "E5", 0.058), (16.95, "D5", 0.055),
    (18.30, "A5", 0.072), (19.05, "G5", 0.058), (19.80, "E5", 0.055),
    (21.30, "C5", 0.080), (21.90, "E5", 0.080), (22.50, "G5", 0.085),
    (23.10, "A5", 0.095), (23.55, "E5", 0.085),
]
for at, note, amp in МЕЛОДІЯ:
    mix += pluck(НОТИ[note], at, dur=1.3, amp=amp, detune=0.0015)

# ── 5. Звуки інтерфейсу. Рівно там, де щось відбувається в кадрі. ─────────
# 🔑 Клацання стоять НА СТИКАХ ЕКРАНІВ (12.2, 15.2, 18.2, 21.2) — тих самих,
# що прописані в `film.html`. Якщо посунеться монтаж, посунути й тут, інакше
# звук «відклеїться» від картинки, і це чути одразу.
for at in (12.20, 15.20, 18.20, 21.20):
    mix += noise_burst(at, 0.055, 0.055, 12000, 6000)     # клац
    mix += pluck(1760.0, at, dur=0.16, amp=0.020)          # тонкий призвук

# Свисти на великих переходах.
mix += noise_burst(2.78, 0.34, 0.048, 7000, 1400, rev=True)   # у жорсткий стик на 3.0
mix += noise_burst(5.72, 0.42, 0.055, 6000, 1200, rev=True)   # поява телефона
mix += noise_burst(23.70, 0.46, 0.050, 5000, 1100, rev=True)  # вихід на героя

# Капсули: чотири дрібні «тіки», по одному на кожну.
for at in (21.30, 21.68, 22.06, 22.44):
    mix += noise_burst(at, 0.045, 0.030, 14000, 7000)
    mix += pluck(2093.0, at, dur=0.12, amp=0.012)

# ── 6. ТИША 26.62–27.00, потім УДАР під знак. ────────────────────────────
# Замовлення: «At 00:27 introduce a short silence before logo reveal. Final
# logo gets a subtle low-frequency impact.» Тишу робимо ВИРІЗАННЯМ усього, що
# вже змікшовано: інакше хвости від пульсу й подушки її б затягнули.
# ⚠️ 26.40, а не 26.58. Перша редакція гасила з 26.58 до 26.90, і власна
# перевірка внизу одразу показала, що в «тиші» на 26.70 лишається 0.57 від
# піку — тобто тиші не було, був спад. Пауза перед знаком мусить бути ЧУТНОЮ,
# а чутна вона лише якщо встигла встановитись до початку вікна.
mix *= 1 - ramp(26.40, 26.66)

# Удар: 62 → 33 Гц, довгий спад. Плюс ледь чутний «видих» повітря.
at = 27.02
m = seg(at, at + 2.6)
local = np.where(m > 0, t - at, 0.0)
f = 33 + 29 * np.exp(-local * 12.0)
mix += np.sin(2 * math.pi * f * local) * np.exp(-local * 2.1) * m * 0.42
mix += noise_burst(26.94, 0.30, 0.030, 4000, 900, rev=True)

# Фінальний акорд — той самий ля-мінор, тихо, під титри.
fin = (0.5 * sine(110.0) + 0.42 * sine(220.0) + 0.30 * sine(329.63) + 0.16 * sine(440.0))
fin_env = 0.085 * ramp(27.05, 27.9) * (1 - ramp(29.2, 30.0))
mix += fin * fin_env

# ── 7. Загальний спад у кінці, щоб не обривалось на півслові ─────────────
mix *= 1 - ramp(29.45, 30.0)
# І плавний вхід — перші 120 мс з нуля, інакше на старті клацне.
mix *= ramp(0.0, 0.12, ease=False)


# ═══════════════════════════════════════════════════════════════════════════
# ЗВЕДЕННЯ
# ═══════════════════════════════════════════════════════════════════════════
# Мʼяке обмеження (tanh) замість жорсткого зрізу: зріз дає хрускіт саме на
# низьких частотах, яких тут найбільше.
peak = float(np.max(np.abs(mix)))
if peak > 0:
    mix = mix / peak * 0.92
mix = np.tanh(mix * 1.18) / math.tanh(1.18)
mix *= 0.89                                    # запас до 0 dBFS

# Стерео: подушка й ноти трохи розведені, низ — строго в центрі.
# Розведення роблять затримкою на 9 семплів (~0.19 мс) — на слух це ширина,
# а не відлуння, і при зведенні в моно нічого не зникає.
# 🔑 Розводимо ЛИШЕ верх (вище 200 Гц). Низ лишається строго по центру —
# інакше на телефонному динаміку й у навушниках бас «пливе» між каналами.
hi = mix - onepole_lp(mix, 200.0)
left = mix + 0.13 * hi
right = mix - 0.13 * hi

stereo = np.stack([left, right], axis=1)
stereo = np.clip(stereo, -1.0, 1.0)
pcm = (stereo * 32767).astype("<i2")

шлях = OUT / "cstl-life-30s.wav"
with wave.open(str(шлях), "wb") as w:
    w.setnchannels(2)
    w.setsampwidth(2)
    w.setframerate(SR)
    w.writeframes(pcm.tobytes())

rms = float(np.sqrt(np.mean(mix ** 2)))
print(f"✅ {шлях}")
print(f"   {DUR:.0f} с · {SR} Гц · стерео · пік {float(np.max(np.abs(stereo))):.3f} · RMS {rms:.4f}")
# 🔬 Самоперевірка на ГОТОВІЙ доріжці, а не на проміжному міксі: саме вона
# спіймала, що пауза перед знаком не була паузою.
тиша = stereo[int(26.70 * SR):int(27.00 * SR)]
пік_тиші = float(np.max(np.abs(тиша)))
print(f"   пауза 26.70–27.00: пік {пік_тиші:.5f}")
if пік_тиші > 0.02:
    raise SystemExit(f"❌ Паузи перед знаком НЕМАЄ: пік {пік_тиші:.4f} > 0.02")
удар = stereo[int(27.00 * SR):int(27.60 * SR)]
print(f"   удар 27.00–27.60: пік {float(np.max(np.abs(удар))):.3f} (має бути помітно більший)")
