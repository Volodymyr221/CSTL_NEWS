const { execSync } = require('child_process');

try {
  execSync('node scripts/check-imports.js', { stdio: 'inherit' });
} catch (e) {
  console.error('\n❌ check-imports.js знайшов проблеми. Виправ перш ніж build.\n');
  process.exit(1);
}

// 🔴 19.08 — ПУБЛІЧНА СТОРІНКА ПОЛІТИКИ. Google Play вимагає посилання на політику
// конфіденційності, яке відкривається ЗЗОВНІ застосунку, а в нас вона жила лише в
// модалці. `privacy.html` генерується з того самого `src/core/legal.js`, тож копії
// тексту не існує і розійтись нема чому.
// ⚠️ Стоїть у збірці, а не запускається руками: сторінка, яку треба не забути
// перегенерувати, рано чи пізно відстане від документа, під яким люди дали згоду.
try {
  // `--disable-warning` точковий, а не `--no-warnings`: Node попереджає, що
  // `src/core/legal.js` не має `"type": "module"` у package.json. Поставити його
  // не можна — тоді зламається сам `build.js` (він на `require`). Попередження
  // безпечне, але засмічує журнал збірки, а засмічений журнал ховає справжні.
  execSync('node --disable-warning=MODULE_TYPELESS_PACKAGE_JSON scripts/gen_privacy.mjs',
           { stdio: 'inherit' });
} catch (e) {
  console.error('\n❌ gen_privacy.mjs не зміг згенерувати privacy.html.\n');
  process.exit(1);
}

// 🔴 16.08 — `minify: true`. Стояло `false`, і `bundle.js` важив 957 КБ сирого
// тексту — з коментарями, відступами й довгими іменами. Це найважчий файл, який
// телефон качає при КОЖНОМУ деплої (`CACHE_NAME` міняється щоразу), а аудиторія
// сидить на мобільному інтернеті.
// ⚠️ `sourcemap: true` лишається: мапа дозволяє читати помилки з проду по іменах
// вихідних файлів, а браузер її НЕ качає, поки не відкрито devtools.
// 🛑 Формат `iife` і точка входу не змінені — мініфікація не міняє поведінку коду,
//    лише його запис.
// 🔴 24.09 — СТИЛІ ТЕПЕР ТЕЖ ЗБИРАЮТЬСЯ. Досі мініфікувався лише JS, а 24 файли
// CSS їхали на телефон СИРИМИ, з усіма коментарями. Заміряно перед правкою
// (`node tests/css-build-parity.mjs` міряє те саме й досі):
//   24 файли, 1.23 МБ сирого тексту → 385 КБ gzip сумарно
//   складені в один файл, без мініфікації → 57 КБ gzip
//   складені й мініфіковані                → 52 КБ gzip
// ⚠️ ЧЕСНО ПРО АТРИБУЦІЮ: майже весь виграш дає не мініфікація, а сама збірка,
// бо esbuild викидає коментарі (їх тут ~900 КБ — шість із кожних семи
// кілобайтів стилів були поясненнями для розробника). Мініфікація зверху
// додає лише 57 → 52 КБ. Не плутати одне з одним у звітах.
//
// 🔑 ДРУГИЙ ВИГРАШ — І ВІН ГОЛОВНИЙ. `style.css` це ланцюг із 23 `@import`, а про
// них браузер дізнається лише ПРОЧИТАВШИ його. Тобто перед першим малюванням
// стояло два послідовних походи в мережу замість одного. Збірка склеює їх у
// файл, і ланцюга більше немає.
//
// 🛑 ЧОМУ ЦЕ БЕЗПЕЧНО ДЛЯ КАСКАДУ. `@import` за стандартом рівносильний вставці
// вмісту в тому самому місці, а esbuild саме вставляє — у порядку імпортів,
// не переставляючи. Тобто правило «board.css одразу після community.css, і ніде
// інде» (воно живе в `style.css` і доведене зліпком на 224 елементах) лишається
// чинним: порядок задає `style.css`, а не збірка.
// ⚠️ І все одно це перевірено НАСЛІДКОМ, а не міркуванням:
// `tests/tools/css-snapshot.mjs` зняв обчислені стилі 197 елементів до і після.
//
// ⚠️ ДЖЕРЕЛА НЕ ЧІПАЄМО. `style/*.css` лишаються з коментарями — вони й є
// документація каскаду. Мініфікується тільки те, що їде людям.
// 🔴 `style.min.css` — ГЕНЕРОВАНИЙ. Правити його руками не можна (правило
// проєкту: генероване не зводять, перегенеровують).
require('esbuild').buildSync({
  entryPoints: ['style.css'],
  bundle: true,
  outfile: 'style.min.css',
  minify: true,
  // Та сама причина, що й у JS нижче: інтерфейс україномовний, і без цього
  // кожна кирилична літера в `content:` займала б 6 байт замість 2.
  charset: 'utf8',
  // ⚠️ `loader: { '.css': 'css' }` не потрібен, а от зовнішні посилання —
  // так: у стилях є `url(...)` на іконки й шрифти, і їх не можна вшивати в
  // файл. `external` лишає їх як є.
  external: ['*.png', '*.jpg', '*.svg', '*.woff', '*.woff2', '*.gif', '*.webp'],
});

require('esbuild').buildSync({
  entryPoints: ['src/app.js'],
  bundle: true,
  outfile: 'bundle.js',
  format: 'iife',
  minify: true,
  // 🔴 16.08 — `charset: 'utf8'`. За замовчуванням esbuild ескейпить кожен
  // не-ASCII символ у `\uXXXX`, тобто КОЖНА українська літера займає 6 байт
  // замість 2. А в цьому застосунку українською написаний весь інтерфейс —
  // сотні рядків підписів, тостів і пояснень. Заміряно: 655 → 545 КБ, мінус 110 КБ
  // на порожньому місці.
  // ⚠️ Безпечно тому, що сторінка і так віддається як UTF-8 (`<meta charset>` у
  //    `index.html`), а GitHub Pages ставить `charset=utf-8` у заголовку JS.
  charset: 'utf8',
  sourcemap: true,
});
