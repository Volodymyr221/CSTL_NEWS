#!/usr/bin/env python3
"""Ділить `data/articles.json` на легкий список і окремий текст статей.

🔴 ЗАРАДИ ЧОГО (22.09.2026). У ніч, коли ліг шар даних Supabase, Вова спитав:
«Чому додаток так довго став завантажувати вкладки?» Поки розбирався, заміряв
вагу того, що застосунок тягне на кожне відкриття:

    data/articles.json   1.8 МБ      ← і з них `content` = 1.38 МБ (78% ваги)
    data/schedule.json   673 КБ
    bundle.js            650 КБ

⚠️ Перший мій замір дав «858 КБ» — я рахував СИМВОЛИ, а кирилиця в UTF-8 важить
два байти. У байтах, тобто в тому, що реально їде по мережі, це 1.38 МБ.

`content` — повний текст статті. Його показує РІВНО ОДИН екран: читання статті
(`renderArticleBody` у `src/tabs/news.js`). Списку новин, віджету Громади,
значкам і фільтрам він не потрібен ЖОДНОГО разу. Тобто чотири з пʼяти мегабайт
на старті качались для екрана, на який більшість навіть не заходить.

🔑 ЧОМУ ПОДІЛ ТУТ, А НЕ В ПАРСЕРІ. `data/articles.json` пишуть ДВА процеси —
`parse_rss.py` і `sync_cms.py`, кожен зі свого знімка (через це в проєкті й
зʼявився `CMS_ID_BASE`). Навчити обох тримати ще й другий файл у злагоді
означало б завести другу пару джерел правди, які неминуче розійдуться.
➡️ Тому в git лишається ОДИН файл, як і був, а поділ робиться при складанні
сайту — над готовим артефактом. Ламається — прибрав крок, і все як було.

📐 Заміряно на живому файлі: список **1844 КБ → 457 КБ, легше вчетверо**.

🛑 ПОДІЛ БЕЗ ВТРАТ, і це перевіряється: `tests/articles-split.mjs` склеює обидва
файли назад і вимагає побайтової рівності з оригіналом. Якість тексту не може
постраждати від переїзду, бо жоден символ не викидається.

🛑 ЗАПОБІЖНИК ВІД САМОГО СЕБЕ. Скрипт переписує `data/articles.json` НА МІСЦІ.
Запустив його хтось у своїй теці, зробив `git add -A` — і текст усіх статей
зник із ДЖЕРЕЛА ПРАВДИ, тихо й назавжди. Той самий клас, що «`cat >` мовчки
затирає» в гарячих правилах. Тому без явного `--деплой` скрипт нічого не робить.

Використання:
    python3 scripts/split_articles.py --деплой [тека]
"""
import json
import sys
from pathlib import Path

ПОЛЕ = "content"


def поділити(статті: list) -> tuple[list, dict]:
    """Віддає (легкий список, мапа id → текст). Порядок статей не чіпається."""
    легкі, тексти = [], {}
    for стаття in статті:
        копія = dict(стаття)
        текст = копія.pop(ПОЛЕ, None)
        # 🔑 Ключ — рядок: JSON однаково зробить його рядком, і краще щоб код
        # по обидва боки бачив те саме, ніж покладався на мовчазне перетворення.
        if текст is not None:
            тексти[str(копія.get("id"))] = текст
        легкі.append(копія)
    return легкі, тексти


def склеїти(легкі: list, тексти: dict) -> list:
    """Зворотна дія — нею стенд доводить, що поділ нічого не загубив."""
    назад = []
    for стаття in легкі:
        копія = dict(стаття)
        текст = тексти.get(str(копія.get("id")))
        if текст is not None:
            копія[ПОЛЕ] = текст
        назад.append(копія)
    return назад


def main() -> int:
    прапорці = [a for a in sys.argv[1:] if a.startswith("--")]
    решта = [a for a in sys.argv[1:] if not a.startswith("--")]
    if "--деплой" not in прапорці:
        print("🛑 Цей скрипт ПЕРЕПИСУЄ data/articles.json на місці — тобто витирає")
        print("   поле `content` із джерела правди. У репозиторії воно мусить бути.")
        print("   Місце цієї дії — складання сайту, і тільки воно:")
        print("       python3 scripts/split_articles.py --деплой")
        return 1

    корінь = Path(решта[0] if решта else ".")
    джерело = корінь / "data" / "articles.json"
    if not джерело.exists():
        print(f"⚠ {джерело} немає — ділити нічого, лишаю як є")
        return 0

    сирі = json.loads(джерело.read_text(encoding="utf-8"))
    if not isinstance(сирі, list):
        # 🛑 Не здогадуємось про формат: несподіванка краще лишиться нерозділеною,
        # ніж мовчки поїде на сайт покаліченою.
        print("⚠ articles.json не масив — не чіпаю")
        return 0

    легкі, тексти = поділити(сирі)
    ціль_список = джерело
    ціль_текст = корінь / "data" / "articles-text.json"

    було = len(джерело.read_bytes())
    ціль_список.write_text(json.dumps(легкі, ensure_ascii=False, indent=2), encoding="utf-8")
    ціль_текст.write_text(json.dumps(тексти, ensure_ascii=False), encoding="utf-8")
    стало = len(ціль_список.read_bytes())
    текстом = len(ціль_текст.read_bytes())

    print(f"✂️  статей {len(сирі)} · з текстом {len(тексти)}")
    print(f"   список: {було/1024:.0f} КБ → {стало/1024:.0f} КБ "
          f"(легше в {було/max(стало,1):.1f} рази)")
    print(f"   тексти: {текстом/1024:.0f} КБ — качаються, лише коли відкривають статтю")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
