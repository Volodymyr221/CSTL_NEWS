def fetch_ready():
    """Готові статті ДЛЯ НОВИН — тобто ті, чий маршрут не веде у спільноту."""
    return [r for r in _готові() if маршрут(r) is None]


def fetch_ready_pages():
    """Готові статті ДЛЯ СПІЛЬНОТ — ті самі рядки, що їх відсіює `fetch_ready`."""
    return [r for r in _готові() if маршрут(r) is not None]


def стаття_у_пост(row) -> str:
    """Стаття кабінету → текст допису спільноти.

    🔑 Рішення Вови 28.08: «Це не має бути стаття, це має бути пост як в інстаграмі
    чи в фейсбуці». Тому ні розмітки, ні «читати далі» — заголовок першим рядком,
    далі текст.
    ⚠️ Заголовок НЕ викидаємо: у стрічці він читається як перший рядок допису, а
    без нього губиться те, чим допис назвали.
    🔴 03.09 уточнено двічі: заголовок пишемо ВЕЛИКИМИ (у дописі немає поля
    заголовка), а тіло чистимо від розмітки — припущення «content у кабінеті вже
    простий текст» справджувалось лише для статей агента, не для статей із джерел.
    """
    заголовок = (row.get("title") or "").strip()
    # 🔴 03.09 — ТІЛО ЧИСТИМО ВІД РОЗМІТКИ. Заміряно на кабінеті: у статей із
    # джерел (id 36, 38, 44) `content` приходить із `<p>` та `<a href>`, а допис
    # у стрічці малюється як звичайний текст — тобто людина побачила б теги
    # замість статті. `strip_html` — той самий, яким чистить парсер.
    # ⚠️ `strip_html` міняє теги на пробіл, тому кожен абзац після першого
    # починався з пробілу (заміряно на статті id=44). Прибираємо порядково.
    тіло = "\n".join(р.strip() for р in pr.strip_html(row.get("content") or "").split("\n")).strip()
    if not заголовок:
        return тіло
    # 🔑 ЗАГОЛОВОК — ВЕЛИКИМИ. Пряме формулювання Вови 03.09: «заголовку в постах,
    # у стрічці, немає, тому потрібно писати його великими буквами, але як
    # звичайний пост». Це не окраса: великі літери — єдине, чим у дописі без поля
    # заголовка видно, де заголовок.
    великими = заголовок.upper()
    # 🛑 Знімаємо повтор ЛИШЕ якщо заголовок займає ВЕСЬ перший рядок тіла.
    # Перевірка «тіло починається із заголовка» ріже живий текст: у статті
    # «Личани» тіло починається словом «Личани — село…», і від нього лишався
    # обрубок «— село Олицької громади». Заміряно на смоуку 03.09.
    перший, _, решта = тіло.partition("\n")
    if перший.strip().lower() == заголовок.lower():
        тіло = решта.lstrip()
    return f"{великими}\n\n{тіло}" if тіло else великими


def фото_статті(row) -> list:
    """Усі фото статті по порядку: обкладинка, далі знімки з тіла, без повторів.

    🗣️ Вова 03.09: «якщо там є фотографії, то фотографії в карусель пустити».
    📐 Заміряно того ж дня на всіх 47 рядках кабінету: `<img>` у тілі немає в
    жодному — сьогодні фото рівно одне на статтю. Карусель від цього не зайва:
    `page_posts.image_urls` уже масив, тож щойно у статті зʼявиться друге фото,
    воно поїде в карусель саме собою, а не після ще однієї правки синку.
    """
    зібрані, бачені = [], set()
    з_тіла = re.findall(r"<img[^>]+src=[\"']([^\"']+)", row.get("content") or "", re.I)
    for u in [row.get("image")] + з_тіла:
        u = (u or "").strip()
        if u and u not in бачені:
            бачені.add(u)
            зібрані.append(u)
    return зібрані


def публікувати_в_спільноту(row, page_id=None) -> bool:
    """Кладе статтю кабінету у стрічку спільноти ОПУБЛІКОВАНИМ дописом.

    🔑 Саме `published`, а не `draft`. Чернетку кладе АГЕНТ (він пише сам, і його
    треба перечитати перед показом). А сюди стаття приходить із кабінету, де
    людина вже натиснула «Публікувати» — просити її схвалити те саме вдруге
    означало б, що кнопка збрехала.
    """
    row_id = row.get("id")
    # 🛑 Сторінку беремо з маршруту, а не з константи: із 03.09 їх може бути
    # скільки завгодно, і «історія» — лише один із випадків.
    сторінка = page_id if page_id is not None else маршрут(row)
    if not сторінка:
        print(f"⚠ id={row_id}: маршрут не веде у спільноту — пропускаю")
        return False
    тіло = стаття_у_пост(row)
    if not тіло:
        print(f"⚠ id={row_id}: порожній текст — пропускаю")
        return False
    пост = {
        "page_id": сторінка,
        "text": тіло,
        "status": "published",
        "show_author": False,
        "author_uid": None,
    }
    фото = фото_статті(row)
    if фото:
        пост["image_url"] = фото[0]
        пост["image_urls"] = фото
    try:
        req = urllib.request.Request(
            PAGE_POSTS,
            data=json.dumps(пост).encode("utf-8"),
            headers={
                "apikey": SERVICE_KEY,
                "Authorization": "Bearer " + SERVICE_KEY,
                "Content-Type": "application/json",
                "Prefer": "return=representation",
            },
            method="POST",
        )
        with urllib.request.urlopen(req, timeout=30) as r:
            створено = json.loads(r.read().decode("utf-8") or "[]")
    except Exception as e:
        print(f"⚠ id={row_id}: не поклалась у спільноту {сторінка} — {e}")
        return False
    новий = (створено[0] or {}).get("id") if створено else None
    # 🛑 Позначаємо ТІЛЬКИ після того, як пост справді створено. Порядок тут той
    # самий урок, що й у `позначити_доїхалі`: спершу наслідок, потім статус —
    # інакше база рапортує про публікацію, якої не сталося.
    mark_published(row_id, None)
    print(f"🏛 стаття id={row_id} → допис спільноти {сторінка} (page_post id={новий})")
    return True


def sync_pages():
    """Статті з маршрутом у спільноту → дописи в її стрічці. Новин не торкається."""
    рядки = fetch_ready_pages()
    if not рядки:
        return 0
    print(f"🏛 статей до спільнот: {len(рядки)}")
    return sum(1 for row in рядки if публікувати_в_спільноту(row, маршрут(row)))


def mark_published(row_id, git_id):
    body = {
        "status": "published",
        "git_id": git_id,
        "published_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }
    _req("PATCH", REST + "?id=eq.%s" % row_id, body)


def promote_scheduled():
    """Автопостинг: заплановані статті, яким настав час (publish_at<=now),
    переводимо scheduled→ready. Далі їх публікує звичайний потік синку."""
    now = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    url = REST + "?status=eq.scheduled&publish_at=lte." + now
    try:
        _req("PATCH", url, {"status": "ready"})
        print(f"⏰ автопостинг: заплановані з часом <= {now} → ready")
    except Exception as e:
        print(f"⚠ promote_scheduled: {e}")


def heal_phantom_drafts():
    """Само-лікування «фантомних чернеток»: рядок зі status='draft', але з git_id —
    стаття ВЖЕ викладена у стрічку (git), а потім щось повернуло статус у чернетки
    (старий баг: редагування опублікованої деградувало статус; закрито у PR #258,
    але такі рядки лишились). Стрічка статтю тримає далі, тож чесний статус —
    published: закриваємо, щоб не займав слот AI-агента і не плутав редактора.
    Легальні чернетки (git_id IS NULL — ще не публікувались) не чіпаємо."""
    url = REST + "?status=eq.draft&git_id=not.is.null&select=id,title"
    headers = {"apikey": SERVICE_KEY, "Authorization": "Bearer " + SERVICE_KEY}
    try:
        req = urllib.request.Request(url, headers=headers)
        with urllib.request.urlopen(req, timeout=20) as r:
            rows = json.loads(r.read() or "[]")
        for row in rows:
            _req("PATCH", REST + "?id=eq.%s" % row["id"], {"status": "published"})
            print(f"🩹 фантомну чернетку закрито як published: id={row['id']} «{(row.get('title') or '')[:60]}»")
    except Exception as e:
        print(f"⚠ heal_phantom_drafts: {e}")


