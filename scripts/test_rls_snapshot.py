#!/usr/bin/env python3
"""Сторож зліпка RLS: файл `scripts/RLS_SNAPSHOT.md` не має мовчки старіти.

НАВІЩО. RLS — єдиний рубіж захисту даних у цьому проєкті (свого бекенду немає,
ключ у `bundle.js` публічний за призначенням). До 13.08 політики жили ТІЛЬКИ в
базі: аудит по коду був неможливий, зміну політики не побачив би жоден код-рев'ю,
а після збою відновлювати не було з чого.

🔑 ЩО САМЕ МІРЯЄ. Не «чи правильні політики» — цього з файлу не видно. Міряє
ЦІЛІСНІСТЬ ЗЛІПКА: що він на місці, що в ньому названо стільки політик, скільки
було на момент вивантаження, і що не загубились рядки про найчутливіші таблиці.
Розходження з живою базою ловить не цей стенд, а людина, яка перезніме зліпок
запитом із шапки файлу.

⚠️ ЧОМУ НЕ ХОДИМО В БАЗУ ЗВІДСИ. Стенди проєкту запускаються в CI і локально, без
секретів Supabase. Стенд, який мовчки «зеленіє» через відсутність доступу, гірший
за відсутність стенда — у проєкті вже було кілька таких випадків. Тому перевіряємо
рівно те, що можна перевірити чесно: сам файл.

Запуск: python3 scripts/test_rls_snapshot.py
"""
import os
import re
import sys

КОРІНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ШЛЯХ = os.path.join(КОРІНЬ, "scripts", "RLS_SNAPSHOT.md")

ok_count = fail_count = 0


def ok(name, cond, detail=""):
    global ok_count, fail_count
    if cond:
        ok_count += 1
        print(f"✅ {name}" + (f"  — {detail}" if detail else ""))
    else:
        fail_count += 1
        print(f"❌ {name}" + (f"  — {detail}" if detail else ""))


print("🧪 test_rls_snapshot — зліпок політик доступу\n")

ok("зліпок існує", os.path.exists(ШЛЯХ), ШЛЯХ)
if not os.path.exists(ШЛЯХ):
    sys.exit(1)

текст = open(ШЛЯХ, encoding="utf-8").read()

# Кількість політик названа в самому файлі — і має збігатися з тим, скільки
# рядків у блоці. Розійдеться — значить хтось дописав політику, не поправивши
# підсумок, і зліпку більше не можна вірити на слово.
m = re.search(r"Разом на [\d.]+: (\d+) політик", текст)
ok("у файлі названо підсумкове число політик", bool(m), m.group(1) if m else "не знайдено")

блок = re.search(r"```\n(ad_events.*?)\n```", текст, re.S)
ok("блок зі списком політик на місці", bool(блок))

if блок:
    рядки = [r for r in блок.group(1).splitlines() if r.strip() and "|" in r]
    ok("у списку є рядки", len(рядки) > 40, f"{len(рядки)} рядків")

# 🔴 Найчутливіші таблиці мають бути у зліпку ПОІМЕННО. Якщо колись хтось
# перезніме зліпок і загубить їх — це найдорожча втрата: саме тут приватність.
for таблиця, чому in [
    ("threads",            "приватні розмови"),
    ("messages",           "тексти листування"),
    ("profiles",           "персональні дані"),
    ("app_secrets",        "секрети серверних функцій"),
    ("admins",             "права адміністратора"),
    ("push_subscriptions", "ключі push і маршрути поїздок"),
]:
    ok(f"у зліпку є «{таблиця}» ({чому})", таблиця in текст)

# ⚠️ Урок аудиту, записаний у файлі: `qual = true` без погляду на ролі читається
# як «доступно всім» і дає ХИБНУ тривогу. Попередження має лишатись у файлі.
ok("🔴 у файлі лишилось попередження про `qual = true` і ролі",
   "qual = true" in текст and "service_role" in текст,
   "інакше наступний аудит знову «знайде» неіснуючий витік")

ok("описано, як перезняти зліпок", "pg_policies" in текст)

print()
if fail_count:
    print(f"❌ {ok_count}/{ok_count + fail_count} перевірок пройдено")
    sys.exit(1)
print(f"✅ {ok_count}/{ok_count} перевірок пройдено")
