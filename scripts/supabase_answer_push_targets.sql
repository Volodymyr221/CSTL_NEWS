-- 🔴 НАВІЩО ОКРЕМА ТАБЛИЦЯ, КОЛИ ВЖЕ Є `answer_push_log`.
-- Наявний журнал пише «про цю відповідь сповіщення надсилалось» — і цього
-- досить для ідемпотентності (не надіслати двічі про той самий коментар). Але
-- він НЕ знає, КОМУ саме надсилали. А без цього неможливі дві речі, які замовив
-- Вова:
--   1) вікно тиші НА ЛЮДИНУ, а не на пост. Тип 3 («відповіли на питання, яке
--      вас цікавить») має свій ритм (30 хв), і рахувати його по журналу постів
--      означало б: автору щойно надіслали — отже всі підписники мовчать;
--   2) число пропущеного («ще 4 відповіді на ваше питання», крок А2). Щоб
--      сказати «4», треба знати, коли ЦІЙ людині писали востаннє.
--
-- 🛑 Тому тут пишуться ВСІ ТРИ типи, хоча читає поки лише третій. Це не запас
-- «про всяк випадок»: без записів типів 1-2 крок А2 не матиме з чого рахувати
-- число для автора питання, і його довелось би чекати ще один цикл даних.
--
-- ⚠️ Таблиця СЛУЖБОВА: RLS увімкнено, політик НЕМАЄ жодної — рівно як у
-- `answer_push_log`. Отже дістатись до неї може лише `service_role` (Edge
-- Function), а житель, редактор і гість не бачать нічого. Це важливо: рядки
-- кажуть, ХТО чим цікавиться, і це персональні дані.

create table if not exists public.answer_push_targets (
  comment_id  bigint      not null references public.comments(id) on delete cascade,
  uid         uuid        not null,
  post_id     bigint      not null,
  -- 'reply'    — тобі відповіли особисто
  -- 'owner'    — відповідь під твоїм записом
  -- 'interest' — відповідь у питанні, яке ти позначив «Мене теж цікавить»
  kind        text        not null,
  created_at  timestamptz not null default now(),
  primary key (comment_id, uid)
);

-- Головний запит функції: «чи писали цій людині під цим постом останнім часом».
-- Саме в такому порядку колонок — фільтр іде по (uid, post_id), сортування по часу.
create index if not exists answer_push_targets_recent
  on public.answer_push_targets (uid, post_id, created_at desc);

alter table public.answer_push_targets enable row level security;
-- Політик немає навмисно — доступ лише service_role (див. пояснення вище).

