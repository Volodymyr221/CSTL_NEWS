-- 🔴 ЗАРАДИ ЧОГО. Курс (`KURS.md`) стоїть на двох речах, і друга — живі
-- спільноти з живими адмінами: 🗣️ «для них важливо те, щоб вони бачили що це не
-- дарма, що їх читають». Події читання застосунок пише з 21.09
-- (`content_open` / `content_seen`), згортання по днях стоїть у розкладі — але
-- ПОКАЗУ авторові не було. Аудит 30.09 назвав це найдешевшим засобом утримання
-- адмінів з усього плану: без нього на старті адмін бачить нуль лайків,
-- вирішує «мене ніхто не читає» і кидає писати саме тоді, коли його вже читають.
