-- ═════════════════════════════════════════════════════════════════════════════
-- 🛑 ЧОМУ ЦЯ ФУНКЦІЯ РАХУЄ СИРІ ПОДІЇ, А НЕ ГОТОВИЙ ПІДСУМОК
-- `content_views_daily` лежить поруч і виглядає як очевидне джерело — але
-- підсумок там по ДНЯХ, тобто `людей` це унікальні читачі ЗА ДЕНЬ. Сума по
-- днях не є числом людей: хто прочитав допис у вівторок і перечитав у
-- четвер, увійде двічі, і число поїде ВГОРУ.
-- 🔑 А саме на цьому числі адмін вирішує, писати йому далі. Завищене число
-- гірше за відсутнє (`HOT_RULES.md` №12) — тим паче тут, де воно підлещує.
-- ➡️ Тому рахуємо `COUNT(DISTINCT читач)` по сирих подіях. Вони живуть 90 днів
-- (`rollup_content_views` прибирає старші), і для допису Стрічки це практично
-- все його життя: читають у перші дні, не на четвертому місяці.
-- ⚠️ ЧЕСНА МЕЖА, ЯКУ ТРЕБА ЗНАТИ: допис, старший за 90 днів, покаже меншe,
-- ніж було насправді. Це свідомий вибір — применшити старе, але ніколи не
-- завищити свіже. Складати сире з підсумком не можна: ті самі люди порахувались
-- би двічі, і ми отримали б найгірший із варіантів.
-- ═════════════════════════════════════════════════════════════════════════════
--
-- 🔑 ОДНА ЛЮДИНА = ОДИН АКАУНТ, ГІСТЬ = ОДИН ПРИСТРІЙ. Той самий вираз, що в
-- `rollup_content_views` і в `admin_analytics_overview`: розходитись із рештою
-- аналітики не можна, два різні «унікальні» в одному кабінеті вже коштували
-- окремого розслідування 26.08.
--
-- 🛑 ЧИСЛО, НІКОЛИ ІМЕНА. Функція віддає лише кількості. Олика це містечко, де
-- всі одне одного знають, і «прочитав Сергій» відлякує сильніше, ніж допомагає
-- (те саме правило, що тримає капсули).

CREATE OR REPLACE FUNCTION post_read_counts(p_ids BIGINT[])
RETURNS TABLE (post_id BIGINT, людей INTEGER)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  WITH мої AS (
    -- 🔴 СТОРОЖА ПРАВ — У САМОМУ ЗАПИТІ, А НЕ ОКРЕМОЮ ПЕРЕВІРКОЮ ЗВЕРХУ.
    -- Функція `SECURITY DEFINER`, тобто працює з правами власника і RLS їй не
    -- указ. Якби вона рахувала все, що попросили, будь-хто ввійшлий дізнався б
    -- число по ЧУЖОМУ допису простим викликом RPC. Тому список одразу
    -- звужується до дописів, на які той, хто питає, має право.
    -- 🔑 Право те саме, яким малюється меню «⋯» у Стрічці: автор допису АБО
    -- команда сторінки (`page_admins`). Розходитись із клієнтом тут не можна —
    -- інакше кнопка є, а число не приходить, і це читалось би як поломка.
    SELECT pp.id
      FROM page_posts pp
     WHERE pp.id = ANY(p_ids)
       AND (
         pp.author_uid = auth.uid()
         OR EXISTS (SELECT 1 FROM page_admins pa
                     WHERE pa.page_id = pp.page_id AND pa.uid = auth.uid())
       )
  )
  SELECT м.id,
         COUNT(DISTINCT COALESCE(e.user_id::text, e.anon_id, e.visitor_id))::INTEGER
    FROM мої м
    LEFT JOIN analytics_events e
           ON e.event_type IN ('content_open', 'content_seen')
          AND e.meta->>'kind' = 'feed_post'
          AND e.meta->>'id'   = м.id::text
   GROUP BY м.id;
$$;

-- Гостю це не потрібно: число бачить лише автор або команда сторінки, а вони
-- завжди ввійшли. 🛑 `anon` навмисно не даємо — щоб функція не стояла відкритою
-- поверхнею (лінтер Supabase справедливо чіпляється саме за такі).
REVOKE ALL ON FUNCTION post_read_counts(BIGINT[]) FROM PUBLIC;
REVOKE ALL ON FUNCTION post_read_counts(BIGINT[]) FROM anon;
GRANT EXECUTE ON FUNCTION post_read_counts(BIGINT[]) TO authenticated;

-- 📐 Покажчик під цей запит. Без нього кожен виклик читав би таблицю подій
-- суцільно, а вона найбільша в базі (4 647 рядків сьогодні, під ціль курсу —
-- ~1,5 млн на місяць до згортання). Частковий: інші типи подій тут не потрібні.
CREATE INDEX IF NOT EXISTS analytics_events_content_idx
  ON analytics_events ((meta->>'kind'), (meta->>'id'))
  WHERE event_type IN ('content_open', 'content_seen');
