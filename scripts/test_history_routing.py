def лише_вказівки(промпт: str) -> str:
    """Промпт без блоків памʼяті — саме ЗАВДАННЯ, яке ми даємо моделі.

    🔴 Перша версія перевірки міряла промпт цілком і червоніла через заголовки
    вже НАПИСАНИХ статей («Покащів: село, яке колись очолювало цілу волость»).
    Але памʼять — це список «не повторюй цього», тобто протилежність вказівці
    писати історію. Викидати з памʼяті старі заголовки не можна: без них агент
    почав би дублювати. Тому міряємо те, що справді керує пошуком."""
    for межа in ("\n\nВЖЕ У СТРІЧЦІ", "\n\nПРО ЩО ВЖЕ ПИСАЛИ", "\n\nСВІЖЕ З ОФІЦІЙНИХ"):
        i = промпт.find(межа)
        if i > 0:
            промпт = промпт[:i]
    return промпт


