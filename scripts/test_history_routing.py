# ⚠️ Так, це звірка ДВОХ ОГОЛОШЕНЬ, а не наслідку — інакше тут не можна: одного
# середовища, де живуть обидві копії, не існує. Але ризик тут саме в розходженні,
# і воно видно лише так.
js = (ROOT / "admin.html").read_text(encoding="utf-8")
збіг = re.search(r"ІСТОРИЧНІ_КАТЕГОРІЇ\s*=\s*\[([^\]]*)\]", js)
js_ознаки = tuple(m.group(1) for m in re.finditer(r"['\"]([^'\"]+)['\"]", збіг.group(1))) if збіг else ()
ok("🔴 ознака «це історія» ОДНАКОВА в кабінеті (JS) і в синку (Python)",
   js_ознаки == sc.ІСТОРИЧНІ_КАТЕГОРІЇ,
   f"кабінет {js_ознаки} · синк {sc.ІСТОРИЧНІ_КАТЕГОРІЇ}")

# 🛑 Контроль на власний спосіб міряти: якби ознака історії була сліпа, обидва
# рядки поїхали б в новини — і перша перевірка почервоніла б.
ok("КОНТРОЛЬ: без ознаки історії обидва рядки пішли б у новини",
   len([r for r in РЯДКИ]) == 2 and sc.це_історія(РЯДКИ[1]) and not sc.це_історія(РЯДКИ[0]))

# ── 6. КОНТРОЛЬ: перевірка мусить уміти впасти ─────────────────────────────
# Якби історичні теми лишились у новинній місії, перша ж ознака протекла б.
підробка = json.loads(json.dumps(cfg))
підробка["missions"]["Громада"]["create_themes"] = тем_історії
новини_підробка = ag.build_prompt("Громада", підробка, [], target=2)
протекло_б = [сл for сл in історичні_ознаки if сл in лише_вказівки(новини_підробка)]
ok("КОНТРОЛЬ: зі старим конфігом історія справді протікала б у вказівки новин",
   bool(протекло_б), "ознаки: " + ", ".join(протекло_б)[:60])

print(f"\n{'❌' if fail_count else '✅'} {ok_count}/{ok_count + fail_count} перевірок пройдено")
sys.exit(1 if fail_count else 0)
