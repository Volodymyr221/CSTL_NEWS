-- scripts/supabase_cms_target.sql
-- КУДИ ПУБЛІКУВАТИ СТАТТЮ КАБІНЕТУ: у Новини чи у стрічку конкретної спільноти.
--
-- 🗣️ Замовлення Вови 03.09.2026: «Треба зробити можливість таку, щоб якщо
-- парсяться якісь статті, туди можна було б вирішувати, куди публікувати. Чи в
-- новини… чи, наприклад, в стрічку під якимось логотипом, де власником чи
-- адміністратором є я або певна людина, яка зараз знаходиться в адмінці.»
--
-- 🔑 ЧОМУ ДВІ КОЛОНКИ, А НЕ ОДНА. На пряме питання «що сильніше — правило за
-- категорією чи вибір людини» Вова відповів одним словом: «перебивати». Отже
-- ручний вибір мусить перемагати ЗАВЖДИ, зокрема й вибір «у Новини» на
-- історичній статті. З однією колонкою `target_page_id` цей випадок неможливо
-- відрізнити від «людина нічого не обирала»: обидва були б NULL, і правило
-- «істор/краєзнав → Історія Громади» тихо перемагало б людину.
--   target_locked = false → маршрут визначає правило за категорією (як із 28.08);
--   target_locked = true  → обрала людина: target_page_id NULL = Новини,
--                           число = `pages.id` спільноти.
--
-- ⚠️ Права НЕ роздаються тут. Хто в яку спільноту може постити — вирішує
-- `page_admins` + RLS на `page_posts`; адмінка лише не пропонує людині того,
-- чого їй однаково не можна («кожен свої, і адмінк застосунку всі»).
--
-- Накачено на проект Olyka Castle 03.09.2026 (міграція cms_articles_target_page).
alter table public.cms_articles
  add column if not exists target_page_id bigint references public.pages(id) on delete set null,
  add column if not exists target_locked boolean not null default false;

comment on column public.cms_articles.target_page_id is
  'Спільнота-призначення (pages.id). Діє лише коли target_locked = true; null при target_locked = true означає «у Новини».';
comment on column public.cms_articles.target_locked is
  'true = маршрут обрано людиною вручну і він перебиває автоправило за категорією.';
