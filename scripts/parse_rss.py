# 🔑 ЗАГАЛЬНЕ ПРАВИЛО, А НЕ ЗАПЛАТКА НА ОДИН ЗАГОЛОВОК: у новинному заголовку те,
# що в лапках, — це майже завжди ІМʼЯ (позивний, назва підрозділу, бренду, справи),
# а не тема. Тема живе в словах БЕЗ лапок. Тому лапки з їхнім вмістом прибираємо
# перед звіркою — і «птахи» перестають бути птахами.
# ⚠️ Втратити через це тему майже неможливо: якщо після викидання лапок у заголовку
# не лишилось ЖОДНОГО збігу, працює запасна гілка й ми питаємо опис. Саме так
# стаття Мадяра і потрапляє у Війну: в описі «військовослужбовців», «бригади
