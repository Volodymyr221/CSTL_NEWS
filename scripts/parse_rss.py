# «втрати», «безпілотн», «боєприпас»; Культура — «день міста», «урочист»,
# «виступит») змінилось РІВНО ЧОТИРИ статті, і всі чотири на краще.
_QUOTED = re.compile(r'[«"\u201c\u201e]([^«»"\u201c\u201d\u201e]{1,40})[»"\u201d]')


def _category_score(text: str) -> dict:
    """Скільки слів кожної теми в тексті. Порожній словник = жодного збігу."""
    hits = {}
    for cat, rx in _CATEGORY_RE:
        n = len(rx.findall(text or ""))
        if n:
            hits[cat] = n
    return hits


def detect_category(title: str, body: str = "") -> str:
    """Тематична категорія новини. Заголовок головний, опис — лише як запасний.

    Повний розбір рішень — у коментарі над `_CATEGORY_RULES`. Коротко:
    рахунок замість першого збігу; порядок списку вирішує нічию; цілі слова (\\b),
    бо підрядок давав «тран-СПОРТ-ні» → Спорт.
    """
    hits = _category_score(_QUOTED.sub(' ', title or ''))   # лапки = імена, не теми
    if not hits:
        hits = _category_score(body)      # заголовок-загадка — питаємо опис
    if not hits:
        return CATEGORY_DEFAULT
    best = max(hits.values())
    for cat, _ in _CATEGORY_RULES:        # перший у списку з найбільшим рахунком
        if hits.get(cat) == best:
            return cat
    return CATEGORY_DEFAULT


def recategorize_stored_articles(articles: list) -> int:
    """Перерозкладає ВЖЕ ЗБЕРЕЖЕНІ статті новими правилами. Повертає кількість ЗАЧЕПЛЕНИХ.

    🔑 Категорія — поле ПОХІДНЕ (обчислене із заголовка), а не авторське. Тому
    його можна і треба переобчислювати: інакше кожне покращення класифікатора
    діяло б лише на завтрашні статті, а стрічка ще місяць показувала б учорашню
    розкладку.
    🛑 ЧІПАЄМО ЛИШЕ ТЕ, ЩО РОЗІБРАВ ПАРСЕР — тобто статті БЕЗ поля `kind`.
    Усе, що має `kind`, написала людина, і категорію їй теж ставила людина:
      • `kind == "editor"` — редактор кабінету («Історія краю», «молодь громади»);
      • `kind == "story"`  — історії Олики з `data/olyka-stories.json` («Історія»).
    🔑 Правило саме таке — «немає `kind`», а не перелік відомих значень. Перша
    версія цієї функції пропускала лише `editor` і мовчки переписала б усі пʼять
    історій Олики. Перелік доводиться доповнювати при кожному новому виді запису,
    і забути один раз досить, щоб затерти чужу роботу; «немає `kind`» захищає
    наперед і тих, кого ще не завели.
    """
    зачеплено = змінено = 0
    for a in articles:
        if a.get("kind"):          # написане людиною — категорію обирала теж людина
            continue
        if a.get("_cat") == CATEGORY_VERSION:
            continue
        a["_cat"] = CATEGORY_VERSION
        зачеплено += 1
        нова = detect_category(a.get("title", ""), a.get("excerpt", ""))
        if нова != a.get("category"):
            a["category"] = нова
            змінено += 1
    if зачеплено:
        print(f"✓ Категорії: звірено {зачеплено}, змінено {змінено}")
    # 🔑 Повертаємо ЗАЧЕПЛЕНІ, а не змінені, і різниця тут не косметична.
    # Позначка `_cat` — теж зміна файлу. Якби поверталось «змінено», то в разі
    # «категорії й так усі правильні» функція розставила б позначки, віддала 0,
    # файл не зберігся б — і наступний прогін робив би ту саму роботу знову. Вічно.
    return зачеплено


def sanitize_image_url(u):
    """Прибирає склеєні URL типу 'https://ahttps://img.../x.jpg' → бере останній http(s).
    Фіксить баг подвійного домену (напр. картинки Конкурента). Повертає url або None."""
    if not u or not isinstance(u, str):
        return None
    u = u.strip()
    idx = max(u.rfind("http://"), u.rfind("https://"))
    if idx > 0:
        u = u[idx:]
    return u if u.startswith(("http://", "https://")) else None


def extract_image(entry) -> str | None:
    media = getattr(entry, "media_content", None)
    if media and isinstance(media, list):
        for m in media:
            if not isinstance(m, dict):
                continue
            url = m.get("url", "") or ""
            if any(ext in url.lower() for ext in [".jpg", ".jpeg", ".png", ".webp"]):
                return sanitize_image_url(url)
    enclosures = getattr(entry, "enclosures", None)
    if enclosures:
        for enc in enclosures:
            if not isinstance(enc, dict):
                continue
            if enc.get("type", "").startswith("image"):
                return sanitize_image_url(enc.get("href") or enc.get("url"))
    return None


def classify_entry(title: str, text: str) -> str:
    """Визначає тип запису: 'event' або 'news'.

    Логіка: є ключові слова події + знайдено майбутню дату → 'event'.
    Або 3+ ключових слова без дати — теж 'event' (сильний сигнал).
    """
    low = (title + " " + text).lower()

    event_hits = sum(1 for kw in EVENT_KEYWORDS if kw in low)
    if event_hits == 0:
        return "news"

    today = datetime.date.today()
    for m in FUTURE_DATE_RE.finditer(low):
        day = int(m.group(1))
        month = MONTHS_UK.get(m.group(2).lower(), 0)
        if not month:
            continue
        year = int(m.group(3)) if m.group(3) else today.year
        if year == today.year and month < today.month:
            year += 1
        try:
            if datetime.date(year, month, day) >= today:
                return "event"
        except ValueError:
            pass

    # Немає явної майбутньої дати, але дуже сильний сигнал
    if event_hits >= 3:
        return "event"

    return "news"


def extract_event_data(title: str, text: str, ts: int) -> dict:
    """Витягує дату, час і локацію з тексту події."""
    today = datetime.date.today()

    # Дата
    event_date = None
    for m in FUTURE_DATE_RE.finditer(text.lower()):
        day = int(m.group(1))
        month = MONTHS_UK.get(m.group(2).lower(), 0)
        if not month:
            continue
        year = int(m.group(3)) if m.group(3) else today.year
        if year == today.year and month < today.month:
            year += 1
        try:
            d = datetime.date(year, month, day)
            if d >= today:
                event_date = d.strftime("%Y-%m-%d")
                break
        except ValueError:
            pass

    if not event_date:
        # Fallback: дата публікації
        event_date = datetime.date.fromtimestamp(ts / 1000).strftime("%Y-%m-%d")

    # Час
    event_time = None
    for m in TIME_RE.finditer(text):
        h, mi = int(m.group(1)), int(m.group(2))
        if 6 <= h <= 23:
            event_time = f"{h:02d}:{mi:02d}"
            break

    # Локація
    event_location = None
    loc_m = LOCATION_RE.search(text)
    if loc_m:
        event_location = loc_m.group(1).strip()

    return {"date": event_date, "time": event_time, "location": event_location}


