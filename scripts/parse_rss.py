# ── ВІДЕО З YOUTUBE ────────────────────────────────────────────────────────
# 🔴 ЗАВЕДЕНО 29.08 за прикладом Вови: стаття «У Луцьку близько тисячі студентів
# заселилися у гуртожитки» має в оригіналі відео в кінці, а в нас його НЕМАЄ
# ВЗАГАЛІ — заміряно в базі: `iframe: 0, youtube: 0`.
# 📐 І це не поодинокий випадок: 20 статей із 392 мають «відео» в заголовку, і всі
# втратили його. Причина проста — `iframe` не входив у список тегів, з яких
# `_blocks_to_html` збирає тіло.
#
# 🛑 ЧОМУ НЕ МОЖНА ПРОСТО ДОДАТИ `iframe` У ТОЙ СПИСОК. Тіло статті клієнт малює
# через `innerHTML` БЕЗ санітайзера — уся безпека тримається на обіцянці «єдиний
# атрибут це `href`, і його пише сам парсер після перевірки». Пропустивши чужий
# `<iframe>`, ми пустили б у свою сторінку `src`, написаний стороннім сайтом.
# 🔑 Тому шлях той самий, що з посиланнями: впізнаємо ІДЕНТИФІКАТОР відео,
# перевіряємо його СВОЇМ правилом і малюємо СВОЮ розмітку. Чужий рядок у
# сторінку не потрапляє взагалі — з розбору виходить лише 11 наших символів.
#
# 🔑 РІШЕННЯ ВОВИ (варіант «А»): у тіло йде ОБКЛАДИНКА, а не плеєр. Поки читач не
# натиснув, з YouTube не вантажиться нічого — ні плеєр (~1 МБ), ні куки. Стаття
# лишається легкою, а YouTube не бачить читача, доки той сам не захотів.
_YT_ID = re.compile(r"^[A-Za-z0-9_-]{11}$")
_YT_URL = re.compile(
    r"(?i)(?:youtube(?:-nocookie)?\.com/(?:embed|v|shorts)/|youtu\.be/|[?&]v=)"
    r"([A-Za-z0-9_-]{11})")


def _youtube_id(node) -> str:
    """Ідентифікатор відео з вузла, або порожньо.

    ⚠️ Дивимось не лише `src`: половина сайтів вантажить плеєр ліниво і тримає
    адресу в `data-src`/`data-url`/`data-embed`, а сам `src` порожній. Без цього
    відео «є в розмітці», але для нас його ніби немає.
    """
    for атр in ("src", "data-src", "data-url", "data-embed", "data-video", "href"):
        m = _YT_URL.search(node.get(атр) or "")
        if m:
            return m.group(1)
    # Голий ідентифікатор в атрибуті (`data-youtube="dQw4w9WgXcQ"`).
    for атр in ("data-youtube", "data-yt", "data-id", "data-video-id"):
        зн = (node.get(атр) or "").strip()
        if _YT_ID.match(зн):
            return зн
    return ""


def _video_html(vid: str) -> str:
    """Наша власна розмітка відео: обкладинка + позначка «грати».

    🛑 Жодного рядка з чужого сайту тут немає — ані в адресі, ані в атрибутах.
    `vid` уже перевірений `_YT_ID`, тобто це рівно 11 символів [A-Za-z0-9_-].
    Обкладинку віддає сам YouTube за тим самим ідентифікатором.
    """
    if not _YT_ID.match(vid or ""):
        return ""
    return ('<figure class="art-video" data-yt="' + vid + '">'
            '<img src="https://i.ytimg.com/vi/' + vid + '/hqdefault.jpg" alt="Відео">'
            '<span class="art-video-play" aria-hidden="true"></span>'
            '</figure>')


def _figure_html(im, base_url: str, cover_url: str) -> str:
    """`<img>` (можливо, всередині `<figure>`) → наш блок фото. Порожньо — якщо
    фото не пройшло відсів або це обкладинка, яка вже стоїть угорі статті."""
    url = _photo_url(im, base_url)
    if not url or _same_photo(url, cover_url):
        return ""
    підпис = ""
    fig = im.find_parent("figure")
    if fig:
        cap = fig.find("figcaption")
        if cap:
            підпис = html.escape(cap.get_text(" ", strip=True))[:300]
    return ('<figure><img src="' + html.escape(url, quote=True) + '" alt="">'
            + (f"<figcaption>{підпис}</figcaption>" if підпис else "")
            + "</figure>")


