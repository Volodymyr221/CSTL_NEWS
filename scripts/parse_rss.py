_BLOCK_TAG_RE = re.compile(r"<(p|div|li|h[1-6])\b[^>]*>(.*?)</\1>", re.I | re.S)
# Тег або ЦІЛЕ посилання: усередину `<a>…</a>` не заглядаємо, інакше отримали б
# посилання в посиланні (та сама пастка, що й у `_inline_one`).
_TAG_OR_LINK_RE = re.compile(r"<a\b[^>]*>.*?</a>|<[^>]+>", re.I | re.S)


def _linkify_escaped(шматок: str) -> str:
    """Адреси в УЖЕ екранованому тексті → посилання. Решту не чіпаємо.

    Відрізняється від `_linkify` рівно тим, що НЕ екранує текст повторно: сюди
    приходить готовий HTML, і друге екранування показало б людині `&amp;lt;`.
    """
    out, last = [], 0
    for поч, кін, сира in _bare_urls(шматок):
        if поч < last:
            continue
        href = _href_for(сира)
        if not href:
            continue
        out.append(шматок[last:поч])
        out.append('<a href="' + html.escape(href, quote=True) + '"'
                   ' target="_blank" rel="noopener">' + сира + "</a>")
        last = кін
    out.append(шматок[last:])
    return "".join(out)


# Провідний `<figure>` на самому початку тіла — той самий знімок, що вже стоїть
# обкладинкою (див. блок над `_figure_html`). Тут прибираємо його БЕЗ мережі, у
# вже збережених статтях: інакше виправлення чекало б, поки самолікування дійде
# до кожної (40 сторінок на прогін при 400 статтях — понад десять прогонів, а
# прогони GitHub кидає).
_LEAD_FIGURE_RE = re.compile(r"^\s*<figure>.*?</figure>", re.I | re.S)


# 🔴 27.08 (ніч) — ВІДОМІ «ХАБИ», ЩО РЕДИРЕКТЯТЬ НА САЙТИ-ПОБРАТИМИ.
# `pravda.com.ua` роздає у своїй стрічці й матеріали «Європейської»/«Економічної»
# правди через власні адреси. До фіксу бази відносні посилання в таких статтях
# зводились до `pravda.com.ua` — і вели на ІНШУ статтю (скарга Вови).
# 🛑 Поки стаття не перебрана новими правилами, її посилання НЕ ВАРТО показувати:
# слова Вови — «або це пофіксити, або взагалі не обманювати людей». Текст
# лишається цілим, зникає лише натискність. Перебір поверне посилання правильними.
# ⚠️ Список навмисно вузький: рвати справні посилання решти джерел, аби «про всяк
# випадок», означало б зіпсувати те, що працює.
_REDIRECT_HUBS = {"pravda.com.ua"}
_LINK_TAG_RE = re.compile(r"<a\b[^>]*>(.*?)</a>", re.I | re.S)


def _host(url: str) -> str:
    return re.sub(r"^www\.", "", urllib.parse.urlparse(url or "").netloc.lower())


def polish_markup(вміст: str, cover: str = "", посилання_надійні: bool = True) -> str:
    """Прибирає навігацію джерела, дубль обкладинки і робить адреси натискними.

    Без мережі: нічого не перезбирає, лише чистить те, що вже написано.
    `посилання_надійні=False` — розгортає `<a>` у текст (див. `_REDIRECT_HUBS`).
    """
    if not вміст:
        return вміст
    if cover:
        вміст = _LEAD_FIGURE_RE.sub("", вміст, count=1)
    if not посилання_надійні:
        # Текст посилання лишається — зникає тільки натискність.
        return _LINK_TAG_RE.sub(lambda m: m.group(1), вміст)
    # 1. Блоки, що складаються з самої навігації («« повернутися», «до списку»).
    вміст = _BLOCK_TAG_RE.sub(
        lambda m: "" if _лише_навігація(strip_html(m.group(2))) else m.group(0), вміст)
    # 2. Той самий напис у тексті БЕЗ розмітки — останнім рядком.
    if "<" not in вміст:
        рядки = вміст.rstrip().split("\n")
        while рядки and _лише_навігація(рядки[-1]):
            рядки.pop()
        вміст = "\n".join(рядки)
    # 3. Голі адреси — поза тегами і поза наявними посиланнями.
    out, last = [], 0
    for m in _TAG_OR_LINK_RE.finditer(вміст):
        out.append(_linkify_escaped(вміст[last:m.start()]))
        out.append(m.group(0))
        last = m.end()
    out.append(_linkify_escaped(вміст[last:]))
    return "".join(out)


def polish_stored_articles(articles: list) -> int:
    """Полірує розмітку збережених статей. Повертає кількість змінених."""
    змінено = 0
    for a in articles:
        if a.get("_polish") == POLISH_VERSION:
            continue
        було = a.get("content") or ""
        # Посилання з «хаба, що редиректить» надійні лише після перебору новими
        # правилами (RICH_ALGO_VERSION 5): до того їхня база була хибна.
        надійні = (_host(a.get("sourceUrl")) not in _REDIRECT_HUBS
                   or a.get("_richAlgo") == RICH_ALGO_VERSION)
        стало = polish_markup(було, a.get("image") or "", надійні)
        a["_polish"] = POLISH_VERSION
        if стало != було:
            a["content"] = стало
            змінено += 1
    if змінено:
        print(f"✨ Розмітку відполіровано: {змінено} статей (посилання, навігація джерела)")
    return змінено


def _norm_for_compare(t: str) -> str:
    """Текст до порівняння: без розмітки, регістру, пунктуації і пробілів."""
    return re.sub(r"[^\w]+", "", strip_html(t or "").lower())


def looks_like_same_text(page_text: str, rss_text: str) -> bool:
    """Чи текст зі сторінки — це той самий анонс, що вже був у RSS.

    Порівнюємо ВКЛАДЕНІСТЬ, а не рівність: сторінка зазвичай містить анонс
    плюс решту статті, тож рівними вони не бувають майже ніколи. Питання в
    тому, чи додалось щось СУТТЄВЕ понад анонс.
    """
    a, b = _norm_for_compare(page_text), _norm_for_compare(rss_text)
    if not a or not b:
        return False
    # Якщо сторінка не довша за анонс більш ніж на 10% — нового немає.
    return len(a) <= len(b) / SIMILAR_RATIO * 1.0 and (b[:200] in a or a[:200] in b)


def decide_content(rss_html: str, page_html: str | None, rss_summary: str) -> tuple[str, str]:
    """Вирішує, який текст лишити і звідки він. Повертає (html, contentSource).

    🔑 Уся логіка «повно чи ні» живе ТУТ, в одній функції, і її споживають
    обидва шляхи — свіжий розбір (`parse_source`) і самолікування
    (`rehydrate_short_articles`). До 12.08 правило було записане ДВІЧІ, різними
    числами (500 у парсері, 600 у клієнті), і саме тому розійшлось.
    """
    page_plain = strip_html(page_html or "")
    rss_plain  = strip_html(rss_html or "")

    if page_html and len(page_plain) >= MIN_BODY_CHARS:
        # Сторінка дала щось змістовне. Лишається спитати, чи це не той самий анонс.
        if looks_like_same_text(page_plain, rss_summary or rss_plain):
            return (page_html if len(page_plain) > len(rss_plain) else rss_html), "rss"
        return page_html, "page"

    # Сторінку не взяли (403, JS-only, немає тіла) → лишається те, що дав RSS.
    return rss_html, "rss"


def get_full_content(entry, title: str = "", base_url: str = "") -> str:
    """Повний текст статті → БАГАТИЙ HTML (варіант A): з content:encoded зберігаємо
    структуру (_blocks_to_html), інакше summary → абзаци. Повертає безпечний HTML.

    ⚠️ `base_url` тут — посилання самого запису RSS. Воно потрібне рівно для того,
    щоб відносні адреси всередині `content:encoded` («/news/999») стали
    абсолютними: без нього посилання вело б на НАШ домен."""
    content_list = getattr(entry, "content", None)
    if content_list:
        valid = [c for c in content_list if isinstance(c, dict)]
        if valid:
            best = max(valid, key=lambda c: len(c.get("value") or ""), default=None)
            if best:
                raw = best.get("value") or ""
                if len(strip_html(raw)) > 150:
                    from bs4 import BeautifulSoup
                    rich = _blocks_to_html(BeautifulSoup(raw, "html.parser"), title, base_url=base_url)
                    if len(rich) > 60:
                        return rich[:8000]
    summ = strip_html(entry.get("summary") or entry.get("description") or "")
    return _split_runon_html("".join(f"<p>{html.escape(p)}</p>" for p in summ.split("\n\n") if p.strip()))


def normalize_title(title: str) -> str:
    """Нормалізований заголовок для порівняння між джерелами."""
    t = title.lower()
    t = re.sub(r"[^\w\s]", "", t)   # прибрати пунктуацію
    t = re.sub(r"\s+", " ", t).strip()
    return t


# ── Дедуплікація (Крок 2 ТЗ парсерів, 01.07) — нечітка, у межах розділу ──────────
# Ловить не лише 100% однакові заголовки, а й ПЕРЕФРАЗОВані про ту саму подію.
# Порівнюємо заголовки як МНОЖИНИ значущих слів (Jaccard — % спільних слів від
# їх об'єднання). Дедуп у МЕЖАХ РОЗДІЛУ (Україна та Світ / Волинь / Громада) —
# та сама тема в різних розділах не зникає помилково.

# Стоп-слова — службові слова без сенсу для порівняння (прийменники, сполучники)
STOPWORDS_UK = {
    "і", "й", "та", "а", "але", "або", "в", "у", "на", "з", "із", "зі", "до",
    "за", "по", "про", "від", "для", "що", "як", "це", "не", "є", "під", "над",
    "при", "о", "об", "the", "of", "in", "on", "and",
}

# Поріг схожості заголовків: ≥65% спільних слів → дубль (рішення Роми 01.07).
TITLE_SIM_THRESHOLD = 0.65


def section_of(geo: str) -> str:
    """Розділ стрічки для дедуплікації (визначається за geo статті)."""
    if geo in ("Україна", "Світ"):
        return "Україна та Світ"
    if geo == "Волинь":
        return "Волинь"
    if geo in ("Олика", "Громада"):   # «Олика» — стара назва, «Громада» — нова (05.07)
        return "Громада"
    return geo or "інше"


def title_tokens(title: str) -> set:
    """Множина значущих слів заголовка (для порівняння схожості)."""
    return {w for w in normalize_title(title).split()
            if len(w) > 2 and w not in STOPWORDS_UK}


def is_dup_title(tokens: set, section: str, seen_by_section: dict) -> bool:
    """True якщо заголовок схожий на вже бачений У ЦЬОМУ Ж РОЗДІЛІ (Jaccard ≥ поріг)."""
    if not tokens:
        return False
    for prev in seen_by_section.get(section, ()):
        p = prev["t"]
        union = tokens | p
        if union and len(tokens & p) / len(union) >= TITLE_SIM_THRESHOLD:
            return True
    return False


