# -*- coding: utf-8 -*-
"""СТОРОЖ: ДОПИС СПІЛЬНОТИ У СТРІЧЦІ НОВИН — І ЩОБ БЕЗ ДУБЛЯ.

🔴 Заведено 17.09.2026 разом із самою фічею.

🗣️ Замовлення Вови: «щоб ми запостили, що щось відбулося, в спільноту, і це
відобразилося в блоці новин, типу, як від імені спільноти… це, можливо, буде
дублювати, але нам треба прибрати дубль».

🔑 ЩО САМЕ МІРЯЄМО. Не «чи є функція в коді», а ПОВЕДІНКУ на підроблених даних:
які записи доїжджають у стрічку, а які свідомо ні. Головна цінність тут —
НЕГАТИВНІ випадки: дубль за `post_id` і дубль за темою. Перевірка, яка лише
показує «допис доїхав», зеленіла б і на коді, що тягне все підряд щопрогону.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

import parse_rss as pr          # noqa: E402
import sync_cms as sc           # noqa: E402

провали = []


def check(назва, умова, деталь=""):
    print(("  ✓ " if умова else "  ✗ ") + назва + (f"  — {деталь}" if деталь else ""))
    if not умова:
        провали.append(назва)


def дописи(*rows):
    sc.fetch_community_to_news = lambda: list(rows)


def допис(id_, text, name="OLYKA CASTLE"):
    return {"id": id_, "page_id": 3, "text": text, "image_urls": [],
            "image_url": None, "created_at": "2026-09-17T10:00:00+00:00",
            "pages": {"name": name}}


print("СТОРОЖ: допис спільноти → Новини\n")

# ── 1. ЗВИЧАЙНИЙ ШЛЯХ ────────────────────────────────────────────────────────
дописи(допис(11, "У неділю в Олиці відбудеться ярмарок ремесел. Починаємо об 11:00."))
нові, next_id = sc.sync_community_posts([], {}, 1000001)
check("допис із прапорцем доїжджає у стрічку", len(нові) == 1, f"{len(нові)} шт.")
if нові:
    a = нові[0]
    check("підписано ІМЕНЕМ СПІЛЬНОТИ, не «CSTL LIFE»", a["source"] == "OLYKA CASTLE", a["source"])
    # 🛑 Джерело мусить бути з тих, які РОЗПІЗНАЄ `handlePostHash` у `src/app.js`:
    # feed|board|disc|news. Невпізнане він мовчки ігнорує — тобто картка відкривала б
    # пустоту без жодної помилки. Перша версія писала `page` і саме так і ламалась.
    check("🔑 веде НАЗАД у допис (не копія-стаття)", a["sourceUrl"] == "#/post/feed/11", a["sourceUrl"])
    check("🛑 джерело deep-link РОЗПІЗНАЄТЬСЯ застосунком",
          a["sourceUrl"].split("/")[2] in ("feed", "board", "disc", "news"),
          a["sourceUrl"])
    check("несе post_id — за ним ловиться повтор", a.get("post_id") == 11, str(a.get("post_id")))
    check("kind=community (recategorize його не чіпає)", a["kind"] == "community", a["kind"])
    check("гео — Громада", a["geo"] == "Громада", a["geo"])
    check("категорія КАНОНІЧНА", a["category"] in pr.CATEGORIES_CANON, a["category"])
    check("номер із простору кабінету (не перетнеться з парсером)", a["id"] >= 1_000_000, str(a["id"]))
check("лічильник номерів зрушив", next_id == 1000002, str(next_id))

# ── 2. 🔴 ПОВТОР ЗА post_id — НЕ ДОДАЄМО ВДРУГЕ ──────────────────────────────
# Без цього кожен прогін синку (він ходить за розкладом) клав би той самий допис
# у стрічку ЩЕ РАЗ — тобто фіча сама стала б генератором дублів.
дописи(допис(11, "У неділю в Олиці відбудеться ярмарок ремесел."))
вже = [{"id": 1000001, "post_id": 11, "title": "У неділю в Олиці відбудеться ярмарок ремесел."}]
нові2, _ = sc.sync_community_posts(вже, {}, 1000002)
check("🔴 допис, що вже у стрічці, ВДРУГЕ не кладеться", len(нові2) == 0, f"{len(нові2)} шт.")

# ── 3. 🔴 ПРО ЦЕ ВЖЕ Є НОВИНА — НАШ ПЕРЕКАЗ НЕ ДОДАЄМО ───────────────────────
# ⚠️ Вирішено на користь наявної новини: прибрати чуже означало б СХОВАТИ новину,
# а це найдорожча помилка (B-22). Краще не показати свій переказ, ніж стерти факт.
заг = "В Олиці відбулася зустріч для жінок «Крила Волині»"
seen = {}
pr.remember_title(pr.title_tokens(заг), pr.section_of("Громада"), seen)
дописи(допис(12, заг + ". Говорили про підтримку."))
нові3, _ = sc.sync_community_posts([], seen, 1000002)
check("🔴 коли про це вже є новина — допис у Новини НЕ дублюється", len(нові3) == 0, f"{len(нові3)} шт.")

# 🔑 КОНТРОЛЬ: на ЧИСТІЙ памʼяті той самий допис доїжджає. Без цього рядка
# перевірка вище зеленіла б і на коді, який не бере ЖОДНОГО допису взагалі.
дописи(допис(12, заг + ". Говорили про підтримку."))
контроль, _ = sc.sync_community_posts([], {}, 1000002)
check("КОНТРОЛЬ: той самий допис на чистій стрічці доїжджає", len(контроль) == 1, f"{len(контроль)} шт.")

# ── 4. ПОРОЖНІЙ ТЕКСТ ────────────────────────────────────────────────────────
# Допис буває з самого фото. Заголовка з нього не зробити, а картка новини без
# заголовка — зламані дані на екрані.
дописи(допис(13, "   "))
нові4, _ = sc.sync_community_posts([], {}, 1000002)
check("допис без тексту у Новини не береться", len(нові4) == 0, f"{len(нові4)} шт.")

# ── 5. ЗАГОЛОВОК ІЗ ТЕКСТУ ───────────────────────────────────────────────────
check("заголовок ріжеться по МЕЖІ СЛОВА, а не посеред",
      not sc.заголовок_допису("а" * 50 + " " + "б" * 60).endswith("б…")
      or " " in sc.заголовок_допису("слово " * 40),
      sc.заголовок_допису("слово " * 40)[-24:])
check("перше речення стає заголовком",
      sc.заголовок_допису("Коротке речення. Друге вже зайве.") == "Коротке речення.",
      sc.заголовок_допису("Коротке речення. Друге вже зайве."))

# ── 6. ЛАНЦЮГ У КЛІЄНТІ: ГАЛОЧКА → СТАН → БАЗА ──────────────────────────────
# ⚠️ ЧЕСНО ПРО МЕЖУ ЦИХ ТРЬОХ ПЕРЕВІРОК: вони ТЕКСТОВІ, тобто слабші за поведінкові.
# Живим браузером композер тут не відкрити — він за входом, а стенд `feed-composer`
# працює на власній пісочниці-розмітці, не на справжньому застосунку.
# 🔑 Але ловлять вони найімовірнішу ваду цієї роботи — РОЗРИВ ЛАНЦЮГА: галочка
# намальована, а стан нікуди не йде. Саме так виглядав B-33, де чотири вимикачі
# сповіщень підтверджували дію, якої не відбувалось.
feed_js = (ROOT / "src/tabs/feed.js").read_text(encoding="utf-8")
supa_js = (ROOT / "src/core/supabase.js").read_text(encoding="utf-8")

check("1/3 галочка є в розмітці композера", "fd-comp-tonews-cb" in feed_js)
check("2/3 її зміна пише в стан (слухач, а не лише вигляд)",
      "fd-comp-tonews-cb')?.addEventListener('change'" in feed_js
      or "fd-comp-tonews-cb'" in feed_js and "toNews = e.target.checked" in feed_js)
check("3/3 стан доїжджає в базу при СТВОРЕННІ",
      "eventFields, showAuthor, toNews)" in feed_js, "createPagePost(…, toNews)")
check("3/3 і при РЕДАГУВАННІ (інакше галочку не можна було б зняти)",
      "to_news: toNews" in feed_js)
check("клієнт читає колонку `to_news` назад із бази",
      "to_news" in supa_js and "show_author, to_news" in supa_js)

print()
if провали:
    print("ПРОВАЛИ: " + ", ".join(провали))
    sys.exit(1)
print("УСЕ ЗЕЛЕНЕ")
