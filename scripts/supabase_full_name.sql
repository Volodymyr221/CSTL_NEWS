-- ПРІЗВИЩЕ ДОЇЖДЖАЄ ДО ЕКРАНА — замовлення Вови 04.09.2026.
-- Накачено на прод через Supabase MCP, міграція `surname_split_and_public_rpc`.
-- Тут — дзеркало для історії в репо. Ідемпотентний (можна виконувати повторно).
--
-- 🗣️ Слова Вови: «при коментуванні постів автор пише просто імʼя, а треба, щоб
-- писав імʼя та прізвище. Тобто так само, коли натискає на будь-якого жителя…
-- Так само, коли якийсь автор публікує від себе пост в стрічку… Де це доцільно.
-- А в більшості випадків це доцільно».
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 🔴 ВАДА БУЛА НЕ В ОФОРМЛЕННІ, А В ТОМУ, ЩО ПРІЗВИЩЕ НЕ ДОЇЖДЖАЛО ВЗАГАЛІ.
-- `profiles.surname` існує з липня (`supabase_profiles_extended.sql`), але
-- ЖОДЕН публічний RPC його не віддавав:
--   • `get_avatars`        — на ньому тримається `hydrateNames()`, тобто ВСІ
--                            підписи: коментарі, дописи, чати, списки розмов;
--   • `get_public_profile` — картка жителя (тап по аватару).
-- Обидва селектили лише `p.name`. Тобто прізвище лежало в базі й фізично не
-- могло потрапити на екран — жодна правка розмітки цього не лікувала.
--
-- 🔴 І ДАНІ РОЗІЙШЛИСЬ НА ДВА ФОРМАТИ. До 29.08 анкета мала одне поле «Імʼя»,
-- куди лягав увесь рядок від Google; з 29.08 поля розділені (`account-ui.js`,
-- `splitProviderName()`). Заміряно ДО міграції на 14 рядках:
--     8 — прізвище всередині `name` одним рядком (старий формат)
--     4 — `name` + `surname` окремо (новий)
--     2 — прізвища немає ніде
--     0 — пробіл у `name` І заповнений `surname` (подвоєння)
-- Тобто прізвище губилось ДВОМА різними способами залежно від віку профілю:
-- у нових — бо RPC мовчав, у старих — бо клієнт різав рядок до першого слова.
-- ПІСЛЯ міграції: 12 розділено · 2 без прізвища · 0 старого формату · 0 подвоєнь.
--
-- ⚠️ МІНА, ЯКУ ЦЕ ЗАРАЗОМ ЗНЯЛО. Кабінет показував старому профілю «Імʼя
-- Прізвище» в полі *Імʼя* і порожнє *Прізвище* (`account-ui.js`, `openAccount`).
-- Варто було людині вписати туди прізвище — і вийшов би формат A, тобто
-- «Володимир Шевчук Шевчук» на екрані. Таких рядків було 0, але шлях до них
-- був відкритий у кожного з восьми.
-- ─────────────────────────────────────────────────────────────────────────────

-- ── КРОК 1. Старий формат → розділені поля ───────────────────────────────────
-- Ділимо по ПЕРШОМУ пробілу: усе після нього — прізвище. Та сама угода, що в
-- `splitProviderName()` на клієнті (подвійні прізвища бувають, подвійні імена в
-- наших краях майже ні). Заміряно перед прогоном: усі 8 рядків рівно з двох
-- слів, тобто крайніх випадків сьогодні немає взагалі.
--
-- 🔑 Ідемпотентність не «на віру»: умова чіпає лише рядки, де `surname`
-- ПОРОЖНІЙ, а `name` містить пробіл. Після прогону таких 0 → повтор це no-op.
-- Подвоїти прізвище цей UPDATE не може в принципі: рядок із заповненим
-- `surname` він не бачить.
update public.profiles
   set name    = split_part(btrim(name), ' ', 1),
       surname = btrim(substr(btrim(name), position(' ' in btrim(name)) + 1))
 where name like '% %'
   and coalesce(btrim(surname), '') = '';

-- ── КРОК 2. `get_avatars` віддає прізвище ────────────────────────────────────
-- 🔑 ЧОМУ САМЕ СЮДИ, А НЕ НОВИМ ЗАПИТОМ. Цей RPC — ЄДИНЕ місце, звідки
-- застосунок дізнається, як звати людину (`fetchAvatars` → `_nameCache` →
-- `hydrateNames`). Другий запит по ту саму людину неминуче розійшовся б із цим,
-- а в проєкті це вже траплялось чотири рази (два списки антиспаму, дві
-- каруселі, дві розмітки пункту FAB, три переглядачі фото) — і симптом щоразу
-- виглядав як вада продукту, а не як розсинхрон.
--
-- ⚠️ Тип повернення змінюється, тому drop + create, а не CREATE OR REPLACE:
-- Postgres не дає замінити функцію з іншим `returns table`.
-- 🛑 Порядок наявних колонок збережено байт-у-байт, `surname` дописано В КІНЕЦЬ.
drop function if exists public.get_avatars(uuid[]);
create function public.get_avatars(uids uuid[])
returns table(uid uuid, name text, avatar_url text, official boolean, surname text)
language sql
stable
security definer
set search_path to 'public'
as $function$
  select p.uid, p.name, p.avatar_url, p.official, p.surname
  from public.profiles p
  where p.uid = any(uids[1:500])
$function$;

grant execute on function public.get_avatars(uuid[])
  to anon, authenticated, service_role;

-- ── КРОК 3. Картка жителя теж ────────────────────────────────────────────────
-- Тап по аватару — рівно те місце, де людину впізнають, тож прізвище тут
-- доцільне найбільше.
--
-- 🛑 ЗВІРЕНО З ЖИВОЮ БАЗОЮ, А НЕ З РЕПО (04.09). `supabase_public_profile.sql`
-- описував цю функцію з полем `age` і БЕЗ `official` — на проді все навпаки.
-- Тобто файл у репозиторії розійшовся з тим, що реально виконується. Нижче —
-- підпис, знятий із самої бази (`pg_get_functiondef`), плюс `surname`.
drop function if exists public.get_public_profile(uuid);
create function public.get_public_profile(p_uid uuid)
returns table(uid uuid, name text, avatar_url text, settlement text,
              trusted boolean, official boolean, bio text,
              created_at timestamptz, surname text)
language sql
stable
security definer
set search_path to 'public'
as $function$
  select p.uid, p.name, p.avatar_url, p.settlement, p.trusted, p.official,
         p.bio, p.created_at, p.surname
  from public.profiles p where p.uid = p_uid
$function$;

grant execute on function public.get_public_profile(uuid) to anon, authenticated;

