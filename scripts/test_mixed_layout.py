# -*- coding: utf-8 -*-
"""Стенд: ЗМІШАНА ВЕРСТКА — абзаци голим текстом, заголовки й списки тегами.

🗣️ Скарга Вови (31.08): «Чому стаття не в повному обсягу?» — у статті Волинь Post
«Житло біля Луцька в розтермінування» на екрані лишились самі підзаголовки й
марковані списки, а всі абзаци зникли.

📐 ЗАМІРЯНО на збереженій статті 13519 у `data/articles.json`:
      <h3> ×3 · <ul> ×2 · <p> ×0
   і при цьому `contentSource: page` — тобто парсер вважав витяг УСПІШНИМ.
   Перевірка повноти цього спіймати не могла: вона міряє ДОВЖИНУ (929 символів
   проти порога 180), а не ЧАСТКУ захопленого тексту.

🔑 ПРИЧИНА. Волинь Post верстає тіло змішано: абзаци — голим текстом через <br>,
   заголовки й списки — справжніми тегами. Блоковий збирач бачить лише другу
   половину. А запобіжник «нема текстових блоків → вмикай потоковий шлях» мовчить,
   бо заголовки підняли лічильник вище нуля.
   ➡️ Це ТОЙ САМИЙ КЛАС, що вада 27.08, тільки на крок далі: там роль
   «непорожнього списку» грав <img>, тут її грають <h3> і <ul>.

🛑 І ПРОСТО ПЕРЕМКНУТИСЬ НА ПОТОКОВИЙ ШЛЯХ БУЛО НЕ МОЖНА: він давав 100% тексту,
   але сплющував усе в абзаци — заголовок переставав бути заголовком, пункт
   списку пунктом. Тому правок дві, і стенд стереже ОБИДВІ: повноту І структуру.

🔴 КОНТРОЛЬ: REV=origin/main python scripts/test_mixed_layout.py
   → на старому коді падають перевірки про абзаци (їх там нема зовсім).

Запуск: python scripts/test_mixed_layout.py
"""
import importlib.util
import os
import subprocess
import sys
import tempfile

from bs4 import BeautifulSoup

REV = os.environ.get("REV", "")
КОРІНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def завантажити():
    """Модуль парсера — свіжий або з git (для контрольного прогону)."""
    шлях = os.path.join(КОРІНЬ, "scripts", "parse_rss.py")
    if REV:
        текст = subprocess.check_output(
            ["git", "-C", КОРІНЬ, "show", f"{REV}:scripts/parse_rss.py"])
        tmp = tempfile.NamedTemporaryFile("wb", suffix=".py", delete=False)
        tmp.write(текст); tmp.close()
        шлях = tmp.name
    spec = importlib.util.spec_from_file_location("pr_under_test", шлях)
    mod = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(mod)
    except SystemExit:
        pass
    return mod


pr = завантажити()

_пройдено = _усього = 0


def ok(назва, умова, деталі=""):
    global _пройдено, _усього
    _усього += 1
    if умова:
        _пройдено += 1
        print(f"✅ {назва}" + (f"  — {деталі}" if деталі else ""))
    else:
        print(f"❌ {назва}" + (f"  — {деталі}" if деталі else ""))


def зібрати(html, title="Заголовок"):
    el = BeautifulSoup(html, "html.parser").find("div")
    return pr._blocks_to_html(el, title=title)


# ── СЦЕНА 1. ЗМІШАНА ВЕРСТКА — ВИПАДОК ВОВИ ─────────────────────────────────
# ⚠️ Це РЕКОНСТРУКЦІЯ верстки, а не збережена копія сторінки: з пісочниці
# volynpost.com недосяжний (проксі віддає 403). Реконструкція відтворює ту саму
# ознаку, що й жива стаття — заголовки й списки є, абзаців нема, — тож вона
# доводить МЕХАНІЗМ. Що сторінка джерела влаштована саме так, підтвердить лише
# прогін у CI, де мережа справжня.
ЗМІШАНА = """<div>Придбання власної квартири — важливе рішення, яке не потребує сплати всієї суми одразу.<br><br>
Саме таку можливість пропонує компанія «Сімейна Фортеця», яка реалізує ЖК «От Кутюр».<br><br>
<h3>ЖК «От Кутюр»: сучасний простір для життя</h3>
«От Кутюр» створений для людей, які цінують спокій, комфорт і якісне житлове середовище.<br><br>
Окрему увагу приділено щільності забудови.<br><br>
<h3>Розтермінування: можливість придбати квартиру без банківського кредиту</h3>
Не кожна сімʼя готова одразу сплатити повну вартість квартири.<br><br>
Такий формат дозволяє:
<ul><li>розподілити оплату на кілька платежів;</li><li>не користуватися кредитуванням;</li></ul>
<h3>Які умови діють зараз</h3>Умови узгоджуються індивідуально.</div>"""

вихід = зібрати(ЗМІШАНА, "Житло біля Луцька в розтермінування: які є пропозиції")

# ── 1. ПОВНОТА ───────────────────────────────────────────────────────────────
ok("🔴 абзаци зі змішаної верстки НЕ втрачені (скарга Вови)",
   вихід.count("<p>") >= 6, f"<p> ×{вихід.count('<p>')}")

повний = len(pr.strip_html(ЗМІШАНА).strip())
зібрано = len(pr.strip_html(вихід).strip())
ok("захоплено щонайменше 85% тексту контейнера",
   зібрано >= повний * 0.85, f"{зібрано} з {повний} ({100 * зібрано // повний}%)")

# ── 2. І ПРИ ЦЬОМУ СТРУКТУРА ЦІЛА ───────────────────────────────────────────
# 🛑 Найлегша помилка тут — полагодити повноту, сплющивши все в абзаци. Тоді
# перевірка вище була б зеленою, а стаття втратила б рівно те, що Вова БАЧИВ.
ok("🛑 заголовки лишились заголовками, а не стали абзацами",
   вихід.count("<h3>") == 3, f"<h3> ×{вихід.count('<h3>')}")
ok("🛑 список лишився списком", вихід.count("<ul>") == 1 and вихід.count("<li>") == 2,
   f"<ul> ×{вихід.count('<ul>')} · <li> ×{вихід.count('<li>')}")

# ── 3. ПОРЯДОК ДОКУМЕНТА ЗБЕРЕЖЕНО ──────────────────────────────────────────
# 🔑 Без цього «повнота» і «структура» могли б бути зелені над текстом, у якому
# всі заголовки з'їхали в кінець — читати таку статтю неможливо.
i_перший_абзац = вихід.find("<p>")
i_перший_h3 = вихід.find("<h3>")
i_список = вихід.find("<ul>")
ok("вступний абзац стоїть ПЕРЕД першим підзаголовком",
   0 <= i_перший_абзац < i_перший_h3, f"<p>@{i_перший_абзац} · <h3>@{i_перший_h3}")
ok("список стоїть після свого підзаголовка, а не в кінці",
   i_перший_h3 < i_список < len(вихід) - 60, f"<ul>@{i_список} з {len(вихід)}")

# ── 4. ЧИСТА ВЕРСТКА НЕ ЗЛАМАНА ─────────────────────────────────────────────
# ⚠️ Головний ризик правки: вона змінює ВИБІР збирача, тобто чіпає всі джерела.
# 96% статей Волинь Post і всі інші видання йшли блоковим шляхом і мусять іти ним далі.
ЧИСТА = """<div><p>У Луцьку затримали чоловіка, який перевозив ноутбуки на пів мільйона.</p>
<p>Як повідомили в митниці, товар намагались провезти «зеленим коридором».</p>
<h3>Що каже митниця</h3>
<p>За словами речниці, справу передали до суду.</p>
<ul><li>вилучено 12 ноутбуків;</li><li>складено протокол;</li></ul>
<p>Розслідування триває.</p></div>"""
чиста = зібрати(ЧИСТА, "Ноутбуки на пів мільйона")
ok("чиста блокова верстка збирається без втрат", чиста.count("<p>") == 4,
   f"<p> ×{чиста.count('<p>')}")
ok("чиста блокова верстка зберігає заголовок і список",
   чиста.count("<h3>") == 1 and чиста.count("<li>") == 2,
   f"<h3> ×{чиста.count('<h3>')} · <li> ×{чиста.count('<li>')}")

# ── 5. ПОРІГ НЕ БАЛАНСУЄ НА МЕЖІ ────────────────────────────────────────────
# 📐 Поріг 1.25 заміряний: чиста верстка дає відношення 1.00, змішана — 3.07.
# Ця перевірка стежить, щоб розрив лишався великим: якщо він з часом стиснеться,
# вибір збирача почне спрацьовувати випадково, і це треба помітити ЗАРАЗ.
def відношення(html, title="Заголовок"):
    el = BeautifulSoup(html, "html.parser").find("div")
    б = len(pr.strip_html(pr._blocks_to_html(el, title=title)).strip())
    п = len(pr.strip_html(pr._flow_to_html(el, title)).strip())
    return п / max(б, 1)

# ⚠️ Міряємо на СВІЖОМУ модулі завжди: у контролі `_blocks_to_html` уже перемикає
# шлях, і відношення там нічого не сказало б про поріг.
if not REV:
    r_чиста = відношення(ЧИСТА, "Ноутбуки на пів мільйона")
    ok("чиста верстка не наближається до порога 1.25", r_чиста < 1.1, f"×{r_чиста:.2f}")

# ── 6. ВІДБИТОК ЖИВОЇ ВАДИ ──────────────────────────────────────────────────
# 🔑 Ознака, за якою ваду видно в даних: є заголовки або списки, і НУЛЬ абзаців.
# Стережемо саме її, бо саме так вона виглядала на екрані Вови.
import json
шлях_даних = os.path.join(КОРІНЬ, "data", "articles.json")
if os.path.exists(шлях_даних):
    with open(шлях_даних, encoding="utf-8") as f:
        статті = json.load(f)
    биті = [x for x in статті
            if (c := x.get("content") or "")
            and ("<h3>" in c or "<ul>" in c) and "<p>" not in c]
    ok("ПРИЛАД: у даних видно ознаку вади (заголовки без жодного абзацу)",
       True, f"таких статей у поточному файлі: {len(биті)}")

print()
print(f"{'✅' if _пройдено == _усього else '❌'} {_пройдено}/{_усього} перевірок пройдено")
sys.exit(0 if _пройдено == _усього else 1)
