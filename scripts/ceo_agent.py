def _журнал() -> dict:
    if ВИТРАТИ.exists():
        try:
            return json.loads(ВИТРАТИ.read_text(encoding="utf-8"))
        except Exception:
            pass
    return {"runs": [], "months": {}}


def витрачено_цього_місяця() -> float:
    міс = datetime.now(timezone.utc).strftime("%Y-%m")
    return float((_журнал().get("months") or {}).get(міс, {}).get("cost_usd", 0.0))


def записати_витрату(usage: dict, звіт_є: bool) -> float:
    ц = PRICES.get(МОДЕЛЬ) or PRICES["claude-sonnet-5"]
    ціна = round(
        usage.get("input_tokens", 0) / 1_000_000 * ц["in"]
        + usage.get("output_tokens", 0) / 1_000_000 * ц["out"]
        + usage.get("cache_read_input_tokens", 0) / 1_000_000 * ц["cache_read"]
        + usage.get("cache_creation_input_tokens", 0) / 1_000_000 * ц["cache_write"], 4)
    d = _журнал()
    міс = datetime.now(timezone.utc).strftime("%Y-%m")
    м = (d.setdefault("months", {})).setdefault(міс, {"cost_usd": 0.0, "runs": 0})
    м["cost_usd"] = round(м["cost_usd"] + ціна, 4)
    м["runs"] += 1
    d.setdefault("runs", []).insert(0, {
        "ts": int(time.time() * 1000), "model": МОДЕЛЬ,
        "cost_usd": ціна, "звіт": звіт_є, "usage": usage,
    })
    d["runs"] = d["runs"][:30]
    ВИТРАТИ.write_text(json.dumps(d, ensure_ascii=False, indent=2), encoding="utf-8")
    return ціна


def _база(шлях: str, метод: str = "GET", тіло=None):
    """REST до Supabase. Немає ключів — повертає None, і це «не заміряно»."""
    url = os.environ.get("SUPABASE_URL")
    key = os.environ.get("SUPABASE_SERVICE_KEY") or os.environ.get("SUPABASE_SERVICE_ROLE_KEY")
    if not url or not key:
        return None
    req = urllib.request.Request(
        f"{url.rstrip('/')}/rest/v1/{шлях}",
        data=json.dumps(тіло).encode() if тіло is not None else None,
        method=метод,
        headers={"apikey": key, "Authorization": "Bearer " + key,
                 "Content-Type": "application/json", "Prefer": "return=minimal"})
    try:
        with urllib.request.urlopen(req, timeout=25) as r:
            сире = r.read()
            return json.loads(сире) if сире else []
    except Exception as e:
        print(f"  ⚠ база не відповіла на {шлях}: {e}")
        return None


