def покликати(prompt: str):
    key = os.environ.get("ANTHROPIC_API_KEY")
    if not key:
        return "", {}, "немає ANTHROPIC_API_KEY"
    req = urllib.request.Request(
        "https://api.anthropic.com/v1/messages",
        data=json.dumps({
            "model": МОДЕЛЬ, "max_tokens": 4000,
            "messages": [{"role": "user", "content": prompt}],
        }).encode(),
        headers={"x-api-key": key, "anthropic-version": "2023-06-01",
                 "content-type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=180) as r:
            d = json.loads(r.read())
    except Exception as e:
        return "", {}, f"Anthropic не відповів: {e}"
    # 🔑 Читаємо ВСІ текстові блоки, а не `content[0]` — той самий запобіжник, що
    # в `ai-analytics-summary`: текстовий блок не обовʼязково перший, і `content[0].text`
    # мовчки віддавав би порожнечу.
    блоки = [b for b in (d.get("content") or []) if b.get("type") == "text"]
    текст = "\n".join(b.get("text", "") for b in блоки).strip()
    if d.get("stop_reason") == "max_tokens":
        текст += ("\n\n⚠️ Звіт обірвався: модель уперлась у стелю довжини. "
                  "Це НЕ повний звіт.")
    return текст, (d.get("usage") or {}), ""


ЗАГОЛОВОК_ЗАВДАНЬ = "ЗАВДАННЯ-ДО-РЕЄСТРУ:"


def витягти_завдання(звіт: str) -> list[str]:
    """Рядки, які агент просить занести в реєстр невиконаного.

    🔴 ЧОМУ ЧЕРЕЗ PR, А НЕ ПРЯМО В ФАЙЛ (рішення 20.09, поправка до «хай зводить»).
    Вова сказав «хай зводить» — і це правильно, бо найдорожча повторювана вада
    проєкту саме «замовлення загубилось». Але агент, який пише в реєстр сам,
    через місяць зробить реєстр наполовину агентським, і Вова перестане його
    читати — тобто ми полагодимо забування ціною уваги. PR лишає рішення за
    людиною і коштує їй один тап.
    🛑 Тому цей файл НІКОЛИ не редагує `NEVYKONANI_ZAVDANNIA.md` — він лише
    складає пропозицію поруч.
    """
    якщо_є = звіт.split(ЗАГОЛОВОК_ЗАВДАНЬ)
    if len(якщо_є) < 2:
        return []
    рядки = []
    for р in якщо_є[1].split("\n"):
        р = р.strip()
        if not р:
            # Порожній рядок після початку списку — кінець розділу.
            if рядки:
                break
            continue
        if not р.startswith("-"):
            break
        текст = р.lstrip("-").strip()
        if текст:
            рядки.append(текст)
    return рядки


def зберегти_пропозицію(завдання: list[str]) -> None:
    """Кладе пропозицію в `data/ceo_tasks_proposed.json`, звідки її бере
    воркфлов і відкриває PR. ⚠️ Порожній список теж пишемо — інакше вчорашня
    пропозиція виглядала б як сьогоднішня."""
    (КОРІНЬ / "data").mkdir(exist_ok=True)
    (КОРІНЬ / "data" / "ceo_tasks_proposed.json").write_text(
        json.dumps({"коли": datetime.now(timezone.utc).isoformat(),
                    "завдання": завдання}, ensure_ascii=False, indent=2),
        encoding="utf-8")
    if завдання:
        print(f"  📝 пропозицій до реєстру: {len(завдання)}")


def main() -> int:
    суха = "--dry-run" in sys.argv
    ctx = зібрати_контекст()
    prompt = зібрати_промпт(ctx)

    if суха:
        print(prompt)
        print(f"\n─── довжина промпта: {len(prompt)} символів ───")
        return 0

    # 🛑 БЮДЖЕТ ПЕРЕВІРЯЄТЬСЯ ДО ВИКЛИКУ, і мовчати про паузу не можна: саме
    # мовчазна пауза агента новин коштувала двох тижнів порожньої черги.
    вже = витрачено_цього_місяця()
    if вже >= СТЕЛЯ_МІС_USD:
        print(f"⏸ пауза: витрачено ${вже:.4f} зі стелі ${СТЕЛЯ_МІС_USD:.2f}")
        зберегти_звіт("", стан="пауза",
                      причина=f"місячна стеля ${СТЕЛЯ_МІС_USD:.2f} вичерпана, "
                              f"витрачено ${вже:.4f}")
        return 0

    текст, usage, помилка = покликати(prompt)
    if помилка or not текст:
        print(f"✗ звіт не склався: {помилка or 'порожня відповідь'}")
        зберегти_звіт("", стан="збій", причина=помилка or "порожня відповідь")
        return 1

    ціна = записати_витрату(usage, bool(текст))
    print(f"✓ звіт готовий ({len(текст)} символів, ${ціна:.4f})")
    зберегти_звіт(текст, стан="готово", причина="", ціна=ціна)
    зберегти_пропозицію(витягти_завдання(текст))
    print(текст)
    return 0


def зберегти_звіт(текст: str, стан: str, причина: str, ціна: float = 0.0) -> None:
    """Пише звіт у базу. ⚠️ Збій запису НЕ ховаємо: звіт, якого немає в кабінеті,
    для Вови не існує — так само, як документ, на який ніхто не посилається."""
    рядок = {
        "model": МОДЕЛЬ, "prompt_version": ВЕРСІЯ_ПРОМПТА,
        "report_text": текст, "стан": стан, "причина": причина, "cost_usd": ціна,
    }
    ок = _база("ceo_reports", "POST", рядок)
    if ок is None:
        print("  ⚠ звіт НЕ записаний у базу (немає ключів або база не відповіла)")
        (КОРІНЬ / "data").mkdir(exist_ok=True)
        (КОРІНЬ / "data" / "ceo_report_last.json").write_text(
            json.dumps({**рядок, "коли": datetime.now(timezone.utc).isoformat()},
                       ensure_ascii=False, indent=2), encoding="utf-8")
        print("  💾 збережено локально в data/ceo_report_last.json")


if __name__ == "__main__":
    sys.exit(main())
