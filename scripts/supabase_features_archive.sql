-- 🗣️ «Екран завантаження я вже побачив і натиснув усім. Але воно так і буде
-- висіти в загальному списку? Чи може окремий список / вкладку зробимо?»
--
-- 📐 ЗАМІРЯНО НА ЖИВІЙ БАЗІ ПЕРЕД РОБОТОЮ: у `app_features` ОДИН рядок —
-- `skeleton_shapes`, стан `all`, випущено 19.09 19:59. І він сидить під
-- заголовком «Що зараз тестуємо», тобто заголовок уже бреше на єдиному рядку,
-- який там є. Прибрати його з екрана не можна нічим: ні поля, ні кнопки.
--
-- 🔑 ЩО ТАКЕ «АРХІВ» І ЧОГО ВІН НЕ РОБИТЬ.
-- Життя прапорця: народився `off` → `circle` (Вова тапає) → `all` (годиться) →
-- **прапорець знімається з КОДУ** → перемикач більше нікому не потрібен.
-- Архів позначає саме останній крок. Це БУХГАЛТЕРІЯ, а не дія над застосунком.
--
-- 🛑 І САМЕ ТОМУ `my_features()` ЗАЛИШЕНО НЕДОТОРКАНИМ — це головне рішення
-- цього файлу. Напрошується «архівована → не віддавати клієнту», і воно
-- небезпечне: якщо прапорець насправді ще стоїть у коді (людина натиснула
-- «Прибрано», а зняти забула), `featureOn()` поверне `false` і фіча ТИХО
-- ВИМКНЕТЬСЯ в усієї громади. Тобто дія «прибрати перемичку з екрана адмінки»
-- вимкнула б робочу фічу людям. Архів ховає рядок ЛИШЕ в адмінці.
--
-- 🛑 АРХІВУВАТИ МОЖНА ЛИШЕ ТЕ, ЩО ВЖЕ В УСІХ. Недороблене (`off`) і те, що на
-- перевірці (`circle`), сховати не можна: це був би спосіб забути про роботу,
-- яку не закінчили.
--
-- ✅ НАКАТАНО 20.09 (міграція `feature_archive`) і доведено на живій базі
-- транзакціями з відкотом — 9 перевірок під JWT власника і сторонньої людини:
--   A. архівувати фічу в стані `all`                         → {"ok": true}
--   B. `archived_at` проставився                             → true
--   C. 🔴 `my_features()` про АРХІВОВАНУ                      → {"on": true, "stage": "all"}
--   D. повернути з архіву                                    → {"ok": true}
--   E. `archived_at` знявся                                  → true
--   F. 🛑 архівувати `circle`                                 → «Прибрати можна лише фічу, яка вже працює в усіх»
--   G. 🛑 архівувати неіснуючу                                → «Такої фічі немає»
--   H. 🛑 стороння людина архівує                             → «Немає права керувати оновленнями»
--   I. 🛑 стороння людина повертає з архіву                   → «Немає права керувати оновленнями»
--
-- ⚠️ ПОМИЛКА ВИМІРУ, ЯКОЇ ВАРТО УНИКНУТИ НАСТУПНОГО РАЗУ. Перша спроба зібрала
-- всі кроки в ОДИН `select ... union all ...`. Гілки такого запиту читають
-- ЗНІМОК на початок ЗАПИТУ, тож крок B віддав `false` над уже зміненим рядком —
-- тобто прилад «довів» би, що архівування не працює. Кроки мусять бути окремими
-- операторами (тут — вставками у тимчасову таблицю).
-- ============================================================================

alter table public.app_features
  add column if not exists archived_at timestamptz;

-- Повернути з архіву теж мусить бути можливо: натиснути не те легко, а
-- одностороння дія без вороття — це пастка, а не захист.
create or replace function public.archive_feature(p_key text, p_on boolean default true)
returns jsonb
language plpgsql security definer set search_path = public
as $fn$
declare v_stage text;
begin
  if not public.has_perm('updates','manage') then
    return jsonb_build_object('ok', false, 'error', 'Немає права керувати оновленнями');
  end if;
  select stage into v_stage from app_features where key = p_key;
  if v_stage is null then
    return jsonb_build_object('ok', false, 'error', 'Такої фічі немає');
  end if;
  -- 🔑 Межа з шапки файлу: ховати можна лише завершене.
  if p_on and v_stage <> 'all' then
    return jsonb_build_object('ok', false, 'error', 'Прибрати можна лише фічу, яка вже працює в усіх');
  end if;
  update app_features
     set archived_at = case when p_on then now() else null end,
         changed_by  = auth.uid()
   where key = p_key;
  return jsonb_build_object('ok', true);
end;
$fn$;

revoke execute on function public.archive_feature(text, boolean) from public, anon;
grant  execute on function public.archive_feature(text, boolean) to authenticated;
