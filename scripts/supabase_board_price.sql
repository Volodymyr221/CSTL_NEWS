-- Повний текст обох функцій — у міграціях Supabase
-- (`board_price_support_submit`, `board_price_support_update`).
-- Ключові правила, однакові в обох:
--   • ціна дозволена лише для категорій ('продам','послуга','куплю');
--     'віддам' СВІДОМО не тут — воно безкоштовне за визначенням, і слово «Безкоштовно»
--     малює клієнт, а не збережене число;
--   • price парситься через безпечне приведення в BEGIN/EXCEPTION — `payload->>'price'`
--     може бути будь-чим, типу довіряти не можна;
--   • price < 0 → «Ціна не може бути відʼємною»;
--   • price > 100000000 → «Завелика ціна» (без стелі хтось вписав би 10^20 і зламав
--     верстку картки);
--   • round(price, 2);
--   • категорія без ціни → price = null, negotiable = false (навіть якщо клієнт надіслав);
--   • число і «договірна» взаємовиключні, ЧИСЛО має пріоритет (людина таки назвала ціну);
--   • currency НЕ беремо від клієнта — форсимо 'UAH' (у громаді розрахунки в гривні).
--
