-- Колонки `price` (numeric) і `currency` (text default 'UAH') стояли в `posts` з самого
-- початку — див. `supabase_schema.sql:72-73`. Але НІ клієнт, НІ RPC їх не торкались:
-- `grep -rn "price" src/ admin.html` не давав жодної згадки, а в `insert` функції
-- `submit_board_post` цих колонок просто не було в списку. Тобто поле лежало МЕРТВИМ.
-- Тому «додати ціну» — це не міграція даних, а навчити дві функції її писати.
--
-- ⚠️ ЧОМУ ОКРЕМА КОЛОНКА `price_negotiable`, А НЕ МАРКЕР У `price`:
-- «договірна» і «не вказано» — РІЗНІ стани, і сортування за ціною (потік 3) мусить їх
-- розрізняти. Хак `price = -1` зламав би сортування, унеможливив майбутнє «від N до M»,
-- а наступна сесія не зрозуміла б, що це маркер, а не дані.
--
-- ⚠️ ЧОМУ ВАЛІДАЦІЯ В БАЗІ, А НЕ ЛИШЕ В ФОРМІ:
-- RPC можна викликати напряму, в обхід застосунку. Тому саме сервер вирішує, для яких
-- категорій ціна має сенс, і сам витирає її для решти — інакше в «Загубився кіт» колись
-- зʼявилась би ціна, і сортування за ціною стало б сміттям. Та сама причина, через яку
-- антиспам живе в базі (`text_abuse_reason`), а не лише в `src/core/utils.js`.
--
-- 🔴 ДВІ КОПІЇ ВАЛІДАЦІЇ — і це неминуче: `submit_board_post` і `update_board_post` це
-- дві окремі функції. **Міняєш умову в одній — міняй у другій.** У проєкті вже був баг
-- саме через дві копії, що розійшлись (списки антиспаму).
--
-- ⚠️ ПАСТКА, ЯКУ ЗАКРИВАЄ ЧАСТИНА 2: `update` перелічує колонки явно. Якби ціну додали
-- лише в `submit`, правка оголошення не змінювала б ціну взагалі; а варіант із `price`
-- без перевірки категорії — СТИРАВ би її при перемиканні категорії не туди.
-- Навпаки, витирання при зміні категорії («Продам» → «Загубилось») тут НАВМИСНЕ.
--
-- 📊 ЗАМІРЯНО НА ЖИВІЙ БАЗІ (усе в транзакції з відкотом, сміття не лишилось):
--   Продам 4500.50            → price=4500.50, negot=false
--   Продам «договірна»        → price=NULL,    negot=true
--   Загубилось з ціною 999    → price=NULL,    negot=false   (сервер витер)
--   Продам 120 + «договірна»  → price=120.00,  negot=false   (число перемогло)
--   Віддам з ціною 50         → price=NULL,    negot=false   (сервер витер)
-- Плюс помилки валідації: відʼємна · не число · завелика · без заголовка — усі спрацювали.

-- ── ЧАСТИНА 1: колонка «договірна» ───────────────────────────────────────────
alter table public.posts
  add column if not exists price_negotiable boolean not null default false;

comment on column public.posts.price_negotiable is
  'Ціна договірна: товар продається, але число не вказане. Взаємовиключне з price (див. submit_board_post).';

