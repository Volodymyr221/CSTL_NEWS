#!/usr/bin/env python3
"""Стенд: ЗВОРОТНІ РЕЙСИ — розрахунок «туди → назад».

🔴 РОЗБЛОКОВУЄ А-1, яка стояла з 03.07.2026. Діагноз тоді: VOPAS зворотних рейсів
не віддає (Олика для нього — проміжна зупинка), «кодом це не лікується, потрібне
ІНШЕ джерело». Джерело дав Вова 05.09 — шість ланцюжків зі своїх спостережень.

🗣️ Його правило дослівно: «якщо автобус, який їде туди, відмінено, то… його і не
буде зворотнім рейсом». Тому зворотний рейс тут ПОХІДНИЙ, а не окремий запис.

📐 НАЙЦІННІША ПЕРЕВІРКА ТУТ — ЧУЖЕ ЧИСЛО. Вова сказав, що рейс із Жорнища о 06:45
стоїть в Олиці о 07:00. Це число НЕ бралося з нашої формули — воно прийшло ззовні,
тож збіг доводить сам задум («ті самі зупинки навпаки, та сама тривалість»), а не
те, що код узгоджений сам із собою.
"""
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
spec = importlib.util.spec_from_file_location("pv", ROOT / "scripts" / "parse_vopas.py")
pv = importlib.util.module_from_spec(spec)
sys.modules["pv"] = pv
spec.loader.exec_module(pv)

ok_count = fail_count = 0


def ok(назва, умова, деталь=""):
    global ok_count, fail_count
    if умова:
        ok_count += 1
        print(f"✅ {назва}" + (f"  — {деталь}" if деталь else ""))
    else:
        fail_count += 1
        print(f"❌ {назва}" + (f"  — {деталь}" if деталь else ""))


# ── Сцена: справжній прямий рейс «Луцьк Жорнище», на якому Вова назвав число ──
# ⚠️ Кілометраж і тривалість — РЕАЛЬНІ з `data/schedule.json`, а не вигадані:
# на круглих числах збіг 07:00 нічого не довів би.
ЗУПИНКИ = [
    ("Луцьк", 0.0), ("Струмівка", 7.5), ("Гаразджа", 10.0), ("Піддубці", 13.5),
    ("Звірів", 18.0), ("Арматнів", 22.0), ("Пальче", 24.5), ("Хорлупи", 29.3),
    ("Покащів", 31.8), ("Одеради", 36.1), ("Хромяків", 38.1), ("Дідичі", 40.6),
    ("Олика", 43.1), ("Чемерин", 46.6), ("Носовичі", 49.7), ("Жорнище", 52.4),
]


def прямий(dep="20:05", status="scheduled", rid="vopas_1"):
    return {
        "id": rid, "name": "Луцьк Жорнище", "carrier": "черняк", "bus": "БАЗ",
        "days": "щодня", "status": status, "sale_active": True,
        "departure_time": dep, "arrival_time": "21:30", "duration_min": 85,
        "auto_generated": False, "vopas_url": "https://vopas.com.ua/x",
        "stops": [{"name": n, "km": k, "price_from_start": 50} for n, k in ЗУПИНКИ],
    }


def день(рейси):
    return {"routes": list(рейси), "fetchedAt": "05.09.2026", "fetchedTime": "22:00"}


# ── 1. 🔴 ЧУЖЕ ЧИСЛО: Жорнище 06:45 → Олика 07:00 ──────────────────────────
дні = {"2026-09-05": день([прямий()]), "2026-09-06": день([])}
pv.додати_зворотні(дні)
зв = [r for r in дні["2026-09-06"]["routes"] if r.get("auto_generated")]
ok("зворотний рейс із учорашнього вечірнього побудований", len(зв) == 1, f"{len(зв)}")

if зв:
    r = зв[0]
    # Час зупинки рахує КЛІЄНТ, тією самою формулою, що для прямих рейсів:
    # відправлення + (км / усього км) × тривалість (`core/bus-schedule.js`).
    усього = r["stops"][-1]["km"]
    олика = next(s for s in r["stops"] if s["name"] == "Олика")
    хв = pv.hhmm_to_min(r["departure_time"]) + round(олика["km"] / усього * r["duration_min"])
    ok("🔴 ЧИСЛО ВОВИ: о 07:00 автобус в Олиці", pv._хв_у_ччмм(хв) == "07:00", pv._хв_у_ччмм(хв))
    ok("зворотний починається там, де прямий закінчувався",
       r["stops"][0]["name"] == "Жорнище" and r["stops"][-1]["name"] == "Луцьк")
    ok("кілометраж перерахований від нового початку",
       r["stops"][0]["km"] == 0.0 and abs(r["stops"][-1]["km"] - 52.4) < 0.05,
       f'{r["stops"][0]["km"]} → {r["stops"][-1]["km"]}')
    ok("тривалість успадкована", r["duration_min"] == 85)
    ok("перевізник успадкований", r["carrier"] == "черняк")
    ok("рейс позначений як розрахований", r["auto_generated"] is True)
    ok("видно, з чого порахований", r["reverse_of"] == "vopas_1" and r["reverse_of_date"] == "2026-09-05")
    # 🛑 Ціну не переносимо: тариф у зворотному напрямку нам ніхто не називав.
    ok("🛑 ціна НЕ вигадана", all(s["price_from_start"] is None for s in r["stops"]))
    # 🛑 Посилання веде на сторінку ПРЯМОГО рейсу — тобто описувало б інший рейс.
    ok("🛑 посилання на VOPAS не перенесено", r["vopas_url"] is None)

# ── 2. 🔴 СКАСУВАННЯ ПРЯМОГО ГАСИТЬ ЗВОРОТНИЙ ──────────────────────────────
дні = {"2026-09-05": день([прямий(status="cancelled")]), "2026-09-06": день([])}
pv.додати_зворотні(дні)
зв = [r for r in дні["2026-09-06"]["routes"] if r.get("auto_generated")]
ok("🔴 скасований прямий → зворотний теж скасований (правило Вови)",
   len(зв) == 1 and зв[0]["status"] == "cancelled",
   зв[0]["status"] if зв else "рейсу немає")

# 🛑 КОНТРОЛЬ: перевірка вище мусить уміти впасти — на справному прямому стан інший.
дні = {"2026-09-05": день([прямий(status="scheduled")]), "2026-09-06": день([])}
pv.додати_зворотні(дні)
зв = [r for r in дні["2026-09-06"]["routes"] if r.get("auto_generated")]
ok("КОНТРОЛЬ: незачеплений прямий → зворотний не скасований",
   len(зв) == 1 and зв[0]["status"] == "scheduled")

# ── 3. НЕМАЄ ПРЯМОГО — НЕМАЄ ЗВОРОТНОГО (не вигадуємо) ─────────────────────
дні = {"2026-09-06": день([])}
pv.додати_зворотні(дні)
ok("🛑 без прямого зворотний НЕ вигадується",
   not [r for r in дні["2026-09-06"]["routes"] if r.get("auto_generated")])

# ── 4. ІДЕМПОТЕНТНІСТЬ: парсер ганяється щогодини ──────────────────────────
дні = {"2026-09-05": день([прямий()]), "2026-09-06": день([прямий(dep="20:05", rid="vopas_2")])}
pv.додати_зворотні(дні)
перший = len(дні["2026-09-06"]["routes"])
pv.додати_зворотні(дні)
pv.додати_зворотні(дні)
ok("🔑 повторні прогони не плодять дублів", len(дні["2026-09-06"]["routes"]) == перший,
   f"{перший} → {len(дні['2026-09-06']['routes'])}")

# ── 5. ДОПУСК ЧАСУ: Вова назвав 10:05, у базі 10:06 ────────────────────────
# ⚠️ Розклад перевізника «пливе» на хвилину, і назване людиною число не
# зобовʼязане збігатися з базою посимвольно. Але допуск мусить лишатись ВУЗЬКИМ:
# інакше він почав би чіпляти сусідній рейс того самого напрямку.
жорнище_денний = прямий(dep="10:06", rid="vopas_3")
жорнище_денний["duration_min"] = 119
дні = {"2026-09-06": день([жорнище_денний])}
pv.додати_зворотні(дні)
зв = [r for r in дні["2026-09-06"]["routes"] if r.get("auto_generated")]
ok("⚠️ «10:05» від людини знаходить «10:06» у базі",
   any(r["departure_time"] == "12:45" for r in зв), [r["departure_time"] for r in зв])

далекий = прямий(dep="10:20", rid="vopas_4")
дні = {"2026-09-06": день([далекий])}
pv.додати_зворотні(дні)
ok("🛑 КОНТРОЛЬ: допуск вузький — 10:20 уже НЕ той рейс",
   not [r for r in дні["2026-09-06"]["routes"] if r.get("auto_generated") and r["departure_time"] == "12:45"])

# ── 6. НА ЖИВИХ ДАНИХ ──────────────────────────────────────────────────────
d = json.loads((ROOT / "data" / "schedule.json").read_text(encoding="utf-8"))
повні = [iso for iso, v in d["days"].items() if len(v.get("routes") or []) > 20]
if повні:
    iso = sorted(повні)[len(повні) // 2]
    зв = [r for r in d["days"][iso]["routes"] if r.get("auto_generated")]
    ok("на живому повному дні побудовані всі шість ланцюжків", len(зв) == 6, f"{iso}: {len(зв)}")
    ok("усі зворотні йдуть ДО Луцька",
       all(r["stops"][-1]["name"] == "Луцьк" for r in зв),
       ", ".join(f"{r['departure_time']} {r['name']}" for r in зв))

print(f"\n{'❌' if fail_count else '✅'} {ok_count}/{ok_count + fail_count} перевірок пройдено")
sys.exit(1 if fail_count else 0)
