create or replace function public.nudge_rss_parser()
returns void
language plpgsql
set search_path to 'public', 'extensions'
as $function$
declare
  секрет text;
begin
  -- 🔑 Секрет НЕ в тексті розкладу (на відміну від `send-bus-push`): читається
  -- тут, у момент виклику, тож ротація не вимагає чіпати `cron.job`.
  select value into секрет from public.app_secrets where name = 'page_push_secret';
  if секрет is null or секрет = '' then
    return;
  end if;

  perform net.http_post(
    url     := 'https://uabyfecseqnemvcqhdem.supabase.co/functions/v1/nudge-parser',
    headers := jsonb_build_object(
      'Content-Type',        'application/json',
      'Authorization',       'Bearer sb_publishable_sbV0XNktCiTK0iA4659P9g_Y3sT0mDv',
      'x-cstl-push-secret',  секрет),
    body    := '{}'::jsonb);
end;
$function$;

revoke execute on function public.nudge_rss_parser() from public, anon, authenticated;

