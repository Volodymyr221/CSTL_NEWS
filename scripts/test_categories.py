#!/usr/bin/env python3
"""Сторож класифікатора категорій новин (баг B-28).

🔴 НАВІЩО. 30.08 класифікатор переписали: було три теми і 93.5% статей у
«Суспільстві», стало десять і 3.0%. Усі вади тут ТИХІ — ніщо не падає і не
пише в консоль:
  • правило зачепило зайве («загинув» → кожне ДТП ставало Війною);
  • назва категорії розійшлась із `CATEGORY_COLORS` у `src/tabs/news.js`, і
    клієнт мовчки звів її назад у «Суспільство» — тобто вся робота парсера
    зникла, а на вигляд усе ціле;
  • перерозклад збережених затер рукописну категорію з редактора кабінету.
Побачити це можна лише ВИКОНАВШИ класифікатор і порахувавши результат.

Запуск:  python3 scripts/test_categories.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import parse_rss as P

# 🔑 Дістаємо через getattr, а не прямо: на КОНТРОЛІ (старий `origin/main`) цих імен
# ще немає, і стенд мусить показати ЧЕРВОНІ РЯДКИ, а не впасти зі стектрейсом —
# інакше з контролю не видно, що саме він стереже.
CAT_DEFAULT = getattr(P, "CATEGORY_DEFAULT", "Суспільство")
CAT_VERSION = getattr(P, "CATEGORY_VERSION", None)
recategorize = getattr(P, "recategorize_stored_articles", None)

fails = []


def check(name, cond, info=""):
    print(("  ✓ " if cond else "  ✗ ") + name + (f"  — {info}" if info else ""))
    if not cond:
        fails.append(name)


# ── 1. ДВА СПИСКИ НАЗВ МУСЯТЬ ЗБІГАТИСЬ ──────────────────────────────────────
# 🔑 Найдорожча вада всієї фічі і водночас найтихіша: парсер пише «Надзвичайне»,
# у клієнті такої назви немає — `normCategory` зводить її в «Суспільство», і
# зовні це не відрізнити від «класифікатор не спрацював».
news_js = (ROOT / "src/tabs/news.js").read_text(encoding="utf-8")
block = re.search(r"const CATEGORY_COLORS = \{(.*?)\n\};", news_js, re.S)
client = set(re.findall(r"^\s*'([^']+)'|^\s*\"([^\"]+)\"", block.group(1), re.M))
client = {a or b for a, b in client}
parser = {c for c, _ in P._CATEGORY_RULES} | {CAT_DEFAULT}

check("назви парсера і клієнта збігаються", client == parser,
      f"лише в парсері: {sorted(parser - client)} · лише в клієнті: {sorted(client - parser)}")

alias = re.search(r"const CATEGORY_ALIAS = \{(.*?)\n\};", news_js, re.S).group(1)
alias_targets = set(re.findall(r":\s*'([^']+)'|:\s*\"([^\"]+)\"", alias))
alias_targets = {a or b for a, b in alias_targets}
check("звід веде тільки в наявні категорії", alias_targets <= client,
      f"невідомі цілі: {sorted(alias_targets - client)}")

# ── 2. РЕГРЕСІЇ, ЯКІ ВЖЕ ТРАПЛЯЛИСЬ ──────────────────────────────────────────
# Кожен рядок нижче — справжній заголовок із живих даних, на якому класифікатор
# помилявся до 30.08.
check("ДТП із словом «загинув» — це НЕ війна",
      P.detect_category("На Волині в ДТП загинув 18-річний мотоцикліст: що відомо") == "Надзвичайне")
check("«транспортні» не робить статтю Спортом",
      P.detect_category("У Луцьку через транспортні проблеми змінили маршрут") != "Спорт")
check("воєнний заголовок лишається Війною",
      P.detect_category("На війні загинув Герой з Волині Олег Адамчук") == "Війна")
check("погода — окрема тема, а не «Суспільство»",
      P.detect_category("Дощ, гроза і сильний вітер: погода на Волині 29 серпня") == "Природа")
check("місцевий футбол доходить до Спорту",
      P.detect_category("ФК «Олика» виборов «бронзу» на домашньому турнірі «OLYKA CUP 2026»") == "Спорт")

# 🔑 РАХУНОК ПЕРЕВАЖАЄ ПОРЯДОК. До 30.08 забирало перше правило, що зачепилось,
# тож порядок списку важив більше за зміст статті.
check("більший рахунок перемагає, а не місце в списку",
      P.detect_category("Спортсмен розповів, як росіяни атакували Запоріжжя дронами") == "Війна")

# 🔑 ОПИС — ЛИШЕ ЗАПАСНИЙ. Заголовок, що дав хоч один збіг, опис уже не питає:
# інакше повернувся б шум тіла статті, через який 21.07 і залишили тільки заголовок.
check("заголовок-загадка звертається до опису",
      P.detect_category("Лізли через вікно: у Нововолинську рятували чоловіка",
                        "рятувальники ДСНС відчинили двері квартири") == "Надзвичайне")
check("заголовок зі змістом опис НЕ перебиває",
      P.detect_category("Концерт у Луцьку", "матч, турнір, чемпіонат, кубок") == "Культура")

# ── 3. ЖИВІ ДАНІ: «СУСПІЛЬСТВО» БІЛЬШЕ НЕ СМІТНИК ────────────────────────────
# 📐 Стеля, а не знімок: заміряно 3.0%, беремо 25% із запасом. Стенд має ловити
# повернення вади (десятки відсотків), а не хитання на пів відсотка.
arts = json.loads((ROOT / "data/articles.json").read_text(encoding="utf-8"))
got = [P.detect_category(a.get("title", ""), a.get("excerpt", "")) for a in arts]
share = 100.0 * got.count(CAT_DEFAULT) / max(len(arts), 1)
check("«Суспільство» не забирає стрічку", share <= 25.0, f"{share:.1f}% з {len(arts)} статей")

# Кожна оголошена категорія мусить бодай щось ловити на живих даних — інакше це
# мертва назва, яка лише додає фішку у фільтр і ніколи її не наповнює.
порожні = [c for c, _ in P._CATEGORY_RULES if c not in got]
check("жодна категорія не порожня на живих даних", not порожні, f"порожні: {порожні}")

# ── 4. ПЕРЕРОЗКЛАД ЗБЕРЕЖЕНИХ ────────────────────────────────────────────────
зразок = [
    {"title": "На війні загинув Герой з Волині", "excerpt": "", "category": "Суспільство"},
    {"title": "Метельне: дерев'яна Покровська церква", "excerpt": "",
     "category": "Історія краю", "kind": "editor"},
    {"title": "Скарби Радзивіллів і привид пані: легенди Олики", "excerpt": "",
     "category": "Історія", "kind": "story"},
]
змінено = recategorize(зразок) if recategorize else -1
check("новини перерозкладає, рукописне — ні", зразок[0]["category"] == "Війна" and змінено == 1,
      "функції `recategorize_stored_articles` немає" if not recategorize else "")
# 🛑 Категорію рукописної статті писала ЛЮДИНА в редакторі кабінету. Затерти її
# означало б переписати чужу роботу — і саме це найлегше зробити не помітивши.
check("рукописну статтю з редактора НЕ чіпає", зразок[1]["category"] == "Історія краю")
# 🛑 Історії Олики (`data/olyka-stories.json`) — теж рукописні, але `kind` у них
# ІНШИЙ. Перша версія перерозкладу пропускала лише `editor` і переписала б усі пʼять.
# Тому правило — «є будь-який `kind` → не чіпаємо», а не перелік відомих значень.
check("історію Олики (kind=story) теж НЕ чіпає", зразок[2]["category"] == "Історія")
check("другий прогін нічого не робить", bool(recategorize) and recategorize(зразок) == 0)
# 🔑 Пастка, в яку я вже вступив: якщо повертати «скільки ЗМІНЕНО», то стаття з уже
# правильною категорією дає 0 — парсер вирішує, що зберігати нічого, позначка `_cat`
# не доїжджає на диск, і наступний прогін робить ту саму роботу знову. Вічно.
вже_правильна = [{"title": "На війні загинув Герой з Волині", "excerpt": "", "category": "Війна"}]
check("стаття з уже правильною категорією теж рахується",
      bool(recategorize) and recategorize(вже_правильна) == 1,
      "інакше позначка версії ніколи не збережеться")
check("версія правил проставлена", CAT_VERSION is not None and зразок[0].get("_cat") == CAT_VERSION)
# Версію піднімають разом із правилами — інакше вже збережені статті лишаться зі
# старою розкладкою, і покращення класифікатора буде видно лише через тиждень.
check("версія правил — ціле число, більше за початкове",
      isinstance(CAT_VERSION, int) and CAT_VERSION >= 2)

print(f"\n{'УСЕ ЗЕЛЕНЕ' if not fails else 'ПРОВАЛИ: ' + ', '.join(fails)}")
sys.exit(1 if fails else 0)
