-- ✅ НАКАТАНО НА ПРОД (міграція `push_subscriptions_select_own`).
--
-- 🔴 СИМПТОМ. Тап по «відстежувати рейс» → тост «Не вдалося увімкнути
-- сповіщення». У логах Postgres тієї ж секунди:
--     42501  new row violates row-level security policy for table "push_subscriptions"
-- Таблиця при цьому мала **0 рядків** — тобто жодна підписка не створилась НІКОЛИ,
-- і автобусні сповіщення не працювали з самого початку.
--
-- 🔑 ПРИЧИНА. Клієнт зберігає підписку через
--     .upsert(payload, { onConflict: 'endpoint,route_id,track_date' })
-- тобто `INSERT ... ON CONFLICT DO UPDATE`. Щоб виконати гілку `DO UPDATE`,
-- Postgres мусить **прочитати** конфліктний рядок — а SELECT-політики для ролі
-- `authenticated` не існувало взагалі: читати могла тільки `service_role`
-- (`push_select ... TO service_role USING (true)`).
-- Через це падала ВСЯ операція, хоча INSERT-політика правильна і збіг
-- `user_uuid = auth.uid()::text` теж правильний.
--
-- ⚠️ Найпідступніше тут те, що помилка вказує на INSERT («new row violates…»),
--    тобто веде розслідування зовсім не туди. Саме тому дві попередні спроби
--    (insert→upsert, uid з живої сесії замість кешу) нічого не змінили: вони
--    лікували те, що й так було справним.
--
-- ✅ ДОВЕДЕНО ЕКСПЕРИМЕНТОМ на живій базі — роль і JWT підставлені так само, як
--    це робить PostgREST для запиту залогіненої людини:
--
--      set_config('role', 'authenticated');
--      set_config('request.jwt.claims', '{"sub":"<реальний uid>","role":"authenticated"}');
--
--      чистий INSERT того самого рядка …………… OK
--      той самий рядок через ON CONFLICT ……… 42501  ← симптом відтворено
--      SELECT власних рядків ………………………… «видно 0», хоча рядок існує
--
--    Після додавання політики нижче, у тих самих умовах:
--      ON CONFLICT ………………………………………… OK
--      SELECT ……………………………………………………… «видно 1»
--
-- 🛑 ЩО ЦЕ **НЕ** ПОСЛАБЛЮЄ. Політика вузька: людина бачить лише СВОЇ підписки
--    (`user_uuid = auth.uid()`), як і в решті таблиць проєкту. Доступу до чужих
--    рядків не зʼявляється; `service_role` (Edge Function `send-bus-push`) читає
--    все, як і читала.
-- ============================================================================

create policy "push_select_own"
  on public.push_subscriptions
  for select
  to authenticated
  using (user_uuid = (auth.uid())::text);

-- ── ЩО ПЕРЕВІРЕНО ЗАРАЗОМ І ВИЯВИЛОСЬ НЕ ПРИЧИНОЮ ───────────────────────────
-- • Тригерів на `push_subscriptions` немає (0) — підміни `user_uuid` у BEFORE
--   INSERT, яка теж дала б 42501, не існує.
-- • `anon` НЕ має гранту INSERT (лише SELECT/REFERENCES/TRIGGER/TRUNCATE), тож
--   запит від анонімної ролі дав би «permission denied», а не RLS-помилку —
--   тобто токен долітав правильно, роль була `authenticated`.
-- • Тип колонки `user_uuid TEXT` проти `auth.uid()::text` — коректний каст,
--   порівняння `text = text`. Не причина.
-- • Дубльовані PERMISSIVE-політики (`push_insert` + `Auth insert own push sub`,
--   і так само для UPDATE/DELETE) нічого не ламають: PERMISSIVE комбінуються
--   через OR. Це зайвий шум, прибирати можна окремо і свідомо.
--
-- ⚠️ НАСЛІДОК ДЛЯ БУДЬ-ЯКОЇ ІНШОЇ ТАБЛИЦІ ПРОЄКТУ: якщо клієнт пише в неї через
--    `upsert`, їй ПОТРІБНА не лише INSERT/UPDATE, а й SELECT-політика на власні
--    рядки. Інакше вада повториться слово в слово — з повідомленням, що вказує
--    на INSERT.
