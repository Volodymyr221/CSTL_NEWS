#
# 🔑 ПРАВИЛО №14: беремо ЗМІСТ, не оформлення. Парсер каже «це фото з підписом» —
# як воно виглядає, вирішує CSS. Тому тут перевіряється лише СТРУКТУРА і ВІДСІВ.
#
# 🛑 ЩО САМЕ МІРЯЄМО, і чому кожне:
#   • фото лишається НА СВОЄМУ МІСЦІ між абзацами — інакше воно ілюструє не той
#     абзац, і стаття починає брехати;
#   • підпис зберігається — це єдине, що пояснює, ЩО на знімку;
#   • обкладинка не дублюється — вона вже стоїть угорі статті;
#   • дрібні значки й лічильники не проходять — інакше в тілі зʼявляться логотипи,
#     аватарки авторів і рекламні піксели розміром 1×1.
def тіло_з_фото(html_, base="", cover=""):
    """Як `тіло()`, але передає адресу обкладинки — якщо парсер її вже приймає."""
    el = BeautifulSoup(html_, "html.parser")
    п = inspect.signature(P._blocks_to_html).parameters
    kw = {}
    if base and "base_url" in п:
        kw["base_url"] = base
    if cover and "cover_url" in п:
        kw["cover_url"] = cover
    return P._blocks_to_html(el, "", **kw)


