def прогін(arts, віддає):
    викликів["n"] = 0

    # ⚠️ Підпис дзеркалить СПРАВЖНІЙ: 27.08 у `fetch_full_article` зʼявився третій
    # аргумент (адреса обкладинки), заглушка лишилась із двома — виклик падав на
    # TypeError, який `rehydrate` мовчки ловить, і стенд показав «звернень: 0».
    # Тобто розходження підписів виглядало як «механізм не працює».
    # 🔴 Того ж дня функція розділилась ще раз: `fetch_article_page` віддає ПАРУ
    # (тіло, обкладинка), а `fetch_full_article` лишилась обгорткою для
    # AI-редактора. Підміняти треба ту, яку зве rehydrate, — інакше та сама
    # тиша: «звернень: 0» замість «механізм не працює».
    # 🔴 27.08 (ніч) — функція віддає вже ТРІЙКУ: третім іде КІНЦЕВА адреса після
    # редиректів (до неї зводяться відносні посилання статті). Заглушка з парою
    # знову дала б `TypeError`, який `rehydrate` мовчки ловить, тобто «звернень: 1»
    # і жодного перебору — виглядало б як «механізм не працює».
    def підміна(url, title="", cover_url=""):
        викликів["n"] += 1
        return віддає, "", url

    P.fetch_article_page = підміна
    try:
        return P.rehydrate_short_articles(arts)
    finally:
        P.fetch_article_page = справжній_fetch


