class _Відповідь:
    """⚠️ `geturl()` тут не для повноти: саме він каже, ДЕ ми опинились після
    редиректів, і саме до цієї адреси зводяться відносні посилання статті."""
    def __init__(self, raw, кінцева): self._raw, self._url = raw, кінцева
    def read(self, n=None): return self._raw
    def geturl(self): return self._url
    def __enter__(self): return self
    def __exit__(self, *a): return False


class _Опенер:
    def __init__(self, raw, кінцева): self._raw, self._url = raw, кінцева
    def open(self, req, timeout=None): return _Відповідь(self._raw, self._url)


