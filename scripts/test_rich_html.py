# ── 5. САМОЛІКУВАННЯ: ЧИ ПЕРЕБЕРУТЬСЯ ВЖЕ ЗБЕРЕЖЕНІ СТАТТІ ───────────────────
#
# 🔴 БЕЗ ЦЬОГО ПІВ РОБОТИ НЕ ДОЇДЕ ДО ЛЮДИНИ. Парсер дедуплікує за URL, тож
# виправлення розмітки побачили б лише НОВІ статті, а всі 400 наявних лишились би
# зі стертими посиланнями. Механізм є (`rehydrate_short_articles` + версія правил),
# і тут перевіряється, що він справді бере повні статті, не бере зайвого і — це
# найважливіше — не псує те, що вже працює.
#
# ⚠️ Мережу підміняємо: стенд не має ходити на чужі сайти. Підміна ще й дозволяє
# перевірити випадок «сторінка не відповіла», якого інакше не відтворити.
викликів = {"n": 0}
справжній_fetch = P.fetch_full_article


def стаття(**kw):
    a = {"title": "Тест", "sourceUrl": "https://konkurent.ua/news/1",
         "content": "<p>Старий текст статті без посилань, довжиною понад сорок символів.</p>",
         "excerpt": "Старий текст статті без посилань, довжиною понад сорок символів.",
         "fullText": True}
    a.update(kw)
    return a


def прогін(arts, віддає):
    викликів["n"] = 0

    # ⚠️ Підпис дзеркалить СПРАВЖНІЙ: 27.08 у `fetch_full_article` зʼявився третій
    # аргумент (адреса обкладинки), заглушка лишилась із двома — виклик падав на
    # TypeError, який `rehydrate` мовчки ловить, і стенд показав «звернень: 0».
    # Тобто розходження підписів виглядало як «механізм не працює».
    def підміна(url, title="", cover_url=""):
        викликів["n"] += 1
        return віддає

    P.fetch_full_article = підміна
    try:
        return P.rehydrate_short_articles(arts)
    finally:
        P.fetch_full_article = справжній_fetch


НОВИЙ = ('<p>Старий текст статті без посилань, довжиною понад сорок символів, '
         'а ще <a href="https://www.facebook.com/olykarada/posts/1" target="_blank" '
         'rel="noopener">посилання</a>.</p>')

# А. Повна стаття зі СТАРОЮ розміткою — має перебратись.
a1 = стаття()
змінено = прогін([a1], НОВИЙ)
ok("повна стаття зі старою розміткою перебирається",
   викликів["n"] == 1 and "<a " in (a1.get("content") or ""), f"звернень: {викликів['n']}")
ok("після перебору статтю позначено чинною версією розмітки",
   a1.get("_richAlgo") == P.RICH_ALGO_VERSION, str(a1.get("_richAlgo")))
ok("🛑 перебрані статті потрапляють у число змінених (інакше файл не збережеться)",
   змінено >= 1, f"повернуто: {змінено}")

# Б. Та сама стаття вдруге — мережу вже чіпати не можна.
викликів["n"] = 0
прогін([a1], НОВИЙ)
ok("🛑 вдруге по мережу не ходимо — версія вже чинна",
   викликів["n"] == 0, f"звернень: {викликів['n']}")

# В. Сторінка не відповіла — повна стаття НЕ має постраждати.
# 🔴 Це найдорожча помилка з можливих у цьому механізмі: гілка невдачі ставить
# `contentSource = "rss"`, а клієнт на цю ознаку малює плашку «джерело надає лише
# анонс» (`showsShortNote` у `news.js`). Тобто спроба ПОКРАЩИТИ розмітку зіпсувала б
# те, що вже працювало, і виглядало б це як регресія на рівному місці.
a3 = стаття(contentSource="page")
було = a3["content"]
прогін([a3], None)
ok("🛑 невдалий перебір НЕ понижує повну статтю до «лише анонс»",
   a3.get("contentSource") == "page" and a3.get("fullText") is True,
   f"contentSource={a3.get('contentSource')}, fullText={a3.get('fullText')}")
ok("🛑 невдалий перебір не чіпає сам текст", a3["content"] == було)
ok("невдала спроба рахується власним лічильником",
   a3.get("_richTries") == 1 and "_fullTries" not in a3, str(a3.get("_richTries")))

