# 🔑 МІРЯЄМО ДВІ РЕЧІ ОДРАЗУ, і друга важливіша за першу:
#   1. відео ДОХОДИТЬ до тіла статті;
#   2. з чужого сайту в нашу сторінку не потрапляє ЖОДНОГО рядка — ні `src`,
