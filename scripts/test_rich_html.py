#!/usr/bin/env python3
"""Стенд БАГАТОГО HTML статті: посилання живі, цитати цілі (27.08).

НАВІЩО. Вова прислав скріни статті «Культурний код» (Район.Ківерці, id 12248):
на сайті-джерелі слово «повідомили» — клікабельне посилання на фейсбук Олицької
міської ради, а цитата стоїть одним блоком. У нас посилання стало звичайним
текстом, а цитата розірвалась на два абзаци посеред фрази.

📐 ЗАМІРЯНО НА ЖИВИХ ДАНИХ (`data/articles.json`, 27.08):
  · `<a` у тілі статей — **0 із 400**;
  · тіло взяте зі сторінки видання (`fullText`) — **381 із 400**, тобто кожна з
    них пройшла через `_inline_html`, який розгортає `<a>` у голий текст.

🔑 ЩО САМЕ МІРЯЄМО — НАСЛІДОК, А НЕ ФОРМУ ЗАПИСУ. Не «чи є слово `a` в аллоулисті»,
а «чи приходить із розбору посилання, на яке можна натиснути, і чи не проходить
адреса, якої там бути не повинно». Той самий підхід, що в `test_fulltext.py`.

🛑 ЧОМУ БЕЗПЕКА ТУТ, А НЕ «ПОТІМ». `content` іде на клієнті в `innerHTML` без
жодної санітизації — це чинний контракт, і тримається він на тому, що парсер
пише РІВНО дозволені теги без атрибутів. Атрибут `href` — перший атрибут, який ми
взагалі впускаємо, тож перевірки схеми й екранування мусять зʼявитись у ту саму
мить, що й сам тег.

Запуск:  python3 scripts/test_rich_html.py
"""
import inspect
import json
import re
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__)))
import parse_rss as P  # noqa: E402
from bs4 import BeautifulSoup  # noqa: E402

ok_count = fail_count = 0


def ok(name, cond, detail=""):
    global ok_count, fail_count
    if cond:
        ok_count += 1
        print(f"✅ {name}" + (f"  — {detail}" if detail else ""))
    else:
        fail_count += 1
        print(f"❌ {name}" + (f"  — {detail}" if detail else ""))


def тіло(html, title="", base=""):
    """Прогнати шматок сторінки через розбір тіла статті.

    ⚠️ Базову адресу передаємо ЛИШЕ якщо парсер її приймає: до кроку 2 підпис
    функції її не має, і стенд мусить сказати про це перевіркою, а не впасти
    з `TypeError` — інакше з нього не видно, що саме не готове.
    """
    el = BeautifulSoup(html, "html.parser")
    if base and "base_url" in inspect.signature(P._blocks_to_html).parameters:
        return P._blocks_to_html(el, title, base_url=base)
    return P._blocks_to_html(el, title)


print("🧪 test_rich_html — посилання живі, цитати цілі\n")

БАЗА = "https://kivertsi.rayon.in.ua/news/1095485-v-olici-kulturnii-kod"

# ── 1. ПОСИЛАННЯ ─────────────────────────────────────────────────────────────
# Розмітка відтворює саме те речення зі статті 12248.
СТАТТЯ = (
    '<div><p>В Олиці інтерактивний тренінг на тему «Культурний код».</p>'
    '<p>Про це <a href="https://www.facebook.com/olykarada/posts/123">повідомили</a> '
    'на фейсбук-сторінці Олицької міської ради.</p></div>'
)
r = тіло(СТАТТЯ, base=БАЗА)
ok("посилання виживає розбір", "<a " in r and "facebook.com/olykarada" in r, r[-140:])
ok("текст посилання лишається на місці", ">повідомили</a>" in r)
ok("чуже вікно не отримує доступу до нашого (rel=noopener)", 'rel="noopener"' in r)
ok("посилання відкривається окремо (target=_blank)", 'target="_blank"' in r)

# ── 2. ВІДНОСНА АДРЕСА ───────────────────────────────────────────────────────
# 🔑 Видання масово пишуть «/news/123», і без бази таке посилання на нашому
# домені вело б у нікуди — на `castlelife.org/news/123`.
ВІДНОСНЕ = '<div><p>Читай <a href="/news/999">попередню новину</a> про це.</p></div>'
r2 = тіло(ВІДНОСНЕ, base=БАЗА)
ok("відносна адреса стає абсолютною",
   "https://kivertsi.rayon.in.ua/news/999" in r2, r2)

# ── 3. БЕЗПЕКА: що НЕ має пройти ─────────────────────────────────────────────
# 🛑 Це не теорія: тіло йде в `innerHTML`, тож будь-яка адреса, яку ми впустимо
# без перевірки, виконається у людини на телефоні.
for назва, зле in (
    ("javascript:", '<div><p>Тиць <a href="javascript:alert(1)">сюди</a>.</p></div>'),
    ("data:",       '<div><p>Тиць <a href="data:text/html,<script>x</script>">сюди</a>.</p></div>'),
    ("vbscript:",   '<div><p>Тиць <a href="vbscript:msgbox(1)">сюди</a>.</p></div>'),
):
    rr = тіло(зле, base=БАЗА)
    ok(f"🛑 адреса «{назва}» НЕ проходить", назва not in rr.lower(), rr)
    ok(f"   але текст із неї лишається читабельним ({назва})", "сюди" in rr)

# 🛑 ВИТІК З АТРИБУТА: лапка в адресі не має закривати `href` і відкривати обробник.
#
# ⚠️ ПЕРША РЕДАКЦІЯ ЦІЄЇ ПЕРЕВІРКИ БУЛА ХИБНА, і це варто лишити записаним. Вона
# шукала рядок «onmouseover=» у результаті, попередньо ПРИБРАВШИ з нього `&quot;`.
# Але саме `&quot;` і є доказом, що атрибут НЕ вирвався: прибравши його, мірка
# власноруч перетворювала знешкоджений текст назад на небезпечний і червоніла на
# цілком правильному коді. Той самий клас помилки, що з фікстурою цитати вище.
#
# ➡️ Міряємо НАСЛІДОК: віддаємо результат назад у розбір HTML — тобто дивимось на
# нього так, як подивиться браузер, — і питаємо, які атрибути реально має тег.
ВТЕЧА = '<div><p>Тиць <a href=\'https://a.com/" onmouseover="alert(1)\'>сюди</a>.</p></div>'
rv = тіло(ВТЕЧА, base=БАЗА)
тег = BeautifulSoup(rv, "html.parser").find("a")
ok("🛑 лапка в адресі не вириває атрибут: у тега рівно три наші атрибути",
   тег is not None and set(тег.attrs) == {"href", "target", "rel"},
   f"атрибути: {sorted(тег.attrs) if тег else '—'}")
ok("🛑 обробник подій не став атрибутом",
   тег is not None and not any(k.lower().startswith("on") for k in тег.attrs),
   rv)

# ── 3б. РОЗДІЛЮВАЧ АБЗАЦІВ І ПОСИЛАННЯ ───────────────────────────────────────
# 🔴 РИЗИК, ЯКИЙ ЗʼЯВИВСЯ РАЗОМ ІЗ ПОСИЛАННЯМИ. `_split_runon_html` шукає втрачені
# межі абзаців усередині готового `<p>` і ріже його на кілька. Доки в тілі були
# самі `<strong>`/`<em>`, найгірше, що могло статись, — розрив виділення. Тепер
# усередині абзацу є `<a href=…>`, і розріз посеред нього дав би `<p>…<a href=x>Текст</p>`
# — тобто зламану розмітку, яку браузер «полагодить» по-своєму, розтягнувши
# посилання на пів статті.
# ➡️ Міряємо наслідок: скільки посилань бачить розбір HTML після всієї обробки.
# ⚠️ ПЕРША РЕДАКЦІЯ ФІКСТУРИ ПРОЙШЛА ВИПАДКОВО: текст до розриву був коротший за
# 40 символів, і його врятував запобіжник довжини всередині самого розділювача, а
# не якийсь захист від розриву тега. Тобто перевірка зеленіла, нічого не довівши.
# Тепер перед розривом ~80 символів — розділювач МУСИТЬ спробувати різати.
ПОСИЛАННЯ_ЗІ_СКЛЕЙКОЮ = (
    '<div><p>Про це вже вчора ввечері докладно <a href="https://www.facebook.com/olykarada/posts/1">'
    'повідомили на офіційній сторінці міської ради.Наступне речення теж усередині '
    'цього самого посилання ось так</a> далі звичайний текст статті.</p></div>'
)
rl = тіло(ПОСИЛАННЯ_ЗІ_СКЛЕЙКОЮ, base=БАЗА)

# 🔴 ТРЕТЯ ХИБНА МІРКА В ЦЬОМУ Ж СТЕНДІ, і причина щоразу та сама: я питав не те.
# Тут я рахував теги `<a>` ПІСЛЯ розбору HTML — а розбір мовчки лагодить зламану
# розмітку, тобто ховає рівно ту ваду, яку перевірка мала знайти. Браузер зробить
# так само, але полагодить ПО-СВОЄМУ: у людини посилання розтягнеться на наступні
# абзаци або обірветься.
# ➡️ Питаємо сам РЯДОК, який ми віддаємо: посилання мусить відкритись і закритись
# усередині ОДНОГО абзацу. Це і є та властивість, яку ламає розрив.
абзаци = re.findall(r"<p>.*?</p>", rl, re.S)
цілі = all(a.count("<a ") == a.count("</a>") for a in абзаци)
ok("🛑 розрив абзацу не ламає посилання: воно відкрите й закрите в одному абзаці",
   абзаци and цілі,
   " | ".join(f"відкрито {a.count('<a ')}, закрито {a.count('</a>')}" for a in абзаци))
ok("🛑 адреса посилання не загубилась",
   rl.count("https://www.facebook.com/olykarada/posts/1") == 1, rl[:150])

# ── 4. ЦИТАТА НЕ РВЕТЬСЯ ─────────────────────────────────────────────────────
# 🔴 ДОСЛІВНО з живої статті 12248 — БЕЗ ПРОБІЛУ після «круто!».
# ⚠️ Перша редакція цієї фікстури пробіл поставила, і перевірка вийшла ЗЕЛЕНОЮ,
# нічого не довівши: `_RUNON_BOUNDARY` шукає розділовий знак УПРИТУЛ до великої
# літери, тож із пробілом він і не мав спрацювати. Тобто я міряв не той текст,
# який зламався. Пробілу немає і на скріні Вови, і в самому дописі: фейсбук дав
# там перенос рядка, а rayon.in.ua склеїв його без пробілу.
ЦИТАТА = (
    '<div><p>«Було справді цікаво, пізнавально й дуже круто!'
    'І це лише початок Попереду – продовження нашої зустрічі та нові цікаві теми!», '
    '– йдеться у дописі.</p></div>'
)
rc = тіло(ЦИТАТА)
ok("цитата лишається ОДНИМ абзацом", rc.count("<p>") == 1,
   f"абзаців: {rc.count('<p>')} · {rc[:120]}")

# 🔴 КОНТРОЛЬ: правило не має вимкнути те, заради чого його заводили.
# RSS справді втрачає межі абзаців — «.Наступний» без пробілу це ДВА абзаци.
СКЛЕЙКА = (
    '<div><p>Зустріч організував центр культури спільно з молодіжною радою.'
    'Учасники говорили про традиції, звичаї та символи української культури.</p></div>'
)
rs = тіло(СКЛЕЙКА)
ok("🔴 КОНТРОЛЬ: справжня склейка абзаців усе ще розбивається",
   rs.count("<p>") == 2, f"абзаців: {rs.count('<p>')}")

# 🔴 КОНТРОЛЬ №2: правило не має бути ЗАНАДТО широким.
# Межа одразу ПІСЛЯ закритої лапки — законна: там справді закінчився один абзац і
# почався інший. Якби заборона поширювалась на весь абзац із лапками, цей розріз
# теж зник би — і замість однієї вади ми дістали б протилежну, тихішу.
ЗАКРИТА_ЛАПКА = (
    '<div><p>«Було дуже цікаво», – сказала організаторка заходу в Олиці.'
    'Наступного тижня учасники зберуться знову і продовжать обговорення теми.</p></div>'
)
rz = тіло(ЗАКРИТА_ЛАПКА)
ok("🔴 КОНТРОЛЬ: після ЗАКРИТОЇ лапки розріз усе ще можливий",
   rz.count("<p>") == 2, f"абзаців: {rz.count('<p>')} · {rz[:130]}")

# 🔴 КОНТРОЛЬ №3: незакрита лапка не має тихо забороняти геть усе далі по тексту,
# якщо межа стоїть ПЕРЕД нею.
ЛАПКА_ПІЗНІШЕ = (
    '<div><p>Зустріч організував центр культури спільно з молодіжною радою.'
    'Учасники говорили про традиції та звичаї, а потім прозвучало «Культурний код».</p></div>'
)
rp = тіло(ЛАПКА_ПІЗНІШЕ)
ok("🔴 КОНТРОЛЬ: межа ПЕРЕД лапками не блокується",
   rp.count("<p>") == 2, f"абзаців: {rp.count('<p>')}")

# ── 5. ЖИВІ ДАНІ ─────────────────────────────────────────────────────────────
шлях = os.path.join(os.path.dirname(__file__), "..", "data", "articles.json")
with open(шлях, encoding="utf-8") as f:
    arts = json.load(f)
з_посиланням = [a for a in arts if "<a " in (a.get("content") or "")]
зі_сторінки = [a for a in arts if a.get("fullText")]
print(f"\n📐 На ЖИВИХ даних: посилання мають {len(з_посиланням)} із {len(arts)} статей; "
      f"тіло взяте зі сторінки — у {len(зі_сторінки)}")
ok("живі дані читаються", len(arts) > 100, f"{len(arts)} статей")

print()
if fail_count:
    print(f"❌ {ok_count}/{ok_count + fail_count} перевірок пройдено")
    sys.exit(1)
print(f"✅ {ok_count}/{ok_count} перевірок пройдено")
