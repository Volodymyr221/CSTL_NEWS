# -*- coding: utf-8 -*-
"""СТОРОЖ РОЗДІЛЕННЯ СПІЛЬНОТ — яка місія які теми бере і як рахує пропорцію.

🔴 Заведено 27.08.2026 на замовлення Вови: історичне їде в спільноту «Історія
Громади», а OLYKA CASTLE лишається брендовою — «що цікавого в Олиці сьогодні».

📐 ЧОМУ ВЗАГАЛІ ЗНАДОБИЛОСЬ РОЗДІЛЕННЯ (заміряно ПЕРЕД правкою, не на око):
із 9 постів, написаних агентом у OLYKA CASTLE, історичних було **5** — тобто
більшість спільноти бренду розповідала про те, що було колись.

🔑 ЩО МІРЯЄМО І ЧОМУ САМЕ ТАК. Не наявність ключа `pools` у файлі місії — це
довело б лише те, що я його туди вписав. Міряємо ПОВЕДІНКУ джерела: даємо йому
справжні конфіги місій і питаємо, які теми воно віддало.

🛑 НАЙТОНШЕ МІСЦЕ — ПРОПОРЦІЯ. Файл памʼяті у двох місій СПІЛЬНИЙ (щоб та сама
тема не пішла двічі в різні спільноти), але правило Вови «постів про функції
менша частина» мусить рахуватись ОКРЕМО для кожної. Інакше пост в «Історії
Громади» мовчки відкривав би квоту на функцію в OLYKA CASTLE — тобто правило
обходилось би чужою спільнотою. Це і є та вада, яку тут стережуть три перевірки.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from editor.core.config import load_mission          # noqa: E402
from editor.core.registry import load_plugins, get   # noqa: E402
from editor.sources import plan as plan_src          # noqa: E402

ok_count = fail_count = 0


def ok(назва, умова, деталь=""):
    global ok_count, fail_count
    if умова:
        ok_count += 1
        print(f"✅ {назва}" + (f"  — {деталь}" if деталь else ""))
    else:
        fail_count += 1
        print(f"❌ {назва}" + (f"  — {деталь}" if деталь else ""))
    return bool(умова)


load_plugins()
джерело = get("source", "plan")()

# ── 1. Конфіги місій — справжні, з диска ────────────────────────────────────
історія = load_mission("istoriya_hromady")
бренд = load_mission("olyka_castle")

ok("місія «Історія Громади» існує і пише в сторінку 6",
   json.loads((ROOT / "editor/plans/istoriya_hromady.json").read_text(encoding="utf-8"))["page_id"] == 6,
   "page_id з плану")
ok("в неї свій кошик витрат, не спільний з брендом",
   історія.get("spend_prefix") and історія["spend_prefix"] != бренд.get("spend_prefix"),
   f"{історія.get('spend_prefix')} проти {бренд.get('spend_prefix')}")
# Рішення Вови 27.08: пост має виглядати «як в інстаграмі», тобто з фото. У
# бренду стоїть `none`, і саме тому всі 5 історичних постів вийшли без картинки.
ok("історична місія шукає фото (у бренду було вимкнено)",
   історія.get("image") == "wikimedia", f"image={історія.get('image')}")
ok("у неї власний голос, а не голос бренду",
   історія.get("voice") == "istoriya_hromady" and (ROOT / "editor/voice/istoriya_hromady.md").exists())

# ── 2. ПУЛИ: хто які теми бачить ───────────────────────────────────────────
# Памʼять підмінюємо порожньою — інакше стенд міряв би не розподіл тем, а те,
# скільки з них уже написано, і «зеленів» би просто тому, що черга вичерпана.
справжній_load_state = plan_src.load_state
plan_src.load_state = lambda: {"done": [], "kinds": {}, "missions": {}}
try:
    теми_історії = джерело.fetch({**історія, "per_run": 99})
    теми_бренду = джерело.fetch({**бренд, "per_run": 99})
finally:
    plan_src.load_state = справжній_load_state

іст_id = [t.get("id", "") for t in теми_історії]
бренд_id = [t.get("id", "") for t in теми_бренду]

ok("«Історія Громади» отримує історії", any(i.startswith("story:") for i in іст_id),
   f"{len(іст_id)} тем: {', '.join(іст_id[:3])}")
ok("🔴 OLYKA CASTLE історій БІЛЬШЕ НЕ ОТРИМУЄ", not any(i.startswith("story:") for i in бренд_id),
   f"{len(бренд_id)} тем: {', '.join(бренд_id[:3]) or '—'}")
ok("в історичну не течуть теми про функції застосунку",
   not any(t.get("kind") == "feature" for t in теми_історії))
ok("усі теми історичної місії ведуть у сторінку 6",
   all(t.get("page_id") == 6 for t in теми_історії) if теми_історії else False,
   f"page_id: {sorted({t.get('page_id') for t in теми_історії})}")
ok("теми бренду ведуть у сторінку 3", all(t.get("page_id") == 3 for t in теми_бренду) if теми_бренду else True)

# ── 3. ПРОПОРЦІЯ РАХУЄТЬСЯ ОКРЕМО В КОЖНІЙ СПІЛЬНОТІ ───────────────────────
# Сцена: у спільній памʼяті три «звичайні» пости, і ВСІ вони чужі — з історичної
# спільноти. Для OLYKA CASTLE це має означати «звичайних постів у мене нема».
памʼять = {
    "done": ["story:a", "story:b", "story:c"],
    "kinds": {"story:a": "brand", "story:b": "brand", "story:c": "brand"},
    "missions": {"story:a": "istoriya_hromady", "story:b": "istoriya_hromady",
                 "story:c": "istoriya_hromady"},
}
план_бренду = json.loads((ROOT / "editor/plans/olyka_castle.json").read_text(encoding="utf-8"))
свої = plan_src._види(памʼять, план_бренду, "olyka_castle")
чужі = plan_src._види(памʼять, план_бренду, "istoriya_hromady")
ok("🔴 чужі пости НЕ рахуються як свої", свої == [], f"OLYKA CASTLE бачить {len(свої)}, а не {len(памʼять['done'])}")
ok("своя ж місія свої пости бачить", len(чужі) == 3, f"{len(чужі)}")
# 🛑 Тут стояла перевірка з `or True` — тобто така, що не вміла впасти. Прибрано
# одразу: у цьому проєкті фальшива зелень уже коштувала не одного розслідування.
# Чесне твердження про цей стан таке: коли своїх постів НЕМАЄ, функція дозволена
# (частка рахується від нуля). Це поведінка до 27.08, і вона не мінялась.
ok("при нулі своїх постів функція дозволена — поведінка не змінилась",
   plan_src.функція_дозволена(свої, план_бренду.get("max_feature_share", 0.34)) == "")
причина = plan_src.функція_дозволена(свої + ["feature"], план_бренду.get("max_feature_share", 0.34))
ok("🛑 дві функції поспіль заборонені й далі", bool(причина), причина[:70])

# ── 4. КОНТРОЛЬ: без фільтра за місією стенд мусить почервоніти ─────────────
# Перевірка, яка не вміє впасти, нічого не стереже.
без_фільтра = plan_src._види(памʼять, план_бренду, "")
ok("КОНТРОЛЬ: без фільтра чужі пости справді протікали б у бренд",
   len(без_фільтра) == 3, f"{len(без_фільтра)} чужих порахувалось би як свої")

# ── 5. Невідомий пул називається вголос, а не ковтається ───────────────────
теми_дурні = джерело.fetch({**історія, "pools": ["вигаданий"], "per_run": 9})
ok("невідомий пул не дає тем (і про нього сказано в лог)", теми_дурні == [])

print(f"\n{'❌' if fail_count else '✅'} {ok_count}/{ok_count + fail_count} перевірок пройдено")
sys.exit(1 if fail_count else 0)
