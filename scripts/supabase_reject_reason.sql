-- 🔴 НАВІЩО. Житель бачив у «Моїх оголошеннях» статус «Відхилено» і НЕ ЗНАВ ЧОМУ.
--    Виправити й подати знову він не міг — не розумів, що саме не так. Адмінка
--    ставила лише `status = 'rejected'` (три різні місця в `admin.html`), поля з
--    текстом не існувало взагалі. Тобто модерація була однобічною: рішення є,
--    пояснення немає.
--
-- 🔑 ЧОМУ КОЛОНКА В `posts`, А НЕ ОКРЕМА ТАБЛИЦЯ «журнал модерації». Причина
--    потрібна РІВНО одна — остання, і рівно поки пост відхилений. Журнал рішень
--    це інша задача (історія модерації, хто і коли), і вона не потрібна, щоб
--    людина зрозуміла, що виправити.
--
-- 🛡 ПРАВА не додаються і не міняються — наявних досить (звірено запитом до
--    `pg_policies` 17.08):
--      • UPDATE на `posts` дозволений ЛИШЕ `is_admin()` → житель не може ні
--        вписати собі причину, ні стерти її;
--      • «Owner reads own posts» (`owner_uid = auth.uid()`) → свою причину
--        житель бачить, чужу — ні.
--    ⚠️ RPC редагування (`update_board_post`) перелічує колонки поіменно і цієї
--    не торкається, тобто автор не сховає причину правкою оголошення.
-- ============================================================================

alter table public.posts add column if not exists reject_reason text;

-- Стеля довжини: причина — це одне речення, а не лист.
-- 300 символів свідомо БІЛЬШЕ за бюджет капсули на головній (вона обріже по межі
-- слова), бо той самий текст показує ще й екран «Мої оголошення», де місця більше.
alter table public.posts drop constraint if exists posts_reject_reason_len;
alter table public.posts add constraint posts_reject_reason_len
  check (reject_reason is null or char_length(reject_reason) <= 300);

-- 🔑 Причина живе РІВНО поки пост відхилений.
-- Без цього правила вона висіла б і після повторної публікації — житель читав би
-- докір за вже виправлене оголошення.
-- 🛑 Правило в БАЗІ, а не в адмінці: статус там міняють ТРИ різні місця
-- (модерація · знімання з публікації · картка поста), і забути одне з них —
-- питання часу. У базі це одне місце на всі шляхи, включно з SQL напряму.
create or replace function public.clear_reject_reason()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if new.status is distinct from 'rejected' then
    new.reject_reason := null;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_clear_reject_reason on public.posts;
create trigger trg_clear_reject_reason
  before insert or update on public.posts
  for each row execute function public.clear_reject_reason();

