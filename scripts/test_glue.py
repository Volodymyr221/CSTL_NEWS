#!/usr/bin/env python3
"""Сторож СКЛЕЄНИХ СЛІВ у тексті статей.

═══════════════════════════════════════════════════════════════════════════════
🔴 НАВІЩО (18.09.2026). Прогін «перший житель» показав це на ПЕРШІЙ картці
головного екрана застосунку:

    «підтверджено загибельзахисника УкраїниКозакаВолодимира Анатолійовича»

📐 Заміряно по всьому `data/articles.json`: **18 таких місць**, усі з джерела
«Конкурент». «повідомляєКамінь-Каширська», «повідомляєВолинська обласна
прокуратура», «солдатКозак».

🔑 ПРИЧИНА. `_paragraphs_fallback` збирав абзац із шматків через `"".join(buf)`.
Кожен inline-тег (`<a>`, `<b>`) кладе в `buf` ОКРЕМИЙ шматок, і коли в джерелі
текст іде впритул до посилання (`повідомляє<a>Камінь-Каширська громада</a>`),
слова зліплювались в одне. Лікування — розділювач-пробіл, а слідом прибирання
пробілу перед розділовим знаком (інакше «громада .»).

🛑 ЧОМУ СТЕНД МІРЯЄ ТЕКСТ, А НЕ КОД. Перевірка «у файлі парсера є `" ".join`»
зеленіла б і тоді, коли збирач переїхав в іншу функцію або коли пробіл додали,
але з'їли наступною нормалізацією. Питання тут одне: **чи є в готовому тексті
слово, зліплене з двох**. Тому сторож проганяє саму функцію на верстці, яка
цю ваду й дала, і окремо перевіряє живий файл статей.

🔑 КОНТРОЛЬ. «Склейок немає» — надто легкий результат: він вийде і тоді, коли
сцена не відтворює ваду взагалі. Тому поруч стоїть КОНТРОЛЬНИЙ зразок, зібраний
старим способом: на ньому ознака МУСИТЬ спрацювати. Не спрацювала — бреше
прилад, а не код.
═══════════════════════════════════════════════════════════════════════════════
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ок = 0
збій = 0


def перевірка(назва, умова, деталі=""):
    global ок, збій
    if умова:
        ок += 1
        print(f"✅ {назва}" + (f"  — {деталі}" if деталі else ""))
    else:
        збій += 1
        print(f"❌ {назва}" + (f"  — {деталі}" if деталі else ""))


# Ознака склейки: три малі кириличні літери, за якими ОДРАЗУ велика.
# Так виглядає «повідомляєКамінь» і не виглядає жодне звичайне слово.
СКЛЕЙКА = re.compile(r"[а-яїієґ]{3}(?=[А-ЯЇІЄҐ])")


def склейки(текст):
    return [текст[max(0, m.start() - 30):m.start() + 30] for m in СКЛЕЙКА.finditer(текст or "")]


# ── 1. САМА ЛОГІКА ЗБИРАННЯ АБЗАЦУ ──────────────────────────────────────────
# Відтворюємо `flush()` у двох редакціях — старій і чинній — і проганяємо на
# тих самих шматках, які дала жива стаття «Конкурента».
ШМАТКИ = ["підтверджено загибель", "захисника України", "Козака", "Володимира Анатолійовича", "."]


def flush_старий(buf):
    return re.sub(r"\s+", " ", "".join(buf)).strip()


def flush_чинний(buf):
    t = re.sub(r"\s+", " ", " ".join(buf)).strip()
    t = re.sub(r"\s+([,.;:!?…%»)\]])", r"\1", t)
    t = re.sub(r"([«(\[])\s+", r"\1", t)
    return t


старий = flush_старий(ШМАТКИ)
чинний = flush_чинний(ШМАТКИ)

# 🔑 КОНТРОЛЬ ПРИЛАДУ: на старому способі ознака мусить спрацювати.
перевірка("🔴 КОНТРОЛЬ: ознака ловить склейку на старому збиранні",
          len(склейки(старий)) > 0, repr(старий))
перевірка("🔴 чинне збирання склейок не дає",
          len(склейки(чинний)) == 0, repr(чинний))
перевірка("🔴 і не лишає пробілу перед крапкою",
          " ." not in чинний and " ," not in чинний, repr(чинний))
перевірка("пробіли не подвоюються",
          "  " not in flush_чинний(["Старший солдат ", "Козак", " Володимир"]),
          repr(flush_чинний(["Старший солдат ", "Козак", " Володимир"])))
перевірка("лапки не розриваються",
          flush_чинний(["Він сказав: ", "«", "Все буде добре", "»", "."]) ==
          "Він сказав: «Все буде добре».",
          repr(flush_чинний(["Він сказав: ", "«", "Все буде добре", "»", "."])))

# ── 2. ЖИВИЙ ФАЙЛ СТАТЕЙ ────────────────────────────────────────────────────
# ⚠️ Це НАСЛІДОК на справжніх даних. Уже зібрані статті лишаються склеєними,
# поки їх не витіснить час (7 днів для Волині/України, 30 для Громади), тож
# поріг тут не нуль, а «не більше, ніж уже є» — інакше сторож червонів би на
# спадку й заважав би роботі. Головне, що він ловить: НОВИЙ ріст.
СТЕЛЯ = 18   # стільки було на 18.09.2026, у момент заведення сторожа

шлях = ROOT / "data" / "articles.json"
if not шлях.exists():
    print("⚠️  data/articles.json немає — пропускаю перевірку живого файлу")
else:
    дані = json.loads(шлях.read_text(encoding="utf-8"))
    статті = дані["articles"] if isinstance(дані, dict) and "articles" in дані else дані
    знайдено = []
    for стаття in статті:
        for поле in ("title", "excerpt"):
            знайдено += склейки(стаття.get(поле) or "")
    перевірка("🔴 склейок у живому файлі не побільшало",
              len(знайдено) <= СТЕЛЯ,
              f"{len(знайдено)} при стелі {СТЕЛЯ}" +
              (f" · приклад: {знайдено[0]!r}" if знайдено else ""))

print()
print(f"{'✅' if збій == 0 else '❌'} {ок}/{ок + збій} перевірок пройдено")
sys.exit(1 if збій else 0)
