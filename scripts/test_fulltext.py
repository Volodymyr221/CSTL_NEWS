#!/usr/bin/env python3
"""Стенд правил ПОВНОТИ ТЕКСТУ новини (12.08).

НАВІЩО. До 12.08 «повний текст» означало «довжина ≥ 500 символів». Це плутало два
стани, які нічим не схожі: «RSS дав анонс, статті ми не бачили» і «взяли всю
статтю зі сторінки, і вона коротка». Ціна помилки заміряна на живих даних:
стаття про загиблого земляка (452 символи — уся стаття) тричі витягалась зі
сторінки і тричі відкидалась через недобір 48 символів, а людині показувалась
плашка «джерело надає лише анонс» під ПОВНИМ текстом.

🔑 Стенд міряє ПРАВИЛО, а не число: «повнота = походження тексту». Тому тут є
контроль на стару логіку — перевірка, що поріг 500 справді ламав короткі статті.

Запуск:  python3 scripts/test_fulltext.py
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__)))
import parse_rss as P  # noqa: E402

ok_count = fail_count = 0


def ok(name, cond, detail=""):
    global ok_count, fail_count
    if cond:
        ok_count += 1
        print(f"✅ {name}" + (f"  — {detail}" if detail else ""))
    else:
        fail_count += 1
        print(f"❌ {name}" + (f"  — {detail}" if detail else ""))


print("🧪 test_fulltext — правила повноти тексту\n")

# ── 1. Ядро: походження, а не довжина ────────────────────────────────────────
АНОНС = "<p>У громаді повідомили сумну звістку.</p>"
SUMMARY = "У громаді повідомили сумну звістку."

# Це РЕАЛЬНИЙ випадок зі скріна Вови (v4271): уся стаття, 452 символи.
КОРОТКА_ПОВНА = (
    "<p>На війні загинув військовослужбовець Сергій Щербатих 27.02.1981р. н., "
    "житель села Ставок.</p><p>Сумну звістку повідомили у Олицькій громаді.</p>"
    "<p>Сергій Володимирович Щербатих народився 27 лютого 1981 року. Він проживав "
    "у селі Ставок та захищав Україну у лавах Збройних сил.</p>"
    "<p>Світла та вічна пам'ять Герою.</p><p>Про дату та час зустрічі Захисника, "
    "прощання і чин поховання повідомлять додатково.</p>"
    "<p>Редакція сайту новин Волині «Конкурент» висловлює співчуття рідним і близьким.</p>"
)
довжина = len(P.strip_html(КОРОТКА_ПОВНА))

_, src = P.decide_content(АНОНС, КОРОТКА_ПОВНА, SUMMARY)
ok("🔴 КОРОТКА, але ПОВНА стаття зі сторінки = 'page'", src == "page",
   f"{довжина} символів (стара логіка вимагала 500)")

# 🔴 КОНТРОЛЬ: доводимо, що стара логіка на цій самій статті помилялась.
# Без цього рядка перевірка вище нічого не доводить — вона була б зеленою і тоді,
# коли проблеми ніколи не існувало.
ok("🔴 КОНТРОЛЬ: стара логіка (поріг 500) цю статтю відкидала", довжина < 500,
   f"{довжина} < 500 — саме через це стаття мала плашку")

ДОВГА = "<p>" + ("Повний текст статті. " * 60) + "</p>"
_, src = P.decide_content(АНОНС, ДОВГА, SUMMARY)
ok("довга стаття зі сторінки = 'page'", src == "page")

_, src = P.decide_content(АНОНС, None, SUMMARY)
ok("сторінку не взяли (403 / JS-only) = 'rss'", src == "rss")

_, src = P.decide_content(АНОНС, АНОНС, SUMMARY)
ok("🔴 сторінка віддала ТОЙ САМИЙ анонс = 'rss' (не видаємо анонс за статтю)",
   src == "rss")

СМІТТЯ = "<p>Читати далі</p>"
_, src = P.decide_content(АНОНС, СМІТТЯ, SUMMARY)
ok("недоїдок розмітки не зараховується як стаття", src == "rss",
   f"{len(P.strip_html(СМІТТЯ))} символів < {P.MIN_BODY_CHARS}")

# ── 2. Довгий RSS-анонс: зворотна помилка ────────────────────────────────────
# Джерело віддає в RSS 700 символів. Стара логіка зараховувала це як повний текст
# і на сторінку не йшла ВЗАГАЛІ — саме так «Українська правда» давала 15 статей
# із плашкою при формально «повному» тілі.
ДОВГИЙ_АНОНС = "<p>" + ("Анонс новини. " * 50) + "</p>"
довж_анонсу = len(P.strip_html(ДОВГИЙ_АНОНС))
ok("🔴 КОНТРОЛЬ: довгий RSS-анонс стара логіка вважала повним текстом",
   довж_анонсу >= 500, f"{довж_анонсу} символів ≥ 500")

_, src = P.decide_content(ДОВГИЙ_АНОНС, None, P.strip_html(ДОВГИЙ_АНОНС))
ok("довгий анонс БЕЗ сторінки більше не вважається повним", src == "rss",
   f"{довж_анонсу} символів, але походження — RSS")

# ── 3. Версія алгоритму скидає лічильник спроб ───────────────────────────────
# Без цього виправлення не доходить до вже збережених статей: заміряно 12.08 —
# у 100 зі 107 статей із плашкою `_fullTries` уже стояв на стелі 3.
ok("версія алгоритму оголошена", isinstance(P.FULL_ALGO_VERSION, int),
   f"FULL_ALGO_VERSION = {P.FULL_ALGO_VERSION}")

стаття = {"content": АНОНС, "excerpt": SUMMARY, "sourceUrl": "https://example.com/a",
          "_fullTries": 3, "_fullAlgo": 1, "fullText": False}
# Мережі в стенді немає — fetch поверне None, і стаття лишиться 'rss'. Нас цікавить
# РІВНО одне: чи скинувся лічильник, тобто чи дістала стаття новий шанс.
P.fetch_full_article = lambda url, title="": None
P.rehydrate_short_articles([стаття])
ok("🔴 лічильник спроб скинуто при новій версії алгоритму",
   стаття.get("_fullAlgo") == P.FULL_ALGO_VERSION and стаття.get("_fullTries", 0) <= 1,
   f"_fullAlgo={стаття.get('_fullAlgo')}, _fullTries={стаття.get('_fullTries')}")

стаття2 = {"content": АНОНС, "excerpt": SUMMARY, "sourceUrl": "https://example.com/b",
           "_fullTries": 3, "_fullAlgo": P.FULL_ALGO_VERSION, "fullText": False}
P.rehydrate_short_articles([стаття2])
ok("🔴 КОНТРОЛЬ: на ТІЙ САМІЙ версії лічильник НЕ скидається (не довбимо сайт вічно)",
   стаття2.get("_fullTries") == 3, f"_fullTries={стаття2.get('_fullTries')}")

# ── 3.5 Екстракція зі сторінок, де текст НЕ в <p> ────────────────────────────
# 🔴 Знайдено з логів GitHub Actions: volynpost віддає сторінку цілою (37 341 байт),
# але жоден контейнер не має двох тегів <p> — «0 кандидатів», 73 з 73 статей без
# тексту. Видання верстає абзаци голим текстом із <br>.
# ⚠️ Мій ПЕРШИЙ діагноз («сайт віддає 403») був ХИБНИЙ — 403 приходив від проксі
# пісочниці, а не від сайту. Перевірка з середовища, де домен заблокований,
# доводила не те, що я думав. Саме тому тут стенд на РОЗМІТКУ, а не на мережу.
from bs4 import BeautifulSoup, NavigableString  # noqa: E402

СТАРА_ВЕРСТКА = """<html><body>
<nav>Меню Головна Новини Контакти</nav>
<div class="node-content">
Волинська митниця перерахувала до бюджету 1,4 млрд грн за сім місяців 2026 року.<br><br>
Найбільше надходжень принесло розмитнення автівок — про це повідомили у пресслужбі
Волинської митниці. За словами очільника відомства, це на 12% більше за минулий рік.<br><br>
Загалом за сім місяців оформлено понад 20 тисяч транспортних засобів. Митники наголошують,
що попит на розмитнення тримається стабільно високим протягом усього року.<br><br>
Раніше повідомлялося, що надходження до бюджету зросли у всіх областях заходу країни.
</div></body></html>"""

суп = BeautifulSoup(СТАРА_ВЕРСТКА, "html.parser")
старі = [t for t in суп.find_all(["div", "section", "article"])
         if len(t.find_all("p", recursive=True)) >= 2]
ok("🔴 КОНТРОЛЬ: старий пошук кандидатів на такій сторінці давав НУЛЬ",
   len(старі) == 0, "саме це логи CI писали як «0 кандидатів»")

нові = []
for t in суп.find_all(["div", "section", "article"]):
    own = sum(len(str(c).strip()) for c in t.children if isinstance(c, NavigableString))
    if own >= 400 and len(t.find_all("br", recursive=False)) >= 2:
        нові.append((own, t))
ok("другий фолбек знаходить тіло у верстці без <p>", len(нові) == 1,
   f"кандидатів: {len(нові)}")

if нові:
    витяг = P._blocks_to_text(max(нові, key=lambda x: x[0])[1])
    ok("витягнутий текст змістовний", len(витяг) >= P.MIN_BODY_CHARS, f"{len(витяг)} символів")
    ok("🔴 меню НЕ потрапило в текст статті", "Контакти" not in витяг)

# ── 3.6 Політика публікації ──────────────────────────────────────────────────
# Рішення 12.08: Громаду беремо завжди (місцева новина потрібна навіть анонсом —
# іншого джерела в людини немає), решту розділів без повного тексту не публікуємо.
СПОЛУКИ = [
    ("Громада", "rss",  True,  "місцева новина береться навіть анонсом"),
    ("Олика",   "rss",  True,  "стара назва Громади — те саме правило"),
    ("Волинь",  "rss",  False, "область без повного тексту не публікуємо"),
    ("Україна", "rss",  False, "країна без повного тексту не публікуємо"),
    ("Волинь",  "page", True,  "з повним текстом публікуємо будь-який розділ"),
]
for geo, src_kind, треба, чому in СПОЛУКИ:
    береться = not (src_kind == "rss" and geo not in ("Громада", "Олика"))
    ok(f"політика: {geo} + {src_kind} → {'беремо' if треба else 'пропускаємо'}",
       береться == треба, чому)

# ── 4. Живі дані: скільки статей лишиться з плашкою ──────────────────────────
import json  # noqa: E402
шлях = os.path.join(os.path.dirname(__file__), "..", "data", "articles.json")
with open(шлях, encoding="utf-8") as f:
    arts = json.load(f)

def плашка(a):
    """Дзеркалить showsShortNote() у src/tabs/news.js."""
    if a.get("exclusive") or not a.get("sourceUrl"):
        return False
    if a.get("contentSource"):
        return a["contentSource"] == "rss"
    return not a.get("fullText") and len(P.strip_html(a.get("content") or "").strip()) < 600

з_плашкою = [a for a in arts if плашка(a)]
print(f"\n📐 На ЖИВИХ даних: {len(з_плашкою)} із {len(arts)} статей показують плашку "
      f"({round(len(з_плашкою) / len(arts) * 100)}%)")
ok("живі дані читаються і правило до них застосовується", len(arts) > 100,
   f"{len(arts)} статей")

print()
if fail_count:
    print(f"❌ {ok_count}/{ok_count + fail_count} перевірок пройдено")
    sys.exit(1)
print(f"✅ {ok_count}/{ok_count} перевірок пройдено")
