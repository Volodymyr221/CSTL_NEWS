// Стенд: ПІДПИС АВТОРА НЕ БЛИМАЄ (19.09.2026).
//
// 🗣️ Скарга Вови: «спочатку вибиває тільки імʼя, тобто Сергій, і потім блимає і
// підтягує фамілію. Чому воно блимає, що це таке, я не розумію. Воно має відразу
// всю карточку підтягувати. У нас стоїть імʼя і прізвище».
//
// 🔑 ПРИЧИНА БУЛА НЕ В ГІДРАЦІЇ, А В РОЗХОДЖЕННІ ДВОХ ДЖЕРЕЛ ПРАВДИ (клас B-27).
// Картка малюється зі ЗНІМКОМ підпису (`posts.author`), а `hydrateNames()` потім
// підставляє живе імʼя з `profiles`. Поки обидва збігаються, заміна непомітна.
// 📐 Заміряно на живій базі 19.09: розходились **14 постів із 14** і **11
// коментарів з 11** — бо тригер `enforce_denorm_identity` (09.08) писав лише
// `name`, а прізвища завели аж 04.09 (`fullName()`). Тобто знімок фізично не міг
// збігтися з профілем у жодного, хто має прізвище.
//
// 🛑 ЧОМУ ЛІКУВАЛИ БАЗУ, А НЕ ГІДРАЦІЮ. Прибрати гідрацію означало б заморозити
// підпис назавжди — рівно вада, від якої її й заводили 07.08 (людина міняє імʼя,
// а чужі екрани показують старе). Правильне лікування — щоб ДЖЕРЕЛА ЗБІГАЛИСЬ.
//
// 🔑 ЩО САМЕ МІРЯЄ ЦЕЙ ФАЙЛ: не «чи правильний підпис» (це побачив би і глядач
// одного кадру), а **чи змінювався текст після першого малювання**. Саме зміна і
// є те блимання, яке бачив Вова. Ловить її `MutationObserver`, поставлений ДО
// відкриття вкладки.

import { chromium } from 'playwright';
import { launch, serve, reporter } from './_lib.mjs';
import { mockSupabase } from './_board-fixture.mjs';

const { ok, done } = reporter();

const t0 = Date.now() - 864e5;
const питання = (i, uid, знімок) => ({
  id: 700 + i, type: 'chat', status: 'published', author: знімок, owner_uid: uid,
  title: null, text: `Питання номер ${i} про життя громади?`,
  location: null, tags: [], ts: t0 + i * 6e4,
  created_at: new Date(t0 + i * 6e4).toISOString(),
  published_at: new Date(t0 + i * 6e4).toISOString(),
});

const ПРОФІЛІ = [
  { uid: 'u1', name: 'Сергій',    surname: 'Андрощук' },
  { uid: 'u2', name: 'Катерина',  surname: 'Гордійчук' },
  { uid: 'u3', name: 'Владислав', surname: 'Міленін' },
];

const { url, stop } = await serve();
const b = await launch(chromium);

// 🔑 `знімки` — що лежить у `posts.author` ДО того, як заглушка підставить
// серверний підпис. Стенд свідомо кладе сюди КОРОТКЕ імʼя: саме так виглядала
// база до 19.09, і саме це має виправити дзеркало тригера у фікстурі.
async function сцена({ профілі = ПРОФІЛІ } = {}) {
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true,
                                   hasTouch: true, serviceWorkers: 'block' });
  const p = await ctx.newPage();
  await mockSupabase(p, {
    posts: [питання(1, 'u1', 'Сергій'), питання(2, 'u2', 'Катерина'), питання(3, 'u3', 'Владислав')],
    announcements: [], comments: [], reactions: [], saved_posts: [],
  }, { user: { id: 'u9', email: 'me@example.com' }, profiles: профілі,
       // 🔴 ГОЛОВНА ДЕТАЛЬ СЦЕНИ. `liveName()` бере КЕШ імен, і лише як
       // запасне — знімок із поста. Поки кеш устигає заповнитись до малювання,
       // блимання немає НІ ПРИ ЯКОМУ знімку, і стенд зеленів би над вадою.
       // 📐 Перевірено мутацією: без цієї затримки зламане дзеркало тригера
       // давало 5/5. Профілі мусять їхати ПІЗНІШЕ за список — як у житті.
       slow: { get_avatars: 2500, get_public_profile: 2500 } });
  await p.route('**://api.open-meteo.com/**', r => r.abort());

  // Спостерігач ставиться ДО першого малювання списку — інакше перша ж заміна
  // тексту пройшла б повз нього, і стенд зеленів би над блиманням.
  //
  // 🔴 ПЕРША РЕДАКЦІЯ ЦЬОГО СПОСТЕРІГАЧА БРЕХАЛА, І ВАРТО ЗНАТИ ЯК — інакше
  // наступна сесія «спростить» його назад. Вона брала `r.oldValue` і рахувала
  // зміною лише те, де старе значення непорожнє. Але `hydrateNames()` робить
  // `el.textContent = nm`, а це ЗАМІНА ТЕКСТОВОГО ВУЗЛА (`childList`), а не
  // правка символів (`characterData`) — тож у записі стоїть `oldValue: null`,
  // і фільтр викидав саме ту подію, заради якої все й писалось.
  // 📐 Доведено приладом `tests/tools/_name-probe.mjs`: зі зламаним дзеркалом
  // тригера підпис ішов «КОРОТКО» (300-900мс) → «ПОВНЕ ПРІЗВИЩЕ» (~1800мс), а
  // стенд при цьому давав 5/5. Дві мутації поспіль не валили його саме через це.
  // ✅ Тепер спостерігач тримає ВЛАСНИЙ знімок останнього тексту кожного uid і
  // рахує зміну як розбіжність із ним — незалежно від типу події.
  await p.addInitScript(() => {
    window.__зміниІмен = [];
    const відомо = new Map();
    const глянути = (el) => {
      const uid = el.dataset.nameUid;
      const текст = (el.textContent || '').trim();
      if (!uid || !текст) return;
      const старе = відомо.get(uid);
      if (старе !== undefined && старе !== текст) {
        window.__зміниІмен.push({ uid, було: старе, стало: текст });
      }
      відомо.set(uid, текст);
    };
    addEventListener('DOMContentLoaded', () => {
      new MutationObserver(() => {
        document.querySelectorAll('[data-name-uid]').forEach(глянути);
      }).observe(document.documentElement, {
        subtree: true, childList: true, characterData: true,
      });
    });
  });

  // 🔑 ХОЛОДНИЙ СТАРТ ПРЯМО НА ПИТАННЯХ — друга половина тієї ж сцени.
  // Якщо спершу відкрити інші вкладки, кеш імен наповнять вони, і до Питань
  // людина дійде вже з готовими підписами. Вова бачить блимання саме тоді,
  // коли заходить на вкладку першою.
  await p.goto(url + '#/tab/disc', { waitUntil: 'domcontentloaded' });
  await p.waitForTimeout(1400);
  await p.evaluate(() => document.querySelector('.consent-accept')?.click());
  await p.waitForTimeout(4200);   // довше за затримку профілів — гідрація встигає
  return { ctx, p };
}

const підписи = (p) => p.evaluate(() => [...document.querySelectorAll('#disc-content [data-name-uid]')]
  .map(el => ({ uid: el.dataset.nameUid, текст: el.textContent.trim() })));

// ── 0. ПРИЛАД БАЧИТЬ ТЕ, ЩО ЗАЯВЛЯЄ ──────────────────────────────────────
//
// 🔴 Без цього блоку решта нічого не варта: якщо підписів на екрані немає
// (перейменували атрибут, зламався рендер), «жодної зміни тексту» буде
// ІСТИННИМ над порожнечею — і стенд зеленітиме над зламаним екраном.
const { ctx, p } = await сцена();
const список = await підписи(p);
ok('прилад БАЧИТЬ підписи авторів у картках',
   список.length >= 3 && список.every(r => r.текст.length > 0),
   `знайдено ${список.length}: ${список.map(r => r.текст).join(' · ')}`);

// ── 1. 🔴 ГОЛОВНЕ: ТЕКСТ ПІДПИСУ НЕ МІНЯВСЯ ПІСЛЯ МАЛЮВАННЯ ──────────────
{
  const зміни = await p.evaluate(() => window.__зміниІмен || []);
  ok('🔴 підпис автора НЕ перемальовувався (не блимає)',
     зміни.length === 0,
     зміни.length
       ? `замін тексту: ${зміни.length} — ${зміни.slice(0, 3).map(z => `"${z.було}"→"${z.стало}"`).join(', ')}`
       : 'жодної заміни тексту');
}

// ── 2. І ПІДПИС ПОВНИЙ, А НЕ САМЕ ІМʼЯ ───────────────────────────────────
//
// Зустрічна межа до блоку 1: «не блимає» саме по собі здобувається і тим, щоб
// показати коротке імʼя й ніколи його не оновлювати. Тобто без цієї перевірки
// сторож приймав би лікування, протилежне замовленню Вови.
{
  const неповні = список.filter(r => !/\s/.test(r.текст));
  ok('🛑 у картці стоїть ІМʼЯ І ПРІЗВИЩЕ, а не саме імʼя',
     неповні.length === 0,
     неповні.length ? `без прізвища: ${неповні.map(r => r.текст).join(', ')}` : список.map(r => r.текст).join(' · '));
}

// ── 3. 🛑 ТІНЬ НАД СПИСКОМ ПИТАНЬ ─────────────────────────────────────────
//
// 🗣️ Друга скарга того ж повідомлення: «зверху над блоком шапки падає якась тінь
// на питання. Її немає в жодній вкладці, тому її потрібно забрати».
// 📐 Заміряно контролем: віньєтка займала 390×140 від самого верху при шапці
// заввишки 59px — тобто **81px затемнення висіло прямо над картками**, 34%
// чорного на верхньому краї.
{
  const тінь = await p.evaluate(() => {
    const v = document.querySelector('.board-vignette, .board-vignette--top');
    if (!v) return null;
    const r = v.getBoundingClientRect();
    return { w: Math.round(r.width), h: Math.round(r.height) };
  });
  ok('🛑 над списком Питань НЕМАЄ затемнення (віньєтки)',
     тінь === null, тінь ? `лишилась смуга ${тінь.w}×${тінь.h}` : 'чисто');
}
await ctx.close();

// ── 4. ЧОГО ЦЕЙ СТЕНД НЕ ПЕРЕВІРЯЄ, І ЧОМУ ТАК ЧЕСНІШЕ ───────────────────
//
// 🔴 ТУТ СТОЯВ БЛОК «гідрація жива — ми її не зламали», І ЙОГО ПРИБРАНО ПІСЛЯ
// ЧОТИРЬОХ МУТАЦІЙ, ЖОДНА З ЯКИХ ЙОГО НЕ ЗВАЛИЛА. Варто знати, що показали
// прогони, інакше наступна сесія заведе його знову:
//   • знято `hydrateNames(el)` з `renderAll()` → стенд 6/6;
//   • сама `hydrateNames()` перетворена на порожню → 6/6;
//   • знято підписку `onReturn('board', …)` → 6/6.
//
// 🔑 ПРИЧИНА НЕ В ПРИЛАДІ, А В ТОМУ, ЩО СИСТЕМА СТАЛА ПРОСТІШОЮ. Після фіксу
// 19.09 підпис у `posts.author` вирівнюється за профілем НА БОЦІ СЕРВЕРА
// (`enforce_denorm_identity` + `sync_profile_denorm`), і заглушка це дзеркалить.
// Тобто будь-яке перемалювання списку вже дає правильне імʼя — і жоден із трьох
// шляхів оновлення не можна ізолювати цією сценою. Перевірка, яку неможливо
// завалити, не стереже нічого: вона лише вдає захист.
//
// ➡️ Гідрацію стереже ВЛАСНИЙ сторож `tests/live-profile.mjs` (4/4) — він для
// цього й заведений 07.08. Дублювати його тут означало б розвести дві копії
// одного правила, які колись розійдуться.

await stop();
await b.close();
done();
