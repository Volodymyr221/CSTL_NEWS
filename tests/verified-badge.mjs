// Стенд: СИНЯ ГАЛОЧКА СТОЇТЬ ОДНАКОВО НА ВСІХ ПОВЕРХНЯХ.
//
// 🔴 ЗАМОВЛЕННЯ ВОВИ (23.08, дослівно): *«нам потрібно стандартизувати цю
// галочку синю… щоб вона була рівномірно напроти імені завжди, а не так, що
// вона десь знизу, зверху. І вона має бути в розмір імені… що в шапці, що в
// чаті, що в стрічці, що на спільноті, що в загальних повідомленнях»*.
//
// 🔑 ЧИМ ЦЕЙ СТЕНД ВІДРІЗНЯЄТЬСЯ ВІД `official-badge.mjs`. Той міряє, чи знак
// Є там, де треба, і чи його НЕМА у звичайного жителя — тобто ПРАВО на знак.
// Цей міряє ГЕОМЕТРІЮ: розмір відносно кегля імені і вертикальний збіг центрів.
// Дві різні вади, два різні стенди: знак може стояти в правильної людини і при
// цьому бути вдвічі меншим і з'їхати під рядок — саме це Вова і побачив.
//
// 📐 ЩО САМЕ МІРЯЄМО, І ЧОМУ НАЖИВО, А НЕ ПО КОДУ. Обидві половини вади були
// невидимі в тексті стилю: `0.82em` виглядає правильно, поки не спитаєш, ВІД
// ЧОГО той `em` рахується; `vertical-align` виглядає правильно, поки не
// спитаєш, чи батько взагалі `flex` (там воно не діє зовсім). Тому питаємо
// браузер про підсумкові прямокутники, а не читаємо декларації.
//
// 🔴 КОНТРОЛЬ: LEGACY=1 node tests/verified-badge.mjs
// Збирає ту саму сторінку зі СТАРОЮ розміткою (знак — сусід класу-кегля, поза
// гніздом) і мусить УПАСТИ. Без цього стенд не доводить, що ловить саме ту
// ваду, на яку скаржився Вова. Контроль вбудований у файл навмисно: сторожі
// цього проєкту вже двічі виявлялись брехливими, бо їх контроль жив у git-ревізії
// і тихо переставав відтворювати стару поведінку.
import { chromium } from 'playwright';
import { launch, reporter, projectFile } from './_lib.mjs';

const { ok, done } = reporter();
const LEGACY = !!process.env.LEGACY;

const base = projectFile('style/base.css');
const messages = projectFile('style/messages.css');
const board = projectFile('style/board.css');
const feed = projectFile('style/feed.css');

// Знак — рівно той самий рядок, що віддає `officialMarkHtml()`.
const ЗНАК = '<span class="cstl-verified" role="img" aria-label="Офіційний акаунт">'
  + '<svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">'
  + '<circle class="cstl-verified-bg" cx="12" cy="12" r="11"/>'
  + '<path class="cstl-verified-tick" d="M10.35 17.1 L5.5 12.25 L7.6 10.15 L10.35 12.9 L16.4 6.85 L18.5 8.95 Z"/>'
  + '</svg></span>';

const ІМʼЯ = 'Олександр Прендецький';

// 🔴 ТУТ ЖИВЕ ЧЕСНІСТЬ ЦЬОГО СТЕНДА, І ПЕРША РЕДАКЦІЯ ЇЇ НЕ МАЛА.
// Спершу LEGACY підставляв `<span data-name-uid>імʼя</span>ЗНАК` УСЕРЕДИНУ
// класу-кегля — і контроль пройшов на всі 37 перевірок, тобто стенд «довів»
// відсутність вади, якої в тій розмітці й не було. Стара вада полягала саме в
// тому, що знак стояв ПОЗА елементом із кеглем: `<span class="pm-head-name"
// data-name-uid>імʼя</span>ЗНАК`. Тому перемикач мусить будувати весь вузол
// імені цілком, а не його начинку.
//
// ⚠️ Це двадцять якийсь випадок брехливої перевірки в проєкті, і механізм той
// самий, що завжди: контроль відтворював НЕ ту форму, яку мав відтворити.
const вузолІмені = (клас, текст = ІМʼЯ) => LEGACY
  // ДО 23.08: клас-кегль і маркер на одному вузлі, знак — його сусід ЗОВНІ.
  ? `<span class="${клас}" data-name-uid="u">${текст}</span>${ЗНАК}`
  // ПІСЛЯ: клас-кегль зовні, гніздо всередині, знак — сусід тексту в гнізді.
  : `<span class="${клас}"><span class="cstl-name">`
    + `<span class="cstl-name-txt" data-name-uid="u">${текст}</span>${ЗНАК}</span></span>`;

// Сім поверхонь. Розмітка кожної — копія з коду, включно з батьківськими
// контейнерами: саме батько і був джерелом вади, тож без нього стенд міряв би
// стерильний випадок, якого в застосунку не існує.
const ПОВЕРХНІ = [
  { id: 'chat-head', назва: 'Шапка чату', кегль: '.pm-head-name',
    html: `<header class="pm-head pm-head--chat"><div class="pm-head-titles">
             ${вузолІмені('pm-head-name')}
           </div></header>` },

  { id: 'thread', назва: 'Список розмов', кегль: '.pm-thread-name',
    html: `<div class="pm-thread-body"><div class="pm-thread-top">
             ${вузолІмені('pm-thread-name')}
             <span class="pm-thread-time">12:30</span>
           </div></div>` },

  { id: 'com', назва: 'Коментар Стрічки', кегль: '.fd-com-name',
    html: `<div class="fd-com-body"><div class="fd-com-head">
             ${вузолІмені('fd-com-name')}
             <span class="fd-com-time">5 хв</span>
           </div></div>` },

  { id: 'author', назва: 'Автор допису Стрічки', кегль: '.fd-author',
    // ⚠️ Тут клас-кегль — БЛОКОВИЙ `div`, і саме тому стара форма кидала знак
    // на новий рядок. Відтворюємо це чесно, разом із тире перед іменем.
    html: LEGACY
      ? `<div class="fd-author" data-name-uid="u">— ${ІМʼЯ}</div>${ЗНАК}`
      : `<div class="fd-author">— <span class="cstl-name">`
        + `<span class="cstl-name-txt" data-name-uid="u">${ІМʼЯ}</span>${ЗНАК}</span></div>` },

  { id: 'qa-answer', назва: 'Відповідь у Питаннях', кегль: '.qa-answer-name',
    html: `<div class="qa-answer-body"><div class="qa-answer-head">
             ${вузолІмені('qa-answer-name')}
             <span class="qa-answer-when">8 липня</span>
           </div></div>` },

  { id: 'qa-question', назва: 'Автор питання', кегль: '.qa-question-name',
    html: `<div class="qa-question-by">
             ${вузолІмені('qa-question-name')}
             <span class="qa-card-dot">·</span><span class="qa-question-when">8 липня</span>
           </div>` },

  { id: 'ad-author', назва: 'Автор оголошення', кегль: '.cm-ad-author-name',
    html: `<div class="cm-ad-author"><span class="cm-ad-author-info">
             ${вузолІмені('cm-ad-author-name')}
             <span class="cm-ad-author-since">Учасник CSTL LIFE</span>
           </span></div>` },
];

const html = `<!doctype html><html><head><meta charset="utf-8"><style>
 *,*::before,*::after{box-sizing:border-box;margin:0;padding:0}
 :root{
   --fd-surface:#fff; --fd-ink:#2b2b2b; --fd-muted:#888; --fd-accent:#722F37;
   --fd-bg:#f4f1ec; --fd-card-r:14px;
   --ink:#2A2520; --ink-mute:#9C9080; --red:#722F37; --border:#E5E0D8;
   --qa-ink:#1B1B1F; --qa-ink-2:#54565E; --qa-ink-3:#8A8D96; --qa-fill:#F1F1F4;
   --app-bg:#fff; --board-bg:#fff;
 }
 body{background:#fff;font-family:-apple-system,system-ui,sans-serif}
 .випроб{padding:10px 14px;background:#fff}
 ${base}
 ${messages}
 ${board}
 ${feed}
</style></head><body>
${ПОВЕРХНІ.map(s => `<div class="випроб" id="${s.id}">${s.html}</div>`).join('\n')}
</body></html>`;

const b = await launch(chromium);
const ctx = await b.newContext({ viewport: { width: 390, height: 900 }, isMobile: true });
const p = await ctx.newPage();
await p.setContent(html, { waitUntil: 'load' });

// Міряємо підсумкові прямокутники, а не декларації стилю.
const заміри = await p.evaluate((поверхні) => поверхні.map((s) => {
  const корінь = document.getElementById(s.id);
  const кегльEl = корінь.querySelector(s.кегль);
  const знак = корінь.querySelector('.cstl-verified');
  // Вузол тексту імені: у гнізді це `.cstl-name-txt`, у LEGACY — сам вузол з маркером.
  const текст = корінь.querySelector('.cstl-name-txt') || корінь.querySelector('[data-name-uid]');
  if (!кегльEl || !знак || !текст) return { id: s.id, назва: s.назва, знайдено: false };

  const rз = знак.getBoundingClientRect();
  const rт = текст.getBoundingClientRect();
  const кегль = parseFloat(getComputedStyle(кегльEl).fontSize);

  return {
    id: s.id, назва: s.назва, знайдено: true,
    кегль,
    ширина: rз.width,
    висота: rз.height,
    // Очікуваний розмір — та сама формула, що в CSS: clamp(11px, 0.82em, 20px).
    очікувано: Math.min(20, Math.max(11, кегль * 0.82)),
    // Різниця вертикальних центрів знака й тексту. Це і є «десь знизу, зверху».
    зсув: (rз.top + rз.height / 2) - (rт.top + rт.height / 2),
    // Чи не впав знак на інший рядок, ніж імʼя (найгрубіший прояв вади).
    той_самий_рядок: Math.abs(rз.top - rт.top) < rт.height,
  };
}), ПОВЕРХНІ.map(s => ({ id: s.id, назва: s.назва, кегль: s.кегль })));

// ── 1. РОЗМІР — «вона має бути в розмір імені» ──────────────────────────────
// Допуск 0.75px: субпіксельне округлення браузера, не розбіжність правила.
for (const з of заміри) {
  ok(`${з.назва}: розмітка зібралась`, з.знайдено);
  if (!з.знайдено) continue;
  ok(`🔴 ${з.назва}: знак у розмір імені (кегль ${з.кегль}px → ${з.очікувано.toFixed(1)}px)`,
     Math.abs(з.ширина - з.очікувано) < 0.75,
     `виміряно ${з.ширина.toFixed(1)}px, очікувано ${з.очікувано.toFixed(1)}px`);
  ok(`${з.назва}: знак круглий (ширина = висота)`,
     Math.abs(з.ширина - з.висота) < 0.6,
     `${з.ширина.toFixed(1)}×${з.висота.toFixed(1)}`);
}

// ── 2. ВЕРТИКАЛЬ — «рівномірно напроти імені, а не десь знизу, зверху» ──────
// Допуск 1.5px. Він не «щоб пройшло»: центр рядка тексту і оптичний центр літер
// різняться на частку пікселя через нижні виносні (р, у, д), і вимагати нуля
// означало б вимагати неможливого. 1.5px — межа, за якою зсув видно оком.
for (const з of заміри) {
  if (!з.знайдено) continue;
  ok(`🔴 ${з.назва}: знак на одному рядку з іменем`, з.той_самий_рядок,
     `зсув по вертикалі ${з.зсув.toFixed(1)}px`);
  ok(`🔴 ${з.назва}: центр знака збігається з центром імені`,
     Math.abs(з.зсув) < 1.5, `зсув ${з.зсув.toFixed(2)}px`);
}

// ── 3. ГОЛОВНЕ — ОДНАКОВІСТЬ, а не сім окремо правильних місць ─────────────
// Саме про це просив Вова: «це має виглядати все гармонійно». Кожне місце може
// пройти дві перевірки вище і все одно жити за власним правилом — наприклад,
// якщо знак усюди прибити до 13px. Тут вимагаємо, щоб ВІДНОШЕННЯ знака до кегля
// було спільним, тобто щоб правило було одне на застосунок.
const живі = заміри.filter(з => з.знайдено);
// Беремо лише кеглі всередині шкали (11…20px), бо на краях `clamp` навмисно
// відв'язує знак від кегля — і там відношення законно інше.
const усередині = живі.filter(з => з.кегль * 0.82 > 11 && з.кегль * 0.82 < 20);
const відношення = усередині.map(з => з.ширина / з.кегль);
const розкид = відношення.length
  ? Math.max(...відношення) - Math.min(...відношення) : 0;
ok('🔴 Пропорція знака ОДНА на всі поверхні (розкид < 0.01)',
   усередині.length >= 3 && розкид < 0.01,
   `поверхонь у шкалі: ${усередині.length}, розкид ${розкид.toFixed(4)}, ` +
   усередині.map(з => `${з.id}=${(з.ширина / з.кегль).toFixed(3)}`).join(' '));

// Підлога 11px мусить справді рятувати найдрібніше місце (підпис автора, 12.5px):
// без неї знак вийшов би 10.25px і зливався б у синю крапку — рівно та вада,
// на яку Вова скаржився 09.08.
const дрібне = живі.filter(з => з.кегль < 14);
ok('🔴 У найдрібніших місцях знак не менший за 11px',
   dрібнеОк(дрібне), дрібне.map(з => `${з.id}: кегль ${з.кегль}px → ${з.ширина.toFixed(1)}px`).join(' · ') || '(таких місць нема)');
function dрібнеОк(список) {
  return список.length > 0 && список.every(з => з.ширина >= 10.9);
}

if (LEGACY) {
  console.log('\n⚠️  Це КОНТРОЛЬНИЙ прогін (LEGACY=1) — стара розмітка.');
  console.log('   Червоні рядки вище і є доказом, що стенд ловить ваду.\n');
}

await b.close();
done();
