// Стенд: ШКАЛА БАЛІВ КАПСУЛ — інваріанти, які легко зламати мовчки.
//
// 🔴 НАВІЩО ЗАВЕДЕНИЙ (31.08.2026). Сьогодні прибирали віджет автобусів із
// Громади — і виявилось, що бал `FEED_REPLIES: 65` стояв вище за `BUS_SOON: 60`
// САМЕ ТОМУ, що віджет існував: обґрунтування в коді казало дослівно «рейс за
// 16-45 хв людина побачить іще й у віджеті автобусів на цій самій сторінці».
//
// 🛑 Тобто шкала спиралась на верстку іншої вкладки, і трималось це виключно
// на коментарі. Прибери віджет, не прочитавши той абзац, — і рейс за 20 хвилин
// перестав би показуватись людині, у якої є три інші події. Нічого б не впало.
//
// 🔑 ЦЕЙ СТЕНД ПЕРЕТВОРЮЄ ТУ ЗАЛЕЖНІСТЬ НА ПЕРЕВІРКУ. Він читає ВИХІДНИЙ КОД
// (не браузер): шкала — це константи, і дивитись на них треба там, де вони
// оголошені. Читання через `projectFile`, як у решти текстових стендів.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, reporter } from './_lib.mjs';

const { ok, done } = reporter();

const capsSrc = readFileSync(join(ROOT, 'src/tabs/home-caps.js'), 'utf8');
const commSrc = readFileSync(join(ROOT, 'src/tabs/community.js'), 'utf8');

// Витягуємо бали з блоку `const RANK = { … }`.
const блок = capsSrc.match(/const RANK = \{([\s\S]*?)\n\};/);
const RANK = {};
if (блок) {
  for (const m of блок[1].matchAll(/^\s*([A-Z_]+):\s*(\d+)/gm)) RANK[m[1]] = Number(m[2]);
}

ok('шкала балів прочиталась', Object.keys(RANK).length >= 12, `${Object.keys(RANK).length} балів`);

// ── 1. ГОЛОВНИЙ ІНВАРІАНТ, заради якого стенд і заведено ────────────────────
// Віджета автобусів на Громаді немає → у рейсу «ось-ось» немає другої поверхні,
// тож він мусить стояти вище за подію, яка не спливає.
const віджетаНемає = !commSrc.includes('cm-bus-content') && !commSrc.includes('id="hm-bus"');
ok('віджет автобусів на Громаді відсутній (як вирішив Вова)', віджетаНемає);
ok('🔴 БЕЗ ВІДЖЕТА: BUS_SOON вище за FEED_REPLIES',
   !віджетаНемає || RANK.BUS_SOON > RANK.FEED_REPLIES,
   `BUS_SOON ${RANK.BUS_SOON} проти FEED_REPLIES ${RANK.FEED_REPLIES}`);

// ── 2. Порядок усередині автобусних балів ───────────────────────────────────
// Читається як одна фраза: «через скільки цей рядок стане непотрібним».
ok('скасування вище за «ось-ось»', RANK.BUS_CANCELLED > RANK.BUS_NOW,
   `${RANK.BUS_CANCELLED} > ${RANK.BUS_NOW}`);
ok('«ось-ось» вище за «скоро»', RANK.BUS_NOW > RANK.BUS_SOON);
ok('«скоро» вище за «пізніше»', RANK.BUS_SOON > RANK.BUS_LATER);
ok('«пізніше» вище за «завтра»', RANK.BUS_LATER > RANK.BUS_TOMORROW);

// ── 3. Особисте лишається вище за загальне ──────────────────────────────────
ok('приватне повідомлення вище за рейс «скоро»', RANK.MSG > RANK.BUS_SOON,
   `MSG ${RANK.MSG} > ${RANK.BUS_SOON}`);
ok('моє відхилене оголошення вище за питання громади', RANK.AD_REJECTED > RANK.QUESTION);
ok('«завтрашній рейс» — найнижчий бал у шкалі',
   RANK.BUS_TOMORROW === Math.min(...Object.values(RANK)), `${RANK.BUS_TOMORROW}`);

// ── 4. Усі бали різні: однакові роблять порядок довільним ───────────────────
const значення = Object.values(RANK);
const дублі = значення.filter((v, i) => значення.indexOf(v) !== i);
ok('однакових балів немає (інакше порядок довільний)', дублі.length === 0,
   дублі.length ? `дублі: ${[...new Set(дублі)].join(', ')}` : 'усі різні');

done();
