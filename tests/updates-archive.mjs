// 🗣️ Вова 20.09: «екран завантаження я вже побачив і натиснув усім. Але воно так
// і буде висіти в загальному списку? Чи може окремий список / вкладку зробимо?»
//
// 📐 Питання було вчасне, бо вада ВЖЕ БУЛА, а не мала настати: у `app_features`
// рівно ОДИН рядок (`skeleton_shapes`, стан `all`, випущено 19.09 19:59), і той
// сидів під заголовком «Що зараз тестуємо». Заголовок брехав на єдиному рядку,
// який там є, а прибрати рядок не було чим — ні поля в таблиці, ні кнопки.
//
// 🔑 ЧОМУ ЛОГІКА, А НЕ ЖИВА СЦЕНА — той самий висновок, що в `analytics-screen`
// і `admin-reports`: `admin.html` відкриває лише залогінений адмін, і підняти
// сцену означало б підробити сесію і перевіряти власну підробку. Тому вирізаємо
// `renderUpdates` з файлу і виконуємо на вигаданих даних: це перевірка
// ПОВЕДІНКИ рендера, а не наявності рядка в коді.
//
// ⚠️ МЕЖА, ЯКУ ТРЕБА ЗНАТИ: слухачі кліків цей стенд не виконує — він каже
// «розмітка вийде правильна», а не «тап справді архівує». Що архівування робить
// у БАЗІ, доведено окремо і в інший спосіб: транзакціями з відкотом на живій базі
// 20.09 (9 перевірок, записані в шапці `scripts/supabase_features_archive.sql`),
// зокрема обидві межі, які МАЮТЬ відмовляти, і головна — що `my_features()`
// віддає архівовану фічу так само `on: true`.

import { projectFile, reporter } from './_lib.mjs';

const { ok, done } = reporter();
const REV = process.env.BUNDLE_REV || '';
const читати = (шлях) => { try { return projectFile(шлях, REV); } catch { return ''; } };
const HTML = читати('admin.html');
const SQL  = читати('scripts/supabase_features_archive.sql');

// Вирізаємо функцію від оголошення до першого `}` на нульовому відступі.
function вирізати(назва) {
  const i = HTML.indexOf(`function ${назва}(`);
  if (i < 0) return null;
  const хвіст = HTML.slice(i);
  const кінець = хвіст.indexOf('\n}\n');
  return кінець < 0 ? null : хвіст.slice(0, кінець + 2);
}

const шматки = ['escapeHtml', 'renderUpdates'].map(вирізати);
let render = null;
if (шматки.every(Boolean)) {
  try {
    // 🛑 Вільні імена передаються ПАРАМЕТРАМИ, а не глобалями: інакше стенд ліз
    // би в `globalThis` і тягнув за собою стан між перевірками.
    render = new Function('can', 'myAccess', 'features', 'testers', 'formatDate',
                          'supa', 'showToast', 'loadAll', 'renderApp',
                          `${шматки.join('\n')}\nreturn renderUpdates;`);
  } catch (e) { ok('вирізаний рендер виконується', false, e.message); }
}

const ФІЧА = (o) => ({ key: 'k', label: 'Фіча', descr: null, stage: 'off',
                       created_at: '2026-09-19T10:00:00Z', released_at: null, archived_at: null, ...o });

// Малюємо розмітку на вигаданих даних. `el` підроблений: нам потрібен рядок, а
// не жива сторінка.
function намалювати({ фічі, manage = true, release = true }) {
  if (!render) return '';
  const el = {
    _h: '',
    set innerHTML(v) { this._h = v; }, get innerHTML() { return this._h; },
    querySelectorAll: () => [], querySelector: () => null,
  };
  const can = (_р, рівень) => (рівень === 'manage' ? manage : true);
  render(can, { can_release_update: release }, фічі, [], () => '19.09',
         null, () => {}, async () => {}, () => {})(el);
  return el.innerHTML;
}

// ── 0. ПРИЛАД БАЧИТЬ ТЕ, ЩО ЗАЯВЛЯЄ ──────────────────────────────────────
// 🔴 Без цього блоку решта нічого не варта: якщо рендер не вирізався, будь-яке
// «у групі Х немає зайвого» буде ІСТИННИМ над порожнім рядком.
ok('рендер «Оновлень» вирізано з admin.html і він виконується',
   !!render && намалювати({ фічі: [ФІЧА({})] }).length > 200,
   render ? `${намалювати({ фічі: [ФІЧА({})] }).length} символів` : 'не вирізався');

// ── 1. 🔴 ГОЛОВНЕ: ВИПУЩЕНЕ НЕ ВИСИТЬ СЕРЕД ТОГО, ЩО ПЕРЕВІРЯЄМО ──────────
{
  const html = намалювати({ фічі: [
    ФІЧА({ key: 'а', label: 'На перевірці', stage: 'circle' }),
    ФІЧА({ key: 'б', label: 'Мовчазна',     stage: 'off' }),
    // ⚠️ Назви карток навмисно НЕ схожі на заголовки груп. Перша редакція
    // назвала картку «Вже в усіх» при заголовку «Уже в усіх» — і перевірка
    // «стоїть у своїй групі» шукала не те слово й червоніла над справним кодом.
    ФІЧА({ key: 'в', label: 'Випущена фіча', stage: 'all', released_at: '2026-09-19T19:59:00Z' }),
  ] });
  const група = (назва) => {
    const i = html.indexOf(назва);
    if (i < 0) return null;
    // Кусок до наступного заголовка — рівно те, що людина бачить під ним.
    const далі = html.slice(i + назва.length);
    const кінець = далі.search(/section-title|<details/);
    return далі.slice(0, кінець < 0 ? далі.length : кінець);
  };
  ok('🔴 три групи замість одного списку',
     /Перевіряємо зараз \(1\)/.test(html) && /ще нікому не показане \(1\)/.test(html) && /Уже в усіх \(1\)/.test(html),
     (html.match(/section-title">[^<]+/g) || []).join(' · '));
  const перевіряємо = група('Перевіряємо зараз');
  ok('🔴 випущена фіча НЕ висить у «перевіряємо зараз»',
     !!перевіряємо && !/Випущена фіча/.test(перевіряємо),
     перевіряємо ? перевіряємо.slice(0, 160).replace(/\s+/g, ' ') : '(групи немає)');
  ok('і вона справді стоїть у своїй групі',
     /Випущена фіча/.test(група('Уже в усіх') || ''),
     (група('Уже в усіх') || '').slice(0, 120).replace(/\s+/g, ' '));
}

// ── 2. 🔴 АРХІВ ПРИБИРАЄ РЯДОК З ЕКРАНА ──────────────────────────────────
{
  const живий = намалювати({ фічі: [ФІЧА({ key: 'в', label: 'Стара фіча', stage: 'all' })] });
  const архів = намалювати({ фічі: [ФІЧА({ key: 'в', label: 'Стара фіча', stage: 'all',
                                           archived_at: '2026-09-20T07:00:00Z' })] });
  ok('🔴 архівована зникає з групи «Уже в усіх»',
     /Уже в усіх \(1\)/.test(живий) && /Уже в усіх \(0\)/.test(архів),
     `до: ${(живий.match(/Уже в усіх \(\d\)/) || [])[0]} · після: ${(архів.match(/Уже в усіх \(\d\)/) || [])[0]}`);
  ok('🔴 і переїжджає у згорнутий блок «Прибрані прапорці»',
     /<details/.test(архів) && /Прибрані прапорці \(1\)/.test(архів) && !/<details/.test(живий));
  // 🛑 Зустрічна межа: «зникла з екрана» не сміє означати «зникла з життя».
  // У блоці мусить стояти сама фіча і слова, що вона працює далі.
  ok('🛑 архів каже, що фіча ПРАЦЮЄ ДАЛІ, а не вимкнена',
     /Стара фіча/.test(архів) && /працює далі/i.test(архів));
  ok('з архіву можна повернути', /Повернути в список/.test(архів));
}

// ── 3. КНОПКА СТОЇТЬ ЛИШЕ ТАМ, ДЕ МАЄ ────────────────────────────────────
// 🛑 Без цього «архів працює» здобувалося б кнопкою на кожній картці — і нею
// сховали б недороблене, тобто спосіб забути про незакінчену роботу.
{
  const наПеревірці = намалювати({ фічі: [ФІЧА({ stage: 'circle' })] });
  const мовчазна    = намалювати({ фічі: [ФІЧА({ stage: 'off' })] });
  const вУсіх       = намалювати({ фічі: [ФІЧА({ stage: 'all' })] });
  ok('🛑 недороблену сховати не можна (кнопки немає)',
     !/data-feat-arch=/.test(наПеревірці) && !/data-feat-arch=/.test(мовчазна));
  ok('а на випущеній кнопка є', /data-feat-arch=/.test(вУсіх));
  // Права: `updates` = view бачить стан, але нічого не міняє.
  const глядач = намалювати({ фічі: [ФІЧА({ stage: 'all' })], manage: false });
  ok('🛑 без права «керувати» кнопки архіву немає', !/data-feat-arch=/.test(глядач));
}

// ── 4. НАГАДУВАННЯ НАЗИВАЄ КЛЮЧ, А НЕ ПРОСТО «ЧАС ПРИБРАТИ» ─────────────
// 🔑 Порада без адреси нічого не коштує: людина читає «час прибрати прапорець»
// і не знає, звідки саме. Ключ у тексті — це і є адреса.
{
  const давня = намалювати({ фічі: [ФІЧА({ key: 'skeleton_shapes', stage: 'all',
                                           released_at: new Date(Date.now() - 9 * 86400000).toISOString() })] });
  ok('🔴 нагадування називає ТОЧНИЙ виклик, який треба зняти з коду',
     /featureOn\('skeleton_shapes'\)/.test(давня), (давня.match(/ⓘ[^<]+/) || ['(немає)'])[0]);
  const свіжа = намалювати({ фічі: [ФІЧА({ key: 'x', stage: 'all', released_at: new Date().toISOString() })] });
  ok('🛑 і не зʼявляється в день випуску', !/час прибрати|featureOn\('x'\)/.test(свіжа));
}

// ── 5. МІГРАЦІЯ: ДВІ МЕЖІ, ЯКІ ЛЕГКО ЗГУБИТИ ПРИ ПЕРЕПИСУВАННІ ──────────
ok('міграція архіву є в репозиторії', SQL.length > 0);
ok('🔴 архівувати можна ЛИШЕ те, що вже в усіх',
   /p_on and v_stage <> 'all'/.test(SQL));
ok('🔴 архів вимагає права керувати оновленнями',
   /has_perm\('updates','manage'\)/.test(SQL));
// 🔴 НАЙВАЖЛИВІШЕ В ЦЬОМУ ФАЙЛІ. Напрошується «архівована → не віддавати
// клієнту», і воно тихо вимкнуло б робочу фічу в усієї громади, якби прапорець
// насправді ще стояв у коді. Міграція НЕ СМІЄ чіпати `my_features()`.
ok('🛑 міграція архіву НЕ чіпає my_features() — архів не вимикає фічу',
   SQL.length > 0 && !/create or replace function public\.my_features/.test(SQL));
ok('повернення з архіву передбачене (p_on boolean)',
   /archive_feature\(p_key text, p_on boolean/.test(SQL));
ok('адмінка кличе саме цю функцію', /supa\.rpc\('archive_feature'/.test(HTML));

done();
