// Стенд: ЄДИНИЙ ПОШУК ЗНАХОДИТЬ ТЕ, ЩО ЛЮДИНА МАЛА НА УВАЗІ.
//
// 🗣️ Замовлення Вови (30.08): «автор написав одне, а користувач хоче знайти те
// саме, але формулює зовсім по-іншому… нам треба як в OLX».
//
// 🔴 ЧОМУ ЦЕЙ СТЕНД МІРЯЄ НАСЛІДОК, А НЕ ФУНКЦІЇ ОКРЕМО.
// Проєкт уже обпікся на цьому 30.08: сторожі міряли помічники (`singleFlight`,
// `setBusy`) і були зелені, поки екран входу не збирався ЗОВСІМ. Тому тут немає
// перевірок «стемер працює» — вони в `search-stem.mjs`. Тут сцена: справжні
// оголошення, справжній запит людини, і питання одне — знайшлось чи ні.
//
// 📐 КОНТРОЛЬ ВСЕРЕДИНІ: кожен приклад проганяється ДВІЧІ — новим пошуком і
// СТАРИМ (`hay.includes(q)`, як у board.js:1415 до цієї роботи). Старий мусить
// провалитись, інакше перевірка нічого не доводить: якби вона світилась зеленою
// на обох, це означало б, що приклад і без нас працював.
//
// Запуск: node tests/search-engine.mjs

import { search, detectIntent, normalize, tokenize } from '../src/core/search.js';

let ok = 0, fail = 0; const bad = [];
const check = (cond, name, detail = '') => {
  if (cond) { ok++; console.log(`✅ ${name}${detail ? '  — ' + detail : ''}`); }
  else { fail++; bad.push(name); console.log(`❌ ${name}${detail ? '  — ' + detail : ''}`); }
};

// СТАРИЙ пошук — дослівно те, що стояло в board.js:1415.
const старий = (items, q) => items.filter(p => {
  const hay = [p.text, p.title, p.author, ...(p.tags || [])].filter(Boolean).join(' ').toLowerCase();
  return hay.includes(String(q).trim().toLowerCase());
});

// Сцена. Тексти написані в стилі живих оголошень бази (де «будинок» ×9,
// «будинку» ×6, «будинки» ×3), але без чужих контактів і імен.
const ОГОЛОШЕННЯ = [
  { id: 1, title: 'Продам будинок в Жорнищах', text: 'Цегляний будинок, 90 кв.м, є вода та електроенергія. Розгляну пропозиції.', location: 'Жорнище', tags: ['нерухомість'], price: 45000 },
  { id: 2, title: 'Продається приватний житловий будинок', text: 'Земельна ділянка 25 соток, поруч зупинка.', location: 'Олика', tags: ['нерухомість'], price: 30000 },
  { id: 3, title: 'Надаю послуги з косіння газонів', text: 'Покошу траву на прибудинковій території, свій інструмент.', location: 'Олика', tags: ['послуги'], price: null },
  { id: 4, title: 'Ремонт побутової техніки', text: 'Майстер відремонтує пральні машини, холодильники.', location: 'Олика', tags: ['послуги'], price: null },
  { id: 5, title: 'Куплю велосипед дорослий', text: 'Розгляну варіанти в доброму стані.', location: 'Дерно', tags: ['транспорт'], price: null },
  { id: 6, title: 'Продам автомобіль', text: 'Машина на ходу, потребує невеликого ремонту.', location: 'Олика', tags: ['транспорт'], price: 2500 },
];

const назви = ids => ids.map(i => `#${i}`).join(',');
const знайдено = q => search(ОГОЛОШЕННЯ, q).map(r => r.item.id);

// ── А. ПРИКЛАДИ ВОВИ ДОСЛІВНО ────────────────────────────────────────────────
console.log('\n── А. Приклади Вови (кожен — з контролем на старому пошуку) ──');
const СЦЕНАРІЇ = [
  { q: 'будинок жорнище',        треба: 1, чому: 'інший порядок + відмінок' },
  { q: 'Будинок Жорнище',        треба: 1, чому: 'великі літери' },
  { q: 'будинки',                треба: 1, чому: 'множина проти однини' },
  { q: 'хочу купити хату',       треба: 2, чому: 'синонім хата→будинок + стоп-слова' },
  { q: 'хто може покосити траву', треба: 3, чому: 'косіння↔покосити' },
  { q: 'ремонт пральної машини', треба: 4, чому: 'пральна→побутова техніка' },
  { q: 'буднок жорнище',         треба: 1, чому: 'друкарська помилка' },
];

for (const { q, треба, чому } of СЦЕНАРІЇ) {
  const нове = знайдено(q);
  const старе = старий(ОГОЛОШЕННЯ, q).map(p => p.id);
  check(нове.includes(треба), `«${q}» → #${треба}`, `${чому} · знайшло ${назви(нове) || '—'}`);
  check(!старе.includes(треба), `   ↳ КОНТРОЛЬ: старий пошук НЕ знаходив`, `старий дав ${назви(старе) || '—'}`);
}

// ── Б. НЕ ПІДМІШУЄ ЗАЙВОГО ───────────────────────────────────────────────────
// 🛑 Найлегший спосіб пройти блок А — знаходити все на світі. Тут це ловиться.
console.log('\n── Б. Точність: зайве не підмішується ──');
check(!знайдено('будинок жорнище').includes(2), 'будинок в Жорнищах ≠ будинок в Олиці', `дало ${назви(знайдено('будинок жорнище'))}`);
check(!знайдено('велосипед').includes(6),        'велосипед ≠ автомобіль');
check(знайдено('квартира київ').length === 0,     'чужий запит → порожньо');
check(!знайдено('холодильник').includes(3),       'холодильник ≠ косіння газонів');

// ── В. НАМІР (продам / куплю) ────────────────────────────────────────────────
console.log('\n── В. Намір читається, а не викидається ──');
// 🔑 Намір називається ТАК САМО, як категорія Дошки — не 'buy'/'sell', а 'куплю'/'продам'.
check(detectIntent('куплю будинок') === 'куплю',   '«куплю будинок» → категорія «куплю»');
check(detectIntent('продам будинок') === 'продам', '«продам будинок» → категорія «продам»');
check(detectIntent('шукаю майстра') === 'шукаю',   '«шукаю майстра» → категорія «шукаю»');
check(detectIntent('будинок') === null,          'без слова наміру → null');
check(tokenize('хочу купити хату').join(' ') === 'хат',
      'стоп-слова і намір не потрапляють у токени', tokenize('хочу купити хату').join(' '));

// ── Г. ПІДПИС «ЧОМУ ЗНАЙШЛОСЬ» ───────────────────────────────────────────────
// Вова: «1 - так» на питання, чи показувати причину збігу.
console.log('\n── Г. Підпис «знайдено за…» ──');
const r1 = search(ОГОЛОШЕННЯ, 'будинок жорнище')[0];
check(r1 && r1.matched.length === 2, 'два слова запиту → два збіги в підписі', (r1?.matched || []).join(', '));
const r2 = search(ОГОЛОШЕННЯ, 'хочу купити хату')[0];
check(r2 && r2.matched.length > 0, 'синонім теж дає підпис', (r2?.matched || []).join(', '));

// ── Д. РАНЖУВАННЯ ────────────────────────────────────────────────────────────
console.log('\n── Д. Найрелевантніше — першим ──');
const ранг = search(ОГОЛОШЕННЯ, 'будинок');
check(ранг[0]?.item.id === 1 || ранг[0]?.item.id === 2, 'обидва будинки знайдено, перший — з заголовком', назви(ранг.map(r => r.item.id)));
check(ранг.length === 2, 'рівно два будинки, нічого зайвого', `${ранг.length}`);
const заг = search(ОГОЛОШЕННЯ, 'автомобіль');
check(заг[0]?.item.id === 6, 'збіг у заголовку важить більше за збіг у тексті');

// ── Е. НОРМАЛІЗАЦІЯ ──────────────────────────────────────────────────────────
console.log('\n── Е. Апостроф і пунктуація ──');
check(normalize("об'єкт, 90 кв.м!") === 'обєкт 90 кв м', 'апостроф знято, пунктуація прибрана', normalize("об'єкт, 90 кв.м!"));
check(normalize('обʼєкт') === normalize("об'єкт"), 'різні накреслення апострофа однакові');

console.log(`\n${fail ? '❌' : '✅'} ${ok}/${ok + fail} перевірок пройдено`);
if (fail) { console.log('   провалено:', bad.join(' · ')); process.exit(1); }
