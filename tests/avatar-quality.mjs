// Стенд: ФОТО ЖИТЕЛЯ ВИСТАЧАЄ НА ВСІ МІСЦЯ, ДЕ ЙОГО ПОКАЗУЮТЬ.
//
// 🔴 ЗАМОВЛЕННЯ ВОВИ (23.08, дослівно): *«я відкриваю карточку, і ця фотографія
// дуже неякісна, вона така розмита, піксельна трошки… нам треба тут максимальна
// якість»*.
//
// 📐 ПРИЧИНА БУЛА ВИМІРНА, А НЕ СМАКОВА. Аватар зберігався ОДНИМ файлом
// 256×256 (`maxDim: 256`), а показувався двома різними за розміром місцями, і
// обидва більші за нього:
//   • кружечок картки жителя 120px × щільність екрана 3 = **360 точок**;
//   • тап по кружечку → фото на весь екран, на iPhone Pro Max це ~1238 точок
//     завширшки, а для портретного фото 3:4 більша сторона виходить **1651** —
//     розтяг у 4.5 раза.
// ⚠️ 04.09 — МІСЦЕ ПОКАЗУ ПЕРЕЇХАЛО. Було `.pm-lightbox` (`style/messages.css`),
// стало `.fd-viewer` (`style/feed.css`): три переглядачі фото зведено в один,
// із зумом. Стенд міряє НОВЕ місце, вимога та сама. 🛑 Не помітити переїзд було
// б найгірше: без CSS `<img>` розтягується в натуральну величину (4000 точок),
// перевірка червоніє — і виглядає як «фото стало гіршим», хоча воно те саме.
// «Стиснути без втрати якості» тут неможливо в принципі: деталей, яких у файлі
// немає, не поверне ніщо. Тому стенд міряє РІВНО ЦЕ — чи вистачає пікселів.
//
// 🔑 ЩО САМЕ МІРЯЄМО, І ЧОМУ НАЖИВО. Розмір знімка можна порахувати на папері й
// помилитись: кружечок задає CSS, лайтбокс — відсотки від екрана, а щільність —
// пристрій. Тому питаємо браузер про підсумкові прямокутники при справжньому
// `deviceScaleFactor`, а не читаємо числа з коду.
//
// 🛑 ОКРЕМА ПЕРЕВІРКА — ЧЕСНІСТЬ КОДУВАННЯ. `canvas.toBlob(cb,'image/webp',q)`
// у браузері, що не вміє кодувати формат, **не падає і не віддає null** — він
// мовчки повертає PNG. Заміряно 23.08: попросили AVIF на 1024px → отримали PNG
// на **1273.9 KB** замість очікуваних ~48 KB, тобто в 26 разів важче, і жодної
// помилки ніде. Safari навчився кодувати WebP лише в iOS 17, тож на телефонах
// жителів це не теорія. Стенд вимагає, щоб код перевіряв ФАКТИЧНИЙ тип.
import { chromium } from 'playwright';
import { launch, reporter, projectFile } from './_lib.mjs';

const { ok, done } = reporter();

const utils = projectFile('src/core/utils.js');
const upload = projectFile('src/core/upload.js');
const account = projectFile('src/core/account-ui.js');
const card = projectFile('src/core/profile-card.js');
const supabase = projectFile('src/core/supabase.js');
const accountCss = projectFile('style/account.css');
const feedCss = projectFile('style/feed.css');   // 04.09: перегляд фото живе тут

// ── 1. РОЗМІРИ, ЯКІ КОД ОБІЦЯЄ ЗБЕРЕГТИ ────────────────────────────────────
const pair = utils.match(/avatarPairBlobs\(file,\s*\{\s*small\s*=\s*(\d+),\s*large\s*=\s*(\d+)/);
ok('`avatarPairBlobs` існує і називає обидва розміри', !!pair,
   pair ? `small=${pair[1]} large=${pair[2]}` : '(не знайдено)');
const SMALL = pair ? +pair[1] : 0;
const LARGE = pair ? +pair[2] : 0;

// ── 2. ЖИВІ ЗАМІРИ МІСЦЬ ПОКАЗУ ────────────────────────────────────────────
// Найбільший екран, який реально буває в жителя: iPhone Pro Max.
const b = await launch(chromium);
const ctx = await b.newContext({
  viewport: { width: 430, height: 932 }, deviceScaleFactor: 3, isMobile: true,
});
const p = await ctx.newPage();

// 🔴 ПОРТРЕТ 3:4 СПРАВЖНІМ ЗОБРАЖЕННЯМ, А НЕ ЧИСЛОМ ЗІ СТИЛЮ.
// Перша редакція цього стенда брала стелю лайтбокса через `getComputedStyle`
// і `parseFloat(st.maxWidth)`. У `position:fixed`-шарі відсоток НЕ резолвиться
// в пікселі — властивість повертається рядком `"96%"`, а `parseFloat("96%")`
// дорівнює **96**. Стенд множив цю дев'яносто шістку на щільність і рапортував
// «лайтбокс 288 точок» замість справжніх ~1240, тобто міряв не екран, а
// відсоток. Перевірка при цьому світилась ЗЕЛЕНИМ (384 < 1600) — і мовчала б,
// навіть якби розміру не вистачало.
// ✅ Тепер вставляємо РЕАЛЬНУ картинку відомих пропорцій і питаємо браузер, до
// якого прямокутника він її довів. Відсотки при цьому рахує він сам.
// ⚠️ І ДРУГА ПАСТКА ТІЄЇ САМОЇ МІРКИ, спіймана наступним прогоном. Спершу тут
// стояв портрет 300×400 — і браузер показав його як 900×1200 точок, тобто в
// натуральну величину. `max-width`/`max-height` лише ОБМЕЖУЮТЬ, вони не
// розтягують: картинка, менша за стелю, до стелі не доростає, і мірка знову
// показувала не максимум. Тому джерело свідомо БІЛЬШЕ за будь-який екран —
// 3000×4000, як справжнє фото з телефона, — і впирається саме в обмеження.
const ПОРТРЕТ = 'data:image/svg+xml;base64,' + Buffer.from(
  '<svg xmlns="http://www.w3.org/2000/svg" width="3000" height="4000"><rect width="3000" height="4000" fill="#888"/></svg>'
).toString('base64');

// ⚠️ ТРЕТЯ ПАСТКА ТІЄЇ САМОЇ МІРКИ. Без цього рядка мобільний Chromium бере
// віртуальний viewport 980px замість ширини пристрою, і `max-width: 96%`
// рахується від 980 — мірка показувала фото 2822 точки завширшки на екрані,
// де фізично є 1290. Стенд мусить мати ТОЙ САМИЙ `viewport`, що `index.html`,
// інакше він міряє сторінку, якої в застосунку не існує.
await p.setContent(`<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no, viewport-fit=cover"><style>
 *,*::before,*::after{box-sizing:border-box;margin:0;padding:0}
 :root{--ink:#2b2b2b;--ink-soft:#8a8a8a;--red:#722F37}
 body{background:#fff}
 ${accountCss}
 ${feedCss}
</style></head><body>
 <div class="pcard"><div class="pcard-avwrap"><span class="pcard-av pcard-av--img">
   <img src="${ПОРТРЕТ}" alt=""></span></div></div>
 <div class="fd-viewer"><div class="fd-viewer-track">
   <div class="fd-viewer-slide"><img src="${ПОРТРЕТ}" alt="фото"></div></div></div>
</body></html>`, { waitUntil: 'load' });

const заміри = await p.evaluate(async () => {
  const im = document.querySelector('.fd-viewer img');
  if (!im.complete) await new Promise(r => { im.onload = r; im.onerror = r; });
  const dpr = window.devicePixelRatio;
  const кружечок = document.querySelector('.pcard-av').getBoundingClientRect();
  const фото = im.getBoundingClientRect();
  return {
    dpr,
    завантажилось: im.naturalWidth > 0,
    кружечокТочок: Math.round(кружечок.width * dpr),
    фотоШиринаТочок: Math.round(фото.width * dpr),
    фотоВисотаТочок: Math.round(фото.height * dpr),
  };
});
await b.close();

// Більша сторона портретного фото на весь екран — це його ВИСОТА, зміряна
// браузером. Саме вона і є найсуворішою вимогою до великого файлу.
const портретБільшаСторона = Math.max(заміри.фотоШиринаТочок, заміри.фотоВисотаТочок);

ok('Заміри знято на реальному екрані справжньою картинкою',
   заміри.dpr === 3 && заміри.завантажилось && заміри.фотоВисотаТочок > 1000,
   `dpr=${заміри.dpr}, кружечок=${заміри.кружечокТочок}т, фото=${заміри.фотоШиринаТочок}×${заміри.фотоВисотаТочок}т`);

ok('🔴 Великого файла вистачає на кружечок картки', LARGE >= заміри.кружечокТочок,
   `треба ${заміри.кружечокТочок} точок, маємо ${LARGE}`);

ok('🔴 Великого файла вистачає на фото у весь екран (портрет 3:4)',
   LARGE >= портретБільшаСторона * 0.97,
   `треба ${портретБільшаСторона} точок, маємо ${LARGE}`);

// 🔑 Контроль здорового глузду: саме ДРІБНОГО файла НЕ вистачало б — це і є
// вада, на яку скаржився Вова. Якщо колись дрібний доростить до кружечка,
// перевірка почервоніє і змусить перечитати, навіщо взагалі два розміри.
ok('🔴 Дрібного файла на картку НЕ вистачає — тому версій і дві',
   SMALL > 0 && SMALL < заміри.кружечокТочок,
   `дрібний ${SMALL} проти ${заміри.кружечокТочок} потрібних`);

// ── 3. ЧЕСНІСТЬ КОДУВАННЯ ──────────────────────────────────────────────────
ok('🔴 Тип стиснутого файлу перевіряється ФАКТОМ, а не вірою в підтримку',
   /webp\.type === 'image\/webp'/.test(utils),
   'у `encodeCanvas` має стояти звірка `blob.type === "image/webp"`');
ok('🔴 Є відкат на JPEG, коли WebP не закодувався',
   /toBlob\('image\/jpeg'\)/.test(utils));
ok('🛑 AVIF не проситься ніде — його `toBlob` не кодує жоден браузер',
   !/toBlob\([^)]*image\/avif/.test(utils) && !/'image\/avif'/.test(upload));

// ── 4. ЛАНЦЮГ ЗІБРАНИЙ ─────────────────────────────────────────────────────
ok('Кабінет вантажить ПАРУ, а не один файл',
   /uploadAvatarPair\(file\)/.test(account) && !/square:\s*true,\s*maxDim:\s*256/.test(account));
ok('🔴 Картка просить ВЕЛИКУ версію', /largePhotoUrl\(url\)/.test(card));
ok('🔴 Картка має відкат на дрібну (аватари, старші за 23.08)',
   /pcardPhotoSm/.test(card) && /fellBack/.test(card));
// 04.09: відкат переїхав разом із переглядачем — картка передає запасну адресу
// третім аргументом, а тримає її `core/photo-viewer.js`, а не `utils.js`.
const viewer = projectFile('src/core/photo-viewer.js');
ok('🔴 Перегляд фото теж уміє відкат',
   /openPhotoViewer\(url, 0, \{ fallbackUrl: small \}\)/.test(card)
   && /fallbackUrl/.test(viewer));
ok('Адреса великої версії виводиться з дрібної одним правилом',
   /export function largePhotoUrl/.test(supabase) && /LARGE_PHOTO_SUFFIX/.test(supabase));
// У базу мусить іти адреса ДРІБНОЇ: її читають усі наявні списки, і якби туди
// потрапила велика, кожен кружечок у Стрічці тягнув би файл на 80 KB.
ok('🔴 У профіль зберігається адреса ДРІБНОЇ версії',
   /return \{ url: small\.url, error: null \}/.test(upload),
   'інакше списки почали б вантажити велике фото');

done();
