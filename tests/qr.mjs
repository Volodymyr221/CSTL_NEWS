// tests/qr.mjs — КОДУВАЛЬНИК QR ВИДАЄ САМЕ ТЕ, ЩО ПРОЧИТАЄ КАМЕРА.
//
// 🔴 ЗАРАДИ ЧОГО. `src/core/qr.js` написаний у проєкті з нуля (стороння
// бібліотека зламала б офлайн і привела б третю сторону до наших відвідувачів).
// Ціна такого рішення одна: помилку в ньому НЕ ВИДНО. Зіпсований QR виглядає як
// звичайний QR — квадратики на місці, кути на місці, — і про те, що він не
// читається, дізнається тільки людина з телефоном у руках.
//
// 🔬 ПРИКЛАД ІЗ ЦЬОГО Ж ДНЯ, ЧОМУ ЦЕ НЕ ПАРАНОЯ: перша версія файлу малювала
// службові біти формату з переплутаними рядком і колонкою. Розбіжність — девʼять
// точок із 625. Код виглядав бездоганно і не сканувався б **жодною** камерою.
//
// ➡️ ТОМУ ЕТАЛОН ТУТ ЧУЖИЙ. Числа нижче зняті 29.08 з **незалежної реалізації**
// (пакет `qrcode`, режим «байти», рівень M) і заморожені. Вони не виведені з
// нашого коду, тож наш код не може «підтвердити сам себе»: він або збігається з
// чужою реалізацією точка-в-точку, або стенд падає.
// 🛑 Самого пакета в залежностях проєкту НЕМАЄ і бути не має — заморожений
// відбиток дає ту саму гарантію без зайвої залежності у збірці.

import { createHash } from 'crypto';
import { projectFile, reporter } from './_lib.mjs';

const { ok, done } = reporter();
const REV = process.env.BUNDLE_REV || '';

// Модуль — ESM, а проєкт без `"type": "module"`, тож просто `import` його не
// візьме. Піднімаємо як data-модуль: заразом працює контроль `BUNDLE_REV`.
let qr = null;
try {
  const src = projectFile('src/core/qr.js', REV);
  qr = await import('data:text/javascript;base64,' + Buffer.from(src).toString('base64'));
} catch (_) { /* контрольний прогін на старому коді — файлу ще немає */ }

ok('модуль існує і віддає qrMatrix/qrSvg',
   !!qr && typeof qr.qrMatrix === 'function' && typeof qr.qrSvg === 'function');

if (!qr) { done(); }

const fp = (m) => {
  let bits = '';
  for (let r = 0; r < m.size; r++) for (let c = 0; c < m.size; c++) bits += m.modules[r][c] ? '1' : '0';
  return createHash('sha256').update(bits).digest('hex').slice(0, 16);
};

// ── 1. ЗБІГ ІЗ ЧУЖОЮ РЕАЛІЗАЦІЄЮ, ТОЧКА-В-ТОЧКУ ──────────────────────────────
// [текст, очікуваний розмір сітки, відбиток усіх точок]
const ETALON = [
  ['https://castlelife.org/',                 25, '8871f4bceeb7afc0'],
  ['https://castlelife.org/#/post/news/12345', 29, '762f85fb0098df01'],
  ['Олика',                                    21, '2522abab2edbedbe'],
  ['https://castlelife.org/#/tab/board',       29, '37b65951e3bbf85e'],
  ['z'.repeat(200),                            57, '2d12ffbc18c105d6'],
];

for (const [text, size, hash] of ETALON) {
  let m = null;
  try { m = qr.qrMatrix(text); } catch (_) {}
  const label = text.length > 26 ? text.slice(0, 23) + '…' : text;
  ok(`«${label}» — сітка ${size}×${size}`, !!m && m.size === size, m ? `дав ${m.size}` : 'помилка');
  ok(`«${label}» — усі точки як в еталона`, !!m && fp(m) === hash,
     m ? `${fp(m)} проти ${hash}` : '');
}

// ── 2. КОРОТКИЙ І ДОВГИЙ ТЕКСТ ───────────────────────────────────────────────
// Українська адреса в UTF-8 важить удвічі — версія має підрости сама.
ok('версія росте під довжину', qr.qrMatrix('A').size < qr.qrMatrix('x'.repeat(150)).size);

// 🛑 Найважливіше в цьому розділі: задовгий текст мусить КИНУТИ ПОМИЛКУ, а не
// намалювати обрізаний код. Мовчазний зіпсований QR — саме той клас вади, коли
// людина бачить картинку і вважає, що все гаразд.
let threw = false;
try { qr.qrMatrix('q'.repeat(400)); } catch (_) { threw = true; }
ok('🔴 задовгий текст → помилка, а не зіпсований код', threw);

// ── 3. SVG ───────────────────────────────────────────────────────────────────
const svg = qr.qrSvg('https://castlelife.org/');
ok('svg — це один <svg> з одним контуром',
   /^<svg /.test(svg) && (svg.match(/<path /g) || []).length === 1);
// Світле поле навколо коду обовʼязкове за стандартом: без нього камера не бачить
// меж і код не читається на строкатому тлі.
ok('світле поле навколо коду 4 точки', / viewBox="0 0 33 33"/.test(svg),
   'сітка 25 + 4 + 4');
ok('svg має суцільне світле тло', /<rect width="33" height="33" fill="#ffffff"\/>/.test(svg));

// Контур малюється відрізками, а не окремими квадратиками — інакше картинка
// важить учетверо більше на порожньому місці.
const runs = (svg.match(/h(\d+)v1/g) || []).map(s => +s.match(/h(\d+)/)[1]);
ok('точки склеєні у відрізки', runs.length > 0 && Math.max(...runs) > 1,
   `найдовший відрізок ${runs.length ? Math.max(...runs) : 0}`);

done();
