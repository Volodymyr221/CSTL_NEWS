// Стенд: ЕКРАН НЕ МОВЧИТЬ, КОЛИ БАЗА НЕ ВІДПОВІЛА.
//
// ═════════════════════════════════════════════════════════════════════════════
// 🔴 ЗАРАДИ ЧОГО (18.09.2026). Прогін «перший житель із поганим інтернетом»
// заміряв на живому застосунку з недосяжною базою:
//   • Стрічка — **0 знаків** на екрані. Порожнє полотно;
//   • Питання — **0 знаків**;
//   • Дошка   — «Тут поки порожньо», тобто «оголошень у громаді немає». Неправда.
// На повільному звʼязку (база думає 12 с) усі три мовчали ЩОНАЙМЕНШЕ шість секунд.
//
// 🛑 ЧОМУ ЦЕ ПРОЙШЛО ПОВЗ 155 СТЕНДІВ. Кожен із них підміняє Supabase заглушкою,
// яка ЗАВЖДИ відповідає. Сцена простіша за життя — і вада живе рівно там, куди
// жоден стенд не заглядав. Тому цей сторож робить протилежне: він ЛАМАЄ мережу
// і питає, що людина побачить.
//
// 📐 ЩО САМЕ МІРЯЄМО — НАСЛІДОК, А НЕ КОД. Питання одне: **чи є на екрані слова**.
// Не «чи викликали paintOffline», не «чи є клас у бандлі» — а чи людина, яка
// дивиться в телефон, дістала відповідь. Тому тут справжні тапи по таб-бару й
// читання `innerText`.
//
// 🔑 КОНТРОЛЬ, без якого стенд нічого не вартий. «На екрані є слова» — надто
// легкий результат: він вийде і тоді, коли ми виміряли не ту вкладку, і тоді,
// коли застосунок узагалі не піднявся. Приладом слугує ГРОМАДА: вона при тій
// самій зламаній мережі мусить показати «Погода тимчасово недоступна» і новини
// з локального файлу. Змовкла й вона — бреше прилад, а не код.
// ═════════════════════════════════════════════════════════════════════════════
import { chromium } from 'playwright';
import { chromiumPath, serve, reporter } from './_lib.mjs';

const { ok, done } = reporter();
const { url, stop } = await serve();
const ep = chromiumPath();
const b = await chromium.launch({ ...(ep ? { executablePath: ep } : {}) });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true,
                                 hasTouch: true, serviceWorkers: 'block', locale: 'uk-UA' });
const p = await ctx.newPage();

// 🔴 РІЖЕМО ВСЕ ЗОВНІШНЄ. Сам сайт віддається локально, решта світу — недосяжна.
// Це і є сцена: база, погода й геокодер мовчать, як у селі зі слабким сигналом.
await p.route('**', r => r.request().url().startsWith(url)
  ? r.continue()
  : r.abort('internetdisconnected'));

await p.goto(url, { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(3500);
// Людина спершу приймає згоду — інакше банер перекриває низ екрана.
await p.locator('.consent-ok, [data-consent-ok], button:has-text("Погоджуюсь")')
       .first().click({ force: true }).catch(() => {});
await p.waitForTimeout(400);

// Читаємо вміст головної області. Таб-бар і банер згоди в неї не входять —
// саме тому пустий екран дає нуль знаків, а не «Стрічка · Питання · Громада».
async function оглянути(tab) {
  // Повертаємось на Громаду перед кожним переходом: на Дошці перший візит
  // зустрічає аркуш правил, і він перехоплює наступний тап по таб-бару.
  await p.locator('.tab-item[data-tab="community"]').first().click({ force: true });
  await p.waitForTimeout(500);
  await p.locator(`.tab-item[data-tab="${tab}"]`).first().click({ force: true });
  // ⏳ Чекаємо на ВІДПОВІДЬ, а не фіксовану паузу: Supabase повторює запит
  // кілька разів, перш ніж здатись, і на різних машинах це різний час. Ловимо
  // появу стану збою; не дочекались — читаємо що є (стенд однаково скаже правду).
  await p.waitForSelector('.scr-offline, .bd-offline', { timeout: 20000 }).catch(() => {});
  await p.waitForTimeout(400);
  return p.evaluate(() => {
    const m = document.querySelector('main.app-main');
    const txt = ((m && m.innerText) || '').trim();
    return {
      знаків: txt.length,
      текст: txt.slice(0, 400),
      стан: !!document.querySelector('.scr-loading, .scr-offline, .bd-offline'),
      кнопка: !!document.querySelector('.scr-offline-btn, .bd-offline-btn'),
    };
  });
}

// ── КОНТРОЛЬ ПРИЛАДУ: ГРОМАДА ПРИ ТІЙ САМІЙ ЗЛАМАНІЙ МЕРЕЖІ ГОВОРИТЬ ─────────
await p.locator('.tab-item[data-tab="community"]').first().click({ force: true });
await p.waitForTimeout(2500);
const громада = await p.evaluate(() => {
  const m = document.querySelector('main.app-main');
  return { текст: ((m && m.innerText) || '').trim() };
});
ok('🔴 КОНТРОЛЬ: Громада при зламаній мережі не мовчить (прилад не бреше)',
   /Погода тимчасово недоступна/.test(громада.текст),
   `перші слова: «${громада.текст.slice(0, 80)}»`);

// ── 1. СТРІЧКА ──────────────────────────────────────────────────────────────
const стрічка = await оглянути('shotam');
ok('🔴 Стрічка не лишається порожньою', стрічка.знаків > 0, `знаків: ${стрічка.знаків}`);
ok('🔴 Стрічка каже, що не змогла звʼязатися',
   /не вдал|недоступн|перевір інтернет/i.test(стрічка.текст),
   `«${стрічка.текст.slice(0, 120)}»`);
ok('🔴 у Стрічці є кнопка повтору', стрічка.кнопка);

// ── 2. ПИТАННЯ ──────────────────────────────────────────────────────────────
const питання = await оглянути('discussions');
ok('🔴 Питання не лишаються порожніми', питання.знаків > 0, `знаків: ${питання.знаків}`);
ok('🔴 Питання кажуть, що не змогли звʼязатися',
   /не вдал|недоступн|перевір інтернет/i.test(питання.текст),
   `«${питання.текст.slice(0, 120)}»`);

// ── 3. ДОШКА: НЕ «ПОРОЖНЬО», А «НЕ ЗМОГЛИ» ──────────────────────────────────
// 📐 Найважливіша з трьох перевірок. «Тут поки порожньо» — це ВІДПОВІДЬ ПРО
// ГРОМАДУ, і давати її, коли відповіді немає, гірше за мовчання: людина повірить.
const дошка = await оглянути('board');
ok('🔴 Дошка не лишається порожньою', дошка.знаків > 0, `знаків: ${дошка.знаків}`);
ok('🔴 Дошка НЕ каже «порожньо», коли база не відповіла',
   !/Тут поки порожньо/i.test(дошка.текст),
   `«${дошка.текст.slice(0, 120)}»`);
ok('🔴 Дошка каже, що не змогла звʼязатися',
   /не вдал|недоступн|перевір інтернет/i.test(дошка.текст),
   `«${дошка.текст.slice(0, 120)}»`);

await b.close(); await stop();
done();
