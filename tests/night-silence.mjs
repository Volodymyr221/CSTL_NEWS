// tests/night-silence.mjs — НІЧНА ТИША 22:00–08:00, 25.08.2026.
//
// 🔴 ЧОМУ ЦЕЙ СТОРОЖ ЗАВЕДЕНО. Правило §12 `docs/QA_CONCEPT.md`: «ніч у містечку
// — не той час, коли телефон має дзвонити через питання про ремонт дороги».
// Реалізоване воно 25.08 в `send-answer-push` v6. Небезпека тут особлива: обидва
// способи зламати правило МОВЧАЗНІ. Якщо тиша не спрацює — про це дізнається
// людина, яку розбудили о 3-й ночі. Якщо спрацює зайвий раз — сповіщення просто
// не прийде, і ніхто ніколи не зрозуміє чому.
//
// 🔑 СТЕНД ВИКОНУЄ УМОВУ, А НЕ ГРЕПАЄ ЇЇ. Це головне рішення файлу. Пастка в
// цьому коді арифметична: вікно перетинає північ, тому умова мусить бути через
// `||`. Запис `h >= 22 && h < 8` виглядає РІВНО ТАК САМО правильно на око — і
// дає **нуль** годин тиші, тобто правило не працює жодного разу за добу.
// Регулярка «є слово NIGHT_FROM» такий код пропустила б із зеленим прапорцем.
// Тому стенд витягає справжній текст `ніч()` із файлу, підставляє свій
// годинник і ПРОГАНЯЄ всі 24 години. Він не питає «чи схожий код на правильний»
// — він рахує, скільки годин на добу телефон мовчить.
//
// 🔑 ДРУГА ПОЛОВИНА — ПОРЯДОК, А НЕ НАЯВНІСТЬ. Мовчання не сміє лишати сліду:
// вихід із типу 3 стоїть ДО `mark()`. Якби він стояв після, ми записали б
// адресатів у журнал, `missed()` зсунув би точку відліку — і нічні відповіді
// зникли б із ранкового «3 нові відповіді». Тиша перетворилась би на втрату.
// Це не питання стилю, і в тексті функції воно тримається лише порядком рядків
// — тобто рівно те, що ламається при першому ж рефакторингу.
//
// ⚠️ МЕЖІ. Стенд доводить ЛОГІКУ у вихідному файлі. Він не доводить, що в
// Supabase задеплоєна саме ця редакція (це перевірено живими викликами 25.08:
// чужий секрет → 401, справжній + неіснуючий коментар → `answer gone`), і не
// перевіряє `send-unanswered-push`: у типу 4 єдиний прохід об 11:00, ніч він не
// зачіпає за побудовою.
//
// 🔴 КОНТРОЛЬ — ДВА ШАРИ, і другий важливіший за перший.
// 1) `FN_REV=origin/main node tests/night-silence.mjs` → **1/14**: до 25.08
//    нічної тиші в коді не було взагалі.
// 2) МУТАНТ. Підмінити в `ніч()` `||` на `&&` і прогнати → **10/14**: падають
//    рівно чотири перевірки вікна («мовчить 0 год: []»). Це і є доказ, що
//    сторож ловить справжню помилку, а не лише відсутність коду: мутант
//    проходить будь-яку регулярку, бо всі слова на місці. Заміряно 25.08.

import { readFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { reporter } from './_lib.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REV = process.env.FN_REV || '';
const FILE = 'supabase/functions/send-answer-push/index.ts';

function read(rel) {
  if (REV) {
    try { return execSync(`git show ${REV}:${rel}`, { cwd: ROOT, encoding: 'utf8' }); }
    catch { return ''; }
  }
  return readFileSync(join(ROOT, rel), 'utf8');
}

const { ok, done } = reporter();
const src = read(FILE);

console.log('\n── 1. Вікно тиші рахується, а не вгадується ──');

// Витягаємо ЖИВИЙ текст правила і виконуємо його зі своїм годинником.
// Так само, як це зробить Deno, тільки година підставлена нами.
const мFrom = src.match(/const\s+NIGHT_FROM\s*=\s*(\d+)/);
const мTo   = src.match(/const\s+NIGHT_TO\s*=\s*(\d+)/);
const мНіч  = src.match(/function\s+ніч\s*\([\s\S]*?\n}/);

ok('межі вікна оголошені константами', !!мFrom && !!мTo,
   мFrom && мTo ? `NIGHT_FROM=${мFrom[1]} NIGHT_TO=${мTo[1]}` : 'NIGHT_FROM/NIGHT_TO у файлі немає');
ok('функція ніч() існує', !!мНіч, мНіч ? '' : 'у файлі немає function ніч()');

// Збираємо виконуваний зліпок: константи + сама функція + підставний годинник.
let ніч = null;
if (мFrom && мTo && мНіч) {
  try {
    ніч = new Function('година', `
      const NIGHT_FROM = ${мFrom[1]};
      const NIGHT_TO   = ${мTo[1]};
      const kyivHour = () => година;
      ${мНіч[0]}
      return ніч();
    `);
  } catch (e) { console.log('  ⚠️ не зібралось:', e.message); }
}

const тихі = ніч ? [...Array(24).keys()].filter((h) => ніч(h)) : [];

// 🔴 ГОЛОВНА ПЕРЕВІРКА ФАЙЛУ. Через `&&` цей список порожній.
ok('телефон мовчить рівно 10 годин на добу', тихі.length === 10,
   `мовчить ${тихі.length} год: [${тихі.join(', ')}]`);

ok('тихі години — саме 22,23 і 00–07',
   JSON.stringify(тихі) === JSON.stringify([0,1,2,3,4,5,6,7,22,23]),
   `порахувалось [${тихі.join(', ')}]`);

// Межі — окремо: саме на них живуть помилки «на одиницю».
ok('о 21:00 ще шлемо, о 22:00 вже мовчимо', !!ніч && !ніч(21) && ніч(22));
ok('о 07:00 ще мовчимо, о 08:00 вже шлемо', !!ніч && ніч(7) && !ніч(8));

// Збій визначення поясу мусить ВІДКРИВАТИ ворота, а не зачиняти: краще зайве
// сповіщення, ніж мовчки проковтнути всі.
const відкрито = !!ніч && ніч(-1) === false;
ok('невідома година (-1) — це НЕ ніч', відкрито,
   відкрито ? '' : 'при збої поясу функція замовкла б назавжди');

console.log('\n── 2. Кого тиша стосується, а кого ні ──');

const блок1 = src.match(/if\s*\(c\.reply_to_id\)\s*\{[\s\S]*?\n  \}/);
// 🛑 Тип 1 «вам відповіли» — персональне звернення, і §12 виводить його з-під
// правила НАВМИСНО. Якщо тиша колись просочиться сюди, це буде тиха втрата
// найважливішого сповіщення в застосунку.
const тип1чисто = !!блок1 && !/ніч\(\)/.test(блок1[0]);
ok('тип 1 («вам відповіли») тиші НЕ має — так і задумано', тип1чисто,
   тип1чисто ? '' : (блок1 ? 'у блок особистої відповіді просочилась нічна тиша'
                          : 'блок особистої відповіді у файлі не знайдено'));

const тип2 = /!recent\?\.length[^\n]*!ніч\(\)/.test(src);
ok('тип 2 (автору запису) тишу має', тип2, тип2 ? '' : 'умова типу 2 не питає про ніч');

const тип3 = /if\s*\(ніч\(\)\)\s*return/.test(src);
ok('тип 3 («мене теж цікавить») тишу має', тип3, тип3 ? '' : 'у типу 3 немає раннього виходу по ночі');

console.log('\n── 3. Мовчання не лишає сліду ──');

const вихід    = src.indexOf('if (ніч()) return');
const markInt  = src.indexOf(`'interest'`);
const порядок = вихід > 0 && markInt > 0 && вихід < markInt;
ok('вихід по ночі стоїть ДО mark(…\'interest\')', порядок,
   порядок ? '' : 'запис у журнал адресатів відбувся б РАНІШЕ мовчання — і ранкове число з’їло б нічні відповіді');

// Ранній вихід мусить пройти через finish(): він дописує підсумок `sent` у
// журнал. Голий `return` лишив би журнал без запису, і вікно тиші автора
// рахувалося б по діркавому журналу.
const черезFinish = /if\s*\(ніч\(\)\)\s*return\s+await\s+finish\(/.test(src);
ok('вихід по ночі йде через finish(), а не голим return', черезFinish,
   черезFinish ? '' : 'ранній вихід не дописує підсумок у журнал');

console.log('\n── 4. Годинник ──');

const пояс = /timeZone:\s*'Europe\/Kyiv'/.test(src);
ok('година береться по Europe/Kyiv', пояс, пояс ? '' : 'пояс не заданий — тиша рахувалась би по UTC');
// Без h23 частина реалізацій віддає «24» замість «0» опівночі — і година
// мовчки поїхала б рівно в найтихішу мить доби.
const h23 = /hourCycle:\s*'h23'/.test(src);
ok("hourCycle: 'h23' на місці", h23, h23 ? '' : 'опівночі година могла б прийти як 24');

done();
