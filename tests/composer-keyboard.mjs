// Стенд: КЛАВІАТУРА В КОМПОЗЕРІ — ЇЇ ВІДКРИВАЄ БУДЬ-ЯКЕ ПОЛЕ, І ПОЛЕ ВИДНО.
//
// 🗣️ СКАРГА ВОВИ (04.09, знімок композера події): «коли відкривається клавіатура,
// модалка з подією не підтягується… я натисну вибрати місце проведення, і воно не
// підтягується, клавіатура перекриває це все».
//
// 🔴 ПРИЧИНА БУЛА В ГЕЙТІ, А НЕ У ФОРМУЛІ ВИСОТИ. `attachKeyboardSheet` вважає
// клавіатуру відкритою, лише поки сфокусоване передане йому поле — а композер
// передавав ОДНЕ: текст допису. Фокус у даті, часі чи місці модуль не бачив
// узагалі, аркуш не стискався, і поля лишались під клавіатурою.
//
// ✅ Лікує `multiFieldFocus` — адаптер, який У ПРОЄКТІ ВЖЕ БУВ (`setupSheetShell`
// використовує його для редактора сторінки й команди). До композера він просто не
// доїхав, бо той кличе `attachKeyboardSheet` напряму.
//
// 🛑 `core/keyboard.js` НЕ ЗМІНЮВАВСЯ — і це окрема перевірка нижче. Там два фікси
// вже провалились (HOT_RULES №9 і №10: PR #638 зламав замок фону, PR #641 зробив
// так, що тап у поле закривав лист). Формула висоти в тому файлі вистраждана, і
// сторож стежить, щоб наступний захід на цю скаргу знову не поліз саме туди.
//
// 📐 ЩО МІРЯЄМО. Головна частина ВИКОНУЄ справжній `multiFieldFocus` із `feed.js`
// на живих полях: регулярка «є слово multiFieldFocus» зеленіла б і над адаптером,
// який мовчить на переході між полями — а саме це давало б «дьоргання» аркуша.
//
// 🔴 КОНТРОЛЬ: BUNDLE_REV=origin/main node tests/composer-keyboard.mjs → **9/13**.
// Падають рівно перевірки ЗАСТОСУВАННЯ: гейт (`input: textEl` замість адаптера) і
// підтягування поля.
// ⚠️ А чотири перевірки ВИКОНАННЯ там зелені — і це не слабкість контролю, а
// точний діагноз: сам `multiFieldFocus` був справний і раніше, зламаним було те,
// що композер його НЕ КЛИКАВ. Сторож розрізняє ці дві речі, і саме тому в ньому є
// обидві групи: якби лишились тільки перевірки виконання, він світився б зеленим
// над скаргою Вови.
import { chromium } from 'playwright';
import { projectFile, launch, reporter } from './_lib.mjs';

const REV = process.env.BUNDLE_REV || '';
const { ok, done } = reporter();

const feed = projectFile('src/tabs/feed.js', REV);
const kb   = projectFile('src/core/keyboard.js', REV);

console.log(`\n── КЛАВІАТУРА В КОМПОЗЕРІ${REV ? `   (КОНТРОЛЬ на ${REV})` : ''}`);

// ── 1. ГЕЙТ: не одне поле, а весь аркуш ─────────────────────────────────────
const блок = (feed.match(/detachKb = attachKeyboardSheet\(back\.querySelector\('\.fd-sheet-vp'\), compSheet[\s\S]{0,300}/) || [''])[0];
ok('композер віддає модулю БАГАТОПОЛЬОВИЙ фокус, а не одне поле',
   /input: compFocus/.test(блок), блок ? 'input: compFocus' : 'блок не знайдено');
ok('і бере для цього НАЯВНИЙ адаптер, а не свою копію',
   /multiFieldFocus\(compSheet\)/.test(feed));

// 🛑 Головне правило класу: адаптер мусить лишатись ЄДИНИМ. Друга копія тієї
// самої логіки в цьому проєкті вже розходилась чотири рази.
const копій = (feed.match(/function multiFieldFocus\(/g) || []).length;
ok('адаптер багатопольового фокуса в проєкті ОДИН', копій === 1, `копій: ${копій}`);

// ── 2. КРИХКИЙ МОДУЛЬ НЕ ЧІПАЛИ ─────────────────────────────────────────────
// ⚠️ Це не «перевірка на всяк випадок». Скарга звучить як «клавіатура ламає
// розкладку», і найпростіша реакція — піти правити формулу висоти в
// `core/keyboard.js`. Саме там два фікси провалились поспіль.
ok('🛑 формула висоти в core/keyboard.js на місці (`kb = max(стиск, зсув)`)',
   /const kb\s*=\s*Math\.max\(/.test(kb) || /kb = Math\.max/.test(kb));
ok('🛑 замок фону не прибрано (урок PR #638)', /freezeBackground\(/.test(kb));

// ── 3. ПОЛЕ ПІДТЯГУЄТЬСЯ У ВИДИМУ ЗОНУ ──────────────────────────────────────
// Стиснення аркуша лише ЗВІЛЬНЯЄ місце; поля дати/часу/місця лежать нижче в тілі,
// тож без прокрутки їх однаково не видно.
ok('сфокусоване поле підтягується у видиму зону тіла',
   /revealInScroller\(bodyEl, поле/.test(feed));
ok('…і саме в скролері `.fd-comp-body`, а не в аркуші',
   /const bodyEl\s*=\s*back\.querySelector\('\.fd-comp-body'\)/.test(feed));
// ⚠️ Затримка обовʼязкова: доти клавіатура ще виїжджає і вимір «чи видно поле»
// відповідав би про СТАРУ розкладку.
ok('вимір робиться ПІСЛЯ того, як розкладка стала на місце',
   /setTimeout\(\(\) => revealInScroller\(bodyEl, поле, 16\), \d{3}\)/.test(feed));

// ── 4. ВИКОНАННЯ: адаптер поводиться правильно (головна частина) ────────────
const тіло = (feed.match(/function multiFieldFocus\(root\)[\s\S]*?\n\}/) || [''])[0];

const сцена = `<!doctype html><html><head><meta charset="utf-8"></head>
<body>
  <div id="аркуш">
    <textarea id="a"></textarea>
    <input id="b" type="date">
    <input id="c" type="text">
  </div>
  <input id="поза" type="text">
<script type="module">
  ${тіло}
  const root = document.getElementById('аркуш');
  window.__готово = typeof multiFieldFocus === 'function';
  window.__міряти = async () => {
    const лог = [];
    const ад = multiFieldFocus(root);
    ад.addEventListener('focus', () => лог.push('focus'));
    ад.addEventListener('blur',  () => лог.push('blur'));
    const пауза = () => new Promise(r => setTimeout(r, 10));

    document.getElementById('a').focus(); await пауза();   // 1. тап у текст
    const післяТексту = лог.slice();
    document.getElementById('b').focus(); await пауза();   // 2. перехід у ДАТУ
    const післяДати = лог.slice();
    document.getElementById('c').focus(); await пауза();   // 3. перехід у МІСЦЕ
    const післяМісця = лог.slice();
    document.getElementById('поза').focus(); await пауза();// 4. вихід З аркуша
    const післяВиходу = лог.slice();

    return {
      текстВідкрив:  післяТексту.join(',') === 'focus',
      датаНеЗакрила: післяДати.join(',') === 'focus,focus',
      місцеНеЗакрило: післяМісця.join(',') === 'focus,focus,focus',
      вихідЗакрив:   післяВиходу.includes('blur'),
      усе: лог.join(','),
    };
  };
</script></body></html>`;

const b = await launch(chromium);
const p = await b.newPage();
await p.setContent(сцена);
await p.waitForTimeout(200);
const живий = await p.evaluate(() => window.__готово === true);
ok('адаптер виконується', живий);
const m = живий ? await p.evaluate(() => window.__міряти()) : {};
await b.close();

// 🔴 Це і є скарга Вови, зведена до перевірки: фокус у ДАТІ мусить тримати
// клавіатуру відкритою так само, як фокус у тексті.
ok('тап у текст відкриває клавіатуру', m.текстВідкрив === true, m.усе);
ok('🔴 перехід у поле ДАТИ не закриває її', m.датаНеЗакрила === true, m.усе);
ok('🔴 перехід у поле МІСЦЯ не закриває її', m.місцеНеЗакрило === true, m.усе);
// 🛑 Зустрічна межа: вихід за межі аркуша МУСИТЬ закривати. Без неї перевірки вище
// проходив би й адаптер, який просто ніколи не каже «blur» — тобто аркуш лишався б
// стиснутим назавжди.
ok('🛑 а вихід ЗА межі аркуша — закриває (інакше аркуш завис би стиснутим)',
   m.вихідЗакрив === true, m.усе);

done();
