// Стенд: ІЛЮСТРАЦІЯ ДЛЯ СТАТТІ ШУКАЄТЬСЯ СХОДИНКАМИ.
//
// 🔴 Привід (21.08): з 11 опублікованих статей кабінету 4 вийшли БЕЗ фото —
// «Радзивіллівські землі навколо Олики», «Ставок», «Олика на зламі епох»,
// «Дерно». Механізм пошуку працював (три інші ілюстрацію отримали), але за
// конкретним запитом про мале село на Wikimedia Commons немає нічого, а
// запасного ходу не було. Наслідок було видно на екрані: у стрічці Громади
// зникла велика перша картка (`markLead` вимагає фото — і правильно робить).
//
// ⚠️ ЧОМУ ПОШУК ПІДМІНЕНИЙ, А НЕ СПРАВЖНІЙ. Егрес-проксі цього середовища не
// пускає до commons.wikimedia.org (403), тож «нічого не знайшлось» тут означало
// б лише блокування мережі, а не поведінку коду. Перевіряємо саме те, що
// перевірити чесно можна: ПОРЯДОК спроб і зупинку на першому влучанні.
import { execFileSync } from 'child_process';
import { reporter } from './_lib.mjs';

const { ok, done } = reporter();

const прогін = (влучає) => {
  const код = `
import sys, json
sys.path.insert(0, 'scripts')
import ai_news_agent as ag

спроби = []
ВЛУЧАЄ = ${JSON.stringify(влучає)}
def підробка(q):
    спроби.append(q)
    return ("https://example.org/foto.jpg", "автор") if q == ВЛУЧАЄ else (None, None)

ag.fetch_wikimedia_image = підробка
img, credit = ag._ілюстрація({"image_query": "Radziwill lands census", "title": "Ставок: село при замку"})
print("РЕЗУЛЬТАТ", json.dumps({"спроби": спроби, "фото": img, "автор": credit}, ensure_ascii=False))
`;
  const out = execFileSync('python3', ['-c', код], { encoding: 'utf-8' });
  return JSON.parse(out.split('\n').find(l => l.startsWith('РЕЗУЛЬТАТ')).slice(10));
};

// 1. Перша сходинка — те, що попросив сам агент. Якщо вона влучає, далі не йдемо:
//    зайві звернення до чужого безкоштовного сервісу — це та сама вада, через
//    яку `nearestSettlement` заборонили ходити в геокодер.
{
  const r = прогін('Radziwill lands census');
  ok('🔴 перша спроба — запит самого агента', r.спроби[0] === 'Radziwill lands census', r.спроби.join(' → '));
  ok('🔴 на влучанні пошук спиняється (не б’ємо сервіс марно)', r.спроби.length === 1, `${r.спроби.length} спроб`);
  ok('фото і автор повертаються разом', !!r.фото && !!r.автор, `${r.фото} · ${r.автор}`);
}

// 2. Головне: коли конкретного немає — доходимо до запасних. Саме цього бракувало.
{
  const r = прогін('Olyka Castle');
  ok('🔴 коли конкретного фото немає — доходимо до замку Радзивіллів',
     r.фото && r.спроби.includes('Olyka Castle'), r.спроби.join(' → '));
  ok('🔴 порядок від точного до загального (заголовок раніше за запасні)',
     r.спроби.indexOf('Ставок: село при замку') < r.спроби.indexOf('Olyka Castle'),
     r.спроби.join(' → '));
}

// 3. Нічого не знайшлось — чесно повертаємо порожнечу, а не чуже фото.
//    🛑 Останньою сходинкою свідомо НЕ ставимо «Волинь» чи «Україна»: знімок
//    випадкового місця під статтею про Ставок гірший за відсутність знімка.
{
  const r = прогін('нічого-не-влучає');
  ok('🔴 нічого не знайшлось — жодного фото, а не випадкове', r.фото === null, String(r.фото));
  ok('запасні вичерпні й не безмежні', r.спроби.length === 5, `${r.спроби.length}: ${r.спроби.join(' → ')}`);
}

done();
