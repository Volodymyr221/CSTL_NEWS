# Сцена для стенда `tests/ceo-report.mjs` — НЕ самостійний стенд.
#
# 🔴 НАВІЩО ОКРЕМИМ ФАЙЛОМ. Рішення про обірвану відповідь агент ухвалює
# всередині `main()`, і перевірити його можна лише прогнавши СПРАВЖНІЙ `main()`.
# Виклик моделі коштує грошей, тож підміняємо найнижче, що можна — `urlopen`:
# тоді весь шлях «відповідь → стан → код виходу» проходить код агента, а не моя
# вигадка про нього. Підміна самої `покликати()` перевіряла б лише заглушку.
#
# 🛑 Слідів не лишаємо навмисно: ні запису витрат на диск, ні звіту в базу.
import io, json, sys, urllib.request
sys.path.insert(0, 'scripts')
import ceo_agent as а

випадок = sys.argv[1]            # 'обірвано' | 'готово'
відповідь = {
    "content": [{"type": "text", "text": "# ЗВІТ\n\nтекст\n\nЗАВДАННЯ-ДО-РЕЄСТРУ:\n- полагодити запит\n"}],
    "usage": {"input_tokens": 1000, "output_tokens": 500},
    "stop_reason": "max_tokens" if випадок == "обірвано" else "end_turn",
}
тіло_запиту = {}

class ВідповідьЗаглушка(io.BytesIO):
    def __enter__(self): return self
    def __exit__(self, *a): return False

def підміна(req, timeout=None):
    тіло_запиту.update(json.loads(req.data))
    return ВідповідьЗаглушка(json.dumps(відповідь).encode())

urllib.request.urlopen = підміна

слід = {}
а.зібрати_контекст = lambda: {}
а.зібрати_промпт = lambda ctx: "запит"
а.витрачено_цього_місяця = lambda: 0.0
а.записати_витрату = lambda usage, є: 0.1454          # без запису на диск
а.зберегти_звіт = lambda текст, стан, причина, ціна=0.0: слід.update(
    {"стан": стан, "причина": причина, "символів": len(текст)})
а.зберегти_пропозицію = lambda з: слід.update({"пропозиції": з})

код = а.main()
print(json.dumps({"код": код, "стеля_довжини": тіло_запиту.get("max_tokens"), **слід},
                 ensure_ascii=False))
