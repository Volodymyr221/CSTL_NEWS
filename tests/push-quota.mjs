// Стенд: СТЕЛЯ ЧАСТОТИ СПОВІЩЕНЬ СТОЇТЬ ТАМ, ДЕ ПОТРІБНО, І НЕ СТОЇТЬ ДЕ НЕ ТРЕБА.
//
// 🔴 ЗАРАДИ ЧОГО (аудит готовності 30.09). `notif_prefs` дає ВИМИКАЧІ по
// розділах, і це не стеля: від «вісім сповіщень за вечір, і людина заборонила
// їх у телефоні» захисту не було. 🛑 Заборона на рівні телефона — це кінець:
// людина вимкнула не розділ, що надокучив, а ЗАСТОСУНОК, і повернути її в
// сповіщення вже нічим.
//
// 🔑 ГОЛОВНЕ, ЩО СТЕРЕЖЕ ЦЕЙ ФАЙЛ — НЕ НАЯВНІСТЬ СТЕЛІ, А ЇЇ МЕЖУ.
// Стеля на персональному сповіщенні гірша за відсутність стелі: проґавлена
// відповідь на МОЄ питання або скасування МОГО рейсу коштує дорожче за зайве
// сповіщення, і саме на цьому тримається вся звичка («спитав → відповіли →
// вернувся»). Тому половина перевірок тут — про те, де квоти БУТИ НЕ МАЄ.
//
// 🛑 ЧОМУ ЦЕ ТЕКСТОВИЙ СТОРОЖ — та сама причина, що в `push-scale`: Edge
// Functions із пісочниці не запускаються, а підписників у базі сьогодні
// десятки, тож навіть живий прогін нічого б не довів. Беремо живий текст
// функцій і вимагаємо, щоб рішення були на місці.
//
// ⚠️ ЦЕЙ СТЕНД НЕ ДОВОДИТЬ, ЩО СТЕЛЯ ПРАЦЮЄ НА ЖИВІЙ БАЗІ. Він доводить, що
// вона прикладена до правильного класу і що квота повертається, коли розсилка
// не дійшла. Серверна половина (`push_quota_take` одним оператором) доводиться
// транзакцією з відкотом на живій базі — не тут.

import { readFileSync, readdirSync, existsSync } from 'fs';
import { join } from 'path';
import { ROOT, reporter } from './_lib.mjs';

const { ok, done } = reporter();

const ДИР = join(ROOT, 'supabase/functions');
const функції = readdirSync(ДИР).filter(н => н.startsWith('send-'));
// Коментарі знімаємо ПЕРШИМ. Інакше сторож червоніє на власній пояснювальній
// прозі: у шапці `send-page-push` слова «push_quota_take» і «персональне»
// стоять навмисно, і текстова перевірка не відрізняє код від розмови про код
// (та сама пастка, що спіймала `boot-noise`).
const код = н => readFileSync(join(ДИР, н, 'index.ts'), 'utf-8')
  .replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

ok('знайшов функції розсилки', функції.length >= 6, функції.join(', '));

// ── 1. SQL-ЧАСТИНА ІСНУЄ І НЕ ЗАБУТА ───────────────────────────────────────
// 🔑 Без цього файлу стеля в Edge Function — виклик у порожнечу: `rpc` віддасть
// помилку, а домовленість «збій = пропускаємо всіх» мовчки знімає стелю цілком.
// Тобто забутий SQL виглядав би точно як працююча стеля — рівно той клас вади,
// від якого правило «якщо „не працює“ не відрізнити від „усе гаразд“».
const sqlШлях = join(ROOT, 'scripts/supabase_push_quota.sql');
ok('🔴 SQL-частина стелі лежить у `scripts/`', existsSync(sqlШлях), sqlШлях);
const sql = existsSync(sqlШлях) ? readFileSync(sqlШлях, 'utf-8') : '';
ok('…і несе обидві функції та прибирання журналу',
   /push_quota_take/.test(sql) && /push_quota_release/.test(sql) && /prune_push_quota_log/.test(sql),
   'take/release/prune');

// 📐 Журнал стелі мусить прибиратись за розкладом. 24.09 диск Supabase вичерпав
// бюджет IO саме через розпухлі службові журнали — повторювати не будемо.
ok('🔴 журнал стелі стоїть у розкладі на прибирання',
   /cron\.schedule\('prune-push-quota'/.test(sql),
   (sql.match(/cron\.schedule\('[^']+'[^,]*, *'[^']+'/) || ['—'])[0]);

// ── 2. СТЕЛЯ ПРИКЛАДЕНА ДО КЛАСУ «ГРОМАДА» ─────────────────────────────────
// Потоп приходить звідси: один допис на спільноту × пʼять спільнот × вечір.
ok('🔔 `send-page-push` бере квоту перед розсилкою',
   /push_quota_take/.test(код('send-page-push')),
   'квота на місці');

// ── 3. КВОТА ПОВЕРТАЄТЬСЯ, КОЛИ НЕ ДІЙШЛО НІКОМУ ───────────────────────────
// Інакше людина втратила б добову квоту на сповіщення, якого не бачила — і це
// гірше за відсутність стелі, бо збій сервісу push тихо з'їдав би чужі
// сповіщення. Той самий прийом, що з `page_push_log`.
ok('🔴 при `sent === 0` квота повертається',
   /push_quota_release/.test(код('send-page-push')),
   'повернення на місці');

// ── 4. ГОЛОВНЕ: ПЕРСОНАЛЬНЕ НЕ ПРИТИШУЄТЬСЯ ────────────────────────────────
// 🛑 Перелік закритий НАВМИСНО. Якщо колись знадобиться прикласти стелю ще до
// одного класу, це мусить бути окреме рішення з окремим рядком тут, а не
// тихе розповзання квоти по всіх функціях підряд.
const ПЕРСОНАЛЬНІ = [
  'send-answer-push',     // відповідь на МОЄ питання — двигун звички
  'send-chat-push',       // повідомлення в чаті
  'send-comment-push',    // коментар під моїм дописом (і так пакетується щохвилини)
  'send-bus-push',        // скасування МОГО рейсу: людина прийде на зупинку
  'send-event-push',      // нагадування про подію, яку людина сама позначила
  'send-group-push',      // повідомлення в групі, до якої людина вступила
];
const зКвотою = ПЕРСОНАЛЬНІ.filter(н => функції.includes(н) && /push_quota_take/.test(код(н)));
ok('🔴 персональні сповіщення НЕ притишуються стелею',
   зКвотою.length === 0,
   зКвотою.length ? `стеля проникла в: ${зКвотою.join(', ')}` : ПЕРСОНАЛЬНІ.length + ' функцій чисті');

// ── 5. ЧОМУ `send-unanswered-push` БЕЗ СТЕЛІ — І ЦЕ НЕ НЕДОГЛЯД ─────────────
// Воно вже самообмежене двічі: розклад (`0 8,9`) і власний журнал за добу. Але
// якщо колись хтось знімe цей самообмеж, стеля стане потрібна — тож стенд
// вимагає, щоб ОДНЕ з двох було на місці.
{
  const т = код('send-unanswered-push');
  ok('🟡 `send-unanswered-push` самообмежене (година доби або власний журнал)',
     /kyivHour/.test(т) || /qa_unanswered_push_log/.test(т),
     'самообмеж на місці');
}

// ── 6. КОНТРОЛЬ: СТОРОЖ УМІЄ ЧЕРВОНІТИ ─────────────────────────────────────
// Без цього рядка весь файл міг би зеленіти на будь-якому тексті. Шукаємо
// назву, якої в коді немає й бути не має, тим самим способом, яким шукаємо
// справжні: якщо тут зелено, значить спосіб пошуку взагалі нічого не бачить.
ok('контроль: той самий пошук НЕ знаходить вигаданої назви',
   !/push_quota_вигадана/.test(код('send-page-push')),
   'спосіб пошуку розрізняє наявне і відсутнє');

done();
