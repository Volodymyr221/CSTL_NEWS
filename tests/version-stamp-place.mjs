// Стенд: ЛІЧИЛЬНИК ВЕРСІЇ НЕ ЛІЗЕ НА ЗНІМКИ ЕКРАНА.
//
// 🔴 ЗАРАДИ ЧОГО ВІН ІСНУЄ (18.09). 🗣️ Вова: «лічильник версії зараз у шапці
// біля назви. Перемісти в бургер-меню, щоб його не було видно на цих скрінах».
// Знімки застосунку йдуть у презентацію на грант і в рекламні креативи — дрібний
// технічний напис `v6204 · 18.09 10:48` на кожному з них виглядає як недороблене.
//
// 🔑 ЩО САМЕ МІРЯЄМО — НАСЛІДОК НА ЕКРАНІ, а не наявність класу в розмітці.
// Текстова перевірка «чи лежить `.deploy-stamp` усередині `.sidebar`» пропустила б
// найпростішу регресію: хтось лишає його в меню, але ставить `position: fixed` —
// і напис знову на екрані. Тому питаємо браузер, чи потрапляє він у кадр.
//
// 🛑 І ДРУГЕ, ВАЖЛИВІШЕ ЗА ПЕРШЕ: лічильник мусить лишитись ЖИВИМ.
// Його текст підміняє деплой (`.github/workflows/deploy.yml`) через `sed` по
// ШАБЛОНУ `v<число> · ДД.ММ ГГ:ХХ` — не по класу і не по позиції. Досить комусь
// «причепурити» рядок (забрати `·`, дописати слово, розбити на два вузли) — і
// підміна перестане влучати МОВЧКИ: лічильник замерзне на `v1 · 01.01 00:00`, а
// це єдиний спосіб побачити з телефона, чи доїхав деплой. Саме цей клас вад —
// «нічого не впало, просто перестало працювати» — коштував проєкту 16 діб простою
// агента новин. Тому шаблон деплою перевіряється тут ТИМ САМИМ виразом.
import { chromium } from 'playwright';
import { launch, serve, reporter, projectFile } from './_lib.mjs';

const { ok, done } = reporter();
const { url, stop } = await serve();
const b = await launch(chromium);
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true,
                                 hasTouch: true, serviceWorkers: 'block' });
const p = await ctx.newPage();
await p.route('**://*.supabase.co/**', r => r.abort());
await p.route('**://api.open-meteo.com/**', r => r.abort());

await p.goto(url, { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(1500);
await p.evaluate(() => document.querySelector('.consent-accept')?.click());
await p.waitForTimeout(300);

// Чи видно вузол ОКОМ: він у документі, має розмір, не прозорий і його рамка
// перетинається з видимою частиною екрана.
const видимість = sel => p.evaluate(s => {
  const el = document.querySelector(s);
  if (!el) return { нема: true };
  const r = el.getBoundingClientRect();
  const cs = getComputedStyle(el);
  const уКадрі = r.width > 0 && r.height > 0 &&
                 r.bottom > 0 && r.right > 0 &&
                 r.top < innerHeight && r.left < innerWidth;
  return {
    нема: false,
    видно: уКадрі && cs.visibility !== 'hidden' && parseFloat(cs.opacity) > 0.01,
    рамка: `${Math.round(r.left)},${Math.round(r.top)} ${Math.round(r.width)}×${Math.round(r.height)}`,
    текст: el.textContent.trim(),
  };
// ⚠️ СЕЛЕКТОР ПЕРЕДАЄТЬСЯ ДРУГИМ АРГУМЕНТОМ, І ЦЕ НЕ ДРІБНИЦЯ.
// Перша редакція його забула: усередині `s` був `undefined`, `querySelector(undefined)`
// віддав `null`, і стенд заявив «вузла немає ЗОВСІМ» на ЦІЛКОМ СПРАВНОМУ коді.
// Правило проєкту № 1: червоне над правильним кодом — перша підозрювана завжди перевірка.
}, sel);

// ── КОНТРОЛЬ ПЕРШОГО ПОРЯДКУ: лічильник узагалі існує ──────────────────────
// Без цього рядка «його не видно» доводило б лише те, що його видалили зовсім —
// а це не те, що просив Вова, і зламало б перевірку деплою.
const спершу = await видимість('.deploy-stamp');
ok('контроль: лічильник версії є в застосунку', !спершу.нема,
   спершу.нема ? 'вузла .deploy-stamp немає ЗОВСІМ — деплой більше нічим перевірити' : спершу.текст);

if (!спершу.нема) {
  // ── ГОЛОВНЕ: на екрані застосунку його НЕ видно ──────────────────────────
  ok('🔴 при закритому меню лічильника НЕ видно — знімок екрана чистий',
     !спершу.видно, спершу.видно ? `він у кадрі: ${спершу.рамка}` : 'поза кадром');

  // ── ДРУГЕ: за один тап по бургеру він знаходиться ────────────────────────
  // Інакше «сховали» перетворилось би на «викинули»: перевірити деплой з
  // телефона стало б нічим.
  await p.evaluate(() => document.getElementById('sidebar-toggle')?.click());
  await p.waitForTimeout(700);
  const уМеню = await видимість('.deploy-stamp');
  ok('🔴 у відкритому бургер-меню лічильник видно', уМеню.видно,
     уМеню.видно ? уМеню.рамка : 'не потрапив у кадр навіть при відкритому меню');

  const уСайдбарі = await p.evaluate(() => !!document.querySelector('.sidebar .deploy-stamp'));
  ok('лічильник живе саме в меню, а не десь іще', уСайдбарі);
}

await b.close(); await stop();

// ── ШАБЛОН ДЕПЛОЮ: підміна мусить влучати ──────────────────────────────────
// Беремо ТОЙ САМИЙ вираз, що стоїть у воркфлові, і перевіряємо його по живому
// `index.html`. Розбіжність тут = мовчазно замерзлий лічильник на проді.
const html = projectFile('index.html');
const yml  = projectFile('.github/workflows/deploy.yml');

const шаблонДеплою = /v\[0-9\]\\\+ · \[0-9\]\[0-9\]\\?\.\[0-9\]\[0-9\] \[0-9\]\[0-9\]:\[0-9\]\[0-9\]/;
ok('контроль: воркфлов деплою досі підміняє лічильник по шаблону',
   шаблонДеплою.test(yml), 'sed-рядок у deploy.yml змінився — звір цей стенд із ним');

const збігів = (html.match(/v\d+ · \d\d\.\d\d \d\d:\d\d/g) || []);
ok('🔴 рядок лічильника відповідає шаблону, який шукає деплой',
   збігів.length === 1, `збігів: ${збігів.length}${збігів.length ? ' → ' + збігів.join(' · ') : ' — підміна не влучить, лічильник замерзне'}`);

// ── КОНТРОЛЬ: перевірка шаблону вміє падати ────────────────────────────────
ok('контроль: зіпсований рядок шаблону НЕ проходить',
   !/v\d+ · \d\d\.\d\d \d\d:\d\d/.test('<div class="deploy-stamp">версія 1 від 01.01</div>'));

done();
