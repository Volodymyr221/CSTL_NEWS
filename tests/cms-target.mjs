// Стенд: КУДИ ЙДЕ СТАТТЯ КАБІНЕТУ — ВИБІР ЛЮДИНИ, А НЕ ЛИШЕ КАТЕГОРІЯ.
//
// 🗣️ Замовлення Вови 03.09.2026, дослівно: «Треба зробити можливість таку, щоб
// якщо парсяться якісь статті, туди можна було б вирішувати, куди публікувати.
// Чи в новини… чи, наприклад, в стрічку під якимось логотипом, де власником чи
// адміністратором є я або певна людина, яка зараз знаходиться в адмінці. Та якщо
// там є фотографії, то фотографії в карусель пустити. Написати пост, але
// заголовку в постах, у стрічці, немає, тому потрібно писати його великими
// буквами, але як звичайний пост.»
//
// 🔑 Три його ж рішення, які цей стенд і стереже:
//   1. «Кожен свої, і адмінк застосунку всі» — список спільнот у селекті;
//   2. «перебивати» — ручний вибір сильніший за правило «істор/краєзнав»;
//   3. заголовок ВЕЛИКИМИ першим рядком, бо поля заголовка в дописі немає.
//
// 🛑 ЧОМУ ЦЕ ВЗАГАЛІ СТЕНД. Правило маршруту в цьому проєкті живе у ДВОХ місцях —
// `admin.html` (підпис на картці) і `scripts/sync_cms.py` (сам маршрут), — і воно
// вже одного разу розійшлось: 28.08 картка обіцяла «→ Історія Громади», а синк
// клав статтю в новини. Тому міряємо ПОВЕДІНКУ обох копій, а не наявність рядків.
//
// ⚠️ Python компілюється З ДЖЕРЕЛА (`compile()`), а не через `importlib`:
// 03.09 заміряно на `news-dedup`, що `__pycache__` віддавав старий байт-код і
// контрольний прогін світився зеленим на коді, якого вже не існувало.
import { execFileSync } from 'node:child_process';
import { chromium } from '@playwright/test';
import { ROOT, launch, reporter, serve } from './_lib.mjs';

const { ok, done } = reporter();

// ── 1. МАРШРУТ І ТЕКСТ ДОПИСУ (scripts/sync_cms.py) ────────────────────────
const py = `
import json, sys, types
sys.path.insert(0, 'scripts')
_src = open('scripts/sync_cms.py', encoding='utf-8').read()
m = types.ModuleType('sc'); m.__file__ = 'scripts/sync_cms.py'
exec(compile(_src, 'scripts/sync_cms.py', 'exec'), m.__dict__)

# Сцена: справжні тексти з кабінету (id 42 «Маршрут одного дня» і id 46 «Личани»).
ІСТОРІЯ  = {"id": 1, "category": "історія та культура", "title": "Личани",
            "content": "Личани — село Олицької міської громади.", "image": "https://s/a.jpg"}
ТУРИЗМ   = {"id": 2, "category": "туризм", "title": "Маршрут одного дня",
            "content": "<p>Олика — місто в Луцькому районі.</p><p>Замок Радзивілів.</p>",
            "image": "https://s/b.jpg"}
ВРУЧНУ_НОВИНИ  = dict(ІСТОРІЯ, target_locked=True, target_page_id=None)
ВРУЧНУ_СПІЛЬНО = dict(ТУРИЗМ,  target_locked=True, target_page_id=2)
ДУБЛЬ_ЗАГОЛОВКА = {"id": 3, "title": "Личани", "content": "Личани\\n\\nСело на Путилівці."}
З_ФОТО_В_ТІЛІ  = {"id": 4, "title": "Галерея", "image": "https://s/1.jpg",
                  "content": '<p>Текст</p><img src="https://s/2.jpg"><img src="https://s/1.jpg">'}

# Пости, що пішли б у базу — ловимо запит замість мережі.
відправлені = []
class _Відповідь:
    def __enter__(self): return self
    def __exit__(self, *a): return False
    def read(self): return b'[{"id": 99}]'
def _urlopen(req, timeout=None):
    відправлені.append(json.loads(req.data.decode('utf-8')))
    return _Відповідь()
m.urllib.request.urlopen = _urlopen
m.mark_published = lambda *a, **k: None
m.публікувати_в_спільноту(ВРУЧНУ_СПІЛЬНО, m.маршрут(ВРУЧНУ_СПІЛЬНО))
m.публікувати_в_спільноту(З_ФОТО_В_ТІЛІ, 3)

print('---РЕЗУЛЬТАТ---')
print(json.dumps({
  "авто_історія":    m.маршрут(ІСТОРІЯ),
  "авто_туризм":     m.маршрут(ТУРИЗМ),
  "вручну_новини":   m.маршрут(ВРУЧНУ_НОВИНИ),
  "вручну_спільнота": m.маршрут(ВРУЧНУ_СПІЛЬНО),
  "текст_туризм":    m.стаття_у_пост(ТУРИЗМ),
  "текст_історія":   m.стаття_у_пост(ІСТОРІЯ),
  "текст_дубль":     m.стаття_у_пост(ДУБЛЬ_ЗАГОЛОВКА),
  "фото":            m.фото_статті(З_ФОТО_В_ТІЛІ),
  "пости":           відправлені,
  "кроки":           [f.__name__ for f in (m.promote_scheduled, m.heal_phantom_drafts, m.publish_shotam, m.sync_pages)],
}, ensure_ascii=False))`;
const р = JSON.parse(execFileSync('python3', ['-c', py], { cwd: ROOT, encoding: 'utf-8' })
  .split('---РЕЗУЛЬТАТ---')[1].trim());

ok('автоправило живе: історична стаття без ручного вибору йде у спільноту «Історія Громади» (6)',
   р.авто_історія === 6, String(р.авто_історія));
ok('автоправило живе: звичайна стаття без ручного вибору йде у Новини',
   р.авто_туризм === null, String(р.авто_туризм));
ok('🔴 «ПЕРЕБИВАТИ»: ручні Новини сильніші за категорію «історія»',
   р.вручну_новини === null, String(р.вручну_новини));
ok('🔴 «ПЕРЕБИВАТИ»: ручна спільнота везе туди, куди обрала людина, а не за категорією',
   р.вручну_спільнота === 2, String(р.вручну_спільнота));

ok('🔑 заголовок у дописі — ВЕЛИКИМИ, першим рядком (поля заголовка в стрічці немає)',
   р.текст_туризм.startsWith('МАРШРУТ ОДНОГО ДНЯ\n\n'), р.текст_туризм.slice(0, 40));
ok('🛑 розмітка з джерела не доїжджає до людини: ні тегів, ні «<p>»',
   !/[<>]/.test(р.текст_туризм), р.текст_туризм.slice(0, 60));
ok('абзаци не починаються з пробілу (теги мінялись на пробіл — заміряно на id=44)',
   р.текст_туризм.split('\n').every(р2 => р2 === р2.trimStart()),
   JSON.stringify(р.текст_туризм));
ok('🛑 живий текст не обрізається, коли заголовок — перше СЛОВО тіла',
   р.текст_історія.includes('Личани — село Олицької міської громади'), р.текст_історія);
ok('а справжній повтор заголовка окремим рядком прибирається',
   р.текст_дубль === 'ЛИЧАНИ\n\nСело на Путилівці.', JSON.stringify(р.текст_дубль));

ok('карусель: обкладинка перша, фото з тіла далі, без повторів',
   JSON.stringify(р.фото) === JSON.stringify(['https://s/1.jpg', 'https://s/2.jpg']),
   JSON.stringify(р.фото));
ok('допис іде на ОБРАНУ сторінку, а не на константу «Історія Громади»',
   р.пости[0] && р.пости[0].page_id === 2, JSON.stringify(р.пости[0] || {}).slice(0, 80));
ok('фото їдуть масивом `image_urls` — саме з нього стрічка малює карусель',
   Array.isArray(р.пости[1]?.image_urls) && р.пости[1].image_urls.length === 2,
   JSON.stringify(р.пости[1]?.image_urls));
ok('синк справді викликає новий крок `sync_pages` у своєму ланцюжку',
   р.кроки.includes('sync_pages'), р.кроки.join(', '));

// ── 2. АДМІНКА КАЖЕ ТЕ САМЕ (admin.html) ───────────────────────────────────
const { url, stop } = await serve();
const b = await launch(chromium);
const p = await b.newPage();
await p.goto(url + '/admin.html', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(400);

const адмінка = await p.evaluate(() => {
  myPages = [{ id: 2, name: 'ТУРИСТИЧНА ОЛИКА' }, { id: 6, name: 'ІСТОРІЯ ГРОМАДИ' }];
  return {
    авто:      призначення({ category: 'історія та культура', type: 'news' }).текст,
    вручнуНов: призначення({ category: 'історія та культура', type: 'news', target_locked: true, target_page_id: null }).текст,
    вручнуСпіл: призначення({ category: 'туризм', type: 'news', target_locked: true, target_page_id: 2 }).текст,
    варіанти:  варіантиПризначення({ target_locked: true, target_page_id: 2 }),
    чуже:      варіантиПризначення({ target_locked: true, target_page_id: 99 }),
    читання: {
      auto: читатиПризначення('auto'),
      news: читатиПризначення('news'),
      page: читатиПризначення('page:6'),
    },
  };
});

ok('картка теж каже «→ Історія Громади», коли вибору не робили',
   /Історія Громади/.test(адмінка.авто), адмінка.авто);
ok('🔴 картка показує РУЧНИЙ вибір «Новини» на історичній статті — а не правило',
   /Новини/.test(адмінка.вручнуНов), адмінка.вручнуНов);
ok('картка називає обрану спільноту імʼям, а не номером',
   адмінка.вручнуСпіл.includes('ТУРИСТИЧНА ОЛИКА'), адмінка.вручнуСпіл);
ok('у селекті є «Автоматично», «Новини» і кожна доступна спільнота',
   /value="auto"/.test(адмінка.варіанти) && /value="news"/.test(адмінка.варіанти)
   && /value="page:2"/.test(адмінка.варіанти) && /value="page:6"/.test(адмінка.варіанти));
ok('обране значення справді позначене `selected`, а не губиться',
   /value="page:2" selected/.test(адмінка.варіанти), адмінка.варіанти.slice(0, 120));
ok('🛑 чужий вибір (спільнота не з мого списку) не підміняється мовчки на «Автоматично»',
   /value="page:99" selected/.test(адмінка.чуже), адмінка.чуже.slice(0, 160));
ok('читання селекта: auto → правило, news → замок без сторінки, page:6 → замок і сторінка',
   адмінка.читання.auto.target_locked === false
   && адмінка.читання.news.target_locked === true && адмінка.читання.news.target_page_id === null
   && адмінка.читання.page.target_locked === true && адмінка.читання.page.target_page_id === 6,
   JSON.stringify(адмінка.читання));

await b.close(); await stop();
done();
