// tests/sdk-local.mjs — SDK SUPABASE ЖИВЕ НА НАШОМУ ДОМЕНІ, А НЕ НА ЧУЖОМУ CDN.
//
// 🔴 ЗАРАДИ ЧОГО. 26.08, 22:42, Вова зі скріна в Safari: «Немає звʼязку з сервером» при
// спробі входу — при живому інтернеті (новини на тому ж екрані завантажились).
// 🛑 Той тост показується рівно в одному місці: коли клієнт Supabase дорівнює `null`.
// А клієнт створювався ОДИН РАЗ, у мить завантаження `bundle.js`. Не доїхав сторонній
// скрипт із `cdn.jsdelivr.net` — і застосунок лишався без бази НАЗАВЖДИ, до
// перезавантаження сторінки. Ні входу, ні Дошки, ні Стрічки, ні збереження.
// 📐 Заміряно в `sw.js`: сторонні запити йшли «тільки мережа», і на збої Service Worker
// сам віддавав порожнє 503.
// ⚠️ І найгірше: діагностика (`js_error`, `db_refusal`) шле через ТОЙ САМИЙ клієнт —
// тобто про цей збій ми б не дізнались узагалі, журнал збоїв мовчав би.
//
// 🔑 Стенд стереже три різні речі, і кожна закриває свою половину вади:
//   1. файл лежить у нас і підключається з нашого домену;
//   2. він не качається заново на кожен деплой (окремий вічний кеш);
//   3. якщо його однаково немає — застосунок каже ПРАВДУ, а не «немає звʼязку».

import { projectFile, reporter } from './_lib.mjs';
import { existsSync, statSync } from 'fs';
import { join } from 'path';
import { ROOT } from './_lib.mjs';

const { ok, done } = reporter();
const REV = process.env.BUNDLE_REV || '';
const читати = (шлях) => { try { return projectFile(шлях, REV); } catch { return ''; } };

const INDEX = читати('index.html');
const SW    = читати('sw.js');
const CORE  = читати('src/core/supabase.js');
const AUTH  = читати('src/core/auth.js');
const DEPLOY = читати('.github/workflows/deploy.yml');

// ── 1. ФАЙЛ У НАС, А НЕ В ЧУЖИХ ───────────────────────────────────────────
const шлях = (INDEX.match(/src="(vendor\/supabase-js[^"]+)"/) || [])[1];
ok('🔴 SDK підключається з нашого домену', !!шлях, шлях || 'не знайдено');
ok('🔴 чужого CDN у розмітці більше немає',
   !/cdn\.jsdelivr\.net[^"]*supabase/.test(INDEX));
// 🛑 Адмінка мала ТУ САМУ ваду, і там вона гірша: саме сюди дивляться, коли щось
// зламалось. Не доїхав чужий CDN — і екран, який мав пояснити поломку, не працює сам.
const ADMIN = читати('admin.html');
ok('🔴 адмінка бере SDK звідти ж, а не з чужого CDN',
   /vendor\/supabase-js/.test(ADMIN) && !/cdn\.jsdelivr\.net[^"]*supabase/.test(ADMIN));
// 🔑 Заглушки стендів мусять ловити SDK за НОВОЮ адресою — інакше на сцену приїде
// справжній клієнт, підробленої бази не буде, і півсотні перевірок почервоніють разом.
// 📐 Саме це й сталося 26.08: десять стендів упали одночасно на першому ж прогоні.
const FIX = читати('tests/_board-fixture.mjs');
ok('🔴 заглушка стендів ловить SDK і за новою адресою',
   /vendor\/supabase-js/.test(FIX));
ok('стара адреса в заглушці лишилась — для контрольних прогонів',
   /cdn\.jsdelivr\.net/.test(FIX));
if (шлях && !REV) {
  const повний = join(ROOT, шлях);
  ok('файл справді лежить у репозиторії', existsSync(повний), шлях);
  // 🛑 Порожній або обрізаний файл пройшов би перевірку «існує» і зламав би все.
  const байт = existsSync(повний) ? statSync(повний).size : 0;
  ok('файл не порожній і схожий на повний SDK', байт > 150000, `${байт} байт`);
}
// 🔑 Версія в імені навмисно: `@2` на CDN означав «будь-яка мінорна», тобто чужий реліз
// міг мовчки приїхати в бойовий застосунок. Тепер оновлення — наше рішення.
ok('🔴 у назві файлу є версія — оновлення стає нашим рішенням',
   /supabase-js-\d+\.\d+\.\d+\.min\.js/.test(шлях || ''));

// ── 2. НЕ КАЧАЄТЬСЯ ЗАНОВО НА КОЖЕН ДЕПЛОЙ ────────────────────────────────
// 🛑 `CACHE_NAME` міняється при КОЖНОМУ деплої, і передкеш качається заново. Покласти
// туди 212 КБ означало б два мегабайти трафіку за вечір на кожному телефоні — за файл,
// який не змінився жодного разу.
ok('🔴 SDK має власний кеш, а не передкеш', /VENDOR_CACHE/.test(SW));
ok('🔴 цей кеш переживає активацію нового Service Worker',
   /k !== CACHE_NAME && k !== VENDOR_CACHE/.test(SW));
// ⚠️ Міряємо САМ СПИСОК, а не текст навколо нього. Перша редакція цієї перевірки шукала
// «vendor/» у двох тисячах символів після слова `STATIC_ASSETS` — і почервоніла на
// власному КОМЕНТАРІ, який пояснює, чому SDK туди не кладуть. Третій випадок за вечір,
// коли перевірка міряє форму запису замість наслідку.
const СПИСОК = (SW.match(/const STATIC_ASSETS = \[([\s\S]*?)\];/) || [, ''])[1];
ok('SDK не в списку передкешу', !!СПИСОК && !/vendor\//.test(СПИСОК));
ok('запит до vendor обслуговується з кешу першим', /vendor\/[\s\S]{0,400}caches\.open\(VENDOR_CACHE\)/.test(SW));
// 🛑 Якби теку викинули з артефакту деплою, застосунок лишився б без бази й без входу.
ok('🔴 тека vendor захищена від прибирання при деплої', /vendor\//.test(DEPLOY));

// ── 3. ЯКЩО SDK ОДНАКОВО НЕМАЄ — КАЖЕМО ПРАВДУ ────────────────────────────
// 🛑 Перший рубіж може впасти. Тоді має спрацювати другий: клієнт створюється ліниво,
// а не «один раз і назавжди».
ok('🔴 клієнт створюється ліниво, а не один раз назавжди',
   /return supa \|\| створити\(\)/.test(CORE));
// 🔑 «Немає звʼязку» і «немає файлу бібліотеки» — різні причини. Раніше екран на обидві
// казав одне й те саме, і людина шукала проблему в мережі, якої там немає.
ok('🔴 застосунок відрізняє «немає звʼязку» від «не завантажилась бібліотека»',
   /export function sdkLoaded/.test(CORE) && /sdkLoaded\(\)/.test(AUTH));
ok('текст про бібліотеку каже, що робити', /Онови сторінку/.test(AUTH));
ok('старого однакового тосту на обидві причини більше немає',
   !/showToast\('Немає звʼязку з сервером', 3000, 'error'\)/.test(AUTH));

done();
