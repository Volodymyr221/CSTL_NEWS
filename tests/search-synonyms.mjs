// Стенд: СЛОВНИК ПОШУКУ РОЗШИРЮЄ ЗАПИТ РІВНО ТАМ, ДЕ ТРЕБА.
//
// 🗣️ Замовлення Вови (30.08): «проведи максимально детальний аудит щодо цих слів».
//
// 🔴 ГОЛОВНЕ, ЩО ТУТ СТЕРЕЖЕТЬСЯ — НЕ «ЧИ ЗНАЙДЕ», А «ЧИ НЕ ЗНАЙДЕ ЗАЙВОГО».
// Словник — єдина частина пошуку, яка не виводиться алгоритмом, тобто єдина, куди
// можна тихо дописати сміття. Кожен зайвий синонім розширює запит і тягне чуже.
// Тому блоків контролю тут більше, ніж блоків користі.
//
// 📐 Вада, заради якої заведено ієрархію, була ВИМІРЯНА, а не уявлена: у чорновому
// словнику всі слова техніки лежали пласкою групою, і запит «холодильник» знаходив
// «Ремонт пральних машин».
//
// Запуск: node tests/search-synonyms.mjs

import { search, detectIntent } from '../src/core/search.js';
import { EQUIVALENT, HIERARCHY, ONE_WAY } from '../src/core/search-vocab.js';
import { stem } from '../src/core/search.js';
import { BOARD_CATEGORIES } from '../src/core/board-categories.js';

let ok = 0, fail = 0; const bad = [];
const check = (cond, name, detail = '') => {
  if (cond) { ok++; console.log(`✅ ${name}${detail ? '  — ' + detail : ''}`); }
  else { fail++; bad.push(name); console.log(`❌ ${name}${detail ? '  — ' + detail : ''}`); }
};

const IT = [
  { id: 'пралка', title: 'Ремонт пральних машин', text: '', location: 'Олика', tags: [] },
  { id: 'холод',  title: 'Продам холодильник',    text: '', location: 'Олика', tags: [] },
  { id: 'авто',   title: 'Продам автомобіль',     text: '', location: 'Олика', tags: [] },
  { id: 'дрова',  title: 'Продам дрова',          text: '', location: 'Олика', tags: [] },
  { id: 'вугіл',  title: 'Продам вугілля',        text: '', location: 'Олика', tags: [] },
  { id: 'хата',   title: 'Продам будинок',        text: '', location: 'Жорнище', tags: [] },
  { id: 'город',  title: 'Продам город під картоплю', text: '', location: 'Олика', tags: [] },
];
const q = s => search(IT, s).map(r => r.item.id).sort().join(',');

// ── А. ВИД З ВИДОМ НЕ ЗВʼЯЗУЄТЬСЯ (та сама вада, що була виміряна) ───────────
console.log('\n── А. Вид з видом — НІКОЛИ ──');
check(q('холодильник') === 'холод',     'холодильник → лише холодильник', q('холодильник'));
check(q('пральна машина') === 'пралка', 'пральна машина → лише ремонт пралок', q('пральна машина'));
check(q('дрова') === 'дрова',           'дрова → лише дрова, не вугілля', q('дрова'));

// ── Б. ВИД ↔ РІД МУСИТЬ ПРАЦЮВАТИ В ОБИДВА БОКИ ──────────────────────────────
console.log('\n── Б. Вид ↔ рід ──');
check(q('побутова техніка') === 'пралка,холод', 'рід знаходить усі свої види', q('побутова техніка'));
check(q('паливо') === 'вугіл,дрова',            'паливо → дрова і вугілля', q('паливо'));
check(q('транспорт') === 'авто',                'транспорт → автомобіль', q('транспорт'));

// ── В. ОМОНІМ — ЛИШЕ В ОДИН БІК ──────────────────────────────────────────────
// 🔑 `stem('машину')` і `stem('пральних машин')` дають те саме «машин». Якби звʼязок
// був двобічним, запит «автомобіль» витягував би ремонт пральних машин.
console.log('\n── В. Омонім «машина» ──');
// ⚠️ ОЧІКУВАННЯ ВИПРАВЛЕНО ПІСЛЯ ПАДІННЯ — і виправлено САМЕ ТУТ, а не в коді.
// Спершу тут стояло `=== 'авто'`, і стенд червонів. Розбір показав, що правий код:
// «Ремонт пральних машин» містить слово «машин» БУКВАЛЬНО, тобто знаходиться прямим
// збігом, а не через словник. Ховати його було б брехнею — слово справді означає
// дві речі, і людині чесніше показати обидві.
// 🔑 Захист лежить у СУСІДНІЙ перевірці: «автомобіль» пральні НЕ тягне. Саме вона
// доводить однобічність ONE_WAY, а ця лише описує чесну неоднозначність.
check(q('машина') === 'авто,пралка', '«машина» → авто + пральні (слово двозначне, обидва чесні)', q('машина'));
check(q('автомобіль') === 'авто',  '🛑 «автомобіль» НЕ тягне пральні машини', q('автомобіль'));

// ── Г. РІВНІ СИНОНІМИ ────────────────────────────────────────────────────────
console.log('\n── Г. Рівні синоніми ──');
check(q('хата') === 'хата',  '«хата» знаходить «будинок»', q('хата'));
check(q('дім') === 'хата',   '«дім» знаходить «будинок»', q('дім'));

// ── Д. СВІДОМІ НЕ-ЗВʼЯЗКИ (записані в шапці словника) ────────────────────────
// 🛑 Без цього блоку наступна сесія «дописала» б їх як недогляд.
console.log('\n── Д. Те, що НЕ синоніми — і це рішення, не недогляд ──');
check(!q('ділянка').includes('город'), '«ділянка» ≠ «город» (грядки vs земля під забудову)', q('ділянка') || '—');
check(q('морозильник') === '',          '«морозильник» ≠ «холодильник»', q('морозильник') || '—');

// ── Е. ЦІЛІСНІСТЬ СЛОВНИКА (структурні перевірки) ────────────────────────────
console.log('\n── Е. Цілісність словника ──');

// 🔴 Намір мусить говорити мовою Дошки: ключі INTENT_FORMS = id категорій.
// Без цієї перевірки два списки тихо розійшлися б — рівно як два списки антиспаму.
const catIds = new Set(BOARD_CATEGORIES.map(c => c.id));
const наміри = ['продам', 'куплю', 'шукаю', 'віддам', 'послуга'];
check(наміри.every(n => catIds.has(n)),
      'усі наміри є категоріями Дошки', наміри.filter(n => !catIds.has(n)).join(',') || 'усі збігаються');
check(detectIntent('продам хату') === 'продам', 'намір читається', detectIntent('продам хату'));

// Жодне слово не сміє стояти у двох різних групах EQUIVALENT — це зробило б
// транзитивний міст між незвʼязаними поняттями.
const де = new Map();
let колізій = 0;
EQUIVALENT.forEach((g, i) => g.forEach(w => {
  const s = stem(w);
  if (де.has(s) && де.get(s) !== i) colision(s, i);
  де.set(s, i);
}));
function colision(s, i) { колізій++; console.log(`   ↳ «${s}» у групах ${де.get(s)} і ${i}`); }
check(колізій === 0, 'жодне слово не стоїть у двох групах рівних синонімів', `колізій ${колізій}`);

// Вид не сміє належати двом родам — інакше через нього роди зливаються.
const види = new Map(); let дубльВидів = 0;
for (const [head, kinds] of Object.entries(HIERARCHY)) {
  for (const k of kinds) {
    const s = stem(k);
    if (види.has(s)) { дубльВидів++; console.log(`   ↳ «${k}» і в «${види.get(s)}», і в «${head}»`); }
    види.set(s, head);
  }
}
check(дубльВидів === 0, 'жоден вид не належить двом родам', `дублів ${дубльВидів}`);

// Омонім не сміє водночас лежати в рівних синонімах: там звʼязок двобічний,
// і однобічність, заради якої ONE_WAY існує, зникла б.
const рівні = new Set(EQUIVALENT.flat().map(stem));
const конфлікт = Object.keys(ONE_WAY).filter(w => рівні.has(stem(w)));
check(конфлікт.length === 0, 'омоніми не дублюються в рівних синонімах', конфлікт.join(',') || 'чисто');

console.log(`\n${fail ? '❌' : '✅'} ${ok}/${ok + fail} перевірок пройдено`);
if (fail) { console.log('   провалено:', bad.join(' · ')); process.exit(1); }
