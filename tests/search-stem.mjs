// Стенд: УКРАЇНСЬКА МОРФОЛОГІЯ ПОШУКУ — основи слів зводяться, РІЗНІ слова НІ.
//
// 🗣️ Замовлення Вови (30.08): «автор написав одне, а користувач формулює по-іншому».
//
// 🔴 ЧОМУ В ЦЬОМУ СТЕНДІ ДВІ ПОЛОВИНИ, І ДРУГА ВАЖЛИВІША.
// Половина А доводить, що пошук ЗНАЙДЕ («будинки» = «будинок»).
// Половина Б доводить, що він не знайде ЗАЙВОГО («мило» ≠ «милий»).
// Без Б стенд світився б зеленим над зіпсованим пошуком: найпростіший спосіб
// пройти А — рубати слова до двох літер, і тоді збігається ВСЕ з УСІМ.
// ⚠️ Саме на це заперечував ChatGPT, коли радив не писати свій стемер. Заперечення
// правильне — тому воно закрите ВИМІРОМ, а не обіцянкою.
//
// 📐 Ціна помилки асиметрична (той самий принцип, що в B-14):
//     не дообрізали → слово не знайшлось = як було, не гірше
//     склеїли       → знайшлось ЧУЖЕ     = гірше, ніж було
//
// Запуск: node tests/search-stem.mjs

import { stem } from '../src/core/search.js';

let ok = 0, fail = 0;
const bad = [];

function check(cond, name, detail = '') {
  if (cond) { ok++; console.log(`✅ ${name}${detail ? '  — ' + detail : ''}`); }
  else { fail++; bad.push(name); console.log(`❌ ${name}${detail ? '  — ' + detail : ''}`); }
}

// ── ПОЛОВИНА А: ці форми МУСЯТЬ зійтись ──────────────────────────────────────
// Кожна група — слова, які людина вважає одним і тим самим. Перші три групи
// взяті НЕ з голови: це реальні слова з живих оголошень бази (30.08),
// «будинок» ×9 · «будинку» ×6 · «будинки» ×3.
const MUST_MATCH = [
  ['будинок', 'будинку', 'будинки', 'будинком', 'будинка'],
  ['варіант', 'варіанти', 'варіантів', 'варіантом'],
  ['готовий', 'готових', 'готові', 'готова'],
  ['жорнище', 'жорнищах', 'жорнищі', 'жорнища'],
  ['квартира', 'квартиру', 'квартири', 'квартирою'],
  ['ділянка', 'ділянки', 'ділянок'],
  ['нерухомість', 'нерухомості', 'нерухомістю'],
  ['земельна', 'земельної', 'земельних', 'земельним'],
  ['машина', 'машину', 'машини', 'машиною'],
  ['послуга', 'послуги', 'послугу', 'послугами'],
];

console.log('\n── А. Форми одного слова мусять зійтись ──');
for (const group of MUST_MATCH) {
  const stems = group.map(stem);
  const uniq = [...new Set(stems)];
  check(uniq.length === 1, `«${group[0]}» — ${group.length} форм`,
        uniq.length === 1 ? `основа «${uniq[0]}»` : `розійшлись: ${stems.join(' / ')}`);
}

// ── ПОЛОВИНА Б: ці слова НЕ СМІЮТЬ склеїтись ─────────────────────────────────
// 🛑 Контроль на переобрізання. Пари підібрані так, що наївний стемер
// («ріж усі закінчення до кореня») склеїв би їх — і пошук «мило» видавав би
// «милий будинок».
const MUST_DIFFER = [
  ['мило', 'милий'],
  ['рама', 'Рим'],
  ['коса', 'косий'],
  ['вода', 'водій'],
  ['сіль', 'сільський'],
  ['кран', 'країна'],
  ['дім', 'діма'],
  ['піч', 'пічка'],
];

console.log('\n── Б. Різні слова НЕ сміють склеїтись (контроль) ──');
for (const [a, b] of MUST_DIFFER) {
  const sa = stem(a), sb = stem(b);
  check(sa !== sb, `«${a}» ≠ «${b}»`, `${sa} / ${sb}`);
}

// ── В. ПРИКЛАД ВОВИ ЦІЛКОМ ───────────────────────────────────────────────────
// Той самий, з якого почалася задача. Міряємо не слова, а НАСЛІДОК:
// чи перетинаються основи запиту й оголошення.
console.log('\n── В. Приклад Вови: «будинок жорнище» → «Продам будинок в Жорнищах» ──');
const оголошення = 'Продам будинок в Жорнищах'.toLowerCase().split(/[^а-яіїєґʼ']+/i).filter(Boolean).map(stem);
for (const запит of ['будинок жорнище', 'жорнищах будинок', 'будинки жорнищі']) {
  const слова = запит.split(/\s+/).map(stem);
  const усі = слова.every(s => оголошення.includes(s));
  check(усі, `запит «${запит}» знаходить оголошення`,
        усі ? `основи ${слова.join(' + ')}` : `не збіглось: ${слова.join(' + ')} проти ${оголошення.join(' ')}`);
}

// 🛑 І зворотна перевірка: чужий запит НЕ мусить знаходити це оголошення.
// Без неї попередні три могли б проходити на стемері, що зводить усе в порожній рядок.
const чужі = ['квартира київ', 'велосипед'];
for (const запит of чужі) {
  const слова = запит.split(/\s+/).map(stem);
  const усі = слова.every(s => оголошення.includes(s));
  check(!усі, `чужий запит «${запит}» НЕ знаходить оголошення`);
}

// ── Г. ОСНОВА МУСИТЬ БУТИ ОСМИСЛЕНОЮ, А НЕ ПРОСТО ОДНАКОВОЮ ──────────────────
// 🔴 ЦЕЙ БЛОК ЗАВЕДЕНО ПІСЛЯ СПРАВЖНЬОЇ ВАДИ, ЯКУ ПОПЕРЕДНІ БЛОКИ ПРОПУСТИЛИ.
// Перша редакція стемера зводила «готовий/готових/готові/готова» в «готв» —
// правило біглого голосного зʼїдало голосну з КОРЕНЯ. Блок А був ЗЕЛЕНИЙ, бо всі
// чотири форми зіпсувались однаково і чесно збіглись між собою.
// ➡️ Збіг форм між собою НЕ доводить, що основа осмислена. Тому очікувані основи
// виписані явно: наступна зміна правил не зможе тихо спотворити корінь.
console.log('\n── Г. Очікувана основа (ловить спотворення кореня) ──');
const EXPECT = {
  'будинок': 'будинк', 'будинки': 'будинк',
  'готовий': 'готов',  'готові':  'готов',
  'жорнищах': 'жорнищ',
  'нерухомість': 'нерухомост', 'нерухомості': 'нерухомост',
  'земельним': 'земельн',
  'машину': 'машин',
  'турист': 'турист', // контроль вузькості правила «-іст → -ост»: тут «ист», не чіпаємо
};
for (const [word, want] of Object.entries(EXPECT)) {
  const got = stem(word);
  check(got === want, `«${word}» → «${want}»`, got === want ? '' : `отримано «${got}»`);
}

// ── НАЗВАНІ МЕЖІ (свідомо не підтримуємо) ────────────────────────────────────
// 🛑 Це не недогляд, а вибір на користь безпеки. Правило, що звело б ці пари,
// склеювало б і сторонні слова («місяці» → «місяк», «палаці» → «палак»).
// Ціна помилки асиметрична: недозведення = як зараз; склеювання = гірше за зараз.
console.log('\n── Межі, названі чесно (чергування приголосних не робимо) ──');
for (const [a, b] of [['ділянка', 'ділянці'], ['рука', 'руці']]) {
  const різні = stem(a) !== stem(b);
  check(різні, `⚠️ ВІДОМА МЕЖА: «${a}» / «${b}» не зводяться`, `${stem(a)} / ${stem(b)}`);
}

console.log(`\n${fail ? '❌' : '✅'} ${ok}/${ok + fail} перевірок пройдено`);
if (fail) { console.log('   провалено:', bad.join(' · ')); process.exit(1); }
