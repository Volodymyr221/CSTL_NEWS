// ── СМУГА МУСИТЬ ЗЛИВАТИСЬ ІЗ БЛОКОМ (замовлення Вови 10.08) ────────────────
// «Він просто бордовий. Можеш зробити з лівого краю по праву градієнтом і
// переливом, як і сам блок… щоб воно зливалося просто. І так само в дошці».
//
// 🔬 МІРЯЄМО ПІКСЕЛІ, А НЕ ПРАВИЛА. «Зливається» — властивість картинки; правило
// можна написати правильно і все одно дістати шов, бо в `--brand-grad` ДВА шари
// і геометрія рахується від розміру екрана. Саме так і сталось у роботі: перша
// редакція смуги повторила лише радіальну підсвітку, читалась як «готово», а
// замір показав на правому краю стик у 19 пунктів каналу.
//
// 🔑 ОДНА ФУНКЦІЯ НА ОБИДВІ ЗОНИ — НАВМИСНО. Числа для смуги виводяться з
// геометрії блока, і в Громади з Дошкою вони РІЗНІ (`#4C131D` проти `#47111B`,
// бо блоки різної висоти). Спільна перевірка не дає перенести підібране число з
// однієї зони в іншу «бо там же так само»: вона щоразу міряє, що дає ця зона.
async function перевіритиСмугу(sel, зона) {
  const геом = await cloneForShot(p, sel);
  if (!ok(`${зона}: блок для заміру знайдено`, !!геом, sel)) return;
  const { w: шир, px, ярк } = await pixelsOf(p, '#seam-probe');
  const R = геом.рамка;
  const наX = f => Math.round(f * (шир - 1));

  // 🔴 БЕЗ СМУГИ МІРЯТИ НЕМА ЧОГО — і саме тут стенд мало не збрехав.
  // Перша редакція просто читала ряд `y = 4`. На коді ДО зміни рамки немає (R=0),
  // тож `y = 4` потрапляв уже В САМ БЛОК, у якого градієнт, звісно, є — і
  // контроль показав ЗЕЛЕНЕ «перелив угорі смуги живий» там, де смуги не існує.
  // Класика брехливої перевірки: критерій міряв не те, про що звітував.
  // ⚠️ Кількість перевірок навмисно не змінюється, коли смуги немає: інакше
  // контроль і робочий прогін давали б різні підсумки й не порівнювались.
  const єСмуга = R >= 200;

  // 1. ШОВ: останній ряд смуги проти першого ряду блока, по всій ширині.
  let шов = Infinity;
  if (єСмуга) {
    шов = 0;
    for (let x = 2; x < шир - 2; x++) {
      const a = px(x, R - 2), c = px(x, R + 1);
      шов = Math.max(шов, Math.abs(a[0] - c[0]), Math.abs(a[1] - c[1]), Math.abs(a[2] - c[2]));
    }
  }
  // Поріг 8 лежить у РОЗРИВІ між заміряними станами: пласка смуга дає 17-19,
  // смуга з обома шарами — 2-3. Це не «з запасом на око», це середина прірви.
  // Заразом він терпить дрібну зміну висоти шапки (та зсуває стик на 2-3).
  ok(`🔴 ${зона}: смуга ЗЛИВАЄТЬСЯ з блоком, стику не видно (різниця каналу ≤ 8)`,
     шов <= 8, єСмуга ? `максимальна різниця каналу на стику = ${шов}`
                      : `смуги немає (рамка ${R}px) — стик відкритий`);

  // 2. ПЕРЕЛИВ: смуга не пласка — ліворуч світліше, праворуч сходить у бордо.
  // Без цієї перевірки шов можна було б «полагодити», зробивши смугу рівномірно
  // темною, — і вона знову стала б пласкою, тобто рівно тим, на що скаржився Вова.
  const розмахРяду = y => {
    const v = [0.06, 0.26, 0.5, 0.8, 0.97].map(f => ярк(px(наX(f), y)));
    return { v, d: +(Math.max(...v) - Math.min(...v)).toFixed(1) };
  };
  const низ = єСмуга ? розмахРяду(R - 2) : { v: [], d: 0 };
  ok(`🔴 ${зона}: смуга має ПЕРЕЛИВ зліва направо, а не рівне бордо (розмах ≥ 4)`,
     низ.d >= 4, єСмуга ? `ліво ${низ.v[0]} · пік ${низ.v[1]} · право ${низ.v[4]} → розмах ${низ.d}`
                        : `смуги немає (рамка ${R}px)`);
  const верх = єСмуга ? розмахРяду(4) : { v: [], d: 0 };
  ok(`${зона}: перелив живий і у ВЕРХНІЙ частині смуги (її видно при сильному відтягуванні)`,
     верх.d >= 3, єСмуга ? `розмах ${верх.d}` : `смуги немає (рамка ${R}px)`);

  await p.evaluate(() => document.getElementById('seam-probe')?.remove());
}

// ── ГРОМАДА: рідна гумка + бордовий запас угору ─────────────────────────────
// 🔴 ТРЕТІЙ ЗАХІД, і два попередні тут варто памʼятати:
//   1. просто `contain` → над бордовим блоком сірий провал (фото-тло прибите,
//      а блок їде) — відкат;
//   2. свій відскок на JS → числа правильні, але Вова: «дьоргається, зроби як
//      у стрічці». Кадри малював головний потік, рідну гумку веде композитор.
// ✅ Тепер: рідний відскок, а діра закрита ГЕОМЕТРІЄЮ — бордова рамка 260px
// угору на самій шапці. У спокої вона вище нуля прокрутки, тобто невидима.
//
// 🔬 Стенд міряє ТРИ речі, і третя найважливіша.
const гром = await наВкладці('community');
ok('🔴 Громада: рідний відскок увімкнено (кадри малює композитор, не скрипт)',
   гром.overscroll === 'contain', `overscroll-behavior-y: ${гром.overscroll}`);

const шапка = await p.evaluate(() => {
  const el = document.querySelector('.hm-top');
  if (!el) return null;
  const s = getComputedStyle(el);
  const r = el.getBoundingClientRect();
  const привіт = document.querySelector('.hm-hi');
  return {
    рамка: parseFloat(s.borderTopWidth),
    колірРамки: s.borderTopColor,
    clip: s.backgroundClip || s.webkitBackgroundClip,
    верхБлока: Math.round(r.top),
    верхПривітання: привіт ? Math.round(привіт.getBoundingClientRect().top) : null,
  };
});

ok('🔴 бордовий запас угору є (рамка 260px кольору верхнього стопу градієнта)',
   !!шапка && шапка.рамка >= 200 && /94,\s*23,\s*35/.test(шапка.колірРамки),
   шапка ? `${шапка.рамка}px ${шапка.колірРамки}` : 'нема');

// 🔴 ГОЛОВНА ПЕРЕВІРКА: рамка не сміє зсунути ЖОДНОГО пікселя вмісту.
// `margin-top` мусить компенсувати її РІВНО. Розійдеться компенсація — поїде
// вся сторінка, і це буде набагато гірше за проблему, яку лікуємо.
//
// ⚠️ ТУТ СТОЯЛА ВИГАДАНА КОНСТАНТА, і це варто памʼятати. Перша редакція
// перевіряла «привітання на 96px» — число я не зміряв, а припустив, і стенд
// одразу «знайшов» зсув на неіснуючі 4px. Живий замір origin/main проти
// поточного коду показав: привітання 100 → 100, капсули 213 → 213, контакти
// без змін, зсунулась лише рамка блока (−260, як і задумано).
// ➡️ Тому тут НЕМАЄ магічних чисел. Перевіряється структурний інваріант:
// внутрішній край бордової шапки (тобто там, де починається градієнт і текст)
// збігається з нижнім краєм шапки застосунку. Він істинний і до зміни, і після,
// і не залежить від висоти екрана, safe-area чи шрифту.
const стик = await p.evaluate(() => {
  const top = document.querySelector('.hm-top');
  const hdr = document.querySelector('.app-header');
  if (!top || !hdr) return null;
  const s = getComputedStyle(top);
  return {
    внутрішнійКрай: +(top.getBoundingClientRect().top + parseFloat(s.borderTopWidth)).toFixed(1),
    низШапкиЗастосунку: +hdr.getBoundingClientRect().bottom.toFixed(1),
  };
});
ok('🔴 вміст НЕ зʼїхав: бордова шапка починається рівно під шапкою застосунку',
   !!стик && Math.abs(стик.внутрішнійКрай - стик.низШапкиЗастосунку) <= 1,
   стик ? `край блока ${стик.внутрішнійКрай} · низ шапки ${стик.низШапкиЗастосунку}` : 'нема');

// Градієнт мусить малюватись у СТАРІЙ області — інакше видима частина бордо
// змінила б відтінок, а Вова цю різницю ловить (історія кольору шапки).
ok('градієнт обмежено padding-box, тож його геометрія не змінилась',
   !!шапка && /padding-box/.test(шапка.clip || ''), шапка ? шапка.clip : '—');

await перевіритиСмугу('.hm-top', 'Громада');

ok('відскок не «протікає» на сторінку (не auto — таб-бар не обріжеться)',
   гром.overscroll !== 'auto', гром.overscroll);

// ── ДОШКА: гумка теж увімкнена (10.08, «і так само в дошці») ────────────────
// 🔴 ТУТ БУЛО РІВНО ПРОТИЛЕЖНЕ, і це варто памʼятати. До 10.08 стенд стеріг, що
// на Дошці відскоку НЕМА, і мав на це живу підставу: її фон світло-сірий
// (`#E6E6E3`) під БОРДОВОЮ шапкою, тож гумка відкрила б сіру смугу над бордовим.
// Дві спроби закрити ту зону малюванням провалились (тінь зі зсувом · псевдо
// за межами елемента — його обрізає скролер).
// ➡️ Змінилось не бажання, а ЗНАННЯ: прийом із Громади закриває зону не
// малюванням, а геометрією — рамкою всередині самого блока. Підстава для «стіни»
// зникла, тому стенд перевернуто свідомо, а не «щоб зеленів».
const дошка = await наВкладці('board');
ok('🔴 Дошка: рідний відскок увімкнено',
   дошка.overscroll === 'contain', `overscroll-behavior-y: ${дошка.overscroll}`);
ok('відскок Дошки не «протікає» на сторінку (не auto — таб-бар не обріжеться)',
   дошка.overscroll !== 'auto', дошка.overscroll);

// 🔴 ГОЛОВНЕ ЗАСТЕРЕЖЕННЯ ВОВИ: «не поламати логіку ховання та логіку, коли
// вилазить оцей блок пошуку разом з фільтрами».
// І ховання, і поріг показу тримаються на ОДНОМУ числі — `offsetHeight`
// контейнера `.bd-controls` (з нього `--bd-h` для точки прилипання `sticky` і
// `headerH()` у `board.js`). Рамка +260 і поле −260 мусять гаситись РІВНО;
// розійдуться — шапка почне прилипати не там, і зламається саме те, що просили
// не ламати. Тому міряємо не «чи є смуга», а чи висота лишилась колишньою.
const шапкаДошки = await p.evaluate(() => {
  const c = document.querySelector('#board-content .bd-controls');
  const t = document.querySelector('#board-content .bd-titlebar');
  const hdr = document.querySelector('.app-header');
  if (!c || !t || !hdr) return null;
  const s = getComputedStyle(t);
  return {
    висотаШапки: c.offsetHeight,
    змінна: parseFloat(getComputedStyle(document.getElementById('board-content')).getPropertyValue('--bd-h')),
    рамка: parseFloat(s.borderTopWidth),
    поле: parseFloat(s.marginTop),
    clip: s.backgroundClip || s.webkitBackgroundClip,
    внутрішнійКрай: +(t.getBoundingClientRect().top + parseFloat(s.borderTopWidth)).toFixed(1),
    низШапкиЗастосунку: +hdr.getBoundingClientRect().bottom.toFixed(1),
    пошукВсередині: !!t.querySelector('.bd-search-row'),
  };
});
ok('🔴 бордовий запас угору є і на Дошці (рамка 260px)',
   !!шапкаДошки && шапкаДошки.рамка >= 200,
   шапкаДошки ? `${шапкаДошки.рамка}px` : 'нема');
ok('🔴 рамка скомпенсована РІВНО: висота шапки не змінилась (на ній ховання і поріг показу)',
   !!шапкаДошки && Math.abs(шапкаДошки.рамка + шапкаДошки.поле) < 1 &&
     шапкаДошки.висотаШапки > 0 && шапкаДошки.висотаШапки < 260,
   шапкаДошки ? `рамка ${шапкаДошки.рамка} + поле ${шапкаДошки.поле} · .bd-controls ${шапкаДошки.висотаШапки}px` : 'нема');
ok('🔴 `--bd-h` (точка прилипання sticky) дорівнює живій висоті шапки',
   !!шапкаДошки && Math.abs(шапкаДошки.змінна - шапкаДошки.висотаШапки) <= 1,
   шапкаДошки ? `--bd-h ${шапкаДошки.змінна} · offsetHeight ${шапкаДошки.висотаШапки}` : 'нема');
ok('🔴 вміст НЕ зʼїхав: бордова шапка Дошки починається рівно під шапкою застосунку',
   !!шапкаДошки && Math.abs(шапкаДошки.внутрішнійКрай - шапкаДошки.низШапкиЗастосунку) <= 1,
   шапкаДошки ? `край ${шапкаДошки.внутрішнійКрай} · низ шапки ${шапкаДошки.низШапкиЗастосунку}` : 'нема');
ok('градієнт Дошки обмежено padding-box — видима частина бордо не змінила відтінку',
   !!шапкаДошки && /padding-box/.test(шапкаДошки.clip || ''), шапкаДошки ? шапкаДошки.clip : '—');
// Блок пошуку з фільтрами лежить УСЕРЕДИНІ бордової шапки — саме тому рамка
// його не зачіпає. Якщо колись його винесуть назовні, відʼємне поле налізе на
// нього зверху, і ця перевірка почервоніє раніше за скаргу Вови.
ok('🔴 блок пошуку з фільтрами лишається ВСЕРЕДИНІ бордової шапки',
   !!шапкаДошки && шапкаДошки.пошукВсередині);

await перевіритиСмугу('#board-content .bd-titlebar', 'Дошка');

await ctx.close(); await b.close(); await stop();
