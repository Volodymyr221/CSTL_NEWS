// Стенд: ГУМОВІ МЕЖІ — Є ТАМ, ДЕ БЕЗПЕЧНО, І НЕМАЄ ТАМ, ДЕ НІ (§9 `apple-design`).
//
// Скіл: «At an edge, resist progressively instead of stopping hard. A hard stop
// reads as frozen». Замовлення Вови 10.08 — «давай спробуємо».
//
// 🔴 ОБИДВІ «СТІНИ» СТАВИЛИ НЕ ВІД НЕЗНАННЯ — це були ФІКСИ двох дефектів,
// які знайшов сам Вова:
//   • Громада (17.07) — «беж заповнює весь низ, а bounce показує порожнечу»;
//   • Дошка (06.08) — гумка відтягує вміст, і над бордовою шапкою відкривається
//     світло-сіра смуга (`#E6E6E3`). Там ДВА обхідні шляхи пробували із заміром
//     (тінь зі зсувом · псевдоелемент за межами елемента), обидва провалились —
//     усе, що виходить за межі скролера, він просто не малює.
//
// 📐 10.08 ОБИДВІ ПІДСТАВИ ЗНЯТО, і кожну — своєю причиною:
//   • Громада після перебудови в Home Dashboard має ТЕМНИЙ власний фон
//     (`rgb(26,10,14)`) — стара підстава зникла разом із бежем;
//   • Дошка дістала прийом, якого 06.08 ще не знали: зона закривається не
//     малюванням, а ГЕОМЕТРІЄЮ — рамка 260px УСЕРЕДИНІ самого бордового блока,
//     скомпенсована відʼємним полем. Це вміст на відʼємному зсуві, а не виліт
//     назовні, тож обрізати нема чого.
//     🔑 Висновок 06.08 «зсередини цю зону закрити неможливо» був не хибний, а
//     ЗАВУЗЬКИЙ: правильне слово не «зсередини», а «псевдоелементом ЗА МЕЖАМИ».
//
// 🔬 ЩО САМЕ СТЕРЕЖЕ ЦЕЙ СТЕНД — не «гумка увімкнена», а ЗВʼЯЗКУ.
// Сам по собі відскок нічого не гарантує: він безпечний ЛИШЕ доки відтягнута
// зона показує той самий колір, що вже на екрані. Тому на кожній вкладці
// перевіряється трійка: відскок є · смуга запасу є · смуга ЗЛИВАЄТЬСЯ з блоком
// (заміряно пікселями). Прибере хтось смугу — стенд почервоніє, і це правильно:
// разом із нею повернеться стара проблема.
//
// 🔴 ОКРЕМО ПРО ДОШКУ — застереження Вови дослівно: «не поламати логіку ховання
// та логіку, коли вилазить оцей блок пошуку разом з фільтрами». Обидві тримаються
// на висоті `.bd-controls`, тож стенд міряє саме її, а не наявність смуги.
//
// ⚠️ `serviceWorkers: 'block'` — восьмий випадок брехливої перевірки в проєкті.
//
// 🔴 КОНТРОЛЬ (обовʼязковий):
//     CSS_REV=origin/main node tests/rubber-band.mjs
// на коді ДО зміни мусять упасти перевірки смуги обох вкладок і відскоку Дошки,
// а структурні (висота шапки, `--bd-h`, стик під шапкою застосунку) — лишитись
// зеленими: разом це доводить, що змінено вигляд, а не каркас.
