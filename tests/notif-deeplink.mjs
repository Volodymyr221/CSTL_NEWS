// Заведено 15.08.2026 на замовлення Вови.
//
// 🔴 ЩО ОХОРОНЯЄМО. Слова Вови: «коли я тапаю на це сповіщення, воно повинно
// відкривати не тільки цю вкладку в стрічку, а наводитись саме на цей допис і
// відкривати модалку коментарів… якщо прийшло приватне повідомлення і я натискаю
// на сповіщення — мене має перекидати прямо в той чат».
//
// 🔑 Ланцюг має ТРИ ланки, і рвався він у двох із них:
//   сервер (Edge Function) кладе `url` → `sw.js` віддає його застосунку →
//   `app.js` розбирає і відкриває.
// Тому перевіряємо ВСІ три, а не лише клієнт: саме розсинхрон сервера з клієнтом
// уже коштував проєкту бага B-24 (фікс лежав у репозиторії 15 днів незадеплоєним,
// і фото в чаті не давали сповіщень узагалі).
//
// ⚠️ Edge Functions живуть НЕ в збірці — вони деплояться в Supabase окремо. Тут
// перевіряється лише те, що в репозиторії вони правильні; факт накату на сервер
// стенд довести не може, і це названо прямо.
import { readFileSync } from 'fs';
import { reporter, projectFile } from './_lib.mjs';

const { ok, done } = reporter();

// Контроль (доведення падінням) — стан ДО фікса:
//   BUNDLE_REV=origin/main node tests/notif-deeplink.mjs
// ⚠️ Ревізію треба ПЕРЕДАВАТИ в кожен `projectFile`. Перша редакція оголосила
// змінну й забула її вжити — контрольний прогін показав ті самі 12/12, тобто
// «довів» фікс, не подивившись на старий код.
const REV  = process.env.BUNDLE_REV || '';
const APP  = projectFile('src/app.js', REV);
const FEED = projectFile('src/tabs/feed.js', REV);
const SW   = projectFile('sw.js', REV);
const COM  = projectFile('supabase/functions/send-comment-push/index.ts', REV);
const CHAT = projectFile('supabase/functions/send-chat-push/index.ts', REV);
const PAGE = projectFile('supabase/functions/send-page-push/index.ts', REV);

// ── 1. СЕРВЕР: посилання ведуть до дії, а не «просто в застосунок» ────────────
ok('1а. сповіщення про ВІДПОВІДЬ на коментар несе номер коментаря',
   /\?c=\$\{c\.id\}/.test(COM), 'url із ?c=<id>');
// 🔴 Саме це й було зламано: зведене вело до поста, і коментарі не відкривались.
ok('1б. 🔴 ЗВЕДЕНЕ «Ще N коментарів» теж веде В КОМЕНТАРІ',
   /\?c=all/.test(COM), /\?c=all/.test(COM) ? 'url із ?c=all' : 'веде лише до поста');
ok('1в. 🔴 приватне повідомлення веде В РОЗМОВУ, а не «просто відкрий»',
   /#\/thread\/\$\{thread\.id\}/.test(CHAT) && !/url:\s*'\.\/'/.test(CHAT),
   /url:\s*'\.\/'/.test(CHAT) ? "лишилось url: './'" : 'url із #/thread/<id>');
ok('1г. сповіщення про новий пост веде на пост', /#\/post\/feed\/\$\{post\.id\}/.test(PAGE));

// ── 2. SERVICE WORKER: передає і url, і номер розмови ─────────────────────────
ok('2а. при відкритому застосунку SW форвардить дані всередину',
   /postMessage\(\{\s*__cstl:\s*'notif-click'/.test(SW));
ok('2б. серед них є threadId (інакше чат не відкрити)', /threadId,\s*groupId,\s*url/.test(SW));
ok('2в. на холодному старті SW відкриває саме розмову',
   /#\/thread\/\$\{threadId\}/.test(SW));

// ── 3. КЛІЄНТ: розбирає обидва види посилань ─────────────────────────────────
// 🔴 Головна поломка гарячого старту: обробник виходив, якщо не було `url`, —
// а для чату сервер шле саме `threadId`. Тобто при ВІДКРИТОМУ застосунку тап
// не робив нічого; на холодному старті працювало, тому вада виглядала як
// «іноді спрацьовує».
ok('3а. 🔴 чат відкривається при ВІДКРИТОМУ застосунку (threadId без url)',
   /if \(d\.threadId != null\) \{ openThreadById/.test(APP),
   /if \(!d \|\| d\.__cstl !== 'notif-click' \|\| !d\.url\) return;/.test(APP)
     ? 'обробник досі відсіює все без url' : 'threadId обробляється першим');
ok('3б. маршрут приймає і номер коментаря, і «all»',
   /\?c=\(\\d\+\|all\)/.test(APP), 'регулярка ?c=(\\d+|all)');
ok('3в. «all» відкриває лист коментарів без підсвітки',
   /commentId === 'all'/.test(APP) && /commentId === 'all'\) openComments\(id\)/.test(FEED));
ok('3г. номер коментаря підсвічує саме той рядок',
   /else if \(commentId\) openComments\(id, commentId\)/.test(FEED));

// ── 4. 🛑 ЧЕСНА МЕЖА ЦЬОГО СТЕНДА ────────────────────────────────────────────
// Edge Functions не потрапляють у `bundle.js` і не деплояться разом із сайтом.
// Стенд бачить лише репозиторій. Якщо функцію не накатити на Supabase, сервер
// і далі слатиме старі посилання — а всі перевірки вище лишаться зеленими.
ok('4. 🛑 позначено, що Edge Functions потребують ОКРЕМОГО накату',
   /деплояться в Supabase окремо/.test(readFileSync(new URL(import.meta.url), 'utf8')),
   'нагадування в шапці стенда на місці');

done();
