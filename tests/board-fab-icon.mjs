// Стенд №26: НИЖНЯ КНОПКА ДОШКИ ЗАЛЕЖИТЬ ВІД СТАНУ.
//
// 🔄 ПЕРЕПИСАНО ДВІЧІ ЗА ДОБУ, історія важлива щоб не ходити по колу:
//   30.07 — кнопка внизу стоїть завжди, іконка морфиться (олівець ↔ конверт);
//   01.08 — дії переїхали під «+» у шапці, внизу лишився конверт;
//   02.08 — ПОМІНЯЛИСЬ МІСЦЯМИ: дії внизу (FAB), конверт у шапці.
// Причина останнього: подати оголошення — найчастіша дія, а верхній правий кут —
// найважча зона для великого пальця; тримати там головну дію означало ставити
// найпотрібніше найдалі.
//
// Задум тепер: немає ні оголошень, ні розмов → кнопки немає; зʼявилось перше з двох →
// кнопка зʼявляється. ⚠️ Умова саме «АБО», і це не дрібниця: заміряно по базі —
// людей з оголошеннями 1, з розмовами 8, і 7 із них не мають жодного оголошення.
// Правило «лише автори» відрізало б цих сімох від їхніх же 218 повідомлень.
//
// ⚠️ ЧЕСНО ПРО МЕЖІ — читай перш ніж довіряти зеленому світлу.
// Це СТОРОЖ ПРИСУТНОСТІ, не поведінковий тест. Живу поведінку тут відтворити не можна:
// вона залежить від `allPosts` (приходять із Supabase) і від `currentUserId()` (потрібен
// вхід), а пісочниця не має ні першого, ні другого. Стенд стежить за тим, що ламається
// МОВЧКИ, і не вдає, що покриває більше. Чи «відчувається» морфінг іконки добре —
// питання до Вови на iPhone, не до стенда.
// (Я був проти самої ідеї; заперечення лишене в `board.js` над `myActiveAdsCount`.)
//
// 🔴 КОНТРОЛЬ ОБОВʼЯЗКОВИЙ і тут: ті самі перевірки проганяються по СИНТЕЗОВАНОМУ
// стані «до фічі» (див. блок 2 — прибираємо з чинного джерела рівно те, що фіча
// додала). Якщо вони і там «зелені» — значить регулярки збігаються з чимось не тим,
// і стенд не вартий нічого. Саме так у цьому проєкті вже брехала перевірка, що
// чіплялась за форму запису.
import { projectFile, reporter } from './_lib.mjs';

const { ok, done } = reporter();

// Набір перевірок як ДАНІ — щоб прогнати той самий список двома ревізіями.
const CHECKS = [
  ['умова показу — оголошення АБО розмови', 'feature',
   s => {
     const c = /function canSeeMessages\(\)\s*\{[\s\S]*?\n\}/.exec(s);
     return !!c && /myActiveAdsCount\(\)\s*>\s*0\s*\|\|\s*hasThreadsCached\(\)/.test(c[0]);
   }],

  // 🔄 04.08 — КНОПКИ ПОМІНЯЛИСЬ МІСЦЯМИ (замовлення Вови): «+» переїхав у шапку
  // і рендериться ЗАВЖДИ (це головна дія екрана), конверт — на нижній круг і
  // показується за тією самою умовою, що раніше керувала верхньою кнопкою.
  // Перевірка міряє те саме правило, лише за новою адресою.
  ['конверт показується лише за умовою (тепер унизу)', 'feature',
   s => /id="bd-msgs-fab"/.test(s)
     && /btn\.hidden\s*=\s*!canSeeMessages\(\)/.test(s)],

  ['«+» у шапці рендериться ЗАВЖДИ, без умови', 'feature',
   s => {
     // Вимагаємо саме PLUS_ICON_SVG усередині шапки: цієї константи у старій
     // ревізії не існує взагалі, тож перевірка не може «вижити» на синтезованому
     // «до» — а контроль стенда стежить рівно за цим.
     const box = /<div class="bd-hero-actions">[\s\S]*?<\/div>/.exec(s);
     return !!box && /id="board-trigger"/.test(box[0])
       && /PLUS_ICON_SVG/.test(box[0]) && !/canSeeMessages/.test(box[0]);
   }],

  ['наявність розмов береться з КЕШУ, без нового запиту', 'feature',
   s => /import\s*\{[^}]*hasThreadsCached[^}]*\}\s*from\s*'\.\/board-chat\.js'/.test(s)],

  ['дії живуть у НИЖНЬОМУ FAB (зона великого пальця)', 'feature',
   s => {
     const m = /id="board-fab-menu"[\s\S]*?<\/div>/.exec(s.slice(s.indexOf('02.08 — ДІЇ ВНИЗУ')));
     return !!m && ['post', 'mine', 'saved'].every(a => m[0].includes(`data-fab="${a}"`));
   }],

  ['конверт веде ПРЯМО в розмови, без меню', 'feature',
   s => /getElementById\('bd-hero-msgs'\)\s*\n?\s*\?\.addEventListener\('click',\s*\(\)\s*=>\s*requireAuth\([^)]*openThreadsList\)\)/.test(s)],

  // 🔴 Найтонше з усього: наявність розмов приходить АСИНХРОННО, вже після першого
  // рендера. Без цієї події конверт не зʼявився б до наступного повного рендеру —
  // тобто покупець із розмовами, але без своїх оголошень, не побачив би входу в
  // листування взагалі. Цей баг реально був і його зловили перечитуванням коду.
  ['асинхронний приїзд розмов домальовує конверт', 'feature',
   s => /addEventListener\('cstl-threads-changed'/.test(s)],

  // ⚠️ ІНВАРІАНТ, не фіча: існував і до 01.08. Якщо тут колись зʼявиться запит,
  // КОЖЕН рендер FAB стане зверненням до бази — рівно та хвороба, яку прибрали
  // з бейджа непрочитаних (аудит Д-Б1 від 30.07).
  ['myActiveAdsCount рахує локально, без мережі', 'invariant',
   s => {
     const c = /function myActiveAdsCount\(\)\s*\{[\s\S]*?\n\}/.exec(s);
     return !!c && !/fetch|await|supa|\.rpc\(/.test(c[0]) && /owner_uid\s*===\s*me/.test(c[0]);
   }],

  // Найтонше місце: після публікації список освіжається `refreshBoardKeepingPlace()`,
  // який СВІДОМО перемальовує лише картки. Без синхронізації людина подала б перше
  // оголошення — і не побачила б кнопку листування саме тоді, коли їй можуть написати.
  ['мʼяке освіження списку синхронізує кнопку', 'feature',
   s => {
     const f = /async function refreshBoardKeepingPlace\(\)\s*\{[\s\S]*?\n\}/.exec(s);
     return !!f && /syncMsgFab\(\)/.test(f[0]);
   }],

  // В Обговорень свій FAB зі своїм меню — ця логіка їх чіпати не має
  // (пряме рішення Вови 01.08: «Ні, обговорення не чіпаємо»).
  ['syncMsgFab має гард discOpen', 'feature',
   s => /function syncMsgFab\(\)\s*\{\s*\n\s*if\s*\(discOpen\)\s*return;/.test(s)],
];

// ── 1) ЧИННИЙ КОД: усе на місці ──────────────────────────────────────────────
const now = projectFile('src/tabs/board.js');
for (const [name, kind, fn] of CHECKS) {
  const pass = fn(now);
  ok(name, pass, pass ? (kind === 'invariant' ? 'на місці (інваріант)' : 'на місці') : '🔴 ВІДСУТНЄ');
}

// ── 2) КОНТРОЛЬ: синтезуємо стан ДО фічі й перевіряємо, що перевірки падають ──
// 🔴 Спершу я брав «до» з git (`HEAD~1..3`) — і це була БОМБА З ТАЙМЕРОМ: за кілька
// комітів усі три ревізії вже містили б фічу, і стенд почав би падати сам, без жодної
// поломки в коді. Тому «до» тепер СИНТЕЗУЄМО з чинного джерела: прибираємо рівно те,
// що фіча додала. Такий контроль не залежить від історії й не старіє.
// (Той самий прийом, що `REVERT_CSS` у `tests/board-cream.mjs`.)
const before = now
  // умова показу → як було: кнопка стояла завжди
  .replace(/function canSeeMessages\(\)\s*\{[\s\S]*?\n\}/, '')
  .replace(/\$\{canSeeMessages\(\) \? `/, '${false ? `')
  // 🔄 04.08: у стані «до» в шапці стояв КОНВЕРТ, а не «+» — тож синтезатор
  // повертає туди стару іконку. Без цього рядка перевірка «+ у шапці завжди»
  // проходила б і на «до», тобто не ловила б нічого.
  .replace(/PLUS_ICON_SVG/g, 'MSG_ICON_SVG')
  .replace(/id="bd-msgs-fab"/g, 'id="board-trigger"')
  // кеш розмов не імпортувався
  .replace(/,\s*hasThreadsCached\s*\}/, ' }')
  // дії жили в меню під «+» у шапці, а не в нижньому FAB
  .replace(/02\.08 — ДІЇ ВНИЗУ/, 'старий заголовок')
  // конверт не вів у розмови
  // ⚠️ /g обовʼязково: обробник конверта стоїть у ДВОХ місцях (перший рендер і
  // `syncMsgFab`, який домальовує конверт на льоту). Без прапорця заміна знімала
  // лише перше, друге виживало — і контроль це чесно спіймав.
  .replace(/getElementById\('bd-hero-msgs'\)\s*\n?\s*\?\.addEventListener\('click',[^;]*;/g, '')
  // події про асинхронний приїзд розмов не було
  .replace(/addEventListener\('cstl-threads-changed'/, "addEventListener('nope'")
  // синхронізація видимості → стара синхронізація іконки
  .replace(/function syncMsgFab\(\)\s*\{[\s\S]*?\n\}/, '')
  .replace(/\n\s*syncMsgFab\(\);[^\n]*/, '');

const feature = CHECKS.filter(([, kind]) => kind === 'feature');
const survived = feature.filter(([, , fn]) => fn(before)).map(([n]) => n);
ok('контроль: на синтезованому «до» фічеві перевірки падають',
   survived.length === 0,
   survived.length === 0
     ? `усі ${feature.length} фічевих упали — регулярки чіпляються саме за фічу`
     : `🔴 вижили: ${survived.join(' · ')} — вони збігаються з чимось не тим`);

// І зворотне: інваріантна перевірка на «до» мусить ВИЖИТИ (вона не про фічу).
const inv = CHECKS.filter(([, kind]) => kind === 'invariant');
ok('контроль: інваріантна перевірка на «до» лишається зеленою',
   inv.every(([, , fn]) => fn(before)),
   'інакше вона теж фічева, і мітка поставлена неправильно');

done();
