// Стенд №26: ІКОНКА FAB ЗАЛЕЖИТЬ ВІД СТАНУ (рішення Вови 30.07).
//
// Задум: нема своїх оголошень → іконка «подати» (олівець); є 1+ активне → «повідомлення».
//
// ⚠️ ЧЕСНО ПРО МЕЖІ — читай перш ніж довіряти зеленому світлу.
// Це СТОРОЖ ПРИСУТНОСТІ, не поведінковий тест. Живу поведінку тут відтворити не можна:
// вона залежить від `allPosts` (приходять із Supabase) і від `currentUserId()` (потрібен
// вхід), а пісочниця не має ні першого, ні другого. Стенд стежить за тим, що ламається
// МОВЧКИ, і не вдає, що покриває більше. Чи «відчувається» морфінг іконки добре —
// питання до Вови на iPhone, не до стенда.
// (Я був проти самої ідеї; заперечення лишене в `board.js` над `myActiveAdsCount`.)
//
// 🔴 КОНТРОЛЬ ОБОВʼЯЗКОВИЙ і тут: ті самі перевірки проганяються по СИНТЕЗОВАНОМУ
// стані «до фічі» (див. блок 2 — прибираємо з чинного джерела рівно те, що фіча
// додала). Якщо вони і там «зелені» — значить регулярки збігаються з чимось не тим,
// і стенд не вартий нічого. Саме так у цьому проєкті вже брехала перевірка, що
// чіплялась за форму запису.
import { projectFile, reporter } from './_lib.mjs';

const { ok, done } = reporter();

// Набір перевірок як ДАНІ — щоб прогнати той самий список двома ревізіями.
const CHECKS = [
  ['рендер обирає іконку за myActiveAdsCount()', 'feature',
   s => /id="board-trigger-icon"[^>]*>\$\{\s*myActiveAdsCount\(\)\s*>\s*0\s*\?\s*MSG_ICON_SVG\s*:\s*EDIT_ICON_SVG\s*\}/.test(s)],

  // ⚠️ ІНВАРІАНТ, не фіча: обидві константи існували й до 30.07 і вже були різні.
  // Тому в контролі нижче ця перевірка ЗАКОНННО проходить на старій ревізії — і саме
  // на цьому мій перший критерій контролю («мусять упасти всі пʼять») зламався.
  // Тримаю її окремо: вона стежить, щоб рефактор не звів дві гілки до однієї картинки.
  ['MSG_ICON_SVG і EDIT_ICON_SVG — РІЗНІ картинки', 'invariant',
   s => {
     const m = /const MSG_ICON_SVG\s*=\s*'([^']+)'/.exec(s);
     const e = /const EDIT_ICON_SVG\s*=\s*(.+);/.exec(s);
     return !!m && !!e && m[1].includes('<svg') && !e[1].includes(m[1]);
   }],

  // Якщо тут колись з'явиться запит, КОЖЕН рендер FAB стане зверненням до бази — рівно
  // та хвороба, яку цією ж сесією прибрали з бейджа непрочитаних (аудит Д-Б1).
  ['myActiveAdsCount рахує локально, без мережі', 'feature',
   s => {
     const c = /function myActiveAdsCount\(\)\s*\{[\s\S]*?\n\}/.exec(s);
     return !!c && !/fetch|await|supa|\.rpc\(/.test(c[0]) && /owner_uid\s*===\s*me/.test(c[0]);
   }],

  // Найтонше місце: після публікації список освіжається `refreshBoardKeepingPlace()`,
  // який СВІДОМО перемальовує лише картки (щоб не смикнути прокрутку). Без виклику
  // синхронізації кнопка лишилась би зі старою іконкою до наступного повного рендеру.
  ['мʼяке освіження списку синхронізує іконку', 'feature',
   s => {
     const f = /async function refreshBoardKeepingPlace\(\)\s*\{[\s\S]*?\n\}/.exec(s);
     return !!f && /syncFabIcon\(\)/.test(f[0]);
   }],

  // В Обговорень своя кнопка («+») і жодних «повідомлень» — морфінг їх чіпати не має.
  ['syncFabIcon має гард discOpen', 'feature',
   s => /function syncFabIcon\(\)\s*\{[\s\S]*?discOpen[\s\S]*?\n\}/.test(s)],
];

// ── 1) ЧИННИЙ КОД: усе на місці ──────────────────────────────────────────────
const now = projectFile('src/tabs/board.js');
for (const [name, kind, fn] of CHECKS) {
  const pass = fn(now);
  ok(name, pass, pass ? (kind === 'invariant' ? 'на місці (інваріант)' : 'на місці') : '🔴 ВІДСУТНЄ');
}

// ── 2) КОНТРОЛЬ: синтезуємо стан ДО фічі й перевіряємо, що перевірки падають ──
// 🔴 Спершу я брав «до» з git (`HEAD~1..3`) — і це була БОМБА З ТАЙМЕРОМ: за кілька
// комітів усі три ревізії вже містили б фічу, і стенд почав би падати сам, без жодної
// поломки в коді. Тому «до» тепер СИНТЕЗУЄМО з чинного джерела: прибираємо рівно те,
// що фіча додала. Такий контроль не залежить від історії й не старіє.
// (Той самий прийом, що `REVERT_CSS` у `tests/board-cream.mjs`.)
const before = now
  // тернарник у розмітці → як було, прибита іконка повідомлень
  .replace(/\$\{\s*myActiveAdsCount\(\)\s*>\s*0\s*\?\s*MSG_ICON_SVG\s*:\s*EDIT_ICON_SVG\s*\}/, '${MSG_ICON_SVG}')
  // обидві нові функції — геть
  .replace(/function myActiveAdsCount\(\)\s*\{[\s\S]*?\n\}/, '')
  .replace(/function syncFabIcon\(\)\s*\{[\s\S]*?\n\}/, '')
  // і виклик синхронізації з мʼякого освіження
  .replace(/\n\s*syncFabIcon\(\);[^\n]*/, '');

const feature = CHECKS.filter(([, kind]) => kind === 'feature');
const survived = feature.filter(([, , fn]) => fn(before)).map(([n]) => n);
ok('контроль: на синтезованому «до» фічеві перевірки падають',
   survived.length === 0,
   survived.length === 0
     ? `усі ${feature.length} фічевих упали — регулярки чіпляються саме за фічу`
     : `🔴 вижили: ${survived.join(' · ')} — вони збігаються з чимось не тим`);

// І зворотне: інваріантна перевірка на «до» мусить ВИЖИТИ (вона не про фічу).
const inv = CHECKS.filter(([, kind]) => kind === 'invariant');
ok('контроль: інваріантна перевірка на «до» лишається зеленою',
   inv.every(([, , fn]) => fn(before)),
   'інакше вона теж фічева, і мітка поставлена неправильно');

done();
