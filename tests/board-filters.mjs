// Стенд №49: ПОШУК І ФІЛЬТРИ ДОШКИ — ПОВЕДІНКА, А НЕ ВИГЛЯД.
//
// 🔴 ЗНАХІДКА A-1 АУДИТУ ДОШКИ (07.08), дослівно: «з 13 предметних стендів 11 міряють
// геометрію, кольори й анімацію. Поведінкових — два». Без нагляду лишились саме ті
// функції, якими людина користується щодня: пошук, фільтри, порожні стани.
//
// 🔑 ЧОМУ ЦЕ НЕБЕЗПЕЧНІШЕ ЗА ЗЛАМАНИЙ ВИГЛЯД. Вигляд ламається ПОМІТНО — його видно
// на першому знімку. Пошук, що перестав шукати, виглядає **точно як «нема оголошень»**:
// ні помилки, ні порожнього екрана, ні падіння. Тобто сторожі стояли там, де дефект
// і так було б видно, і не стояли там, де його не побачити.
// B-30 щойно довів, що це не теорія: пункт FAB мовчки не відкривався, і всі 46
// стендів були зелені.
//
// ЩО МІРЯЄ: скільки карток лишилось на екрані після кожної дії. Не «клас застосовано»,
// не «меню відкрилось» — саме НАСЛІДОК, який бачить людина.
//
// ⚠️ Сцена працює НЕЗАЛОГІНЕНИМ: пошук і фільтри Дошки — публічні, і саме так їх
// уперше зустрічає нова людина.
//
// ⚠️ `serviceWorkers: 'block'` — інакше запити йдуть через `sw.js` повз `page.route`.
import { chromium } from 'playwright';
import { launch, serve, reporter, projectFile } from './_lib.mjs';
import { mockSupabase } from './_board-fixture.mjs';

const { ok, done } = reporter();
const REV = process.env.BUNDLE_REV || '';

// ── Сцена, зібрана під конкретні відтворення з аудиту ───────────────────────
// 🔑 «Куплю» існує ЛИШЕ в Котові — це і є відтворення B-1: категорія «Куплю» разом
// із локацією «Олика» дає порожньо, хоча в самій категорії оголошення Є.
const NOW = new Date().toISOString();
const P = (id, category, location, title, text = 'опис') => ({
  id, type: 'board', category, location, title, text,
  price: '100', author: 'Сусід', owner_uid: 'u-other', contact: '', photos: [],
  status: 'published', published_at: NOW, created_at: NOW,
});

const POSTS = [
  P('p1', 'продам', 'Олика', 'ВЕЛОСИПЕД ДОРОСЛИЙ', 'майже новий'),
  P('p2', 'продам', 'Олика', 'ДРОВА КОЛОТІ', 'дуб і граб'),
  P('p3', 'продам', 'Котів', 'ПРИЧІП ДО АВТО', 'на ходу'),
  P('p4', 'куплю',  'Котів', 'КУПЛЮ КАРТОПЛЮ', 'самовивіз'),
  P('p5', 'послуга', 'Олика', 'РЕМОНТ ВЗУТТЯ', 'швидко'),
];

const { url, stop } = await serve();
const b = await launch(chromium);
const ctx = await b.newContext({
  viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true,
  serviceWorkers: 'block',
});
const p = await ctx.newPage();

await mockSupabase(p, { posts: POSTS, threads: [], messages: [], thread_user_state: [], announcements: [] });
await p.route('**://api.open-meteo.com/**', r => r.abort());
if (REV) {
  const body = projectFile('bundle.js', REV);
  await p.route('**/bundle.js', r => r.fulfill({ contentType: 'text/javascript; charset=utf-8', body }));
}

await p.goto(url, { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(1500);
await p.evaluate(() => document.querySelector('.consent-accept')?.click());
await p.waitForTimeout(200);
await p.evaluate(() => window.switchTab && window.switchTab('board'));
await p.waitForTimeout(1200);
await p.evaluate(() => document.querySelector('.brules-ok')?.click());
await p.waitForTimeout(1200);

// ── Інструменти сцени ───────────────────────────────────────────────────────
const карток = () => p.evaluate(() =>
  document.querySelectorAll('#board-content .bd-ads .cm-board-note').length);

const порожній = () => p.evaluate(() => {
  const el = document.querySelector('#board-content .bd-empty');
  return { є: !!el, текст: el ? el.textContent.trim() : '' };
});

const шукати = async (q) => {
  await p.evaluate((v) => {
    const i = document.getElementById('bd-search-input');
    if (!i) return;
    i.value = v;
    i.dispatchEvent(new Event('input', { bubbles: true }));
  }, q);
  await p.waitForTimeout(450);   // у поля пошуку є debounce 180мс
};

const обратиКатегорію = async (id) => {
  await p.evaluate(() => document.getElementById('bd-cat-btn')?.click());
  await p.waitForTimeout(250);
  await p.evaluate((c) => document.querySelector(`[data-bd-cat="${c}"]`)?.click(), id);
  await p.waitForTimeout(500);
};

const обратиЛокацію = async (loc) => {
  await p.evaluate(() => document.getElementById('bd-loc-btn')?.click());
  await p.waitForTimeout(250);
  await p.evaluate((l) => document.querySelector(`[data-bd-loc="${l}"]`)?.click(), loc);
  await p.waitForTimeout(500);
};

// ── 1. БАЗА: усі оголошення видно ───────────────────────────────────────────
const усього = await карток();
ok('стартово видно всі оголошення', усього === POSTS.length, `${усього} з ${POSTS.length}`);

// ── 2. ПОШУК справді звужує і справді знаходить ─────────────────────────────
await шукати('велосипед');
const поПошуку = await карток();
ok('🔴 пошук знаходить за словом із заголовка', поПошуку === 1, `${поПошуку} картк(и)`);

await шукати('граб');           // слово лише в ОПИСІ, не в заголовку
const поОпису = await карток();
ok('🔴 пошук шукає і в описі, не лише в заголовку', поОпису === 1, `${поОпису} картк(и)`);

await шукати('щосьчогонемає');
const нічого = await карток();
const порожнійПошук = await порожній();
ok('пошук без збігів дає нуль карток', нічого === 0, `${нічого}`);
ok('порожній результат пошуку називає ЗАПИТ', /щосьчогонемає/.test(порожнійПошук.текст),
   порожнійПошук.текст || '(порожньо)');

await шукати('');
const післяОчистки = await карток();
ok('очистка пошуку повертає повний список', післяОчистки === POSTS.length, `${післяОчистки}`);

// ── 3. ФІЛЬТР КАТЕГОРІЇ ─────────────────────────────────────────────────────
await обратиКатегорію('продам');
const продам = await карток();
ok('🔴 фільтр категорії лишає лише свою категорію', продам === 3, `${продам} з 3`);

// ── 4. ФІЛЬТР ЛОКАЦІЇ поверх категорії (комбінування) ───────────────────────
await обратиЛокацію('Олика');
const продамОлика = await карток();
ok('🔴 локація звужує поверх категорії', продамОлика === 2, `${продамОлика} з 2`);

// ── 5. B-1: ПОРОЖНІЙ СТАН ВІД КОМБІНАЦІЇ МУСИТЬ НАЗВАТИ ОБИДВІ ПРИЧИНИ ──────
// Відтворення з аудиту: «Куплю» + «Олика». У самій категорії «Куплю» оголошення Є
// (воно в Котові), тож текст «у цій категорії поки порожньо» — неправда, і людина
// робить хибний висновок «у Куплю нічого немає», хоча досить змінити село.
//
// ⚠️ ПОРЯДОК ДІЙ ТУТ ПРИНЦИПОВИЙ, і перша версія стенда на ньому спіткнулась:
// поки активна локація, меню категорій ХОВАЄ порожні категорії — тобто «Куплю»
// в ньому просто немає, і тап нікуди не веде. Людина потрапляє в цей стан іншим
// шляхом: спершу обирає категорію (з повного списку), а вже потім звужує локацію —
// або локація лишилась увімкненою з минулого разу. Відтворюємо саме це.
await обратиЛокацію('Вся Олицька громада');
await обратиКатегорію('куплю');
const купитиВсюди = await карток();
ok('сцена B-1: у категорії «Куплю» оголошення Є (тобто причина не в ній)',
   купитиВсюди === 1, `${купитиВсюди}`);
await обратиЛокацію('Олика');
const комбо = await карток();
const текстКомбо = await порожній();
ok('сцена B-1 зібралась: комбінація дає нуль', комбо === 0 && текстКомбо.є, `${комбо} карток`);
ok('🔴 B-1: порожній стан називає КАТЕГОРІЮ', /Куплю/i.test(текстКомбо.текст), текстКомбо.текст);
ok('🔴 B-1: порожній стан називає ЛОКАЦІЮ (а не лише категорію)',
   /Олика/i.test(текстКомбо.текст), текстКомбо.текст);

// ── 6. B-2: СКИДАННЯ ФІЛЬТРІВ ОДНИМ ТАПОМ — У САМОМУ ПОРОЖНЬОМУ СТАНІ ───────
// Саме тут людина найменш схильна шукати три органи керування в трьох місцях —
// це момент, коли вона йде з екрана.
const кнопкаСкидання = await p.evaluate(() => {
  const btn = document.querySelector('#board-content .bd-empty [data-bd-reset]');
  if (!btn) return null;
  const r = btn.getBoundingClientRect();
  return { текст: btn.textContent.trim(), висота: Math.round(r.height) };
});
ok('🔴 B-2: у порожньому стані є кнопка скидання фільтрів', !!кнопкаСкидання,
   кнопкаСкидання ? кнопкаСкидання.текст : 'кнопки немає');
ok('кнопка скидання не менша за тап-ціль Apple HIG 44px',
   !!кнопкаСкидання && кнопкаСкидання.висота >= 44,
   кнопкаСкидання ? `${кнопкаСкидання.висота}px` : '—');

if (кнопкаСкидання) {
  await p.evaluate(() => document.querySelector('#board-content .bd-empty [data-bd-reset]')?.click());
  await p.waitForTimeout(700);
  const післяСкидання = await карток();
  ok('🔴 B-2: один тап повертає ПОВНИЙ список (усі три фільтри знято)',
     післяСкидання === POSTS.length, `${післяСкидання} з ${POSTS.length}`);
  const станШапки = await p.evaluate(() => ({
    категорія: document.getElementById('bd-cat-btn')?.classList.contains('bd-hero-cat--on'),
    локація: document.querySelector('.bd-loc-label')?.textContent.trim() || '',
    пошук: document.getElementById('bd-search-input')?.value || '',
  }));
  ok('після скидання шапка теж каже «фільтрів немає»',
     станШапки.категорія === false && станШапки.пошук === '' && /Громада/.test(станШапки.локація),
     JSON.stringify(станШапки));
}

// ── 7. A-2: ОДНА ГІЛКА `messages`, а не дві ─────────────────────────────────
// ⚠️ ЧЕСНО: це перевірка ТЕКСТУ коду, а не поведінки — і це свідомо. Мертвий рядок
// поведінкою не перевіряється: він недосяжний за визначенням, тож жоден сценарій до
// нього не дійде. Небезпека саме структурна: другий `if (act === 'messages')` кличе
// `openThreadsList()` БЕЗ `requireAuth`, а коментар поруч стверджує «requireAuth
// усередині» — неправда для цієї функції. Приберуть колись верхній рядок як «дубль»
// — і замість помилки з'явиться тихий обхід гейта входу (той самий клас, що PR #638).
//
// ⚠️ ДРУГА ПАСТКА, В ЯКУ Я СПОЧАТКУ ВЛІЗ: перша версія рахувала збіги по ВСЬОМУ
// файлу — і залишилась червоною після фіксу, бо мій же пояснювальний коментар
// («тут був другий if (act === 'messages')») теж збігся з регуляркою. Тобто
// перевірка міряла ТЕКСТ, а не код. Тому спершу викидаємо рядки-коментарі.
// Викидаємо лише ті, що ПОЧИНАЮТЬСЯ з `//`: чіпати `//` всередині рядків коду
// (напр. в адресах `https://`) не можна — так можна знищити справжній код.
const src = projectFile('src/tabs/board.js', REV);
const безКоментарів = src.split('\n').filter(l => !/^\s*\/\//.test(l)).join('\n');
const гілок = (безКоментарів.match(/if \(act === 'messages'\)/g) || []).length;
ok('🔴 A-2: гілка «messages» в обробнику FAB рівно одна', гілок === 1, `знайдено ${гілок}`);

await ctx.close(); await b.close(); await stop();
done();
