// tests/bus-scale.mjs — ШКАЛА ВІДСТЕЖЕННЯ АВТОБУСА: крапки зупинок мусять бути
// ЄДИНИМ ЦІЛИМ зі смугою, а не накладеними на неї.
//
// 🔴 ВІД ЧОГО ЗАВЕДЕНО (18.08). Скарга Вови по знімку: «кружечок накладений на
// цю шкалу, він прозорий трохи і видно що він накладений». Причина була не в
// кольорі, а в арифметиці: крапка `rgba(255,255,255,0.35)` лежала ПОВЕРХ такої
// ж прозорої смуги `rgba(255,255,255,0.2)`, а два прозорих шари ДОДАЮТЬСЯ.
// Заміряно на живій картці: всередині кожного кружечка яскравість 105 → 139 →
// 107, тобто крізь нього проходила світліша перемичка +29 пунктів рівно в тих
// 4px, де під ним лежала смуга.
//
// 📐 ЩО САМЕ МІРЯЄ ЦЕЙ СТЕНД — ПІКСЕЛІ, А НЕ ПРАВИЛА CSS. Скаргу «видно, що
// воно накладене» неможливо перевірити читанням стилів: правило можна написати
// бездоганно і все одно отримати перемичку, бо вона народжується не в правилі,
// а в СКЛАДАННІ двох шарів. Тому:
//   1. розкид яскравості ВСЕРЕДИНІ кружечка (перемичка — це і є розкид);
//   2. кожен піксель шкали звіряється з тим, яким він МАЄ бути над своїм
//      власним фоном — тобто фікс не мав права змінити вигляд.
//
// 🔑 ФОН МІРЯЄТЬСЯ, А НЕ ВГАДУЄТЬСЯ. Знімок робиться ДВІЧІ: зі шкалою і без неї
// (`visibility: hidden`). Другий кадр дає точний фон під кожним пікселем, і
// очікуване значення рахується з нього. Інакше поріг довелось би вписати числом,
// а число зламалось би від будь-якої зміни фото чи градієнта картки — і стенд
// звинуватив би справний код (у проєкті таких випадків уже девʼятнадцять).
//
// 🛑 ФОТО КАРТКИ НАВМИСНО ВИМКНЕНЕ. Дефект живе в складанні шарів шкали і від
// фото не залежить узагалі, а живе фото робить фон під крапкою нерівним по
// вертикалі — тоді «розкид усередині крапки» міряв би ФОТОГРАФІЮ, а не ваду.
// Живим фото дивиться інструмент `tests/tools/bus-scale-probe.mjs`.
//
// ✅ КОНТРОЛЬ (обовʼязково ДВІ змінні — вада лежить і в розмітці, і в стилях):
//    SRC_REV=<до фіксу> CSS_REV=<до фіксу> node tests/bus-scale.mjs
// На коді до фіксу перевірки розкиду МУСЯТЬ упасти. Зелений контроль означає,
// що підміна не відбулась і стенд міряє не те.
import { chromium } from '@playwright/test';
import { launch, serve, blockExternal, reporter, pixelsOf, projectFile } from './_lib.mjs';

const SRC_REV = process.env.SRC_REV || '';
const CSS_REV = process.env.CSS_REV || '';

const { ok, done } = reporter();

// ── Беремо ЖИВУ функцію розмітки з `src/tabs/buses.js` ──────────────────────
// 🔑 Не переписуємо розмітку в стенді руками: тоді стенд перевіряв би власну
// копію, а не застосунок, і розійшовся б із ним при першій же зміні (у проєкті
// дві копії того самого вже розходились — списки антиспаму).
const джерело = projectFile('src/tabs/buses.js', SRC_REV);
function витягти(імʼя) {
  const i = джерело.indexOf(`export function ${імʼя}(`);
  if (i < 0) throw new Error(`bus-scale: у buses.js не знайдено ${імʼя}`);
  const j = джерело.indexOf('\n}\n', i);
  if (j < 0) throw new Error(`bus-scale: не знайдено кінець ${імʼя}`);
  return джерело.slice(i, j + 2).replace(/^export /, '');
}
const функції = [витягти('parseRouteEndpoints'), витягти('renderRouteMapV4')].join('\n');

const cssШкали = projectFile('style/buses.css', CSS_REV);

// ── Сцена: 5 зупинок, дві картки — рейс чекає і рейс у дорозі ───────────────
const МАРШРУТ = { name: 'ЛУЦЬК ОЛИКА', stops: [0, 8, 17, 25, 33].map((km, i) => ({ km, name: 'З' + i })) };

const { url, stop } = await serve();
const b = await launch(chromium);
const page = await b.newPage({ viewport: { width: 390, height: 760 }, deviceScaleFactor: 1 });
await blockExternal(page);
await page.route('**/bundle.js', r => r.abort());   // стенду потрібні лише стилі
await page.goto(url + '/index.html');
await page.addStyleTag({ content: cssShim() });
function cssShim() { return cssШкали; }
await page.addStyleTag({ content: `
  .bhv4-bg-img { display: none !important; }        /* див. блок 🛑 у шапці */
  .bhv4-dot--current { animation: none !important; } /* знімок мусить бути відтворюваним */
` });

await page.evaluate(([фн, маршрут]) => {
  const escapeHtml = s => String(s ?? '').replace(/[&<>"']/g, c =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  // eslint-disable-next-line no-new-func
  const карта = new Function('escapeHtml', 'route', 'timings', `${фн}; return renderRouteMapV4(route, timings);`);
  const сцена = [
    карта(escapeHtml, маршрут, { progress: 0,    state: 'waiting' }),
    карта(escapeHtml, маршрут, { progress: 0.42, state: 'enroute' }),
  ].map((html, i) =>
    `<div class="bhv4${i ? ' bhv4--enroute' : ''}" style="margin-bottom:20px">
       <div class="bhv4-overlay"></div>
       <div class="bhv4-content"><div class="bhv4-map-outer">${html}</div></div>
     </div>`).join('');
  document.body.innerHTML =
    `<div id="scene" style="position:fixed;inset:0;background:#ECEEF1;padding:16px;z-index:2147483000">${сцена}</div>`;
}, [функції, МАРШРУТ]);
await page.waitForTimeout(400);

// ── Геометрія: де стоять крапки і де лежить смуга ───────────────────────────
const геом = await page.evaluate(() => [...document.querySelectorAll('#scene .bhv4-map')].map(m => {
  const mr = m.getBoundingClientRect();
  const tr = m.querySelector('.bhv4-track').getBoundingClientRect();
  return {
    центрY: Math.round(tr.top - mr.top + tr.height / 2),
    крапки: [...m.querySelectorAll('.bhv4-dot')].map(d => {
      const r = d.getBoundingClientRect();
      return {
        x: Math.round(r.left - mr.left + r.width / 2),
        рід: d.classList.contains('bhv4-dot--current') ? 'рухома'
           : d.classList.contains('bhv4-dot--passed')  ? 'пройдена' : 'майбутня',
      };
    }),
  };
}));

// Кадр зі шкалою і кадр БЕЗ неї — другий дає точний фон під кожним пікселем.
const кадр = async сховати => {
  await page.evaluate(с => {
    document.getElementById('bs-hide')?.remove();
    if (!с) return;
    const st = document.createElement('style');
    st.id = 'bs-hide';
    st.textContent = '#scene .bhv4-track { visibility: hidden }';
    document.head.appendChild(st);
  }, сховати);
  const out = [];
  for (let i = 0; i < геом.length; i++) out.push(await pixelsOf(page, `#scene .bhv4-map >> nth=${i}`));
  return out;
};
const ЗІ = await кадр(false);
const БЕЗ = await кадр(true);

// ── 1. САМОПЕРЕВІРКА ПРИЛАДУ: кадр із самим собою мусить дати нуль ──────────
// Правило проєкту №1 про мірку: спершу зміряй, що дає порівняння стану з самим
// собою. Шумовий поріг має бути 0, інакше будь-яке число нижче — не замір.
{
  const ще = await кадр(true);
  let шум = 0;
  for (let y = 0; y < БЕЗ[0].h; y++)
    for (let x = 0; x < БЕЗ[0].w; x++)
      шум = Math.max(шум, Math.abs(БЕЗ[0].ярк(БЕЗ[0].px(x, y)) - ще[0].ярк(ще[0].px(x, y))));
  ok('прилад: два однакові кадри дають нуль розбіжності', шум === 0, `шум ${шум}`);
}

// 🔴 РЯДКИ ВИВЕДЕНІ ВИМІРОМ, А НЕ «НА ОКО». Коло 8px займає рядки dy −4…+3
// відносно центру смуги, і ОБИДВА крайні рядки згладжені (антиаліасинг): у білої
// крапки 129.5 і 130.5 проти рівних 137.1 усередині. Перша редакція стенда брала
// −3…+3, ловила нижній згладжений рядок і показувала «розкид 7.7» на цілком
// вилікуваному коді — тобто звинувачувала справний код. Беремо тільки повністю
// внутрішні рядки. (Правило проєкту: першою підозрюваною є перевірка.)
const РЯДКИ = [-3, -2, -1, 0, 1, 2];

const назва = ['рейс чекає (progress 0)', 'рейс у дорозі (progress 42%)'];
for (let i = 0; i < геом.length; i++) {
  const g = геом[i], p = ЗІ[i], f = БЕЗ[i];
  const майбутні = g.крапки.filter(d => d.рід === 'майбутня');
  const пройдені = g.крапки.filter(d => d.рід === 'пройдена');

  // ── 2. Головна перевірка: перемички всередині кружечка немає ──────────────
  let найгірший = 0, деНайгірший = 0;
  for (const d of майбутні) {
    const я = РЯДКИ.map(dy => p.ярк(p.px(d.x, g.центрY + dy)));
    const розкид = Math.max(...я) - Math.min(...я);
    if (розкид > найгірший) { найгірший = розкид; деНайгірший = d.x; }
  }
  ok(`${назва[i]}: у майбутніх крапках немає світлішої перемички`,
     найгірший <= 4, `найбільший розкид яскравості всередині кружечка ${найгірший.toFixed(1)} (x=${деНайгірший}), стеля 4`);

  // ── 3. Пройдені зелені крапки були рівні й до фіксу — регрес ──────────────
  if (пройдені.length) {
    let гірше = 0;
    for (const d of пройдені) {
      const я = РЯДКИ.map(dy => p.ярк(p.px(d.x, g.центрY + dy)));
      гірше = Math.max(гірше, Math.max(...я) - Math.min(...я));
    }
    ok(`${назва[i]}: пройдені зелені крапки лишились рівними`, гірше <= 1, `розкид ${гірше.toFixed(1)}`);
  }

  // ── 4. Вигляд НЕ змінився: кожен піксель = формула над власним фоном ──────
  // смуга  — біле 0.20 над фоном (рівно як було до фіксу)
  // крапка — біле 0.48 над фоном (рівно те, чим була СЕРЕДИНА крапки до фіксу)
  const відхил = (x, y, a) => {
    const ф = f.px(x, y), з = p.px(x, y);
    return Math.max(...[0, 1, 2].map(k => Math.abs(з[k] - (ф[k] * (1 - a) + 255 * a))));
  };
  const між = Math.round((майбутні[0].x + майбутні[1].x) / 2);
  const dсмуга = Math.max(...[-1, 0, 1].map(dy => відхил(між, g.центрY + dy, 0.20)));
  ok(`${назва[i]}: смуга лишилась білим 0.20 над фоном`, dсмуга <= 2, `найбільше відхилення каналу ${dсмуга.toFixed(1)}`);

  const dкрапка = Math.max(...майбутні.map(d => Math.max(...РЯДКИ.map(dy => відхил(d.x, g.центрY + dy, 0.48)))));
  ok(`${назва[i]}: крапка = біле 0.48 над фоном (яскравість середини збережена)`,
     dкрапка <= 3, `найбільше відхилення каналу ${dкрапка.toFixed(1)}`);
}

// ── 5. РОЗМІТКА ШКАЛИ БУДУЄТЬСЯ РІВНО В ОДНОМУ МІСЦІ ────────────────────────
//
// 🔴 Спіймано 18.08 читанням коду, а не приладом, і стенд його не бачив би.
// У живому тіку картки (`startHeroTicker`) лежала ДРУГА копія розмітки шкали:
// вона перебудовувала `.bhv4-track` власним рядком. Після першого ж тіку шкала
// не просто повернула б накладені крапки — вона лишилась би ЗОВСІМ БЕЗ СМУГИ,
// бо фон `.bhv4-track` тепер прозорий, а смугу малює `.bhv4-rail-line` усередині
// групи. Це рівно та хвороба, від якої в проєкті вже застерігали двічі (списки
// антиспаму, правила Дошки): дві копії того самого мовчки розходяться.
{
  const скільки = (джерело.match(/class="bhv4-fill"/g) || []).length;
  ok('розмітка шкали будується рівно в одному місці', скільки === 1,
     `місць, де складається смуга: ${скільки}`);
}

// ── 6. Обідок рухомої крапки не має РІЗКОГО краю ────────────────────────────
// Кільце `0 0 0 3px` давало сходинку рівно на межі смуги — саме вона й читалась
// як «накладене кільце». Міряємо найбільший стрибок яскравості між сусідніми
// рядками у стовпчику, що проходить крізь обідок, але повз ядро крапки.
{
  const g = геом[1], p = ЗІ[1];
  const рух = g.крапки.find(d => d.рід === 'рухома');
  ok('сцена: рухома крапка намальована', !!рух, рух ? `x=${рух.x}` : 'її немає');
  if (рух) {
    // 🔴 МІРЯЄМО НАД ЯДРОМ, А НЕ ЗБОКУ. Перша редакція брала стовпчик праворуч
    // від ядра — і ловила сходинку від краю САМОЇ СМУГИ (смуга це брусок із
    // різким краєм, і сходинка там буде завжди, хоч би який мʼякий був обідок).
    // Прилад показував 41 і звинувачував справний код. Над ядром смуги немає
    // взагалі (вона лише ±2 рядки), тож там видно РІВНО різкість обідка.
    const я = [];
    for (let dy = -6; dy >= -13; dy--) я.push(p.ярк(p.px(рух.x, g.центрY + dy)));
    let стрибок = 0;
    for (let k = 1; k < я.length; k++) стрибок = Math.max(стрибок, Math.abs(я[k] - я[k - 1]));
    ok('обідок рухомої крапки розмитий, а не різкий (немає обриву кільця)',
       стрибок <= 20, `найбільший стрибок між сусідніми рядками ${стрибок.toFixed(1)}, стеля 20`);
  }
}

await b.close(); await stop();
