// Стенд: ЛАНЦЮГ «опубліковано → видно» ПЕРЕВІРЯЄТЬСЯ НА ДАНИХ, А НЕ В КОДІ.
//
// 🔴 20.08. Скарга Вови: «опублікував пости, які ШІ згенерував — чому я їх не
// бачу? Це означає що тут дірка».
//
// 🔬 ЗАМІРЯНО НА ЖИВІЙ БАЗІ І ЖИВОМУ ФАЙЛІ: 6 статей мали в Supabase стан
// `published` + `git_id`, а в `data/articles.json` не було ЖОДНОЇ статті
// кабінету (`kind=editor` — нуль). Два з номерів указували на ЧУЖІ статті
// («Сам викликав евакуатор», Волинь). Тобто база два місяці рапортувала про
// публікацію, якої не сталося.
//
// 🛑 ЧОМУ ЖОДЕН З 92 СТЕНДІВ ЦЬОГО НЕ ЛОВИВ. Усі вони перевіряють КОД: чи є
// функція, чи правильний селектор, чи не змішались сутності. Але тут кожна
// ланка коду була справна — ламався САМ ЛАНЦЮГ, на стику процесів. Такий
// розрив видно лише на даних, і за один день він трапився ДВІЧІ (вранці —
// свята, які їхали в `events.json`, що ніде не показувався; ввечері — статті).
//
// 🔑 Тому цей сторож іншого класу: він бере СПРАВЖНІ файли даних і питає не
// «чи правильний код», а «чи доходить опубліковане до людини».
// 🛑 03.09 — PYTHON-МОДУЛІ ТУТ КОМПІЛЮЮТЬСЯ З ДЖЕРЕЛА (`compile()`), а не
// підвантажуються через `importlib`. 📐 Заміряно того дня на `news-dedup`:
// контрольний прогін міняв стелю `0.03` → `1.00` — рядки ОДНАКОВОЇ довжини, тож
// розмір файлу не змінився, і Python віддав СТАРИЙ байт-код із `__pycache__`.
// Стенд світився зеленим на коді, якого вже не існувало.
// ⚠️ Не «спрощувати» назад до `importlib`: сторож мусить міряти джерело правди.
import { readFileSync, writeFileSync, mkdtempSync, copyFileSync } from 'fs';
import { execFileSync } from 'child_process';
import { tmpdir } from 'os';
import { join } from 'path';
import { projectFile, reporter } from './_lib.mjs';

const { ok, done } = reporter();
const статті = JSON.parse(projectFile('data/articles.json'));
const події  = JSON.parse(projectFile('data/events.json'));
const синк   = projectFile('scripts/sync_cms.py');
const флов   = projectFile('.github/workflows/cms-sync.yml');

// ── 1. НОМЕРИ НЕ МОЖУТЬ ЗБІГТИСЬ ───────────────────────────────────────────
// `articles.json` пишуть ДВА процеси з різних воркфловів, і обидва рахували
// `max(наявних)+1` кожен зі свого знімка. Два лічильники на один простір — це
// не «ризик», а питання часу.
ok('🔴 у статей кабінету власний простір номерів', /CMS_ID_BASE = 1_000_000/.test(синк));
ok('🔴 лічильник кабінету рахує ЛИШЕ свої номери (чужий великий id його не зрушить)',
   /a\["id"\] >= CMS_ID_BASE/.test(синк));
ok('синк більше не бере номер зі спільного максимуму',
   !/next_id = max\(\(a\["id"\] for a in existing/.test(синк));

// ── 2. ПОЗНАЧКУ СТАВИТЬ ТОЙ, ХТО БАЧИВ УСПІХ ───────────────────────────────
// Корінь був у ПОРЯДКУ: база позначалась усередині циклу збору, а доля статті
// вирішувалась після — ліміти, баланс, обрізка, і сам пуш, який міг не доїхати.
ok('🔴 у циклі збору база НЕ позначається', !/mark_published\(row\["id"\], next_id\)/.test(синк));
ok('🔴 підтвердження — окремий такт `--confirm`', /def confirm\(\)/.test(синк) && /--confirm/.test(синк));
ok('🔴 воркфлов кличе підтвердження ЛИШЕ після вдалого пуша',
   /Confirm published[\s\S]{0,400}?sync_cms\.py --confirm/.test(флов)
   && /if: steps\.commit\.outputs\.changed == 'true'[\s\S]{0,300}?--confirm/.test(флов));

// ── 3. ДАНІ: ОПУБЛІКОВАНЕ МУСИТЬ БУТИ ВИДНИМ ───────────────────────────────
// 📐 Найпрямша мірка ланцюга. Свята вже їдуть правильно — це доводить, що
// перевірка вміє бути зеленою, а не просто сувора до всього.
const свята = події.filter(e => (e.title || '').trim());
ok('свята кабінету доходять до файлу подій', свята.length > 0, `${свята.length} подій`);

// ⚠️ Ключова властивість файлу статей: у ньому не може бути двох рядків з одним
// номером. Саме дублікат і означає, що хтось перезаписав чужий id.
const номери = статті.map(a => a.id).filter(n => Number.isInteger(n));
const дублі = номери.filter((n, i) => номери.indexOf(n) !== i);
ok('🔴 у стрічці немає двох статей з однаковим номером', дублі.length === 0,
   дублі.length ? `дублі: ${[...new Set(дублі)].slice(0, 5).join(', ')}` : '');

// Простори не перетинаються: жодна ЧУЖА стаття не залізла у діапазон кабінету.
const чужіВдіапазоні = статті.filter(a => Number.isInteger(a.id) && a.id >= 1_000_000
                                          && a.kind !== 'editor');
ok('🔴 у діапазоні кабінету немає чужих статей', чужіВдіапазоні.length === 0,
   `${чужіВдіапазоні.length}`);


// ── 4. 🔴 СИНК ЗАПУСКАЄТЬСЯ, А НЕ ЛИШЕ ЧИТАЄТЬСЯ ────────────────────────────
// 🛑 НАЙДОРОЖЧИЙ УРОК ДНЯ, І ВІН ПРО МЕНЕ САМОГО. Перевірки вище я написав під
// гаслом «ланцюг міряємо на ДАНИХ, а не в коді» — і полагодив порядок дій та
// простір номерів, жодного разу не ЗАПУСТИВШИ синк.
//
// А він падав. Рівно місяць, з 21.07: у `sync_cms.py` лишились виклики
// `pr.apply_daily_limits()` і `pr.balance_ua_world()` — обидві функції прибрали
// з `parse_rss.py`, коли денні ліміти замінили зберіганням за віком. Кожен
// прогін, у якому БУЛО ЩО СИНКАТИ, помирав з `AttributeError` — уже ПІСЛЯ того,
// як позначив рядки опублікованими. Наступний прогін бачив порожню чергу і
// рапортував «синк не потрібен»: 913 запусків, більшість «успішних», над
// мертвим ланцюгом.
//
// ⚠️ Другий мертвий виклик я знайшов ЛИШЕ запуском. Читанням не побачив: рядок
// `pr.balance_ua_world(merged)` виглядає бездоганно.
//
// 🔑 Тому ця сцена ЗАПУСКАЄ справжній `sync_cms.py` з підробленою чергою і
// тимчасовим файлом. Перевірка на текст коду тут безсила за визначенням: щоб
// побачити `AttributeError`, треба виконати рядок.
const прогін = (() => {
  const dir = mkdtempSync(join(tmpdir(), 'cms-'));
  const art = join(dir, 'articles.json');
  copyFileSync('data/articles.json', art);
  const драйвер = join(dir, 'run.py');
  writeFileSync(драйвер, `
import types, json, os, pathlib
os.environ['SUPABASE_SERVICE_ROLE_KEY'] = 'stub'
_src = open('scripts/sync_cms.py', encoding='utf-8').read()
m = types.ModuleType('sc'); m.__file__ = 'scripts/sync_cms.py'
exec(compile(_src, 'scripts/sync_cms.py', 'exec'), m.__dict__)
m.pr.DATA_PATH = pathlib.Path(${JSON.stringify(art)})
m.PENDING_PATH = pathlib.Path(${JSON.stringify(join(dir, 'pend.json'))})
m.fetch_ready = lambda: [{"id": 4, "title": "Тестова стаття кабінету про Олику XVI століття",
  "excerpt": "лід", "content": "текст", "category": "Історія", "geo": "Громада", "ts": 1750000000000}]
m.sync_events = lambda: None
m.autopublish_scheduled = lambda: None
m.heal_phantom_drafts = lambda: None
було = len([a for a in json.load(open(${JSON.stringify(art)}, encoding='utf-8'))
            if a.get('kind') == 'editor'])
m.main()
файл = json.load(open(${JSON.stringify(art)}, encoding='utf-8'))
ред = [a for a in файл if a.get('kind') == 'editor']
print('РЕЗУЛЬТАТ', json.dumps({'своїх': len(ред), 'приріст': len(ред) - було,
      'номери': [a['id'] for a in ред],
      'наміри': json.load(open(${JSON.stringify(join(dir, 'pend.json'))}, encoding='utf-8'))}, ensure_ascii=False))
`);
  try {
    const out = execFileSync('python3', [драйвер], { encoding: 'utf-8', stdio: ['ignore', 'pipe', 'pipe'] });
    const рядок = out.split('\n').find(l => l.startsWith('РЕЗУЛЬТАТ'));
    return { ok: true, ...JSON.parse(рядок.slice(9)) };
  } catch (e) {
    return { ok: false, err: String(e.stderr || e.message).slice(-400) };
  }
})();

ok('🔴 синк ДОХОДИТЬ ДО КІНЦЯ на справжньому запуску (не падає на мертвому виклику)',
   прогін.ok, прогін.ok ? '' : прогін.err);
// ⚠️ 21.08 — БУЛО `своїх === 1`, і мірка застаріла в ту ж мить, коли ланцюг
// ожив: у справжньому файлі тепер лежать 10 статей кабінету, які синк доставив
// по-справжньому. Число «1» описувало не поведінку, а порожній файл.
// 🔑 Міряємо ПРИРІСТ: скільки було до запуску — стільки й має бути плюс одна.
ok('🔴 стаття кабінету справді лягла у файл', прогін.ok && прогін.приріст === 1,
   `своїх у файлі: ${прогін.своїх}, приріст: ${прогін.приріст}`);
ok('🔴 номер виданий із простору кабінету (≥ 1 000 000)',
   прогін.ok && прогін.номери.every(n => n >= 1_000_000), JSON.stringify(прогін.номери));
ok('🔴 намір відкладено на підтвердження, а не позначено одразу',
   прогін.ok && Array.isArray(прогін.наміри) && прогін.наміри.length === 1,
   JSON.stringify(прогін.наміри));

done();
