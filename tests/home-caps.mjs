    posts: [ПИТАННЯ(70, { text: 'Коли буде ремонт дороги?' })],
    comments: [ВІДПОВІДЬ(80, 70), ВІДПОВІДЬ(81, 70), ВІДПОВІДЬ(82, 70)],
