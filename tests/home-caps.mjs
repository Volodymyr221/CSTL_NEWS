// 🔑 Це і є перевірка САМОГО принципу шкали, а не порядку ролей: перемагає те,
// що швидше втрачає сенс. Повідомлення можна прочитати за годину, автобус через
// 5 хв — не можна. Той самий рейс у сцені 9 стояв ТРЕТІМ (там до нього 40 хв).
{
  const s = await сцена({
    user: USER, routes: [РЕЙС_ОСЬ_ОСЬ],
    profiles: [{ uid: UID, name: 'Вова', settlement: 'Олика' }],
    posts: [],
    threads: [розмова('t1')],
    messages: [повідомлення('m1', 't1')],
  });
  const c = await капсули(s.p);

  ok('🔴 рейс за 10 хв стоїть ВИЩЕ за свіже повідомлення',
     c.ключі.join('→') === 'now→msg', c.ключі.join('→'));
  // ⚠️ 10 хв, а не 5: виїзд 09:05, Олика на ПОЛОВИНІ шляху (60 із 120 км) при
  // тривалості 10 хв → посадка 09:10. Перша редакція перевірки чекала «5 хв» —
  // тобто міряла час до ВИЇЗДУ, рівно ту ваду, від якої заведено цей стенд.
  ok('🔴 і це справді рейс за хвилини (поріг ≤15)',
     c.мітки[0] === 'ЗАРАЗ · ЧЕРЕЗ 10 ХВ', c.мітки[0]);

  ok('помилок у консолі немає (близький рейс)', s.errs.length === 0, s.errs.slice(0, 2).join(' | '));
  await s.ctx.close();
}

// ── СЦЕНА 11: КІЛЬКА РОЗМОВ — НЕ ОБІЦЯЄМО ОДНУ ЛЮДИНУ ──────────────────────
// Назвати «Іван», а повести в список, де ще двоє, означало б збрехати про те,
// куди веде тап. Тому при кількох розмовах капсула каже лише скільки їх.
{
  const s = await сцена({
    user: USER, posts: [],
    threads: [розмова('t1'), розмова('t2', { buyer_uid: 'uid-olya', buyer_name: 'Оля',
                                              last_message_text: 'Добрий вечір' })],
    messages: [повідомлення('m1', 't1'), повідомлення('m2', 't2', { sender_uid: 'uid-olya' })],
  });
  const c = await капсули(s.p);

  ok('🔴 дві розмови — капсула не називає одну людину',
     (c.тексти.find((_, i) => c.ключі[i] === 'msg') || '') === '2 нові розмови',
     c.тексти.join(' | '));

  const єМсг2 = await s.p.evaluate(() => !!document.querySelector('.hm-cap2[data-cap="msg"]'));
  if (єМсг2) { await s.p.locator('.hm-cap2[data-cap="msg"]').click(); await s.p.waitForTimeout(1500); }
  const список = !єМсг2 ? '' : await s.p.evaluate(() =>
    document.querySelector('.pm-screen, .pm-head')?.textContent.slice(0, 120) || '');
  ok('🔴 тап веде у список «Повідомлення»', /повідомлення/i.test(список),
     список ? список.replace(/\s+/g, ' ').slice(0, 60) : 'екрана немає');

  ok('помилок у консолі немає (дві розмови)', s.errs.length === 0, s.errs.slice(0, 2).join(' | '));
  await s.ctx.close();
}

// ── СЦЕНА 12: НІЧОГО НЕ ОБРІЗАЄТЬСЯ НА ЧОТИРЬОХ ШИРИНАХ ЕКРАНА ──────────────
// 🔴 Пряме замовлення Вови 17.08: «в капсулу має влазити хоча б певна інформація,
// а не обрізатися на половині».
//
// 🔑 ЧОМУ ЧОТИРИ ШИРИНИ, А НЕ ОДНА. Заміряно приладом: рядок значення тримає
// **25** символів на 390pt, **24** на 375pt і лише **17** на 320pt. Тобто стеля,
// вписана числом символів, на одному телефоні лишає порожнє місце, а на іншому
// ріже слово — і сторож на одній ширині цього не побачив би НІКОЛИ.
// 430pt (великий iPhone, як у Вови) стоїть тут як протилежний край: там текст
// мусить бути ПОВНИЙ, а не обрізаний «про запас».
{
  const ПИТАННЯ = 'Коли вивозять сміття з вулиці Замкової і чи буде графік';
  const ДОВГА_НАЗВА = 'Продам плуг МТЗ триколісний у гарному стані недорого';

  for (const ширина of [320, 375, 390, 430]) {
    const s = await сцена({
      ширина, user: USER,
      profiles: [{ uid: UID, name: 'Вова', settlement: 'Олика' }],
      posts: [
        питання(80, { text: ПИТАННЯ }),
        оголошення(81, { owner_uid: UID, status: 'rejected', title: ДОВГА_НАЗВА }),
      ],
      threads: [розмова('t1', { post_id: 81 })],
      messages: [повідомлення('m1', 't1')],
    });
    const c = await капсули(s.p);

    ok(`🔴 ${ширина}pt — жоден рядок не обрізаний`, c.обрізано === 0,
       `обрізано ${c.обрізано} з ${c.n}: ${c.мітки.join(' | ')} / ${c.тексти.join(' | ')}`);

    // Питання могло не влізти в топ-3 на вузькому екрані — беремо його, якщо є.
    const q = c.тексти.find((_, i) => c.ключі[i] === 'new') || '';
    if (q) {
      ok(`🔴 ${ширина}pt — питання обрізане ПО СЛОВУ, а не посеред слова`,
         поСловах(q, ПИТАННЯ), q);
      // 🛑 Другий бік тієї самої вимоги: обрізка не має зводити рядок до одного
      // слова. «Коли…» технічно по межі слова, але інформації в ньому нема.
      ok(`🔴 ${ширина}pt — у питанні лишилось щонайменше 3 слова`,
         q.replace('…', '').trim().split(/\s+/).length >= 3, q);
    }

    // 🔑 На широкому екрані текст мусить бути ЦІЛИЙ — інакше «вміщення» звелося б
    // до того, що ми ріжемо завжди й на всяк випадок.
    if (ширина === 430 && q) {
      ok('🔴 430pt — питання вміщується ПОВНІСТЮ, без трикрапки',
         q === ПИТАННЯ, q);
    }

    ok(`помилок у консолі немає (${ширина}pt)`, s.errs.length === 0, s.errs.slice(0, 2).join(' | '));
    await s.ctx.close();
  }
}

