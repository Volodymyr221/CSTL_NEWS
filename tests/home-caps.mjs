// Чи обрізано рядок ПО МЕЖІ СЛОВА щодо відомого оригіналу.
// 🛑 Евристикою «чи стоїть „…“ після літери» це перевірити НЕ можна: правильна
// обрізка теж дає «слово…». Єдиний чесний спосіб — звірити з повним текстом:
// показане мусить бути початком оригіналу, і рівно на межі слова.
function поСловах(показане, оригінал) {
  if (показане === оригінал) return true;
  if (!показане.endsWith('…')) return false;
  const тіло = показане.slice(0, -1);
  if (!оригінал.startsWith(тіло)) return false;
  const далі = оригінал.slice(тіло.length);
  return /^\s/.test(далі);            // наступний символ оригіналу — пробіл
}

