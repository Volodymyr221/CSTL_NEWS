// Стенд: АГЕНТ CEO НЕ ВИГАДУЄ І НЕ ЗМІШУЄ ФАКТ ІЗ ДУМКОЮ (21.09.2026).
//
// 🔴 ЗАРАДИ ЧОГО. Вова замовив у звіті субʼєктивну думку CEO («моментами цікаво
// почути субʼєктивну думку СЕО»). Це корисно — і це ж найнебезпечніше місце
// всієї затії: думка, не відділена від заміру, читається як факт, і рішення
// ухвалюються по ній. Тому три рівні (`ЗАМІРЯНО` / `ВИСНОВОК` / `ДУМКА CEO`) —
// не стилістика, а вимога, і вона мусить стерегтися приладом.
//
// 🔑 ЩО САМЕ МІРЯЄМО. Виклик моделі коштує грошей, тож сцена ганяє агента в
// сухому режимі (`--dry-run`) і перевіряє ЗАПИТ, який пішов би до моделі:
//   1. у ньому є КУРС — інакше «вектор» нема від чого відштовхнути;
//   2. у ньому є ФАКТИ зі збирача, а не самі лише інструкції;
//   3. у ньому стоїть заборона вигадувати числа і правило «не заміряно ≠ нуль»;
//   4. у ньому є всі пʼять блоків звіту і три мітки рівнів;
//   5. він НЕ вимагає рахувати рух до «20 млн» — це візія, не показник.
// ⚠️ Чого цей стенд НЕ доводить: якості самого звіту. Її не перевірить жоден
// прилад — її перевіряє Вова, читаючи. Казати інакше було б тією самою брехнею
// приладу, від якої проєкт уже страждав.
import { execFileSync } from 'child_process';
import { readFileSync, mkdtempSync } from 'fs';
import { tmpdir } from 'os';
import { join } from 'path';
import { reporter } from './_lib.mjs';

const { ok, done } = reporter();

const промпт = execFileSync('python3', ['scripts/ceo_agent.py', '--dry-run'],
  { encoding: 'utf-8', timeout: 90000 });

// ── 1. КУРС І ФАКТИ ВСЕРЕДИНІ ──────────────────────────────────────────────
{
  const курс = readFileSync('CSTL NEWS VOVA/KURS.md', 'utf-8');
  // Беремо рядок, який є ЛИШЕ в курсі, і вимагаємо, щоб вимір його побачив —
  // підкидаємо відоме значення, а не питаємо «чи схоже».
  const мітка = курс.split('\n').find(р => р.includes('ЦІЛЬ №1'));
  ok('🔴 у запиті є КУРС (інакше «вектор» нема від чого відштовхнути)',
     !!мітка && промпт.includes(мітка.trim()), (мітка || '(не знайшов рядка в курсі)').slice(0, 60));

  const факти = JSON.parse(execFileSync('python3', ['scripts/ceo_facts.py', '--json'],
    { encoding: 'utf-8', timeout: 60000 }));
  ok('🔴 у запиті є ФАКТИ зі збирача, а не самі інструкції',
     промпт.includes('"стендів_у_проєкті"')
     && промпт.includes(String(факти.виробництво.стендів_у_проєкті)),
     `стендів: ${факти.виробництво.стендів_у_проєкті}`);
}

// ── 2. 🛑 ТРИ РІВНІ ТЕКСТУ ─────────────────────────────────────────────────
{
  // 🔴 21.09 — ПЕРША РЕДАКЦІЯ ЦЬОГО БЛОКУ БРЕХАЛА, І СПІЙМАЛА ЦЕ МУТАЦІЯ.
  // Вона шукала мітки по ВСЬОМУ запиту, а `ДУМКА CEO:` згадується ще й у описі
  // блоку 4 («саме тут доречні рядки…»). Тому мутація «прибрати визначення
  // рівня» лишала стенд зеленим: мітка знаходилась не там, де потрібна.
  // ✅ Тепер дивимось РІВНО в секцію, де рівні ВИЗНАЧАЮТЬСЯ.
  const секція = (промпт.split('ТРИ РІВНІ ТЕКСТУ')[1] || '').split('ЧОГО НЕ РОБИТИ')[0];
  ok('прилад знайшов секцію з визначенням рівнів', секція.length > 100,
     `${секція.length} символів`);
  for (const мітка of ['ЗАМІРЯНО:', 'ВИСНОВОК:', 'ДУМКА CEO:']) {
    ok(`🛑 рівень «${мітка}» ВИЗНАЧЕНО, а не просто згадано`, секція.includes(мітка));
  }
  // Зустрічна межа: мало перелічити мітки — треба сказати, ЧОМУ думка окремо.
  ok('🔑 і сказано, навіщо думка відокремлена',
     /не читалась як вимір|не прикидається фактом/.test(промпт));
}

// ── 3. 🔴 ЗАБОРОНИ, БЕЗ ЯКИХ ЗВІТ СТАЄ ВИГАДКОЮ ────────────────────────────
{
  ok('🔴 заборонено вигадувати числа', /Вигадувати числа\s*\n?\s*заборонено/.test(промпт));
  ok('🔴 «не заміряно» прямо названо НЕ нулем',
     /«не заміряно» — це НЕ нуль|значенням «не заміряно» — це НЕ нуль/.test(промпт)
     || /не заміряно[»"]? — це НЕ нуль/.test(промпт));
  ok('🛑 сказано, що запуску ще НЕ БУЛО (інакше висновки про людей)',
     /запуску ще НЕ БУЛО/.test(промпт));
  ok('🛑 заборонено міряти рух до 20 млн (це візія, не показник)',
     /20 млн/.test(промпт) && /візія/.test(промпт));
  ok('🛑 плоский тиждень не вважається поганим сигналом',
     /плоский тиждень/.test(промпт));
}

// ── 4. ПʼЯТЬ БЛОКІВ ЗВІТУ ──────────────────────────────────────────────────
{
  const блоки = ['ДЕ МИ ПРОТИ КУРСУ', 'ЩО ЗМІНИЛОСЬ У ЦИФРАХ', 'ЩО ЗАБЛОКОВАНО',
                 'ВЕКТОР', 'РІШЕННЯ НА ПІДПИС'];
  const нема = блоки.filter(б => !промпт.includes(б));
  ok('🔴 у завданні всі пʼять блоків звіту', нема.length === 0,
     нема.length ? `бракує: ${нема.join(', ')}` : 'усі пʼять');
}

// ── 5. 🔑 ДУМКА ПРО ЦИФРИ ЛИШАЄТЬСЯ ОДНА ───────────────────────────────────
//
// Агент CEO не перетлумачує аналітику заново — він бере готовий висновок
// `ai-analytics-summary`. Два тексти про ті самі числа розійшлись би, і стало б
// незрозуміло, хто з них бреше (це вже було з двома чергами завдань).
{
  ok('🔑 аналітичний висновок вбудовано як даність, а не перераховано',
     /ОСТАННІЙ АНАЛІТИЧНИЙ ВИСНОВОК/.test(промпт)
     && /НЕ перетлумачуй його заново/.test(промпт));
  ok('🔑 і попередній звіт CEO теж — для спадкоємності',
     /ПОПЕРЕДНІЙ ЗВІТ CEO/.test(промпт));
}

// ── 6. 🔴 ВОРКФЛОВ НЕ ПУШИТЬ ПРОПОЗИЦІЇ В `main` ───────────────────────────
//
// 🔬 ЗАРАДИ ЧОГО, І ЦЕ НЕ ГІПОТЕЗА — ЦЕ СТАЛОСЬ. Перший же прогін агента
// (21.09, run #1) поклав пропозиції агента ПРЯМО в `main`, повз PR. Механіка:
// крок «Commit spend ledger» пушив `HEAD:main`, а HEAD на той момент уже був
// гілкою `ceo/tasks-…`, створеною попереднім кроком. Тобто межа, заради якої
// крок 5 узагалі робився («рішення за людиною»), впала через ПОРЯДОК КРОКІВ.
//
// 🔑 Стережемо саме порядок і права, бо симптом тихий: прогін зелений, а
// реєстр уже змінено без рішення власника.
{
  const yml = readFileSync('.github/workflows/ceo-agent.yml', 'utf-8');

  const iВитрати = yml.indexOf('name: Commit spend ledger');
  const iПропозиції = yml.indexOf('name: Propose tasks');
  ok('прилад знайшов обидва кроки', iВитрати > 0 && iПропозиції > 0,
     `витрати ${iВитрати} · пропозиції ${iПропозиції}`);
  ok('🔴 крок витрат іде ПЕРЕД кроком пропозицій (інакше пуш у main забере гілку з собою)',
     iВитрати < iПропозиції, `витрати ${iВитрати} · пропозиції ${iПропозиції}`);

  // Другий пояс: крок витрат явно стає на main перед комітом.
  const блокВитрат = yml.slice(iВитрати, iПропозиції);
  ok('🛑 і сам крок явно переходить на `main` перед комітом',
     /git checkout main/.test(блокВитрат));

  ok('🔴 воркфлов просить право створювати PR',
     /pull-requests:\s*write/.test(yml));

  // 🛑 Тиха поразка PR — те, з чим ми боремось усюди: невдача мусить червоніти.
  const блокПропозицій = yml.slice(iПропозиції);
  ok('🛑 невдача створення PR НЕ мовчить (крок падає)',
     /raise SystemExit\(1\)/.test(блокПропозицій));
}

// ── 7. 🔴 ОБІРВАНИЙ ЗВІТ НЕ НАЗИВАЄТЬСЯ «ГОТОВО» ───────────────────────────
//
// 🔬 ВАДА ЗАМІРЯНА, НЕ ПРИДУМАНА (прогін 21.09): відповідь уперлась у стелю
// довжини 4000, звіт обірвався на третьому пункті вектора — пʼятий блок і
// розділ «ЗАВДАННЯ-ДО-РЕЄСТРУ» не були написані взагалі. У лозі це виглядало
// як «агент нічого не запропонував», а в базі — як `стан = готово`, тобто
// Вова побачив би піврозбір із зеленою позначкою. Клас той самий, що B-33.
//
// 🔑 Прогін справжнього `main()` з підміненим `urlopen` — сцена в
// `tests/_ceo-scene.py`. Міряємо РІШЕННЯ агента, а не наявність рядків у коді.
{
  const сцена = (випадок) => JSON.parse(execFileSync('python3',
    ['tests/_ceo-scene.py', випадок],
    { encoding: 'utf-8', timeout: 60000,
      // 🛑 Свій кеш байткоду: стале `scripts/__pycache__` вже показало цьому
      //    стендові СТАРИЙ код і лишило мутацію зеленою.
      env: { ...process.env, ANTHROPIC_API_KEY: 'стенд-не-справжній-ключ',
             PYTHONPYCACHEPREFIX: mkdtempSync(join(tmpdir(), 'cstl-py-')) } })
    .trim().split('\n').pop());

  const обірваний = сцена('обірвано');
  const цілий     = сцена('готово');

  ok('🔴 обірваний звіт лягає в базу зі станом «обірвано», а не «готово»',
     обірваний.стан === 'обірвано', обірваний.стан);
  ok('🛑 і крок ПАДАЄ — тихий зелений тут і був вадою',
     обірваний.код === 1, 'код виходу ' + обірваний.код);
  ok('🔑 причина названа словами, а не самим статусом',
     /стел[юі] довжини/.test(обірваний.причина || ''), (обірваний.причина || '—').slice(0, 60));
  // 🛑 Пів-рядка в реєстрі гірше, ніж порожньо: у обірваному звіті розділ
  //    завдань або відсутній, або недописаний.
  ok('🔴 з обірваного звіту завдання в реєстр НЕ витягуються',
     обірваний.пропозиції === undefined, JSON.stringify(обірваний.пропозиції ?? null));
  ok('🔑 текст усе одно зберігається — половина звіту корисніша за порожнечу',
     обірваний.символів > 0, обірваний.символів + ' символів');

  ok('цілий звіт лишився «готово» і з кодом 0',
     цілий.стан === 'готово' && цілий.код === 0, `${цілий.стан} / ${цілий.код}`);
  ok('🔑 і з нього завдання витягуються, як і раніше',
     Array.isArray(цілий.пропозиції) && цілий.пропозиції.length === 1,
     JSON.stringify(цілий.пропозиції));

  // 📐 Стеля довжини — не думка, а число в запиті до моделі. 4000 виявилось
  //    замало: кирилиця дорога в токенах, звіт на 4822 символи його вичерпав.
  ok('📐 стеля довжини піднята (4000 не вистачило на живому звіті)',
     цілий.стеля_довжини >= 8000, String(цілий.стеля_довжини));
}

done();
