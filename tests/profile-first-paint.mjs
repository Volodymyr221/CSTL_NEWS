//
// 🗣️ СКАРГА ВОВИ: «заходжу в додаток… спочатку підгружає зверху: Добрий день і
// англійською мовою Володимир. Це було моє колись старе ім'я. Я його замінив ще
// десь місяць назад… І без фотографії. Тобто воно так секунду-дві і підгружає
// моє нове ім'я». Вимога окремо: «не просто латкою… виправити максимально
// технічно».
//
// 🔬 ЩО САМЕ СТЕРЕЖЕ ЦЕЙ СТЕНД. Імʼя мало ДВА джерела: `profiles.name` (правда,
// але по мережі) і `user_metadata.name` від Google (знімок при ПЕРШОМУ вході,
// але миттєвий, бо лежить у сесії на пристрої). Кеш у памʼяті модуля вмирає з
// закриттям застосунку, тож перший кадр щоразу малював застаріле джерело.
// Лікування — дзеркало `profiles` у `localStorage` під ключем з `uid`, і вивід
// метаданих із ланцюжка для того, чий профіль уже відомий.
//
// 🔑 МІРЯЄМО ПЕРШИЙ КАДР, А НЕ НАЯВНІСТЬ КОДУ. Перевірка «у auth.js є
// localStorage» зеленіла б і тоді, коли кеш пишеться, але не читається; і тоді,
// коли читається, але привітання малюється раніше. Питання одне: ЩО ЛЮДИНА
// БАЧИТЬ у перші секунди. Тому відповідь `profiles` навмисно СПОВІЛЬНЕНА
// (`slow`), і текст знімається ДО її приходу.
//
// 🛑 ЧЕСНА МЕЖА, ЗАПИСАНА ПЕРЕВІРКОЮ №1: на пристрої, де кешу ще немає (перший
// запуск після цієї зміни або новий телефон), старе імʼя один раз усе одно
// зʼявиться. Інакше довелось би показати порожнє привітання людині, яка щойно
// зареєструвалась і в якої рядка `profiles` ще не існує. Ця перевірка стоїть
// тут НАВМИСНО зеленою на обох ревізіях — вона фіксує межу, а не досягнення.
//
// Контроль: BUNDLE_REV=origin/main node tests/profile-first-paint.mjs

import { chromium } from 'playwright';
import { launch, serve, reporter, projectFile } from './_lib.mjs';
import { mockSupabase } from './_board-fixture.mjs';

const { ok, done } = reporter();
const fail = (name, info) => ok(name, false, info);
const REV = process.env.BUNDLE_REV || '';

const СТАРЕ = 'Volodymyr';        // імʼя з метаданих Google — те, що людина ЗМІНИЛА
const НОВЕ  = 'Володимир';        // імʼя з `profiles` — правда
const ФОТО  = 'data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7';
const ME = { id: 'u-me', email: 'me@example.com',
             user_metadata: { name: СТАРЕ, full_name: СТАРЕ } };

const { url, stop } = await serve();
const b = await launch(chromium);
// 🔑 ОДИН контекст на весь прогін — саме він тримає `localStorage` між
// завантаженнями. Новий контекст на кожен «холодний старт» стер би кеш і
// «довів» би, що фікс не працює.
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true,
  hasTouch: true, serviceWorkers: 'block', locale: 'uk-UA' });
const p = await ctx.newPage();

await mockSupabase(p,
  { posts: [], comments: [], announcements: [], pages: [], page_posts: [],
    threads: [], messages: [], thread_user_state: [],
    profiles: [{ uid: 'u-me', name: НОВЕ, avatar_url: ФОТО, email: 'me@example.com' }] },
  { user: ME,
    profiles: [{ uid: 'u-me', name: НОВЕ, avatar_url: ФОТО }],
    // ⏳ Без цієї затримки розриву не існує: заглушка відповідає миттєво, і
    // навіть зламаний код «встигав» би показати правильне імʼя.
    slow: { profiles: 2500 } });
await p.route(/^https?:\/\/(?!127\.0\.0\.1)[^/]+\//, r => r.abort());
// 🔴 Контроль: підміняємо ЗІБРАНИЙ файл ревізією без фікса. Вада лежить у логіці,
// тож `BUNDLE_REV` тут достатньо — стилів вона не торкається.
if (REV) {
  const body = projectFile('bundle.js', REV);
  await p.route('**/bundle.js', r => r.fulfill({ contentType: 'text/javascript; charset=utf-8', body }));
}

// Знімок того, що бачить людина: текст привітання + чи є у кнопці кабінету ФОТО.
const кадр = () => p.evaluate(() => {
  const hi = document.querySelector('.hm-hi');
  const btn = document.querySelector('[data-account-btn]');
  return {
    привітання: hi ? hi.textContent.trim() : null,
    фото: !!(btn && btn.querySelector('img')),
  };
});

// Один «холодний старт»: перезавантаження сторінки і зняття кадру ДО того, як
// прийде повільна відповідь `profiles`.
const холодний = async () => {
  await p.goto(url, { waitUntil: 'domcontentloaded' });
  await p.waitForTimeout(1100);
  await p.evaluate(() => { document.getElementById('splash')?.remove();
                           document.querySelector('.consent-accept')?.click(); });
  await p.waitForTimeout(200);
  return кадр();
};

// ── 1. Перший запуск: кешу ще немає ─────────────────────────────────────────
const перший = await холодний();
ok('ПРИЛАД: привітання є на сцені', перший.привітання !== null, String(перший.привітання));
// 🛑 МЕЖА, А НЕ ДОСЯГНЕННЯ (див. шапку). Зелена на обох ревізіях навмисно.
ok('МЕЖА: без кешу перший кадр бере імʼя входу — інакше новачок побачив би порожнє привітання',
   перший.привітання === null || перший.привітання.includes(СТАРЕ) || перший.привітання.includes(НОВЕ),
   `«${перший.привітання}»`);

// ── 2. Відповідь бази прийшла — правда на екрані ────────────────────────────
await p.waitForTimeout(2600);
const післяМережі = await кадр();
післяМережі.привітання && післяМережі.привітання.includes(НОВЕ)
  ? ok(`після відповіді бази у привітанні правдиве імʼя («${післяМережі.привітання}»)`, true)
  : fail('після відповіді бази у привітанні правдиве імʼя', `«${післяМережі.привітання}»`);

// ── 3. 🔴 ГОЛОВНЕ: другий холодний старт ────────────────────────────────────
// Кеш уже є. Перший кадр мусить показати ПРАВДУ, не чекаючи на мережу.
const другий = await холодний();
другий.привітання && другий.привітання.includes(НОВЕ) && !другий.привітання.includes(СТАРЕ)
  ? ok(`🔴 ПЕРШИЙ КАДР показує правдиве імʼя ще ДО відповіді бази («${другий.привітання}»)`, true)
  : fail('🔴 ПЕРШИЙ КАДР показує правдиве імʼя ще ДО відповіді бази',
         `«${другий.привітання}» — старе імʼя ще живе як джерело`);

другий.фото
  ? ok('🔴 ПЕРШИЙ КАДР показує фото профілю (друга половина скарги)', true)
  : fail('🔴 ПЕРШИЙ КАДР показує фото профілю', 'кнопка кабінету без <img>');

// ── 4. Кеш ключується акаунтом (правило `account-scope`) ────────────────────
const ключі = await p.evaluate(() => Object.keys(localStorage).filter(k => k.startsWith('cstl_profile')));
ключі.includes('cstl_profile:u-me')
  ? ok('кеш профілю ключується uid («cstl_profile:u-me»)', true)
  : fail('кеш профілю ключується uid', ключі.join(', ') || 'ключів немає');
ключі.every(k => k !== 'cstl_profile')
  ? ok('безіменного (спільного) ключа профілю немає', true)
  : fail('безіменного (спільного) ключа профілю немає', 'є «cstl_profile» без uid');

// ── 5. 🛑 ЧУЖИЙ КЕШ НЕ ПІДХОПЛЮЄТЬСЯ ────────────────────────────────────────
// Другий акаунт на тому самому телефоні не сміє побачити чуже імʼя. Сіємо запис
// під ЧУЖИМ uid і перевіряємо, що привітання його ігнорує.
await p.evaluate(() => localStorage.setItem('cstl_profile:u-other',
  JSON.stringify({ name: 'Стороння Людина', avatar_url: null })));
const зЧужим = await холодний();
зЧужим.привітання && !зЧужим.привітання.includes('Стороння')
  ? ok('🛑 запис іншого акаунта на цьому ж пристрої НЕ підхоплюється', true)
  : fail('🛑 запис іншого акаунта на цьому ж пристрої НЕ підхоплюється', `«${зЧужим.привітання}»`);

// ── 6. 🔴 НОВАЧОК БЕЗ АНКЕТИ НЕ СМІЄ СТАТИ «ЖИТЕЛЕМ» ────────────────────────
// 🛑 ЦЯ ПЕРЕВІРКА ЗАВЕДЕНА ПІСЛЯ ВЛАСНОЇ ПОМИЛКИ, ЯКА ДОЇХАЛА ДО ПРОДУ.
// Перша редакція фікса вимикала метадані за САМОЮ НАЯВНІСТЮ запису в кеші. А
// `getProfile()` пише запис і тоді, коли рядка в `profiles` немає — тобто
// людина, яка щойно зареєструвалась і ще не заповнила анкету, діставала
// «Житель» замість свого Google-імені. Я вбив рівно той випадок, заради якого
// метадані й лишались у ланцюжку. Спіймав `sidebar-menu`, уже після деплою.
// 🔑 Правило, яке ця перевірка тримає: кеш перебиває метадані ЛИШЕ КОЛИ В
// НЬОМУ Є ІМʼЯ. Запис без імені — це «профіль без імені», і для нього
// метадані і є найкраща відповідь.
await p.evaluate(([k, v]) => localStorage.setItem(k, v),
  ['cstl_profile:u-me', JSON.stringify({ name: null, avatar_url: null })]);
const безАнкети = await холодний();
безАнкети.привітання && безАнкети.привітання.includes(СТАРЕ)
  ? ok('🔴 порожній профіль НЕ глушить імʼя входу (новачок не стає «Жителем»)', true)
  : fail('🔴 порожній профіль НЕ глушить імʼя входу (новачок не стає «Жителем»)',
         `«${безАнкети.привітання}» — очікувалось імʼя з метаданих`);

await ctx.close(); await b.close(); await stop();
done();
