// Стенд: ЗБИРАЧ ФАКТІВ ДЛЯ CEO НЕ ВИДАЄ ТИШУ ЗА НУЛЬ (21.09.2026).
//
// 🔴 ЗАРАДИ ЧОГО. Агент CEO відповідає на питання «де ми проти курсу», і
// найдорожча помилка тут навіть не «порахував неправильно», а **прийняв тишу
// джерела за факт про світ**. Нуль читається як «нічого не сталось» і веде до
// рішень; «не заміряно» — твердження про нас, і воно веде до ремонту.
// 🔬 Клас вади не вигаданий: агент новин мовчав через вичерпаний бюджет два
// тижні, а в кабінеті це виглядало як порожня черга чернеток — тобто як факт
// про роботу, а не як зламаний вимірювач. Вова помітив це сам.
//
// 🔑 ЩО ТУТ СТЕРЕЖЕТЬСЯ:
//   1. без доступу до бази розділ аналітики каже «не заміряно», а НЕ нуль;
//   2. числа, які збирач бере з git і файлів, збігаються з джерелом — тобто
//      підкидаємо ВІДОМЕ значення і вимагаємо, щоб вимір його побачив
//      (`HOT_RULES`: контроль не привʼязувати до стану гілки);
//   3. назви полів не брешуть: «не в main» і «не на GitHub» — різні числа.
import { execFileSync } from 'child_process';
import { readdirSync, mkdtempSync } from 'fs';
import { tmpdir } from 'os';
import { join } from 'path';
import { reporter } from './_lib.mjs';

const { ok, done } = reporter();

// 🛑 ВЛАСНИЙ КЕШ БАЙТКОДУ. Стале `scripts/__pycache__` вже показало цьому
// стендові СТАРИЙ код агента (мутація лишилась «зеленою» після відкату).
// Окрема тека на прогін означає, що python щоразу компілює з джерела.
const СВІЖИЙ_PYTHON = { ...process.env, PYTHONPYCACHEPREFIX: mkdtempSync(join(tmpdir(), 'cstl-py-')) };

function збирач(env = {}) {
  const out = execFileSync('python3', ['scripts/ceo_facts.py', '--json'],
    { encoding: 'utf-8', env: { ...process.env, ...env }, timeout: 60000 });
  return JSON.parse(out);
}

// Без ключів бази — саме той запуск, що робитиме більшість сесій.
const факти = збирач({ SUPABASE_URL: '', SUPABASE_SERVICE_KEY: '', SUPABASE_SERVICE_ROLE_KEY: '' });

// ── 1. 🔴 ТИША НЕ СТАЄ НУЛЕМ ───────────────────────────────────────────────
{
  const а = факти.аналітика || {};
  ok('🔴 без доступу до бази аналітика каже «не заміряно»',
     а.стан === 'не заміряно', JSON.stringify(а).slice(0, 120));
  // 🛑 Зустрічна межа: мало сказати «не заміряно» — не можна ПРИ ЦЬОМУ
  // надрукувати числа, бо око читає число, а не примітку біля нього.
  const числа = Object.entries(а).filter(([, v]) => typeof v === 'number');
  ok('🛑 і при цьому НЕ друкує жодного числа поруч',
     числа.length === 0, JSON.stringify(числа));
  ok('🔑 і каже ЧОМУ (інакше нема що ремонтувати)',
     typeof а.чому === 'string' && а.чому.length > 10, а.чому || '(порожньо)');
}

// ── 2. 🔴 ЧИСЛА ЗБІГАЮТЬСЯ З ДЖЕРЕЛОМ ──────────────────────────────────────
//
// Підкидаємо ВІДОМЕ значення і вимагаємо, щоб вимір його побачив. Прилад, який
// рахує сам по собі і ні з чим не звіряється, зеленіє над будь-чим.
{
  const справжніх = readdirSync('tests')
    .filter(f => f.endsWith('.mjs') && f !== 'run.mjs' && !f.startsWith('_')).length;
  ok('🔴 кількість стендів рахується ТИМ САМИМ правилом, що `tests/run.mjs`',
     факти.виробництво.стендів_у_проєкті === справжніх,
     `збирач ${факти.виробництво.стендів_у_проєкті} · насправді ${справжніх}`);

  const гілка = execFileSync('git', ['rev-parse', '--abbrev-ref', 'HEAD'],
    { encoding: 'utf-8' }).trim();
  ok('гілка названа правильно', факти.виробництво.гілка === гілка,
     `${факти.виробництво.гілка} проти ${гілка}`);

  const неВmain = execFileSync('git', ['log', '--oneline', 'HEAD', '^origin/main'],
    { encoding: 'utf-8' }).split('\n').filter(Boolean).length;
  ok('🔴 «комітів не в main» збігається з git',
     факти.виробництво.комітів_не_в_main === неВmain,
     `збирач ${факти.виробництво.комітів_не_в_main} · git ${неВmain}`);
}

// ── 3. 🛑 ДВА РІЗНІ «НЕ ДОЇХАЛО» НЕ ЗЛИТІ В ОДНЕ ───────────────────────────
//
// Перша редакція збирача мала одне поле «незапушених комітів», і воно рахувало
// різницю з `main` — тобто на робочій гілці показувало тривогу там, де все
// гаразд. Число брехало НАЗВОЮ, а це найтихіший вид брехні приладу.
{
  const в = факти.виробництво;
  ok('🛑 «не в main» і «не на GitHub» — окремі поля',
     'комітів_не_в_main' in в && 'комітів_не_на_GitHub' in в,
     Object.keys(в).join(', '));
  ok('🔑 робота, яка існує лише на диску, видна окремим числом',
     в.комітів_не_на_GitHub === 0 || typeof в.комітів_не_на_GitHub === 'number'
       || в.комітів_не_на_GitHub === 'не заміряно',
     String(в.комітів_не_на_GitHub));
}

// ── 4. РОЗДІЛИ НА МІСЦІ ────────────────────────────────────────────────────
//
// 🔑 Порожній розділ гірший за відсутній: він виглядає як відповідь. Те саме
// правило вже стереже пульс (`docs-fresh`).
{
  for (const р of ['виробництво', 'борги', 'контент', 'гроші', 'аналітика']) {
    const з = факти[р];
    ok(`розділ «${р}» не порожній`, !!з && Object.keys(з).length > 0);
  }
  ok('гроші названі за ЧИННИМИ цінами (fair_usd), а не за журнальними',
     факти.гроші.витрачено_usd === 'не заміряно'
     || typeof факти.гроші.витрачено_usd === 'number',
     String(факти.гроші.витрачено_usd));
}

// ── 5. 🔴 АДРЕСА ДО БАЗИ НЕ ЛАМАЄТЬСЯ НА «+» ───────────────────────────────
//
// 🔬 ВАДУ ЗНАЙШОВ САМ АГЕНТ (прогін 21.09): причина «не заміряно» змінилась із
// «немає ключів» на `HTTP 400 Bad Request`. Корінь — мітка часу від
// `isoformat()` має «+00:00», а ПЛЮС в адресі означає ПРОБІЛ, тож база
// отримувала «…517217 00:00» і не могла її розібрати.
//
// 🛑 ПЕРША ВЕРСІЯ ЦІЄЇ ПЕРЕВІРКИ БУЛА БРЕХЛИВА: вона складала адресу ПРЯМО В
// СТЕНДІ й перевіряла саму себе — мутація «поверни склейку рядком» у
// `ceo_facts.py` лишила її зеленою. Спіймала це мутація, не око.
// ➡️ Тепер адресу будує СПРАВЖНЯ `аналітика()`, а сцена
// `tests/_facts-url-scene.py` перехоплює запит на рівні `urlopen` і друкує те,
// що пішло б у мережу.
{
  const сцена = () => JSON.parse(execFileSync('python3',
    ['tests/_facts-url-scene.py'], { encoding: 'utf-8', timeout: 60000, env: СВІЖИЙ_PYTHON }));
  const р = сцена();
  const мітка = р.created_at_як_прочитає_сервер;

  ok('🔴 мітка часу доїжджає до сервера БЕЗ втрат',
     /^gte\.\d{4}-\d{2}-\d{2}T[\d:.]+\+00:00$/.test(мітка), мітка.slice(-26) || '—');
  ok('🛑 і в ній немає пробілу на місці «+»', !/ /.test(мітка), JSON.stringify(мітка.slice(-12)));
  ok('🔑 у самій адресі плюс екранований (%2B), а не голий',
     /%2B/.test(р.адреса) && !/gte\.[^&]*\+/.test(р.адреса), р.адреса.slice(-46));
}

// ── 6. 🔴 ЧИСЛО, ЯКЕ УПЕРЛОСЬ У СТЕЛЮ ФАЙЛУ, ПІДПИСАНЕ ─────────────────────
//
// 🔬 І це теж помітив агент: «усього 400 і за 7 днів 352 — ті самі, що тиждень
// тому; так не буває». Причина не «застиглий лічильник», а стеля
// `MAX_ARTICLES` у парсері: потік Волині/України забиває файл за кілька діб.
// 🛑 Небезпека саме в тому, що число ВИГЛЯДАЄ як обсяг виробництва.
{
  const к = факти.контент || {};
  ok('файл міряється глибиною історії, а не самою кількістю',
     typeof к.глибина_потоку_днів === 'number' || к.глибина_потоку_днів === 'не заміряно',
     String(к.глибина_потоку_днів));
  const мілко = typeof к.глибина_потоку_днів === 'number' && к.глибина_потоку_днів < 7;
  ok('🔴 коли файл тримає менше тижня потоку — про це сказано ПРЯМО',
     !мілко || (typeof к['⚠️'] === 'string' && /НЕ міряє виробництво/.test(к['⚠️'])),
     (к['⚠️'] || '—').slice(0, 80));
  ok('🔑 Громада рахується окремо — у неї власна квота, її число чесне',
     typeof к.громади_у_файлі === 'number', String(к.громади_у_файлі));
}

done();
