// Стенд: АДМІНКА КАЖЕ ПРАВДУ ПРО ПУБЛІКАЦІЮ І ПРО ПРИЗНАЧЕННЯ.
//
// 🔴 ЗАРАДИ ЧОГО (скарга Вови 28.08). «Я натиснув хвилин 20 назад публікація, і воно
// постійно висить, виходить на сайт хвилину-дві, і так з кожною новиною. І незрозуміло,
// куди воно вийде.»
//
// 📐 ЗАМІРЯНО ТОГО Ж ДНЯ, і виявилось, що вада не у швидкості, а в БРЕХНІ:
//   • `publish-now` повертає `{nudged:false, reason:'Немає секрету GITHUB_DISPATCH_TOKEN'}`
//     — тобто синк не будиться взагалі. Відповідь ковтав `catch (_)`;
//   • запасний розклад мертвий: `cms-sync` востаннє відпрацював о 01:03 при розкладі
//     «кожні 15 хвилин», тобто мовчав 17 годин;
//   • а картка весь цей час бадьоро писала «виходить на сайт (1-2 хв)».
//
// 🔑 ЩО МІРЯЄМО. Не наявність рядка в файлі, а ПОВЕДІНКУ двох чистих функцій адмінки:
// що вони віддають на конкретних даних. Обидві не чіпають мережу, тож стенд швидкий і
// не залежить від стану бази.
//
// 🛑 Функції живуть усередині `<script>` в `admin.html` (адмінка навмисно одним файлом,
// без збірки). Тому дістаємо їх у справжньому браузері з реальної сторінки, а не
// копіюємо в стенд: копія розійшлася б із оригіналом при першій же правці.
import { chromium } from '@playwright/test';
import { launch, reporter, serve } from './_lib.mjs';

const { ok, done } = reporter();
const { url, stop } = await serve();
const b = await launch(chromium);
const p = await b.newPage();
const помилки = [];
p.on('pageerror', e => помилки.push(e.message));
await p.goto(url + '/admin.html', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(400);

// ── 1. МІТКА ОЧІКУВАННЯ КАЖЕ ПРАВДУ ────────────────────────────────────────
const мітки = await p.evaluate(() => {
  const хвилинТому = хв => new Date(Date.now() - хв * 60000).toISOString();
  const взяти = хв => міткаОчікування({ updated_at: хвилинТому(хв) });
  return { свіжа: взяти(2), майже: взяти(9), застрягла: взяти(20), доба: взяти(1000) };
});

ok('🔴 щойно натиснуто — мітка показує РЕАЛЬНІ хвилини, а не обіцянку',
   /2 хв/.test(мітки.свіжа) && !/1-2 хв/.test(мітки.свіжа), мітки.свіжа.slice(0, 90));
ok('до 10 хвилин — спокійне «чекає на синк»',
   /чекає на синк/.test(мітки.майже) && !/ЗАСТРЯГЛО/.test(мітки.майже));
ok('🛑 понад 10 хвилин — прямо каже ЗАСТРЯГЛО, а не «хвилина-дві»',
   /ЗАСТРЯГЛО/.test(мітки.застрягла) && /20 хв/.test(мітки.застрягла),
   мітки.застрягла.slice(0, 70));
ok('годинне очікування показується годинами, а не сотнями хвилин',
   /16 год/.test(мітки.доба), мітки.доба.match(/чекає [^<]*/)?.[0] || '—');
ok('🔑 у мітці лишається ПІДКАЗКА, куди дивитись причину',
   /GITHUB_DISPATCH_TOKEN/.test(мітки.застрягла) && /README_publish_now/.test(мітки.застрягла));

// ── 2. КОЖНА КАРТКА КАЖЕ, КУДИ ВОНА ВИЙДЕ ──────────────────────────────────
// 🔴 Пряме замовлення Вови: «підпиши, що куди публікується».
const куди = await p.evaluate(() => ({
  історія:    призначення({ category: 'Історія та краєзнавство', type: 'news' }),
  краєзнав:   призначення({ category: 'краєзнавство', type: 'news' }),
  новина:     призначення({ category: 'Оборона та мобілізація', type: 'news' }),
  подія:      призначення({ category: 'Подія', type: 'event' }),
  свято:      призначення({ category: 'Свято', type: 'holiday' }),
  безКатегорії: призначення({ type: 'news' }),
}));

ok('🔴 історичний матеріал підписаний «→ Історія Громади», а НЕ «→ Новини»',
   /Історія Громади/.test(куди.історія.текст), куди.історія.текст);
ok('«краєзнавство» теж веде в історичну спільноту (категорія пишеться по-різному)',
   /Історія Громади/.test(куди.краєзнав.текст), куди.краєзнав.текст);
ok('звичайна новина підписана «→ Новини»',
   /Новини/.test(куди.новина.текст), куди.новина.текст);
ok('подія і свято мають свої призначення',
   /Події/.test(куди.подія.текст) && /Свята/.test(куди.свято.текст));
// 🛑 Матеріал без категорії не має мовчати: за замовчуванням це новина, і так і
// підписано. Порожня мітка була б гіршою за неточну — саме на неї Вова і скаржився.
ok('матеріал без категорії теж має підпис (порожнеча — це та сама вада)',
   !!куди.безКатегорії.текст, куди.безКатегорії.текст);
ok('у кожного призначення є підказка, чому саме туди',
   Object.values(куди).every(п => (п.підказка || '').length > 20));

// ── 3. КОНТРОЛЬ: стенд мусить уміти впасти ─────────────────────────────────
// Якби мітка лишилась старою обіцянкою, перша ж перевірка почервоніла б.
ok('КОНТРОЛЬ: стара обіцянка «1-2 хв» справді не пройшла б перевірку',
   !/1-2 хв/.test(мітки.свіжа) && /1-2 хв/.test('⏳ виходить на сайт (1-2 хв)'));

ok('жодної помилки в консолі адмінки', помилки.length === 0, помилки.join(' · ').slice(0, 120) || '—');

await b.close(); await stop();
done();
