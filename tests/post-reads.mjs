// Стенд: «ПРОЧИТАЛИ N» — ЧИСЛО, ЯКЕ БАЧИТЬ ЛИШЕ АВТОР (01.10.2026).
//
// 🔴 ЗАРАДИ ЧОГО ВІН ІСНУЄ. Друга половина цілі курсу — живі спільноти з живими
// адмінами, і 🗣️ «для них важливо те, щоб вони бачили що це не дарма, що їх
// читають». Події читання застосунок пише з 21.09, згортання стоїть у розкладі,
// а ПОКАЗУ не було: адмін на старті бачить нуль лайків і вирішує «мене ніхто не
// читає» саме тоді, коли його вже читають. Аудит 30.09 назвав це найдешевшим
// засобом утримання адмінів з усього плану запуску.
//
// 🔑 ЩО МІРЯЄМО — ТЕ, ЩО ВИДНО НА ЕКРАНІ, а не наявність функції в коді. Тут
// ціна помилки не в тому, що рядка немає, а в тому, що він з'явиться НЕ ТАМ:
//
//   • число по ЧУЖОМУ допису — зі Стрічки вийшло б змагання, і це не та
//     мотивація, яку просить курс;
//   • «прочитали 0» — рядок, що робить рівно протилежне задуманому: гасить
//     автора замість підтримати;
//   • число на ЧЕРНЕТЦІ — її ще ніхто не бачив, тож «прочитали» там безглузде.
//
// 🛑 ЗАГЛУШКА ТУТ ЗВУЖУЄ ПРАВА ТАК САМО, ЯК ПРОД (`post_read_counts` віддає
// числа лише авторові або команді сторінки). Саме тому перевірка 4 доводить
// ДВА замки одразу: що сервер не віддав чужого числа і що рендер його не
// намалював. Добріша заглушка зеленіла б над кодом, який показує чуже.
import { chromium } from 'playwright';
import { launch, serve, reporter } from './_lib.mjs';
import { mockSupabase } from './_board-fixture.mjs';

const { ok, done } = reporter();

const Я = { id: 'uid-me', email: 'me@example.com', user_metadata: { full_name: 'Вова' } };
const ЗАРАЗ = Date.now();

// Сцена: сторінка 4 — МОЯ (я в її команді), сторінка 9 — чужа.
const допис = (id, page_id, зайве = {}) => ({
  id, page_id, author_uid: 'u-page',
  text: `Допис ${id} — кілька слів, щоб картка мала висоту і її було видно.`,
  photos: [], created_at: new Date(ЗАРАЗ - id * 6e4).toISOString(),
  ts: ЗАРАЗ - id * 6e4, status: 'published', ...зайве,
});

const СЦЕНА = {
  posts: [], announcements: [], profiles: [],
  pages: [
    { id: 4, name: 'Олицька міська рада', verified: true },
    { id: 9, name: 'Сусідня спільнота' },
  ],
  page_posts: [
    допис(501, 4),                            // моя сторінка, читачі є
    допис(502, 4),                            // моя сторінка, читачів нуль
    допис(503, 4, { status: 'draft' }),       // моя чернетка, читачі «є»
    допис(504, 9),                            // ЧУЖА сторінка, читачів багато
  ],
  page_admins: [{ page_id: 4, uid: Я.id, role: 'owner' }],
  content_reads: [
    { post_id: 501, 'людей': 12 },
    { post_id: 502, 'людей': 0 },
    { post_id: 503, 'людей': 7 },
    { post_id: 504, 'людей': 50 },
  ],
};

const { url, stop } = await serve();
const b = await launch(chromium);

async function сцена(хто) {
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true,
                                   hasTouch: true, serviceWorkers: 'block' });
  const p = await ctx.newPage();
  await mockSupabase(p, СЦЕНА, хто ? { user: хто } : {});
  await p.route('**://api.open-meteo.com/**', r => r.abort());
  await p.goto(url, { waitUntil: 'domcontentloaded' });
  await p.waitForTimeout(2600);
  await p.evaluate(() => document.querySelector('.consent-accept')?.click());
  await p.waitForTimeout(1200);
  // Стрічка — друга вкладка. Без переходу картки взагалі не побудовані.
  await p.evaluate(() => window.switchTab && window.switchTab('feed'));
  await p.waitForTimeout(1600);
  return { ctx, p };
}

// Текст рядка «Прочитали …» на картці конкретного допису (або null).
const рядок = (p, id) => p.evaluate((i) => {
  const card = document.querySelector(`.fd-card[data-post="${i}"]`);
  if (!card) return '__КАРТКИ_НЕМА__';
  const el = card.querySelector('.fd-reads');
  return el ? el.textContent.trim() : null;
}, id);

// ── 1. КОНТРОЛЬ ПЕРШОГО ПОРЯДКУ: НА СВОЄМУ ДОПИСІ РЯДОК Є ──────────────────
// Стоїть першим саме як контроль. Усі наступні перевірки — про те, де рядка
// БУТИ НЕ МАЄ; без цієї вони зеленіли б над кодом, де рядка немає ніде, тобто
// показували б не межу, а власну сліпоту.
const { ctx: c1, p: p1 } = await сцена(Я);
const свій = await рядок(p1, 501);
ok('🔴 контроль: на СВОЄМУ допису рядок «Прочитали 12» видно',
   !!свій && /Прочитали\s*12/.test(свій), `текст: ${JSON.stringify(свій)}`);

// ── 2. НУЛЬ НЕ ПОКАЗУЄМО ВЗАГАЛІ ───────────────────────────────────────────
// «Прочитали 0» гасить автора — це рівно протилежне тому, заради чого рядок
// заведено. Поки читачів немає, порожнє місце чесніше за нуль.
const нуль = await рядок(p1, 502);
ok('🛑 «прочитали 0» не показуємо — рядка на такому допису немає',
   нуль === null, `текст: ${JSON.stringify(нуль)}`);

// ── 3. НА ЧЕРНЕТЦІ РЯДКА НЕМА ──────────────────────────────────────────────
// Чернетку ще ніхто не бачив, крім автора: «прочитали» там безглузде, і
// число 7 у сцені стоїть саме для того, щоб це спіймати.
const чернетка = await рядок(p1, 503);
ok('🛑 на чернетці рядка немає, хоч число в сцені є',
   чернетка === null, `текст: ${JSON.stringify(чернетка)}`);

// ── 4. ЧУЖИЙ ДОПИС: ЗАПИТ ПО НЬОГО НЕ ЙДЕ ВЗАГАЛІ ──────────────────────────
//
// 🔴 ЦЕЙ РОЗДІЛ ПЕРЕПИСАНО ПІСЛЯ МУТАЦІЇ, І САМА ІСТОРІЯ ВАРТА РЯДКА.
// Спершу тут стояла одна перевірка «на чужому допису рядка немає», і вона була
// зелена. Мутація «знято умову `мійДопис` у рендері» лишила її ЗЕЛЕНОЮ — тобто
// перевірка проходила з НЕПРАВИЛЬНОЇ причини і не стерегла нічого.
// 🔑 Справжнє звуження стоїть РАНІШЕ за рендер: `loadData` питає числа лише по
// своїх дописах, тож чуже число в застосунок просто не приїжджає. Отже міряти
// треба ЗАПИТ, а не наслідок. Умова в рендері лишається другим замком на
// випадок, якщо завантаження колись розширять.
// 📐 Три замки разом: клієнт не питає чужого · сервер не віддав би
// (`post_read_counts`) · рендер не намалював би.
const виклики = await p1.evaluate(() => (window.__cstlRpcCallsLog || [])
  .filter(r => r.fn === 'post_read_counts').map(r => (r.args && r.args.p_ids) || []));
const усіІд = виклики.flat();
ok('🔴 числа читань просять ЛИШЕ по своїх дописах — чужого id у запиті немає',
   виклики.length > 0 && !усіІд.includes(504) && усіІд.includes(501),
   `p_ids: ${JSON.stringify(виклики)}`);

const чужий = await рядок(p1, 504);
ok('🛑 і на екрані чужого допису рядка немає', чужий === null, `текст: ${JSON.stringify(чужий)}`);
await c1.close();

// ── 5. ГІСТЬ НЕ БАЧИТЬ ЖОДНОГО РЯДКА ───────────────────────────────────────
// Читачеві це число не потрібне, і публічний показ зробив би зі Стрічки
// змагання. Гість не ввійшов, тож і питати нема за кого.
const { ctx: c2, p: p2 } = await сцена(null);
const всіРядки = await p2.evaluate(() => document.querySelectorAll('.fd-reads').length);
ok('🛑 гість не бачить «Прочитали» ніде', всіРядки === 0, `рядків на екрані: ${всіРядки}`);
await c2.close();

await b.close(); await stop();
done();
