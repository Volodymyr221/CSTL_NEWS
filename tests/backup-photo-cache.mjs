р = прогін();
перевірка('крок не впав через один збій', 0, р.код);
перевірка('в архіві те, що дійшло', 1, файлів('out/storage'));
перевірка('🛑 обрізок не осів у кеші', 'нема', є('.photo-cache/files/zzz.jpg'));

rmSync(СТЕНД, { recursive: true, force: true });

console.log('');
if (червоних === 0) {
  console.log(`✅ ${зелених}/${зелених + червоних} перевірок пройдено`);
} else {
  console.log(`❌ ${зелених}/${зелених + червоних} перевірок пройдено`);
  process.exit(1);
}
