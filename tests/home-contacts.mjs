await p.waitForTimeout(300);

const зріз = await p.evaluate(() => {
  const c = document.getElementById('cm-contacts-content');
  const root = c;
  const вузли = [...c.querySelectorAll('.hm-ct, .hm-sos-b')];
  const контакти = [...c.querySelectorAll('.hm-ct')];

  // Емодзі шукаємо у ТЕКСТІ вузлів. Діапазони — символи-піктограми і
  // варіаційний селектор; літери, цифри й пунктуація сюди не потрапляють.
  const ЕМОДЗІ = /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}\u{2190}-\u{21FF}\u{2B00}-\u{2BFF}]/u;
  const текст = c.innerText || '';

  return {
    контактів: контакти.length,
    груп: c.querySelectorAll('.hm-cgrp').length,
    екстрених: c.querySelectorAll('.hm-sos-b').length,
    // Порядок читаємо з DOM: CSS міг би намалювати навпаки.
    громадаПерша: (() => {
      const пг = вузли.findIndex(n => n.classList.contains('hm-ct'));
      const пе = вузли.findIndex(n => n.classList.contains('hm-sos-b'));
      return пг !== -1 && пе !== -1 && пг < пе;
    })(),
    емодзіВТексті: (текст.match(ЕМОДЗІ) || [])[0] || '',
    // Кожен контакт мусить мати ВЕКТОРНИЙ значок.
    зіЗначком: контакти.filter(n => n.querySelector('.hm-ct-ic svg')).length,
    // Кнопки швидких дій теж мають бути векторні, а не гліфи «⧉» / «📍».
    діїВектор: [...c.querySelectorAll('.hm-ct-act')].every(b => !!b.querySelector('svg')),
    дій: c.querySelectorAll('.hm-ct-act').length,
    // Ціль пальця: 44px за посібником Apple.
    цілі44: [...c.querySelectorAll('.hm-ct-act')].every(b => b.getBoundingClientRect().width >= 43),
    // Значок не сміє стискатись у смужку при довгій назві.
    значкиЦілі: [...c.querySelectorAll('.hm-ct-ic')].every(n => n.getBoundingClientRect().width >= 33),
    // Тап по контакту веде в дзвінок.
    telУсі: contactsTel(c),
    // 🔴 01.09 — ДРУГИЙ НОМЕР (замовлення Вови «давай два, але компактне і не
    // таке широке»). Стережемо три речі, і кожна куплена заміром:
    //   • ширина карток НЕ змінилась (другий номер іде вниз, а не поруч);
    //   • цифри другого номера стоять РІВНО під першим — перша редакція мала
    //     значок трубки, і він вирівнювався сам, а цифри зʼїжджали на 18px;
    //   • ціль пальця ≥ 34px — перший замір дав 22px.
    другий: (() => {
      const a = root.querySelector('.hm-ct-alt');
      if (!a) return null;
      const картка = a.closest('.hm-ct');
      const перший = картка.querySelector('.hm-ct-phone');
      const rng = document.createRange(); rng.selectNodeContents(a.lastChild);
      return {
        tel: (a.getAttribute('href') || '').startsWith('tel:'),
        висота: Math.round(a.getBoundingClientRect().height),
        рівно: Math.round(rng.getBoundingClientRect().left)
             === Math.round(перший.getBoundingClientRect().left),
      };
    })(),
    // ─────────────────────────────────────────────────────────────────────
    // 🔴 01.09 «c» — ТРИ ПРЕТЕНЗІЇ ВОВИ ПО ЦЬОМУ Ж БЛОКУ. Кожна тут не тому, що
    // «варто перевірити», а тому, що ЗАМІРЯНА на живих вузлах і полагоджена.
    //
    // 🛑 ЧОМУ ЦЕ ВЗАГАЛІ ЗЛАМАЛОСЬ. Вада (2) — регрес МОГО Ж PR #1134 добою
    // раніше: обгортка `.hm-ct-row` не мала `flex-grow`. І сімнадцять зелених
    // перевірок цього самого стенда її НЕ ПОБАЧИЛИ, бо жодна не питала «а де
    // саме стоїть кнопка». Тобто дірка була не в коді, а в мірці.
    // ⚠️ Ще підступніше: на трьох картках із адресою кнопки стояли рівно
    // ВИПАДКОВО — довга адреса переносила рядок, вміст упирався в максимум, і
    // край збігався з краєм картки. Тому перевіряти треба ВСІ картки разом, а
    // не «одну показову»: на одній картці вада невидима в принципі.
    // ─────────────────────────────────────────────────────────────────────

    // (2) «щоб копіювати було під копіювати, а пін під піном».
    // Заміряно ДО фіксу: «копіювати» мало ТРИ різні x — 267 (картки з адресою),
    // 294.7 (Соцзахист), 249.2 (Волиньобленерго).
    стовпціДій: (() => {
      const x = мітка => [...root.querySelectorAll('.hm-ct')]
        .map(k => k.querySelector(`.hm-ct-act[aria-label*="${мітка}"]`))
        .filter(Boolean)
        .map(b => Math.round(b.getBoundingClientRect().left));
      const копі = x('Копіювати'), піни = x('карті');
      return {
        копіювати: копі, пін: піни,
        копіРівно: копі.length > 1 && new Set(копі).size === 1,
        пінРівно: піни.length > 1 && new Set(піни).size === 1,
        // Пін і «копіювати» — РІЗНІ стовпці, інакше «рівно» вийшло б і тоді,
        // коли всі кнопки просто злиплись в одну купу.
        різніСтовпці: копі.length && піни.length && копі[0] !== піни[0],
      };
    })(),

    // (1) «номер має бути під номером… далі вулиця Замкова, 17».
    // Заміряно ДО фіксу на картці ЦНАПу: name → phone → АДРЕСА → phone2.
    порядокДругого: (() => {
      const alt = root.querySelector('.hm-ct-alt');
      if (!alt) return null;
      const k = alt.closest('.hm-ct');
      const y = el => el ? el.getBoundingClientRect().top : null;
      const перший = k.querySelector('.hm-ct-main');
      const мета = k.querySelector('.hm-ct-meta');
      return {
        підПершим: y(alt) > y(перший),
        // Головне: адреса ПІСЛЯ другого номера, а не між номерами.
        адресаНижче: мета ? y(мета) > y(alt) : null,
      };
    })(),

    // (3) «іконки… відцентрувати вертикально, по центру самого тексту».
    // Заміряно ДО фіксу: на картці ЦНАПу значок і обидві кнопки стояли на
    // −16.0px від центру картки (центрувались усередині `.hm-ct-row`, а рядок
    // другого номера лежав поза нею).
    центри: [...root.querySelectorAll('.hm-ct')].map(k => {
      const c2 = el => { const r = el.getBoundingClientRect(); return r.top + r.height / 2; };
      const значок = k.querySelector('.hm-ct-ic');
      const дії = [...k.querySelectorAll('.hm-ct-act')];
      return {
        значок: Math.abs(c2(значок) - c2(k)),
        найгірша: дії.reduce((m, b) => Math.max(m, Math.abs(c2(b) - c2(k))), 0),
      };
    }),

    ширинаОднакова: (() => {
      const ш = [...root.querySelectorAll('.hm-ct')]
        .map(x => Math.round(x.getBoundingClientRect().width));
      return new Set(ш).size === 1;
    })(),
    // Нічого не вилазить за правий край екрана.
    влазить: [...c.querySelectorAll('.hm-ct, .hm-sos-b')]
      .every(n => n.getBoundingClientRect().right <= window.innerWidth + 1),
  };

  function contactsTel(root) {
    const посилання = [...root.querySelectorAll('.hm-ct-main')];
    return посилання.length > 0 && посилання.every(a => (a.getAttribute('href') || '').startsWith('tel:'));
  }
});

ok('контакти громади намальовані', зріз.контактів >= 4, `${зріз.контактів}`);
ok('екстрені служби намальовані', зріз.екстрених >= 3, `${зріз.екстрених} плиток`);
ok('🔴 №1 — телефони громади СТОЯТЬ ПЕРЕД екстреними', зріз.громадаПерша);
ok('🔴 №2 — при малій кількості груп немає (пласко)',
   зріз.контактів < 9 ? зріз.груп === 0 : зріз.груп > 0,
   `${зріз.контактів} контактів / ${зріз.груп} груп`);
ok('🔴 №3 — у блоці НЕМАЄ жодного емодзі', зріз.емодзіВТексті === '',
   зріз.емодзіВТексті ? `знайдено «${зріз.емодзіВТексті}»` : 'чисто');
ok('кожен контакт має векторний значок', зріз.зіЗначком === зріз.контактів,
   `${зріз.зіЗначком}/${зріз.контактів}`);
ok('швидкі дії — вектор, не гліфи', зріз.діїВектор && зріз.дій > 0, `${зріз.дій} кнопок`);
ok('ціль пальця дій ≥ 44px', зріз.цілі44);
ok('значок не стискається (34px)', зріз.значкиЦілі);
ok('тап по контакту веде в дзвінок', зріз.telУсі);
ok('нічого не вилазить за екран', зріз.влазить);
ok('🔴 другий номер ЦНАПу намальовано', !!зріз.другий);
ok('другий номер веде в дзвінок', зріз.другий?.tel);
ok('🔴 цифри другого РІВНО під першим', зріз.другий?.рівно);
ok('ціль пальця другого ≥ 34px', (зріз.другий?.висота || 0) >= 34, `${зріз.другий?.висота}px`);
ok('🔴 ширина карток НЕ змінилась (номер пішов вниз, не вбік)', зріз.ширинаОднакова);

// ── 01.09 «c» — три претензії Вови ───────────────────────────────────────────
const сд = зріз.стовпціДій;
ok('🔴 (2) «копіювати» в ОДНОМУ стовпці на всіх картках', сд.копіРівно,
   `x = ${[...new Set(сд.копіювати)].join(' / ')}`);
ok('🔴 (2) пін в ОДНОМУ стовпці на всіх картках, де він є', сд.пінРівно,
   `x = ${[...new Set(сд.пін)].join(' / ')}`);
ok('(2) КОНТРОЛЬ: пін і «копіювати» — різні стовпці, а не злиплись', сд.різніСтовпці,
   `пін ${сд.пін[0]} · копіювати ${сд.копіювати[0]}`);

ok('🔴 (1) другий номер стоїть ПІД першим', !!зріз.порядокДругого?.підПершим);
ok('🔴 (1) адреса — ПІСЛЯ обох номерів, а не між ними', зріз.порядокДругого?.адресаНижче === true);

const найгірший = зріз.центри.reduce((m, k) => Math.max(m, k.значок, k.найгірша), 0);
ok('🔴 (3) значок і кнопки центровані по картці на ВСІХ картках', найгірший <= 1,
   `найбільший зсув ${найгірший.toFixed(1)}px`);

ok('помилок у консолі нема', errs.length === 0, errs.slice(0, 2).join(' | '));

// ═══════════════════════════════════════════════════════════════════════════
// 🔴 04.09 — ПʼЯТЬ СКАРГ ВОВИ ПРО ЦЕЙ БЛОК, КОЖНА ЗІ СВОЄЮ ПЕРЕВІРКОЮ
// ═══════════════════════════════════════════════════════════════════════════
const нове = await p.evaluate(() => {
  const карта = [...document.querySelectorAll('.hm-ct-act[href]')].map(a => decodeURIComponent(a.getAttribute('href')));
  const мета = [...document.querySelectorAll('.hm-ct')].map(c =>
    [...c.querySelectorAll('.hm-ct-meta')].map(m => m.textContent.trim()));
  const плитки = [...document.querySelectorAll('.hm-sos-b')].map(e => {
    const t = e.querySelector('.hm-sos-t'), r = e.getBoundingClientRect();
    return { назва: t ? t.textContent.trim() : '',
             обрізано: t ? t.scrollWidth > t.clientWidth + 1 : true,
             top: Math.round(r.top) };
  });
  return { карта, мета, плитки };
});

// (1) 🗣️ «мене перекидає Замкова, 17 в місті Луцьк, в тому, в якому я знаходжусь».
// Причина була в ДАНИХ: адреса без міста. Міряємо ПОСИЛАННЯ, бо саме воно їде
// в карту — перевірка «в JSON є слово Олика» зеленіла б і тоді, коли посилання
// збирається з іншого поля.
нове.карта.length
  ? ok(`🔴 кожне посилання на карту називає МІСТО (${нове.карта.length} шт.)`,
       нове.карта.every(h => /Олика/.test(h)),
       нове.карта.find(h => !/Олика/.test(h)) || 'усі з містом')
  : ok('🔴 кожне посилання на карту називає МІСТО', false, 'посилань немає');
ok('посилання на карту звужене областю (інакше пошук тягне до поточного міста)',
   нове.карта.every(h => /Волинськ/.test(h)));

// (2) 🗣️ «вулиця, місто Олика, і знизу тільки вхід ліворуч… але не разом, бо
// воно переноситься так і так в два рядка». Тобто адреса і підказка про вхід —
// РІЗНІ рядки, а не один злитий.
// ⚠️ Шукаємо ПІДКАЗКУ (рядок у дужках), а не дослівну фразу: прив'язка до
// формулювання зробила б сторожа крихким — 04.09 текст скоротили, і він
// «знайшов ваду» там, де її не було.
const цнап = нове.мета.find(m => m.some(t => /^\(.*\)$/.test(t)));
цнап
  ? ok('🔴 адреса і підказка про вхід — ОКРЕМІ рядки',
       цнап.some(t => /Олика/.test(t)) && цнап.some(t => /^\(.*\)$/.test(t) && !/Замкова/.test(t)),
       цнап.join(' | '))
  : ok('🔴 адреса і підказка про вхід — ОКРЕМІ рядки', false, 'картки з підказкою немає');
// 🗣️ «візьми це в дужки… типу що це як підказка». Дужки — те, що відрізняє
// підказку від факту, тож вони й стережуться.
ok('підказка стоїть у дужках (щоб читалась як підказка, а не як друга адреса)',
   !!цнап && цнап.some(t => /^\(.*\)$/.test(t) && /ліворуч/.test(t)),
   (цнап || []).find(t => /ліворуч/.test(t)) || '—');

// 🗣️ «дуже велика відстань… відцентруй номери вертикально, щоб рівномірно».
// 📐 Міряємо ПРОСВІТИ навколо другого номера: над ним і під ним вони мусять
// бути приблизно однакові. Перевірка на «є margin-block» зеленіла б і тоді,
// коли цифри знову притиснуті до назви.
const просвіти = await p.evaluate(() => {
  const alt = document.querySelector('.hm-ct-alt');
  if (!alt) return null;
  const r = alt.getBoundingClientRect();
  const цифри = alt.firstChild && alt.firstChild.nodeType === 3
    ? null : alt;                     // сам вузол і є рядком цифр
  const діапазон = document.createRange();
  діапазон.selectNodeContents(цифри || alt);
  const т = діапазон.getBoundingClientRect();
  return { над: Math.round(т.top - r.top), під: Math.round(r.bottom - т.bottom) };
});
просвіти
  ? ok('🔴 другий номер відцентрований у своїй цілі (просвіти згори й знизу рівні)',
       Math.abs(просвіти.над - просвіти.під) <= 2,
       `над ${просвіти.над}px · під ${просвіти.під}px`)
  : ok('🔴 другий номер відцентрований у своїй цілі', false, 'другого номера немає');

// (3) 🗣️ «не влазить повністю вся назва… швидка допомога, аварійна і не видно,
// що там пише». 🛑 Міряємо ОБРІЗКУ (`scrollWidth > clientWidth`), а не кегль:
// назва може вміститись і на 9px, і не вміститись на 12 — питання у ширині
// колонки, а не в шрифті.
ok(`🔴 жодна назва екстреної служби не обрізана (${нове.плитки.length} шт.)`,
   нове.плитки.length >= 5 && нове.плитки.every(t => !t.обрізано),
   нове.плитки.filter(t => t.обрізано).map(t => t.назва).join(', ') || 'усі повні');

// (4) Пʼять плиток в один ряд і були причиною обрізки: 67px на плитку. Тому
// стережеться саме РЯДІВ ≥2 — це умова, за якої повна назва взагалі можлива.
const ряди = new Set(нове.плитки.map(t => t.top));
ok('екстрені стоять у два ряди (у пʼяти колонках повна назва не вміщується)',
   ряди.size >= 2, `рядів: ${ряди.size}`);

// (5) 🗣️ «натискаю на номер, і він зразу пропадає, починає блимати місце
// натиску». 🛑 ЧЕСНО ПРО МЕЖУ: стан `:active` браузером не емулюється, тож це
// перевірка ДЖЕРЕЛА — єдина можлива тут. Вона тримає рівно те, що ламалось:
// накладка розтягнута на всю картку і лежить ПОВЕРХ тексту, тож будь-який
// непрозорий фон на ній ховає вміст.
// ⚠️ Читаємо CSS ТІЄЇ ревізії, яку перевіряємо, — інакше при `CSS_REV`
// джерельна перевірка дивилась би на свіжий файл і зеленіла б над старим кодом.
const css = CSS_REV ? projectFile('style/home.css', CSS_REV) : readFileSync(join(ROOT, 'style/home.css'), 'utf8');
const заливка = /\.hm-ct-main:active::after\s*\{[^}]*background/.test(css);
ok('🔴 на натиск номера НЕ малюється плита поверх тексту (інакше номер зникає)',
   !заливка, заливка ? 'у .hm-ct-main:active::after є background' : 'відгук дає сам номер');

await browser.close();
await stop();
done();
