// Стенд: ВАРТОВИЙ ШАРУ ДАНИХ СТЕРЕЖЕ СПРАВЖНІ ДВЕРІ, А НЕ ПОРОЖНЕЧУ.
//
// 🔴 ЗАРАДИ ЧОГО (22.09.2026). Про падіння шару даних у ніч на 22.09 ми
// дізнались від Вови — «чому додаток так довго вантажить вкладки?». Вартовий
// `.github/workflows/health-check.yml` тепер питає базу раз на 15 хвилин.
//
// 🔑 АЛЕ САМ ВАРТОВИЙ — ТЕЖ ПРИЛАД, і бреше він тихо. Він дістає адресу та
// публічний ключ із `src/core/supabase.js` РЕГУЛЯРНИМ ВИРАЗОМ. Перейменують
// там константу — вираз нічого не знайде, і вартовий або мовчатиме, або
// червонітиме щочверть години на порожньому місці.
//
// 📏 ТОМУ МІРЯЄМО ТАК: беремо вираз НЕ з голови, а з самого воркфлову, і
// застосовуємо до живого коду застосунку. Розійдуться — падає тут, у спокійний
// час, а не о третій ночі листом про «аварію», якої немає.
import { readFileSync } from 'fs';
import { reporter } from './_lib.mjs';

const { ok, done } = reporter();

const yml = readFileSync('.github/workflows/health-check.yml', 'utf-8');
const код = readFileSync('src/core/supabase.js', 'utf-8');

// ── 1. 🔴 ВИРАЗИ З ВОРКФЛОВУ ЗНАХОДЯТЬ ТЕ, ЩО ШУКАЮТЬ ──────────────────────
{
  // Витягуємо саме ті `grep -oP "…"`, якими користується вартовий.
  const вирази = [...yml.matchAll(/grep -oP "([^"]+)"/g)].map(m => m[1]);
  ok('вартовий справді дістає щось із коду застосунку',
     вирази.length === 2, `знайдено виразів: ${вирази.length}`);

  const застосувати = (pcre) => {
    // \K у PCRE = «забудь усе до цього місця». У JS його немає — перетворюємо
    // на групу захоплення, зміст виразу від цього не міняється.
    const js = '(' + pcre.replace(/\\K/, ')(') + ')';
    const m = код.match(new RegExp(js));
    return m ? m[2] : null;
  };

  const [адреса, ключ] = вирази.map(застосувати);
  ok('🔴 адресу бази вираз ЗНАХОДИТЬ і вона схожа на адресу',
     !!адреса && /^https:\/\/\S+\.supabase\.co$/.test(адреса.trim()),
     адреса ? адреса.slice(0, 18) + '…' : '(не знайшов)');
  // 🛑 Сам ключ НЕ друкуємо: репозиторій публічний, і хоч ключ відкритий,
  //    сипати його в журнали прогонів — погана звичка.
  // Ключ буває двох форм: старий JWT (`eyJ…`, ~200 знаків) і новий
  // публікований (`sb_publishable_…`). Приймаємо обидві — вимагати одну
  // означало б червоніти на плановій заміні ключа.
  ok('🔴 публічний ключ вираз теж знаходить',
     !!ключ && ключ.length > 30 && /^(sb_publishable_|eyJ)/.test(ключ),
     ключ ? `форма впізнана, довжина ${ключ.length}` : '(не знайшов)');
}

// ── 1-БІС. 🔴 РОЗКЛАД, ЯКИЙ GITHUB СПРАВДІ ВИКОНУЄ ────────────────────────
//
// 📐 ЗАМІРЯНО 22.09, І ЦЕ НЕ СМАК. Перша редакція вартового стояла на `*/15` і
// за **4.5 години не дала ЖОДНОГО прогону**, хоч воркфлов зареєстрований і
// `active`. Інші розклади репозиторію в той самий час ішли справно (новини
// 03:47 · 04:47 · 05:47 · 06:47 · 07:47).
//
// 🔑 ПРОЄКТ ЗНАВ ЦЕ ДВІЧІ, А Я НЕ ПРОЧИТАВ СУСІДНІЙ ФАЙЛ:
//   • `rss-parser.yml` — `0,30 * * * *` і коментар «GitHub надійно виконує такі
//     cron-jobs»;
//   • `vopas-parser.yml` — `*/30`, і в журналі 21.09: «обіцяє кожні 30 хвилин,
//     фактично раз на ~2 години».
// 🛑 Вартовий на кроковому синтаксисі — це вартовий, який спить. Найгірший
//    можливий стан: він Є, на нього покладаються, і він мовчить не тому, що
//    все гаразд.
{
  const крон = (yml.match(/cron:\s*'([^']+)'/) || [])[1] || '';
  ok('вартовий має розклад', !!крон, крон || '(немає)');
  ok('🔴 розклад НЕ на кроковому синтаксисі (`*/N` тут не виконується)',
     !крон.includes('*/'), крон);
  ok('🔑 а на явних хвилинах — як у `rss-parser`, що йде справно',
     /^[\d,]+ /.test(крон), крон.split(' ')[0]);
}

// ── 1-ТРИ. 🛑 ЗМІННІ ОБОЛОНКИ — ЛИШЕ ЛАТИНИЦЕЮ ────────────────────────────
//
// 📐 ЗАМІРЯНО НА ЖИВИХ ПРОГОНАХ. Перші два запуски вартового впали, не
// перевіривши НІЧОГО:
//     КОД=200: command not found
//     ЧАС=0.463209: command not found
//     дані: HTTP $КОД · вхід: ${ЧАС}s: bad substitution
// Тобто він був червоний не тому, що знайшов ваду, а тому, що сам не вмів
// запуститись. Це гаряче правило проєкту («кирилиця в змінних bash»), на яке
// я наступив того самого дня ВДРУГЕ — і вдруге саме в цьому файлі.
//
// 🔑 МІРЯЄМО ПРИСВОЄННЯ В ОБОЛОНЦІ, А НЕ ВЕСЬ ФАЙЛ: усередині python-heredoc
// кирилиця законна і має лишатись — там це змінні Python.
{
  const кроки = [...yml.matchAll(/run: \|([\s\S]*?)(?=\n      - name:|\n*$)/g)].map(m => m[1]);
  ok('кроки з командами знайдено', кроки.length >= 2, `${кроки.length}`);

  // Відрізаємо тіла heredoc: там інша мова і інші правила.
  const лишеОболонка = кроки.map(к => к.replace(/<<'PY'[\s\S]*?\n\s*PY/g, '')).join('\n');
  const погані = [...лишеОболонка.matchAll(/^\s*([A-Za-z_]*[А-Яа-яІіЇїЄєҐґ][A-Za-z_А-Яа-яІіЇїЄєҐґ]*)=/gm)]
    .map(m => m[1]);

  ok('🛑 у змінних оболонки НЕМАЄ кирилиці (інакше `command not found`)',
     погані.length === 0, погані.join(', ') || 'усі латиницею');

  // 🔑 КОНТРОЛЬ на власний спосіб міряти: вираз мусить ловити саме те, що впало.
  const зразок = 'КОД=$(curl -s -w "%{http_code}")';
  ok('КОНТРОЛЬ: вираз справді ловить рядок, на якому впали прогони',
     /^\s*([A-Za-z_]*[А-Яа-яІіЇїЄєҐґ][A-Za-z_А-Яа-яІіЇїЄєҐґ]*)=/m.test(зразок));
}

// ── 2. ОДИН ЗБІЙ — НЕ АВАРІЯ ───────────────────────────────────────────────
// Вартовий, який будить через кожен чих, навчає не читати його листи.
{
  ok('питає кілька разів, а не один',
     /for i in 1 2 3/.test(yml), 'три спроби');
  ok('між спробами чекає', /sleep 20/.test(yml));
  ok('🛑 і не чекає відповіді довше, ніж чекав би житель',
     /-m 20/.test(yml), 'стеля запиту 20 с');
}

// ── 3. ПОРАЗКА НЕ МОВЧИТЬ ──────────────────────────────────────────────────
// 🔑 Головна вимога всього проєкту: тихий зелений гірший за червоний.
{
  ok('🔴 при недоступній базі прогін ПАДАЄ',
     /exit 1/.test(yml) && /ШАР ДАНИХ НЕ ВІДПОВІДАЄ/.test(yml));
  ok('🔴 і коли вираз нічого не знайшов — теж падає, а не стереже порожнечу',
     /не знайшов адресу або публічний ключ/.test(yml));
  ok('🔑 у листі є ГОТОВИЙ засіб, а не самий діагноз',
     /pg_timezone_names/.test(yml) && /Restart project/.test(yml));
  ok('засіб названо перевіреним, із датою, коли спрацював',
     /22\.09/.test(yml));
}

// ── 3-А. ЛИСТ ЧИТАЄТЬСЯ, КОЛИ БАЗА МОВЧИТЬ ────────────────────────────────
//
// 🔴 Знайшов ПЕРШИЙ ЖЕ живий прогін по хворій базі (#4, 22.09 20:13 UTC).
// Вердикт вартового був правильний, а лист — ні:
//
//     дані: HTTP 000000 · вхід: 20.002404-1s
//     head: cannot open '/tmp/body.txt'
//
// Причина: `$(curl … || echo 000)`. curl із `-w '%{http_code}'` друкує `000`
// САМ, тож гілка `||` дописувала друге значення до першого. І файл тіла при
// таймауті не створювався зовсім — тобто гілка, що впізнає `PGRST002` і дає
// ГОТОВИЙ ЗАСІБ, була сліпа рівно в тому випадку, заради якого написана.
//
// 🔑 Стережемо обидві половини, бо ціна тут не косметична: людина о третій
// ночі мусить прочитати, що сталось із базою, а не що зламався прилад.
{
  // ⚠️ КОМЕНТАРІ ЗНІМАЄМО. Усередині функції дослівно процитована стара
  // редакція («тут стояло `|| echo 000`»), і перша редакція цієї перевірки
  // почервоніла на власному поясненні — тобто міряла ПРОЗУ, а не код.
  // Той самий прийом, що зі зніманням тіл heredoc нижче.
  const probeRaw = (yml.match(/probe\(\) \{[\s\S]*?\n\s*\}/) || [''])[0];
  const probe = probeRaw.split('\n').filter(р => !/^\s*#/.test(р)).join('\n');
  ok('функцію опитування знайдено', probe.length > 100, `${probe.length} символів`);

  // ⚠️ `|| echo` стоїть УСЕРЕДИНІ `$( … )`, а не після неї — перша редакція
  // цієї перевірки шукала його після дужки і не знайшла б нічого ніколи.
  ok('🔴 немає `|| echo` у підстановках — інакше значення СКЛЕЮЮТЬСЯ',
     !/\|\|\s*echo/.test(probe),
     'заміряно на проді: HTTP 000000 · 20.002404-1s');

  ok('🛑 файл тіла створюється ДО запиту (при таймауті curl його не пише)',
     /:\s*>\s*\/tmp\/body\.txt/.test(probe));

  ok('порожній вивід підставляється ОКРЕМО, а не склеюванням',
     /\[ -n "\$CODE" \] \|\| CODE=000/.test(probe));

  ok('порожнє тіло має зрозумілий підпис, а не `head: cannot open`',
     /BODY:-/.test(yml));

  // 🔑 КОНТРОЛЬ на сам вираз: він мусить ЧЕРВОНІТИ на старій редакції.
  const стара = `CODE=$(curl -s -w '%{http_code}' "$URL" || echo 000)`;
  ok('КОНТРОЛЬ: вираз ловить саме ту редакцію, що впала на проді',
     /\|\|\s*echo/.test(стара) && !/\|\|\s*echo/.test('CODE=$(curl -s) || true'));
}

// ── 3-БІС. ВАРТОВИЙ СТЕРЕЖЕ Й ПОДІЛ СТАТЕЙ ────────────────────────────────
//
// 🔴 Поділ (`scripts/split_articles.py`) робиться ЛИШЕ при складанні сайту, тож
// зламатись він може там, куди жоден стенд не дістає: у репозиторії файл один і
// цілий, а на сайті може лежати список без текстів — і жоден житель не прочитає
// статті далі анонсу. Мовчазно.
// 🛑 Саме цю перевірку неможливо зробити з пісочниці розробки (вихід на Pages
// звідти закритий), тому вона живе у вартовому і йде щочверть години.
{
  ok('вартовий питає обидва файли статей',
     /data\/articles\.json/.test(yml) && /data\/articles-text\.json/.test(yml));
  ok('🔴 і червоніє, якщо поділ не відпрацював (у списку лишився `content`)',
     /КРОК ПОДІЛУ НЕ ВІДПРАЦЮВАВ/.test(yml));
  ok('🔴 і якщо тексти загубились — житель побачив би самі анонси',
     /ТЕКСТИ ЗАГУБИЛИСЬ/.test(yml));
  // 🔑 Не «є текст» — а чи справді ПАДАЄ. Крок мусить мати власні `sys.exit(1)`.
  const блок = yml.slice(yml.indexOf('поділ статей доїхав'));
  ok('🛑 обидві біди валять крок, а не просто друкуються',
     (блок.match(/sys\.exit\(1\)/g) || []).length >= 3,
     `${(блок.match(/sys\.exit\(1\)/g) || []).length} виходів із помилкою`);
}

// ── 4. КОНТРОЛЬ: стенд мусить уміти впасти ─────────────────────────────────
// Якби вираз шукав константу, якої в коді немає, перевірка 1 почервоніла б.
{
  const вигаданий = код.match(/SUPABASE_НЕМАЄ_ТАКОГО\s*=\s*'([^']+)'/);
  ok('КОНТРОЛЬ: неіснуюча константа справді не знаходиться', вигаданий === null);
}

done();
