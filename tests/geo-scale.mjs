// Стенд: МАСШТАБ І АДРЕСА ПОСТА — агент не звужує громаду до її центру.
//
// 🔴 ЗАРАДИ ЧОГО. 20.08 агент написав чернетку про День Незалежності України,
// яка починалась «Для нас, жителів Олики, це свято має особливий смисл». Вова:
// «це стосується не тільки жителів Олики, а всієї громади — правильно було б
// „жителів Олицької громади“». Олицька громада це Олика + 16 сіл, тобто фраза
// виключала 16 сіл з їхнього ж державного свята.
//
// Корінь був не в стилі: у промті святкового письменника стояло «редактор
// локального медіа МІСТЕЧКА ОЛИКА … для жителів ГРОМАДИ» — два масштаби в
// одному реченні і жодного правила, коли який.
//
// 🛑 ЧОМУ СТЕНД НЕ ШУКАЄ СЛІВ У ФАЙЛАХ. «У промті є слово громада» зелене і
// тоді, коли правило написане, але не працює. Тому модуль тут ЗАПУСКАЄТЬСЯ на
// справжньому тексті чернетки, і ми дивимось, що з ним стало. Плюс контроль:
// на пості ПРО САМУ ОЛИКУ той самий текст чіпати не можна — інакше «виправляє
// завжди» теж зійшло б за успіх.
import { execFileSync } from 'child_process';
import { readFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import { reporter } from './_lib.mjs';

const { ok, done } = reporter();
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Запускає гео-модуль у корені репозиторію і віддає розібраний JSON. */
function гео(код) {
  const повний = `
import sys, json; sys.path.insert(0, ${JSON.stringify(ROOT)})
from editor.core import geo
${код}`;
  return JSON.parse(execFileSync('python3', ['-c', повний],
    { cwd: ROOT, encoding: 'utf-8' }).trim());
}

// Справжній початок тієї чернетки — не вигаданий приклад.
const ТЕКСТ = 'Для нас, жителів Олики, це свято має особливий смисл.';

// ── 1. ДОВІДКА ЖИВА І ЧИТАЄТЬСЯ З КОНФІГА, А НЕ ЗАШИТА ─────────────────────
const села = гео('print(json.dumps(geo.села()))');
ok('гео-довідка знає села громади (не порожня)', села.length >= 16, `сіл ${села.length}`);
ok('серед сіл є ті, що були в тексті скарги', ['Метельне', 'Одеради'].every(с => села.includes(с)));

// 🔑 Доводимо, що список НЕ зашитий у модуль: підміняємо конфіг у памʼяті і
// дивимось, чи довідка змінилась. Якби села були в коді — не змінилась би.
const підміна = гео(`
geo._кеш = {"name": "Тестова громада", "center": "Тестопіль",
            "center_status": "місто", "district": "р", "oblast": "о",
            "villages": ["Вигадкове"]}
print(json.dumps({"текст": geo.довідка(), "села": geo.села()}))`);
ok('🔴 довідка будується з конфіга, а не зашита в код',
   підміна.села.length === 1 && підміна.текст.includes('Вигадкове')
   && !підміна.текст.includes('Метельне'));

// ── 2. МАСШТАБ ВИЗНАЧАЄТЬСЯ ДО ПИСЬМА ──────────────────────────────────────
const масштаби = гео(`
print(json.dumps({
 "незалежність": geo.масштаб_свята({"title": "🇺🇦 День Незалежності України", "kind": "державне"}),
 "різдво":       geo.масштаб_свята({"title": "⛪ Різдво Христове", "kind": "релігійне"}),
 "олика":        geo.масштаб_свята({"title": "День міста Олика", "kind": "місцеве"}),
 "село":         geo.масштаб_свята({"title": "Храмове свято в Метельному", "kind": "місцеве"}),
 "невідоме":     geo.масштаб_свята({"title": "Щось", "kind": ""}),
}))`);
ok('🔴 державне свято — національний масштаб', масштаби.незалежність === 'національний');
ok('релігійне свято теж національний масштаб', масштаби.різдво === 'національний');
ok('свято про саму Олику — масштаб центру', масштаби.олика === 'центр');
ok('свято в селі — масштаб села', масштаби.село === 'село');
// ⚠️ Помилитись у бік «сказав про всіх» дешевше, ніж виключити село зі свята.
ok('невідомий рід свята падає в ШИРШИЙ масштаб, не у вужчий',
   масштаби.невідоме === 'національний');

// ── 3. ЗВУЖЕННЯ ВИПРАВЛЯЄТЬСЯ НА СПРАВЖНЬОМУ ТЕКСТІ ────────────────────────
const нац = гео(`
t, z, p = geo.виправити(${JSON.stringify(ТЕКСТ)}, geo.НАЦІОНАЛЬНИЙ)
print(json.dumps({"текст": t, "зміни": z, "поперед": p}))`);
ok('🔴 «жителів Олики» на державному святі стає «жителів Олицької громади»',
   нац.текст === 'Для нас, жителів Олицької громади, це свято має особливий смисл.',
   нац.текст);
ok('виправлення не мовчазне — його видно у звіті', нац.зміни.length === 1);

// 🛑 КОНТРОЛЬ. Той самий текст у пості ПРО ОЛИКУ чіпати не можна: там «жителі
// Олики» — правильна адреса. Без цієї перевірки заслон міг би бути глухим
// молотком, що псує справні тексти.
const центр = гео(`
t, z, p = geo.виправити(${JSON.stringify(ТЕКСТ)}, geo.ЦЕНТР)
print(json.dumps({"текст": t, "зміни": z}))`);
ok('🔴 КОНТРОЛЬ: у пості про саму Олику текст НЕ чіпається',
   центр.текст === ТЕКСТ && центр.зміни.length === 0);

// Відмінок зберігається — інакше вийшло б «жителів Олицької громади знають».
const відмінки = гео(`
t, _, _p = geo.виправити("Жителі Олики знають. Мешканцям Олики теж.", geo.НАЦІОНАЛЬНИЙ)
print(json.dumps({"текст": t}))`);
ok('заміна зберігає відмінок слова, а не ліпить один шаблон',
   відмінки.текст === 'Жителі Олицької громади знають. Мешканцям Олицької громади теж.',
   відмінки.текст);

// ── 4. СТАТУС ОЛИКИ ────────────────────────────────────────────────────────
// ⚠️ Сторонній ШІ, якого питали поради, назвав Олику селом. Олика — місто з
// 17.04.2025. Помилка в цей бік гірша за ту, що виправляємо.
const статус = гео(`
_t, _z, p1 = geo.виправити("Наше село Олика прокидається.", geo.НАЦІОНАЛЬНИЙ)
_t2, _z2, p2 = geo.виправити("У смт Олика відкрили.", geo.ГРОМАДА)
print(json.dumps({"село": p1, "смт": p2, "довідка": geo.довідка()}))`);
ok('🔴 «село Олика» позначається як помилка', статус.село.length > 0);
ok('«смт Олика» позначається як застаріле', статус.смт.length > 0);
ok('довідка прямо каже, що Олика місто, а не село і не смт',
   /міст[оа]/.test(статус.довідка) && /НЕ село і НЕ смт/.test(статус.довідка));

// ── 5. ДОВІДКА СПРАВДІ ДОЇЖДЖАЄ ДО ОБОХ ПИСЬМЕННИКІВ ───────────────────────
// Правило, яке нікуди не підключене, — це файл, а не поведінка.
const aiPy = readFileSync(join(ROOT, 'editor/writers/ai_writer.py'), 'utf-8');
const brandPy = readFileSync(join(ROOT, 'editor/writers/brand_writer.py'), 'utf-8');
ok('🔴 святковий письменник вкладає гео-довідку в промт', /гео\.довідка\(/.test(aiPy));
ok('🔴 письменник спільноти вкладає гео-довідку в промт', /гео\.довідка\(/.test(brandPy));
// 🛑 Саме це формулювання і плутало масштаби — воно не має повернутись.
ok('зі святкового промта прибрано «медіа містечка Олика»',
   !/медіа містечка Олика/.test(aiPy));

// ── 6. ЗАСЛОН УВІМКНЕНИЙ, А НЕ ПРОСТО НАПИСАНИЙ ────────────────────────────
const реєстр = readFileSync(join(ROOT, 'editor/core/registry.py'), 'utf-8');
ok('фільтр підключено в реєстрі плагінів', /from editor\.filters import geo_scale/.test(реєстр));
for (const м of ['holidays', 'olyka_castle']) {
  const місія = JSON.parse(readFileSync(join(ROOT, `editor/missions/${м}.json`), 'utf-8'));
  ok(`місія «${м}» проходить через заслон масштабу`,
     (місія.filters || []).includes('geo_scale'), JSON.stringify(місія.filters));
}

// Заслон запускаємо по-справжньому — на чернетці з тим самим текстом.
// ⚠️ Заслон навмисно говорить у лог — тож його друк відводимо вбік, інакше
// він змішується з відповіддю стенда.
const крізьЗаслон = гео(`
import contextlib, io as _io
from editor.core.models import Draft
from editor.core.registry import load_plugins, get
load_plugins()
d = Draft(title="🇺🇦 День Незалежності України",
          content=${JSON.stringify(ТЕКСТ)},
          meta={"kind_свята": "державне"})
with contextlib.redirect_stdout(_io.StringIO()) as лог:
    живий = get("filter", "geo_scale")().keep(d, {})
голосно = лог.getvalue()
print(json.dumps({"лишив": живий, "текст": d.content, "масштаб": d.meta.get("масштаб"),
                  "слід": d.meta.get("гео_виправлено", []), "лог": голосно}))`);
ok('🔴 заслон править чернетку ДО кабінету, а не після публікації',
   крізьЗаслон.текст.includes('жителів Олицької громади'), крізьЗаслон.текст);
ok('заслон не викидає чернетку (оплачений текст не пропадає)', крізьЗаслон.лишив === true);
ok('заслон лишає слід у meta — при вичитці видно, що текст правили',
   крізьЗаслон.слід.length > 0 && крізьЗаслон.масштаб === 'національний');
// 🔑 Тиха автозаміна тексту була б гіршою за помилку: не видно, що правили.
ok('заслон каже про виправлення ВГОЛОС, а не мовчки',
   /🌍/.test(крізьЗаслон.лог), JSON.stringify(крізьЗаслон.лог));

// ── 7. ГОЛОС НЕ СУПЕРЕЧИТЬ САМ СОБІ ────────────────────────────────────────
// ⚠️ Файл голосу починався з «медіабренд містечка Олика», а всередині тепер
// стоїть «не звужуй до Олики». Агент читає його цілком — суперечність у ньому
// означає, що він обере одне з двох навмання.
const голос = readFileSync(join(ROOT, 'editor/voice/olyka_castle.md'), 'utf-8');
ok('🔴 у голосі є правило масштабу', /МАСШТАБ І АДРЕСА/.test(голос));
ok('голос називає бренд медіа ГРОМАДИ, а не самого лише центру',
   /медіабренд \*\*Олицької громади\*\*/.test(голос));
ok('у голосі не лишилось самоопису «медіабренд містечка Олика»',
   !/медіабренд містечка Олика/.test(голос));
ok('голос перелічує села поіменно (щоб «16 сіл» не було абстракцією)',
   ['Метельне', 'Одеради', 'Чемерин'].every(с => голос.includes(с)));

done();
