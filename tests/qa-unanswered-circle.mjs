// Стенд: КОЛО ТИПУ 4 НЕ ПОРОЖНЄ НА ЗАПУСКУ, І ЗВІТ НЕ БРЕШЕ.
//
// 🔴 ЗАРАДИ ЧОГО (25.09.2026). Тип 4 — «у громаді є питання без відповіді» —
// шле лише тим, хто сам щось робив у Питаннях (§14). Було: єдиний факт
// «написала хоча б одну ВІДПОВІДЬ за 90 днів». 📐 Заміряно на живій базі 25.09:
// таких людей ДВОЄ, із них із пристроєм ОДИН, а на першому дні запуску їх нуль
// за визначенням — тобто сповіщення мовчало б рівно тоді, коли перше питання
// громади й повисло без відповіді.
// ➡️ Тепер коло — обʼєднання трьох фактів: відповідала · ставила питання ·
// тиснула «Мене теж цікавить».
//
// 🛑 ЧОМУ СТЕНД ТЕКСТОВИЙ. Edge Functions із пісочниці не запускаються, а в базі
// сьогодні один адресат — навіть живий прогін нічого б не довів. Тому беремо
// ЖИВИЙ текст функції і вимагаємо, щоб конкретні рішення були на місці.
// ⚠️ Він НЕ доводить, що сповіщення приходять. Він доводить, що коло не
// звужується до нуля на запуску, автор питання зі свого списку так само
// випадає, а звіт відрізняє «надіслали» від «слати нікуди».
//
// 🔑 Кожна ознака навмисно звужена до того рядка, який можна зламати правкою:
// перевірка на саме слово («reactions») червоніє від видалення джерела кола,
// а не від переставляння коментарів.

import { readFileSync } from 'fs';
import { join } from 'path';
import { ROOT, reporter } from './_lib.mjs';

const { ok, done } = reporter();

const ФАЙЛ = join(ROOT, 'supabase/functions/send-unanswered-push/index.ts');
const т = readFileSync(ФАЙЛ, 'utf-8');

// ── 1. ТРИ ДЖЕРЕЛА КОЛА ─────────────────────────────────────────────────────
// Найважливіша ознака: жодне з трьох не має права тихо зникнути при рефакторингу.
ok('коло бере тих, хто ВІДПОВІДАВ',
   /відповідачі\s*=/.test(т) && /sender_uid/.test(т),
   'comments.sender_uid');

ok('коло бере тих, хто СТАВИВ ПИТАННЯ',
   /автори\s*=/.test(т) && /owner_uid/.test(т),
   'posts.owner_uid');

ok('коло бере тих, хто тиснув «МЕНЕ ТЕЖ ЦІКАВИТЬ»',
   /зацікавлені\s*=/.test(т) && /from\('reactions'\)/.test(т) && /❤️/.test(т),
   'reactions ❤️ на питанні');

ok('усі три зведені в одне коло без повторів',
   /коло[^\n]*=\s*\[\.\.\.new Set\(\[\.\.\.відповідачі,\s*\.\.\.автори,\s*\.\.\.зацікавлені/.test(т),
   'Set над трьома джерелами');

// ── 2. ФІЛЬТР ФОРМИ UUID ПЕРЕД `.in(...)` ───────────────────────────────────
// 🛑 `reactions.user_id` — TEXT і тримає ще й анонімні id (`'anon-' + …`), а
// `notif_prefs.uid` / `user_push_devices.uid` — `uuid`. Один сторонній рядок у
// переліку відкидає ВЕСЬ запит, тобто через чужий id мовчки не отримує
// сповіщення ЖОДЕН із кола. Правило «TEXT проти uuid» з `HOT_RULES.md`.
const uuidРядок = /\^\[0-9a-f\]\{8\}-\[0-9a-f\]\{4\}-\[0-9a-f\]\{4\}-\[0-9a-f\]\{4\}-\[0-9a-f\]\{12\}\$/;
ok('id із реакцій проціджені фільтром форми UUID',
   uuidРядок.test(т) && /UUID\.test\(/.test(т),
   'інакше один anon-id глушить усе коло');

// ── 3. ЩО ФІКС НЕ МАВ ПРАВА ЗЛАМАТИ ─────────────────────────────────────────
// Автор питання зі СВОГО списку випадає (§15): «допоможіть відповісти на ваше
// питання» — знущання. Розширення кола робить цю перевірку критичнішою, бо тепер
// автори в колі є за визначенням.
ok('автор питання випадає зі свого списку',
   /owner_uid\s*!==\s*uid/.test(т),
   '§15');

ok('вимикач «Питання» в кабінеті питається так само',
   /allowed\(admin,\s*коло\.filter/.test(т),
   'notif_prefs.questions');

ok('стеля «раз на 3 доби» рахується по новому колу',
   /qa_unanswered_push_log[\s\S]{0,120}\.in\('uid',\s*коло\)/.test(т),
   'журнал читається для кола, не для відповідачів');

// ── 4. ЖУРНАЛ НЕ ПАЛИТЬ СТЕЛЮ ТИМ, КОМУ НІКУДИ СЛАТИ ───────────────────────
// 📐 У живому журналі є рядки 12.09 і 16.09 із `sent: 0` на ту саму людину: у неї
// немає жодного пристрою, тож вона двічі зʼїла свою триденну стелю, нічого не
// отримавши. Мертва підписка — інша річ, її в журнал писати правильно.
ok('той, у кого немає пристрою, не потрапляє в журнал',
   /безПристрою/.test(т) && /рядки\s*=\s*\[\.\.\.план\]\.filter\(\(\[uid\]\)\s*=>\s*!немає\.has\(uid\)\)/.test(т),
   'журнал = спроби звернутись, а не «нікуди слати»');

// ── 5. ЗВІТ ВІДРІЗНЯЄ «НАДІСЛАЛИ» ВІД «НІКУДИ СЛАТИ» ───────────────────────
// 🔑 Досі звіт казав `people: 2` при `sent: 1`, і з нього виходило, що звернулись
// до двох. Число брехало назвою — той самий клас, що в `NOW.md`.
ok('робочий звіт віддає no_device і розмір кола',
   /no_device:\s*безПристрою\.length/.test(т) && /circle:\s*коло\.length/.test(т),
   'sent · people · no_device · circle');

ok('сухий прогін показує склад кола',
   /circle_parts:\s*\{\s*responders:/.test(т),
   'responders · askers · interested');

// ── МЕЖІ МЕТОДУ ─────────────────────────────────────────────────────────────
// • Стенд читає ТЕКСТ, а не поведінку: він не знає, чи Supabase віддасть рядки.
// • Він не перевіряє, що push доходить до телефону — це можливо лише живим
//   прогоном, і 24.08 такий уже робився («ТИП 4 — ЧОМУ 25.08 НІЧОГО НЕ ПРИЙШЛО»).
// • Він НЕ доводить, що коло правильне за змістом: «кого саме питати» — рішення
//   Вови, а не властивість коду.
done();
