// 🔑 ЧОМУ СТЕНД САМЕ ТАКИЙ. `admin.html` — окрема самостійна сторінка (свій
// HTML+CSS+JS, не в `bundle.js`), і відкрити її може лише залогінений адмін.
// Підняти живу сцену означало б підробити сесію адміна, тобто перевіряти власну
// підробку. Тому беремо ЛОГІКУ: вирізаємо функції з файлу і виконуємо їх на
// вигаданих даних. Це справжня перевірка поведінки, а не наявності рядка в коді.
//
// ⚠️ МЕЖА, ЯКУ ТРЕБА ЗНАТИ: розмітку і слухачі цей стенд НЕ перевіряє. Він каже
// «дані згрупуються правильно», а не «екран виглядає правильно». Названо чесно,
// щоб наступна сесія не думала, що розділ покрито цілком.
//
// Що саме стережемо (розбір — `_ai-tools/AUDIT_SKARGY_2026-08.md`):
//   Д5 — п'ять скарг на одне оголошення мусять читатись як ОДИН випадок;
//   пріоритет — групи з кількома скаргами йдуть угору (замість автоприховування,
//   якого свідомо немає: троє знайомих у селі зацькували б конкурента за 5 хвилин).

import { projectFile, reporter } from './_lib.mjs';

const { ok, done } = reporter();
const HTML = projectFile('admin.html');

// Вирізаємо дві чисті функції разом — `groupReports` не залежить ні від чого
// зовнішнього, тому виконується як є.
function вирізати(назва) {
  const i = HTML.indexOf(`function ${назва}(`);
  if (i < 0) return null;
  // Кінець — перший рядок, що починається з `}` на нульовому відступі.
  const хвіст = HTML.slice(i);
  const кінець = хвіст.indexOf('\n}\n');
  return кінець < 0 ? null : хвіст.slice(0, кінець + 2);
}

const src = вирізати('groupReports');
ok('функцію groupReports знайдено у admin.html', !!src, src ? `${src.length} символів` : 'немає');

const groupReports = new Function(`${src}; return groupReports;`)();

// ── Дані: 3 скарги на #1, 1 на #2, 2 на #3 ──────────────────────────────────
const д = (id, post_id, дні, reason = 'spam') => ({
  id, post_id, reason, status: 'new',
  created_at: new Date(Date.now() - дні * 864e5).toISOString(),
});
const скарги = [
  д(1, 1, 0, 'scam'), д(2, 1, 1, 'scam'), д(3, 1, 2, 'spam'),
  д(4, 2, 0),
  д(5, 3, 3), д(6, 3, 4),
];

const g = groupReports(скарги);
ok('скарги на одне оголошення злились в одну групу', g.length === 3, `груп ${g.length} з 6 скарг`);
ok('групи не втратили жодної скарги',
   g.reduce((n, x) => n + x.length, 0) === 6, `${g.reduce((n, x) => n + x.length, 0)} з 6`);

// 🔑 ГОЛОВНЕ: більше скарг = вище. Це заміна автоприховуванню — прискорюємо
// людину, а не замінюємо її.
ok('група з найбільшою кількістю скарг стоїть ПЕРШОЮ',
   g[0].length === 3 && String(g[0][0].post_id) === '1',
   `перша група: оголошення #${g[0][0].post_id}, скарг ${g[0].length}`);
ok('далі йде група з двома, остання — одиночна',
   g[1].length === 2 && g[2].length === 1,
   `${g.map(x => x.length).join(' / ')}`);

// При рівній кількості вирішує свіжість — інакше порядок був би випадковим і
// список «перестрибував» би між заходами.
const рівні = [д(10, 7, 5), д(11, 8, 0)];
const g2 = groupReports(рівні);
ok('при рівній кількості скарг свіжіша група вище',
   String(g2[0][0].post_id) === '8', `перша: #${g2[0][0].post_id}`);

ok('порожній список не ламає групування', groupReports([]).length === 0);

// ── Дії над оголошенням доступні прямо зі скарги (рішення Вови 06.08) ───────
// Це вже статична перевірка — слабша, і названа слабкою. Але без неї не лишилось
// би жодного сторожа на Д3: «висновок ні до чого не веде».
const єЗняти  = /data-rep-unpublish/.test(HTML);
const єВидал  = /data-rep-delete/.test(HTML);
const єПрев   = /function reportPreviewHtml\(/.test(HTML);
ok('у картці скарги є дія «зняти з публікації»', єЗняти,
   єЗняти ? 'data-rep-unpublish' : 'ДІЇ НЕМАЄ — адмін мусить шукати оголошення в іншому розділі');
ok('і дія «видалити оголошення»', єВидал, єВидал ? 'data-rep-delete' : 'дії немає');
ok('і превʼю самого оголошення', єПрев,
   єПрев ? 'reportPreviewHtml' : 'ПРЕВʼЮ НЕМАЄ — рішення приймають про річ, якої не видно');

// ⚠️ Зняття з публікації МУСИТЬ питати підтвердження: одне випадкове торкання
// інакше прибирає чуже оголошення, і людина цього не побачить до наступного заходу.
const блок = HTML.slice(HTML.indexOf('data-rep-unpublish]'), HTML.indexOf('data-rep-delete]'));
ok('зняття з публікації питає підтвердження', /confirm\(/.test(блок),
   /confirm\(/.test(блок) ? 'confirm() на місці' : 'ПІДТВЕРДЖЕННЯ НЕМАЄ');

done();
