const оператор = (текст, імʼя) => текст.search(new RegExp('\\n\\s+' + імʼя + '\\(\\);'));
ok('позначки вкладок чекають «хто я» ДО запису під ключ людини',
   слухач.indexOf('await authReady()') >= 0
   && слухач.indexOf('await authReady()') < оператор(слухач, 'markQaFloorOnce'),
   слухач ? 'слухач знайдено' : 'слухача не знайдено');
// 🛑 І СТРАХОВКА НА ТЕ, ЩО МИ НЕ РОЗСИПАЛИ ПОРЯДОК, куплений 25.08:
// `markChatSeen()` зрушує ту саму мітку, яку читає `markQaFloorOnce()`. Постав його
// першим — і поріг щоразу дорівнює поточній миті, тобто свіже питання стає
// «історією» від одного тапу по вкладці. Обидва мусять лишитись СИНХРОННИМИ.
ok('порядок markQaFloorOnce → markChatSeen НЕ порушено',
   оператор(слухач, 'markQaFloorOnce') >= 0
   && оператор(слухач, 'markQaFloorOnce') < оператор(слухач, 'markChatSeen'));
ok('позначки лишились синхронними (порядок не розсипано на обіцянки)',
   !/await\s+markQaFloorOnce|await\s+markChatSeen/.test(слухач));

// ── ДОШКА: закладки і лайки читаються В ОДНОМУ МІСЦІ ─────────────────────────
// 🔑 `loadBoardData()` — єдина точка читання для Дошки, і `uid` іде в ОБИДВА
// персональні запити: `fetchSavedPostIds(uid)` без нього навіть не викликається,
// `fetchAllReactions(uid || getAnonId())` без нього питає про АНОНІМА. Плюс ті самі
// реакції їдуть у `setDiscussionsData()`, на яких тримається «мене теж цікавить»
// у Питаннях. Тому одна перевірка тут стереже три поверхні.
const дані = (board.match(/async function loadBoardData\(\)[\s\S]*?\n\}/) || [''])[0];
ok('loadBoardData ЧЕКАЄ «хто я» ДО читання закладок і лайків',
   дані.indexOf('await authReady()') >= 0
   && дані.indexOf('await authReady()') < дані.search(/\n\s*const uid = currentUserId\(\);/),
   дані ? 'тіло знайдено' : 'функцію не знайдено');
// 🛑 І страховка на те, що гарантія не «переїхала» за перший вихід: `isSupabaseReady()`
// віддає false ще до всякого входу, і поставити очікування після нього було б
// нешкідливо — а от поставити його після `const uid` означало б не полагодити нічого.
// ⚠️ І тут та сама пастка вчетверте: обидві назви згадані в коментарі ВИЩЕ за
// саму гарантію. Міряємо аргументи `Promise.all` — початок рядка + відступ, без
// бектиків і маркерів списку, під які проза не підпадає.
ok('гарантія стоїть ДО обох персональних запитів',
   дані.indexOf('await authReady()') < дані.search(/\n\s+uid \? fetchSavedPostIds\(/)
   && дані.indexOf('await authReady()') < дані.search(/\n\s+fetchAllReactions\(/));

// ── АВТОБУСИ: розклад НЕ чекає, відстеження чекає ────────────────────────────
// 🛑 Тут гарантія мала б зіпсувати вкладку, якби її поставили «як усюди». Автобуси —
// єдина вкладка, що малюється з локального файлу і працює офлайн; `await` перед тілом
// `initBuses()` тримав би розклад порожнім до межі часу. Тому міряємо ДВА факти
// одразу: персональне чекає, а сама вкладка — ні.
const buses = projectFile('src/tabs/buses.js', REV);
ok('buses.js імпортує гарантію',
   /import \{[^}]*authReady[^}]*\} from '\.\.\/core\/auth\.js'/.test(buses));
const рейси = (buses.match(/async function loadTrackedRoute\(\)[\s\S]*?\n\}/) || [''])[0];
ok('loadTrackedRoute ЧЕКАЄ «хто я» ДО рішення про гостя',
   чекає(рейси), рейси ? 'тіло знайдено' : 'функцію не знайдено');
// 🔴 РОЗКЛАД НЕ СМІЄ ЧЕКАТИ. `initBuses()` не має права стати залежним від сесії:
// це зламало б офлайн заради підсвітки. Персональне йде окремою гілкою.
const init = (buses.match(/export async function initBuses\(\)[\s\S]*?loadPrefs\(\);[\s\S]*?flushPendingUnsub\(\);/) || [''])[0];
ok('initBuses НЕ чекає гарантію перед розкладом (офлайн цілий)',
   init.indexOf('await authReady()') < 0, init ? 'початок знайдено' : 'функцію не знайдено');
ok('самолікування push іде ПІСЛЯ факту, а не по порожньому списку',
   /loadTrackedRoute\(\)\.then\(\(\) => \{[\s\S]{0,400}?selfHealPushSubscriptions\(\)/.test(buses));
// 🛑 І ПАСТКА, ЯКУ ВІДКРИЛА САМА ЗМІНА: `hydrateTrackedFromDB()` ДОПИСУЄ в той самий
// список і зберігає його. Побачивши список ДО завантаження (порожній), він дописав би
// своє і зберіг — локальні відстеження цього телефона зникли б із памʼяті пристрою.
const підписка = (buses.match(/onAuthChange\(async \(\) => \{[\s\S]*?hydrateTrackedFromDB\(\);/) || [''])[0];
ok('у підписці завантаження ДОЧІКУЄТЬСЯ перед дописуванням із бази',
   /await loadTrackedRoute\(\);/.test(підписка)
   && підписка.indexOf('await loadTrackedRoute();') < підписка.indexOf('await hydrateTrackedFromDB();'),
   підписка ? 'підписку знайдено' : 'підписки не знайдено');

// ── КАПСУЛИ ГРОМАДИ: правило «максимум 3» робить перегони ВИДИМИМИ ───────────
// 🔑 Чотири ролі з шести персональні. Поки «хто я» невідоме, вони чесно віддають
// `null`, слоти дістаються неперсональним — а за мить підписка перемальовує смугу,
// і рядки міняються місцями в людини на очах. Тобто тут вада не «щось не
