// Стенд: СТРІЧКА МУСИТЬ РЕАГУВАТИ НА ЗМІНУ ВХОДУ.
//
// 🔴 СКАРГА ВОВИ (25.08, дослівно): «пропала можливість писати пости в всі
// спільноти де я Адмін чи учасник команди… це в мене вже стається другий чи
// третій раз… це треба пофіксити комплексно тому що в користувачів цього не
// має бути».
//
// 🔑 ЩО НАСПРАВДІ ЛАМАЛОСЬ — ПЕРЕГОНИ, А НЕ ПРАВА.
// `initAuth()` в `app.js` кличеться БЕЗ `await`. Якщо `loadData()` у Стрічці
// встигав раніше за відновлення сесії, `isLoggedIn()` ще давав false — і
// `fetchMyEditablePageIds()` навіть не викликався. `myPageIds` лишався ПОРОЖНІМ
// на всю сесію, а на ньому висять і композер «Написати пост…», і меню «⋯».
// Тобто ВЛАСНИК спільноти бачив її як стороння людина.
//
// 🛑 ЧОМУ ЦЕ НЕ ЛОВИЛОСЬ РАНІШЕ І ЧОМУ ВАДА «ЗНИКАЛА САМА»: перегони виграє то
// одне, то інше — звідси «другий чи третій раз», а не «завжди». А `onReturn`
// (повернення на вкладку) перечитував дані вже з відновленою сесією, тобто вада
// лікувалась сама і виглядала як примара. Саме тому потрібен СТОРОЖ, а не «я
// перевірив, працює».
//
// 📐 ЩО САМЕ МІРЯЄМО. Довести перегони в браузері означало б відтворити точний
// порядок двох незалежних обіцянок — це перевірка на власну симуляцію, а не на
// застосунок. Тому міряємо ІНВАРІАНТИ, які роблять перегони нешкідливими,
// і ОКРЕМО — правило класу, щоб та сама вада не завелась у сусідньому файлі.
//
// 🔴 КОНТРОЛЬ: BUNDLE_REV=origin/main node tests/feed-auth-race.mjs
// На коді до фіксу перевірки 1-4 мусять УПАСТИ.
import { chromium } from 'playwright';
import { readdirSync } from 'fs';
import { join } from 'path';
import { projectFile, ROOT, launch } from './_lib.mjs';

const REV = process.env.BUNDLE_REV || '';
const res = [];
const ok = (n, c, i = '') => { res.push(c); console.log(`${c ? '✅' : '❌'} ${n}${i ? '  — ' + i : ''}`); };

const feed = projectFile('src/tabs/feed.js', REV);

console.log(`\n── СТРІЧКА РЕАГУЄ НА ВХІД${REV ? `   (КОНТРОЛЬ на ${REV})` : ''}`);

// 1-2. Сам механізм: підписка є і вона справді перечитує дані.
ok('feed.js імпортує onAuthChange', /import \{[^}]*onAuthChange[^}]*\} from '\.\.\/core\/auth\.js'/.test(feed));
ok('на зміну входу Стрічка ПЕРЕЧИТУЄ дані',
   /onAuthChange\(\(\) => \{[\s\S]{0,400}?loadData\(\)/.test(feed));

// 2-БІС. 🔴 ГОЛОВНИЙ ІНВАРІАНТ ПІСЛЯ ПЕРЕПИСУВАННЯ 25.08: Стрічка ЧЕКАЄ факт «хто я»
//    ДО того, як читати дані. Без цього підписка лишалась би «лікарем після факту» —
//    спершу малюємо вигляд гостя, потім перемальовуємо. Саме це Вова й бачив.
const тіло = (feed.match(/async function loadData\(\)[\s\S]*?Promise\.all/) || [''])[0];
ok('loadData ЧЕКАЄ «хто я» ДО читання даних',
   /await authReady\(\)/.test(тіло), тіло ? 'тіло знайдено' : 'loadData не знайдено');
ok('feed.js імпортує саму гарантію',
   /import \{[^}]*authReady[^}]*\} from '\.\.\/core\/auth\.js'/.test(feed));

// 3. 🔑 Звірка з попереднім входом. Без неї фікс сам стає вадою: подія шлеться
//    кілька разів поспіль про ТУ САМУ людину (відновлення сесії → оновлення
//    токена → прогрів профілю), і стрічка тяглася б з мережі 2-3 рази на старт.
ok('перечитуємо ЛИШЕ коли вхід справді змінився',
   /currentUserId\(\) === loadedForUid/.test(feed) && /loadedForUid = currentUserId\(\);/.test(feed));

// 4. 🛑 Фікс не сміє чіпати шар і історію браузера. Повторне відкриття екрана
//    заради композера зачепило б `openLayer` і жест «назад» — а це рівно та зона,
//    де проєкт уже двічі обпікався (PR #638 і #641, HOT_RULES №9 і №10).
const patch = (feed.match(/function patchOpenScreenRights\(\)[\s\S]*?\n\}/) || [''])[0];
ok('домальовка композера НЕ чіпає шар/історію',
   patch.length > 0 && !/openLayer|closeLayer|openPageScreen/.test(patch),
   patch ? 'функція є, шар не чіпає' : 'функції немає');

console.log('\n── ГАРАНТІЯ «ХТО Я» ВИКОНУЄТЬСЯ НАСПРАВДІ (не регулярка)');

// 🔑 ЦЕ ГОЛОВНА ЧАСТИНА СТЕНДА. Вище — інваріанти в тексті коду; тут ми БЕРЕМО
// справжній `auth.js`, підсовуємо йому підроблену базу і ВИКОНУЄМО три сценарії,
// які й вирішують, чи буде вада. Регулярка не відрізнила б робочу гарантію від
// написаної з помилкою — а саме така помилка й коштувала б повернення скарги.
// ⚠️ Беремо `auth.js` ТІЄЇ САМОЇ ревізії, що й решта стенда. Інакше контрольний
// прогін виконував би свіжу гарантію і світився зеленим над кодом, де її немає, —
// «контроль, який не може впасти» у цьому проєкті вже траплявся (17.08).
const authSrc = projectFile('src/core/auth.js', REV)
  // Вирізаємо імпорти й робимо модуль інлайновим — рівно так само, як це вже
  // робить стенд клавіатури з `core/keyboard.js`.
  .replace(/^import .*$/gm, '')
  .replace(/^export /gm, '');

const сцена = (режим) => `<!doctype html><html><head><meta charset="utf-8"></head><body><script type="module">
  const showToast = () => {};
  const netErrorText = () => ''; const netCall = async () => ({ ok: true });
  const releasePushDevice = async () => {};
  // Підроблена база: три режими — сесія є, сесії нема, виклик ВИСНЕ назавжди.
  const getSupabase = () => (${режим === 'нема-бази' ? 'null' : `({
    auth: {
      getSession: ${режим === 'висне'
        ? 'async () => new Promise(() => {})'
        : режим === 'гість'
          ? 'async () => ({ data: { session: null } })'
          : 'async () => ({ data: { session: { user: { id: "u-1" } } } })'},
      onAuthStateChange: () => ({ data: { subscription: { unsubscribe() {} } } }),
    },
    from: () => ({ select: () => ({ eq: () => ({ maybeSingle: async () => ({ data: null }) }) }) }),
  })`});
  ${authSrc}
  window.__t0 = performance.now();
  window.__ready = null;
  authReady(400).then(() => { window.__ready = Math.round(performance.now() - window.__t0); });
  initAuth();
  window.__uid = () => currentUserId();
  // Друге очікування вже після того, як факт відомий — має бути миттєвим.
  window.__second = async () => { const t = performance.now(); await authReady(400); return Math.round(performance.now() - t); };
</script></body></html>`;

const b2 = await launch(chromium);
const прогнати = async (режим) => {
  const p = await b2.newPage();
  await p.setContent(сцена(режим));
  await p.waitForTimeout(700);
  // На старому коді гарантії немає взагалі — модуль впаде на `authReady is not
  // defined`. Це не збій стенда, а очікуваний результат контролю, тож ловимо.
  const r = await p.evaluate(async () => {
    try { return { ready: window.__ready, uid: window.__uid ? window.__uid() : null,
                   second: window.__second ? await window.__second() : null }; }
    catch (_) { return { ready: null, uid: null, second: null }; }
  });
  await p.close();
  return r;
};

const людина = await прогнати('людина');
const гість  = await прогнати('гість');
const висне  = await прогнати('висне');
const безБази = await прогнати('нема-бази');
await b2.close();

console.log(`   сесія є:      готово через ${людина.ready}мс · uid=${людина.uid} · друге очікування ${людина.second}мс`);
console.log(`   гість:        готово через ${гість.ready}мс · uid=${гість.uid}`);
console.log(`   виклик висне: готово через ${висне.ready}мс (межа 400) · uid=${висне.uid}`);
console.log(`   бази немає:   готово через ${безБази.ready}мс · uid=${безБази.uid}`);

// 🔴 Головне: коли гарантія завершилась, «хто я» ВЖЕ відомо. Саме цього бракувало.
ok('сесія є → на момент готовності uid уже відомий', людина.uid === 'u-1', `uid=${людина.uid}`);
ok('готовність настає швидко, а не по межі часу', людина.ready != null && людина.ready < 300, `${людина.ready}мс`);
ok('гість — теж відповідь, а не очікування', гість.ready != null && гість.ready < 300, `${гість.ready}мс`);
// 🛑 Найдорожча перевірка: завислий виклик НЕ сміє підвісити вкладку назавжди.
// Це той самий клас, що `serviceWorker.ready` — воно не падає, воно ВИСНЕ.
ok('завислий виклик НЕ вішає вкладку — межа часу спрацьовує',
   висне.ready != null && висне.ready >= 350 && висне.ready < 700, `${висне.ready}мс`);
ok('бази немає → гість одразу, без чекання межі',
   безБази.ready != null && безБази.ready < 300, `${безБази.ready}мс`);
// Повторне очікування вже після факту має коштувати нуль.
ok('друге очікування миттєве (факт уже відомий)', людина.second <= 30, `${людина.second}мс`);

console.log('\n── ПРАВИЛО КЛАСУ: хто кешує МОЇ права — той їх і перечитує');

// 🔑 Вада була не в правах, а в КЕШУВАННІ прав при старті. Модалка чи екран,
// відкриті на вимогу, читають свіжий стан самі — їм підписка не потрібна, і
// вимагати її від усіх було б хибним правилом із купою фальшивих спрацювань.
// Небезпечні рівно ті файли, які складають «моє» у власну змінну модуля один раз
// при завантаженні.
//
// 🔴 25.08, РОЗШИРЕНО РАЗОМ ІЗ РОБОТОЮ (беклог, пункт 0). Було звужено до Стрічки
// («сьогодні такий рівно один»), і саме тому Дошка могла роками мати ту саму ваду
// зеленою: `refreshUnreadBadge()` складає `_unreadChats`, `_hasThreads` і
// `_unreadTop` при старті — тобто рівно кешує «моє», тільки називається інакше.
// ➡️ ПРАВИЛО ДЛЯ НАСТУПНОЇ СЕСІЇ: узяв вкладку — додай сюди її функцію, інакше
// сторож мовчки перестає її стерегти.
const ФУНКЦІЇ_ПРАВ = /fetchMyEditablePageIds|fetchMySubscriptions|fetchThreadPairs/;
const tabsDir = join(ROOT, 'src', 'tabs');
// 🛑 ЧИТАЄМО ЧЕРЕЗ `projectFile`, А НЕ З ДИСКУ (виправлено 25.08). Було
// `readFileSync` — і правило класу не реагувало на `BUNDLE_REV` взагалі: у
// контрольному прогоні на `origin/main` обидва рядки лишались ЗЕЛЕНИМИ, хоч мали
// показати рівно ту ваду, заради якої контроль і запускають. Тобто перевірка не
// вміла впасти — той самий клас, що «контроль, який нічого не контролює».
// ⚠️ Перелік ФАЙЛІВ і далі з диска (нових вкладок у старій ревізії просто немає);
// з `rev` беремо ВМІСТ, а зниклий у тій ревізії файл пропускаємо.
const вкладки = readdirSync(tabsDir).filter(n => n.endsWith('.js'));
const читати = (f) => {
  try { return projectFile(`src/tabs/${f}`, REV); } catch (_) { return ''; }
};
const винні = [];
for (const f of вкладки) {
  const src = читати(f);
  if (ФУНКЦІЇ_ПРАВ.test(src) && !/onAuthChange/.test(src)) винні.push(f);
}
ok('кожен, хто кешує мої права, підписаний на зміну входу',
   винні.length === 0, винні.length ? `без підписки: ${винні.join(', ')}` : 'порушників немає');

// 🔑 І ДРУГА ПОЛОВИНА ТОГО САМОГО ПРАВИЛА. Підписка робить показ правдивим ПІСЛЯ
// зміни входу; гарантія робить правдивим ПЕРШИЙ показ. Одного без іншого мало:
// без підписки не побачиш входу посеред сесії, без гарантії блимне вигляд гостя.
const безГарантії = [];
for (const f of вкладки) {
  const src = читати(f);
  if (ФУНКЦІЇ_ПРАВ.test(src) && !/authReady/.test(src)) безГарантії.push(f);
}
ok('кожен, хто кешує мої права, ЧЕКАЄ факт перед першим показом',
   безГарантії.length === 0,
   безГарантії.length ? `без гарантії: ${безГарантії.join(', ')}` : 'порушників немає');

// 🔑 І ОКРЕМО — САМЕ ЦЯ ВКЛАДКА, ІМЕННО, А НЕ ЛИШЕ ЧЕРЕЗ РЕГУЛЯРКУ КЛАСУ.
// Правило класу ловить файл, але не каже, У ЯКОМУ МІСЦІ стоїть гарантія. А ціна
// помилки тут конкретна: `initBoardChat()` кличе `refreshUnreadBadge()` ПЕРШИМ
// рядком, отже без очікування бейдж, крапка вкладки і капсула «ПОВІДОМЛЕННЯ»
// малюють вигляд гостя людині, якій писали.
const chat = projectFile('src/tabs/board-chat.js', REV);
ok('board-chat.js імпортує гарантію',
   /import \{[^}]*authReady[^}]*\} from '\.\.\/core\/auth\.js'/.test(chat));
// Міряємо ПОРЯДОК усередині функції: очікування мусить стояти ДО першої перевірки
// входу, інакше воно нічого не гарантує — рішення вже ухвалене.
// 🛑 УРОК 25.08, КУПЛЕНИЙ ПРЯМО ТУТ: перша редакція цієї мірки шукала позицію
// підрядка `if (!isLoggedIn())` — і знайшла його В КОМЕНТАРІ, який пояснює, чому
// раннього виходу тут бути не сміє. Перевірка впала на СПРАВНОМУ коді.
// ➡️ Міряємо ОПЕРАТОР, а не текст: `if (!isLoggedIn()) {` на початку рядка. Проза
// в коментарі під це не підпадає, бо там немає відкритої дужки блоку.
const гейт = /\n\s*if \(!isLoggedIn\(\)\) \{/;
const чекає = (тіло) => {
  const a = тіло.indexOf('await authReady()');
  const g = тіло.search(гейт);
  return a >= 0 && g >= 0 && a < g;
};
const бейдж = (chat.match(/export async function refreshUnreadBadge\(\)[\s\S]*?\n\}/) || [''])[0];
ok('refreshUnreadBadge ЧЕКАЄ «хто я» ДО рішення про гостя',
   чекає(бейдж), бейдж ? 'тіло знайдено' : 'функцію не знайдено');
const тред = (chat.match(/export async function openThreadById\([\s\S]*?\n\}/) || [''])[0];
ok('openThreadById ЧЕКАЄ «хто я» ДО відкладеного наміру',
   чекає(тред), тред ? 'тіло знайдено' : 'функцію не знайдено');
// 🛑 І страховка на те, що ми не «полагодили» перегони ціною втрати другого
// механізму: відкладений намір мусить лишитись на місці (справжній вхід руками).
ok('відкладений намір по сповіщенню НЕ прибрано',
   /_pendingThreadId/.test(тред) && /_pendingThreadUntil/.test(тред));

// Контроль самого правила: воно мусить УМІТИ спрацювати. Інакше зелений рядок
// нічого не вартий — саме так у проєкті вже був «контроль, який не може впасти».
const підробка = 'const x = fetchMyEditablePageIds();';
ok('КОНТРОЛЬ: правило справді ловить файл без підписки',
   ФУНКЦІЇ_ПРАВ.test(підробка) && !/onAuthChange/.test(підробка));
// 🔴 І КОНТРОЛЬ САМОЇ МІРКИ ПОРЯДКУ. Без нього зелений рядок вище нічого не
// вартий: перевірка, яка не вміє впасти, у цьому проєкті вже траплялась.
ok('КОНТРОЛЬ: мірка порядку ловить гарантію ПІСЛЯ гейта',
   !чекає('\n  if (!isLoggedIn()) {\n    return;\n  }\n  await authReady();')
   && чекає('\n  await authReady();\n  if (!isLoggedIn()) {\n    return;\n  }'));

const bad = res.filter(r => !r).length;
console.log(`\n${bad ? '❌' : '✅'} ${res.length - bad}/${res.length} перевірок пройдено`);
process.exit(bad ? 1 : 0);
