// Стенд: СТРІЧКА МУСИТЬ РЕАГУВАТИ НА ЗМІНУ ВХОДУ.
//
// 🔴 СКАРГА ВОВИ (25.08, дослівно): «пропала можливість писати пости в всі
// спільноти де я Адмін чи учасник команди… це в мене вже стається другий чи
// третій раз… це треба пофіксити комплексно тому що в користувачів цього не
// має бути».
//
// 🔑 ЩО НАСПРАВДІ ЛАМАЛОСЬ — ПЕРЕГОНИ, А НЕ ПРАВА.
// `initAuth()` в `app.js` кличеться БЕЗ `await`. Якщо `loadData()` у Стрічці
// встигав раніше за відновлення сесії, `isLoggedIn()` ще давав false — і
// `fetchMyEditablePageIds()` навіть не викликався. `myPageIds` лишався ПОРОЖНІМ
// на всю сесію, а на ньому висять і композер «Написати пост…», і меню «⋯».
// Тобто ВЛАСНИК спільноти бачив її як стороння людина.
//
// 🛑 ЧОМУ ЦЕ НЕ ЛОВИЛОСЬ РАНІШЕ І ЧОМУ ВАДА «ЗНИКАЛА САМА»: перегони виграє то
// одне, то інше — звідси «другий чи третій раз», а не «завжди». А `onReturn`
// (повернення на вкладку) перечитував дані вже з відновленою сесією, тобто вада
// лікувалась сама і виглядала як примара. Саме тому потрібен СТОРОЖ, а не «я
// перевірив, працює».
//
// 📐 ЩО САМЕ МІРЯЄМО. Довести перегони в браузері означало б відтворити точний
// порядок двох незалежних обіцянок — це перевірка на власну симуляцію, а не на
// застосунок. Тому міряємо ІНВАРІАНТИ, які роблять перегони нешкідливими,
// і ОКРЕМО — правило класу, щоб та сама вада не завелась у сусідньому файлі.
//
// 🔴 КОНТРОЛЬ: BUNDLE_REV=origin/main node tests/feed-auth-race.mjs
// На коді до фіксу перевірки 1-4 мусять УПАСТИ.
import { readdirSync, readFileSync } from 'fs';
import { join } from 'path';
import { projectFile, ROOT } from './_lib.mjs';

const REV = process.env.BUNDLE_REV || '';
const res = [];
const ok = (n, c, i = '') => { res.push(c); console.log(`${c ? '✅' : '❌'} ${n}${i ? '  — ' + i : ''}`); };

const feed = projectFile('src/tabs/feed.js', REV);

console.log(`\n── СТРІЧКА РЕАГУЄ НА ВХІД${REV ? `   (КОНТРОЛЬ на ${REV})` : ''}`);

// 1-2. Сам механізм: підписка є і вона справді перечитує дані.
ok('feed.js імпортує onAuthChange', /import \{[^}]*onAuthChange[^}]*\} from '\.\.\/core\/auth\.js'/.test(feed));
ok('на зміну входу Стрічка ПЕРЕЧИТУЄ дані',
   /onAuthChange\(\(\) => \{[\s\S]{0,400}?loadData\(\)/.test(feed));

// 3. 🔑 Звірка з попереднім входом. Без неї фікс сам стає вадою: подія шлеться
//    кілька разів поспіль про ТУ САМУ людину (відновлення сесії → оновлення
//    токена → прогрів профілю), і стрічка тяглася б з мережі 2-3 рази на старт.
ok('перечитуємо ЛИШЕ коли вхід справді змінився',
   /currentUserId\(\) === loadedForUid/.test(feed) && /loadedForUid = currentUserId\(\);/.test(feed));

// 4. 🛑 Фікс не сміє чіпати шар і історію браузера. Повторне відкриття екрана
//    заради композера зачепило б `openLayer` і жест «назад» — а це рівно та зона,
//    де проєкт уже двічі обпікався (PR #638 і #641, HOT_RULES №9 і №10).
const patch = (feed.match(/function patchOpenScreenRights\(\)[\s\S]*?\n\}/) || [''])[0];
ok('домальовка композера НЕ чіпає шар/історію',
   patch.length > 0 && !/openLayer|closeLayer|openPageScreen/.test(patch),
   patch ? 'функція є, шар не чіпає' : 'функції немає');

console.log('\n── ПРАВИЛО КЛАСУ: хто кешує МОЇ права — той їх і перечитує');

// 🔑 Вада була не в правах, а в КЕШУВАННІ прав при старті. Модалка чи екран,
// відкриті на вимогу, читають свіжий стан самі — їм підписка не потрібна, і
// вимагати її від усіх було б хибним правилом із купою фальшивих спрацювань.
// Небезпечні рівно ті файли, які складають «мої права» у власну змінну модуля
// один раз при завантаженні. Сьогодні такий рівно один — Стрічка.
const ФУНКЦІЇ_ПРАВ = /fetchMyEditablePageIds|fetchMySubscriptions/;
const tabsDir = join(ROOT, 'src', 'tabs');
const винні = [];
for (const f of readdirSync(tabsDir).filter(n => n.endsWith('.js'))) {
  const src = readFileSync(join(tabsDir, f), 'utf8');
  if (ФУНКЦІЇ_ПРАВ.test(src) && !/onAuthChange/.test(src)) винні.push(f);
}
ok('кожен, хто кешує мої права, підписаний на зміну входу',
   винні.length === 0, винні.length ? `без підписки: ${винні.join(', ')}` : 'порушників немає');

// Контроль самого правила: воно мусить УМІТИ спрацювати. Інакше зелений рядок
// нічого не вартий — саме так у проєкті вже був «контроль, який не може впасти».
const підробка = 'const x = fetchMyEditablePageIds();';
ok('КОНТРОЛЬ: правило справді ловить файл без підписки',
   ФУНКЦІЇ_ПРАВ.test(підробка) && !/onAuthChange/.test(підробка));

const bad = res.filter(r => !r).length;
console.log(`\n${bad ? '❌' : '✅'} ${res.length - bad}/${res.length} перевірок пройдено`);
process.exit(bad ? 1 : 0);
