// Стенд: МІНІФІКАЦІЯ НЕ МІНЯЄ КАСКАД.
//
// 🔴 НАВІЩО. 24.09 стилі почали збиратись і мініфікуватись: 24 файли через
// ланцюжок `@import` (385 КБ gzip сумарно) стали одним файлом на 52 КБ gzip.
// Виграш великий, але й ризик реальний: якщо мініфікатор викине «зайве»
// оголошення — наприклад, другий `display` поруч із `-webkit-line-clamp`, —
// екран поїде тихо, і помітить це житель, а не ми.
//
// 🛑 ЧОМУ НЕ БРАУЗЕРНИЙ ЗЛІПОК. `tests/tools/css-snapshot.mjs` міряє обчислені
// стилі живих екранів — це сильніший доказ, і він ТЕЖ прогнаний (0 розбіжностей
// на 197 елементах). Але він часозалежний: один прогін із чотирьох показав
// розбіжності, які виявились різним вмістом оголошень, а не стилем. Сторож,
// який раз на чотири прогони червоніє без причини, перестають читати.
// ➡️ Тому щоденна перевірка — детермінована і текстова, а зліпок лишається
//    важким інструментом для великих переїздів каскаду.
//
// 🔑 ЩО САМЕ ПОРІВНЮЄМО — і чому не «список пар по порядку».
// Перша редакція цього стенда звіряла впорядкований список «селектор →
// властивість» і червоніла на 31 місці. Жодне з них не було вадою: esbuild
// ЗАКОННО переписує стилі, і саме ці переписування треба було навчитись
// не помічати (кожне заміряне на живій збірці, не з голови):
//   1. `@keyframes`: `100%` стає `to`, `from` стає `0%`;
//   2. однакові тіла склеюються: `.a{x}.b{x}` → `.a,.b{x}`;
//   3. пробіли зникають зі списків селекторів і зсередини `:is(a, b)`;
//   4. `::before` стає `:before`;
//   5. чотири `top/right/bottom/left` згортаються в один `inset`,
//      `margin` + `margin-bottom` — в один `margin`.
// ➡️ Тому звіряємо НЕ порядок, а КАРТУ: для кожного окремого селектора (групи
//    розбиті) — які властивості на ньому лишились. Значення не звіряємо
//    навмисно: `#ffffff` → `#fff` це шум, а не каскад.
//
// ⚠️ КІЛЬКІСТЬ ЗВІРЯЄМО ТІЛЬКИ ТАМ, ДЕ ЗГОРТКА НЕМОЖЛИВА. Для властивостей без
// збірної родини (`display`, `-webkit-line-clamp`, `color`…) два оголошення
// мусять лишитись двома — це і є захист від того самого `display`-дубля.
// Для збірних родин (`inset`, `margin`, `padding`…) вимагаємо лише наявність,
// бо згортка чотирьох в одне — законна.

import { gzipSync } from 'zlib';
import { readFileSync } from 'fs';
import { join, dirname, resolve } from 'path';
import { ROOT, reporter } from './_lib.mjs';

const { ok, done } = reporter();
const esbuild = await import(join(ROOT, 'node_modules/esbuild/lib/main.js'));

const СПІЛЬНЕ = {
  entryPoints: [join(ROOT, 'style.css')],
  bundle: true,
  charset: 'utf8',
  external: ['*.png', '*.jpg', '*.svg', '*.woff', '*.woff2', '*.gif', '*.webp'],
  write: false,
};

const сирий = esbuild.buildSync({ ...СПІЛЬНЕ, minify: false }).outputFiles[0].text;
const малий = esbuild.buildSync({ ...СПІЛЬНЕ, minify: true  }).outputFiles[0].text;

const гз = t => gzipSync(Buffer.from(t)).length;
const кб = n => (n / 1024).toFixed(0);

// 🔑 ЧЕСНИЙ ЗАМІР «БУЛО». «Було» — це не складений файл, а 24 окремі файли, які
// браузер тягнув ланцюжком `@import`: `style.css` імпортує `style/base.css`,
// той наступний, і кожен наступний запит починався лише після попереднього.
// Тому рахуємо суму gzip усіх файлів ланцюжка, а не один складений.
function ланцюжок(файл, бачив = new Set()) {
  файл = resolve(файл);
  if (бачив.has(файл)) return [];
  бачив.add(файл);
  let t;
  try { t = readFileSync(файл); } catch { return []; }
  const свої = [t];
  for (const m of t.toString().matchAll(/@import\s+(?:url\()?["']([^"']+)["']/g)) {
    if (/^https?:/.test(m[1])) continue;
    свої.push(...ланцюжок(join(dirname(файл), m[1]), бачив));
  }
  return свої;
}

const файли = ланцюжок(join(ROOT, 'style.css'));
const булоGz = файли.reduce((s, t) => s + гз(t), 0);

ok('складений файл зібрався', сирий.length > 100000, `${кб(сирий.length)} КБ сирих`);
ok('було саме ланцюжком файлів', файли.length > 15, `${файли.length} файлів через @import`);

// ⚠️ ЧЕСНО ПРО ТЕ, ЗВІДКИ ВИГРАШ (заміряно, не з голови):
//    24 файли, 385 КБ gzip сумарно → один файл, 52 КБ gzip.
//    Але більшість цього дає НЕ мініфікація, а сама збірка: esbuild викидає
//    коментарі (у цих файлах їх ~900 КБ), тож складений-без-мініфікації вже
//    57 КБ gzip. Мініфікація зверху додає лише 57 → 52 КБ.
//    ➡️ Головний виграш збірки — не байти, а зняття послідовного ланцюжка
//       з 24 запитів, де кожен чекав на попередній.
ok('один файл замість ланцюжка важить у рази менше', гз(малий) < булоGz * 0.25,
   `${кб(гз(малий))} КБ проти ${кб(булоGz)} КБ gzip (${файли.length} файлів)`);
ok('мініфікація зверху ще трохи зрізає', гз(малий) < гз(сирий),
   `${кб(гз(малий))} проти ${кб(гз(сирий))} КБ gzip`);

// ── Розбір ──────────────────────────────────────────────────────────────────

// Збірні родини: тут згортка законна, тому звіряємо лише наявність.
const РОДИНИ = ['inset', 'margin', 'padding', 'border-radius', 'border', 'background',
  'font', 'flex', 'gap', 'grid-area', 'overflow', 'transition', 'animation',
  'outline', 'mask', 'place-items', 'place-content', 'inset-inline', 'inset-block'];
const ЧАСТИНИ_INSET = ['top', 'right', 'bottom', 'left'];

function родина(p) {
  p = p.replace(/^-(webkit|moz|ms|o)-/, '');
  if (ЧАСТИНИ_INSET.includes(p)) return 'inset';
  for (const г of РОДИНИ) if (p === г || p.startsWith(г + '-')) return г;
  return p;
}

const крок = s => s.replace(/\bfrom\b/g, '0%').replace(/\bto\b/g, '100%');

// Верхньорівневий спліт по комах: `:is(a, b) .c, .d` це ДВА селектори, а не три.
function розбити(сел) {
  const out = []; let гл = 0, б = '';
  for (const c of сел) {
    if (c === '(') гл++; if (c === ')') гл--;
    if (c === ',' && гл === 0) { out.push(б); б = ''; } else б += c;
  }
  out.push(б);
  return out.map(s => s.trim()).filter(Boolean);
}

const норм = s => s
  .replace(/::(before|after|first-line|first-letter|placeholder|selection|backdrop|marker)\b/g, ':$1')
  .replace(/\s*([>+~,])\s*/g, '$1')
  .replace(/\s+/g, ' ').trim().toLowerCase();

// Розбір, що рахує дужки: `@media` і `@supports` вкладені, тож наївний спліт по
// `}` зібрав би сміття. Беремо тільки ЛИСТКОВІ правила — ті, у чиєму тілі вже
// немає `{`. Саме вони й несуть оголошення.
function карта(css) {
  const m = new Map();
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  let i = 0, шлях = [], буфер = '';
  while (i < css.length) {
    const c = css[i];
    if (c === '{') {
      шлях.push(буфер.trim().replace(/\s+/g, ' ')); буфер = ''; i++;
      const закр = css.indexOf('}', i), відкр = css.indexOf('{', i);
      if (закр !== -1 && (відкр === -1 || закр < відкр)) {
        const тіло = css.slice(i, закр);
        const конт = шлях.slice(0, -1).map(x => норм(крок(x))).join(' ▸ ');
        const вКейфреймах = /@keyframes/i.test(конт);
        for (const один of розбити(шлях[шлях.length - 1])) {
          const ключ = (конт ? конт + ' ▸ ' : '') + норм(вКейфреймах ? крок(один) : один);
          if (!m.has(ключ)) m.set(ключ, new Map());
          const лічильник = m.get(ключ);
          for (const д of тіло.split(';')) {
            const двокр = д.indexOf(':');
            if (двокр < 1) continue;
            const f = родина(д.slice(0, двокр).trim().toLowerCase());
            лічильник.set(f, (лічильник.get(f) || 0) + 1);
          }
        }
        i = закр + 1; шлях.pop();
      }
      continue;
    }
    if (c === '}') { шлях.pop(); буфер = ''; i++; continue; }
    буфер += c; i++;
  }
  return m;
}

// Повертає список розбіжностей «що втратив мініфікований проти сирого».
function звірити(A, B) {
  const біди = [];
  for (const [ключ, властивості] of A) {
    const там = B.get(ключ);
    if (!там) { біди.push(`зник селектор ${ключ}`); continue; }
    for (const [p, скільки] of властивості) {
      const стало = там.get(p) || 0;
      if (стало === 0) { біди.push(`${ключ} ▸ ${p} зникла`); continue; }
      if (!РОДИНИ.includes(p) && стало !== скільки) {
        біди.push(`${ключ} ▸ ${p}: було ${скільки}, стало ${стало}`);
      }
    }
  }
  for (const ключ of B.keys()) if (!A.has(ключ)) біди.push(`зайвий селектор ${ключ}`);
  return біди;
}

const A = карта(сирий), B = карта(малий);
ok('знайшов селектори для звірки', A.size > 1500, `${A.size} селекторів`);

const біди = звірити(A, B);
ok('жодна властивість не зникла і жоден селектор не додався',
   біди.length === 0,
   біди.length === 0 ? `${A.size} селекторів збіглися` : `${біди.length}: ${біди.slice(0, 3).join(' · ')}`);

// ── Мутації ─────────────────────────────────────────────────────────────────
// 🛑 Без них «зелено» могло б означати «розбір нічого не знайшов».

// 1) Дубль `display` поруч із `-webkit-line-clamp` — рівно той випадок, якого
//    боїмось. Розбір мусить побачити ОБИДВА, і звірка мусить червоніти, якщо
//    один зник.
const ДУБЛЬ = '.x{display:block;-webkit-line-clamp:2;display:-webkit-box}';
ok('розбір бачить обидва однойменні оголошення',
   карта(ДУБЛЬ).get('.x')?.get('display') === 2);
ok('звірка червоніє, коли дубль загубився',
   звірити(карта(ДУБЛЬ), карта('.x{display:block;-webkit-line-clamp:2}')).length === 1);

// 2) Зникла звичайна властивість.
ok('звірка червоніє, коли властивість зникла',
   звірити(карта('.y{color:red;opacity:.5}'), карта('.y{color:red}')).length === 1);

// 3) Законна згортка чотирьох сторін в `inset` мусить лишатись зеленою —
//    інакше стенд червонів би на кожній збірці й перестав би щось значити.
ok('звірка мовчить на законній згортці в inset',
   звірити(карта('.z{top:0;right:0;bottom:0;left:0}'), карта('.z{inset:0}')).length === 0);

// 4) Розбір заходить усередину @media — інакше половина файлу йшла б повз нього.
ok('розбір заходить усередину @media',
   [...карта('@media (max-width:400px){.y{color:red}}').keys()].some(k => k.includes('@media') && k.includes('.y')));

// 5) Групу селекторів розбиваємо на окремі — інакше склейка `.a,.b` читалась би
//    як «зник `.a`, зʼявився `.a,.b`».
ok('група селекторів розбивається на окремі',
   звірити(карта('.a{color:red}.b{color:red}'), карта('.a,.b{color:red}')).length === 0);

done();
