//
// 🗣️ Замовлення Вови, дослівно з розмови про систему оновлень: «Роби… зроби
// сторожа, який червонітиме, коли новий екран додано БЕЗ прапорця».
// Привід — моє ж зізнання в тій самій відповіді: «якщо я забуду поставити фічу
// за прапорець — вона поїде всім одразу, і жодна кнопка в адмінці цього не
// спинить. Запобіжника від моєї забудькуватості зараз немає».
//
// 🔑 ЩО ТАКЕ «ПОВЕРХНЯ». Те, що людина БАЧИТЬ і може ТАПНУТИ: пункт бічного
// меню, вкладка таб-бара, розділ адмінки. Не файл, не функція, не модуль —
// інакше стенд червонів би на кожен рефакторинг і його б вимкнули за тиждень.
//
// 🛑 ЧОГО ЦЕЙ СТЕНД НЕ ВМІЄ І НЕ ВДАЄ, ЩО ВМІЄ.
// Він не вміє відрізнити «нову» поверхню від «старої» — у коді такої ознаки
// немає. Він вміє інше й важливіше: помітити поверхню, про яку РІШЕННЯ НЕ
// ЗАПИСАНЕ. Тобто він не змушує ставити прапорець (це рішення людини), він
// змушує ПОДУМАТИ і записати відповідь. Це різні речі, і плутати їх не можна.
//
// 🛑 І ДРУГЕ, ЧОГО ТУТ НЕМАЄ НАВМИСНО: жодної прив'язки до `origin/main`.
// Порівняння «що з'явилось проти гілки» здавалось очевиднішим рішенням і було б
// пасткою: два мої контролі вже читали стан гілки і після мерджу почали падати
// назавжди — зламались від власного успіху (правило в `NOW.md`). Реєстр живе в
// репо поруч із кодом і від стану гілки не залежить узагалі.
//
// 🧪 ДОВЕДЕНО ТРЬОМА МУТАЦІЯМИ (19.09, не припущення — прогін):
//   1. пункт «Галерея громади» дописано в меню повз реєстр → 8/9, падає блок 1;
//   2. `SECTIONS` перейменовано, тобто прилад ОСЛІП → 7/9. 🔑 І ось головне, що
//      показав цей прогін: блок 1 при цьому лишився ЗЕЛЕНИЙ — «перевірено 20
//      поверхонь» замість 37. Без блоку 0 стенд мовчки стеріг би дві третини
//      застосунку і рапортував успіх;
//   3. у ЗА_ПРАПОРЦЕМ вписано ключ, якого в коді немає → 8/9, падає блок 4.

import { reporter, projectFile } from './_lib.mjs';

const { ok, done } = reporter();

// ── РЕЄСТР РІШЕНЬ ─────────────────────────────────────────────────────────
//
// 🔑 Три списки, а не один із причиною в кожному рядку: 30 однакових причин
// «існувало до системи прапорців» — це шум, у якому потоне справжнє рішення.

// Поверхні, що жили в застосунку ДО 19.09, коли системи прапорців ще не було.
// Їх ніхто не ховав і ховати нема сенсу: громада бачить їх місяцями.
const ДО_ПРАПОРЦІВ = new Set([
  // бічне меню
  'account', 'cabinet',
  'community', 'shotam', 'discussions', 'board', 'buses', 'news', 'fund',
  'messages', 'myads', 'saved',
  'contacts', 'support', 'boardrules', 'policy',
  // таб-бар
  'tab:community', 'tab:shotam', 'tab:discussions', 'tab:board', 'tab:buses', 'tab:power',
  // адмінка
  'admin:articles', 'admin:board', 'admin:questions', 'admin:reports',
  'admin:announcements', 'admin:fundraisers', 'admin:communities',
  'admin:people', 'admin:admins', 'admin:access',
  'admin:spend', 'admin:analytics', 'admin:settings',
]);

// Поверхні ЗА ПРАПОРЦЕМ: ключ фічі, яким вони вмикаються.
// ⚠️ Ключ перевіряється в коді (блок 4) — запис «за прапорцем» без прапорця в
// коді був би найгіршим видом брехні: він знімає пильність рівно там, де вона
// потрібна.
const ЗА_ПРАПОРЦЕМ = new Map([
  // (поки порожньо — перша фіча за прапорцем з'явиться з першим оновленням)
]);

// Нові поверхні, які свідомо їдуть БЕЗ прапорця. Причина обов'язкова і має
// відповідати на питання «чому громаді можна це побачити одразу».
const СВІДОМО_БЕЗ = new Map([
  ['as-resident',
   'Сам перемикач системи оновлень. Ховати його за прапорцем — замкнене коло: ' +
   'щоб увімкнути прапорець, треба спершу побачити перемикач. До того ж він ' +
   'уже схований інакше — показується лише тим, хто в колі раннього доступу.'],
  ['admin:updates',
   'Розділ «Оновлення» в адмінці. Та сама причина: це пульт керування ' +
   'прапорцями, і за власним прапорцем він був би недосяжним. Захищений ' +
   'правом `updates` у RLS, а не показом.'],
]);

// ── ЩО В КОДІ ─────────────────────────────────────────────────────────────
//
// 🔑 Читаємо ДЖЕРЕЛО, а не власну копію списку. Копія розійшлася б з оригіналом
// рівно тоді, коли хтось додасть поверхню — тобто в єдиний момент, заради якого
// цей стенд існує.

// 🔑 `projectFile` віддає ВМІСТ (і вміє читати версію з git через `rev`) —
// саме тому контроль нижче вмикається змінною оточення, без жодного `git show`
// у самому стенді.
const REV = process.env.SURFACES_REV || '';
const sidebarSrc = projectFile('src/core/sidebar.js', REV);
const indexSrc   = projectFile('index.html', REV);
const adminSrc   = projectFile('admin.html', REV);

// Пункти бічного меню. Ознака пункту — `label:`; у секцій-груп його немає
// (вони мають `caption:` або `cards: true`), і це надійніше за підрахунок
// вкладеності дужок.
function пунктиМеню(src) {
  const блок = src.match(/const SECTIONS = \[[\s\S]*?\n\];/);
  if (!блок) return null;                       // ← сам відсутній блок і є вадою
  return [...блок[0].matchAll(/\{\s*id:\s*'([\w-]+)'[^\n]*\blabel:/g)].map(m => m[1]);
}

// Вкладки таб-бара. Беремо лише кнопки — `data-tab` стоїть ще й на `<main>`,
// а це контейнер, а не поверхня.
function вкладки(src) {
  return [...src.matchAll(/class="tab-item[^"]*"\s+data-tab="([\w-]+)"/g)].map(m => `tab:${m[1]}`);
}

// Розділи адмінки. Ознака — трійця `id` + `icon` + `show` в одному рядку;
// у переліку агентів нижче в тому ж файлі полів `icon`/`show` немає.
function розділиАдмінки(src) {
  return [...src.matchAll(/\{\s*id:\s*'([\w-]+)',\s*icon:[^\n]*\bshow:/g)].map(m => `admin:${m[1]}`);
}

const зМеню     = пунктиМеню(sidebarSrc);
const зТаббара  = вкладки(indexSrc);
const зАдмінки  = розділиАдмінки(adminSrc);

// ── 0. ПРИЛАД БАЧИТЬ ТЕ, ЩО ЗАЯВЛЯЄ ───────────────────────────────────────
//
// 🔴 БЕЗ ЦЬОГО БЛОКУ ВЕСЬ СТЕНД — ПОРОЖНЄ МІСЦЕ. Якщо вираз перестане збігатись
// (перейменували `SECTIONS`, змінили верстку таб-бара, переписали меню адмінки),
// списки приїдуть ПОРОЖНІ — і перевірки нижче зеленітимуть над нулем поверхонь,
// бо «жодна незнайома не знайдена». Саме так брехали попередні прилади в цьому
// проєкті: міряли не те, що заявляли, і були зелені над зламаним.
ok('прилад БАЧИТЬ пункти меню', Array.isArray(зМеню) && зМеню.length >= 15,
   зМеню ? `знайдено ${зМеню.length}` : 'блок SECTIONS не знайдено взагалі');
ok('прилад БАЧИТЬ вкладки таб-бара', зТаббара.length >= 5, `знайдено ${зТаббара.length}`);
ok('прилад БАЧИТЬ розділи адмінки', зАдмінки.length >= 10, `знайдено ${зАдмінки.length}`);

const усіПоверхні = [...(зМеню || []), ...зТаббара, ...зАдмінки];

// ── 1. 🔴 ГОЛОВНЕ: ПРО КОЖНУ ПОВЕРХНЮ Є ЗАПИСАНЕ РІШЕННЯ ──────────────────
{
  const безРішення = усіПоверхні.filter(id =>
    !ДО_ПРАПОРЦІВ.has(id) && !ЗА_ПРАПОРЦЕМ.has(id) && !СВІДОМО_БЕЗ.has(id));

  ok('🔴 нову поверхню не додано повз рішення про прапорець',
     безРішення.length === 0,
     безРішення.length
       ? `БЕЗ РІШЕННЯ: ${безРішення.join(', ')}\n` +
         '       ➡️ Або постав поверхню за прапорець (`featureOn(<ключ>)`) і впиши\n' +
         '          її в ЗА_ПРАПОРЦЕМ, або впиши в СВІДОМО_БЕЗ із ПРИЧИНОЮ,\n' +
         '          чому громаді можна побачити це одразу.\n' +
         '       🛑 Третього варіанту немає: мовчки поверхня не їде.'
       : `перевірено ${усіПоверхні.length} поверхонь`);
}

// ── 2. РЕЄСТР НЕ ПРОТУХ ───────────────────────────────────────────────────
//
// Зустрічна межа. Запис про поверхню, якої вже немає, — це не нешкідливий
// смітник: наступного разу таку саму назву дадуть чомусь іншому, і воно тихо
// проїде під старим рішенням.
{
  const живі = new Set(усіПоверхні);
  const мертві = [...ДО_ПРАПОРЦІВ, ...ЗА_ПРАПОРЦЕМ.keys(), ...СВІДОМО_БЕЗ.keys()]
    .filter(id => !живі.has(id));

  ok('🛑 у реєстрі немає записів про поверхні, яких уже нема в коді',
     мертві.length === 0,
     мертві.length ? `протухло: ${мертві.join(', ')} — прибери з реєстру` : 'реєстр чистий');
}

// ── 3. ПРИЧИНА — ЦЕ ПРИЧИНА, А НЕ ВІДМАШКА ────────────────────────────────
//
// 🔑 Порожнє або однослівне «бо треба» знімає сенс усього запобіжника: рішення
// має бути таким, щоб через півроку його можна було перечитати й зрозуміти.
{
  const кволі = [...СВІДОМО_БЕЗ.entries()]
    .filter(([, чому]) => !чому || чому.trim().length < 40)
    .map(([id]) => id);

  ok('кожне «свідомо без прапорця» пояснене, а не відмахнуте',
     кволі.length === 0,
     кволі.length ? `надто коротка причина: ${кволі.join(', ')}` : `${СВІДОМО_БЕЗ.size} записів`);
}

// ── 4. 🔴 «ЗА ПРАПОРЦЕМ» ОЗНАЧАЄ, ЩО ПРАПОРЕЦЬ СПРАВДІ Є В КОДІ ───────────
//
// Найважливіша перевірка з усіх, і саме вона найлегше стає декоративною.
// Запис «ця поверхня за прапорцем», під яким у коді прапорця немає, гірший за
// відсутній запис: він каже «тут безпечно» там, де небезпечно. Той самий клас
// вади, що коментар про неіснуючий запобіжник у `saved-hub` (24.08) і в
// `sidebar.js` (19.09) — обидва довелось ловити руками.
{
  const весьКлієнт = sidebarSrc + adminSrc + indexSrc +
    ['src/app.js', 'src/tabs/board.js', 'src/tabs/news.js', 'src/tabs/buses.js',
     'src/tabs/feed.js', 'src/tabs/community.js']
      .map(f => { try { return projectFile(f, REV); } catch { return ''; } })
      .join('\n');

  const бездоказові = [...ЗА_ПРАПОРЦЕМ.entries()]
    .filter(([, ключ]) => !весьКлієнт.includes(`'${ключ}'`) && !весьКлієнт.includes(`"${ключ}"`))
    .map(([id, ключ]) => `${id} → ${ключ}`);

  ok('🔴 кожна «за прапорцем» поверхня справді згадує свій ключ у коді',
     бездоказові.length === 0,
     бездоказові.length
       ? `ключа НЕМАЄ в коді: ${бездоказові.join(', ')} — запис бреше`
       : ЗА_ПРАПОРЦЕМ.size
         ? `${ЗА_ПРАПОРЦЕМ.size} перевірено`
         : 'поки жодної — перша з\'явиться з першим оновленням');
}

// ── 5. МЕХАНІЗМ ПРАПОРЦІВ НА МІСЦІ ────────────────────────────────────────
//
// Якщо `featureOn` зникне або перестане бути вимкненою за замовчуванням, увесь
// реєстр вище втратить сенс тихо, не почервонівши в жодному рядку.
{
  let features = '';
  try { features = projectFile('src/core/features.js', REV); } catch { /* немає — впаде нижче */ }
  ok('`featureOn` існує', /export function featureOn\(/.test(features));
  ok('🛑 невідома фіча лишається ВИМКНЕНОЮ (збій мережі не показує недороблене)',
     /if \(!f\) return false;/.test(features),
     features ? 'запобіжник на місці' : 'features.js не прочитався');
}

done();
