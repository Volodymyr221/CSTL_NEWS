// Модуль піднімаємо ЖИВИМ імпортом — перевіряємо той самий код, що йде в застосунок,
// а не його переказ регуляркою.
const { weatherCodeInfo } = await import('../src/core/weather-icons.js');
const хиби = [];
const малюнки = new Map();
for (const [код, очікується] of КОДИ) {
  const r = weatherCodeInfo(код);
  if (r.text !== очікується) хиби.push(`${код}: «${r.text}» замість «${очікується}»`);
  const src = (r.icon.match(/src="([^"]+)"/) || [])[1] || '';
  малюнки.set(очікується, (малюнки.get(очікується) || new Set()).add(src));
}
ok('🔴 кожен код погоди дає ПРАВИЛЬНУ назву стану', хиби.length === 0,
   хиби.join(' · ') || `звірено ${КОДИ.length} кодів WMO`);

// Один стан — одна картинка. Інакше «Дощ» у понеділок і «Дощ» у вівторок могли б
// виглядати по-різному, і людина шукала б різницю там, де її немає.
const різнобій = [...малюнки.entries()].filter(([, s]) => s.size > 1).map(([t]) => t);
