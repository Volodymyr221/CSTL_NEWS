// ── 5. ВИКОНАННЯ: РЕПУБЛІКАЦІЯ І СТАНИ (головна частина) ────────────────────
// Беремо СПРАВЖНІ `feedSortKey` і `eventState` тієї самої ревізії й проганяємо
// на підробленому годиннику. Регулярка не відрізнила б робоче сортування від
// написаного з переплутаним знаком — а саме воно й вирішує, що побачить людина.
// ⚠️ Вирізаємо функції ПОШУКОМ МЕЖ, а не регуляркою з конструктора: перша
// редакція будувала `new RegExp` усередині шаблонного рядка, екранування
// подвоїлось і вираз падав із «Unterminated group» — тобто стенд ламався на
// власному приладі, ще не дійшовши до коду. Той самий клас, що й решта
// брехливих мірок проєкту: спершу перевір прилад.
const інлайн = (src) => ['eventDayStart', 'feedSortKey', 'eventState'].map(n => {
  const i = src.indexOf('export function ' + n + '(');
  if (i < 0) return '';
  const end = src.indexOf('\n}', i);
  return end > 0 ? src.slice(i, end + 2).replace(/^export /, '') : '';
}).join('\n\n');

const сцена = `<!doctype html><html><head><meta charset="utf-8"></head><body><script type="module">
  ${інлайн(supabase)}
  window.__готово = typeof feedSortKey === 'function' && typeof eventState === 'function';
  window.__міряти = () => {
    const день = 86400000;
    const днями = (n) => { const d = new Date(); d.setHours(0,0,0,0); return new Date(d.getTime() + n*день)
      .toISOString().slice(0,10); };
    const давно = new Date(Date.now() - 30*день).toISOString();
    const щойно = new Date().toISOString();

    // Подія, опублікована МІСЯЦЬ ТОМУ, чия дата — СЬОГОДНІ.
    const подіяСьогодні = { created_at: давно, event_date: днями(0) };
    // Звичайний допис місячної давнини.
    const старийДопис   = { created_at: давно };
    // Свіжий допис, опублікований щойно.
    const новийДопис    = { created_at: щойно };
    // Подія, що буде через тиждень (опублікована місяць тому).
    const подіяПотім    = { created_at: давно, event_date: днями(7) };

    return {
      // 4️⃣ У СВІЙ ДЕНЬ подія обганяє старий допис — це і є републікація.
      піднялась: feedSortKey(подіяСьогодні) > feedSortKey(старийДопис),
      // 🛑 …але НЕ обганяє свіжий допис — тобто не закріплена (вимога Вови).
      неЗакріплена: feedSortKey(новийДопис) > feedSortKey(подіяСьогодні),
      // Майбутня подія не лізе вгору заздалегідь.
      майбутняНеЛізе: feedSortKey(подіяПотім) > feedSortKey(новийДопис),
      // Стани в часі.
      стани: [eventState(днями(0)), eventState(днями(3)), eventState(днями(-3))],
      // Дата без часового поясу: 'сьогодні' лишається сьогодні і о 01:00 ночі.
      деньПочатку: eventDayStart(днями(0)) === new Date(new Date().setHours(0,0,0,0)).getTime(),
    };
  };
</script></body></html>`;

const b = await launch(chromium);
