const видно = await p4.evaluate((html) => {
  document.getElementById('к').innerHTML = html;
  return (document.getElementById('к').textContent || '').replace(/\s+/g, ' ').trim();
}, безПідстановок(кістяк));
await b4.close();

const маркери = ['🛑', '🔴', '⚠️', '🔑', '🗣️', 'рішення Вови', 'HOT_RULES'];
