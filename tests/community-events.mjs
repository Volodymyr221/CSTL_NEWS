// Стенд: ПОДІЇ СПІЛЬНОТ — ОДНЕ ДЖЕРЕЛО, ВИДИМА ФОРМА, НАГАДУВАННЯ ПО ВЛАСНОМУ ВИБОРУ.
//
// 🗣️ ЗАМОВЛЕННЯ ВОВИ (04.09.2026): «в спільнотах є дописи, а є події… потрібно
// зробити редизайн вигляду публікації подій, і як вони будуть відображатись в
// стрічці, і як в спільноті… щоб людина могла створити нагадування… можливо
// зробити окремим віджетом в вкладці Громада… коли наступає день події, як це
// буде відображатися».
//
// Пʼять його рішень, які цей стенд і стереже:
//   1. «Зводь» — одне джерело подій (спільноти), не два;
//   2. події створюють ТІЛЬКИ спільноти;
//   3. нагадування — лише тому, хто натиснув сам;
//   4. у день події вона «піднімається… ніби републікація», НЕ закріплена;
//   5. подій немає — віджет «ховається».
//
// 📐 ЩО МІРЯЄМО І ЧОМУ САМЕ ТАК. Головне тут — ПОРЯДОК і СТАНИ в часі, тобто
// поведінка, а не текст коду. Регулярка «є слово event_date» зеленіла б і над
// сортуванням, написаним із переплутаним знаком. Тому ключові перевірки
// ВИКОНУЮТЬ справжні функції з `core/supabase.js` на підробленому годиннику.
//
// 🔴 КОНТРОЛЬ: BUNDLE_REV=origin/main node tests/community-events.mjs
// На коді до роботи мусять упасти всі перевірки виконання (`feedSortKey` і
// `eventState` там не існують) і всі перевірки зведення джерел.
import { chromium } from 'playwright';
import { projectFile, launch, reporter } from './_lib.mjs';

const REV = process.env.BUNDLE_REV || '';
const { ok, done } = reporter();

const supabase = projectFile('src/core/supabase.js', REV);
const feed     = projectFile('src/tabs/feed.js', REV);
const blocks   = projectFile('src/tabs/community-blocks.js', REV);
const community= projectFile('src/tabs/community.js', REV);
const account  = projectFile('src/core/account-ui.js', REV);

console.log(`\n── ПОДІЇ СПІЛЬНОТ${REV ? `   (КОНТРОЛЬ на ${REV})` : ''}`);

// ── 1. ОДНЕ ДЖЕРЕЛО (рішення Вови «зводь») ──────────────────────────────────
// 🔴 До 04.09 віджет на Громаді читав `data/events.json` — файл у git, який
// протух (7 записів, 0 майбутніх) і з подіями спільнот НЕ МАВ ЗВʼЯЗКУ. Тобто
// міськрада могла опублікувати концерт, і у віджет він не потрапив би ніколи.
ok('віджет Громади бере події З БАЗИ',
   /fetchUpcomingEvents\(/.test(blocks));
ok('віджет більше НЕ читає статичний файл подій',
   !/fetch\(['"]\.\/data\/events\.json/.test(blocks));
ok('тап по події веде в саму подію (а не в абстрактну афішу)',
   /focusFeedPost\(/.test(blocks));
// 🛑 Другого шляху до події не заводимо: `focusFeedPost` — та сама функція,
// якою відкриває допис deep-link зі сповіщення.
ok('секція «Події громади» є в скелеті Громади',
   /id="hm-events"/.test(community) && /Події громади/.test(community));
ok('порожньо → секція ХОВАЄТЬСЯ (рішення Вови)',
   /hm-events/.test(blocks) && /sec\.hidden = true/.test(blocks));

// ── 2. ПОДІЮ СТВОРЮЄ ТІЛЬКИ СПІЛЬНОТА ───────────────────────────────────────
// Композер спільноти має перемикач «Допис / Подія» — іншого входу немає.
ok('поля події живуть у композері спільноти',
   /fd-comp-date/.test(feed) && /fd-comp-eloc/.test(feed));

// ── 3. НАГАДУВАННЯ ТІЛЬКИ ЗА ВЛАСНИМ ВИБОРОМ ────────────────────────────────
ok('кнопка «Нагадати» є на картці події', /data-remind=/.test(feed));
ok('нагадування пише в базу через RPC', /toggle_event_reminder/.test(supabase));
// 🛑 Дозвіл браузера питається ДО запису: інакше людина бачила б «Нагадаю», а
// телефон не мав би права дзвонити — вимикач підтверджував би дію, якої не буде
// (рівно вада B-33).
const тіло = (feed.match(/async function toggleRemind[\s\S]*?\n\}/) || [''])[0];
ok('дозвіл на сповіщення питається ДО запису підписки',
   тіло.indexOf('ensurePushSubscription') > 0 &&
   тіло.indexOf('ensurePushSubscription') < тіло.indexOf('toggleEventReminder'),
   тіло ? 'порядок кроків правильний' : 'функції не знайдено');
ok('вимкнути нагадування можна БЕЗ дозволу браузера',
   /if \(!wasOn\) \{[\s\S]{0,120}ensurePushSubscription/.test(тіло));
// 🔴 Біле правило: тема, якої немає в `NOTIF_TOPICS`, у базу не запишеться —
// вимикач клацав би, а сервер далі слав би сповіщення.
ok('тема «events» є в білому списку тем сповіщень',
   /NOTIF_TOPICS = \[[^\]]*'events'/.test(supabase));
ok('пʼятий вимикач стоїть у кабінеті',
   /k: 'events'/.test(account) && /Події/.test(account));
ok('і його підпис каже, що це ВЛАСНИЙ вибір людини',
   /які ви позначили/.test(account));

// ── 4. ФОРМА: ПОДІЯ ЧИТАЄТЬСЯ ЯК ПОДІЯ ──────────────────────────────────────
ok('дата стоїть окремим блоком, а не рядком у тексті',
   /fd-ev-date/.test(feed));
// 🛑 Емодзі прибрано: дизайн-аудит 03.09 вичистив їх з інтерфейсу.
ok('емодзі 🗓 у картці події більше немає', !/🗓 \$\{when\}/.test(feed));
ok('стан «СЬОГОДНІ» має власну мітку', /СЬОГОДНІ/.test(feed));

// ── 5. ВИКОНАННЯ: РЕПУБЛІКАЦІЯ І СТАНИ (головна частина) ────────────────────
// Беремо СПРАВЖНІ `feedSortKey` і `eventState` тієї самої ревізії й проганяємо
// на підробленому годиннику. Регулярка не відрізнила б робоче сортування від
// написаного з переплутаним знаком — а саме воно й вирішує, що побачить людина.
// ⚠️ Вирізаємо функції ПОШУКОМ МЕЖ, а не регуляркою з конструктора: перша
// редакція будувала `new RegExp` усередині шаблонного рядка, екранування
// подвоїлось і вираз падав із «Unterminated group» — тобто стенд ламався на
// власному приладі, ще не дійшовши до коду. Той самий клас, що й решта
// брехливих мірок проєкту: спершу перевір прилад.
const інлайн = (src) => ['eventDayStart', 'feedSortKey', 'eventState'].map(n => {
  const i = src.indexOf('export function ' + n + '(');
  if (i < 0) return '';
  const end = src.indexOf('\n}', i);
  return end > 0 ? src.slice(i, end + 2).replace(/^export /, '') : '';
}).join('\n\n');

const сцена = `<!doctype html><html><head><meta charset="utf-8"></head><body><script type="module">
  ${інлайн(supabase)}
  window.__готово = typeof feedSortKey === 'function' && typeof eventState === 'function';
  window.__міряти = () => {
    const день = 86400000;
    const днями = (n) => { const d = new Date(); d.setHours(0,0,0,0); return new Date(d.getTime() + n*день)
      .toISOString().slice(0,10); };
    const давно = new Date(Date.now() - 30*день).toISOString();
    const щойно = new Date().toISOString();

    // Подія, опублікована МІСЯЦЬ ТОМУ, чия дата — СЬОГОДНІ.
    const подіяСьогодні = { created_at: давно, event_date: днями(0) };
    // Звичайний допис місячної давнини.
    const старийДопис   = { created_at: давно };
    // Свіжий допис, опублікований щойно.
    const новийДопис    = { created_at: щойно };
    // Подія, що буде через тиждень (опублікована місяць тому).
    const подіяПотім    = { created_at: давно, event_date: днями(7) };

    return {
      // 4️⃣ У СВІЙ ДЕНЬ подія обганяє старий допис — це і є републікація.
      піднялась: feedSortKey(подіяСьогодні) > feedSortKey(старийДопис),
      // 🛑 …але НЕ обганяє свіжий допис — тобто не закріплена (вимога Вови).
      неЗакріплена: feedSortKey(новийДопис) > feedSortKey(подіяСьогодні),
      // Майбутня подія не лізе вгору заздалегідь.
      майбутняНеЛізе: feedSortKey(подіяПотім) > feedSortKey(новийДопис),
      // Стани в часі.
      стани: [eventState(днями(0)), eventState(днями(3)), eventState(днями(-3))],
      // Дата без часового поясу: 'сьогодні' лишається сьогодні і о 01:00 ночі.
      деньПочатку: eventDayStart(днями(0)) === new Date(new Date().setHours(0,0,0,0)).getTime(),
    };
  };
</script></body></html>`;

const b = await launch(chromium);
const p = await b.newPage();
await p.setContent(сцена);
await p.waitForTimeout(250);
const живий = await p.evaluate(() => window.__готово === true);
ok('функції порядку і станів виконуються', живий);
const m = живий ? await p.evaluate(() => window.__міряти()) : {};
await b.close();

ok('у СВІЙ ДЕНЬ подія піднімається над старими дописами',
   m.піднялась === true, `результат: ${m.піднялась}`);
// 🔑 Ця пара і доводить «републікацію, а не закріплення»: закріплене трималось
// би вгорі попри все, а тут його обганяє будь-який новий допис того ж дня.
ok('…але НЕ закріплена: свіжий допис її обганяє',
   m.неЗакріплена === true, `результат: ${m.неЗакріплена}`);
ok('майбутня подія не лізе вгору заздалегідь',
   m.майбутняНеЛізе === true, `результат: ${m.майбутняНеЛізе}`);
ok('стани читаються правильно: сьогодні · майбутня · минула',
   JSON.stringify(m.стани) === JSON.stringify(['today', 'future', 'past']),
   JSON.stringify(m.стани));
// ⚠️ Пастка, на якій легко спіткнутись: рядок дати з «Z» браузер читає як UTC,
// і на київському пристрої «сьогодні» ставало вчорашнім до третьої ночі.
ok('день події рахується локально, без зсуву поясу', m.деньПочатку === true);

// ── 6. SQL-ДЗЕРКАЛО ─────────────────────────────────────────────────────────
let sql = ''; try { sql = projectFile('scripts/supabase_events_reminders.sql', REV); } catch (_) {}
ok('SQL-дзеркало міграції лежить у репо', sql.length > 0);
ok('підписка має SELECT-політику (правило 11-БІС)', /evr own read/.test(sql));
ok('розклад нагадувань заведено', /cron\.schedule\('event-reminders'/.test(sql));

done();
