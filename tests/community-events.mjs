// ── 13. ПОРЯДОК В АФІШІ — ЗА ДАТОЮ ПОДІЇ, А НЕ ПУБЛІКАЦІЇ ───────────────────
// 📐 ВИКОНУЄМО справжній `afishaHtml` на підроблених подіях: регулярка «є слово
