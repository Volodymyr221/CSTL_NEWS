//
//   ПОДІЯ — ЦЕ ДОПИС ІЗ ДАТОЮ. Один запис, одні коментарі, одні лайки.
//   Місця застосунку — це ПОГЛЯДИ на нього, а не окремі сутності:
//     • Стрічка          — що спільноти СКАЗАЛИ (порядок за публікацією);
//     • екран спільноти  — розклад ОДНІЄЇ спільноти (сегмент «Події»);
//     • АФІША            — розклад УСІЄЇ громади (порядок за датою події);
