// tests/css-alive.mjs — ПРАВИЛО, ЗАПИСАНЕ У ФАЙЛІ, МУСИТЬ ДІЯТИ В БРАУЗЕРІ.
//
// 🔴 ЗАВЕДЕНО 06.08 ПІСЛЯ РЕАЛЬНОЇ ПОЛОМКИ, ЯКУ ЗНАЙШОВ ВОВА, А НЕ СТЕНД.
//
// Розділення `community.css` → `board.css` (05.08, PR #786) розрізало два
// коментарі НАВПІЛ: початок лишився в одному файлі, кінець поїхав у другий.
// Обидві половини стали невалідними, і браузер тихо викинув сусідні правила:
//
//   .cm-ad-author-since  — розмір рядка «Учасник CSTL LIFE з …»  → ВИКИНУТО
//   .bd-group-title      — підзаголовок групи при фільтрі НП     → ВИКИНУТО
//
// Симптом, який побачив Вова: «чому „Учасник CSTL LIFE…“ більшими буквами
// почало писатись?» Правило без свого `font-size` успадковує батьківський.
//
// 🔴 ЧОМУ ЦЬОГО НЕ ПОБАЧИВ ЗЛІПОК `tests/tools/css-snapshot.mjs`, яким те
// розділення й доводили як безпечне («224 елементи, 0 розбіжностей»).
// Він міряв ОБЧИСЛЕНІ стилі елементів, які були на екрані, — а сторінки
// оголошення й підзаголовка групи НП у вибірці не було. Тобто зліпок чесно
// сказав правду про те, що бачив, і промовчав про решту файлу.
// **Одинадцятий випадок брехливої перевірки в проєкті.**
//
// 🔑 ЦЕЙ СТОРОЖ МІРЯЄ ІНШЕ І ТОМУ НЕ ДУБЛЮЄ ЗЛІПОК: не «чи однаковий вигляд
// до і після», а «чи ДОЖИЛО кожне написане правило до CSSOM». Йому не потрібна
// ані сцена, ані елемент на екрані — тільки сам файл. Через це він ловить і
// поламану дужку, і зайвий `*/`, і сміття перед селектором — будь-яку причину,
// з якої браузер мовчки викидає правило.
//
// ⚠️ Мовчки — ключове слово. CSS не має синтаксичних помилок у звичному сенсі:
// незрозуміле правило просто зникає, консоль порожня, збірка зелена.

import { chromium } from '@playwright/test';
import { readFileSync, readdirSync } from 'fs';
import { join } from 'path';
import { ROOT, launch, reporter } from './_lib.mjs';

const { ok, done } = reporter();
const CSS_DIR = join(ROOT, 'style');
const файли = readdirSync(CSS_DIR).filter(f => f.endsWith('.css')).sort();

// Селектори, записані в тексті: беремо все, що стоїть перед `{`.
//
// ⚠️ ПЕРША ВЕРСІЯ БРАЛА ЛИШЕ `.клас {` НА ПОЧАТКУ РЯДКА — і одразу дала два
// хибні спрацювання (`.bd-ad-img`, `.bd-ad-foot`). Там коментар стоїть ПОСЕРЕД
// селектора (`#board-content /* … */ .bd-ad-img`) — конструкція цілком валідна,
// правило діє, просто називається `#board-content .bd-ad-img`.
// 🔑 Правило проєкту спрацювало як треба: перевірка «завалила» робочий код —
// першою підозрюваною стала перевірка, а не код.
function записаніСелектори(css) {
  const без = css.replace(/\/\*[\s\S]*?\*\//g, ' ');   // прибрати ЦІЛІ коментарі
  const out = new Set();
  for (const m of без.matchAll(/([^{}]+)\{/g)) {
    const sel = m[1].split(/[;}]/).pop().trim().replace(/\s+/g, ' ');
    if (!sel || sel.startsWith('@')) continue;
    // Кроки `@keyframes` (`from` · `to` · `40%`) — не селектори правил, у CSSOM
    // вони лежать окремим типом вузла і в `all` не потраплять за побудовою.
    if (/^(from|to|\d+(\.\d+)?%)(\s*,\s*(from|to|\d+(\.\d+)?%))*$/.test(sel)) continue;
    out.add(sel);
  }
  return [...out];
}

const b = await launch(chromium);
const p = await b.newPage();
await p.goto('about:blank');

let мертвих = 0;
const деталі = [];

for (const f of файли) {
  const css = readFileSync(join(CSS_DIR, f), 'utf8');
  const треба = записаніСелектори(css);
  if (!треба.length) continue;

  const живі = await p.evaluate(({ src, треба }) => {
    const st = document.createElement('style');
    st.textContent = src;
    document.head.appendChild(st);
    const all = new Set();
    const walk = rules => [...rules].forEach(x => {
      if (x.type === 1) all.add(x.selectorText);
      else if (x.cssRules) walk(x.cssRules);
    });
    walk(st.sheet.cssRules);
    st.remove();

    // 🔑 Обидві сторони канонізує САМ БРАУЗЕР. Інакше довелось би вгадувати, як
    // він нормалізує пробіли навколо `>`, регістр і порядок у групі через кому —
    // і кожна розбіжність написання читалась би як зникле правило.
    const norm = document.createElement('style');
    document.head.appendChild(norm);
    const canon = s => {
      try {
        norm.textContent = s + '{}';
        return norm.sheet.cssRules.length ? norm.sheet.cssRules[0].selectorText : null;
      } catch { return null; }
    };
    const живіCanon = new Set([...all].map(canon).filter(Boolean));
    // 🔴 `c === null` (селектор перед `{` невалідний) — це НЕ привід пропустити,
    // це і є симптом. Перша версія тут стояла `c !== null && …` і через це
    // ПРОПУСКАЛА рівно ту поломку, заради якої стенд писався: при розрізаному
    // коментарі сміття прилипає до селектора спереду, той стає невалідним, і
    // «нема чого перевіряти» читалось як «усе гаразд». Доведено контролем нижче.
    const мертві = треба.map(s => {
      const c = canon(s);
      if (c === null) return `${s.slice(0, 40).replace(/\s+/g, ' ')}… (невалідний селектор)`;
      return живіCanon.has(c) ? null : s;
    }).filter(Boolean);
    norm.remove();
    return мертві;
  }, { src: css, треба });

  мертвих += живі.length;
  if (живі.length) деталі.push(`${f}: ${живі.join(', ')}`);
}

ok('кожне записане правило дожило до браузера', мертвих === 0,
   мертвих ? деталі.join(' · ') : `${файли.length} файлів чисті`);

// ── Друга лінія: сама причина, а не лише наслідок ───────────────────────────
// Наслідок ловить перевірка вище. Але коментар можна розірвати так, що жодне
// правило не постраждає (розріз між двома коментарями) — і наступний перенос
// рядка вже вб'є сусіда. Тому окремо стежимо за балансом `/* */` у КОЖНОМУ
// файлі: після розділення файлів це рівно те, що ламається першим.
let рвані = [];
for (const f of файли) {
  const css = readFileSync(join(CSS_DIR, f), 'utf8');
  // ⚠️ Коментарі CSS НЕ вкладаються: `/*` усередині коментаря — просто текст.
  // Тому це прапорець, а не лічильник глибини (перша версія рахувала глибину
  // і через це «знаходила» неіснуючі поломки).
  let i = 0, усередині = false, незакритих = 0, зайвих = 0;
  while (i < css.length - 1) {
    if (!усередині && css.startsWith('/*', i)) { усередині = true; i += 2; continue; }
    if (css.startsWith('*/', i)) {
      if (усередині) усередині = false; else зайвих++;
      i += 2; continue;
    }
    i++;
  }
  if (усередині) незакритих = 1;
  const відкрито = незакритих;
  if (відкрито || зайвих) рвані.push(`${f}: незакритих ${відкрито}, зайвих «*/» ${зайвих}`);
}
ok('коментарі не розірвані між файлами', рвані.length === 0,
   рвані.length ? рвані.join(' · ') : `${файли.length} файлів збалансовані`);

// ── КОНТРОЛЬ: сторож мусить упасти на навмисно зламаному файлі ──────────────
// Без цього перевірка могла б бути порожньою і ніхто б не помітив.
// Відтворюємо РІВНО ту поломку 05.08: хвіст коментаря без початку перед правилом.
const зламаний = `
.живий-клас { color: red; }
 хвіст розрізаного коментаря. */
.жертва { font-size: 12px; }
`;
const контроль = await p.evaluate(src => {
  const st = document.createElement('style');
  st.textContent = src;
  document.head.appendChild(st);
  const all = new Set();
  [...st.sheet.cssRules].forEach(x => { if (x.type === 1) all.add(x.selectorText); });
  st.remove();
  return { живий: all.has('.живий-клас'), жертва: all.has('.жертва') };
}, зламаний);
ok('контроль: на зламаному коментарі правило СПРАВДІ зникає',
   контроль.живий === true && контроль.жертва === false,
   `.живий-клас ${контроль.живий} · .жертва ${контроль.жертва}`);

await b.close();
done();
