// Стенд: КООРДИНАТИ СІЛ ГРОМАДИ — ЧИСЛА, ЯКІ НЕМА КОМУ ПЕРЕВІРИТИ ОКОМ.
//
// 🔴 НАВІЩО ЦЕЙ СТОРОЖ. Файл `data/settlements-geo.json` наповнює скрипт
// `geocode-settlements.mjs` тим, що віддав OpenStreetMap. Помилка там виглядає
// як **нормальне число**: 50.7 замість 50.79, чи Ставок із Рівненщини замість
// нашого. Людина, яка «дивиться очима», такого не спіймає — а наслідок побачить
// житель, якому капсула запропонує автобус із чужого села.
//
// 🔑 Тому числа перевіряє не око, а геометрія: усе, що ми ПРО НИХ ЗНАЄМО
// напевно — це що села лежать купно навколо Олики і не збігаються між собою.
// Саме це й міряємо.
//
// ⚠️ Файла може не бути — і це НЕ провал. Застосунок без нього працює (падає на
// назву з погоди й анкету). Стенд тоді чесно каже «нема чого перевіряти», а не
// вигадує проблему.
import { existsSync, readFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import { reporter } from './_lib.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ФАЙЛ = join(ROOT, 'data/settlements-geo.json');
const { ok, done } = reporter();

// Список сіл беремо з того самого місця, що застосунок і скрипт — інакше
// перевірка звіряла б файл із власною копією списку.
const src = readFileSync(join(ROOT, 'src/core/settlements.js'), 'utf8');
const SETTLEMENTS = [...src.match(/export const SETTLEMENTS = \[([\s\S]*?)\];/)[1]
  .matchAll(/'((?:[^'\\]|\\.)*)'/g)].map(m => m[1].replace(/\\'/g, "'"));

// Олика — єдина точка, яку проєкт знає напевно (вона в `core/utils.js` з 04.08
// і живить погоду). Від неї й міряємо.
const ОЛИКА = { lat: 50.7333, lon: 25.8167 };
const МЕЖА_КМ = 25;    // громада компактна; 25 км — із запасом на крайні села
const МІН_КМ = 0.4;    // два різні села не можуть стояти в одній точці

const км = (a, b) => {
  const R = 6371, рад = д => (д * Math.PI) / 180;
  const dLat = рад(b.lat - a.lat), dLon = рад(b.lon - a.lon);
  const h = Math.sin(dLat / 2) ** 2
          + Math.cos(рад(a.lat)) * Math.cos(рад(b.lat)) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
};

if (!existsSync(ФАЙЛ)) {
  ok('файла координат ще немає — перевіряти нічого (це не поломка)', true,
     'створюється воркфловом «Координати сіл» або локально geocode-settlements.mjs');
  done();
} else {
  const дані = JSON.parse(readFileSync(ФАЙЛ, 'utf8'));
  const назви = Object.keys(дані);

  // 🛑 ПОВНОТА. Половина списку гірша за його відсутність: застосунок вважав би
  // пропущені села «вже з'ясованими» і не спробував би сам.
  const бракує = SETTLEMENTS.filter(n => !дані[n]);
  ok('🔴 у файлі є ВСІ села громади', бракує.length === 0,
     бракує.length ? `бракує: ${бракує.join(', ')}` : `${SETTLEMENTS.length} сіл`);

  // Числа мусять бути числами, а не рядками чи null — інакше порівняння відстані
  // мовчки дасть NaN, і «найближче село» не знайдеться ніколи.
  const кривi = назви.filter(n => !Number.isFinite(дані[n]?.lat) || !Number.isFinite(дані[n]?.lon));
  ok('🔴 усі координати — справжні числа', кривi.length === 0, кривi.join(', '));

  // 🔴 ГОЛОВНА ПЕРЕВІРКА: чуже село з тією ж назвою. «Ставок», «Котів», «Дерно»
  // є не лише на Волині, і геокодер міг віддати тезку за 300 км. Таке число
  // виглядає нормально й оком не ловиться.
  const далекі = назви.filter(n => Number.isFinite(дані[n]?.lat) && км(ОЛИКА, дані[n]) > МЕЖА_КМ);
  ok(`🔴 жодне село не далі ${МЕЖА_КМ} км від Олики (тезка з іншої області)`,
     далекі.length === 0,
     далекі.map(n => `${n} — ${Math.round(км(ОЛИКА, дані[n]))} км`).join(', '));

  // Два села в одній точці означають, що геокодер на щось не відповів і віддав
  // те саме двічі — а капсула тоді показувала б чужу зупинку як свою.
  const пари = [];
  for (let i = 0; i < назви.length; i++) {
    for (let j = i + 1; j < назви.length; j++) {
      const a = дані[назви[i]], b = дані[назви[j]];
      if (Number.isFinite(a?.lat) && Number.isFinite(b?.lat) && км(a, b) < МІН_КМ) {
        пари.push(`${назви[i]} ≈ ${назви[j]}`);
      }
    }
  }
  ok('🔴 різні села не стоять в одній точці', пари.length === 0, пари.join(', '));

  // Олика в файлі має збігтися з тією, що вже живить погоду. Розходження означає
  // два різні уявлення про центр громади — і вони розійдуться далі.
  if (дані['Олика']) {
    const d = км(ОЛИКА, дані['Олика']);
    ok('Олика у файлі збігається з координатами застосунку', d < 3,
       `розбіжність ${d.toFixed(1)} км`);
  }
  done();
}
