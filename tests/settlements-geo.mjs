// Стенд: КООРДИНАТИ СІЛ ГРОМАДИ — ЧИСЛА, ЯКІ НЕМА КОМУ ПЕРЕВІРИТИ ОКОМ.
//
// 🔴 НАВІЩО ЦЕЙ СТОРОЖ. Файл `data/settlements-geo.json` наповнює скрипт
// `geocode-settlements.mjs` тим, що віддав OpenStreetMap. Помилка там виглядає
// як **нормальне число**: 50.7 замість 50.79, чи Ставок із Рівненщини замість
// нашого. Людина, яка «дивиться очима», такого не спіймає — а наслідок побачить
// житель, якому капсула запропонує автобус із чужого села.
//
// 🔑 Тому числа перевіряє не око, а геометрія: усе, що ми ПРО НИХ ЗНАЄМО
// напевно — це що села лежать купно навколо Олики і не збігаються між собою.
// Саме це й міряємо.
//
// ⚠️ Файла може не бути — і це НЕ провал. Застосунок без нього працює (падає на
// назву з погоди й анкету). Стенд тоді чесно каже «нема чого перевіряти», а не
// вигадує проблему.
import { existsSync, readFileSync, mkdtempSync, writeFileSync, mkdirSync } from 'fs';
import { execFileSync } from 'child_process';
import { tmpdir } from 'os';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import { reporter } from './_lib.mjs';
// Правило вибору імпортуємо зі скрипта — сцени мусять ганяти САМЕ ЙОГО.
// А межі для перевірки готового файлу лишаються власні (МЕЖА_КМ нижче): якби
// сторож брав їх зі скрипта, помилку в самій межі він упіймати вже не міг би.
// Що обидві пари не розійшлись — окрема перевірка.
import {
  обратиСвого, СВОЯ_ГРОМАДА,
  МЕЖА_СЕЛА_КМ as МЕЖА_СЕЛА_СКРИПТА, МЕЖА_МІСТА_КМ as МЕЖА_МІСТА_СКРИПТА,
} from '../scripts/geocode-settlements.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ФАЙЛ = join(ROOT, 'data/settlements-geo.json');
const { ok, done } = reporter();

// Список сіл беремо з того самого місця, що застосунок і скрипт — інакше
// перевірка звіряла б файл із власною копією списку.
const src = readFileSync(join(ROOT, 'src/core/settlements.js'), 'utf8');
const SETTLEMENTS = [...src.match(/export const SETTLEMENTS = \[([\s\S]*?)\];/)[1]
  .matchAll(/'((?:[^'\\]|\\.)*)'/g)].map(m => m[1].replace(/\\'/g, "'"));

// Олика — єдина точка, яку проєкт знає напевно (вона в `core/utils.js` з 04.08
// і живить погоду). Від неї й міряємо.
const ОЛИКА = { lat: 50.7333, lon: 25.8167 };
// 🔴 21.08 — ДВІ РІЗНІ МЕЖІ, і це виправлення власної мірки. Перша версія міряла
// 25 км ДЛЯ ВСЬОГО ФАЙЛУ — і на першому ж живому прогоні звинуватила Луцьк («35
// км»), хоча він у файлі НАВМИСНО: це «місто поруч», а не село громади.
// 🔑 Правило треба застосовувати до того набору, для якого воно написане.
// Села громади компактні (25 км із запасом на крайні); місто поруч за
// визначенням далі, але й воно не може бути де завгодно — 60 км ловить чужий
// Луцьк, якщо геокодер віддасть тезку.
const МЕЖА_КМ = 25;    // села громади
const МЕЖА_МІСТА_КМ = 60;
const МІН_КМ = 0.4;    // два різні села не можуть стояти в одній точці

const км = (a, b) => {
  const R = 6371, рад = д => (д * Math.PI) / 180;
  const dLat = рад(b.lat - a.lat), dLon = рад(b.lon - a.lon);
  const h = Math.sin(dLat / 2) ** 2
          + Math.cos(рад(a.lat)) * Math.cos(рад(b.lat)) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
};

// ─────────────────────────────────────────────────────────────────────────────
// ЧАСТИНА 1 — ВИБІР ІЗ КІЛЬКОХ ВІДПОВІДЕЙ ГЕОКОДЕРА.
//
// 🔴 21.08, третій живий прогін кнопки. Файл згенерувався, обгортка читалась —
// і сторож справедливо почервонів на ДВОХ пунктах: «Одеради — 51 км» (Луцька
// міська громада) і «Ставок — 102 км» (Турійська громада, Ковельський район).
// Обидва — ТЕЗКИ В ТІЙ САМІЙ ВОЛИНСЬКІЙ ОБЛАСТІ, тобто уточнення області, на
// яке спирався скрипт, не рятує в принципі.
//
// 📐 Що список сіл правильний — доведено розкладом, а не памʼяттю: «Одеради»
// стоїть у 154 рейсах між Покащевом і Хромяковим за дві зупинки до Олики.
// Село за 51 км від Олики там опинитись не може.
//
// 🔑 Тому скрипт більше не бере першу відповідь, а ОБИРАЄ свою з десяти. Ця
// частина перевіряє САМЕ ВИБІР — без мережі, на справжніх відповідях із логу
// прогону. Перевіряти його через живий запит було б і повільно, і залежно від
// чужого сервера: та сама вада знову проявилась би лише в Actions.
const СЕЛО = { громада: СВОЯ_ГРОМАДА, межа: МЕЖА_СЕЛА_СКРИПТА };
const МІСТО = { громада: null, межа: МЕЖА_МІСТА_СКРИПТА };

// Справжня відповідь із логу — саме її скрипт мовчки прийняв як «Одеради».
const ЧУЖІ_ОДЕРАДИ = { lat: '50.69357', lon: '25.09342',
  display_name: 'Одеради, Луцька міська громада, Луцький район, Волинська область, Україна' };
const НАШІ_ОДЕРАДИ = { lat: '50.75100', lon: '25.74200',
  display_name: 'Одеради, Олицька селищна громада, Луцький район, Волинська область, Україна' };
const ЧУЖИЙ_СТАВОК = { lat: '51.11046', lon: '24.48544',
  display_name: 'Ставок, Турійська селищна громада, Ковельський район, Волинська область, Україна' };

// 🛑 ГОЛОВНА СЦЕНА — рівно та, що впала наживо: чужий тезка йде ПЕРШИМ.
// Перевірка «щось обрано» тут була б зеленою і над старим кодом.
{
  const { обрано } = обратиСвого([ЧУЖІ_ОДЕРАДИ, НАШІ_ОДЕРАДИ], СЕЛО);
  ok('🔴 наше село обирається, навіть коли тезка стоїть першим',
     обрано?.lat === 50.751, обрано ? `${обрано.lat}, ${обрано.lon} — ${обрано.км} км` : 'нічого не обрано');
}

// 🛑 Нашого варіанта в відповіді немає взагалі. Записати 102 км «бо це все, що
// дали» — і є та вада, від якої лікуємось: краще впасти і сказати вголос.
{
  const { обрано, відкинуті } = обратиСвого([ЧУЖИЙ_СТАВОК], СЕЛО);
  ok('🔴 тезка за межею не приймається «за браком кращого»',
     обрано === null && відкинуті.length === 1,
     обрано ? `помилково обрано ${обрано.км} км` : 'відмовились, як і треба');
}

// Страховка: OSM не завжди проставляє громаду в адресі. Тоді працює відстань —
// інакше правило «має бути названа наша громада» саме стало б причиною падінь.
{
  const { обрано } = обратиСвого([
    ЧУЖІ_ОДЕРАДИ,
    { lat: '50.75100', lon: '25.74200', display_name: 'Одеради, Луцький район, Волинська область' },
  ], СЕЛО);
  ok('громаду не названо — рятує відстань, а не відмова',
     обрано?.lat === 50.751, обрано ? `${обрано.км} км` : 'нічого не обрано');
}

// 🔑 Назва громади доводить «це наше» ЛИШЕ разом із відстанню: рядок «Олицьк»
// трапляється і в чужій адресі — наприклад, вулиця Олицька в іншому місті.
{
  const { обрано } = обратиСвого([
    { lat: '50.61990', lon: '26.25160', display_name: 'вулиця Олицька, Рівне, Рівненська область' },
  ], СЕЛО);
  ok('🔴 «Олицьк» у чужій адресі за межею не робить її нашою',
     обрано === null, обрано ? `помилково обрано ${обрано.км} км` : 'відкинуто');
}

// Місто поруч живе за іншим правилом: громада не наша за визначенням, працює
// тільки ширша межа. І вона теж не безмежна — чужий Луцьк має відпасти.
{
  const справжній = { lat: '50.74507', lon: '25.32008',
    display_name: 'Луцьк, Луцька міська громада, Луцький район, Волинська область' };
  const чужий = { lat: '49.55000', lon: '25.60000', display_name: 'Луцьк, інша область' };
  const а = обратиСвого([справжній, чужий], МІСТО);
  const б = обратиСвого([чужий], МІСТО);
  ok(`🔴 місто поруч — своя межа ${МЕЖА_МІСТА_СКРИПТА} км, і вона теж ловить тезку`,
     а.обрано?.lat === 50.74507 && б.обрано === null,
     `справжній: ${а.обрано?.км} км · чужий сам: ${б.обрано ? 'прийнято ❌' : 'відкинуто'}`);
}

// Дві копії однієї межі (у скрипті — щоб обирати, тут — щоб перевіряти) мають
// право існувати лише поки вони збігаються. Розійдуться тихо — і сторож
// пропускатиме рівно те, що скрипт записує.
ok('межі скрипта і сторожа не розійшлись',
   МЕЖА_СЕЛА_СКРИПТА === МЕЖА_КМ && МЕЖА_МІСТА_СКРИПТА === МЕЖА_МІСТА_КМ,
   `скрипт ${МЕЖА_СЕЛА_СКРИПТА}/${МЕЖА_МІСТА_СКРИПТА} · сторож ${МЕЖА_КМ}/${МЕЖА_МІСТА_КМ}`);

// ─────────────────────────────────────────────────────────────────────────────
// ЧАСТИНА 2 — КРОК «ЧИ Є ЩО КОМІТИТИ» У ВОРКФЛОВІ.
//
// 🔴 22.08. Прогін кнопки нарешті став ЗЕЛЕНИМ — і PR усе одно не зʼявився.
// Крок «Відкрити PR» відпрацював за 0 секунд і сказав «Координати не
// змінились». Причина: `git diff --quiet -- <файл>` НЕ БАЧИТЬ невідстежуваних
// файлів, а файла координат у git ніколи не було. Тобто умова гасила саме
// ПЕРШИЙ прогін — єдиний, заради якого все й будувалось, — і рапортувала успіх.
//
// 🛑 ЧОМУ ЦЕ ОКРЕМА ПЕРЕВІРКА, А НЕ ПОШУК РЯДКА В YAML. Grep по тексту сказав
// би «`--cached` на місці» і над будь-якою іншою помилкою в тій самій умові.
// Ми беремо УМОВУ З САМОГО ВОРКФЛОВА і ЗАПУСКАЄМО її в тимчасовому репозиторії
// — у двох станах, які мають дати протилежні відповіді.
{
  const yml = readFileSync(join(ROOT, '.github/workflows/geocode-settlements.yml'), 'utf8');
  const крок = yml.split('- name: Відкрити PR')[1] || '';
  const тіло = (крок.split('run: |')[1] || '').split('\n')
    .map(р => р.replace(/^ {10}/, ''));
  const кінець = тіло.findIndex(р => р.trim() === 'fi');
  const умова = тіло.slice(0, кінець + 1).filter(р => !р.startsWith('git config')).join('\n');
  const МОВЧАНКА = 'PR не потрібен';

  const прогнати = ({ закомітити }) => {
    const дір = mkdtempSync(join(tmpdir(), 'cstl-geo-'));
    const git = (...а) => execFileSync('git', а, { cwd: дір, stdio: 'pipe' });
    git('init', '-q', '.');
    git('config', 'user.email', 'stend@cstl'); git('config', 'user.name', 'stend');
    writeFileSync(join(дір, 'readme'), 'x');
    git('add', '-A'); git('commit', '-qm', 'init');
    mkdirSync(join(дір, 'data'), { recursive: true });
    writeFileSync(join(дір, 'data/settlements-geo.json'), '{"coords":{}}\n');
    if (закомітити) { git('add', '-A'); git('commit', '-qm', 'coords'); }
    return execFileSync('bash', ['-c', умова], { cwd: дір, encoding: 'utf8' });
  };

  // 🔴 Головна: рівно той стан, у якому воркфлов промовчав. Файл щойно
  // згенеровано, у git його ще немає — це НОВІ координати, а не «без змін».
  ok('🔴 новий файл координат не вважається «без змін»',
     !прогнати({ закомітити: false }).includes(МОВЧАНКА),
     'інакше прогін зеленіє, а PR не відкривається');

  // Дзеркальна: без неї «завжди відкривати PR» теж пройшло б — і кнопка
  // плодила б порожні PR щоразу, коли координати не помінялись.
  ok('файл уже в git і не мінявся — PR справді не потрібен',
     прогнати({ закомітити: true }).includes(МОВЧАНКА),
     'інакше кнопка плодить порожні PR');
}

// ─────────────────────────────────────────────────────────────────────────────
// ЧАСТИНА 3 — САМ ФАЙЛ, ЯКЩО ВІН УЖЕ Є.
if (!existsSync(ФАЙЛ)) {
  ok('файла координат ще немає — перевіряти нічого (це не поломка)', true,
     'створюється воркфловом «Координати сіл» або локально geocode-settlements.mjs');
  done();
} else {
  // ⚠️ 21.08 — ФАЙЛ МАЄ ОБГОРТКУ, і перший прогін кнопки це показав: сторож
  // упав на СПРАВНОМУ файлі («бракує: Олика, Горянівка, …», хоча всі 18 пунктів
  // на місці). Скрипт пише `{_note, _generated, coords}`, а я читав верхній
  // рівень — тобто написав перевірку, не подивившись на те, що вона перевіряє.
  // 🔑 Читаємо так само, як застосунок (`loadFile`: `d.coords || d`) — інакше
  // сторож і код мали б два різні уявлення про той самий файл.
  const сире = JSON.parse(readFileSync(ФАЙЛ, 'utf8'));
  const дані = (сире && typeof сире === 'object' && сире.coords) ? сире.coords : сире;
  const назви = Object.keys(дані);

  // 🛑 ПОВНОТА. Половина списку гірша за його відсутність: застосунок вважав би
  // пропущені села «вже з'ясованими» і не спробував би сам.
  const бракує = SETTLEMENTS.filter(n => !дані[n]);
  ok('🔴 у файлі є ВСІ села громади', бракує.length === 0,
     бракує.length ? `бракує: ${бракує.join(', ')}` : `${SETTLEMENTS.length} сіл`);

  // Числа мусять бути числами, а не рядками чи null — інакше порівняння відстані
  // мовчки дасть NaN, і «найближче село» не знайдеться ніколи.
  const кривi = назви.filter(n => !Number.isFinite(дані[n]?.lat) || !Number.isFinite(дані[n]?.lon));
  ok('🔴 усі координати — справжні числа', кривi.length === 0, кривi.join(', '));

  // 🔴 ГОЛОВНА ПЕРЕВІРКА: чуже село з тією ж назвою. «Ставок», «Котів», «Дерно»
  // є не лише на Волині, і геокодер міг віддати тезку за 300 км. Таке число
  // виглядає нормально й оком не ловиться.
  const межа = n => (SETTLEMENTS.includes(n) ? МЕЖА_КМ : МЕЖА_МІСТА_КМ);
  const далекі = назви.filter(n => Number.isFinite(дані[n]?.lat)
                                   && км(ОЛИКА, дані[n]) > межа(n));
  ok(`🔴 жодне село не далі ${МЕЖА_КМ} км від Олики, місто поруч — ${МЕЖА_МІСТА_КМ} км`,
     далекі.length === 0,
     далекі.map(n => `${n} — ${Math.round(км(ОЛИКА, дані[n]))} км`).join(', '));

  // Два села в одній точці означають, що геокодер на щось не відповів і віддав
  // те саме двічі — а капсула тоді показувала б чужу зупинку як свою.
  const пари = [];
  for (let i = 0; i < назви.length; i++) {
    for (let j = i + 1; j < назви.length; j++) {
      const a = дані[назви[i]], b = дані[назви[j]];
      if (Number.isFinite(a?.lat) && Number.isFinite(b?.lat) && км(a, b) < МІН_КМ) {
        пари.push(`${назви[i]} ≈ ${назви[j]}`);
      }
    }
  }
  ok('🔴 різні села не стоять в одній точці', пари.length === 0, пари.join(', '));

  // Олика в файлі має збігтися з тією, що вже живить погоду. Розходження означає
  // два різні уявлення про центр громади — і вони розійдуться далі.
  if (дані['Олика']) {
    const d = км(ОЛИКА, дані['Олика']);
    ok('Олика у файлі збігається з координатами застосунку', d < 3,
       `розбіжність ${d.toFixed(1)} км`);
  }
  done();
}
