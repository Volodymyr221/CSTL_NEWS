// Стенд: ТЕКСТ СТАТЕЙ ПЕРЕЇХАВ — І ПРИ ЦЬОМУ НЕ ЗАГУБИВСЯ.
//
// ═════════════════════════════════════════════════════════════════════════════
// 🔴 ЗАРАДИ ЧОГО (ніч на 22.09.2026). Вова: «Чому додаток так довго став
// завантажувати вкладки?» Заміряно тоді ж, у байтах, тобто в тому, що реально
// їде по мережі:
//
//     data/articles.json   1.8 МБ   ← і 1.38 МБ із них — поле `content`
//     data/schedule.json   673 КБ
//     bundle.js            650 КБ
//
// Повний текст статті показує РІВНО ОДИН екран — читання статті. Списку новин,
// віджету Громади, значкам і фільтрам він не потрібен ЖОДНОГО разу.
// ➡️ `scripts/split_articles.py` ділить файл при складанні сайту: список
// **1844 → 457 КБ**, тексти окремо і лише на вимогу.
//
// 🛑 ГОЛОВНИЙ СТРАХ ВОВИ ПРО ЦЕЙ ФАЙЛ — «якщо це повпливає на якість». Тому
// перша половина стенда не про швидкість, а про ЦІЛІСТЬ: склеюємо поділене
// назад і вимагаємо, щоб вийшов ТОЙ САМИЙ документ, до останнього поля.
// Друга половина — про людину: чи бачить вона повний текст, і що лишається,
// коли файл текстів не доїхав.
// ═════════════════════════════════════════════════════════════════════════════
import { execFileSync } from 'child_process';
import { chromium } from 'playwright';
import { readFileSync } from 'fs';
import { chromiumPath, serve, reporter } from './_lib.mjs';

const { ok, done } = reporter();

// ── ЧАСТИНА 1. ПОДІЛ БЕЗ ВТРАТ (на ЖИВОМУ файлі, не на іграшковому) ────────
{
  const звіт = JSON.parse(execFileSync('python3', ['-c', `
import json, sys
sys.path.insert(0, 'scripts')
from split_articles import поділити, склеїти

сирі = json.load(open('data/articles.json', encoding='utf-8'))
легкі, тексти = поділити(сирі)
назад = склеїти(легкі, тексти)

байт = lambda o: len(json.dumps(o, ensure_ascii=False, indent=2).encode('utf-8'))
print(json.dumps({
    "статей": len(сирі),
    "склеїлось_точно": назад == сирі,
    "з_текстом": sum(1 for a in сирі if a.get("content") is not None),
    "текстів_у_мапі": len(тексти),
    "content_лишився_у_списку": sum(1 for a in легкі if "content" in a),
    "полів_було": sum(len(a) for a in сирі),
    "полів_стало": sum(len(a) for a in легкі),
    "байт_було": байт(сирі),
    "байт_стало": байт(легкі),
}, ensure_ascii=False))
`], { encoding: 'utf-8', cwd: process.cwd() }).trim().split('\n').pop());

  ok('🛑 СКЛЕЄНЕ НАЗАД — ТОЙ САМИЙ ДОКУМЕНТ, до останнього поля',
     звіт.склеїлось_точно === true, звіт.склеїлось_точно ? 'збіглось' : 'РОЗІЙШЛОСЬ');
  ok('жодна стаття не загубилась',
     звіт.полів_стало === звіт.полів_було - звіт.з_текстом,
     `${звіт.полів_було} → ${звіт.полів_стало} при ${звіт.з_текстом} текстах`);
  ok('🔴 у списку не лишилось жодного `content`',
     звіт.content_лишився_у_списку === 0, String(звіт.content_лишився_у_списку));
  ok('кожен текст має свою адресу в мапі',
     звіт.текстів_у_мапі === звіт.з_текстом,
     `${звіт.текстів_у_мапі} із ${звіт.з_текстом}`);
  // 📏 Заради цього все й робилось. Менше ніж удвічі — переїзд не вартий ризику.
  const разів = звіт.байт_було / звіт.байт_стало;
  ok('📏 список справді полегшав, і не на відсотки',
     разів >= 2, `${(звіт.байт_було/1024)|0} КБ → ${(звіт.байт_стало/1024)|0} КБ, у ${разів.toFixed(1)} рази`);
}

// ── ЧАСТИНА 2. ЛЮДИНА БАЧИТЬ ПОВНИЙ ТЕКСТ ──────────────────────────────────
const { url, stop } = await serve();
const executablePath = chromiumPath();
const browser = await chromium.launch({ ...(executablePath ? { executablePath } : {}) });
// Service Worker вимкнено: інакше запити йдуть повз `page.route` і підміна не діє.
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, serviceWorkers: 'block' });

const ПОВНИЙ = '<p>ПОВНИЙ ТЕКСТ СТАТТІ, який приїхав окремим файлом. '
  + 'Він помітно довший за анонс і саме його людина прийшла читати. '.repeat(8) + '</p>';
const АНОНС = 'Короткий анонс статті — рівно те, що лишиться, якщо тексти не доїдуть.';

async function сцена({ текстиДоступні }) {
  const page = await ctx.newPage();
  // 🛑 Збираємо ЗОЙКИ СТОРІНКИ. Мутація «прибрати `.catch` з завантаження
  //    текстів» спершу лишила стенд зеленим: людина й далі бачила анонс, бо
  //    модалку вже намальовано. Тобто той `.catch` стереже не вигляд, а те, що
  //    після невдачі не лишається непроковтнутої помилки — і міряти це треба
  //    окремо, а не вважати доведеним заразом.
  const зойки = [];
  page.on('pageerror', e => зойки.push(String(e.message || e)));
  // ⚠️ Непроковтнутий проміс НЕ дає `pageerror` — це не виняток у коді, а
  //    відмова обіцянки. Тому слухаємо саме її, і саме в сторінці.
  await page.addInitScript(() => {
    window.__відмови = [];
    addEventListener('unhandledrejection', e =>
      window.__відмови.push(String(e.reason && e.reason.message || e.reason)));
  });
  let id = null;
  await page.route('**/data/articles.json', async r => {
    const arts = JSON.parse(await (await r.fetch()).text());
    id = arts[0].id;
    // Рівно те, що віддасть прод після поділу: анонс є, `content` немає.
    arts[0].excerpt = АНОНС;
    delete arts[0].content;
    await r.fulfill({ contentType: 'application/json', body: JSON.stringify(arts) });
  });
  await page.route('**/data/articles-text.json', async r => {
    // 🔑 «Не доїхав» — це ОБРИВ, а не 404: на 404 `fetch` спокійно виконується,
    //    і гілка `.catch` у застосунку навіть не згадується. Перша редакція
    //    цього стенда підставляла 404 — і мутація «прибрати `.catch`» лишалась
    //    зеленою, бо била в код, якого сцена не торкалась.
    if (!текстиДоступні) return r.abort();
    await r.fulfill({ contentType: 'application/json',
                      body: JSON.stringify({ [String(id)]: ПОВНИЙ }) });
  });
  await page.route('**://*.supabase.co/**', r => r.abort());
  await page.route('**://api.open-meteo.com/**', r => r.abort());

  await page.goto(url, { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(2500);
  await page.evaluate(i => { window.location.hash = `#/post/news/${i}`; }, id);
  await page.waitForTimeout(1500);
  const текст = await page.evaluate(() =>
    (document.querySelector('.article-body')?.innerText || '').trim());
  const відмови = await page.evaluate(() => window.__відмови || []);
  await page.close();
  return { текст, зойки: [...зойки, ...відмови] };
}

{
  const { текст } = await сцена({ текстиДоступні: true });
  ok('🔴 стаття без `content` усе одно показує ПОВНИЙ текст',
     текст.includes('ПОВНИЙ ТЕКСТ СТАТТІ'), текст.slice(0, 60) || '(порожньо)');
  ok('📏 і це справді довгий текст, а не анонс під іншою назвою',
     текст.length > АНОНС.length * 3, `${текст.length} знаків проти ${АНОНС.length} в анонсі`);
}

// ── ЧАСТИНА 3. ФАЙЛ НЕ ДОЇХАВ — ЛИШАЄТЬСЯ АНОНС, А НЕ ПОРОЖНЕЧА ────────────
// 🔑 Найважливіша перевірка всього стенда. Переїзд додав новий спосіб зламатись
// (другий файл може не доїхати), і він НЕ СМІЄ лишати людину перед порожнім
// екраном — це рівно та вада, від якої лікувались 18.09 (`offline-screens`).
{
  const { текст, зойки } = await сцена({ текстиДоступні: false });
  ok('🔴 без файлу текстів екран НЕ порожній', текст.length > 20, `${текст.length} знаків`);
  ok('🛑 і показує анонс — те саме, що людина бачила б до переїзду',
     текст.includes('Короткий анонс'), текст.slice(0, 60) || '(порожньо)');
  // 🔑 Невдача мусить бути ПРОКОВТНУТА свідомо, а не лишитись висіти помилкою:
  //    непроковтнута відмова промісу — це шум у консолі кожного жителя і слід,
  //    за яким наступний розбір піде не туди.
  const наші = зойки.filter(з => /articles-text|Unhandled|rejection|fetch/i.test(з));
  ok('🛑 і при цьому не лишає непроковтнутої помилки',
     наші.length === 0, наші.join(' · ').slice(0, 90) || 'тиша');
}

// ── ЧАСТИНА 3-БІС. СКРИПТ НЕ МОЖЕ ЗАТЕРТИ ДЖЕРЕЛО ПРАВДИ ───────────────────
//
// 🛑 Найнебезпечніше в цьому переїзді — не код застосунку, а сам скрипт: він
// переписує `data/articles.json` НА МІСЦІ. Запустив хтось у своїй теці, зробив
// `git add -A` — і текст усіх статей зник із репозиторію, тихо й назавжди.
// Клас той самий, що «`cat >` мовчки затирає» в гарячих правилах.
{
  let код = 0, вивід = '';
  try {
    вивід = execFileSync('python3', ['scripts/split_articles.py'],
                         { encoding: 'utf-8', cwd: process.cwd(), stdio: ['pipe','pipe','pipe'] });
  } catch (e) { код = e.status; вивід = String(e.stdout || ''); }

  ok('🛑 без явного `--деплой` скрипт ВІДМОВЛЯЄТЬСЯ працювати',
     код !== 0, `код виходу ${код}`);
  ok('🔑 і каже, ЧОМУ саме, а не просто «помилка»',
     /джерела правди/.test(вивід), вивід.split('\n')[0].slice(0, 60));

  // 📐 І головне — доводимо, що живий файл ЦІЛИЙ після цієї спроби.
  const цілий = JSON.parse(execFileSync('python3', ['-c', `
import json
a = json.load(open('data/articles.json', encoding='utf-8'))
print(json.dumps({"статей": len(a), "з_текстом": sum(1 for x in a if x.get("content"))}))
`], { encoding: 'utf-8' }).trim());
  ok('🔴 і `data/articles.json` у репозиторії лишився з текстами',
     цілий.з_текстом > 0 && цілий.з_текстом === цілий.статей,
     `${цілий.з_текстом} із ${цілий.статей}`);
}

// ── ЧАСТИНА 4. КОНТРОЛЬ ────────────────────────────────────────────────────
// Якби поділ щось губив, перевірка «склеїлось точно» мусила б це впіймати.
// Доводимо це, навмисно зіпсувавши склейку.
{
  const зіпсовано = execFileSync('python3', ['-c', `
import json, sys
sys.path.insert(0, 'scripts')
from split_articles import поділити
сирі = json.load(open('data/articles.json', encoding='utf-8'))
легкі, тексти = поділити(сирі)
# «Забули» повернути текст — саме та втрата, якої боїться Вова.
print(json.dumps({"збіглось": легкі == сирі}))
`], { encoding: 'utf-8', cwd: process.cwd() }).trim();
  ok('КОНТРОЛЬ: якби текст не повертали, звірка це побачила б',
     JSON.parse(зіпсовано).збіглось === false);
}

await browser.close(); await stop();
done();
