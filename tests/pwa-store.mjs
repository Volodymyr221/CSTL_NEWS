// Стенд: ГОТОВНІСТЬ ДО ВСТАНОВЛЕННЯ І ДО GOOGLE PLAY (TWA).
//
// 🔴 ЗАРАДИ ЧОГО. 19.08 вирішено видавати Android-версію через Play (TWA — тонка
// оболонка навколо цього самого сайту), а iOS лишити на PWA. Усе, від чого це
// залежить, — це кілька файлів у корені, які **ніщо не перевіряло**: маніфест,
// публічна політика, `.nojekyll`, `assetlinks.json`.
//
// 🔑 ЧОМУ САМЕ СТЕНД, А НЕ «Я ПАМʼЯТАЮ». Кожна з цих речей ламається ТИХО:
//   • зіпсований `manifest.json` → застосунок просто перестає пропонуватись до
//     встановлення, помилки в консолі немає;
//   • зниклий `privacy.html` → відхилення в Play через тиждень очікування;
//   • зниклий `.nojekyll` → `.well-known/assetlinks.json` не віддається, і TWA
//     запускається З АДРЕСНИМ РЯДКОМ браузера зверху. Це найчастіша й
//     найнезрозуміліша поломка TWA: додаток «працює», але виглядає як сайт;
//   • `assetlinks.json` із вигаданим відбитком → те саме, але виглядає зробленим.
//
// ⚠️ Браузер тут не потрібен: усе перевіряється по файлах, тому стенд швидкий.
import { readFileSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import { reporter } from './_lib.mjs';

const { ok, done } = reporter();
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const файл = p => join(ROOT, p);
const читати = p => readFileSync(файл(p), 'utf-8');

// 🔑 Дату редакції беремо ТЕКСТОМ із `src/core/legal.js`, а не імпортом модуля.
// Причина практична: `legal.js` — ES-модуль, а `package.json` без `"type":
// "module"` (поставити його не можна, зламається `build.js` на `require`), тож
// кожен імпорт друкував би попередження Node у ВИВІД КОЖНОГО прогону стендів.
// Джерело правди від цього не змінилось — читаємо той самий файл.
const РЕДАКЦІЯ = (читати('src/core/legal.js').match(/LEGAL_UPDATED\s*=\s*'([^']+)'/) || [])[1] || null;

// ── 1. МАНІФЕСТ ──────────────────────────────────────────────────────────────
let m = null;
try { m = JSON.parse(читати('manifest.json')); } catch (e) { /* нижче впаде */ }

ok('manifest.json — правильний JSON', !!m, m ? 'ок' : 'не читається');

if (m) {
  ok('є імʼя і коротке імʼя', !!m.name && !!m.short_name, `${m.name} / ${m.short_name}`);
  ok('display: standalone (інакше Play не візьме як застосунок)',
     m.display === 'standalone', m.display);

  // 🔴 `id` — ПОСТІЙНА ТОТОЖНІСТЬ ЗАСТОСУНКУ. Браузер за ним відрізняє «це той
  // самий додаток» від «це інший». До 19.08 тут стояло `/CSTL_NEWS/` — шлях
  // старого дзеркала на github.io, якого на власному домені НЕ ІСНУЄ.
  // ⚠️ Міняти його після виходу в Play НЕ МОЖНА: для системи це буде інший
  // застосунок. Саме тому виправлено ДО запуску, а стенд тепер тримає значення.
  ok('🔴 id вказує на корінь домену, а не на старий шлях github.io',
     m.id === '/', m.id);

  ok('start_url і scope відносні (сайт живе в корені)',
     m.start_url === './' && m.scope === './', `${m.start_url} · ${m.scope}`);

  const іконки = m.icons || [];
  const має = px => іконки.some(i => (i.sizes || '').includes(`${px}x${px}`));
  ok('є іконки 192 і 512', має(192) && має(512), іконки.map(i => i.sizes).join(' · '));
  // maskable — щоб Android не малював білу підкладку під іконкою на головному екрані.
  ok('512 позначена maskable (Android малює її без білої підкладки)',
     іконки.some(i => (i.sizes || '').includes('512') && /maskable/.test(i.purpose || '')),
     іконки.find(i => (i.sizes || '').includes('512'))?.purpose || '(не задано)');

  for (const шлях of іконки.map(i => i.src)) {
    ok(`іконка ${шлях} існує на диску`, existsSync(файл(шлях)));
  }
  ok('theme_color заданий', !!m.theme_color, m.theme_color);
}

// ── 2. ПУБЛІЧНА ПОЛІТИКА ─────────────────────────────────────────────────────
// Google Play вимагає посилання, яке відкривається ЗЗОВНІ застосунку.
// Контроль: якщо дату не вдалось прочитати — перевірка нижче стала б порожньою і
// пройшла б «успішно», нічого не перевіривши. Кажемо про це прямо.
ok('КОНТРОЛЬ: дату редакції прочитано з legal.js', !!РЕДАКЦІЯ, РЕДАКЦІЯ || 'НЕ ЗНАЙДЕНО');

ok('privacy.html існує (URL для Play Console)', existsSync(файл('privacy.html')));

if (existsSync(файл('privacy.html'))) {
  const p = читати('privacy.html');
  ok('privacy.html не порожній', p.length > 3000, `${Math.round(p.length / 1024)} KB`);
  ok('у ньому справді політика, а не заготовка',
     /Політика конфіденційності/.test(p) && /legal-h/.test(p));
  // 🔴 ГОЛОВНА ПЕРЕВІРКА РОЗДІЛУ. Сторінка генерується з `src/core/legal.js`, і
  // сенс генерації саме в тому, щоб копії тексту не існувало. Якщо дата на
  // сторінці відстала від дати в модулі — значить сторінку хтось написав руками
  // або забув перезібрати, тобто у застосунку одна редакція документа, а на
  // публічній сторінці інша. Для документа, під яким люди дають згоду, це не
  // косметика.
  ok('🔴 редакція на сторінці збігається з `legal.js` (копії тексту не завелось)',
     !!РЕДАКЦІЯ && p.includes(РЕДАКЦІЯ), `у legal.js ${РЕДАКЦІЯ}`);
}

// ── 3. ЩОБ .well-known ВЗАГАЛІ ВІДДАВАВСЯ ────────────────────────────────────
ok('🔴 .nojekyll на місці (без нього Pages може не віддати теку `.well-known`)',
   existsSync(файл('.nojekyll')));

// ── 4. ASSETLINKS — ЯКЩО ВЖЕ СТВОРЕНИЙ ───────────────────────────────────────
// Файла ще немає і це НОРМАЛЬНО: для нього потрібен відбиток ключа підпису, який
// зʼявиться під час першої збірки Bubblewrap. Але щойно він зʼявиться — він має
// бути справжнім.
const AL = '.well-known/assetlinks.json';
if (!existsSync(файл(AL))) {
  ok('assetlinks.json ще немає — очікувано до першої збірки оболонки', true,
     'зʼявиться після `bubblewrap build` (див. docs/PLAY_TWA.md)');
} else {
  let a = null;
  try { a = JSON.parse(читати(AL)); } catch (e) { /* нижче */ }
  ok('assetlinks.json — правильний JSON', !!a);
  if (a) {
    ok('це масив із записом про застосунок', Array.isArray(a) && a.length > 0);
    const t = a[0]?.target || {};
    const відбитки = t.sha256_cert_fingerprints || [];
    ok('вказано package_name', !!t.package_name, t.package_name || '(немає)');
    // 🛑 Відбиток SHA-256 — це рівно 32 байти у шістнадцятковому вигляді через
    // двокрапки. Будь-що інше (зокрема «ВІДБИТОК:З:ДВОКРАПКАМИ» із інструкції)
    // означає, що файл закомітили заготовкою — і TWA мовчки запуститься з
    // адресним рядком браузера, а причину шукатимуть годинами.
    const справжній = /^([0-9A-F]{2}:){31}[0-9A-F]{2}$/i;
    ok('🔴 відбиток справжній, а не заготовка з інструкції',
       відбитки.length > 0 && відбитки.every(f => справжній.test(f)),
       відбитки.join(' · ') || '(порожньо)');
  }
}

done();
