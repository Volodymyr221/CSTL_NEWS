// Стенд: ШІ-АГЕНТ СПІЛЬНОТИ OLYKA CASTLE і безпека чернеток.
//
// 🔴 ЗАРАДИ ЧОГО. 20.08 запущено агента, який пише пости у стрічку від імені
// офіційної спільноти бренду. Вова обрав режим «чернетка»: текст лягає в базу,
// але читач його не бачить, поки Вова не натисне «Опублікувати».
//
// 🛑 ТУТ ДВА КЛАСИ РИЗИКУ, І ОБИДВА ТИХІ:
//   1. ЧЕРНЕТКА ПРОТІКАЄ. Пост, якого Вова ще не вичитав, зʼявляється у людей.
//      Нічого не падає, помилки немає — просто бренд сказав те, чого не збирався.
//      Захист подвійний: політика читання бази + фільтр у клієнті. Стенд
//      перевіряє ОБИДВА, бо кожен окремо колись можна зняти правкою.
//   2. АГЕНТ ПИШЕ БЕЗ ФАКТІВ. Тема без `facts` у плані означала б, що модель
//      складе текст «з голови» — для офіційної сторінки це найдорожча помилка.
//
// ⚠️ Браузер тут не потрібен: перевіряємо файли, конфіг і SQL-міграцію.
import { execFileSync } from 'child_process';
import { readFileSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import { reporter } from './_lib.mjs';

const { ok, done } = reporter();
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const файл = p => join(ROOT, p);
const читати = p => readFileSync(файл(p), 'utf-8');

// ── 1. ЧЕРНЕТКА НЕ ПРОТІКАЄ ──────────────────────────────────────────────────
const міграція = existsSync(файл('scripts/supabase_page_post_drafts.sql'))
  ? читати('scripts/supabase_page_post_drafts.sql') : '';
ok('міграція чернеток є в репозиторії', міграція.length > 0);

// Головна лінія захисту — у базі. Політика має вимагати ОБИДВІ умови разом:
// не видалений І опублікований; редактор сторінки — виняток.
ok('🔴 політика читання ховає чернетки від читача (перша лінія — база)',
   /deleted_at is null\)\s*and\s*\(status\s*=\s*'published'\)/i.test(міграція)
   && /can_edit_page/i.test(міграція),
   міграція.match(/using\s*\([\s\S]*?\);/i)?.[0]?.replace(/\s+/g, ' ').slice(0, 120) || '—');

// Друга лінія — клієнт. Якщо колись знімуть її, база все одно втримає; якщо
// знімуть базу — втримає клієнт. Тому перевіряємо саме ОБИДВІ.
const supa = читати('src/core/supabase.js');
ok('🔴 стрічка просить у бази лише опубліковані (друга лінія — клієнт)',
   /fetchPagePosts[\s\S]{0,1200}?\.eq\('status',\s*'published'\)/.test(supa));

// ⚠️ А ось у запасному запиті фільтра бути НЕ повинно: він існує на випадок, що
// колонки ще немає, і фільтр там перетворив би «нема галочки» на порожню Стрічку.
const запасний = supa.slice(supa.indexOf('let q2 = supa.from(\'page_posts\')'), supa.indexOf('let q2') + 700);
ok('у запасному запиті фільтра свідомо немає (інакше порожня Стрічка при старій базі)',
   !/\.eq\('status'/.test(запасний));

ok('є спосіб опублікувати чернетку', /export async function publishPagePost/.test(supa));
// Публікація має піднімати час: інакше пост, який пролежав чернеткою, вийде
// одразу похованим під свіжими.
ok('публікація оновлює час поста (щоб не вийшов одразу похованим)',
   /publishPagePost[\s\S]{0,400}created_at:\s*new Date\(\)/.test(supa));

const feed = читати('src/tabs/feed.js');
ok('у стрічці чернетка має видиму позначку', /fd-draft-badge/.test(feed));
ok('у стрічці є кнопка «Опублікувати»', /data-publish=/.test(feed) && /publishDraft/.test(feed));
// 🔴 20.08, уточнення Вови: переглядати й публікувати має вся КОМАНДА сторінки,
// не лише власник. Окремого механізму для цього не заводили — і база
// (`can_edit_page`), і клієнт (`myPageIds` ← `page_admins`) питають ОДНЕ І ТЕ САМЕ,
// тож модератор із «Команди сторінки» отримує ті самі права автоматично.
// Стережемо саме цю єдність: кнопка стоїть за тим же прапорцем, що й меню «⋯».
ok('🔴 публікувати може вся команда сторінки (той самий прапорець, що й «⋯»)',
   /чернетка && canEditPost \?/.test(feed) && /const canEditPost = myPageIds\.has/.test(feed));
ok('команда сторінки додається за поштою і вже має інтерфейс',
   /addPageModerator/.test(feed) && /Додати модератора за поштою/.test(feed));

// ── 2. АГЕНТ НЕ ПИШЕ БЕЗ ФАКТІВ ──────────────────────────────────────────────
const план = JSON.parse(читати('editor/plans/olyka_castle.json'));
ok('план постів існує і має сторінку', план.page_id === 3, `page_id: ${план.page_id}`);
// 🔴 20.08 — перевірку УТОЧНЕНО, і це не послаблення. Було: «у кожної теми є
// факти». Стало: тема без фактів дозволена, але ЛИШЕ як явна заготовка з
// позначкою «ЗАПОВНИТИ». Причина: у плані тепер стоять місця під звичайні пости,
// факти для яких знає Вова, а не Claude — і мовчазна заготовка без позначки
// виглядала б як забутий недописаний запис.
// ⚠️ Справжній захист від вигадування живе не тут, а в `plan.py`: тему без
// фактів джерело пропускає. Це перевірено окремо нижче.
const заготовка = p => /^ЗАПОВНИТИ/.test((p.topic || '').trim());
ok('🔴 тема або має факти, або чесно позначена як заготовка',
   (план.posts || []).every(p => (p.topic || '').trim()
     && (заготовка(p) || (Array.isArray(p.facts) && p.facts.length))),
   `тем: ${(план.posts || []).length}, з них заготовок: ${(план.posts || []).filter(заготовка).length}`);
ok('заготовки — саме ЗВИЧАЙНІ пости (бракує нам не функцій)',
   (план.posts || []).filter(заготовка).every(p => (p.kind || 'brand') === 'brand'));
ok('у кожної теми є унікальний id (за ним памʼять не дасть написати двічі)',
   new Set((план.posts || []).map(p => p.id)).size === (план.posts || []).length);
ok('пости про функції пояснюють, ЯК користуватись',
   (план.posts || []).filter(p => p.kind === 'feature').every(p => (p.how || '').trim()));

const джерело = читати('editor/sources/plan.py');
ok('🔴 джерело пропускає теми без фактів, а не додумує',
   /не\s*\(запис\.get\("topic"\)|not \(запис\.get\("topic"\)/.test(джерело) || /немає теми або фактів/.test(джерело));

const письменник = читати('editor/writers/brand_writer.py');
ok('🔴 у промпті стоїть пряма заборона вигадувати факти',
   /ЗАБОРОНА 1: не додавай жодного факту/.test(письменник));
ok('модель — Opus 5 (рішення Вови)', /MODEL = "claude-opus-5"/.test(письменник));
ok('🔴 без ключа агент НЕ пише заглушку в чергу на публікацію',
   /немає ANTHROPIC_API_KEY — пропускаю/.test(письменник));
ok('відмову моделі обробляємо окремо (інакше порожній пост)',
   /stop_reason.*refusal/.test(письменник));

// ── 3. ГРОШІ РАХУЮТЬСЯ ЗА ПРАВИЛЬНОЮ МОДЕЛЛЮ ─────────────────────────────────
// До 20.08 лічильник знав лише ціни Sonnet і мовчки занизив би витрати Opus удвічі.
const spend = читати('editor/core/spend.py');
ok('🔴 лічильник знає ціни Opus 5 окремо від Sonnet',
   /"claude-opus-5":\s*\{"in":\s*5\.0,\s*"out":\s*25\.0/.test(spend));
ok('невідома модель не зникає з обліку, а рахується за Sonnet із попередженням',
   /ціни для .* невідомі — рахую за claude-sonnet-5/.test(spend));
ok('письменник передає модель у лічильник', /model=MODEL/.test(письменник));

// ── 4. КОНВЕЄР І РОЗКЛАД ─────────────────────────────────────────────────────
const місія = JSON.parse(читати('editor/missions/olyka_castle.json'));
ok('місія веде в чернетки сторінки', місія.sink === 'page_draft', місія.sink);
ok('🔴 фото вимкнене явно (інакше під пост бренду поїде випадкове з Вікімедії)',
   місія.image === 'none', місія.image);
ok('за прогін — один пост', місія.per_run === 1);

const робота = читати('.github/workflows/olyka-agent.yml');
const cron = робота.match(/cron:\s*'([^']+)'/)?.[1] || '';
const днів = (cron.split(' ')[4] || '').split(',').filter(Boolean).length;
ok('🔴 розклад — 3-4 пости на тиждень (вибір Вови)', днів >= 3 && днів <= 4,
   `${cron} → днів на тиждень: ${днів}`);
ok('памʼять агента комітиться назад (інакше напише те саме двічі)',
   /olyka_agent_state\.json/.test(робота));

const sink = читати('editor/sinks/page_draft.py');
ok('🔴 sink пише саме чернетку, а не публікацію', /"status": "draft"/.test(sink));
// ⚠️ Шукаємо саме ВИКЛИК `mark_done(...)`, а не слово: перша версія цієї
// перевірки натрапляла на рядок ІМПОРТУ вгорі файлу і тому падала на цілком
// правильному коді. Порівнювати треба те, що виконується, а не те, що написано.
ok('памʼять позначається ЛИШЕ після підтвердженого запису',
   sink.indexOf('mark_done(plan_id,') > sink.indexOf('urlopen('),
   `виклик на ${sink.indexOf('mark_done(plan_id,')}, запит на ${sink.indexOf('urlopen(')}`);
ok('без ключа Supabase нічого не пишеться і про це сказано',
   /немає SUPABASE_SERVICE_ROLE_KEY — чернетку НЕ збережено/.test(sink));

// ── 5. ПОСТ ПИШЕТЬСЯ ДЛЯ ЛЮДИНИ, А НЕ ЗВІТ ПРО РОБОТУ ────────────────────────
// 🔴 20.08, після першого ж живого поста. Він вийшов такий: «раніше картка
// займала 121 піксель… тепер 51-53 пікселі». Вова: «такі технічні деталі для
// людей не цікаві, їм треба розуміти зручність для них».
// ⚠️ ВИНЕН БУВ НЕ АГЕНТ. Агенту заборонено вигадувати — він переказав ті факти,
// які отримав, а факти писав Claude, і саме в них були пікселі. Тому стережемо
// ТРИ місця одразу: сам план, голос і промпт. Досить полагодити одне — і вада
// повернеться з наступною темою, яку впише людина.
const мірки = /\b\d+\s*(пікс|px|відсотк\w* реалізац)/i;
// ⚠️ Дивимось САМЕ текст постів, а не весь файл: у довідці зверху пікселі названі
// НАВМИСНО — як приклад того, чого писати не можна. Перша версія цієї перевірки
// падала саме на ньому, тобто карала документацію за те, що вона попереджає.
const текстПостів = JSON.stringify((план.posts || []).map(
  п => [п.topic, (п.facts || []).join(' '), п.how || '', п.note || ''].join(' ')));
ok('🔴 у фактах плану немає інженерних мірок (пікселів)',
   !мірки.test(текстПостів), текстПостів.match(мірки)?.[0] || 'чисто');
ok('🔴 голос прямо забороняє технічні мірки',
   /НЕ ГОВОРИМО ТЕХНІЧНИМИ МІРКАМИ/.test(читати('editor/voice/olyka_castle.md')));
ok('🔴 промпт теж забороняє (друга лінія — факти пише людина)',
   /ЗАБОРОНА 2 — ТЕХНІЧНІ МІРКИ/.test(письменник));
ok('пост про функцію починається з вигоди, а не з опису зміни',
   /Починай з ВИГОДИ/.test(письменник));

// ── 6. ПОСТИ ПРО ФУНКЦІЇ — МЕНШІСТЬ ──────────────────────────────────────────
// Друга вимога Вови тим же повідомленням: «таких постів має бути менший відсоток
// від постів звичайних». Перевіряємо ЗАПУСКОМ правила, а не наявністю слова:
// правило, яке порахували і не застосували, виглядало б так само.
const правило = (види, максимум = 0.34) => execFileSync('python3', ['-c', `
import sys; sys.path.insert(0, ${JSON.stringify(ROOT)})
from editor.sources.plan import функція_дозволена
print(функція_дозволена(${JSON.stringify(види)}, ${максимум}))`],
  { encoding: 'utf-8' }).trim();

ok('🔴 дві функції поспіль не пишуться ніколи',
   /дві поспіль/.test(правило(['feature'])), правило(['feature']));
ok('🔴 частка функцій тримається в межах (рахується З УРАХУВАННЯМ цього поста)',
   /частка/.test(правило(['feature', 'brand', 'brand'])), правило(['feature', 'brand', 'brand']));
ok('КОНТРОЛЬ: після трьох звичайних функцію писати МОЖНА',
   правило(['brand', 'brand', 'brand']) === '', правило(['brand', 'brand', 'brand']) || 'дозволено');
ok('перший пост не блокується (історії ще немає)',
   правило([]) === '', правило([]) || 'дозволено');
ok('вид поста запамʼятовується — інакше пропорцію не порахувати',
   /mark_done\(plan_id, \(draft\.meta or \{\}\)\.get\("post_kind"/.test(sink));

// ── 7. ТЕМИ ПРО ГРОМАДУ БЕРУТЬСЯ З ПЕРЕВІРЕНИХ ФАЙЛІВ ───────────────────────
// 🔴 20.08, Вова: «більше про громаду, Олику факти і різні пости». Раніше єдиним
// джерелом був план, і коли Вова не встигав його наповнювати, агент мовчав —
// правило пропорції блокувало функції, а звичайних тем не було взагалі.
// 🛑 ГОЛОВНЕ, ЩО ТУТ СТЕРЕЖЕМО: нові теми НЕ означають нових вигадок. Факти
// беруться з файлів, які веде ЛЮДИНА (`olyka-stories.json` — вичитаний текст
// проєкту, `events.json` — дати подій). Якби агент писав про Олику «з памʼяті
// моделі», перша ж неточна дата про замок коштувала б довіри до сторінки.
const теми = (файл, аргументи) => JSON.parse(execFileSync('python3', ['-c', `
import sys, json; sys.path.insert(0, ${JSON.stringify(ROOT)})
from editor.sources.plan import ${файл}
print(json.dumps(${файл}(${аргументи}), ensure_ascii=False))`],
  { cwd: ROOT, encoding: 'utf-8' }));

const історії = теми('історії_олики', 'set()');
ok('🔴 історії про Олику стали темами постів', історії.length >= 3,
   `тем: ${історії.length}`);
ok('🔴 у кожної історії є факти з файлу (не з памʼяті моделі)',
   історії.every(т => (т.facts || []).length >= 2 && (т.topic || '').trim()));
ok('історії — ЗВИЧАЙНІ пости (саме їх бракувало)',
   історії.every(т => т.kind === 'brand'));
// Мітка з назви, а не з порядкового номера: переставили записи у файлі — і агент
// написав би те саме вдруге.
ok('🔴 id теми не залежить від порядку в файлі',
   історії.every(т => /^story:[^:]+$/.test(т.id) && !/^story:\d+$/.test(т.id)),
   історії[0]?.id || '—');
ok('уже написана історія вдруге не пропонується',
   теми('історії_олики', `{${JSON.stringify(історії[0].id)}}`).length === історії.length - 1);

const давно = теми('найближчі_події', "set(), '2020-01-01'");
ok('🔴 подія, що вже минула, у теми не потрапляє',
   давно.every(т => !/2019|2018/.test(JSON.stringify(т.facts))));
const далеко = теми('найближчі_події', "set(), '1990-01-01'");
ok('🔴 подія за півроку теж не береться (анонс нічого не змінює сьогодні)',
   далеко.length === 0, `тем: ${далеко.length}`);

const голос = читати('editor/voice/olyka_castle.md');
ok('файл голосу бренду існує і не порожній', голос.length > 1000, `${голос.length} символів`);
ok('голос теж забороняє вигадувати факти (правило продубльоване навмисно)',
   /Не вигадуємо фактів/.test(голос));

done();
