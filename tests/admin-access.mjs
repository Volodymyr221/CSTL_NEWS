// Стенд: ДОСТУПИ І ЖУРНАЛ ДІЙ АДМІНА.
//
// 🔴 ЗАРАДИ ЧОГО. 20.08 виявилось, що людина, яка пішла з команди 26.07, станом
// на 20.08 досі мала ПОВНІ права публікувати від імені видання. Вона зайшла в
// кабінет рівно один раз — 09.07, того ж дня, коли доступ видали. Прибрати
// вдалось лише SQL-запитом: списку тих, хто має доступ, в адмінці не існувало.
//
// 🛑 ЧОМУ ЦЕЙ СТЕНД ТЕКСТОВИЙ, А НЕ БРАУЗЕРНИЙ. Справжня перевірка прав живе в
// RLS-політиках Postgres, і Playwright її не бачить: він може довести лише, що
// кнопки немає на екрані. А «кнопки немає» — це рівно той вид захисту, який
// проєкт відкидає. Тому тут два різні предмети перевірки:
//   • ЩО ЗАХИЩАЄ — доводиться SQL-експериментом у самій базі (зроблено вручну
//     20.08, результати записані нижче й у журналі сесії);
//   • ЩО НЕ ЗЛАМАЄТЬСЯ ПРАВКОЮ — стереже цей файл.
// Тобто стенд не претендує довести безпеку. Він стереже, щоб зроблене не
// відкотили тихо — а це саме те, що з доступами і сталось.
import { readFileSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import { reporter } from './_lib.mjs';

const { ok, done } = reporter();
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const читати = p => readFileSync(join(ROOT, p), 'utf-8');

const sql   = existsSync(join(ROOT, 'scripts/supabase_admin_access.sql'))
  ? читати('scripts/supabase_admin_access.sql') : '';
const admin = читати('admin.html');

// ── 1. ВІДКЛИКАННЯ ДІЄ В БАЗІ, А НЕ В ІНТЕРФЕЙСІ ────────────────────────────
// 🔑 Головне з усього файлу. Якщо `disabled_at` перевіряє лише клієнт, то
// «відкликано» означає «сховали кнопки», а доступ лишається живим.
ok('міграція доступів є в репозиторії', sql.length > 0);
ok('🔴 права редактора враховують відкликання (has_editor_perm)',
   /has_editor_perm[\s\S]{0,800}?disabled_at is null/i.test(sql));
// ⚠️ Друга половина тієї ж дірки: `is_team_member()` пускає в АДМІНКУ будь-кого,
// хто присутній у `editor_users`. Без цієї правки відкликаний редактор і далі
// бачив би пункт «Адмінка» в меню застосунку і відкривав би кабінет.
ok('🔴 вхід у кабінет теж враховує відкликання (is_team_member)',
   /is_team_member[\s\S]{0,600}?disabled_at is null/i.test(sql));

// ── 2. ДАНІ, БЕЗ ЯКИХ ЕКРАН БЕЗСИЛИЙ ────────────────────────────────────────
// 🛑 Причина діри була не «немає екрана», а «показувати нема чого»: у таблиці не
// існувало ні дати останнього входу, ні позначки відкликання.
for (const колонка of ['disabled_at', 'disabled_by', 'last_seen_at', 'invited_by']) {
  ok(`у editor_users є «${колонка}»`, new RegExp(`add column if not exists\\s+${колонка}`).test(sql));
}

// ── 3. ЖУРНАЛ ДІЙ ───────────────────────────────────────────────────────────
ok('🔴 журнал дій адміна заведено', /create table if not exists admin_audit_log/i.test(sql));
// Журнал, у який може дописати той, чиї дії він фіксує, — не журнал.
ok('🔴 клієнт НЕ може дописати в журнал (політики на запис немає)',
   /create policy audit_read_admin[\s\S]{0,200}?for select/i.test(sql)
   && !/on admin_audit_log[\s\S]{0,200}?for insert/i.test(sql));
ok('🔴 сама функція запису відібрана в клієнтів',
   /revoke all on function public\.admin_audit\([^)]*\) from public, anon, authenticated/i.test(sql));
ok('журнал читає лише адмін', /audit_read_admin[\s\S]{0,120}?is_admin\(\)/i.test(sql));

// ── 4. СТОРОЖ УСЕРЕДИНІ ФУНКЦІЙ, А НЕ ЛИШЕ В ПОЛІТИЦІ ───────────────────────
// Функція з правами власника обходить RLS за визначенням, тож `is_admin()` мусить
// стояти в її ТІЛІ. Той самий урок, що з `submit_board_post` (01.08).
for (const fn of ['admin_set_editor_perms', 'admin_set_editor_disabled']) {
  const тіло = sql.slice(sql.indexOf(`function public.${fn}`));
  ok(`🔴 ${fn} перевіряє is_admin() всередині`,
     /if not public\.is_admin\(\) then\s*\n?\s*raise exception 'not_admin'/i.test(тіло.slice(0, 900)));
}
ok('зміна прав і відкликання пишуть у журнал тією ж дією',
   /admin_set_editor_perms[\s\S]{0,1200}?admin_audit\('editor\.permissions'/.test(sql)
   && /admin_set_editor_disabled[\s\S]{0,1400}?admin_audit\(/.test(sql));

// ── 5. АДМІНКА НЕ ПРАВИТЬ ТАБЛИЦЮ НАПРЯМУ ───────────────────────────────────
// ⚠️ Пряме `update editor_users` з клієнта пройшло б повз журнал — і дія, яку
// найбільше треба бачити в історії, була б єдиною, якої там немає.
ok('🔴 адмінка міняє доступи ЛИШЕ через RPC, не прямим update',
   /supa\.rpc\('admin_set_editor_disabled'/.test(admin)
   && !/from\('editor_users'\)[\s\S]{0,120}?\.update\(/.test(admin));
ok('розділ «Доступи» є в меню і в роутері',
   /id: 'access'/.test(admin) && /activeTab === 'access'/.test(admin));

// ── 6. ЛІЧИЛЬНИК КАЖЕ ПРО ДІЮ, А НЕ ПРО КІЛЬКІСТЬ ───────────────────────────
// Принцип усієї адмінки: плитка показує «скільки чекає МОЄЇ дії». «Скільки всього
// редакторів» — просто число; «скільки забутих доступів» — причина зайти.
ok('🔴 лічильник плитки рахує ЗАБУТІ доступи, а не всіх редакторів',
   /count: \(\) => accessRows\.filter\(забутий\)\.length/.test(admin));
ok('«забутий» = діючий доступ без входу понад 30 днів',
   /ЗАБУТИЙ_ДНІВ = 30/.test(admin) && /function забутий\(r\)/.test(admin));
// 🔑 «Жодного разу не заходив» мусить рахуватись забутим ОДРАЗУ: саме такий
// доступ і був у людини, яка пішла з команди.
ok('🔴 «жодного разу не заходив» — теж забутий',
   /if \(!r\.last_seen_at\) return true/.test(admin));

// ── 7. ВІДМІТКА ПРО КОРИСТУВАННЯ ДОСТУПОМ ───────────────────────────────────
// ⚠️ `auth.users.last_sign_in_at` не годиться: він росте від входу в ЗАСТОСУНОК.
// Людина може щодня заходити як житель і роками не відкривати кабінет.
ok('🔴 вхід у кабінет відмічається окремо від входу в застосунок',
   /supa\.rpc\('touch_editor_seen'\)/.test(admin) && /function public\.touch_editor_seen/.test(sql));
ok('відмітка торкається лише ВЛАСНОГО рядка',
   /touch_editor_seen[\s\S]{0,400}?where uid = auth\.uid\(\)/.test(sql));

// ── 8. ВІДКЛИКАННЯ — З ПІДТВЕРДЖЕННЯМ І БЕЗ ОПТИМІЗМУ ───────────────────────
// Межа проєкту: підтверджуємо незворотне і публічне, не підтверджуємо перегляд.
ok('відкликання питає підтвердження', /data-access-off[\s\S]{0,700}?confirm\(/.test(admin));
// 🛑 «Відкликано» на екрані при невдалому запиті — найгірше, що може показати
// саме цей розділ: людина буде впевнена, що доступу немає, а він є.
ok('🔴 стан не міняється, поки сервер не підтвердив',
   /if \(error\) \{[\s\S]{0,160}?showToast\('Не вдалось/.test(admin));

// ── 9. ГОЛОВНИЙ ЕКРАН: ЧЕРГА ЗАМІСТЬ 14 РІВНИХ ПЛИТОК ───────────────────────
// 🔴 20.08. Було: чотирнадцять рівноправних плиток однією сіткою — «Налаштування»
// важили стільки ж, скільки «Скарги», де хтось чекає рішення просто зараз.
// Стало: черга дій нагорі + групи за змістом роботи.
ok('🔴 нагорі — черга того, що чекає дії', /function чергаДій\(\)/.test(admin) && /queue-row/.test(admin));
// 🛑 Порожня черга мусить бути ВІДПОВІДДЮ, а не порожнечею: інакше треба обійти
// всі розділи, щоб переконатись, що робити нічого.
ok('🔴 порожня черга каже «усе розібрано», а не показує нічого',
   /Усе розібрано/.test(admin) && /queue--calm/.test(admin));
ok('у черги лише ненульові рядки', /if \(n\('reports'\)\)\s*q\.push/.test(admin));
ok('розділи згруповані за змістом роботи',
   ['Модерація','Контент','Громада','Доступ','Система'].every(g => new RegExp(`group: '${g}'`).test(admin)));
// ⚠️ Рахуємо ЛИШЕ всередині `menuItems()`. Перша версія цієї перевірки брала
// весь файл і ловила ще й рядки черги (`{ id: 'reports', n: … }`) — 19 проти 14,
// тобто звинувачувала справний код. Двадцятий випадок брехливої мірки в проєкті.
const менюТіло = admin.slice(admin.indexOf('function menuItems()'), admin.indexOf('function renderApp()'));
const пунктів = (менюТіло.match(/\{ id: '[a-z]+',/g) || []).length;
const груп    = (менюТіло.match(/group: '[А-Яа-яІіЇїЄєҐґ]+'/g) || []).length;
ok('у КОЖНОГО пункту меню є група (жоден не загубиться)',
   пунктів > 0 && пунктів === груп, `пунктів ${пунктів}, груп ${груп}`);

// ── 10. ЛІЧИЛЬНИКИ КАЖУТЬ ПРО ДІЮ, А НЕ ПРО КІЛЬКІСТЬ ───────────────────────
// Принцип був закладений, але половина плиток його порушувала: «Коментарі 200»,
// «Люди 12», «Адміни 1» — це не робота, це просто числа, і вони змагались за
// увагу з тими, де справді хтось чекає.
for (const [id, чому] of [['published','опубліковані не потребують дії'],
                          ['comments','кількість коментарів — не робота'],
                          ['communities','кількість спільнот — не робота'],
                          ['people','кількість профілів — не робота'],
                          ['admins','кількість адмінів — не робота']]) {
  ok(`лічильник «${id}» прибрано (${чому})`,
     new RegExp(`id: '${id}',[^\\n]*count: \\(\\) => 0`).test(admin));
}
// 🔑 А ось у статей лічильник СТАВ осмисленим: не «скільки всього», а скільки
// чернеток чекає вичитки.
ok('🔴 лічильник статей рахує ЧЕРНЕТКИ, а не всі статті',
   /id: 'articles',[^\n]*articles\.filter\(a => a\.status === 'draft'\)\.length/.test(admin));

// ⚠️ «Адміни» і «Доступи» стоять поруч в одній групі: з однаковою іконкою їх
// доводилось розрізняти читанням підпису, тобто іконка не працювала взагалі.
ok('«Доступи» мають власну іконку, не спільну з «Адмінами»',
   /const ICO_KEY =/.test(admin) && /id: 'access',\s*icon: ICO_KEY/.test(admin));

done();
