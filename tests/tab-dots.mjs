// ── Нормалізація часу в зоні питань (фікс 30.07, перенацілено 11.08) ─────────
// 🔴 Баг був такий: `t > dividerTs`, де `t` — ISO-РЯДОК із `created_at`, а
// `dividerTs` — ЧИСЛО мс. Умова завжди false, роздільник «Нові повідомлення» не
// зʼявлявся НІКОЛИ. Виправлено через `tsMs`.
//
// ⚠️ 11.08 — ПЕРЕВІРКУ ПЕРЕНАЦІЛЕНО, І ЦЕ НЕ «ПІДГОНКА ПІД ЗЕЛЕНЕ».
// Сам роздільник зник разом із переходом вкладки на Q&A: він був чат-механікою
// («читай з місця, де спинився»), а в питаннях людина читає згори. Але ПРИЧИНА
// бага нікуди не поділась — межа «прочитано» з localStorage (ЧИСЛО) і далі
// порівнюється з `created_at` (ISO-РЯДОК), тепер у `lastAnswerTs`, на якому
// тримається і сортування списку, і крапка «є нове» біля вкладки.
// 🔑 Тому стенд тримається не за рядок коду, який зник, а за ІНВАРІАНТ: жодне
// порівняння часу в цьому файлі не йде повз `tsMs()`. Той самий урок, що вже
// коштував роботи: перевірка мусить триматись за поведінку, а не за форму запису
// (через це впав `modal-scroll-lock.mjs` при переїзді жесту).
const порівняння = [...DISC_JS.matchAll(/if \(t > max\)|(\S+)\s*>\s*seen\b/g)];
