// ── КРУГЛА КНОПКА «ГРОМАДА» — БІЛА ПІДКЛАДКА, А НЕ ПОРОЖНІЙ ОБІДОК ──────────
// 🔴 Скарга Вови 08.08 зі знімком: «коли натискаю на іконку громади, фотографія
// звужується і збільшується, але взаді фон його видно — просвітлюється, тільки є
// обідок цей білий… зроби, щоб такої прозорої полосочки не було».
//
// Механіка: коло стискається до `scale(0.93)` при натиску, а біле кільце навколо —
// ні. Кільце було `border: 3px solid` — тобто КОНТУР із порожнім нутром, тож у
// момент стиснення між колом і кільцем відкривалась смуга, крізь яку світилась
// сторінка (на Громаді там темне фото — виходила темна дуга).
//
// ⚠️ ЧОМУ ТУТ ПЕРЕВІРКА ВЛАСТИВОСТІ, А НЕ ПІКСЕЛІВ — і це чесно названо.
// Псевдоелемент `::after` не бере участі в hit-test: `elementFromPoint` його не
// повертає взагалі. Дві мої спроби зміряти дірку «як людина бачить» дали спершу
// 136 точок на ВИПРАВЛЕНОМУ коді (міряли клікабельність, не фарбу), а потім 0 і на
// зламаному теж (геометрична перевірка не відрізняла контур від заливки). Тобто
// обидві мірки були тавтологічні. Різницю показало лише порівняння ЗНІМКІВ очима.
// ➡️ Тому сторож тримає ПРИЧИНУ, а не наслідок: підкладка мусить бути залита.
// Це вузько, зате не бреше.
//
// 🔴 08.08, ДРУГА І ТРЕТЯ СКАРГИ ТОГО Ж ДНЯ — сторож розширено.
// Вова після першого виправлення: «видно стик фону язичка з таббаром — це має бути
// одне ціле». Причин виявилось дві, і обидві сюди дописані:
//   (2) заливка обривалась РІВНО на лінії бару, і та лінія різала основу язичка —
//       тому заливка (`::before`) тепер заходить НИЖЧЕ, ніж обідок (`::after`);
//   (3) кнопка кидала власну тінь УНИЗ, тобто просто на білий бар. Заміряно
//       яскравість поперек бару (255 = чисто біле), точки від краю кнопки:
//         ДО:    −30:244 · −25:227 · −20:**208**
//         ПІСЛЯ: −30:253 · −25:251 · −20:**248**
//       Тобто ореол темнив бар на 20px у кожен бік — це і читалось як «стик».
//       Верхня тінь лишається: вона падає на СТОРІНКУ і бару не шкодить.
//
// 🛑 ЧОМУ ЗАМІР РОБИТЬСЯ САМЕ В АКТИВНОМУ СТАНІ — на цьому я вже спіймався.
// Перша редакція сторожа читала стилі «як є» і була зелена, поки заливка НЕ
// МАЛЮВАЛАСЬ ЗОВСІМ на активній «Громаді»: рисочка активної вкладки
// (`.tab-bar .tab-item.active::before`, community.css) перебивала її за вагою
// селектора — три класи проти двох. А «Громада» активна рівно тоді, коли Вова на
// неї дивиться. Тож стан тут ставиться ЯВНО, обидва, і жоден не «за замовчуванням».
const кнопка = await pg.evaluate(() => {
  const item = document.querySelector('.tab-item--home');
  if (!item) return null;
  const бувАктивний = item.classList.contains('active');
  // Знизу `clip-path: inset(0 0 Npx 0)` — беремо третє число, це зріз від низу.
  const зріз = (cs) => parseFloat((cs.clipPath.match(/-?[\d.]+px/g) || [])[2] || 'NaN');
  // Тіні: спершу прибираємо кольорові дужки, тоді ділимо комою — лишаються довжини.
  const зсуви = (тінь) => тінь.replace(/rgba?\([^)]*\)/g, '').split(',')
    .map((s) => s.trim()).filter(Boolean)
    .map((s) => parseFloat(s.split(/\s+/)[1]));   // [1] — зсув по вертикалі
  // ⚠️ `getComputedStyle` повертає ЖИВИЙ обʼєкт — він переобчислюється, щойно
  //    зміниться клас. Тому кожен стан знімаємо в звичайні числа ОДРАЗУ.
  const знімок = () => {
    const заливка = getComputedStyle(item, '::before');
    const обідок  = getComputedStyle(item, '::after');
    const коло    = getComputedStyle(document.querySelector('.tab-home-circle'));
    return {
      фон: заливка.backgroundColor,
      ширина: parseFloat(заливка.width),
      зрізЗаливки: зріз(заливка),
      зрізОбідка: зріз(обідок),
      рамкаОбідка: parseFloat(обідок.borderTopWidth),
      рамкаЗаливки: parseFloat(заливка.borderTopWidth),
      тіні: зсуви(коло.boxShadow),
      колоШирина: parseFloat(коло.width),
    };
  };
  item.classList.add('active');       // ← стан, у якому Вова це й бачить
  const активна = знімок();
  item.classList.remove('active');
  const спокійна = знімок();
  item.classList.toggle('active', бувАктивний);
  return { активна, спокійна };
});
ok('сцена: кругла кнопка «Громада» на місці', !!кнопка);
for (const стан of ['активна', 'спокійна']) {
  const к = кнопка && кнопка[стан];
  if (!к) continue;
  const мітка = стан === 'активна' ? 'АКТИВНА' : 'спокійна';
  ok(`🔴 [${мітка}] підкладка під колом ЗАЛИТА (не порожній контур)`,
     к.фон !== 'rgba(0, 0, 0, 0)' && к.фон !== 'transparent', к.фон);
  // Біла кайма навколо кола лишається — це задум, а не побічний ефект.
  ok(`[${мітка}] підкладка ширша за коло, тож біла кайма видима`,
     к.ширина > к.колоШирина, `${к.ширина}px проти ${к.колоШирина}px`);
  // (2) Заливка мусить накрити лінію бару, обідок — обірватись на ній. Менший зріз
  //     від низу = нижчий край. Якби зрізи зрівняли, лінія бару знову різала б язичок.
  ok(`🔴 [${мітка}] заливка заходить НИЖЧЕ обідка (накриває лінію бару)`,
     к.зрізЗаливки < к.зрізОбідка,
     `заливка ${к.зрізЗаливки}px · обідок ${к.зрізОбідка}px`);
  ok(`[${мітка}] обідок має рамку, а заливка — ні (інакше кайма стане товщою)`,
     к.рамкаОбідка > 0 && к.рамкаЗаливки === 0,
     `обідок ${к.рамкаОбідка}px · заливка ${к.рамкаЗаливки}px`);
  // (3) 🔄 ПЕРЕВІРКУ РОЗВЕРНУТО ТОГО Ж ДНЯ — за рішенням Вови, і це не послаблення.
  // Спершу тут стояло «жодної тіні вниз»: я вирішив, що ореол під кнопкою і є
  // «стик», на який поскаржився Вова, і прибрав нижню тінь. Надвечір Вова:
  // «коли ти лагодив задній язичок, пропав відтінок, який був… він такий
  // світло-бордовий, поверни назад».
  // 🔑 Я був неправий: «стик» робили дві інші причини (лінія бару різала основу
  // язичка; на активній «Громаді» підкладка не малювалась), і обидві полагоджені
  // окремо. Тінь лише підсвічувала ту межу. Коли межі немає — це задумане світло.
  // ➡️ Тепер сторож стежить за ПРИСУТНІСТЮ відтінку: він уже раз зник непомітно,
  //    бо був побічною жертвою іншого фіксу, і саме це має ловитись.
  ok(`🔴 [${мітка}] під кнопкою є світло-бордовий відтінок (тінь униз)`,
     к.тіні.some((y) => y > 0),
     `зсуви по вертикалі: ${к.тіні.join(', ')}`);
  ok(`[${мітка}] верхня тінь теж на місці — вона дає кнопці підйом`,
     к.тіні.some((y) => y < 0), `зсуви: ${к.тіні.join(', ')}`);
}

await browser.close();
done();
