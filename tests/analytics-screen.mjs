//
// 🔑 ЧОМУ ЛОГІКА, А НЕ ЖИВА СЦЕНА. `admin.html` відкриває лише залогінений адмін.
// Підняти сцену означало б підробити сесію адміна і перевіряти власну підробку —
// той самий висновок, що в `admin-reports.mjs`. Тому вирізаємо чисті функції з
