// Вік — питання Вови, на яке екран мусить відповідати сам.
ok('екран пояснює, звідки береться вік', /Google при вході віддає лише пошту/.test(HTML));

// ── 7. ВІКНО ДЕТАЛЕЙ — МОДАЛКА, А НЕ НАКЛАДКА ────────────────────────────
// 🗣️ Вова зі скріна 26.08: «задній фон, він скролиться, і свайпом я не можу закрити цю
//     модалку… заблокуй, щоб задній екран не рухався, це модальне вікно, це неправильно,
//     і зроби так в ВСІХ варіаціях, де я можу тапнути».
// ✅ «Усі варіації» перевіряються самі собою: всі тапи екрана ведуть в ОДНУ `openDetail`.
ok('усі тапи ведуть в одне вікно, а не в кілька копій',
   (HTML.match(/function openDetail\(/g) || []).length === 1);
// 🛑 `overflow: hidden` на body для iOS НЕ ДОСИТЬ — Safari однаково прокручує документ
// під фіксованим шаром. Тому саме `position: fixed` зі зсувом, як у застосунку.
ok('🔴 сторінка під вікном фіксується, а не просто ховає прокрутку',
   /function lockPageScroll/.test(HTML) && /b\.position = 'fixed'/.test(HTML));
ok('позиція сторінки повертається після закриття', /window\.scrollTo\(0, scrollY\)/.test(HTML));
ok('замок ставиться рівно раз на відкриття, а не на кожне оновлення вмісту',
   /if \(!m\.classList\.contains\('open'\)\)[\s\S]{0,120}_detailUnlock = lockPageScroll\(\)/.test(HTML));
ok('🔴 свайп вниз закриває', /function attachDetailSwipe/.test(HTML)
   && /touchstart/.test(HTML) && /touchmove/.test(HTML) && /touchend/.test(HTML));
// 🛑 Замок на жест: рух, який хоч раз БУВ прокруткою, до відпускання пальця вже не може
// стати закриттям. Без нього шапка відривалась від тіла аркуша на iOS.
ok('🔴 жест, що почався як прокрутка, не перехоплюється в закриття',
   /wasScrolling/.test(HTML));
// Граб за шапку закриває навіть із прокрученого списку — інакше з довгого журналу
// випадків не вийти, не догорнувши його вгору.
ok('за шапку можна тягнути навіть коли список прокручено', /inHeader/.test(HTML));
ok('пороги ті самі, що в застосунку (90px і 0.45 px/мс)',
   /SHEET_DIST = 90/.test(HTML) && /SHEET_FLICK = 0\.45/.test(HTML));
ok('крива руху спільна із застосунком',
   /cubic-bezier\(0\.32, 0\.72, 0, 1\)/.test(HTML));
ok('є і кнопка, і тап по тлу, і Escape — адмінку відкривають і з компʼютера',
   /an-detail-close/.test(HTML) && /e\.target === m/.test(HTML) && /'Escape'/.test(HTML));
ok('рисочка-грабер на місці — інакше про свайп ніхто не здогадається',
   /an-detail-grip/.test(HTML));

// ── 8. AI-ВИСНОВОК ЧИТАЄ ТІ САМІ ЧИСЛА, ЩО ЕКРАН ─────────────────────────
// 🔴 Edge Function рахувала агрегати САМА і тим самим способом, який визнали хибним:
// сирі події з `limit(20000)` проти серверної стелі 1000. AI впевнено коментував
// неправду. Це найгірший вид вади — невидимий.
const FN = читати('supabase/functions/ai-analytics-summary/index.ts');
// ⚠️ Міряємо КОД, а не коментарі: у шапці функції старий виклик наведено ДОСЛІВНО як
// опис вади. Перевірка «немає рядка limit(20000) у файлі» червоніла б саме на поясненні,
// чому його прибрали, — тобто карала б за документування помилки.
const FN_КОД = FN.split('\n').filter(l => !l.trim().startsWith('//')).join('\n');
ok('🔴 AI більше НЕ рахує сирі події сам',
   !/limit\(20000\)/.test(FN_КОД) && !/from\('analytics_events'\)/.test(FN_КОД));
ok('🔴 AI бере ті самі агрегати, що екран', /admin_analytics_overview/.test(FN));
ok('AI бачить і збої, і анкети', /admin_failures/.test(FN) && /admin_profile_stats/.test(FN));
ok('AI бачить три періоди, а не один', /'today'/.test(FN) && /'7d'/.test(FN) && /'30d'/.test(FN));
// 🛑 Гейт `is_admin()` читає пошту з JWT — під service_role його немає взагалі.
ok('RPC кличеться від імені викликача, інакше гейт бази віддав би «not admin»',
   /Authorization: authHeader/.test(FN));
// 🔑 Правило №12 проєкту всередині завдання моделі: на 11 акаунтах висновки про
// «аудиторію» були б вигадкою, і саме їх Вова просив не робити.
ok('🔴 у завданні моделі прямо сказано, що запуску ще не було',
   /ЗАПУСКУ ЩЕ НЕ БУЛО/.test(FN));
ok('модель попереджена не плутати людей, гостей і заходи',
   /гості.{0,80}ПРИСТРО/s.test(FN));
ok('відсутній ключ пояснюється інструкцією, а не мовчанням',
   /Project Settings → Edge Functions/.test(FN));
// 🔴 Перший живий натиск Вови дав «AI не повернув відповідь» ПРИ ВІДПОВІДІ 200: ключ на
// місці, Anthropic відповів успішно, а текст на екран не доїхав. Причина — `content` це
// МАСИВ БЛОКІВ РІЗНОГО ТИПУ, і текстовий у ньому не обовʼязково перший.
ok('🔴 текст береться з УСІХ текстових блоків, а не з `content[0]`',
   !/content\?\.\[0\]\?\.text/.test(FN_КОД) && /b\.type === 'text'/.test(FN_КОД));
// 🛑 Порожня відповідь має бути ДІАГНОЗОМ, а не глухим кутом: без причини зупинки і
// переліку блоків наступний крок був би здогадом. Той самий клас, що з журналом збоїв —
// «нічого не сталось» і «сталось, але ми не побачили» виглядали однаково.
ok('порожня відповідь називає причину зупинки і типи блоків',
   /stop_reason/.test(FN_КОД) && /Блоки:/.test(FN));
// 🗣️ Вова про першу робочу відповідь: «чому все не влазить? треба все бачити мені».
// Вона обірвалась на «• Роз» — модель уперлась у стелю довжини.
// 🛑 Мовчки віддавати обрубок не можна: недописаний текст виглядає точно як дописаний.
// «Неповно» і «повно» мусять бути РІЗНІ екрани — той самий клас, що з `content[0]`.
ok('🔴 обрізана відповідь позначається обрізаною',
   /stop_reason === 'max_tokens'/.test(FN_КОД) && /обірвалась/.test(FN));
ok('стеля довжини з запасом (не ріже посеред слова)',
   Number((FN.match(/max_tokens: (\d+)/) || [, 0])[1]) >= 8000);

// ── 9. ЖУРНАЛ AI-ВИСНОВКІВ ────────────────────────────────────────────────
// 🗣️ Вова: «заблокував телефон, він зʼявився, і я розблокував, оновив його — і він
//     відразу пропав… зроби, щоб була якась база зберігання цих аудитів».
// 🔴 Висновок жив лише в пам'яті відкритої сторінки, а кожен виклик КОШТУЄ ГРОШЕЙ:
// випадковий дотик до екрана спалював гроші й забирав уже куплений текст.
const MIG = читати('scripts/supabase_ai_reports.sql');
ok('міграція журналу існує', /create table if not exists public\.analytics_ai_reports/.test(MIG));
ok('🔴 екран показує останній збережений висновок одразу',
   /fetchAiReports/.test(HTML) && /analytics_ai_reports/.test(HTML));
ok('сервер пише висновок у журнал', /analytics_ai_reports'\)\.insert/.test(FN));
// 🔑 Знімок вхідних чисел — головна колонка журналу: без нього через тиждень висновок
// неможливо ні перевірити, ні зрозуміти, бо екран уже показує інші числа.
ok('🔴 разом із текстом зберігається ЗНІМОК чисел, на яких він зроблений',
   /snapshot: дані/.test(FN) && /snapshot\s+jsonb/.test(MIG));
// 🛑 Журнал, у який можна дописати руками, не варто вести взагалі.
ok('🔴 політики INSERT для залогінених у журналі НЕМАЄ',
   !/for insert/i.test(MIG) && /for select to authenticated using \(is_admin\(\)\)/.test(MIG));
ok('журнал читає лише адмін', /enable row level security/.test(MIG));
// ⚠️ «Збережено» — обіцянка. Збрехавши тут, ми відправимо людину по текст, якого немає,
// і вона заплатить за нього вдруге.
ok('🔴 «збережено» пишеться лише коли сервер це підтвердив',
   /data\.saved/.test(HTML) && /зберегти не вдалось/.test(HTML));
ok('збій запису не ламає відповідь — текст однаково показується',
   /saved = !insErr/.test(FN) && /catch/.test(FN));
ok('попередні висновки відкриваються в ТОМУ САМОМУ вікні',
   /ai-past/.test(HTML) && /openDetail\(`AI-висновок від/.test(HTML));

done();
