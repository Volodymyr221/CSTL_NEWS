// tests/analytics-screen.mjs — ЕКРАН АНАЛІТИКИ В АДМІНЦІ.
//
// 🔴 ЗАРАДИ ЧОГО. Розділ «Аналітика» жив без жодного стенда, і всі його вади
// знаходив Вова очима: «Унікальних сьогодні 81 / 526 подій — що це означає, я не
// розумію», «час доби — повна каша, 23 — що це, хвилини?», «третій рядок у
// пристроях — що це таке?». Кожна з них була вадою РЕНДЕРА при правильних даних,
// тобто рівно тим класом, який стенд і мусить ловити.
//
// 🔑 ЧОМУ ЛОГІКА, А НЕ ЖИВА СЦЕНА. `admin.html` відкриває лише залогінений адмін.
// Підняти сцену означало б підробити сесію адміна і перевіряти власну підробку —
// той самий висновок, що в `admin-reports.mjs`. Тому вирізаємо чисті функції з
// файлу і виконуємо їх на вигаданих даних: це перевірка поведінки, а не наявності
// рядка в коді.
//
// ⚠️ МЕЖА, ЯКУ ТРЕБА ЗНАТИ: слухачі кліків і справжню верстку цей стенд НЕ
// виконує. Він каже «розмітка вийде правильна», а не «тап справді відкриває
// вікно». Названо чесно, щоб наступна сесія не думала, що розділ покрито цілком.

import { projectFile, reporter } from './_lib.mjs';

const { ok, done } = reporter();
// 🔑 КОНТРОЛЬНИЙ ПРОГІН: `BUNDLE_REV=origin/main node tests/analytics-screen.mjs` бере
// файли з іншої редакції. Стенд, який не вміє почервоніти на старому коді, доводить
// лише те, що він запускається.
const REV = process.env.BUNDLE_REV || '';
const читати = (шлях) => { try { return projectFile(шлях, REV); } catch { return ''; } };
const HTML = читати('admin.html');
const SQL = читати('scripts/supabase_analytics_drilldown.sql');

// Вирізаємо функцію від оголошення до першого `}` на нульовому відступі.
function вирізати(назва) {
  const i = HTML.indexOf(`function ${назва}(`);
  if (i < 0) return null;
  const хвіст = HTML.slice(i);
  const кінець = хвіст.indexOf('\n}\n');
  return кінець < 0 ? null : хвіст.slice(0, кінець + 2);
}

const назви = ['escapeHtml', 'hourRows', 'tapRows', 'peopleHtml', 'failureRows'];
const шматки = назви.map(вирізати);
ok('усі чотири функції рендера знайшлись у admin.html',
   шматки.every(Boolean), назви.filter((_, i) => !шматки[i]).join(','));

// 🛑 НЕ ДАЄМО СТЕНДУ ВПАСТИ ЗАМІСТЬ ПОЧЕРВОНІТИ. На контрольному прогоні половини
// функцій просто не існує, і `new Function` кинув би виняток — тобто прогін помер би
// із кодом «крешнув», а не «перевірки не пройдено». Цю саму помилку в цьому проєкті
// вже робили: обірваний прогін виглядав як успішний.
let рендер = null;
if (шматки.every(Boolean)) {
  try {
    рендер = new Function(`${шматки.join('\n')}\nreturn { ${назви.join(', ')} };`)();
  } catch (e) { ok('вирізані функції виконуються', false, e.message); }
}
const заглушка = () => '';
const { escapeHtml, hourRows, tapRows, peopleHtml, failureRows } = рендер || {
  escapeHtml: заглушка, hourRows: заглушка, tapRows: заглушка,
  peopleHtml: заглушка, failureRows: заглушка,
};

// ── 1. ЧАС ДОБИ — ВІСЬ, А НЕ РЕЙТИНГ ──────────────────────────────────────
// 🗣️ Вова: «чого воно не від 0:00 і до 23:00… чого воно знову розкидано?»
// 🛑 Дані навмисно подані РОЗКИДАНО і неповно — саме так їх і віддає база
// (`jsonb_object_agg` порядку не гарантує, а порожні години просто відсутні).
const години = hourRows({ 23: 190, 17: 91, 20: 89, 0: 77, 9: 12 });
const підписи = [...години.matchAll(/(\d\d):00/g)].map(m => m[1]);
ok('усі 24 години намальовані', підписи.length === 24, `їх ${підписи.length}`);
ok('години йдуть підряд 00 → 23',
   підписи.join(',') === Array.from({ length: 24 }, (_, i) => String(i).padStart(2, '0')).join(','),
   підписи.join(','));
ok('порожня година лишається на екрані, а не зникає', підписи.includes('04'));
ok('година з нулем притлумлена, а не прихована', /opacity:\.45/.test(години));
// Контроль: якби рендер сортував за кількістю (як `barRows`), перша була б 23.
ok('🔴 КОНТРОЛЬ: перша година НЕ найбільша', підписи[0] === '00', підписи[0]);
ok('порожній зріз каже «немає даних», а не малює 24 нулі',
   /немає даних/.test(hourRows({})));

// ── 2. КОЖЕН РЯДОК НЕСЕ АДРЕСУ ПИТАННЯ «ХТО САМЕ» ─────────────────────────
// 🗣️ «по вкладках… треба тап → хто заходив, скільки разів, за який період».
const рядки = tapRows('tab', [
  { key: 'shotam', label: 'Стрічка', value: 315, sub: '5 людей' },
  { key: 'не вказано', label: 'не вказано', value: 12, sub: '' },
  { key: 'з "лапками"', label: 'з "лапками"', value: 3, sub: '' },
]);
ok('кожен рядок клікабельний', (рядки.match(/class="spend-row an-tap"/g) || []).length === 3);
ok('scope і ключ стоять на рядку', /data-scope="tab" data-key="shotam"/.test(рядки));
ok('ключ із пробілом не ламає розмітку', /data-key="не вказано"/.test(рядки));
// 🛑 Ключ приходить із бази і може містити що завгодно. Неекранована лапка
// закрила б атрибут і зробила б решту рядка розміткою.
ok('🔴 ключ із лапками екранується', /data-key="з &quot;лапками&quot;"/.test(рядки));
ok('порожній список каже «немає даних»', /немає даних/.test(tapRows('tab', [])));

// ── 3. ЛЮДИ — З ІМЕНЕМ І ПОШТОЮ, ГОСТІ — ЧИСЛОМ ───────────────────────────
// 🗣️ «щоб було видно, хто саме заходив»; про збої — «який користувач, його email».
const хто = peopleHtml({
  users: 2, events: 500, guests: 340, guest_events: 711, visits: 17,
  people: [
    { uid: 'a', name: 'Іван Петренко', email: 'ivan@example.com', settlement: 'Метельне',
      events: 400, visits: 9, days: 4, last_at: '2026-08-26T09:00:00Z' },
    { uid: 'b', name: 'без імені', email: null, settlement: 'не вказано',
      events: 100, visits: 2, days: 1, last_at: '2026-08-25T09:00:00Z' },
  ],
});
ok('імʼя людини видно', /Іван Петренко/.test(хто));
ok('пошта видно', /ivan@example\.com/.test(хто));
ok('село видно', /Метельне/.test(хто));
ok('заходи й дні підписані окремо від подій', /заходів:.*<b>9<\/b>/s.test(хто) && /днів:.*<b>4<\/b>/s.test(хто));
ok('відсутня пошта не малює «null»', !/null/.test(хто) && /пошти немає/.test(хто));
// 🛑 Гості — не люди. Рядка їм не дають, але й мовчки не викидають.
ok('гості названі числом і словом «гостьових»', /340<\/b> гостьових/.test(хто));
const безЛюдей = peopleHtml({ users: 0, events: 9, guests: 3, guest_events: 9, visits: 1, people: [] });
ok('зріз без жодного акаунта пояснює себе, а не мовчить',
   /Жодного акаунта/.test(безЛюдей) && /запуску ще не було/i.test(безЛюдей));
ok('збій отримання даних не малюється як «нуль людей»',
   /Не вдалося отримати дані/.test(peopleHtml(null)));

// ── 4. ЗБОЇ ───────────────────────────────────────────────────────────────
// 🗣️ «якщо збоїв немає — так і писати; якщо є — тап відкриває деталі».
const порожньо = failureRows({ groups: [] });
ok('без збоїв екран каже це прямо', /Збоїв немає/.test(порожньо));
ok('🔴 порожній журнал НЕ видає себе за доказ справності',
   /Порожньо ≠ все справно/.test(порожньо));
ok('без збоїв кнопки копіювання немає', !/copy-failures/.test(порожньо));
const зізбоями = failureRows({ groups: [{
  kind: 'db_refusal', code: 'PGRST303', message: 'JWT issued at future "now"',
  where: '', count: 13, guests: 2, accounts_n: 0, accounts: [],
  first_at: '2026-08-24T11:00:00Z', last_at: '2026-08-26T09:41:00Z',
}] });
ok('рядок збою клікабельний', /class="spend-row fail-tap"/.test(зізбоями));
ok('на рядку є код і текст для звуження випадків',
   /data-code="PGRST303"/.test(зізбоями) && /data-msg="JWT issued at future &quot;now&quot;"/.test(зізбоями));
ok('кнопка копіювання на місці', /id="copy-failures"/.test(зізбоями));

// ── 5. UI І БАЗА НЕ РОЗІЙШЛИСЬ ────────────────────────────────────────────
// 🔑 Найдешевша перевірка з усіх і водночас та, якої бракувало найбільше: екран
// читає поля, яких у міграції може не бути — і тоді малює порожньо, ЯК ЯКБИ
// даних не було. Саме так виглядала б наступна тиха вада.
for (const поле of ['by_app_mode', 'by_browser', 'by_settlement', 'modes_since',
                    'sessions_per_user', 'by_hour', 'by_tab', 'by_device']) {
  ok(`поле «${поле}» є і в міграції, і на екрані`,
     SQL.includes(`'${поле}'`) && HTML.includes(поле));
}
for (const rpc of ['admin_analytics_overview', 'admin_analytics_people', 'admin_failure_cases']) {
  ok(`RPC «${rpc}» оголошено в міграції і викликається з адмінки`,
     SQL.includes(`function public.${rpc}`) && HTML.includes(`'${rpc}'`));
}

// ── 6. ПАСТКИ, НА ЯКИХ ЦЕЙ ЕКРАН УЖЕ ЛОВИВСЯ ──────────────────────────────
// 🛑 Делегат живе на контейнері, а контейнер перемальовку переживає: без
// прапорця другий вибір періоду відкривав би вікно двічі.
ok('🔴 делегат кліків прив’язується рівно один раз', /dataset\.anBound/.test(HTML));
// 🛑 Один період на весь екран — інакше повертається питання «81 це за що?».
ok('період керує всім екраном однією змінною', /let anPeriod = /.test(HTML));
// ⚠️ Перевіряємо ЗНАЧЕННЯ, а не розмітку: кнопки збираються шаблоном
// (`data-period="${k}"`), тож шукати літеральний атрибут у файлі безглуздо.
// 🔑 Заразом це стереже головне: ключі періодів на екрані мусять бути рівно ті,
// які розуміє `case p_period` у базі. Розбіжність тут дала б мовчазний «весь час»
// замість обраного періоду — тобто знову неправдиве число без жодної помилки.
const періоди = (HTML.match(/const PERIOD_UK = \{([^}]*)\}/) || [, ''])[1];
for (const к of ['today', "'7d'", "'30d'"]) {
  ok(`період ${к} є на екрані`, періоди.includes(к.replace(/'/g, '')) || періоди.includes(к));
}
for (const к of ['today', '7d', '30d']) {
  ok(`період «${к}» розуміє і база`, new RegExp(`when '${к}'`).test(SQL));
}
// 🛑 Мертвий клієнтський підрахунок ніс у собі стелю 1000 — саме ту, через яку
// екран показував «35 унікальних» замість 736.
const CORE = читати('src/core/supabase.js');
ok('🔴 клієнтського підрахунку подій більше немає',
   !/export async function fetchAnalyticsSummary/.test(CORE));
// 🛑 Захід писався «гостем», бо `currentUserId()` ще не знала відповіді.
const APP = читати('src/app.js');
ok('🔴 захід пишеться лише після відповіді «хто я»',
   /await authReady\(\);[\s\S]{0,400}?'session_start'/.test(APP));
// Вік — питання Вови, на яке екран мусить відповідати сам.
ok('екран пояснює, звідки береться вік', /Google при вході віддає лише пошту/.test(HTML));

done();
