// tests/account-scope.mjs — ЩО НАЛЕЖИТЬ АКАУНТУ, А ЩО ПРИСТРОЮ.
//
// 🔴 НАВІЩО (замовлення Вови 24.08). Слово власника дослівно: «все персональне…
// має зберігатись в акаунті, а не на пристрої, якщо користувач виходить, він
// може тільки переглядати публічну інформацію, а не взаємодіяти в рамках
// додатку». Привід — реальний випадок: Вова вийшов з акаунта «Олександр»,
// зайшов як «Володимир», а push прилетів на попередній акаунт.
//
// 🔑 ЩО САМЕ МІРЯЄМО — ЩО БАЧИТЬ ДРУГА ЛЮДИНА, а не де лежить ключ.
// Перевіряти «чи є uid у назві ключа» означало б міряти ФОРМУ ЗАПИСУ — рівно та
// вада, за яку проєкт уже платив 27.07. Тому сцена завжди однакова: акаунт А
// щось зберігає СВОЇМИ руками через інтерфейс → на тому самому пристрої
// відкривається акаунт Б → дивимось, що Б бачить на екрані «Збережені».
//
// 🛑 КОНТРОЛЬ ТУТ НЕ ПРИКРАСА, А УМОВА ОСМИСЛЕНОСТІ. Перевірка «Б бачить чуже»
// була б червоною і на цілком справному застосунку, якби сцена просто не вміла
// перемикати акаунт. Тому в тій самій сцені їдуть ДВІ сутності:
//   • збережені СТАТТІ — лежать у `localStorage` без прив'язки до людини;
//   • збережені ОГОЛОШЕННЯ — лежать у базі в таблиці `saved_posts` з `uid`.
// Обидві людина зберігає тим самим жестом і бачить в одному аркуші. Якщо стенд
// показує витік в обох — він міряє власне невміння перемкнути акаунт, і падає.
// Правильний результат: статті ПРОТІКАЮТЬ, оголошення НІ.
//
// ⚠️ Межа стенда, названа чесно: він НЕ перевіряє push-пристрої
// (`user_push_devices`) — це стан БАЗИ, і браузер про нього нічого не знає.
// Той бік доведено окремо, запитом до живої бази (див. журнал 24.08).

import { chromium } from 'playwright';
import { launch, serve, reporter } from './_lib.mjs';
import { mockSupabase } from './_board-fixture.mjs';

const { ok, done } = reporter();

const ts = Date.now() - 2 * 864e5;
const ARTICLES = [
  { id: 5001, title: 'СТАТТЯ ПРО ДОРОГУ', excerpt: 'Опис.', content: 'Текст статті.',
    category: 'Суспільство', geo: 'Олика', image: null, source: 'CSTL NEWS',
    sourceUrl: null, exclusive: true, ts },
];
const POSTS = [
  { id: 7001, type: 'board', category: 'продам', title: 'ОГОЛОШЕННЯ ПРО ПІЧ',
    text: 'Опис оголошення.', photos: [], price: null, price_negotiable: true,
    currency: 'UAH', location: 'Олика', author: 'Хтось', author_name: 'Хтось',
    owner_uid: 'u-inshyi', status: 'published', ts,
    created_at: new Date(ts).toISOString(), bumped_at: new Date(ts).toISOString() },
];

const USER_A = { id: 'uid-a', email: 'a@example.com', user_metadata: { full_name: 'Олександр' } };
const USER_B = { id: 'uid-b', email: 'b@example.com', user_metadata: { full_name: 'Володимир' } };

const { url, stop } = await serve();
const b = await launch(chromium);
// ⚠️ ОДИН контекст на весь стенд — і це головна умова сцени: `localStorage`
// живе саме в ньому, тобто «той самий телефон». Другий контекст був би другим
// пристроєм, і жодного витоку ми б не побачили за визначенням.
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true,
                                hasTouch: true, serviceWorkers: 'block' });

const json = (r, body) => r.fulfill({ status: 200, contentType: 'application/json',
  headers: { 'access-control-allow-origin': '*' }, body: JSON.stringify(body) });

/**
 * Відкриває застосунок ЯК ВКАЗАНА ЛЮДИНА на тому самому пристрої.
 * `saved` — рядки таблиці `saved_posts`, тобто те, що база вважає збереженим
 * ЦИМ акаунтом. Саме вона й тримає прив'язку, якої немає у статей.
 */
async function відкрити(user, saved = []) {
  const p = await ctx.newPage();
  await mockSupabase(p, { posts: POSTS, saved_posts: saved, profiles: [] }, { user });
  await p.route('**://api.open-meteo.com/**', r => r.abort());
  await p.route('**/data/articles.json*', r => json(r, ARTICLES));
  await p.goto(url, { waitUntil: 'domcontentloaded' });
  await p.waitForTimeout(2200);
  await p.evaluate(() => document.querySelector('.consent-accept')?.click());
  await p.waitForTimeout(300);
  return p;
}

/**
 * Відкрити аркуш «Збережені» і зчитати, ЩО В НЬОМУ НАПИСАНО.
 *
 * 🔴 ЦЯ ФУНКЦІЯ ПЕРЕПИСАНА ПІСЛЯ ВЛАСНОГО ХИБНОГО ВИМІРУ (24.08). Перша
 * редакція читала текст аркуша ОДРАЗУ після відкриття — а аркуш показує спершу
 * екран КАТЕГОРІЙ («Статті 1 ›»), і назв усередині там немає. Через це пошук
 * заголовка не знаходив нічого НІ В КОГО, і перевірки «витоку немає» світились
 * зеленим над справжнім витоком.
 * 🔑 Спіймала це перевірка «акаунт А бачить СВОЮ статтю»: вона зобовʼязана бути
 * зеленою, і саме її червоний колір показав, що міряють не те. Без неї стенд
 * звітував би «все чисто» і закрив би розслідування.
 * ⚠️ Тому тепер обовʼязково ЗАХОДИМО В КАТЕГОРІЮ — туди, де людина справді
 * бачить назви. Лічильник на першому екрані повертаємо окремо: він сам по собі
 * вже є витоком («Статті 1» у того, хто не зберігав нічого).
 */
async function збережене(p) {
  await p.evaluate(() => document.getElementById('saved-hub-btn')?.click());
  await p.waitForTimeout(1200);
  const відкрився = await p.evaluate(() => !!document.querySelector('.shub-sheet'));
  if (!відкрився) return { відкрився: false, категорії: '', текст: '' };

  const категорії = await p.evaluate(() =>
    document.querySelector('.shub-sheet')?.textContent.replace(/\s+/g, ' ').trim() || '');

  // Заходимо в «Статті» — екран, де людина бачить самі назви.
  const зайшли = await p.evaluate(() => {
    const row = document.querySelector('[data-shub-cat="articles"]');
    if (!row) return false;
    row.click();
    return true;
  });
  await p.waitForTimeout(700);
  const текст = зайшли
    ? await p.evaluate(() =>
        document.querySelector('.shub-sheet')?.textContent.replace(/\s+/g, ' ').trim() || '')
    : '';
  return { відкрився, категорії, текст };
}

// ── СЦЕНА 1. Акаунт А зберігає статтю І оголошення власними руками ──────────
// 🔑 Оголошення підкладаємо в базу під `uid` акаунта А — рівно так, як його туди
// поклав би сам застосунок. Це друга половина контролю: у А воно є, у Б немає.
const pa = await відкрити(USER_A, [{ uid: USER_A.id, post_id: 7001 }]);

// Стаття: відкриваємо картку новини і тиснемо закладку в шапці модалки.
await pa.evaluate(() => window.switchTab && window.switchTab('community'));
await pa.waitForTimeout(1200);
const відкрилась = await pa.evaluate(() => {
  const card = document.querySelector('[data-article-id]');
  if (!card) return false;
  card.click();
  return true;
});
await pa.waitForTimeout(700);
ok('картка новини відкрилась', відкрилась);

const збереглась = await pa.evaluate(() => {
  const btn = document.getElementById('modal-save-btn');
  if (!btn || btn.hidden) return null;
  btn.click();
  return btn.classList.contains('modal-icon-btn--active');
});
ok('акаунт А зберіг статтю (кнопка стала активною)', збереглась === true, String(збереглась));

const післяА = await збережене(pa);
ok('акаунт А бачить свою статтю у «Збережених»',
   післяА.відкрився && післяА.текст.includes('ДОРОГУ'), післяА.текст.slice(0, 120));

// 🔑 Сховище пристрою міряємо ОДИН раз — як ДРУГИЙ, незалежний доказ. Головні
// перевірки нижче дивляться на екран (що бачить людина), а ця — на те, чи
// лишився взагалі слід, з якого витік був можливий.
const ключі = await pa.evaluate(() => Object.keys(localStorage).sort());

// Після переїзду в базу локального ключа бути НЕ повинно: доки він лежить,
// наступний акаунт на цьому телефоні успадкував би його разом із закладками.
ok('🔴 закладок статей більше НЕМАЄ у сховищі пристрою',
   !ключі.includes('cstl_saved_articles'),
   ключі.includes('cstl_saved_articles')
     ? 'ключ лишився — витік просто чекає наступного входу'
     : ключі.join(' · '));

// Мітки «що я вже бачив» лишаються на пристрої свідомо (див. пояснення в
// `core/board-shared.js`), але кожна мусить назвати СВОГО власника.
const мітки = ключі.filter(k => /_seen_ts|chat-seen/.test(k));
ok('🔴 усі мітки «бачив» названі на акаунт',
   мітки.length > 0 && мітки.every(k => k.endsWith(':uid-a')),
   мітки.join(' · ') || 'жодної мітки не знайдено');

await pa.close();

// ── СЦЕНА 2. ТОЙ САМИЙ ПРИСТРІЙ, ІНША ЛЮДИНА ────────────────────────────────
// 🔑 `saved_posts` для Б порожній — база знає, що Б нічого не зберігав.
// Якби застосунок тримав статті так само в базі, аркуш Б був би порожній теж.
const pb = await відкрити(USER_B, []);
const післяБ = await збережене(pb);

ok('аркуш «Збережені» відкрився в акаунта Б', післяБ.відкрився, післяБ.текст.slice(0, 80));

// 🔴 ГОЛОВНА ПЕРЕВІРКА. Червона = витік, і це рівно те, на що скаржився Вова.
ok('🔴 акаунт Б НЕ бачить статтю, збережену акаунтом А',
   !післяБ.текст.includes('ДОРОГУ'),
   післяБ.текст.includes('ДОРОГУ')
     ? 'ВИТІК: стаття акаунта А видна акаунту Б на тому самому пристрої'
     : 'чисто');

// 🛑 КОНТРОЛЬ. Оголошення зберігаються в базу з `uid`, тож тут витоку бути НЕ
// може. Якщо ця перевірка теж червона — стенд не перемкнув акаунт, і всі його
// висновки нічого не варті.
// ⚠️ Міряємо по ЕКРАНУ КАТЕГОРІЙ: у А оголошення в базі є, у Б немає, тож у Б
// рядка «Оголошення» не має бути взагалі (порожня категорія не малюється).
ok('🛑 КОНТРОЛЬ: оголошення (база, з uid) до акаунта Б НЕ протекло',
   післяА.категорії.includes('Оголошення') && !післяБ.категорії.includes('Оголошення'),
   `А: ${післяА.категорії.slice(0, 60)} | Б: ${післяБ.категорії.slice(0, 60)}`);

await pb.close();

// ── СЦЕНА 3. ВИЙШОВ ЗОВСІМ — ЩО ЛИШИЛОСЬ ГОСТЮ ──────────────────────────────
// Слово Вови: гість «може тільки переглядати публічну інформацію, а не
// взаємодіяти в рамках додатку». Збережене чужою людиною — не публічна
// інформація.
const pg = await відкрити(null, []);
const гість = await збережене(pg);

ok('🔴 гість НЕ бачить збереженого попереднім акаунтом',
   !гість.текст.includes('ДОРОГУ'),
   гість.текст.includes('ДОРОГУ')
     ? 'ВИТІК: аркуш відкрився гостю і показав чуже збережене'
     : 'чисто');

// ⚠️ Окремо про сам аркуш: у `sidebar.js` ДВІЧІ написано, що «openSavedHub має
// власну перевірку» входу. Міряємо, чи вона є насправді, — коментар, який
// стверджує неіснуючий запобіжник, знімає обережність із того місця, де її
// найбільше треба (той самий урок, що сторожі `kb-guard.test.js`, яких ніколи
// не існувало, а документація на них посилалась).
ok('гейт входу на аркуші «Збережені» справді існує', !гість.відкрився,
   гість.відкрився ? 'аркуш відкрився гостю без жодної перевірки' : 'не відкрився');

await pg.close();

await ctx.close();
await b.close();
stop();
done();
