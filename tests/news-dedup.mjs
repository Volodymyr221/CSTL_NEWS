// РЕТРО-ПРОХІД (03.09): правило діє й на ВЖЕ ЗБЕРЕЖЕНУ стрічку
//
// 🔬 ЗАРАДИ ЧОГО. Вова прислав знімок із двома статтями про ту саму ДТП. Розбір
// показав, що вони СТАРШІ за саме правило: у стрічку потрапили 01.09 о 08:47,
// а `is_dup_article` приїхав у `main` о 13:26 — на 4 год 39 хв пізніше. Тобто
// правило працювало, але лише на нові статті; вже збережені ніхто не переглядав.
//
// 🛑 ЦЕЙ БЛОК ЗАПУСКАЄ СПРАВЖНІЙ PYTHON, а не повторює логіку втретє. Вище в
// цьому ж файлі логіка вже продубльована навмисно (щоб розходження було видно
// по числах) — але поведінку ВИДАЛЕННЯ так перевіряти не можна: тут ціна
// помилки не «розійшлись числа», а «зникла справжня новина».
function ретро(статті, env = {}) {
  const код = `
import json, sys, types
sys.path.insert(0, 'scripts')
# KOMPILE-FROM-SOURCE (03.09): importlib may serve a stale __pycache__ entry.
# Measured that day: a control run changed RETRO_MAX_SHARE 0.03 -> 1.00 — strings
# of EQUAL length, so the file size did not change and Python returned the OLD
# bytecode. The stand showed green for code that no longer existed.
# A guard must measure the source of truth; compile() has no cache at all.
_src = open('scripts/parse_rss.py', encoding='utf-8').read()
m = types.ModuleType('pr'); m.__file__ = 'scripts/parse_rss.py'
exec(compile(_src, 'scripts/parse_rss.py', 'exec'), m.__dict__)
d = json.loads(sys.stdin.read())
n = m.retro_dedup(d)
print('---РЕЗУЛЬТАТ---')
print(json.dumps({'прибрано': n, 'лишились': [a['title'] for a in d]}, ensure_ascii=False))`;
  const вивід = execFileSync('python3', ['-c', код], {
    cwd: ROOT, encoding: 'utf-8', input: JSON.stringify(статті),
    env: { ...process.env, ...env },
  });
  return JSON.parse(вивід.split('---РЕЗУЛЬТАТ---')[1].trim());
}

