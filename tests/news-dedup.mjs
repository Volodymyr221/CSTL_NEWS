// Стенд: ДЕДУПЛІКАЦІЯ НОВИН (B-22) — та сама подія під різними заголовками.
//
// 🗣️ Скарга Вови (01.09): «одна й та сама новина, тільки з різними заголовками
// і від різних джерел… Вона не має дублюватися, в загальному, не тільки в
// цьому випадку».
//
// 🔬 ВИПАДОК, ЯКИЙ ЦЕ ЗАВІВ — дві статті про ту саму ДТП, різниця ДВІ ХВИЛИНИ:
//   «На Волині в аварію потрапив шкільний автобус: у салоні перебувало 18 людей»
//   «Біля Берестечка шкільний автобус зіткнувся з авто «Укрпошти»…»
// Спільних слів у заголовках два, Jaccard 0.14 — старий поріг 0.65 не бачить.
//
// 🛑 ГОЛОВНЕ, ЩО СТЕРЕЖЕ ЦЕЙ СТЕНД, — НЕ «ЧИ ЛОВИТЬ», А «ЧИ НЕ ЗЛИПАЄ ЗАЙВЕ».
// Ціна помилки несиметрична: пропущений дубль це косметика, а хибне склеювання
// ХОВАЄ СПРАВЖНЮ НОВИНУ, і людина про подію просто не дізнається. Тому стенд
// проганяє правило по ВСЬОМУ живому корпусу `data/articles.json` і падає,
// щойно спрацювань стане більше за перевірену межу.
//
// ⚠️ Стенд НЕ запускає браузер: дедуп живе в парсері (Python), а тут ми міряємо
// саме правило на реальних даних. Логіка продубльована навмисно — якщо котрась
// із копій розійдеться, числа розійдуться теж, і це стане видно.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, reporter } from './_lib.mjs';

const { ok, done } = reporter();
const статті = JSON.parse(readFileSync(join(ROOT, 'data/articles.json'), 'utf8'));

// ── Ті самі числа, що в `scripts/parse_rss.py` ──────────────────────────────
const W_STRONG = 0.80, W_FRESH = 0.70, FRESH_MIN = 30, WINDOW_H = 6;
const СТОП = new Set(('про що для але його її їх цей ця це той та і в у на з із зі до по за від ' +
  'над під при або чи як так теж вже ще бо щоб якщо коли де хто там тут ми ви вони він вона ' +
  'воно я ти не ні також після перед між через без').split(' '));

const текст = a => `${a.title || ''} ${String(a.content || a.excerpt || '').replace(/<[^>]+>/g, ' ')}`
  .slice(0, 900).toLowerCase();
const токени = a => new Set((текст(a).match(/[а-яіїєґa-z0-9]{4,}/g) || [])
  .filter(w => !СТОП.has(w)).map(w => w.slice(0, 6)));

const пул = статті.filter(a => a.geo && a.ts);
const T = new Map(пул.map(a => [a, токени(a)]));
const DF = new Map();
for (const a of пул) for (const t of T.get(a)) DF.set(t, (DF.get(t) || 0) + 1);
const N = пул.length;
const idf = t => Math.log(Math.max(N, 2) / (1 + (DF.get(t) || 0)));
const вага = s => [...s].reduce((n, t) => n + idf(t), 0);
const W = new Map(пул.map(a => [a, вага(T.get(a))]));

function бал(a, b) {
  const A = T.get(a), B = T.get(b);
  const m = Math.min(W.get(a), W.get(b));
  if (!m) return 0;
  let s = 0; for (const t of A) if (B.has(t)) s += idf(t);
  return s / m;
}
const розділ = g => (g === 'Україна' || g === 'Світ') ? 'УС'
  : g === 'Волинь' ? 'В' : (g === 'Олика' || g === 'Громада') ? 'Г' : (g || 'інше');

const спрацювання = [];
for (let i = 0; i < пул.length; i++) for (let j = i + 1; j < пул.length; j++) {
  const a = пул[i], b = пул[j];
  if (розділ(a.geo) !== розділ(b.geo)) continue;
  const хв = Math.abs(a.ts - b.ts) / 60000;
  if (хв > WINDOW_H * 60) continue;
  const s = бал(a, b);
  if (s >= W_STRONG || (s >= W_FRESH && хв <= FRESH_MIN)) спрацювання.push({ s, хв, a, b });
}

ok('корпус прочитано', пул.length > 100, `${пул.length} статей`);

// 🔴 Стеля спрацювань. 14 — заміряно 01.09 на 400 статтях, і всі 14 перевірені
// очима як справжні дублі. Число росте разом із корпусом, тому міряємо ЧАСТКУ:
// більше за 6% пар-спрацювань від кількості статей = правило почало злипати.
const частка = спрацювання.length / пул.length;
ok('🔴 правило НЕ злипає зайве (спрацювань ≤ 6% від корпусу)', частка <= 0.06,
   `${спрацювання.length} на ${пул.length} статей = ${(частка * 100).toFixed(1)}%`);

// Кожне спрацювання мусить мати ВАГОМУ спільну частину — інакше це не дубль,
// а випадковий збіг частих слів.
const слабкі = спрацювання.filter(x => x.s < W_FRESH);
ok('жодне спрацювання не нижче за поріг', слабкі.length === 0, `${слабкі.length}`);

// Свіжа гілка (нижчий поріг) має вмикатись ЛИШЕ на близьких у часі.
const порушники = спрацювання.filter(x => x.s < W_STRONG && x.хв > FRESH_MIN);
ok('🔴 послаблений поріг діє лише на ≤30 хв', порушники.length === 0,
   `${порушники.length} порушень`);

// Дублі мусять бути з РІЗНИХ джерел або хоча б з різними заголовками — якщо
// правило починає ловити статтю саму із собою, щось зламано в ключах.
const самозбіг = спрацювання.filter(x => x.a.id === x.b.id);
ok('стаття не порівнюється сама із собою', самозбіг.length === 0);

console.log(`\n   ℹ️ спрацювань: ${спрацювання.length} (${(частка * 100).toFixed(1)}% корпусу)`);
for (const x of спрацювання) {
  console.log(`      ${x.s.toFixed(2)} Δ=${Math.round(x.хв)}хв · ${x.a.title.slice(0, 44)} :: ${x.b.title.slice(0, 44)}`);
}
done();
