// Стенд: ЖОДЕН `data/*.json` НЕ ХОДИТЬ ІЗ CACHE-BUST.
//
// 🔴 ЩО ЛОВИМО. У `buses.js` стояло
//   fetch(`./data/schedule.json?v=${Math.floor(Date.now() / 60000)}`)
// — адреса мінялась щохвилини, тож `ETag`/`304` і кеш Service Worker не
// спрацьовували ЖОДНОГО разу, і файл на 814 КБ їхав наново при кожному
// відкритті вкладки в нову хвилину.
//
// 🔑 ЧОМУ ЦЕ БУЛО ЗАЙВЕ, А НЕ КОМПРОМІС. `sw.js` тримає весь `data/*.json` на
// «мережа першою»: запит і так іде в мережу, кеш — лише запасний шлях при
// обриві. Cache-bust не додавав свіжості, він лише забороняв серверу
// відповісти «не змінилось». Вартовий 23.09 окремо довів, що Pages віддає
// `ETag` і `304`.
//
// ⚠️ ЧОМУ СТОРОЖ, А НЕ ПРОСТО ПРАВКА. Точок входу за розкладом дві —
// вкладка (`buses.js`) і капсула Громади (`home-caps.js`) — і вони вже раз
// РОЗІЙШЛИСЬ: одна ходила з `?v=`, друга без, тобто показували різні копії
// того самого файлу. Правка без сторожа розійдеться знову.
//
// 🛑 ПРИЛАД ДОВОДИТЬ СЕБЕ МУТАЦІЄЮ (правило з NOW.md: «звужуєш ознаку — доведи
// мутацією; не червоніє на мутанті — не стереже»). Остання перевірка підкидає
// ЗАВІДОМО ЗЛАМАНИЙ рядок і вимагає, щоб ознака його побачила.

import { readdirSync, readFileSync, statSync } from 'fs';
import { join, relative } from 'path';
import { ROOT, reporter } from './_lib.mjs';

const { ok, done } = reporter();

// Усі .js під src/ — рекурсивно, без жорстких переліків: новий файл потрапляє
// під сторожа сам, не чекаючи, поки хтось згадає дописати його сюди.
function walk(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (name.endsWith('.js')) acc.push(p);
  }
  return acc;
}

// Ознака: рядок `data/<щось>.json`, за яким ОДРАЗУ йде `?`.
// ⚠️ Навмисно не ловимо `?` будь-де в рядку — інакше сторож червонів би на
// звичайному тексті з питальним знаком поруч. Ознака вузька: саме query-хвіст
// одразу за `.json`.
const CACHE_BUST = /data\/[a-z0-9_.-]+\.json\?/i;

const files = walk(join(ROOT, 'src'));
ok('знайшов файли для перевірки', files.length > 20, `${files.length} шт.`);

const винні = [];
for (const f of files) {
  const txt = readFileSync(f, 'utf8');
  for (const [i, рядок] of txt.split('\n').entries()) {
    // Рядки-коментарі пропускаємо: у цьому проєкті в коментарях ЦИТУЮТЬ старий
    // код, і без цього сторож червонів би на власному поясненні, чому так не
    // роблять. Саме таку пастку проєкт уже проходив.
    const голий = рядок.trim();
    if (голий.startsWith('//') || голий.startsWith('*')) continue;
    if (CACHE_BUST.test(рядок)) винні.push(`${relative(ROOT, f)}:${i + 1}`);
  }
}
ok('жоден data/*.json не ходить із query-хвостом', винні.length === 0, винні.join(' · ') || 'чисто');

// Обидві точки входу за розкладом мають ходити ОДНАКОВО.
const buses = readFileSync(join(ROOT, 'src/tabs/buses.js'), 'utf8');
const caps  = readFileSync(join(ROOT, 'src/tabs/home-caps.js'), 'utf8');
const ЧИСТИЙ = /fetch\(\s*['"`]\.\/data\/schedule\.json['"`]\s*\)/;
ok('вкладка «Автобуси» бере розклад чистою адресою', ЧИСТИЙ.test(buses));
ok('капсула Громади бере розклад тією самою адресою', ЧИСТИЙ.test(caps));

// SW і далі мусить тримати data/*.json на «мережа першою» — без цього правка
// вище справді коштувала б свіжості.
const sw = readFileSync(join(ROOT, 'sw.js'), 'utf8');
ok('sw.js тримає data/*.json на «мережа першою»',
   /\/data\//.test(sw) && /мережаПершою/.test(sw));

// 🛑 МУТАЦІЯ: підкидаємо відомий зламаний рядок і вимагаємо, щоб ознака його
// побачила. Без цієї перевірки «зелено» могло б означати «регулярка не працює».
const МУТАНТ = "const res = await fetch(`./data/schedule.json?v=${Date.now()}`);";
ok('ознака червоніє на завідомо зламаному рядку', CACHE_BUST.test(МУТАНТ));
// І дзеркально: не червоніє на чистому — інакше вона б забороняла все підряд.
ok('ознака мовчить на чистому рядку',
   !CACHE_BUST.test("const res = await fetch('./data/schedule.json');"));

done();
