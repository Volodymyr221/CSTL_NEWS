const ряд = await p.evaluate(() => {
  const row = document.querySelector('.hm-fd-circles');
  const box = document.getElementById('hm-feed-body');
  if (!row || !box) return null;
  const кола = [...row.querySelectorAll('.hm-fd-c')];
  const rr = row.getBoundingClientRect(), br = box.getBoundingClientRect();
  const перший = кола[0]?.getBoundingClientRect(), останній = кола[кола.length - 1]?.getBoundingClientRect();
  const назви = [...row.querySelectorAll('.hm-fd-c-name')].map(n => {
    // 🔑 КЛОН БЕЗ ОБМЕЖЕННЯ — єдиний чесний спосіб дізнатись, чи текст зрізано.
    // 🔬 Перша версія цієї перевірки міряла `scrollHeight > clientHeight` і
    // ЗАВЖДИ казала «вмістилось»: при `-webkit-line-clamp` браузер обрізає на
    // рівні відображення, тож scrollHeight дорівнює clientHeight навіть на
    // зрізаному тексті. Той самий клас брехні, що з `.eq()` у заглушці.
    const k = n.cloneNode(true);
    k.style.webkitLineClamp = 'unset'; k.style.height = 'auto';
    k.style.position = 'absolute'; k.style.width = n.clientWidth + 'px'; k.style.visibility = 'hidden';
    n.parentNode.appendChild(k);
    const повна = k.scrollHeight;
    k.remove();
    return { імя: n.textContent.trim(), видима: n.clientHeight, повна: Math.round(повна) };
  });
  return {
    ширинаРяду: Math.round(rr.width), ширинаБлока: Math.round(br.width),
    // 🔴 МІРЯЄМО ЕЛЕМЕНТИ, А НЕ КОНТЕЙНЕР. Сам `.hm-fd-circles` — блоковий, тож
    // його ширина ДОРІВНЮЄ ширині віджета завжди, навіть коли кружечки тиснуться
    // в лівій третині. Перша версія цієї перевірки мірила саме контейнер і тому
    // зеленіла на коді з порожньою колонкою праворуч (знайдено контролем 25.08).
    висотаРяду: Math.round(rr.height),
    хвіст: останній ? Math.round(br.right - останній.right) : null,
    голова: перший ? Math.round(перший.left - br.left) : null,
    назви,
  };
});

