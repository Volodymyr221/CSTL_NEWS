// 🔬 Заведена після живого скріна Вови 25.08: підпис під знімком обрізало так, що на
// екрані було видно ВЕРХНІ ПОЛОВИНКИ ЛІТЕР, а назва «КЦ «Центр культури, спорту та…»
// показувала зрізаний навпіл третій рядок.
// 🛑 Стенд цього НЕ ЛОВИВ, бо міряв ВЛАСТИВІСТЬ (`-webkit-line-clamp: 2` стояла на
// місці і була правильна), а не НАСЛІДОК. Різало не число рядків, а ВИСОТУ: у
// flex-колонці кожен елемент має `flex-shrink: 1`, тож знімок ріс і стискав текст.
// 🔑 Тому міряємо так: скільки РЯДКІВ влазить у коробку елемента. Ціле число (або ціле
// з невеликим запасом) — рядки цілі; дробова частина посередині — рядок зрізаний.
