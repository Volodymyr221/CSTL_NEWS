// 🔴 Скарга Вови: «спільноти громади не на всю ширину віджету розташовані» +
// «назви їхні написати повністю, щоб не обрізати, можна навіть в два рядки».
// ⚠️ МІРЯЄМО НАСЛІДОК, А НЕ ПРАВИЛО В CSS: чи ряд справді дорівнює ширині
