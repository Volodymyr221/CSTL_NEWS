// Стенд: КОД ЗВІРЯЄТЬСЯ, А НЕ ЗАКАЧУЄТЬСЯ ЗАНОВО.
//
// 🔴 НАВІЩО. До 24.09 Service Worker ходив у мережу з `cache: 'reload'` — і за
// код застосунку, і за передкеш. `reload` означає «не питай кеш узагалі», тобто
// браузер НЕ шле `If-None-Match`, і сервер не має як відповісти «не змінилось».
// Наслідок заміряний, не уявний: `bundle.js` 667 КБ + `style.min.css` 291 КБ
// качались ЦІЛКОМ при кожному відкритті застосунку, а передкеш — при кожному
// деплої, бо `CACHE_NAME` щоразу новий.
//
// 🔑 `no-cache` НЕ слабша за `reload` у свіжості: обидва ніколи не віддають
// копію без питання до сервера. Різниця лише в тому, що `no-cache` питає
// УМОВНО і приймає `304` без тіла.
//
// 🛑 ЧОМУ ЦЕ СТЕНД, А НЕ «ПОДИВИВСЯ І ВСЕ». Різниця між двома словами невидима
// на екрані: застосунок працює однаково, і повернення `reload` ніхто б не
// помітив — просто трафік мовчки виріс би назад. Рівно той клас регресу, який
// ловлять лише числом.
//
// ⚠️ ЧОГО ЦЕЙ СТЕНД НЕ ДОВОДИТЬ. Що Pages справді віддає `304` — це не до
// `sw.js`. Це заміряно окремо, вартовим `health-watch` на живому сайті (23.09).

import { readFileSync } from 'fs';
import { join } from 'path';
import { ROOT, reporter } from './_lib.mjs';

const { ok, done } = reporter();
const SW = readFileSync(join(ROOT, 'sw.js'), 'utf-8');

// Рахуємо лише ЖИВІ рядки: у файлі багато пояснень, і слово `reload` у них
// згадується навмисно — стенд, який червоніє на коментар, змусив би прибрати
// саме пояснення, заради якого все й писалось.
const живі = SW.split('\n')
  .filter(р => !/^\s*(\/\/|\*|\/\*)/.test(р))
  .join('\n');

ok('у sw.js не лишилось безумовних запитів за кодом',
   !/cache:\s*'reload'/.test(живі),
   живі.match(/cache:\s*'[a-z-]+'/g)?.join(' · ') || 'жодного');

ok('запити за кодом умовні', (живі.match(/cache:\s*'no-cache'/g) || []).length === 2,
   `${(живі.match(/cache:\s*'no-cache'/g) || []).length} місця`);

// Обидва місця мають бути саме ті: передкеш при установці і мережа-першою.
ok('умовний запит стоїть у передкеші', /STATIC_ASSETS\.map\([\s\S]{0,600}?cache:\s*'no-cache'/.test(SW));
ok('умовний запит стоїть у мережі-першою', /function мережаПершою[\s\S]{0,1500}?cache:\s*'no-cache'/.test(SW));

// 🔑 СВІЖІСТЬ НЕ ПОСЛАБЛЕНА: код і далі йде мережею-першою, а не з кешу.
ok('код застосунку лишився мережею-першою',
   /isAppCode[\s\S]{0,400}?мережаПершою\(e\.request,\s*\{\s*звірити:\s*true/.test(SW));

// 🛑 МУТАЦІЯ: доводимо, що перевірка справді впаде на поверненні `reload`.
const зіпсований = живі.replace("cache: 'no-cache'", "cache: 'reload'");
ok('перевірка червоніє, якщо reload повернеться',
   /cache:\s*'reload'/.test(зіпсований));

// Дані (новини, розклад) ходять БЕЗ прапорця — там network-first без умовного
// запиту, бо JSON малий і міняється щогодини. Якщо колись і туди додадуть
// `звірити`, це має бути свідомим рішенням, а не випадковим копіюванням.
ok('за даними прапорець не ставиться',
   /\/data\/[\s\S]{0,200}?мережаПершою\(e\.request\)/.test(SW));

done();
