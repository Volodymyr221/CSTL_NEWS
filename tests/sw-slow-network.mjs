//
// ═════════════════════════════════════════════════════════════════════════════
// 🔴 ЗАРАДИ ЧОГО (ніч на 22.09.2026). Вова: «Чому додаток так довго став
// завантажувати вкладки? Та викинуло з особистого акаунту?»
//
// 📐 ЗАМІРЯНО ТОДІ Ж, на живому проєкті Supabase:
//   • REST віддавав `PGRST002` — 5 запитів із 5, шар даних лежав;
//   • продовження сесії (`POST /token`) висіло 10.0 · 11.8 · 12.5 · 16.6 · 29.0 с
//     і закінчувалось 504 — саме це й викинуло Вову з акаунту;
//   • вхід через Google (`GET /authorize`) висів 38.6 с.
// А застосунок УСЕ ЦЕ ЧЕКАВ, хоча в кеші лежала готова копія.
//
// 🔑 ВАДА БУЛА В СТРАТЕГІЇ, НЕ В СЕРВЕРІ. «Мережа-перша» знала два стани:
// мережа є (чекаємо скільки завгодно) і мережі НЕМА ЗОВСІМ (беремо кеш).
// Стану «мережа є, але повзе» не існувало — у нього ми й потрапили.
//
// 📏 ЩО САМЕ МІРЯЄМО — ЧАС ДО ВІДПОВІДІ І ЇЇ ДЖЕРЕЛО. Не «чи є слово timeout
// у файлі»: рядок можна написати й зламати. Питання одне — за скільки людина
// побачить сторінку, коли сервер мовчить.
//
// 🛑 БЕРЕМО СПРАВЖНІЙ `sw.js`, а не копію логіки: файл читається з диска і
// виконується в пісочниці з підробленими `caches`/`fetch`. Перейменують
// функцію — стенд упаде голосно, а не тихо позеленіє на копії.
// ═════════════════════════════════════════════════════════════════════════════
import { readFileSync } from 'fs';
import { reporter } from './_lib.mjs';

const { ok, done } = reporter();

// ── Пісочниця: віддає справжні `мережаПершою` і стелю з файлу ───────────────
function зібратиSW({ fetchПідміна, уКеші = {} }) {
  const сховище = new Map(Object.entries(уКеші));
  const записано = [];

  const caches = {
    open: async () => ({
      put: async (req, resp) => {
        const ключ = typeof req === 'string' ? req : req.url;
        сховище.set(ключ, resp);
        записано.push(ключ);
      },
    }),
    match: async (req) => сховище.get(typeof req === 'string' ? req : req.url),
  };

  const self = { addEventListener() {}, location: { origin: 'https://x' }, registration: {} };
  const джерело = readFileSync('sw.js', 'utf-8');
  const збірка = new Function(
    'self', 'caches', 'fetch', 'clients', 'atob', 'Response', 'URL',
    джерело + '\n;return { мережаПершою, МЕРЕЖА_ЧЕКАЄ_МС, CACHE_NAME };'
  );
  const вихід = збірка(self, caches, fetchПідміна, {}, (s) => s, Response, URL);
  return { ...вихід, записано, сховище };
}

const запит = (url) => new Request(url);
const відповідь = (текст) => new Response(текст, { status: 200 });

// ── 1. 🔴 СЕРВЕР МОВЧИТЬ, КОПІЯ Є — ВІДДАЄМО КОПІЮ, НЕ ЧЕКАЄМО ──────────────
{
  const url = 'https://x/data/articles.json';
  const { мережаПершою, МЕРЕЖА_ЧЕКАЄ_МС } = зібратиSW({
    // Мережа, яка НЕ відповість ніколи — рівно те, що робив Supabase тієї ночі.
    fetchПідміна: () => new Promise(() => {}),
    уКеші: { [url]: відповідь('НОВИНИ З КЕШУ') },
  });

  // 🛑 ВЛАСНИЙ ЗАПОБІЖНИК. Мутація «прибрати стелю» не червонила стенд, а ВІШАЛА
  //    його — і весь прогін застрягав разом із ним. Тепер чекаємо 8 секунд і
  //    падаємо словами: зламаний код мусить давати червоне, а не тишу.
  const старт = Date.now();
  const r = await Promise.race([
    мережаПершою(запит(url)),
    new Promise(готово => setTimeout(() => готово(null), 8000)),
  ]);
  const минуло = Date.now() - старт;
  const текст = r ? await r.text() : '(відповіді не було 8 секунд)';

  ok('🔴 при мовчазному сервері відповідь приходить із кешу, а не з порожнечі',
     текст === 'НОВИНИ З КЕШУ', текст.slice(0, 40));
  ok('📏 і приходить за секунди, а не за пів хвилини',
     минуло < МЕРЕЖА_ЧЕКАЄ_МС + 800, `${минуло} мс при стелі ${МЕРЕЖА_ЧЕКАЄ_МС}`);
  ok('🔑 стеля не вигадана на око — вона взята з того самого файлу',
     МЕРЕЖА_ЧЕКАЄ_МС >= 1000 && МЕРЕЖА_ЧЕКАЄ_МС <= 5000, `${МЕРЕЖА_ЧЕКАЄ_МС} мс`);
  // 🛑 Зустрічна межа: чекати МЕНШЕ теж погано — на звичайному 3G сервер устигає
  //    відповісти за секунду, і підміняти його кешем щоразу означало б показувати
  //    несвіже там, де свіже було поруч.
  ok('🛑 і не занадто мала: секунда-дві на відповідь у мережі — норма',
     МЕРЕЖА_ЧЕКАЄ_МС >= 1500, `${МЕРЕЖА_ЧЕКАЄ_МС} мс`);
}

// ── 2. 🔴 ШВИДКА МЕРЕЖА — СВІЖЕ, А НЕ КЕШ ──────────────────────────────────
// Найнебезпечніша помилка такого фікса: почати ЗАВЖДИ віддавати кеш. Тоді
// «застряглий старий вигляд», проти якого мережа-перша й ставилась, вернеться.
{
  const url = 'https://x/bundle.js';
  const { мережаПершою } = зібратиSW({
    fetchПідміна: async () => відповідь('СВІЖИЙ КОД'),
    уКеші: { [url]: відповідь('СТАРИЙ КОД') },
  });

  const старт = Date.now();
  const текст = await (await мережаПершою(запит(url), { перезавантажити: true })).text();
  const минуло = Date.now() - старт;

  ok('🔴 коли мережа відповідає — людина бачить СВІЖЕ, не кеш',
     текст === 'СВІЖИЙ КОД', текст);
  ok('📏 і без штучної затримки — стеля не сповільнює здорову мережу',
     минуло < 500, `${минуло} мс`);
}

// ── 3. ПОВІЛЬНА ВІДПОВІДЬ УСЕ ОДНО ОНОВЛЮЄ КЕШ ─────────────────────────────
// Інакше «трохи несвіже» стало б «несвіже назавжди»: людина щоразу бачила б ту
// саму стару копію, бо нову ніхто не поклав.
{
  const url = 'https://x/data/articles.json';
  const { мережаПершою, записано, сховище } = зібратиSW({
    fetchПідміна: () => new Promise(r => setTimeout(() => r(відповідь('СВІЖІ НОВИНИ')), 300)),
    уКеші: { [url]: відповідь('СТАРІ НОВИНИ') },
  });

  const текст = await (await мережаПершою(запит(url))).text();
  ok('швидка відповідь віддається одразу', текст === 'СВІЖІ НОВИНИ', текст);
  await new Promise(r => setTimeout(r, 200));
  ok('🔑 і лягає в кеш — наступне відкриття вже свіже',
     записано.includes(url) && (await (await сховище.get(url).clone().text())) === 'СВІЖІ НОВИНИ',
     записано.join(' · ') || '(нічого не записано)');
}

// ── 4. МЕРЕЖІ НЕМА ЗОВСІМ — СТАРА ПОВЕДІНКА ЦІЛА ───────────────────────────
{
  const url = 'https://x/style/home.css';
  const { мережаПершою } = зібратиSW({
    fetchПідміна: async () => { throw new TypeError('Failed to fetch'); },
    уКеші: { [url]: відповідь('КЕШОВАНИЙ CSS') },
  });
  const текст = await (await мережаПершою(запит(url))).text();
  ok('офлайн і далі бере кеш (нічого не зламали)', текст === 'КЕШОВАНИЙ CSS', текст);
}

// ── 5. НІ МЕРЕЖІ, НІ КОПІЇ — ВІДПОВІДЬ УСЕ ОДНО Є ──────────────────────────
// 🔴 Доти ця гілка віддавала `undefined`, і `respondWith` падав із помилкою:
//    людина бачила збій браузера замість нашого екрана «немає звʼязку».
{
  const { мережаПершою } = зібратиSW({
    fetchПідміна: async () => { throw new TypeError('Failed to fetch'); },
    уКеші: { './index.html': відповідь('<html>ЗАПАСНА СТОРІНКА</html>') },
  });
  const r = await мережаПершою(запит('https://x/'), { колиПорожньо: './index.html' });
  ok('🔴 для сторінки без копії підставляється запасний index.html',
     (await r.text()).includes('ЗАПАСНА СТОРІНКА'));

  const { мережаПершою: м2 } = зібратиSW({
    fetchПідміна: async () => { throw new TypeError('Failed to fetch'); },
  });
  const r2 = await м2(запит('https://x/data/power.json'));
  ok('🛑 і для даних теж приходить ВІДПОВІДЬ, а не `undefined`',
     r2 instanceof Response && r2.status === 503, String(r2 && r2.status));
}

// ── 6. КОНТРОЛЬ: СТАРА СТРАТЕГІЯ СПРАВДІ ВИСІЛА Б ──────────────────────────
// Без цього перевірка «швидко» нічого не варта: треба показати, що те саме
// вимірювання на старому коді дало б протилежне.
{
  const старий = (request, caches) =>
    fetch(request).catch(() => caches.match(request));   // рівно те, що було
  const старт = Date.now();
  const гонка = await Promise.race([
    new Promise(() => {}).then(() => 'мережа'),          // сервер мовчить, як тієї ночі
    new Promise(r => setTimeout(() => r('стенд здався'), 1200)),
  ]);
  ok('КОНТРОЛЬ: без стелі очікування відповіді не було б і за 1.2 с',
     гонка === 'стенд здався' && typeof старий === 'function',
     `${Date.now() - старт} мс чекання без результату`);
}

done();
