// Стенд: ЗВІДКИ ПРИЙШЛА ЛЮДИНА — МІТКА ДЖЕРЕЛА (01.10.2026).
//
// 🔴 ЗАРАДИ ЧОГО ВІН ІСНУЄ. Аудит готовності 30.09 назвав позначку джерела
// єдиним ТЕХНІЧНИМ блокером дня Х: кампанія розводить людей шістьма точками
// (наліпка в автобусі, аркуш у костелі, табличка, Viber, Facebook, Instagram),
// а в коді не було ні читання параметра, ні події. На другому тижні кампанії
// питання «яка точка дала встановлення» — головне, і без цього на нього немає
// відповіді взагалі.
//
// 🔑 ЩО САМЕ МІРЯЄМО — НАСЛІДОК, А НЕ ТЕКСТ КОДУ: що доїхало в базу (заглушка
// пише вставки в `window.__cstlInserted`) і що лишилось в адресі. Перевірка
// «чи є в коді `searchParams.get`» не побачила б ні втраченої мітки при
// встановленні, ні перезапису першого дотику — тобто рівно тих двох вад, проти
// яких цей файл і написаний.
//
// ⚠️ ГОЛОВНА ПЕРЕВІРКА ТУТ — ТРЕТЯ: мітка живе ПІСЛЯ зникнення параметра з
// адреси. Це не дрібниця і не «про всяк випадок»: `manifest.json` має
// `"start_url": "./"` без запиту, тож установлений застосунок стартує з чистої
// адреси ЗАВЖДИ. Стенд, який перевіряв би лише перший захід із `?from=`,
// зеленів би над кодом, де найважливіше число — встановлення по точках —
// порожнє.
import { chromium } from 'playwright';
import { launch, serve, reporter } from './_lib.mjs';
import { mockSupabase } from './_board-fixture.mjs';

const { ok, done } = reporter();

const { url, stop } = await serve();
const b = await launch(chromium);

// Кожен випадок — СВІЙ контекст (окремий «пристрій»), бо памʼять мітки живе в
// `localStorage`, і спільний контекст зробив би випадки залежними від порядку.
async function пристрій() {
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true,
                                   hasTouch: true, serviceWorkers: 'block' });
  const p = await ctx.newPage();
  await mockSupabase(p, { pages: [], page_posts: [], posts: [] });
  await p.route('**://api.open-meteo.com/**', r => r.abort());
  return { ctx, p };
}

// Зайти за адресою і дочекатись події заходу.
// 🔑 Згоду на статистику тиснемо ОБОВʼЯЗКОВО: без неї `logEvent` мовчить, і
// стенд «події немає» зеленів би дарма — та сама пастка, що в `boot-noise`.
async function зайти(p, запит) {
  await p.goto(url + запит, { waitUntil: 'domcontentloaded' });
  await p.waitForTimeout(600);
  await p.evaluate(() => document.querySelector('.consent-accept')?.click());
  await p.waitForTimeout(1400);
}

const заходи = (p) => p.evaluate(() => (window.__cstlInserted || [])
  .filter(r => r.table === 'analytics_events' && r.row?.event_type === 'session_start')
  .map(r => r.row?.meta || {}));

// ── 1. КОНТРОЛЬ ПЕРШОГО ПОРЯДКУ: порожній пристрій НЕ дає мітки ────────────
// Стоїть першим і саме як контроль. Якби `src` з'являлось завжди, усі наступні
// перевірки зеленіли б на будь-якому коді — показували б не мітку, а власний
// шум. Заразом це вимога до поля: воно не має бути `null` у кожному заході.
{
  const { ctx, p } = await пристрій();
  await зайти(p, '/');
  const м = await заходи(p);
  ok('контроль: захід БЕЗ параметра не несе поля `src` узагалі',
     м.length > 0 && м.every(x => !('src' in x)),
     `заходів ${м.length}, meta: ${JSON.stringify(м[0] || {})}`);
  await ctx.close();
}

// ── 2. МІТКА З АДРЕСИ ДОЇЖДЖАЄ В ПОДІЮ ЗАХОДУ ──────────────────────────────
{
  const { ctx, p } = await пристрій();
  await зайти(p, '/?from=bus-sticker');
  const м = await заходи(p);
  ok('🔖 `?from=bus-sticker` доїжджає в `session_start` як `meta.src`',
     м.some(x => x.src === 'bus-sticker'),
     JSON.stringify(м.map(x => x.src)));

  // ── 3. І ПАРАМЕТР ПРИБРАНО З АДРЕСИ ──────────────────────────────────────
  // Щоб людина, яка перешле посилання зі свого екрана, не приписала друга до
  // наліпки, яку сканувала сама.
  const адреса = await p.evaluate(() => location.search);
  ok('🧹 параметр прибрано з адреси після заходу', адреса === '', `search: "${адреса}"`);
  await ctx.close();
}

// ── 4. ГОЛОВНЕ: МІТКА ПЕРЕЖИВАЄ ЗНИКНЕННЯ ПАРАМЕТРА ────────────────────────
// Відтворюємо саме встановлення: перший захід за наліпкою в браузері, далі
// застосунок відкривається з `start_url` — тобто з чистої адреси.
{
  const { ctx, p } = await пристрій();
  await зайти(p, '/?from=kostel');
  await зайти(p, '/');                 // другий захід, адреса чиста
  const м = await заходи(p);
  const другий = м[м.length - 1] || {};
  ok('🔑 мітка живе після зникнення параметра (це і є випадок встановлення)',
     другий.src === 'kostel', `останній захід: ${JSON.stringify(другий)}`);
  await ctx.close();
}

// ── 5. ПЕРШИЙ ДОТИК ВИГРАЄ — ДРУГА МІТКА НЕ ПЕРЕЗАПИСУЄ ────────────────────
// Людина прийшла з наліпки, за тиждень тицьнула посилання з Viber-групи. Без
// цього правила Viber забрав би собі заслугу наліпки, і число, за яким Вова
// вирішує, куди клеїти наступну сотню, показувало б не ту точку.
{
  const { ctx, p } = await пристрій();
  await зайти(p, '/?from=bus-sticker');
  await зайти(p, '/?from=viber');
  const м = await заходи(p);
  const останній = м[м.length - 1] || {};
  ok('🛑 перший дотик виграє: друга мітка НЕ перезаписує першу',
     останній.src === 'bus-sticker', `останній захід: ${JSON.stringify(останній)}`);
  await ctx.close();
}

// ── 6. СМІТТЄВЕ ЗНАЧЕННЯ ВІДКИДАЄТЬСЯ ──────────────────────────────────────
// Значення приходить із-поза застосунку і йде в базу та в звіт, тож відкритим
// текстовим полем бути не має права.
{
  const { ctx, p } = await пристрій();
  await зайти(p, '/?from=' + encodeURIComponent('<script>щось</script> дуже довга назва якої ніде не існує'));
  const м = await заходи(p);
  ok('🛑 значення поза межами (знаки, довжина) не стає міткою',
     м.every(x => !('src' in x)), JSON.stringify(м.map(x => x.src)));
  await ctx.close();
}

// ── 7. `utm_source` ТЕЖ ЧИТАЄТЬСЯ ──────────────────────────────────────────
// Посилання з рекламного кабінету й розсилок приходить саме з ним, і людина,
// яка ставить допис, візьме звичну для себе форму.
{
  const { ctx, p } = await пристрій();
  await зайти(p, '/?utm_source=fb-grupa');
  const м = await заходи(p);
  ok('🔖 `utm_source` читається як джерело теж',
     м.some(x => x.src === 'fb-grupa'), JSON.stringify(м.map(x => x.src)));
  await ctx.close();
}

// ── 8. ВИМИКАЧ СТАТИСТИКИ ГЛУШИТЬ І МІТКУ ──────────────────────────────────
// Хто відкликав згоду — не лишає сліду жодного виду. Але параметр з адреси
// однаково прибираємо: то гігієна адреси, а не збір.
{
  const { ctx, p } = await пристрій();
  await p.addInitScript(() => { try { localStorage.setItem('cstl-analytics-off', '1'); } catch (_) {} });
  await p.goto(url + '/?from=bus-sticker', { waitUntil: 'domcontentloaded' });
  await p.waitForTimeout(1600);
  const запамʼятовано = await p.evaluate(() => localStorage.getItem('cstl-source-v1'));
  const адреса = await p.evaluate(() => location.search);
  ok('🛑 при вимкненій статистиці мітка НЕ зберігається',
     !запамʼятовано, `у памʼяті: ${JSON.stringify(запамʼятовано)}`);
  ok('🧹 …але параметр з адреси все одно прибрано', адреса === '', `search: "${адреса}"`);
  await ctx.close();
}

await b.close(); await stop();
done();
