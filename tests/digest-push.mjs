// Стенд: РАНКОВЕ ЗВЕДЕННЯ — ВОРОТАР ЧАСУ, ТИША НА ПОРОЖНЬОМУ, ОДИН ВИМИКАЧ.
//
// 🔴 ЗАРАДИ ЧОГО (аудит готовності 30.09). Ціль №1 курсу — звичка, а звичка
// тримається на приводі заходити В ТОЙ САМИЙ ЧАС. Такого приводу не було:
// push про новини не існував як тип, зведення в розкладі не стояло.
//
// 🛑 ГОЛОВНЕ, ЩО СТЕРЕЖЕ ЦЕЙ ФАЙЛ, — НЕ НАЯВНІСТЬ ЗВЕДЕННЯ, А ТРИ ЙОГО МЕЖІ.
// Зведення, зроблене неакуратно, гірше за його відсутність:
//
//   1. ВОРОТАР ЧАСУ. 📐 Заміряно 22-23.09: `pg_cron` тут душиться незалежно від
//      синтаксису — з десятка слотів виконуються два, проміжки до 2.5 години.
//      Отже «розклад о 07:30» у цьому проєкті не обіцянка. Зведення о 14:00 —
//      не ранкова звичка, а випадковий шум, який вчить вимикати сповіщення.
//      Тому функція САМА дивиться на годинник, і це єдине, що робить розклад
//      безпечним.
//   2. ТИША НА ПОРОЖНЬОМУ. «За добу нічого нового» витрачає довіру і ще раз
//      каже, що тут порожньо. На старті це буде частий випадок — правило
//      спрацює вже першого тижня.
//   3. ОДИН НА ДОБУ. У вікні 6-9 розклад може дзвонити кілька разів; без
//      журналу `(uid, день)` людина отримала б три зведення за ранок — рівно
//      той потоп, проти якого вся робота.
//
// 🔑 І окремо — СИНХРОН ТРЬОХ ПЕРЕЛІКІВ вимикачів. Новий тип push без свого
// рядка в кожному з трьох місць дає найтихішу з можливих вад: тумблер клацає,
// знімок на пристрої оновлюється, а в базу не доїжджає нічого, і сервер далі
// шле те, що людина щойно вимкнула (клас B-33, 24.08).
//
// 🛑 ЧОМУ ТЕКСТОВИЙ СТОРОЖ — та сама причина, що в `push-scale` і `push-quota`:
// Edge Functions із пісочниці не запускаються. ⚠️ Він НЕ доводить, що зведення
// доходить до телефона — лише що межі на місці. Живу перевірку дає сухий
// прогін (`dry_run: true`), і він навмисно віддає `kyiv_hour`, бо воротар часу
// може зламатись МОВЧКИ: не застосується пояс — лишиться UTC, і влітку
// різниця складе три години.

import { readFileSync, existsSync } from 'fs';
import { join } from 'path';
import { ROOT, reporter } from './_lib.mjs';

const { ok, done } = reporter();

const безКоментарів = (т) => т.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
const файл = (п) => existsSync(join(ROOT, п)) ? readFileSync(join(ROOT, п), 'utf-8') : '';

const ФН_ШЛЯХ = 'supabase/functions/send-digest-push/index.ts';
const SQL_ШЛЯХ = 'scripts/supabase_digest_push.sql';

ok('🔴 функція зведення існує', !!файл(ФН_ШЛЯХ), ФН_ШЛЯХ);
ok('🔴 SQL-частина існує', !!файл(SQL_ШЛЯХ), SQL_ШЛЯХ);

const фн = безКоментарів(файл(ФН_ШЛЯХ));
const sql = файл(SQL_ШЛЯХ);

// ── 1. ВОРОТАР ЧАСУ ────────────────────────────────────────────────────────
// Міряємо не «чи є слово kyivHour», а чи є ПОРІВНЯННЯ з вікном: функція, що
// лише знає годину й нічого з нею не робить, виглядала б так само.
ok('🛑 функція сама звіряє годину і виходить поза вікном',
   /kyivHour\(\)/.test(фн) && /ВІКНО_ВІД/.test(фн) && /ВІКНО_ДО/.test(фн)
     && /not the morning/.test(фн),
   'воротар на місці');

ok('…і пояс саме київський, не UTC',
   /timeZone: *'Europe\/Kyiv'/.test(фн), 'Europe/Kyiv');

// 📐 `hourCycle: 'h23'` — без нього частина реалізацій віддає «24» замість «0»
// опівночі, і година мовчки поїхала б. Вада, яку видно лише раз на добу.
ok('🔴 година читається з `hourCycle: h23`',
   /hourCycle: *'h23'/.test(фн), 'h23');

// ── 2. ТИША НА ПОРОЖНЬОМУ ──────────────────────────────────────────────────
ok('🛑 нічого не сталось — не шлемо нічого',
   /nothing happened/.test(фн), 'тиша на місці');

// ── 3. ОДИН НА ДОБУ ────────────────────────────────────────────────────────
ok('🔴 журнал «одне на добу» читається перед розсилкою',
   /digest_push_log/.test(фн) && /already sent today/.test(фн),
   'журнал на місці');

ok('…і сам журнал тримає межу ключем `(uid, день)`, а не лише перевіркою',
   /PRIMARY KEY \(uid, день\)/.test(sql), 'первинний ключ');

// 🔑 Позначку ставить той, хто БАЧИВ успіх: журнал пишеться ПІСЛЯ надсилання.
// Навпаки — і збій сервісу push зʼїв би людині зведення на добу, не показавши.
const іПозначка = фн.indexOf('digest_push_log')  >= 0
  && фн.lastIndexOf('digest_push_log') > фн.indexOf('слатиПачками(свої');
ok('🔴 у журнал пишемо ПІСЛЯ надсилання, а не до',
   іПозначка, 'порядок правильний');

// ── 4. ВИМИКАЧ: ТРИ ПЕРЕЛІКИ ЗБІГАЮТЬСЯ ────────────────────────────────────
// 🛑 Саме цей розділ ловить найтихішу ваду: тумблер є, а в базі колонки немає
// (або навпаки), і вимикач мовчки нічого не вимикає.
const supaJs = файл('src/core/supabase.js');
const accUi  = файл('src/core/account-ui.js');
const теми = (supaJs.match(/NOTIF_TOPICS = \[([^\]]+)\]/) || [, ''])[1]
  .match(/'([a-z]+)'/g)?.map(s => s.replace(/'/g, '')) || [];
const ключіКабінету = (accUi.match(/\{ k: '([a-z]+)'/g) || []).map(s => s.replace(/.*'([a-z]+)'/, '$1'));

ok('🔴 `digest` є в усіх трьох: тема, тумблер кабінету, колонка в базі',
   теми.includes('digest') && ключіКабінету.includes('digest')
     && /ADD COLUMN IF NOT EXISTS digest/.test(sql),
   `теми: ${теми.join(',')} · кабінет: ${ключіКабінету.join(',')}`);

ok('🔴 переліки тем і тумблерів збігаються ПОВНІСТЮ, не лише по `digest`',
   теми.length === ключіКабінету.length && теми.every(t => ключіКабінету.includes(t)),
   `${теми.length} тем проти ${ключіКабінету.length} тумблерів`);

ok('🛑 функція справді питає вимикач `digest`, а не шле всім',
   /allowed\(admin, *усіUid, *'digest'\)/.test(фн), 'вимикач читається');

// ── 5. ЖУРНАЛ ПРИБИРАЄТЬСЯ ─────────────────────────────────────────────────
// 🔴 24.09 диск Supabase вичерпав бюджет IO через розпухлі службові журнали.
// Кожен новий журнал у цьому проєкті заводиться РАЗОМ із прибиранням.
ok('🔴 журнал зведення прибирається за розкладом',
   /prune_digest_log/.test(sql) && /cron\.schedule\('prune-digest-log'/.test(sql),
   'прибирання в розкладі');

// ── 6. РОЗКЛАД: ЯВНІ ХВИЛИНИ, НЕ КРОК ──────────────────────────────────────
// 🛑 `*/N` у цьому проєкті душиться гірше за явні хвилини (заміряно 22-23.09).
{
  const слоти = sql.match(/cron\.schedule\('[^']+', *'([^']+)'/g) || [];
  const зКроком = слоти.filter(с => /\*\//.test(с));
  ok('🛑 у розкладі немає кроку `*/N` — лише явні хвилини',
     зКроком.length === 0, зКроком.join(' · ') || слоти.join(' · '));
}

// ── 7. КОНТРОЛЬ: СТОРОЖ УМІЄ ЧЕРВОНІТИ ─────────────────────────────────────
// Без цього рядка весь файл міг би зеленіти на будь-якому тексті.
ok('контроль: той самий пошук НЕ знаходить вигаданої назви',
   !/ВІКНО_ВИГАДАНЕ/.test(фн), 'спосіб пошуку розрізняє наявне і відсутнє');

done();
