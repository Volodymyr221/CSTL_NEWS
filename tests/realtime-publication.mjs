//
// 🔴 ЗАРАДИ ЧОГО (знайдено 24.09 звіркою з живою базою). У `supabase.js` є
// `subscribePosts()` — жива Дошка: нове оголошення мало зʼявлятись у інших без
// перезаходу. Код написаний і акуратний. А таблиці `posts` не було в
// публікації `supabase_realtime`, тобто подій до цієї підписки НЕ ПРИХОДИЛО
// ЖОДНОГО РАЗУ.
//
// 🛑 ЧОМУ ЦЕ КЛАС ВАД, А НЕ ОДНА ВАДА. Підписка живе в репозиторії, публікація
// — в базі, і друга половина з коду невидима. Симптом при цьому збігається зі
// станом «фічі ще немає»: дані приїжджають при наступному перезаході, а він
// трапляється постійно. Тобто ЗЛАМАНЕ І НЕЗРОБЛЕНЕ виглядають однаково.
//
// 🔑 ЩО МІРЯЄМО. Перелік таблиць, на які підписується код, проти дзеркала
// публікації `scripts/prod_realtime_tables.txt`. Дзеркало оновлюють разом із
// міграцією, що міняє публікацію, — і саме розбіжність між цими двома
// списками і є вадою.
//
// ⚠️ МЕЖА ЧЕСНОСТІ: стенд не ходить у базу (з пісочниці туди не пишуть і не
// звіряються щопрогону). Він звіряє КОД із ДЗЕРКАЛОМ. Якщо дзеркало збрехало —
// стенд збреше разом із ним; тому у файлі дзеркала записано, яким запитом і
// коли його знято.

import { readFileSync, readdirSync } from 'fs';
import { join } from 'path';
import { ROOT, reporter } from './_lib.mjs';

const { ok, done } = reporter();

// У дзеркалі два списки: що на проді ЗАРАЗ і що чекає накату міграції.
// Розділені навмисно — щоб файл не брехав про живу базу.
const [ЖИВЕ_ТЕКСТ, ЧЕКАЄ_ТЕКСТ = ''] = readFileSync(join(ROOT, 'scripts/prod_realtime_tables.txt'), 'utf-8')
  .split('# --- чекає накату ---');
const рядки = т => т.split('\n').map(р => р.replace(/#.*$/, '').trim()).filter(Boolean);
const ЖИВЕ = рядки(ЖИВЕ_ТЕКСТ), ЧЕКАЄ = рядки(ЧЕКАЄ_ТЕКСТ);
const ДЗЕРКАЛО = [...ЖИВЕ, ...ЧЕКАЄ];

ok('дзеркало публікації прочитано', ЖИВЕ.length >= 8, `${ЖИВЕ.length} на проді, ${ЧЕКАЄ.length} чекає накату`);

// 🔑 ЧЕРГУ НЕ РОБИМО ЧЕРВОНОЮ САМУ ПО СОБІ, і це свідомо. Накат робить Вова
// руками; стенд, який світиться червоним, поки людина не дійшла до SQL Editor,
// перестають читати — а тоді він не спрацює й тоді, коли зламається щось
// справжнє. Натомість вимагаємо, щоб на кожен рядок черги БУВ файл міграції:
// це те, за що відповідає репозиторій, і воно перевірне.
const міграції = readdirSync(join(ROOT, 'supabase/migrations')).join('\n');
const безМіграції = ЧЕКАЄ.filter(т => !new RegExp(т).test(міграції));
ok('на кожну таблицю з черги є міграція',
   безМіграції.length === 0,
   ЧЕКАЄ.length
     ? `чекає накату: ${ЧЕКАЄ.join(', ')} — до того підписка мовчить`
     : 'черга порожня');

// Збираємо всі `table: '…'` з викликів `.on('postgres_changes', …)` по всьому src.
function файли(дир) {
  const out = [];
  for (const е of readdirSync(dir_(дир), { withFileTypes: true })) {
    const п = join(дир, е.name);
    if (е.isDirectory()) out.push(...файли(п));
    else if (е.name.endsWith('.js')) out.push(п);
  }
  return out;
}
function dir_(д) { return join(ROOT, д); }

const підписки = new Map();   // таблиця → чи є filter
for (const ф of файли('src')) {
  const текст = readFileSync(join(ROOT, ф), 'utf-8');
  const re = /\.on\(\s*'postgres_changes'\s*,\s*\{([^}]*)\}/g;
  let m;
  while ((m = re.exec(текст))) {
    const тіло = m[1];
    const т = /table:\s*'([a-z_]+)'/.exec(тіло)?.[1];
    if (!т) continue;
    const зФільтром = /filter:/.test(тіло);
    підписки.set(т, (підписки.get(т) ?? true) && зФільтром);
  }
}

ok('знайшов підписки в коді', підписки.size >= 8, [...підписки.keys()].join(', '));

const безПублікації = [...підписки.keys()].filter(т => !ДЗЕРКАЛО.includes(т));
ok('кожна підписка має таблицю в публікації',
   безПублікації.length === 0,
   безПублікації.length ? `без публікації: ${безПублікації.join(', ')}` : 'усі на місці');

// Зворотний бік: таблиця в публікації, на яку ніхто не підписаний, — це зайвий
// потік подій з бази до кожного клієнта. Не вада, але варто бачити.
const беззайві = ДЗЕРКАЛО.filter(т => !підписки.has(т));
ok('у публікації немає таблиць, які нікому не потрібні',
   беззайві.length === 0,
   беззайві.length ? `нікому не треба: ${беззайві.join(', ')}` : 'зайвих немає');

// 🛑 МУТАЦІЯ: без неї «усі на місці» могло б означати «розбір нічого не знайшов».
ok('звірка червоніє на вигаданій таблиці',
   ['posts', 'вигадана_таблиця'].filter(т => !ДЗЕРКАЛО.includes(т)).length === 1);

done();
