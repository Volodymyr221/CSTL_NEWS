// Стенд: РОЗСИЛКА НЕ ОБРИВАЄТЬСЯ МОВЧКИ НА ВЕЛИКІЙ АУДИТОРІЇ.
//
// 🔴 ЗАРАДИ ЧОГО (аудит 24.09). Функції розсилки переходили три межі, і ЖОДНА
// не давала помилки — саме тому їх ніхто не бачив:
//   1. PostgREST віддає щонайбільше 1000 рядків на запит. Вибірка підписників
//      без сторінок на 1001-му мовчки обрізається: тисяча отримує сповіщення,
//      решта ні, а журнал каже «надіслано».
//   2. `.in('uid', [...])` кладе перелік в АДРЕСУ запиту — кілька тисяч uid
//      дають `414`, і розсилка падає цілком.
//   3. Стеля Edge Function — 150 с. Надсилання йшло по одному пристрою в
//      черзі: ~150 мс × тисяча = функція вмирає на півдорозі.
//
// 🛑 ЧОМУ ЦЕ ТЕКСТОВИЙ СТОРОЖ. Перевірити наслідок нічим: Edge Functions із
// пісочниці не запускаються, а підписників у базі сьогодні десятки — тобто
// навіть живий прогін нічого б не довів. Натомість беремо ЖИВИЙ текст функцій
// і вимагаємо, щоб конкретні рішення були на місці. Межі методу — в кінці.
//
// ⚠️ ЦЕЙ СТЕНД НЕ ДОВОДИТЬ, ЩО РОЗСИЛКА ПРАЦЮЄ. Він доводить лише, що вона не
// впаде на масштабі так, як падала б до 24.09.

import { readFileSync, readdirSync } from 'fs';
import { join } from 'path';
import { ROOT, reporter } from './_lib.mjs';

const { ok, done } = reporter();

const ДИР = join(ROOT, 'supabase/functions');
const функції = readdirSync(ДИР).filter(н => н.startsWith('send-'));
const текст = н => readFileSync(join(ДИР, н, 'index.ts'), 'utf-8');

ok('знайшов функції розсилки', функції.length >= 6, функції.join(', '));

// ── 1. Жодного послідовного надсилання ─────────────────────────────────────
// Один `sendNotification` на файл — той, що всередині `слатиПачками`. Більше
// означає, що десь лишився (або повернувся) цикл «по одному».
const зЦиклом = функції.filter(н => {
  const т = текст(н);
  return (т.match(/webpush\.sendNotification/g) || []).length > 1;
});
ok('ніде не лишилось надсилання по одному',
   зЦиклом.length === 0,
   зЦиклом.length ? зЦиклом.join(', ') : 'усюди пачками');

// ── 2. Хто шле багатьом — робить це пачками ────────────────────────────────
// 🔑 «Масова» тут — та, що шле ОДНАКОВЕ повідомлення багатьом. `send-chat-push`
// шле одній людині, тож пачки там ні до чого. `send-bus-push` теж не тут, і це
// не поблажка: він складає СВІЙ текст кожній підписці (свій рейс, своя зупинка,
// свій час) і одразу після надсилання ставить рядку позначку `notified_*`.
// Збити це в пачку означало б переписати його логіку заради виграшу, якого там
// немає — підписок на добу одиниці. Його межа інша, і вона перевірена нижче.
const масові = функції.filter(н => /user_push_devices'\)[\s\S]{0,160}\.in\('uid'/.test(текст(н))
                                || /слатиПачками/.test(текст(н)));
const безПачок = масові.filter(н => !/слатиПачками/.test(текст(н)));
ok('масові розсилки йдуть пачками',
   безПачок.length === 0,
   безПачок.length ? `по одному: ${безПачок.join(', ')}` : масові.join(', '));

// ── 3. Довгі переліки ріжуться ─────────────────────────────────────────────
const безРізки = масові.filter(н => !/частинами\(/.test(текст(н)));
ok('довгі переліки uid ріжуться на шматки',
   безРізки.length === 0,
   безРізки.length ? безРізки.join(', ') : 'усі ріжуть');

// ── 4. Вибірки підписників читаються сторінками ────────────────────────────
// Хто читає пристрої переліком uid — мусить уміти взяти більше за 1000.
const читаютьПристрої = функції.filter(н => /user_push_devices'\)[\s\S]{0,120}\.in\('uid'/.test(текст(н)));
const безСторінок = читаютьПристрої.filter(н => !/усіРядки/.test(текст(н)));
ok('пристрої читаються сторінками, а не першою тисячею',
   безСторінок.length === 0,
   безСторінок.length ? безСторінок.join(', ') : читаютьПристрої.join(', '));

// ── 5. Видалення мертвих підписок теж шматками ─────────────────────────────
// `.in('id', dead)` з тисячами id — та сама межа адреси, тільки на виході.
const видаляють = функції.filter(н => /delete\(\)\.in\('id'/.test(текст(н)));
const безРізкиВидалення = видаляють.filter(н =>
  !/частинами\([^)]*\)[\s\S]{0,200}delete\(\)\.in\('id'/.test(текст(н)));
ok('мертві підписки видаляються шматками',
   безРізкиВидалення.length === 0,
   безРізкиВидалення.length ? безРізкиВидалення.join(', ') : видаляють.join(', '));

// ── 6. Вибірка підписок на рейси теж читається сторінками ──────────────────
// Своя межа `send-bus-push`: усі сьогоднішні підписки одним `select('*')` — це
// та сама тиша на 1001-му рядку, тільки замість «не отримав пост» буде «не
// отримав сповіщення про СВІЙ рейс».
ok('підписки на рейси читаються сторінками',
   /push_subscriptions[\s\S]{0,400}усіРядки|усіРядки[\s\S]{0,400}push_subscriptions/.test(текст('send-bus-push')));

// ── 7. Помилка одного пристрою не валить розсилку ──────────────────────────
const зAllSettled = масові.filter(н => /Promise\.allSettled/.test(текст(н)));
ok('збій одного пристрою не зупиняє решту',
   зAllSettled.length === масові.length,
   `${зAllSettled.length} із ${масові.length}`);

// 🛑 МУТАЦІЯ: доводимо, що перевірки справді кусаються, а не збігаються з
// будь-яким текстом. Підробляємо файл без пачок — стенд має його впіймати.
const підробка = 'await webpush.sendNotification(a); await webpush.sendNotification(b);';
ok('перевірка червоніє на надсиланні по одному',
   (підробка.match(/webpush\.sendNotification/g) || []).length > 1);

// ── МЕЖІ ЦЬОГО СТОРОЖА (чесно) ─────────────────────────────────────────────
// • Він читає ТЕКСТ, а не поведінку: правильно названа, але зламана функція
//   пройде. Це ціна за те, що Edge Functions звідси не запускаються.
// • Він нічого не каже про те, чи доходять сповіщення.
// • Ширина пачки (50) і шматка (200) не перевіряються: це налаштування, а не
//   рішення — їх видно в коді й міняють свідомо.

done();
