// Стенд: НАЗВА СЕЛА ↔ НАЗВА ЗУПИНКИ В РОЗКЛАДІ ПЕРЕВІЗНИКА.
//
// 🔴 НАВІЩО ЦЕЙ СТОРОЖ. 22.08 виявилось, що вся робота над визначенням місця
// людини впиралась у те, чого ніхто не перевіряв: наші назви сіл і назви
// зупинок у перевізника ПРОСТО НЕ ЗБІГАЛИСЬ. «Хром'яків» проти «Хромяків»,
// «Метельне» проти «Мительно». Звірка йде рядок-у-рядок, тож житель такого
// села не отримував капсули автобуса взагалі — хоч як точно ми визначили, де
// він. «Хромяків» при цьому шоста за завантаженістю зупинка в усьому розкладі.
//
// 🔑 ЧОМУ ЦЕ ПЕРЕВІРЯЄТЬСЯ НА ЖИВОМУ РОЗКЛАДІ, А НЕ НА ВИГАДАНОМУ. Назви пише
// перевізник, і завтра він може написати інакше — це не наш код, який ми
// контролюємо, а чужі дані, які змінюються самі. Стенд на вигаданому наборі
// зеленів би вічно; на справжньому файлі він падає в той день, коли перевізник
// перейменує зупинку, і задовго до того, як хтось поскаржиться.
//
// ⚠️ Розклад оновлюється щодня автоматично, тож «є 17 сіл» перевіряти не можна:
// частина сіл у деякі дні просто не має рейсів. Питання ставимо інше — чи МОЖЕ
// кожне село знайти собі зупинку посадки.
import { readFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import { reporter } from './_lib.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const { ok, done } = reporter();

const { SETTLEMENTS, canonicalPlace } = await import(
  join(ROOT, 'src/core/settlements.js').replace(/^/, 'file://'));

// Назви зупинок беремо з ТОГО САМОГО файлу, який читає застосунок.
const розклад = JSON.parse(readFileSync(join(ROOT, 'data/schedule.json'), 'utf8'));
const сирі = new Set();
for (const день of Object.values(розклад.days || {})) {
  for (const р of (день.routes || [])) {
    for (const з of (р.stops || [])) сирі.add(typeof з === 'string' ? з : з?.name);
  }
}
const зупинки = new Set([...сирі].filter(Boolean).map(canonicalPlace));

// 🔴 ГОЛОВНА ПЕРЕВІРКА. Село, яке перевізник обслуговує, мусить знаходитись за
// НАШОЮ назвою. Саме тут і жила вада: обидві сторони були «правильні», просто
// написані по-різному, і жодна перевірка їх не звіряла.
const обслуговує = н => зупинки.has(н);
const свої = SETTLEMENTS.filter(обслуговує);
ok('🔴 села з рейсами знаходяться за НАШОЮ назвою', свої.length >= 12,
   `${свої.length} із ${SETTLEMENTS.length}: ${свої.join(', ')}`);

// 🛑 Іменно ці два і були зламані. Перевіряємо їх поіменно, бо загальне число
// вище лишиться зеленим, якщо зламається одне з дванадцяти.
for (const [село, як_пише_перевізник] of [["Хром'яків", 'Хромяків'], ['Метельне', 'Мительно']]) {
  ok(`🔴 «${як_пише_перевізник}» у перевізника = «${село}» у нас`,
     сирі.has(як_пише_перевізник) && canonicalPlace(як_пише_перевізник) === село
       && обслуговує(село),
     сирі.has(як_пише_перевізник) ? 'зведено' : 'перевізник більше так не пише — звірити');
}

// ⚠️ Апостроф — це ПРАВИЛО, а не список: перевіряємо всі три друкарські
// варіанти, включно з тим, якого в даних сьогодні немає. Саме «сьогодні немає»
// і є причина перевірити: зʼявиться — має працювати без правок.
ok("апостроф не робить із села інше село",
   ["Хром'яків", 'Хром’яків', 'Хромяків', 'ХРОМЯКІВ'].every(в => canonicalPlace(в) === "Хром'яків"),
   'три написання + верхній регістр');

// 🛑 «Одеради АЗ» — ОКРЕМА зупинка, а не інше написання «Одерад»: у розкладі
// вони живуть поруч. Злити їх означало б пообіцяти зупинку там, де її немає.
ok('🔴 «Одеради АЗ» не зливається з «Одеради»',
   canonicalPlace('Одеради АЗ') === 'Одеради АЗ' && сирі.has('Одеради') && сирі.has('Одеради АЗ'),
   'дві різні зупинки в одному селі');

// «Хорлупи» — справжня чужа зупинка, і вона мусить лишитись собою. Перевірка
// прикриває порядок дій усередині: якби суфікс « пов.» зрізався ДО пошуку в
// таблиці, «Хорлупи пов.» перетворились би на «Хорлупи».
ok('«Хорлупи» лишаються собою, а «Хорлупи пов.» — ні',
   canonicalPlace('Хорлупи') === 'Хорлупи' && canonicalPlace('Хорлупи пов.') === "Хром'яків",
   'порядок: спершу таблиця, потім суфікс');

// Чужі назви не наші — не вигадуємо за перевізника.
ok('назви поза громадою лишаються як є',
   ['Луцьк', 'Рівне', 'Ківерці', 'Клевань'].every(н => canonicalPlace(н) === н));

// 🔴 ПʼЯТЬ СІЛ БЕЗ РЕЙСІВ — не поломка, а факт: туди не їздять. Перевіряємо не
// «їх немає» (це просто опис даних), а що ми ПРО ЦЕ ЗНАЄМО — тобто що список
// незакритих сіл саме такий, як ми думаємо. Зʼявиться туди рейс — стенд
// почервоніє, і це буде добра новина, яку інакше ніхто б не помітив.
const без = SETTLEMENTS.filter(н => !обслуговує(н));
ok('села без жодного рейсу — рівно ті, які ми знаємо',
   без.join(',') === ['Горянівка', 'Залісоче', 'Мощаниця', 'Путилівка', 'Ставок'].join(','),
   без.length ? без.join(', ') : 'таких немає');

done();
