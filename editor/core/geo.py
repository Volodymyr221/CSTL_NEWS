"""Гео-довідка громади — ОДНЕ джерело правди про масштаб для всіх письменників.

🔴 Навіщо цей модуль (20.08.2026). Вова прочитав чернетку про День Незалежності
України і сказав: «пише „Для нас, жителів Олики“, а це стосується не тільки
жителів Олики — всієї громади». Помилка не в стилі, а в тому, що агент стрічки
про громаду НЕ ЗНАВ НІЧОГО: у промті святкового письменника стояло «редактор
локального медіа містечка Олика … для жителів громади» — два різні масштаби в
одному реченні і жодного правила, коли який. Агент обрав перший.

🔑 Тому довідка не переписується прозою в третьому місці, а ЧИТАЄТЬСЯ з
`scripts/hromada_config.json`, який уже веде новинний агент. Друга копія списку
сіл і статусу центру розійшлась би з першою при першій же зміні — а розходження
в такому файлі означає, що агент почне впевнено писати неправду про рідне село.

⚠️ Пастка, в яку ледь не втрапили: сторонній ШІ, якого питали поради, описав
ієрархію як «Олика → село». Олика — МІСТО з 17.04.2025 (до того смт). Якби
правило написали з тієї підказки, агент почав би писати «село Олика» — помилку,
яку земляк помітить миттєво і яка гірша за ту, що виправляємо.
"""
import json
import re
from pathlib import Path

КОНФІГ = Path("scripts/hromada_config.json")

# 🛑 Запас на випадок, коли конфіг недоступний. Він НЕ вигадує сіл: порожній
# список краще за вигаданий, бо вигаданим агент почне користуватись як фактом.
_ЗАПАС = {
    "name": "Олицька громада",
    "full_name_variants": ["Олицька міська громада", "Олицька селищна громада"],
    "center": "Олика",
    "center_status": "місто (з 17.04.2025, раніше смт)",
    "district": "Луцький район",
    "oblast": "Волинська область",
    "villages": [],
}

_кеш = None


def громада() -> dict:
    """Структура громади з конфіга новинного агента (кешується на процес)."""
    global _кеш
    if _кеш is None:
        try:
            _кеш = json.loads(КОНФІГ.read_text(encoding="utf-8"))["hromada"]
        except Exception as e:
            print(f"  ⚠ гео-довідка: не прочитав {КОНФІГ} ({e}) — беру запасну")
            _кеш = dict(_ЗАПАС)
    return _кеш


def села() -> list:
    return list(громада().get("villages") or [])


# ── МАСШТАБ ────────────────────────────────────────────────────────────────
# Чотири рівні, від найширшого. Назва масштабу — це відповідь на питання «про
# кого цей пост», і саме вона визначає, від чийого імені можна говорити «ми».
НАЦІОНАЛЬНИЙ = "національний"
ГРОМАДА = "громада"
ЦЕНТР = "центр"
СЕЛО = "село"

# Свята з `data/holidays.json` за родом. 📐 Заміряно 20.08: усі 33 свята мають
# kind державне/релігійне/народне — ЖОДНОГО місцевого. Тобто святковий пост за
# замовчуванням національний, і звуження до Олики в ньому хибне ЗАВЖДИ.
_РІД_НАЦІОНАЛЬНИЙ = ("державн", "релігійн", "народн", "міжнародн")


def масштаб_свята(h: dict) -> str:
    """Масштаб святкового поста. Місцеве свято розпізнається за згадкою громади
    у назві — щоб «День Олики», якщо його колись додадуть, не лікували правилом
    для Дня Незалежності."""
    текст = f"{h.get('title', '')} {h.get('kind', '')}"
    if re.search(r"Олиц|Олик", текст):
        return ЦЕНТР
    if _згадане_село(текст):
        return СЕЛО
    рід = (h.get("kind") or "").lower()
    if any(r in рід for r in _РІД_НАЦІОНАЛЬНИЙ):
        return НАЦІОНАЛЬНИЙ
    # Невідомий рід — беремо ШИРШИЙ масштаб. Помилитись у бік «сказав про всіх»
    # дешевше, ніж у бік «виключив сусіднє село зі свого ж свята».
    return НАЦІОНАЛЬНИЙ



# ⚠️ Село в тексті стоїть у відмінку («храм у МетельнОМУ»), тож рівність назві
# не спрацює. Порівнюємо за основою — але лише в довгих назв: «Ставок» і
# «Котів» вкорочувати НЕ можна, бо «став» і «кот» ловили б ставок і котів.
# Та сама пастка вже описана в `scripts/parse_rss.py` — не наступаємо вдруге.
def _основа(назва: str) -> str:
    return назва[:-1] if len(назва) >= 7 else назва


def _згадане_село(текст: str) -> str:
    н = (текст or "").lower()
    for с in села():
        if _основа(с).lower() in н:
            return с
    return ""

# ── ПРО ЩО ТЕМА: СЕЛО / ОЛИКА / ВСЯ ГРОМАДА ────────────────────────────────
#
# 🔴 Заведено 28.08.2026 на замовлення Вови: «всі пости мають стосуватися не тільки
# Олики, а всієї Олицької громади… 60% Олика, 40% села».
#
# 📐 ЧОМУ ЦЕ ПОТРІБНО, ЧИСЛАМИ. Заміряно по опублікованих постах обох спільнот: із
# СЕМИ постів про місце — **сім про Олику, про села НУЛЬ**. Тобто перекос був не
# 90/10, а 100/0. У новинного агента правило балансу стоїть від початку (50/50 у
# промті), а спільноти поїхали без нього взагалі.
#
# ⚠️ ПАСТКА, ЧЕРЕЗ ЯКУ ЦЕ НЕ ОДИН РЯДОК. «Олицька громада» містить «Олиц», тобто
# наївна перевірка на «Олик|Олиц» зарахувала б пост ПРО ВСЮ ГРОМАДУ до центру — і
# правило почало б душити рівно ті пости, заради яких воно й заводилось. Тому назву
# громади прибираємо з тексту ПЕРЕД пошуком центру.
_ГРОМАДА_НАЗВА = re.compile(r"олиць\w*\s+(?:міськ\w+\s+|селищн\w+\s+)?громад\w*", re.IGNORECASE)
_ЦЕНТР_ЗГАДКА = re.compile(r"олиц|олик", re.IGNORECASE)


def місце_теми(текст: str) -> str:
    """Про що цей матеріал: `СЕЛО` · `ЦЕНТР` (Олика) · `ГРОМАДА` (уся, або незрозуміло).

    🔑 Порядок перевірок НЕ довільний. Село першим: пост «Метельне — храм 1810 року»
    згадує і село, і громаду, і його адреса — село. Якби першим стояв центр, будь-яка
    згадка Олицької громади поруч перетягувала б сільський пост у центр.

    🛑 Незрозуміле віддаємо в ГРОМАДУ, а не в центр. Помилка «порахував як загальний»
    коштує лише неточності в пропорції; помилка «порахував як Олику» ЗАНИЖУЄ частку
    сіл, тобто працює проти самого правила.
    """
    т = текст or ""
    if _згадане_село(т):
        return СЕЛО
    без_громади = _ГРОМАДА_НАЗВА.sub(" ", т)
    if _ЦЕНТР_ЗГАДКА.search(без_громади):
        return ЦЕНТР
    return ГРОМАДА


def місце_матеріалу(тема: str, факти=None) -> str:
    """Про що матеріал, коли крім теми є ще й факти. ТЕМА ВАЖИТЬ БІЛЬШЕ.

    🔴 ЗАВЕДЕНО 28.08 ПІСЛЯ ЗАМІРУ, А НЕ ЗАЗДАЛЕГІДЬ. Перший живий план дав три
    теми, і `місце_теми(тема + усі факти)` назвала СЕЛОМ усі три — зокрема
    «Олицька ординація: як маєток Радзивіллів отримав особливий правовий статус».
    Причина: серед семи фактів один згадує цуманський тартак, а «Цуман» — село.
    Одна побіжна згадка перебивала заголовок.
    🛑 Наслідок був тихий і гірший за помилку в одному пості: якщо СЕЛОМ стає все
    підряд, пропорція «60% Олика / 40% села» міряє сміття, і правило, яке Вова
    прямо замовив, перестає означати будь-що — лишаючись при цьому зеленим.

    🔑 Порядок: спершу вирішує ЗАГОЛОВОК — це і є предмет матеріалу. Факти
    підключаються, лише коли заголовок не вирішує нічого (`ГРОМАДА`), і саме
    заради випадку, описаного в `plan.py`: у теми «Фото: вулиця біля костелу»
    назви села немає, а в спостереженнях вона цілком може бути.
    ⚠️ `місце_теми` навмисно лишається як була: для ОДНОГО тексту про одне місце
    її логіка правильна, і два різні правила тут були б гірші за одне з надбудовою.
    """
    за_темою = місце_теми(тема or "")
    if за_темою != ГРОМАДА:
        return за_темою
    разом = (тема or "") + " " + " ".join(факти or [])
    return місце_теми(разом)


# ── ЗВУЖЕННЯ ───────────────────────────────────────────────────────────────
# Пара (що знайти, на що замінити). Заміна лише там, де вона однозначна:
# «жител*/мешканц* Олики» → та сама форма слова + «Олицької громади».
# 🔑 Формулювання підказав сам Вова: «в цьому випадку було б правильно написати
# „Для нас, жителів Олицької громади“» — тому саме воно, а не нейтральне
# «для кожного з нас», яке радив сторонній ШІ.
# Зворотне посилання \1 зберігає велику літеру саме, тож окремий шаблон для
# «Жителі» з великої не потрібен — це була б друга копія того самого правила.
_ЗАМІНИ = [
    (re.compile(r"\b(жител|мешканц)(\w*)\s+Олики\b", re.IGNORECASE),
     r"\1\2 Олицької громади"),
]

# Те, що звужує, але автозаміні НЕ піддається: відмінок довелось би вгадувати
# («оличани зберуться» ≠ «жителів Олицької громади зберуться»). Такі місця лише
# називаємо вголос — виправить людина в кабінеті.
_ПОПЕРЕДЖЕННЯ = [
    (re.compile(r"\bолича[нм]\w*", re.IGNORECASE), "«оличани» звужує до центру"),
    (re.compile(r"\bу нашому селі\b", re.IGNORECASE), "«наше село» — Олика має статус міста"),
    (re.compile(r"\bсел[оа]\s+Олик\w*", re.IGNORECASE), "«село Олика» — Олика місто з 17.04.2025"),
    (re.compile(r"\bсмт\s+Олик\w*", re.IGNORECASE), "«смт Олика» застаріле — місто з 17.04.2025"),
]


def виправити(текст: str, м: str):
    """(виправлений текст, [що змінили], [про що попередити]).

    Виправляє ЛИШЕ на національному масштабі: у пості про саму Олику
    «жителі Олики» — правильно, і чіпати його було б зіпсуттям."""
    зміни, застереження = [], []
    for шаблон, чому in _ПОПЕРЕДЖЕННЯ:
        if шаблон.search(текст or ""):
            застереження.append(чому)
    if м != НАЦІОНАЛЬНИЙ or not текст:
        return текст, зміни, застереження
    for шаблон, заміна in _ЗАМІНИ:
        нове, n = шаблон.subn(заміна, текст)
        if n:
            зміни.append(f"{шаблон.pattern} ×{n}")
            текст = нове
    текст, п = _прибрати_надлишок(текст)
    зміни += п
    return текст, зміни, застереження


# 🔴 Знайдено 20.08 на живому тексті, руками. Опублікований пост казав «Для
# мешканців ОЛИКИ та навколишніх сіл» — і це було ПРАВИЛЬНО. Проста заміна
# зробила з нього «мешканців ОЛИЦЬКОЇ ГРОМАДИ та навколишніх сіл», тобто
# нісенітницю: села і Є громада, вони не «навколо» неї.
# 🔑 Урок ширший за один рядок: заміна назви змінює СМИСЛ сусіднього тексту, і
# автозаміна без прибирання за собою вміє зіпсувати справне речення. Тому після
# кожної заміни знімаємо хвіст, який щойно став надлишковим.
_НАДЛИШОК = re.compile(
    r"(Олицької громади)\s+(?:та|і|й)\s+(?:навколишн\w+|сусідн\w+|довколишн\w+|прилегл\w+)\s+сіл",
    re.IGNORECASE)


def _прибрати_надлишок(текст: str):
    нове, n = _НАДЛИШОК.subn(r"\1", текст or "")
    return нове, ([f"надлишок «та навколишніх сіл» ×{n}"] if n else [])


# ── ДОВІДКА ДЛЯ ПРОМТА ─────────────────────────────────────────────────────

def довідка(м: str = None) -> str:
    """Блок для промта: структура громади + правило масштабу для цього поста."""
    г = громада()
    рядки = [
        "=== ГЕОГРАФІЯ ГРОМАДИ (факти, не вигадувати) ===",
        f"Громада: {г.get('name')} ({', '.join(г.get('full_name_variants') or [])}).",
        f"Центр громади: {г.get('center')} — {г.get('center_status')}. "
        f"НЕ село і НЕ смт.",
        f"Район: {г.get('district')}. Область: {г.get('oblast')}.",
    ]
    с = села()
    if с:
        рядки.append(f"Села громади ({len(с)}): {', '.join(с)}.")
    рядки += [
        "",
        "ІЄРАРХІЯ: село громади ⊂ Олицька громада ⊃ Олика (центр). "
        "Олика — ЧАСТИНА громади, а не синонім громади.",
        "",
        "=== МАСШТАБ І АДРЕСА ===",
        "Перед першим реченням визнач, ПРО КОГО пост, і звертайся саме до них:",
        "  • подія країни (державне чи релігійне свято, закон, війна) →",
        "    «для нас, жителів Олицької громади» або «для кожного з нас». "
        "НЕ «жителі Олики» — це виключає 16 сіл із їхнього ж свята.",
        "  • справа всієї громади (рада, бюджет, дороги, школи) → «жителі Олицької громади».",
        "  • подія в самій Олиці (замок, костел, ярмарок у центрі) → «жителі Олики» — доречно.",
        "  • подія в селі → називай СЕЛО: «у Метельному», «в Одерадах». "
        "Не підміняй його громадою і не приписуй громаді те, що сталось в одному селі.",
        "",
        "🛑 Не звужуй загальне і не узагальнюй місцеве. Це дві однакові помилки.",
    ]
    if м:
        рядки += ["", f"МАСШТАБ ЦЬОГО ПОСТА: {м}.", _адреса(м)]
    рядки.append("=== КІНЕЦЬ ГЕО-ДОВІДКИ ===")
    return "\n".join(рядки)


def _адреса(м: str) -> str:
    return {
        НАЦІОНАЛЬНИЙ: "Отже звертайся до ВСІЄЇ громади: «для нас, жителів Олицької "
                      "громади». Фраза «жителі Олики» тут заборонена.",
        ГРОМАДА: "Отже звертайся до всієї громади: «жителі Олицької громади».",
        ЦЕНТР: "Пост про саму Олику — «жителі Олики» тут доречно.",
        СЕЛО: "Пост про конкретне село — назви це село, не підміняй громадою.",
    }.get(м, "")
