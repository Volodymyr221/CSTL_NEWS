"""Правило Вови про час події — ОДНЕ на всіх агентів, що пишуть тексти.

🗣️ Вова, 26.10.2026: «важливо правильно вказувати дати і орієнтуватися, тобто якщо
щось вже відбулось, то не треба писати в новині що буде тільки, бо сама по собі
новина постилась раніше ніж її знайшов агент».

📐 До 26.10 ЖОДЕН промпт не називав сьогоднішньої дати: модель бачила анонс
«20 жовтня відбудеться…» і не мала чим звірити, що 20 жовтня вже минуло. Перший же
прогін після правила спіймав і тонший випадок: тест «з 26 до 30 жовтня» агент
спільноти написав як «проходитиме», хоча 26-те — це сьогодні, тобто «триває».

🔑 Окремий модуль, а не текст у кожному агенті: новинний (`scripts/ai_news_agent.py`)
і агент спільнот (`editor/writers/brand_writer.py`) кличуть ЦЮ функцію — дві копії
правила колись розійшлися б.
⚠️ Дата — за Києвом: події громади живуть за київським часом, а раннер GitHub — в UTC
(о 23:30 за Києвом там ще «вчора»).
"""
import datetime as _dt

_МІСЯЦІ = ["січня", "лютого", "березня", "квітня", "травня", "червня", "липня",
           "серпня", "вересня", "жовтня", "листопада", "грудня"]


def _зараз() -> _dt.datetime:
    try:
        from zoneinfo import ZoneInfo
        return _dt.datetime.now(ZoneInfo("Europe/Kyiv"))
    except Exception:
        return _dt.datetime.now(_dt.timezone.utc) + _dt.timedelta(hours=2)


def правило_часу() -> str:
    now = _зараз()
    сьогодні = f"{now.day} {_МІСЯЦІ[now.month - 1]} {now.year}"
    return (
        f"🔴 ЧАС І ДАТИ. СЬОГОДНІ — {сьогодні} ({now:%Y-%m-%d}, Київ). Текст про подію могли\n"
        "опублікувати раніше, ніж ти його отримав, тож час події звіряй із СЬОГОДНІШНЬОЮ\n"
        "датою, а не з тим, як написано у джерелі:\n"
        "  • подія ВЖЕ ВІДБУЛАСЯ (її дата раніше за сьогодні) — пиши в МИНУЛОМУ часі\n"
        "    («відбувся», «пройшла», «зібрала»). Заборонено «відбудеться», «запрошуємо»,\n"
        "    «буде», «незабаром», «чекаємо» — у заголовку, анонсі й тексті однаково;\n"
        "  • подія ТРИВАЄ (сьогодні між її початком і кінцем) — теперішній час: «триває»,\n"
        "    «стартував», «ще можна до 30 жовтня»;\n"
        "  • джерело — лише АНОНС, а подія вже минула: НЕ вигадуй, як вона пройшла. Пиши\n"
        "    «на 20 жовтня було заплановано…» або пропусти, якщо без запрошення текст\n"
        "    втрачає сенс;\n"
        "  • подія ще ПОПЕРЕДУ — майбутній час і ТОЧНА дата («25 листопада відбудеться…»);\n"
        "  • дату події визначити не вдалось — не пиши ні «буде», ні «відбувся»."
    )
