"""ПРАВДИВІСТЬ ФАКТУ — ОДНЕ МІСЦЕ ПРАВДИ НА ВСІХ АГЕНТІВ.

🔴 Вимога Вови 29.08 дослівно: «агент не має видумувати події чи будь які назви,
інформація має бути достовірна. На цьому ставимо акцент, на всіх агентах які
пишуть нам статті/пости».

🔑 ЧОМУ ОКРЕМИЙ МОДУЛЬ, А НЕ КОПІЯ В КОЖНОМУ АГЕНТІ. Фактів торкаються двоє:
`scripts/ai_news_agent.py` (збирає історію вебпошуком) і `editor/sources/plan.py`
(будує теми зі статей, подій і фотоархіву). Копія правила в обох розійшлася б —
у цьому проєкті таке вже ставалось зі списками антиспаму, і симптом був
найгіршого виду: half-працює, ніхто не помічає.

🛑 ІМПОРТУВАТИ ЖОРСТКО, НЕ `try/except`. Решта пакета `editor` підключається в
агента фейл-софтом (нема семантики — працюємо далі). Тут так НЕ МОЖНА: якщо
модуль не підвантажиться, рубіж зникне МОВЧКИ, і агент писатиме неправду, поки
хтось випадково не помітить. Краще впасти.
"""

import re

# ── ЗАСТАРІЛЕ ЧИСЛО, ПОДАНЕ ЯК СЬОГОДНІШНЄ ──────────────────────────────────
#
# 📐 Привід — знімок Вови 29.08. Спільнота «Історія Громади» написала «Сьогодні
# в Жорнищі 959 людей», а Google на те саме питання відповідає «959 осіб (за
# даними перепису 2001 року)».
#
# 🔑 ЦЕ НЕ ГАЛЮЦИНАЦІЯ — І САМЕ ТОМУ НЕБЕЗПЕЧНО. Число правильне, джерело
# справжнє, вигаданого нічого немає. Загубилось РІВНО ОДНЕ слово — про давність.
# Наявні рубежі такого не ловлять за побудовою: фільтр загальних знань шукає
# здогади («ймовірно», «як відомо»), а тут упевнене твердження; правило
# «невпевненість джерела зберігай» теж мимо — джерело було цілком упевнене,
# просто чверть століття тому.
#
# 📐 І це КЛАС, а не поодинокий випадок: в Україні відбувся ОДИН перепис — 2001
# року. Тобто будь-яке число населення у Вікіпедії старше за 25 років, і слово
# «сьогодні» біля нього хибне ЗАВЖДИ, без винятків.
#
# ⚠️ ОЗНАКА НАВМИСНО ВУЗЬКА, і друга половина важливіша за першу. Ловимо лише
# маркер теперішності ПОРУЧ ІЗ ЧИСЛОМ змінної величини. «І сьогодні село
# входить до складу громади» — правда без числа, не чіпаємо. «Сьогодні тут
# працює школа» — теж. Ширша ознака викидала б правдиві факти, і пости біднішали
# б мовчки: рівно та шкода, від якої ми й захищаємось.
_ТЕПЕРІШНІСТЬ = r"(сьогодні|сьогоднішн|нині|наразі|зараз|тепер|станом на)"
_ЗМІННА_ВЕЛИЧИНА = (r"\d[\d\s ]*\s*"
                    r"(осіб|люд(ей|и)|жител|мешканц|двор|учн|господарств|"
                    r"га\b|гектар|км²|кв\.?\s*км|грн|гривень)")
_РІК = r"\b(1[5-9]\d\d|20\d\d)\b"

# ⚠️ Нечутливість до регістру — АРГУМЕНТОМ `re.I`, а не вставкою `(?i)` посеред
# виразу: у шаблоні з двох гілок друга така вставка падає з
# `global flags not at the start`. Спіймано власним прогоном 29.08.
_НЕДАТОВАНЕ_ЧИСЛО = re.compile(
    _ТЕПЕРІШНІСТЬ + r"[^.]{0,120}?" + _ЗМІННА_ВЕЛИЧИНА
    + r"|" + _ЗМІННА_ВЕЛИЧИНА + r"[^.]{0,60}?" + _ТЕПЕРІШНІСТЬ, re.I)


def факт_недатоване_число(рядок: str) -> bool:
    """Чи видає рядок ЗАСТАРІЛЕ число за сьогоднішній стан.

    Віддає False, якщо рік названо в самому реченні: тоді читач бачить, на який
    момент число дійсне, і претензій до тексту немає.
    """
    р = рядок or ""
    if re.search(_РІК, р):
        return False
    return bool(_НЕДАТОВАНЕ_ЧИСЛО.search(р))


def факти_без_недатованих(факти, лог=None) -> list:
    """Прибирає з переліку рядки, що видають застаріле число за теперішнє.

    🛑 Викидаємо РЯДОК, а не всю тему: решта фактів лишається, пост виходить
    біднішим — але правдивим. Спростування коштує дорожче за коротший пост.
    """
    вихід = []
    for ф in (факти or []):
        т = str(ф).strip()
        if not т:
            continue
        if факт_недатоване_число(т):
            if лог:
                лог(f"  ✂ число без року, подане як сьогоднішнє: «{т[:70]}…»")
            continue
        вихід.append(т)
    return вихід
