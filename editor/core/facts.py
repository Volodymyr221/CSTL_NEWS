"""ПРАВДИВІСТЬ ФАКТУ — ОДНЕ МІСЦЕ ПРАВДИ НА ВСІХ АГЕНТІВ.

🔴 Вимога Вови 29.08 дослівно: «агент не має видумувати події чи будь які назви,
інформація має бути достовірна. На цьому ставимо акцент, на всіх агентах які
пишуть нам статті/пости».

🔑 ЧОМУ ОКРЕМИЙ МОДУЛЬ, А НЕ КОПІЯ В КОЖНОМУ АГЕНТІ. Фактів торкаються двоє:
`scripts/ai_news_agent.py` (збирає історію вебпошуком) і `editor/sources/plan.py`
(будує теми зі статей, подій і фотоархіву). Копія правила в обох розійшлася б —
у цьому проєкті таке вже ставалось зі списками антиспаму, і симптом був
найгіршого виду: half-працює, ніхто не помічає.

🛑 ІМПОРТУВАТИ ЖОРСТКО, НЕ `try/except`. Решта пакета `editor` підключається в
агента фейл-софтом (нема семантики — працюємо далі). Тут так НЕ МОЖНА: якщо
модуль не підвантажиться, рубіж зникне МОВЧКИ, і агент писатиме неправду, поки
хтось випадково не помітить. Краще впасти.
"""

import re

# ── ЗАСТАРІЛЕ ЧИСЛО, ПОДАНЕ ЯК СЬОГОДНІШНЄ ──────────────────────────────────
#
# 📐 Привід — знімок Вови 29.08. Спільнота «Історія Громади» написала «Сьогодні
# в Жорнищі 959 людей», а Google на те саме питання відповідає «959 осіб (за
# даними перепису 2001 року)».
#
# 🔑 ЦЕ НЕ ГАЛЮЦИНАЦІЯ — І САМЕ ТОМУ НЕБЕЗПЕЧНО. Число правильне, джерело
# справжнє, вигаданого нічого немає. Загубилось РІВНО ОДНЕ слово — про давність.
# Наявні рубежі такого не ловлять за побудовою: фільтр загальних знань шукає
# здогади («ймовірно», «як відомо»), а тут упевнене твердження; правило
# «невпевненість джерела зберігай» теж мимо — джерело було цілком упевнене,
# просто чверть століття тому.
#
# 📐 І це КЛАС, а не поодинокий випадок: в Україні відбувся ОДИН перепис — 2001
# року. Тобто будь-яке число населення у Вікіпедії старше за 25 років, і слово
# «сьогодні» біля нього хибне ЗАВЖДИ, без винятків.
#
# ⚠️ ОЗНАКА НАВМИСНО ВУЗЬКА, і друга половина важливіша за першу. Ловимо лише
# маркер теперішності ПОРУЧ ІЗ ЧИСЛОМ змінної величини. «І сьогодні село
# входить до складу громади» — правда без числа, не чіпаємо. «Сьогодні тут
# працює школа» — теж. Ширша ознака викидала б правдиві факти, і пости біднішали
# б мовчки: рівно та шкода, від якої ми й захищаємось.
_ТЕПЕРІШНІСТЬ = r"(сьогодні|сьогоднішн|нині|наразі|зараз|тепер|станом на)"
_ЗМІННА_ВЕЛИЧИНА = (r"\d[\d\s ]*\s*"
                    r"(осіб|люд(ей|и)|жител|мешканц|двор|учн|господарств|"
                    r"га\b|гектар|км²|кв\.?\s*км|грн|гривень)")
_РІК = r"\b(1[5-9]\d\d|20\d\d)\b"

# ⚠️ Нечутливість до регістру — АРГУМЕНТОМ `re.I`, а не вставкою `(?i)` посеред
# виразу: у шаблоні з двох гілок друга така вставка падає з
# `global flags not at the start`. Спіймано власним прогоном 29.08.
_НЕДАТОВАНЕ_ЧИСЛО = re.compile(
    _ТЕПЕРІШНІСТЬ + r"[^.]{0,120}?" + _ЗМІННА_ВЕЛИЧИНА
    + r"|" + _ЗМІННА_ВЕЛИЧИНА + r"[^.]{0,60}?" + _ТЕПЕРІШНІСТЬ, re.I)


# ── ВІДНОСНИЙ ЧАС БЕЗ ЯКОРЯ ────────────────────────────────────────────────
#
# 🔴 Заведено 05.09 — сусідній клас до недатованого числа, той самий корінь.
# Агент пише текст, привʼязаний до МОМЕНТУ НАПИСАННЯ, а показуємо ми його
# потім. «Цьогоріч зібрали 40 тонн» через чотири місяці означає вже інший рік;
# «нещодавно відкрили амбулаторію» у тексті місячної давності бреше про
# свіжість. Вигаданого знову нічого немає — постарів сам текст.
#
# 📐 ЗАМІРЯНО НА 400 СТАТТЯХ `data/articles.json` (854 КБ), 05.09 — саме заміри
# вирішили, які слова сюди НЕ беруться:
#   • «щойно» ВИКИНУТО — у корпусі це підрядне речення часу, а не давність:
#     «Щойно ситуація дозволяла — рятувальники поверталися».
#   • «невдовзі» не беремо взагалі: обіцянка про майбутнє це інший клас, і
#     хибною вона стає з іншої причини, ніж застарілий текст.
# ✅ Решта влучань корпусу — справжні за класом: «торік підприємство отримало
# 131 мільйон», «цьогоріч поступився місцем», «останнім часом активізувались».
_ВІДНОСНИЙ_ЧАС = re.compile(
    r"(?i)(нещодавно|останнім часом|донедавна|віднедавна|цими днями|на днях|"
    r"цьогоріч|торік|"
    r"(цього|минулого|наступного|поточного) (року|тижня|місяця)|"
    r"(цьому|минулому|наступному) (році|тижні|місяці))")


# ── ПОСАДА, ПОДАНА В ТЕПЕРІШНЬОМУ ЧАСІ ─────────────────────────────────────
#
# 🔴 Третій сусід того самого класу. «Громаду очолює Петренко» правдиве рівно
# до наступних виборів або призначення, а текст лишається в застосунку далі.
#
# ⚠️ ОЗНАКА ВИМАГАЄ ДВОХ РЕЧЕЙ ОДРАЗУ — дієслова посади І установи поруч,
# так само як недатоване число вимагає маркера теперішності І величини.
#
# 🛑 І ВАЖИТЬ ТУТ САМЕ ДРУГА ПОЛОВИНА — це виправлення власної помилки, зробленої
# при написанні цього ж модуля 05.09. Спершу я побачив у корпусі «особою, яка
# КЕРУЄ транспортним засобом у стані спʼяніння» та «місія МВФ НА ЧОЛІ з Гевіном
# Греєм», вирішив, що винні самі дієслова, і викинув обидва зі списку. Мутаційна
# перевірка це спростувала: повернув їх — і корпус дав ТІ САМІ 1 влучання, нуль
# нових хибних. Обидва речення відсіює відсутність УСТАНОВИ поруч, а не список
# дієслів. Тобто я приписав заслугу не тій половині ознаки і мало не втратив
# справжні влучання на кшталт «школою керує директор Іваненко».
# ➡️ Урок ширший за цей рядок: перш ніж звужувати ознаку, доведи мутацією, що
# звуження справді робить роботу — інакше воно лише коштує влучань.
_ПОСАДА_ТЕПЕР = (r"(очолює|керує|на чолі|обіймає посаду|"
                 r"є (головою|старостою|директором|настоятелем|завідувач))")
_УСТАНОВА = (r"(громад|сільрад|міськрад|\bрад[аиуоі]\b|школ|ліце|гімназ|"
             r"лікарн|амбулатор|бібліотек|музе|клуб|парафі|церкв|храм|"
             r"господарств|підприємств|садоч|дитсад|старостат|"
             r"будинк[уа] культури)")
_ПОСАДА_БЕЗ_ДАТИ = re.compile(
    _ПОСАДА_ТЕПЕР + r"[^.]{0,90}?" + _УСТАНОВА
    + r"|" + _УСТАНОВА + r"[^.]{0,90}?" + _ПОСАДА_ТЕПЕР, re.I)


def факт_недатоване_число(рядок: str) -> bool:
    """Чи видає рядок ЗАСТАРІЛЕ число за сьогоднішній стан.

    Віддає False, якщо рік названо в самому реченні: тоді читач бачить, на який
    момент число дійсне, і претензій до тексту немає.
    """
    р = рядок or ""
    if re.search(_РІК, р):
        return False
    return bool(_НЕДАТОВАНЕ_ЧИСЛО.search(р))


def факт_відносний_час(рядок: str) -> bool:
    """Чи привʼязаний рядок до МОМЕНТУ НАПИСАННЯ замість дати.

    Той самий виняток, що і в числа: рік у реченні знімає підозру, бо читач
    бачить якір («торік підприємство отримало більше, ніж у 2023-му»).
    """
    р = рядок or ""
    if re.search(_РІК, р):
        return False
    return bool(_ВІДНОСНИЙ_ЧАС.search(р))


def факт_посада_без_дати(рядок: str) -> bool:
    """Чи подає рядок посаду як теперішню, не сказавши, на який момент."""
    р = рядок or ""
    if re.search(_РІК, р):
        return False
    return bool(_ПОСАДА_БЕЗ_ДАТИ.search(р))


# 🔑 ОДНЕ МІСЦЕ, ДЕ ПЕРЕЛІЧЕНІ ВСІ КЛАСИ. Споживач питає ПРИЧИНУ, а не три
# ознаки поспіль: інакше додавання четвертого класу означало б обхід усіх
# споживачів — рівно та розсинхронізація, від якої цей модуль і заведено.
_КЛАСИ = (
    (факт_недатоване_число, "число без року, подане як сьогоднішнє"),
    (факт_відносний_час,    "час відносно моменту написання, без дати"),
    (факт_посада_без_дати,  "посада як теперішня, без дати"),
)


def причина_застарілості(рядок: str):
    """Чому цей рядок постаріє мовчки — або None, якщо він тримається сам.

    🔑 Спільний корінь усіх трьох класів: текст привʼязаний до моменту, коли
    його написали, а показуємо ми його потім. Вигаданого немає в жодному —
    саме тому попередні рубежі («не вигадуй», «зберігай невпевненість») їх не
    ловлять, і саме тому вони небезпечні.
    """
    for ознака, причина in _КЛАСИ:
        if ознака(рядок):
            return причина
    return None


def факти_без_застарілих(факти, лог=None) -> list:
    """Прибирає з переліку рядки, що постаріють мовчки.

    🛑 Викидаємо РЯДОК, а не всю тему: решта фактів лишається, пост виходить
    біднішим — але правдивим. Спростування коштує дорожче за коротший пост.
    """
    вихід = []
    for ф in (факти or []):
        т = str(ф).strip()
        if not т:
            continue
        причина = причина_застарілості(т)
        if причина:
            if лог:
                лог(f"  ✂ {причина}: «{т[:70]}…»")
            continue
        вихід.append(т)
    return вихід

