"""Source «plan» — теми постів спільноти з файлу-плану, який Вова і Claude
ведуть разом (`editor/plans/<name>.json`).

🔴 ЧОМУ ПЛАН, А НЕ АВТОМАТИЧНЕ ДЖЕРЕЛО. Рішення Вови 20.08: «не тільки [з історії
змін], будемо разом створювати копірайтинг текст про функції». Тобто теми і факти
задає людина, а агент відповідає лише за форму — написати це голосом бренду.
Наслідок для якості: агент фізично не має звідки взяти неправдивий факт, бо
єдине, що він бачить, — рядки з `facts`.

📌 ПАМʼЯТЬ ОКРЕМО ВІД ПЛАНУ (`data/olyka_agent_state.json`). План — це намір
людини, памʼять — це факт агента. Тримати їх в одному файлі означало б, що агент
редагує документ, який пишуть люди: два автори в одному файлі розходяться завжди
(у цьому проєкті це вже коштувало розрізаної навпіл історії журналів 06.08).
"""
import json
from pathlib import Path

from editor.core.registry import register
from editor.sources.base import Source

ROOT = Path(__file__).resolve().parent.parent.parent
PLANS = ROOT / "editor" / "plans"
STATE = ROOT / "data" / "olyka_agent_state.json"


def load_state() -> dict:
    """Що агент уже написав. Формат: {"done": ["id", ...]}."""
    try:
        return json.loads(STATE.read_text(encoding="utf-8"))
    except Exception:
        return {"done": []}


def mark_done(post_id: str, kind: str = "") -> None:
    """Позначити тему як опрацьовану. Кличе SINK — саме він знає, що запис у базу
    справді відбувся. Джерело цього знати не може: воно віддає теми наперед.

    ⚠️ Пишемо і ВИД поста (`feature`/`brand`) — без цього не порахувати пропорцію,
    а плану вірити не можна: теми з нього з часом видаляють, а історія лишається."""
    st = load_state()
    done = st.setdefault("done", [])
    if post_id and post_id not in done:
        done.append(post_id)
        st.setdefault("kinds", {})[post_id] = kind or "brand"
        STATE.parent.mkdir(parents=True, exist_ok=True)
        STATE.write_text(json.dumps(st, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def _види(st: dict, план: dict) -> list:
    """Види вже написаних постів, у порядку написання.

    Для старих записів (до 20.08 вид не зберігався) беремо вид із плану — а якщо
    теми там уже немає, вважаємо `brand`: занижувати частку функцій безпечніше,
    ніж завищувати і мовчки заблокувати чергу."""
    з_плану = {(з.get("id") or ""): (з.get("kind") or "brand") for з in план.get("posts", [])}
    види = st.get("kinds", {}) or {}
    return [види.get(pid) or з_плану.get(pid, "brand") for pid in st.get("done", [])]


def функція_дозволена(види: list, максимум: float) -> str:
    """Порожній рядок = функцію писати можна. Інакше — причина відмови.

    🔴 ПРАВИЛО ВОВИ 20.08: «таких постів має бути менший відсоток від постів
    звичайних». Спільнота, яка розповідає переважно про власний застосунок,
    говорить сама про себе — а вона про містечко.

    ⚠️ ДВІ УМОВИ, І ОБИДВІ ПОТРІБНІ. Сама лише частка не рятує: після десяти
    звичайних постів вона дозволила б три функції ПІДРЯД, і стрічка на тиждень
    перетворилась би на список оновлень. Тому окремо — заборона двох поспіль."""
    if види and види[-1] == "feature":
        return "попередній пост був про функцію — дві поспіль не пишемо"
    if види:
        функцій = sum(1 for в in види if в == "feature")
        # Рахуємо частку З УРАХУВАННЯМ цього поста: інакше правило спрацювало б
        # лише постфактум, уже після того, як пропорцію порушено.
        якщо_напишемо = (функцій + 1) / (len(види) + 1)
        if якщо_напишемо > максимум:
            return (f"частка постів про функції вийшла б {round(якщо_напишемо * 100)}% "
                    f"при межі {round(максимум * 100)}% — потрібен звичайний пост")
    return ""


@register("source", "plan")
class PlanSource(Source):
    def fetch(self, cfg):
        назва = cfg.get("plan") or cfg.get("name")
        шлях = PLANS / f"{назва}.json"
        if not шлях.exists():
            print(f"  ⚠ плану немає: {шлях}")
            return []

        план = json.loads(шлях.read_text(encoding="utf-8"))
        стан = load_state()
        зроблено = set(стан.get("done", []))
        ліміт = int(cfg.get("per_run", 1))
        максимум = float(план.get("max_feature_share", cfg.get("max_feature_share", 0.34)))
        види = _види(стан, план)

        готові = []
        відкладені = []
        for запис in план.get("posts", []):
            pid = (запис.get("id") or "").strip()
            if not pid or pid in зроблено:
                continue
            # Порожня тема або порожні факти — не привід щось вигадати, а привід
            # пропустити: агент пише лише з того, що йому дали.
            if not (запис.get("topic") or "").strip() or not запис.get("facts"):
                print(f"  ⚠ пропускаю «{pid}»: немає теми або фактів")
                continue
            # 🔴 ПРОПОРЦІЯ. Функцію беремо лише якщо черга це дозволяє. Тему НЕ
            # викидаємо — вона чекає своєї черги, коли вийде звичайний пост.
            if (запис.get("kind") or "brand") == "feature":
                чому = функція_дозволена(види + [в.get("kind", "brand") for в in готові], максимум)
                if чому:
                    відкладені.append((pid, чому))
                    continue
            запис = dict(запис)
            запис["page_id"] = план.get("page_id")
            готові.append(запис)
            if len(готові) >= ліміт:
                break

        for pid, чому in відкладені:
            print(f"  ⏸ «{pid}» чекає: {чому}")
        якщо_нема = ""
        if not готові:
            якщо_нема = ("— потрібні ЗВИЧАЙНІ теми (про містечко, людей, події)"
                         if відкладені else "— план вичерпано, допиши теми")
        print(f"  → план «{назва}»: {len(готові)} тем(и) до роботи {якщо_нема}")
        return готові
