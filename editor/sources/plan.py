def load_state() -> dict:
    """Що агент уже написав. Формат: {"done": ["id", ...]}."""
    try:
        return json.loads(STATE.read_text(encoding="utf-8"))
    except Exception:
        return {"done": []}


def mark_done(post_id: str, kind: str = "", mission: str = "", place: str = "") -> None:
    """Позначити тему як опрацьовану. Кличе SINK — саме він знає, що запис у базу
    справді відбувся. Джерело цього знати не може: воно віддає теми наперед.

    ⚠️ Пишемо і ВИД поста (`feature`/`brand`) — без цього не порахувати пропорцію,
    а плану вірити не можна: теми з нього з часом видаляють, а історія лишається.

    🆕 27.08 — ПИШЕМО ЩЕ Й МІСІЮ. Спільнот тепер дві (OLYKA CASTLE та «Історія
    Громади»), а файл памʼяті один, і це навмисно: спільний `done` не дає написати
    ту саму тему двічі в різні спільноти. Але ПРОПОРЦІЯ постів має рахуватись
    окремо для кожної — інакше пост в «Історії Громади» мовчки дозволяв би зайвий
    пост про функцію в OLYKA CASTLE, тобто правило Вови про частку обходилось би
    чужою спільнотою."""
    st = load_state()
    done = st.setdefault("done", [])
    if post_id and post_id not in done:
        done.append(post_id)
        st.setdefault("kinds", {})[post_id] = kind or "brand"
        if mission:
            st.setdefault("missions", {})[post_id] = mission
        # 🆕 28.08 — МІСЦЕ поста (село / центр / громада). Без нього пропорцію
        # «60% Олика, 40% села» не порахувати між прогонами: план тем із часом
        # чистять, а історія написаного лишається саме тут.
        if place:
            st.setdefault("places", {})[post_id] = place
        STATE.parent.mkdir(parents=True, exist_ok=True)
        STATE.write_text(json.dumps(st, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


# Місія, якій належать записи, зроблені ДО 27.08. Тоді спільнота була одна, тож
# це не здогад, а факт: інших місій із постами в стрічку просто не існувало.
МІСІЯ_ЗА_ЗАМОВЧУВАННЯМ = "olyka_castle"


def _види(st: dict, план: dict, місія: str = "") -> list:
    """Види вже написаних постів ЦІЄЇ місії, у порядку написання.

    Для старих записів (до 20.08 вид не зберігався) беремо вид із плану — а якщо
    теми там уже немає, вважаємо `brand`: занижувати частку функцій безпечніше,
    ніж завищувати і мовчки заблокувати чергу.

    🔴 27.08 — ФІЛЬТР ЗА МІСІЄЮ. Доти список був спільний на весь файл, і з появою
    другої спільноти це стало б витоком: чужі пости рахувались би як «звичайні» і
    відкривали б квоту на функції там, де звичайних постів не було."""
    з_плану = {(з.get("id") or ""): (з.get("kind") or "brand") for з in план.get("posts", [])}
    види = st.get("kinds", {}) or {}
    місії = st.get("missions", {}) or {}
    вихід = []
    for pid in st.get("done", []):
        if місія and місії.get(pid, МІСІЯ_ЗА_ЗАМОВЧУВАННЯМ) != місія:
            continue
        вихід.append(види.get(pid) or з_плану.get(pid, "brand"))
    return вихід


def функція_дозволена(види: list, максимум: float) -> str:
    """Порожній рядок = функцію писати можна. Інакше — причина відмови.

    🔴 ПРАВИЛО ВОВИ 20.08: «таких постів має бути менший відсоток від постів
    звичайних». Спільнота, яка розповідає переважно про власний застосунок,
    говорить сама про себе — а вона про містечко.

    ⚠️ ДВІ УМОВИ, І ОБИДВІ ПОТРІБНІ. Сама лише частка не рятує: після десяти
    звичайних постів вона дозволила б три функції ПІДРЯД, і стрічка на тиждень
    перетворилась би на список оновлень. Тому окремо — заборона двох поспіль."""
    if види and види[-1] == "feature":
        return "попередній пост був про функцію — дві поспіль не пишемо"
    if види:
        функцій = sum(1 for в in види if в == "feature")
        # Рахуємо частку З УРАХУВАННЯМ цього поста: інакше правило спрацювало б
        # лише постфактум, уже після того, як пропорцію порушено.
        якщо_напишемо = (функцій + 1) / (len(види) + 1)
        if якщо_напишемо > максимум:
            return (f"частка постів про функції вийшла б {round(якщо_напишемо * 100)}% "
                    f"при межі {round(максимум * 100)}% — потрібен звичайний пост")
    return ""


def місця_написаних(st: dict, місія: str) -> list:
    """Місця вже написаних постів ЦІЄЇ місії, у порядку написання."""
    місця = st.get("places", {}) or {}
    місії = st.get("missions", {}) or {}
    вихід = []
    for pid in st.get("done", []):
        if місія and місії.get(pid, МІСІЯ_ЗА_ЗАМОВЧУВАННЯМ) != місія:
            continue
        м = місця.get(pid)
        if м:
            вихід.append(м)
    return вихід


def частка_центру(місця: list) -> float:
    """Частка постів про Олику серед тих, що мають АДРЕСУ.

    🛑 Пости про всю громаду (свята, «школи громади») у знаменник НЕ входять. Вони
    не про Олику і не про село; кинути їх в одну з чашок означало б підробити число.
    Порожній знаменник → 0.0, тобто «перекосу ще немає»."""
    з_адресою = [м for м in місця if м in (гео.ЦЕНТР, гео.СЕЛО)]
    if not з_адресою:
        return 0.0
    return sum(1 for м in з_адресою if м == гео.ЦЕНТР) / len(з_адресою)


def зрівноважити(черга: list, місця: list, стеля: float) -> list:
    """Переставляє чергу так, щоб села не лишались назавжди позаду Олики.

    🔴 ЗАМОВЛЕННЯ ВОВИ 28.08: «60% Олика, 40% села громади… села мають бути
    присутні». 📐 Було заміряно 100/0 — сім постів про місце, усі про Олику.

    🛑 ЦЕ ПРАВИЛО ТІЛЬКИ ПЕРЕСТАВЛЯЄ, І НІКОЛИ НЕ БЛОКУЄ. Якщо сільських тем немає,
    тема про Олику проходить як проходила. Інакше вийшло б, що заради пропорції
    спільнота мовчить — а це суперечить рішенню Вови «краще менше, але живе».

    🔑 Чому не «заборонити центр понад стелю», як зроблено з постами про функції:
    там альтернатива завжди є (звичайний пост), а тут її може не бути взагалі. Тому
    форма правила інша — не заслон, а черговість.
    """
    if стеля <= 0 or частка_центру(місця) <= стеля:
        return черга
    села_, центр_, інше_ = [], [], []
    for з in черга:
        м = з.get("місце")
        (села_ if м == гео.СЕЛО else центр_ if м == гео.ЦЕНТР else інше_).append(з)
    if not села_:
        return черга          # нема чим зрівноважувати — не чіпаємо порядок
    print(f"  ⚖ частка Олики {round(частка_центру(місця) * 100)}% при стелі "
          f"{round(стеля * 100)}% — сільські теми ({len(села_)}) наперед")
    return села_ + інше_ + центр_


def _дата(s: str) -> _date:
    р, м, д = (int(x) for x in s.split("-"))
    return _date(р, м, д)


def _мітка(назва: str, префікс: str) -> str:
    """Стабільний id теми з її назви. Не за порядковим номером: переставили
    записи у файлі — і агент написав би те саме вдруге."""
    сухо = "".join(ch if ch.isalnum() or ch == " " else "" for ch in (назва or "").lower())
    return f"{префікс}:" + "-".join(сухо.split()[:4])[:48]


def _речення(текст: str, скільки: int) -> list:
    вихід = []
    for шматок in (текст or "").replace("\n", " ").split("."):
        ш = шматок.strip()
        if len(ш) > 25:
            вихід.append(ш + ".")
        if len(вихід) >= скільки:
            break
    return вихід


def історії_олики(зроблено: set) -> list:
    """Теми з `data/olyka-stories.json` — перевірених матеріалів про Олику, які
    вже живуть у застосунку.

    🔴 20.08, вимога Вови: «більше про громаду, Олику факти і різні пости».
    Правило «агент не вигадує» лишається недоторканим саме тому, що факти беруться
    ЗВІДСИ, а не з голови моделі: це вже вичитаний текст проєкту, а не переказ
    того, що модель «пам'ятає» про Олику. Різниця критична — місцевий читач
    помітить вигадану дату про замок швидше за будь-кого.

    ⚠️ Це НЕ передрук статті. Агент отримує кілька речень як факти і пише з них
    короткий пост стрічки; повний матеріал лишається там, де був."""
    if not STORIES.exists():
        return []
    try:
        сирі = json.loads(STORIES.read_text(encoding="utf-8"))
    except Exception:
        return []
    теми = []
    for іст in сирі if isinstance(сирі, list) else []:
        назва = (іст.get("title") or "").strip()
        if not назва:
            continue
        pid = _мітка(назва, "story")
        if pid in зроблено:
            continue
        факти = [(іст.get("excerpt") or "").strip()] + _речення(іст.get("content", ""), 5)
        факти = [ф for ф in факти if ф]
        if not факти:
            continue
        теми.append({
            "id": pid, "kind": "brand", "topic": назва, "facts": факти,
            "note": ("Це пост про наше містечко, не про застосунок. Коротко, як розповідають "
                     "своїм: одна думка, без переліку всього, що знаєш. Не переказуй усі факти — "
                     "візьми те, що найбільше чіпляє."),
        })
    return теми


def фото_олики(зроблено: set) -> list:
    """Теми з фотоархіву `data/olyka-photos.json` — власні знімки Вови.

    🔴 ЧОМУ ЦЕ ЦЕНТРАЛЬНЕ ДЖЕРЕЛО, А НЕ «ЩЕ ОДНЕ» (рішення 28.08). Історія має
    джерела, які можна перевірити; сучасне життя містечка на 3 тисячі людей у мережі
    не описане ніде. Тобто автоматичний пошук тем про «Олику сьогодні» дав би не
    факти, а гладенькі загальники. Власний знімок — єдине джерело, якого в агента
    бути не може: це погляд, а не переказ. Він же й найдешевший для людини — фото і
    два-три спостереження замість написаного тексту.

    ⚠️ Знімок ЙДЕ РАЗОМ ІЗ ТЕМОЮ (`image`), а не шукається потім. Конвеєр шукає
    картинку лише тоді, коли писар не дав своєї, тож наше фото нічим не перебʼється.

    🛑 Запис без `facts` пропускається НЕ мовчки — про нього сказано в лог: фото без
    жодного спостереження перетворило б пост на підпис «красиво».
    """
    if not PHOTOS.exists():
        return []
    try:
        сирі = json.loads(PHOTOS.read_text(encoding="utf-8"))
    except Exception:
        return []
    записи = сирі.get("items", []) if isinstance(сирі, dict) else (сирі if isinstance(сирі, list) else [])
    теми = []
    for знімок in записи:
        місце = (знімок.get("place") or "").strip()
        url = (знімок.get("url") or "").strip()
        факти = [str(ф).strip() for ф in (знімок.get("facts") or []) if str(ф).strip()]
        if not url or not місце:
            continue
        pid = знімок.get("id") or _мітка(f"{місце} {знімок.get('date', '')}", "photo")
        if pid in зроблено:
            continue
        if not факти:
            print(f"  ⚠ пропускаю знімок «{місце}»: немає жодного спостереження у facts")
            continue
        коли = (знімок.get("date") or "").strip()
        теми.append({
            "id": pid, "kind": "brand",
            "topic": f"Фото: {місце}" + (f" ({коли})" if коли else ""),
            "facts": факти,
            "image": url,
            "note": (знімок.get("note") or
                     "Це фотопост. Текст СУПРОВОДЖУЄ знімок, а не переказує його: не описуй, "
                     "що видно на фото — скажи те, чого на ньому не видно. Дві-чотири короткі "
                     "фрази, спокійно, як показують своє місце."),
        })
    return теми


# Наскільки наперед анонсуємо подію. Місяць — зарано (пост нічого не змінює
# сьогодні), день — запізно. Два тижні: встигаєш спланувати і ще памʼятаєш.
EVENT_WINDOW_DAYS = 14


def найближчі_події(зроблено: set, сьогодні: str) -> list:
    """Події громади, які ще НЕ минули. Дата з файлу — не з голови моделі.

    ⚠️ Минулі події свідомо не беремо: пост «приходьте» про те, що вже відбулось,
    гірший за відсутність поста."""
    if not EVENTS.exists():
        return []
    try:
        сирі = json.loads(EVENTS.read_text(encoding="utf-8"))
    except Exception:
        return []
    теми = []
    for под in сирі if isinstance(сирі, list) else []:
        дата = (под.get("date") or "").strip()
        назва = (под.get("title") or "").strip()
        if not дата or not назва or дата < сьогодні:
            continue
        try:
            за_скільки = (_дата(дата) - _дата(сьогодні)).days
        except Exception:
            continue
        if за_скільки > EVENT_WINDOW_DAYS:
            continue
        pid = _мітка(назва, "event")
        if pid in зроблено:
            continue
        факти = [f"Дата: {дата}."]
        if под.get("time"):
            факти.append(f"Початок: {под['time']}.")
        if под.get("location"):
            факти.append(f"Місце: {под['location']}.")
        if под.get("description"):
            факти.append(под["description"].strip())
        теми.append({
            "id": pid, "kind": "brand", "topic": f"Подія в громаді: {назва}",
            "facts": факти,
            "note": "Коротко: що, коли, де. Без «обовʼязково приходьте» і без окличних знаків.",
        })
    return теми


