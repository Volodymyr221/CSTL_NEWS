        # що було колись.
        # 🔑 Розподіл на ВХОДІ, а не класифікатор на виході: пул теми відомий ДО
        # звернення до моделі, тож платити за текст, щоб потім вирішувати, куди
        # його діти, немає потреби.
        # ⚠️ Місія без `pools` отримує всі три — стара поведінка не змінюється.
        import time as _t
        сьогодні = _t.strftime("%Y-%m-%d", _t.gmtime())
        пули = [str(x) for x in (cfg.get("pools") or ПУЛИ_УСІ)]
        невідомі = [x for x in пули if x not in ПУЛИ_УСІ]
        if невідомі:
            # Мовчки проігнорувати означало б «місія працює, але теми звідкись
            # зникли» — найгірший вид збою в цьому проєкті.
            print(f"  ⚠ невідомі пули в місії: {', '.join(невідомі)} (знаю: {', '.join(ПУЛИ_УСІ)})")
        черга = []
        if "plan" in пули:
            черга += list(план.get("posts", []))
        if "events" in пули:
            черга += найближчі_події(зроблено, сьогодні)
        if "stories" in пули:
            черга += історії_олики(зроблено)
        # Фото стоять ПІСЛЯ плану й подій, але ПЕРЕД історіями за задумом не ставились:
        # знімок не має терміну придатності, а подія має. Порядок = «що швидше протухне».
        if "photos" in пули:
            черга += фото_олики(зроблено)

        # 🔴 28.08 — БАЛАНС «ОЛИКА / СЕЛА». Місце визначаємо ОДИН раз, тут: далі його
        # питають і черговість, і памʼять, і не має бути двох різних відповідей.
        # ⚠️ Дивимось і тему, і факти: у теми «Фото: вулиця біля костелу» назви села
        # немає, а в спостереженнях вона цілком може бути.
        # 🔴 28.08, ВЕЧІР — ТЕМА ВАЖИТЬ БІЛЬШЕ ЗА ФАКТИ (`місце_матеріалу`).
        # Було: тема + УСІ факти одним рядком. Заміряно на першому живому плані —
        # усі три теми стали «селом», зокрема «Олицька ординація», бо серед фактів
        # один згадує цуманський тартак. Пропорція після цього міряла сміття.
        for запис in черга:
            запис["місце"] = гео.місце_матеріалу(
                запис.get("topic") or "", запис.get("facts") or [])
        стеля_центру = float(cfg.get("place_balance", 0) or 0)
        черга = зрівноважити(черга, місця_написаних(стан, місія), стеля_центру)

        готові = []
        відкладені = []
        for запис in черга:
            pid = (запис.get("id") or "").strip()
            if not pid or pid in зроблено:
                continue
            # Порожня тема або порожні факти — не привід щось вигадати, а привід
            # пропустити: агент пише лише з того, що йому дали.
            if not (запис.get("topic") or "").strip() or not запис.get("facts"):
                print(f"  ⚠ пропускаю «{pid}»: немає теми або фактів")
                continue
            # 🔴 ПРОПОРЦІЯ. Функцію беремо лише якщо черга це дозволяє. Тему НЕ
            # викидаємо — вона чекає своєї черги, коли вийде звичайний пост.
            if (запис.get("kind") or "brand") == "feature":
                чому = функція_дозволена(види + [в.get("kind", "brand") for в in готові], максимум)
                if чому:
                    відкладені.append((pid, чому))
                    continue
            запис = dict(запис)
            запис["page_id"] = план.get("page_id")
            готові.append(запис)
            if len(готові) >= ліміт:
                break

        for pid, чому in відкладені:
            print(f"  ⏸ «{pid}» чекає: {чому}")
        якщо_нема = ""
        if not готові:
            якщо_нема = ("— потрібні ЗВИЧАЙНІ теми (про містечко, людей, події)"
                         if відкладені else "— план вичерпано, допиши теми")
        print(f"  → план «{назва}»: {len(готові)} тем(и) до роботи {якщо_нема}")
        return готові
