"""Фільтр «geo_scale» — заслон від звуження масштабу.

🔴 Навіщо заслон, якщо правило вже є в промті. Промт — це НАДІЯ: модель його
здебільшого виконує, але «здебільшого» на пості про День Незалежності означає
«колись знову напише „жителі Олики“». Заслон стоїть після письменника і до
кабінету, тому помилка не доїжджає до людини взагалі.

🔑 Чому ВИПРАВЛЯЄ, а не відкидає. Відкинути чернетку — це викинути вже
оплачений виклик моделі і лишити свято без поста. А заміна тут однозначна:
«жителів Олики» → «жителів Олицької громади», без вгадування відмінка. Тому
фільтр править, гучно каже в лог що саме змінив і лишає слід у `meta`, щоб при
вичитці було видно, що текст чіпали не руками.

⚠️ Виправляє ЛИШЕ на національному масштабі. У пості про сам замок «жителі
Олики» — правильна адреса, і «виправлення» там зіпсувало б текст.
"""
from editor.core import geo as гео
from editor.core.registry import register


@register("filter", "geo_scale")
class GeoScaleFilter:
    def keep(self, draft, cfg) -> bool:
        м = draft.meta.get("масштаб") or гео.масштаб_свята(
            {"title": draft.title, "kind": draft.meta.get("kind_свята", "")})

        усі_зміни, усі_застереження = [], []
        for поле in ("title", "lead", "content"):
            текст = getattr(draft, поле, "") or ""
            новий, зміни, застереження = гео.виправити(текст, м)
            if зміни:
                setattr(draft, поле, новий)
                усі_зміни += [f"{поле}: {z}" for z in зміни]
            усі_застереження += застереження

        if усі_зміни:
            print(f"  🌍 масштаб «{м}» — звуження виправлено: {', '.join(усі_зміни)}")
            draft.meta["гео_виправлено"] = усі_зміни
        if усі_застереження:
            # Не правимо — називаємо. Людина в кабінеті вирішить.
            for з in sorted(set(усі_застереження)):
                print(f"  ⚠ гео: {з}")
            draft.meta["гео_застереження"] = sorted(set(усі_застереження))

        draft.meta["масштаб"] = м
        return True   # заслон ніколи не викидає чернетку — лише лікує і сигналить
